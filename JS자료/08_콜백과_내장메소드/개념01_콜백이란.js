// 왜 배우나?
//   06단원에서 배열을 반복문으로 돌렸습니다. 세기, 거르기, 바꾸기 —
//   할 때마다 for 문을 처음부터 다시 썼습니다. 매번 같은 뼈대인데도요.
//   "도는 일" 은 자바스크립트에 맡기고 "무엇을 할지" 만 적을 수 있다면 어떨까요?
//   그러려면 '할 일' 을 함수로 만들어 넘겨야 합니다. 그것이 콜백입니다.
//   이 단원의 forEach·map·filter·reduce·sort 가 전부 이 방식으로 동작합니다.
//
// 05단원에서 "함수도 값이다" 를 배웠습니다.
// 값이니까 다른 함수에 인자로 넘길 수 있었죠.
//
// 이렇게 '다른 함수에 넘겨져서 나중에 실행되는 함수'를 콜백이라고 합니다.
// call(부르다) + back(다시) — "이따가 다시 불러 줘" 라는 뜻입니다.


// ── 섹션 1: 함수를 넘기고, 넘겨받은 쪽이 실행한다 ──

function doTwice(callback) {
  callback(); // 넘겨받은 함수를 실행
  callback();
}

function sayHi() {
  console.log("안녕!");
}

doTwice(sayHi);
// 출력: 안녕!
// 출력: 안녕!

// 넘길 때 괄호를 붙이지 않는다는 점이 핵심입니다.
//     doTwice(sayHi)    함수를 넘김 (맞음)
//     doTwice(sayHi())  실행 결과인 undefined 를 넘김 (틀림)

// 여기서 sayHi 가 콜백입니다.
// doTwice 는 "언제 실행할지" 를 정하고, sayHi 는 "무엇을 할지" 를 정합니다.
// 역할이 나뉘어 있다는 게 콜백의 핵심입니다.

// ✏️ 직접 해보기 1 — "반갑습니다" 를 출력하는 함수를 만들어 doTwice 로 두 번 실행해 보세요.


// ── 섹션 2: 그 자리에서 만들어 넘기기 ──

// 한 번만 쓸 함수라면 이름을 붙이지 않고 그 자리에서 만듭니다.
doTwice(function () {
  console.log("이름 없는 함수입니다");
});
// 출력: 이름 없는 함수입니다
// 출력: 이름 없는 함수입니다

// 화살표 함수로 쓰면 훨씬 짧습니다. (05단원 개념05)
doTwice(() => {
  console.log("화살표 함수입니다");
});
// 출력: 화살표 함수입니다
// 출력: 화살표 함수입니다

// 한 줄이면 중괄호도 없앨 수 있습니다.
doTwice(() => console.log("한 줄 화살표"));
// 출력: 한 줄 화살표
// 출력: 한 줄 화살표

// 앞으로 나올 배열 메소드들은 전부 이 모양입니다.
//     배열.forEach(() => { ... })
//     배열.map((x) => ...)
// 처음엔 괄호가 겹쳐 보여 어지럽지만, "함수를 인자로 넣고 있다" 는 것만 기억하세요.

// ✏️ 직접 해보기 2 — doTwice 에 화살표 함수로 "화이팅" 을 출력해 보세요.


// ── 섹션 3: 콜백에 값을 넘겨 주기 ──

// 콜백을 실행하는 쪽이 값을 넘겨 줄 수 있습니다. 이게 진짜 쓸모입니다.

function repeat(count, callback) {
  for (let i = 1; i <= count; i++) {
    callback(i); // 몇 번째인지 콜백에 넘겨 줍니다
  }
}

repeat(3, (n) => {
  console.log(`${n}번째 실행`);
});
// 출력: 1번째 실행
// 출력: 2번째 실행
// 출력: 3번째 실행

// 콜백의 매개변수 n 은 어디서 왔을까요?
//   repeat 안에서 callback(i) 라고 부를 때 i 가 넘어온 것입니다.
//   즉 '넘겨받는 쪽'이 아니라 '실행하는 쪽'이 값을 정합니다.
//
// 이름은 마음대로 지어도 됩니다.
repeat(2, (whatever) => {
  console.log(`이름은 아무거나: ${whatever}`);
});
// 출력: 이름은 아무거나: 1
// 출력: 이름은 아무거나: 2

// 안 받아도 됩니다. 필요 없으면 그냥 안 쓰면 그만입니다.
repeat(2, () => {
  console.log("값을 안 받아도 됩니다");
});
// 출력: 값을 안 받아도 됩니다
// 출력: 값을 안 받아도 됩니다

// ✏️ 직접 해보기 3 — repeat 로 1부터 4까지의 제곱을 출력해 보세요.


// ── 섹션 4: 왜 굳이 이렇게 하나 ──

// "하는 일"과 "무엇을 할지"를 분리할 수 있기 때문입니다.

function processScores(scores, callback) {
  for (const score of scores) {
    callback(score);
  }
}

const scores = [90, 55, 78];

// 같은 processScores 인데 넘기는 함수에 따라 하는 일이 달라집니다.
processScores(scores, (s) => console.log(`점수: ${s}`));
// 출력: 점수: 90
// 출력: 점수: 55
// 출력: 점수: 78

processScores(scores, (s) => console.log(s >= 60 ? "합격" : "불합격"));
// 출력: 합격
// 출력: 불합격
// 출력: 합격

// "배열을 하나씩 도는 코드" 를 매번 새로 쓰지 않아도 됩니다.
// 자바스크립트는 아예 이런 함수들을 배열에 기본으로 넣어 두었습니다.
// 그것이 forEach, map, filter, find, reduce, sort 입니다. 다음 파일부터 배웁니다.

// 미리 맛보기 — 위 코드는 사실 이렇게 씁니다.
scores.forEach((s) => console.log(`점수: ${s}`));
// 출력: 점수: 90
// 출력: 점수: 55
// 출력: 점수: 78


// ── 섹션 5: 콜백에는 화살표 함수를 쓴다 ──

// 07단원에서 "객체의 메소드는 화살표 함수로 만들지 말라" 고 했습니다.
// 콜백은 반대입니다. 화살표 함수가 더 안전하고 짧습니다.

const user = {
  name: "김민준",
  hobbies: ["독서", "등산"],

  // 메소드는 일반 함수 (this 가 user 를 가리켜야 하니까)
  showHobbies() {
    // 콜백은 화살표 함수 (바깥의 this 를 그대로 쓰니까)
    this.hobbies.forEach((hobby) => {
      console.log(`${this.name}의 취미: ${hobby}`);
    });
  },
};

user.showHobbies();
// 출력: 김민준의 취미: 독서
// 출력: 김민준의 취미: 등산

// 말로만 하면 안 믿기니 직접 확인해 봅시다. 콜백만 일반 함수로 바꾼 것입니다.

const badUser = {
  name: "김민준",
  hobbies: ["독서", "등산"],

  showHobbies() {
    this.hobbies.forEach(function (hobby) {
      console.log(`${this.name}의 취미: ${hobby}`);
    });
  },
};

badUser.showHobbies();
// 출력: undefined의 취미: 독서
// 출력: undefined의 취미: 등산

// 07단원과 반대라서 헷갈리시죠? 사실 이유는 하나입니다.
//
//     화살표 함수의 this = 그 화살표 함수를 감싸고 있는 코드의 this
//
//   07단원에서는 화살표 함수를 '객체 안' 에 바로 놓았습니다.
//     그것을 감싼 것은 파일 맨 바깥이고, 거기에는 name 이 없어서 undefined 였습니다.
//   여기서는 화살표 함수를 'showHobbies 메소드 안' 에 놓았습니다.
//     그것을 감싼 것은 showHobbies 이고, 그 안의 this 는 user 라서 잘 됩니다.
//
//   반대로 일반 함수(function)는 '자기만의 this' 를 새로 만들어 버립니다.
//   그래서 위 badUser 처럼 바깥의 this 와 끊겨 undefined 가 나옵니다.
//
// 같은 성질이 한 번은 독이 되고 한 번은 약이 된 것입니다.
// 결론만 쓰면 이렇습니다.
//     객체의 메소드  → 일반 함수 (줄여 쓰기)
//     콜백           → 화살표 함수


// ── 섹션 6: 자주 하는 실수 ──

// [실수 1] 넘길 때 괄호를 붙임
// doTwice(sayHi());
// 실수: sayHi() 가 먼저 실행되어 "안녕!" 이 한 번 찍히고,
//       그 결과인 undefined 가 넘어가서 TypeError 가 납니다.

// [실수 2] 콜백 안에서 return 하면 바깥 함수가 끝날 거라 기대
function findFirst(numbers) {
  numbers.forEach((n) => {
    if (n > 10) {
      return n; // 이 return 은 콜백만 끝냅니다
    }
  });
  return "못 찾음";
}
console.log(findFirst([5, 20, 30]));
// 출력: 못 찾음
// 실수: 콜백의 return 은 콜백 자신만 끝냅니다. findFirst 는 계속 진행됩니다.
//       이럴 때 쓰는 것이 개념04에서 배울 find 입니다.

// [실수 3] 콜백 자리에 함수가 아닌 것을 넣기
// doTwice("안녕");
// 실수: TypeError: callback is not a function

// [실수 4] 화살표 함수에서 중괄호를 쓰고 return 을 빠뜨림
const double = (n) => {
  n * 2;
};
console.log(double(5));
// 출력: undefined
// 실수: 중괄호를 쓰면 return 이 필요합니다. (n) => n * 2 로 쓰거나 return 을 넣으세요.


// ── 정리 ──

// 1. 다른 함수에 넘겨져 나중에 실행되는 함수를 콜백이라고 한다.
// 2. 넘길 때 괄호를 붙이지 않는다. 붙이면 '결과'가 넘어간다.
// 3. 콜백의 매개변수는 '실행하는 쪽'이 넘겨 준다.
// 4. 콜백 덕분에 "도는 방법"과 "할 일"을 나눌 수 있다.
// 5. 콜백은 화살표 함수로 쓴다. (객체 메소드는 반대)
// 6. 콜백 안의 return 은 콜백만 끝낸다.



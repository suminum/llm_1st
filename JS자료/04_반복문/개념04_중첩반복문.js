// ── 섹션 3: 구구단 여러 단 (중첩) ──

// 단이 바깥, 곱하는 수가 안쪽입니다.
// 2~9단 전체는 72줄이라 길어서, 여기서는 2~3단을 3까지만 봅니다.

for (let d = 2; d <= 3; d++) {
  console.log(`--- ${d}단 ---`);

  for (let n = 1; n <= 3; n++) {
    console.log(`${d} x ${n} = ${d * n}`);
  }
}
// 출력: --- 2단 ---
// 출력: 2 x 1 = 2
// 출력: 2 x 2 = 4
// 출력: 2 x 3 = 6
// 출력: --- 3단 ---
// 출력: 3 x 1 = 3
// 출력: 3 x 2 = 6
// 출력: 3 x 3 = 9

// 전체 구구단이 필요하면 d 를 9까지, n 을 9까지로 바꾸면 됩니다.
// (출력이 72줄이라 이 파일에서는 줄여 두었습니다)

// ✏️ 직접 해보기 3 — 4단과 5단을 1~3까지 출력해 보세요.


// ── 섹션 4: 별 찍기 ──

// 중첩 반복문의 단골 문제입니다. 바깥은 '줄', 안쪽은 '한 줄의 글자'입니다.

// [직각삼각형] 첫 줄 1개, 둘째 줄 2개 ...
for (let row = 1; row <= 4; row++) {
  let line = ""; // 줄마다 새로 비웁니다

  for (let col = 1; col <= row; col++) {
    line += "*";
  }

  console.log(line);
}
// 출력: *
// 출력: **
// 출력: ***
// 출력: ****

// 핵심은 안쪽 조건이 col <= row 라는 것입니다.
// 안쪽 반복 횟수가 바깥 변수에 따라 달라집니다.

// [사각형] 안쪽을 고정하면 사각형이 됩니다.
for (let row = 1; row <= 3; row++) {
  let line = "";
  for (let col = 1; col <= 4; col++) {
    line += "#";
  }
  console.log(line);
}
// 출력: ####
// 출력: ####
// 출력: ####

// 문자열을 한 줄로 모아 두었다가 한 번에 출력하는 게 요령입니다.
// 안쪽에서 바로 console.log 를 하면 한 글자씩 줄이 바뀝니다.

// ✏️ 직접 해보기 4 — 거꾸로 된 삼각형을 만들어 보세요.
//                    ****  /  ***  /  **  /  *  (힌트: 안쪽 조건을 바꾸거나 바깥을 감소)


// ── 섹션 5: 중첩에서 break 는 안쪽만 빠져나온다 ──

for (let i = 1; i <= 3; i++) {
  for (let j = 1; j <= 3; j++) {
    if (j === 2) {
      break; // 안쪽 for 만 빠져나옵니다
    }
    console.log(`i=${i}, j=${j}`);
  }
}
// 출력: i=1, j=1
// 출력: i=2, j=1
// 출력: i=3, j=1

// j 가 2가 되면 안쪽이 끝나지만, 바깥은 계속 돕니다.

// 바깥까지 한 번에 빠져나오려면 표시용 변수를 씁니다.
let stop = false;

for (let i = 1; i <= 3; i++) {
  for (let j = 1; j <= 3; j++) {
    if (i === 2 && j === 2) {
      stop = true;
      break; // 안쪽 탈출
    }
    console.log(`전체탈출 예제 i=${i}, j=${j}`);
  }

  if (stop) {
    break; // 바깥 탈출
  }
}
// 출력: 전체탈출 예제 i=1, j=1
// 출력: 전체탈출 예제 i=1, j=2
// 출력: 전체탈출 예제 i=1, j=3
// 출력: 전체탈출 예제 i=2, j=1

// 왜 i=2, j=1 에서 멈췄는지 한 번만 따라가 봅시다.
//
//   i=1 일 때  j 가 1, 2, 3 을 다 돌며 세 줄이 찍힙니다. 조건에 안 걸립니다.
//   i=2, j=1   아직 조건(i가 2이고 j도 2)에 안 맞으니 찍힙니다.  ← 마지막 출력
//   i=2, j=2   조건에 맞습니다. stop 에 true 를 넣고 break 로 안쪽을 빠져나옵니다.
//              그래서 "i=2, j=2" 는 찍히지 않습니다.
//   안쪽을 나오자마자 if (stop) 을 만나 바깥 for 도 break 합니다.
//   i=3 은 아예 시작하지 않습니다.
//
// break 하나로는 안쪽만 나옵니다.
// 그래서 "밖으로도 나가라" 는 쪽지(stop)를 남겨 두는 것입니다.

// 이런 코드가 필요해지면 대개 구조가 복잡해졌다는 신호입니다.
// 05단원에서 함수를 배우면 return 으로 훨씬 깔끔하게 빠져나올 수 있습니다.



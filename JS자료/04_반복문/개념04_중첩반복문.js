// ── 섹션 1: 어떻게 도는가 ──

// 바깥이 한 바퀴 돌 때마다, 안쪽은 처음부터 끝까지 다 돕니다.

for (let outer = 1; outer <= 2; outer++) {
  console.log(`바깥 ${outer} 시작`);

  for (let inner = 1; inner <= 3; inner++) {
    console.log(`   안쪽 ${inner}`);
  }

  console.log(`바깥 ${outer} 끝`);
}
// 출력: 바깥 1 시작
// 출력:    안쪽 1
// 출력:    안쪽 2
// 출력:    안쪽 3
// 출력: 바깥 1 끝
// 출력: 바깥 2 시작
// 출력:    안쪽 1
// 출력:    안쪽 2
// 출력:    안쪽 3
// 출력: 바깥 2 끝

// 전체 실행 횟수 = 바깥 횟수 × 안쪽 횟수 = 2 × 3 = 6번
// 이 곱셈을 꼭 기억하세요. 바깥이 100, 안쪽이 100이면 1만 번입니다.

// 변수 이름은 보통 바깥부터 i, j 를 씁니다.
// 처음엔 outer / inner 처럼 뜻이 보이는 이름을 쓰는 게 헷갈리지 않습니다.

// ✏️ 직접 해보기 1 — 바깥 3번, 안쪽 2번 도는 중첩 반복문을 만들고
//                    안쪽에서 "*" 를 출력해 보세요. (총 6번 찍힙니다)


// ── 섹션 2: 구구단 한 단 ──

// 먼저 반복문 하나로 2단을 만들어 봅니다.
const dan = 2;

for (let n = 1; n <= 9; n++) {
  console.log(`${dan} x ${n} = ${dan * n}`);
}
// 출력: 2 x 1 = 2
// 출력: 2 x 2 = 4
// 출력: 2 x 3 = 6

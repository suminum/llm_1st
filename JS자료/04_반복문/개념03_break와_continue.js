// 반복 도중에 흐름을 바꾸는 두 가지 명령입니다.
//
//     break     반복을 아예 그만둔다 (탈출)
//     continue  이번 바퀴만 건너뛰고 다음 바퀴로 (통과)


// ── 섹션 1: break — 그만두기 ──

for (let i = 1; i <= 10; i++) {
  if (i > 3) {
    break; // 여기서 for 문을 완전히 빠져나갑니다
  }
  console.log("break 예제:", i);
}
// 출력: break 예제: 1
// 출력: break 예제: 2
// 출력: break 예제: 3

console.log("반복문 밖입니다");
// 출력: 반복문 밖입니다

// 10까지 돌게 써 놨지만 i 가 4가 되는 순간 멈췄습니다.
// break 아래의 코드는 실행되지 않고, 반복문 다음 줄로 건너뜁니다.


// ── 섹션 2: continue — 건너뛰기 ──

for (let i = 1; i <= 5; i++) {
  if (i === 3) {
    continue; // 이번 바퀴의 나머지를 건너뛰고 i++ 로 갑니다
  }
  console.log("continue 예제:", i);
}
// 출력: continue 예제: 1
// 출력: continue 예제: 2
// 출력: continue 예제: 4
// 출력: continue 예제: 5

// 3만 빠졌습니다. 반복 자체는 끝까지 돌았습니다.

// 바로 위 코드에서 continue 를 break 로 바꾸면 이렇게 달라집니다.
//   if (i === 3) continue;  → 1, 2, 4, 5 (3만 빠짐)   ← 방금 본 결과
//   if (i === 3) break;     → 1, 2 에서 끝

// ✏️ 직접 해보기 1 — 1부터 10까지 중 짝수만 출력해 보세요.
//                    (홀수일 때 continue 를 쓰면 됩니다. 힌트: i % 2 === 1)


// ── 섹션 3: 찾으면 멈추기 ──

// break 의 가장 흔한 쓰임입니다. 원하는 것을 찾으면 더 볼 필요가 없으니까요.

const target = 7;
let foundAt = -1; // 못 찾았을 때를 뜻하는 값으로 시작합니다

for (let i = 1; i <= 10; i++) {
  console.log(`${i} 확인 중`);

  if (i === target) {
    foundAt = i;
    break; // 찾았으니 나머지는 볼 필요가 없습니다
  }
}
// 출력: 1 확인 중
// 출력: 2 확인 중
// 출력: 3 확인 중
// 출력: 4 확인 중
// 출력: 5 확인 중
// 출력: 6 확인 중
// 출력: 7 확인 중

console.log("찾은 위치:", foundAt);
// 출력: 찾은 위치: 7

// break 가 없었다면 8, 9, 10 까지 쓸데없이 확인했을 겁니다.
// 데이터가 수만 개라면 큰 차이가 됩니다.

// ✏️ 직접 해보기 2 — 1부터 20까지 세다가 처음으로 3의 배수를 만나면
//                    그 수를 출력하고 멈춰 보세요. (힌트: i % 3 === 0)


// ── 섹션 4: while (true) 와 break ──

// "언제 끝날지 모르지만 어떤 일이 생기면 끝낸다" 를 이렇게 씁니다.

let attempt = 0;

while (true) {
  attempt++;
  console.log(`${attempt}번째 시도`);

  if (attempt === 3) {
    console.log("성공! 반복을 끝냅니다");
    break;
  }
}
// 출력: 1번째 시도
// 출력: 2번째 시도
// 출력: 3번째 시도
// 출력: 성공! 반복을 끝냅니다

// while (true) 는 조건이 영원히 참이라 그 자체로 무한 루프입니다.
// 반드시 안에 break 가 있어야 합니다.
// break 를 빠뜨리면 프로그램이 멈추지 않습니다. Ctrl + C 로 강제 종료하세요.


// ── 섹션 5: continue 로 걸러내기 ──

// "조건에 안 맞는 건 건너뛰고, 맞는 것만 처리" 패턴입니다.

let sum = 0;

for (let i = 1; i <= 10; i++) {
  if (i % 2 === 1) {
    continue; // 홀수는 건너뜀
  }
  sum += i; // 짝수만 더함
}

console.log("1~10 짝수의 합:", sum);
// 출력: 1~10 짝수의 합: 30
// 2+4+6+8+10 = 30

// continue 없이 if 로 감싸도 똑같습니다.
let sum2 = 0;
for (let i = 1; i <= 10; i++) {
  if (i % 2 === 0) {
    sum2 += i;
  }
}
console.log("if 로 쓴 같은 결과:", sum2);
// 출력: if 로 쓴 같은 결과: 30

// 어느 쪽이든 맞습니다.
//   걸러낼 게 많고 처리 코드가 길면  → continue 로 먼저 걸러내는 편이 읽기 좋음
//   처리 코드가 짧으면              → if 로 감싸는 게 단순함

// ✏️ 직접 해보기 3 — 1부터 10까지 중 3의 배수만 더한 값을 출력해 보세요. (정답 18)



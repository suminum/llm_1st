// 같은 일을 여러 번 해야 할 때 복사·붙여넣기를 하면 안 됩니다.
// 반복문을 쓰면 몇 번을 하든 코드는 세 줄입니다.
//
//     for (시작값; 조건; 증감) {
//        반복할 코드
//     }
//          ^^^^^  ^^^^  ^^^^
//          어디서   언제까지  얼마씩


// ── 섹션 1: 왜 반복문인가 ──

// [반복문 없이] 출석을 3번 부른다면
console.log("1번 출석");
console.log("2번 출석");
console.log("3번 출석");
// 출력: 1번 출석
// 출력: 2번 출석
// 출력: 3번 출석

// 30명이면 30줄을 써야 합니다. 게다가 숫자를 하나씩 손으로 바꿔야 하죠.

// [반복문으로]
for (let i = 1; i <= 3; i++) {
  console.log(`${i}번 출석 (for)`);
}
// 출력: 1번 출석 (for)
// 출력: 2번 출석 (for)
// 출력: 3번 출석 (for)

// 30명으로 바꾸려면 3 을 30 으로 고치기만 하면 됩니다.

// ✏️ 직접 해보기 1 — for 문으로 "안녕하세요" 를 3번 출력해 보세요.


// ── 섹션 2: for 문의 세 부분 ──

// for (let i = 0; i < 3; i++) 을 뜯어봅시다.
//
//   let i = 0   시작값. 반복을 세는 변수를 만듭니다. 보통 i 라고 짓습니다.
//   i < 3       조건. 이게 true 인 동안 계속 반복합니다.
//   i++         증감. 한 바퀴가 끝날 때마다 실행됩니다.
//
// 실행 순서
//   1) let i = 0 (딱 한 번)
//   2) i < 3 검사 → true 면 중괄호 안 실행
//   3) i++
//   4) 다시 2번으로
//   5) 조건이 false 가 되면 끝

for (let i = 0; i < 3; i++) {
  console.log("i 값:", i);
}
// 출력: i 값: 0
// 출력: i 값: 1
// 출력: i 값: 2

// i 가 3이 되면 3 < 3 이 false 라서 멈춥니다. 그래서 0, 1, 2 세 번입니다.

// i 는 중괄호 안에서만 쓸 수 있습니다. 밖에서 쓰면 에러입니다.
// console.log(i);
// 실수: ReferenceError: i is not defined

// ✏️ 직접 해보기 2 — 0부터 4까지 다섯 개의 숫자를 출력해 보세요.


// ── 섹션 3: 0부터? 1부터? ──

// [0부터] i < 개수  — 0, 1, 2 ... 프로그래밍의 기본입니다
for (let i = 0; i < 3; i++) {
  console.log("0부터:", i);
}
// 출력: 0부터: 0
// 출력: 0부터: 1
// 출력: 0부터: 2

// [1부터] i <= 개수  — 사람이 세는 방식입니다
for (let i = 1; i <= 3; i++) {
  console.log("1부터:", i);
}
// 출력: 1부터: 1
// 출력: 1부터: 2
// 출력: 1부터: 3

// 둘 다 세 번 반복합니다. 짝을 기억하세요.
//   0부터 시작하면  <   (미만)
//   1부터 시작하면  <=  (이하)
// 이 짝을 어기면 한 번 더 돌거나 한 번 덜 돕니다. (섹션 6 실수 1)

// [거꾸로] 감소시키기
for (let i = 3; i >= 1; i--) {
  console.log("거꾸로:", i);
}
// 출력: 거꾸로: 3
// 출력: 거꾸로: 2
// 출력: 거꾸로: 1

// [2씩] 증감은 ++ 말고 다른 것도 됩니다
for (let i = 0; i <= 6; i += 2) {
  console.log("2씩:", i);
}
// 출력: 2씩: 0
// 출력: 2씩: 2
// 출력: 2씩: 4
// 출력: 2씩: 6

// ✏️ 직접 해보기 3 — 10부터 1까지 거꾸로 세는 for 문을 써 보세요.
//                    (출력이 길어지니 5부터 1까지로 해도 됩니다)


// ── 섹션 4: 반복하면서 누적하기 ──

// 반복문의 가장 흔한 쓰임입니다. 02단원에서 배운 += 를 씁니다.
// 누적 변수는 반드시 반복문 '밖'에서 만들고 0으로 시작합니다.

let sum = 0;

for (let i = 1; i <= 5; i++) {
  sum += i;
}

console.log("1부터 5까지의 합:", sum);
// 출력: 1부터 5까지의 합: 15
// 1+2+3+4+5 = 15

// 중간 과정을 눈으로 보고 싶으면 반복문 안에서 찍어 보세요.
let sum2 = 0;
for (let i = 1; i <= 3; i++) {
  sum2 += i;
  console.log(`i=${i} 일 때 sum2=${sum2}`);
}
// 출력: i=1 일 때 sum2=1
// 출력: i=2 일 때 sum2=3
// 출력: i=3 일 때 sum2=6

// [중요] 누적 변수를 반복문 안에서 만들면 매번 초기화되어 버립니다.
for (let i = 1; i <= 3; i++) {
  let wrongSum = 0; // ← 매 바퀴 0으로 되돌아갑니다
  wrongSum += i;
  console.log("잘못된 누적:", wrongSum);
}
// 출력: 잘못된 누적: 1
// 출력: 잘못된 누적: 2
// 출력: 잘못된 누적: 3
// 1, 3, 6 이 나와야 하는데 그냥 i 값이 나왔습니다.

// ✏️ 직접 해보기 4 — 1부터 10까지의 합을 구해 출력해 보세요. (정답은 55)


// ── 섹션 5: 글자를 누적하기 ──

// 숫자만 누적하는 게 아닙니다. 문자열도 += 로 쌓을 수 있습니다.
let stars = "";

for (let i = 1; i <= 5; i++) {
  stars += "*";
}

console.log(stars);
// 출력: *****

// 한 줄씩 늘려 가며 출력하면 이런 모양이 됩니다.

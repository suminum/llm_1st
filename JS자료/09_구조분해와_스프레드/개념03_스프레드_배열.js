// 왜 배우나?
//   지금까지 "원본을 바꾸지 마세요" 라는 말을 여러 번 들었습니다.
//   sort·reverse 는 원본을 바꿨고, 배열을 그냥 대입하면 복사가 아니었죠.
//   그때마다 slice() 를 썼습니다. 스프레드는 그 일을 더 짧게 하고,
//   합치기와 "함수에 낱개로 넘기기" 까지 기호 하나로 해결합니다.
//   06단원에서 못 했던 Math.max(배열) 도 이걸로 됩니다.
//
// 점 세 개(...)를 배열 앞에 붙이면 그 안의 값들이 낱개로 펼쳐집니다.
//
//     const numbers = [1, 2, 3];
//     [...numbers]   →   1, 2, 3 이 하나씩 놓인 것과 같음
//
// 구조분해의 ... 은 '모으기'였고, 여기서는 '펼치기'입니다.
// 위치로 구분합니다. 자세한 건 개념05에서 정리합니다.


// ── 섹션 1: 펼쳐 보기 ──

const numbers = [1, 2, 3];

console.log(numbers);
// 출력: [ 1, 2, 3 ]

console.log(...numbers);
// 출력: 1 2 3
// 대괄호가 사라지고 값이 낱개로 놓였습니다.
// console.log(1, 2, 3) 이라고 쓴 것과 같습니다.

// 새 배열의 재료로 쓰면 그대로 다시 배열이 됩니다.
console.log([...numbers]);
// 출력: [ 1, 2, 3 ]

// 앞뒤에 값을 더할 수 있습니다.
console.log([0, ...numbers, 4]);
// 출력: [ 0, 1, 2, 3, 4 ]

// ✏️ 직접 해보기 1 — ["b", "c"] 앞에 "a" 를 붙인 새 배열을 만들어 보세요.


// ── 섹션 2: 복사하기 ──

// 06·08단원에서 이미 썼던 방법입니다. 이제 원리를 알 수 있습니다.
const original = [1, 2, 3];

// [잘못된 복사] 같은 배열을 가리키는 이름만 하나 더 생깁니다
const notCopy = original;
notCopy.push(99);
console.log(original);
// 출력: [ 1, 2, 3, 99 ]
// 원본까지 바뀌었습니다.

// [진짜 복사]
const original2 = [1, 2, 3];
const realCopy = [...original2];
realCopy.push(99);

console.log(realCopy);
// 출력: [ 1, 2, 3, 99 ]
console.log(original2);
// 출력: [ 1, 2, 3 ]
// 원본이 지켜졌습니다.

// slice() 로도 복사할 수 있습니다. 결과는 같습니다.
const original3 = [1, 2, 3];
console.log([...original3]);
// 출력: [ 1, 2, 3 ]
console.log(original3.slice());
// 출력: [ 1, 2, 3 ]

// 원본을 바꾸는 메소드(sort, reverse, splice) 앞에 붙여 쓰면 안전합니다.
const scores = [30, 10, 20];
console.log([...scores].sort((a, b) => a - b));
// 출력: [ 10, 20, 30 ]
console.log(scores);
// 출력: [ 30, 10, 20 ]

// ✏️ 직접 해보기 2 — 배열을 복사한 뒤 복사본만 뒤집어 보세요. (reverse)


// ── 섹션 3: 합치기 ──

const group1 = ["김민준", "이서연"];
const group2 = ["박지훈", "최유진"];

console.log([...group1, ...group2]);
// 출력: [ '김민준', '이서연', '박지훈', '최유진' ]

// 06단원의 concat 과 결과가 같습니다.
console.log(group1.concat(group2));
// 출력: [ '김민준', '이서연', '박지훈', '최유진' ]

// 스프레드는 순서를 자유롭게 섞을 수 있어서 더 편합니다.
console.log([...group2, "정하늘", ...group1]);
// 출력: [ '박지훈', '최유진', '정하늘', '김민준', '이서연' ]

// 원본은 둘 다 그대로입니다.
console.log(group1);
// 출력: [ '김민준', '이서연' ]

// ✏️ 직접 해보기 3 — 배열 두 개 사이에 "구분" 이라는 값을 끼워 합쳐 보세요.


// ── 섹션 4: 함수 인자로 펼치기 ──

// Math.max 는 배열을 통째로 못 받습니다. 값을 하나씩 받습니다.
console.log(Math.max(3, 7, 5));
// 출력: 7

const temps = [23, 31, 18, 27];

console.log(Math.max(temps));
// 출력: NaN
// 배열을 통째로 넘겨서 계산이 안 됩니다.

console.log(Math.max(...temps));
// 출력: 31
// 스프레드로 펼치면 Math.max(23, 31, 18, 27) 이 됩니다.

console.log(Math.min(...temps));
// 출력: 18

// 06단원에서 반복문으로 구하던 최댓값이 한 줄이 되었습니다.

// 우리가 만든 함수에도 똑같이 쓸 수 있습니다.
function sum3(a, b, c) {
  return a + b + c;
}
const args = [1, 2, 3];
console.log(sum3(...args));
// 출력: 6

// ✏️ 직접 해보기 4 — [45, 88, 62] 의 최댓값과 최솟값을 출력해 보세요.


// ── 섹션 5: 문자열도 펼쳐진다 ──

// 문자열은 글자 하나씩 꺼낼 수 있는 형태라 스프레드가 됩니다.
console.log([..."안녕하세요"]);
// 출력: [ '안', '녕', '하', '세', '요' ]

// split("") 과 결과가 같습니다.
console.log("안녕하세요".split(""));
// 출력: [ '안', '녕', '하', '세', '요' ]

// 글자를 뒤집을 때 이렇게 씁니다.

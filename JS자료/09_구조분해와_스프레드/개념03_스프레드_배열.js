// ── 섹션 6: 원본을 안 바꾸고 값 추가하기 ──

// React 같은 곳에서는 "원본을 바꾸지 말고 새 배열을 만들어라" 가 규칙입니다.
// 스프레드가 그 규칙을 지키는 도구입니다.

const todos = ["장보기", "청소"];

// [원본을 바꾸는 방법]
// todos.push("운동");

// [새 배열을 만드는 방법]
const newTodos = [...todos, "운동"];
console.log(newTodos);
// 출력: [ '장보기', '청소', '운동' ]
console.log(todos);
// 출력: [ '장보기', '청소' ]

// 앞에 추가
console.log(["급한 일", ...todos]);
// 출력: [ '급한 일', '장보기', '청소' ]

// 하나 빼고 새 배열 (filter 와 조합)
console.log(todos.filter((t) => t !== "청소"));
// 출력: [ '장보기' ]

// 하나 바꾸고 새 배열 (map 과 조합)
console.log(todos.map((t) => (t === "청소" ? "대청소" : t)));
// 출력: [ '장보기', '대청소' ]

// 08단원의 map / filter 도 전부 새 배열을 돌려줍니다.
// "원본을 안 건드린다" 는 같은 흐름입니다.


// ── 섹션 7: 얕은 복사 — 한 겹만 복사된다 ──

// 07단원 개념02 섹션6, 개념05 섹션7에서 봤던 함정입니다.
const users = [
  { name: "김민준", age: 20 },
  { name: "이서연", age: 22 },
];

const copied = [...users];

// 배열 자체는 새로 만들어졌습니다.
copied.push({ name: "박지훈", age: 28 });
console.log(users.length);
// 출력: 2
console.log(copied.length);
// 출력: 3

// 하지만 안의 객체는 원본과 같은 것을 가리킵니다.
copied[0].age = 99;
console.log(users[0].age);
// 출력: 99
// 원본까지 바뀌었습니다.

// 스프레드는 '한 겹만' 복사합니다. 이것을 얕은 복사라고 합니다.
// 안쪽 객체까지 복사하려면 map 과 함께 씁니다.
const users2 = [{ name: "정하늘", age: 30 }];
const deepish = users2.map((u) => ({ ...u }));

deepish[0].age = 99;

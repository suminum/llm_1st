// if / else 를 한 줄로 줄여 쓰는 문법입니다.
//
//     조건 ? 참일때값 : 거짓일때값
//          ^          ^
//          물음표      콜론
//
// "조건이 참이야? 그럼 앞의 값, 아니면 뒤의 값"


// ── 섹션 1: 기본 형태 ──

const age = 22;

// [if 버전]
if (age >= 19) {
  console.log("성인");
} else {
  console.log("미성년자");
}
// 출력: 성인

// [삼항 버전] — 위와 완전히 같은 뜻입니다
console.log(age >= 19 ? "성인" : "미성년자");
// 출력: 성인

const age2 = 15;
console.log(age2 >= 19 ? "성인" : "미성년자");
// 출력: 미성년자

// ✏️ 직접 해보기 1 — 점수 55점이 60 이상인지로 "합격"/"불합격" 을
//                    삼항 연산자로 출력해 보세요.


// ── 섹션 2: 값을 골라 변수에 담기 ──

// 삼항 연산자의 진짜 쓸모는 여기입니다. '값'이라서 변수에 담을 수 있습니다.

const stock = 0;

// [if 버전] — 변수를 먼저 만들고 나중에 채워야 해서 let 이 됩니다
let statusText;
if (stock > 0) {
  statusText = "구매 가능";
} else {
  statusText = "품절";
}
console.log(statusText);
// 출력: 품절

// [삼항 버전] — 만들면서 바로 채우니 const 로 쓸 수 있습니다
const statusText2 = stock > 0 ? "구매 가능" : "품절";
console.log(statusText2);
// 출력: 품절

// const 로 쓸 수 있다는 게 생각보다 큰 장점입니다.
// 중간에 값이 바뀔 걱정을 안 해도 되니까요.

// 숫자를 고를 수도 있습니다.
const isMember = true;
const shippingFee = isMember ? 0 : 3000;
console.log(shippingFee);
// 출력: 0

// ✏️ 직접 해보기 2 — 나이 15로 ticketPrice 를 정해 출력해 보세요.
//                    (19세 이상이면 12000, 아니면 8000)


// ── 섹션 3: 템플릿 리터럴 안에서 쓰기 ──

// ${ } 안에는 '값이 나오는 식'이 들어갑니다. 삼항 연산자가 딱 맞습니다.
// (if 는 문장이라 ${ } 안에 넣을 수 없습니다)

const userName = "김민준";
const point = 1500;

console.log(`${userName}님은 ${point >= 1000 ? "VIP" : "일반"} 회원입니다`);
// 출력: 김민준님은 VIP 회원입니다

const count = 1;
console.log(`장바구니에 ${count}개${count > 1 ? "들" : ""} 담겼습니다`);
// 출력: 장바구니에 1개 담겼습니다

const count2 = 3;
console.log(`장바구니에 ${count2}개${count2 > 1 ? "들" : ""} 담겼습니다`);
// 출력: 장바구니에 3개들 담겼습니다

// 이 패턴은 나중에 화면에 글자를 찍을 때(10단원 DOM) 아주 많이 씁니다.

// ✏️ 직접 해보기 3 — 재고가 0이면 "품절", 아니면 "재고 N개" 가 나오도록
//                    백틱 안에서 삼항 연산자를 써 보세요. (재고 5)


// ── 섹션 4: 언제 삼항을 쓰고 언제 if 를 쓸까 ──

// [삼항이 좋을 때] 둘 중 하나의 '값'을 고를 때
const temperature = 31;
const weatherText = temperature >= 28 ? "덥다" : "괜찮다";
console.log(weatherText);
// 출력: 덥다

// [if 가 좋을 때] 실행할 '동작'이 여러 줄일 때
if (temperature >= 28) {
  console.log("에어컨을 켭니다");
  console.log("창문을 닫습니다");
  console.log("선풍기도 켭니다");
}
// 출력: 에어컨을 켭니다
// 출력: 창문을 닫습니다
// 출력: 선풍기도 켭니다

// 한 줄로 쓸 수 있다고 항상 좋은 게 아닙니다.
// 기준: "값을 고르는가(삼항), 일을 시키는가(if)"

// ✏️ 직접 해보기 4 — 아래 if 문을 삼항으로 바꿔 보세요.
//                    if (isRaining) { umbrella = "필요"; } else { umbrella = "불필요"; }


// ── 섹션 5: 중첩 삼항 — 되지만 하지 마세요 ──

const score = 85;

// 삼항 안에 삼항을 넣을 수 있습니다.
const grade = score >= 90 ? "A" : score >= 80 ? "B" : score >= 70 ? "C" : "F";
console.log(grade);
// 출력: B

// 동작은 합니다. 하지만 읽기가 매우 나쁩니다.
// 콜론이 어디에 걸리는지 눈으로 따라가기 어렵고, 조건이 하나만 늘어도 무너집니다.

// 갈림길이 셋 이상이면 else if 를 쓰세요.
let grade2;
if (score >= 90) {
  grade2 = "A";
} else if (score >= 80) {
  grade2 = "B";
} else if (score >= 70) {
  grade2 = "C";
} else {
  grade2 = "F";
}
console.log(grade2);
// 출력: B

// 규칙: 삼항은 갈림길이 '둘'일 때만.


// ── 섹션 6: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] 콜론을 빠뜨리기 → SyntaxError
// const x = age >= 19 ? "성인";
// 실수: 삼항은 ? 와 : 가 반드시 짝입니다. "아니면"을 생략할 수 없습니다.
//       거짓일 때 아무것도 안 하고 싶다면 if 를 쓰세요.

// [실수 2] 삼항 안에서 console.log 를 실행하기
const isVip = true;
isVip ? console.log("VIP 인사") : console.log("일반 인사");
// 출력: VIP 인사
// 문법 오류는 아니고 동작도 합니다. 하지만 삼항은 '값을 고르는' 문법입니다.
// 동작을 시킬 거면 if / else 로 쓰세요. 이렇게 쓰면 읽는 사람이 헷갈립니다.

// [실수 3] 조건 자리에 대입을 쓰기
let level = 1;
// const r = (level = 5) ? "높음" : "낮음";
// 실수: level 에 5를 넣어 버립니다. 비교는 === 입니다.
console.log(level);
// 출력: 1

// [실수 4] 중첩 삼항을 한 줄에 길게 (섹션 5에서 봤습니다)


// ── 정리 ──

// 1. 조건 ? 참일때값 : 거짓일때값

// ── 섹션 3: 만들기와 부르기는 다르다 ──

// 함수를 만들기만 하고 부르지 않으면 아무 일도 일어나지 않습니다.
function neverCalled() {
  console.log("이 줄은 실행되지 않습니다");
}
// (부르지 않았으므로 아무것도 출력되지 않습니다)

// 괄호를 빼먹으면 '실행'이 아니라 '함수 자체'를 가리키게 됩니다.
function sayHi() {
  console.log("안녕하세요");
}

sayHi();
// 출력: 안녕하세요

console.log(typeof sayHi);
// 출력: function
// 괄호 없이 이름만 쓰면 함수라는 '값'입니다. 실행되지 않습니다.

// ✏️ 직접 해보기 2 — sayHi 를 괄호 없이 console.log(sayHi) 로 찍어 보고

//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] 괄호를 빼고 호출
// sayHi;
// 실수: 에러도 안 나고 아무 일도 안 일어납니다. 가장 찾기 힘든 실수입니다.
//       반드시 sayHi() 로 괄호를 붙이세요.

// [실수 2] 없는 함수 부르기 → ReferenceError
// sayBye();

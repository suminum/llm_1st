//   - 한 군데를 빠뜨리면 화면마다 이름이 달라집니다


// ── 섹션 2: 함수로 묶기 ──

// 반복되는 코드에 이름을 붙입니다.
function printHeader() {
  console.log("=====================");
  console.log("  우리편의점입니다");
  console.log("=====================");
}

// 여기까지는 '만들기'입니다. 아직 아무것도 실행되지 않았습니다.
// 이름 뒤에 괄호를 붙여야 그때 실행됩니다.

printHeader();
// 출력: =====================
// 출력:   우리편의점입니다
// 출력: =====================

printHeader();
// 출력: =====================
// 출력:   우리편의점입니다
// 출력: =====================

// 이제 가게 이름을 바꾸려면 함수 안 한 줄만 고치면 됩니다.
// 100군데에서 부르고 있어도 마찬가지입니다.

// ✏️ 직접 해보기 1 — printGoodbye 라는 함수를 만들어

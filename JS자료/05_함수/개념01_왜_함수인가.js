// ── 섹션 6: 이름 짓는 법 ──

// 함수는 '일을 하는 것'이라 이름을 동사로 시작합니다.
//
//   printHeader   출력한다
//   getTotal      가져온다 / 계산해서 돌려준다
//   isAdult       ~인가? (참/거짓을 돌려주는 함수는 is~ / has~)
//   setName       설정한다
//
// 변수는 명사(userName), 함수는 동사(getUserName). 이 구별만 지켜도
// 코드가 훨씬 잘 읽힙니다.

// 변수와 마찬가지로 카멜 표기법을 씁니다.
function showWelcomeMessage() {
  console.log("환영합니다!");
}
showWelcomeMessage();
// 출력: 환영합니다!



//
// 앞에서는 값을 바로 출력했습니다.
//
//     console.log(1200);
//
// 그런데 같은 값을 열 군데에서 쓰다가 가격이 바뀌면 열 군데를 다 고쳐야 합니다.
// 그래서 값에 '이름'을 붙여 두고, 이름으로 부릅니다. 이것이 변수입니다.
//
//     let price = 1200;
//     └┬┘ └─┬─┘ ^ └─┬┘
//      │    │    │   └ 담을 값
//      │    │    └ 대입 기호 (= 는 "같다"가 아니라 "넣어라"입니다)
//      │    └ 이름
//      └ 만드는 방법 (let 또는 const)


// ── 섹션 1: let — 나중에 바뀔 수 있는 값 ──

let price = 1200;
console.log(price);
// 출력: 1200

// 이름만 부르면 담긴 값이 나옵니다. 따옴표를 씌우면 안 됩니다.
console.log("price");
// 출력: price
// (따옴표를 씌우면 값이 아니라 'price'라는 글자 자체가 찍힙니다)

// let 으로 만든 변수는 값을 바꿀 수 있습니다.
price = 1300;
console.log(price);
// 출력: 1300

// 값을 바꿀 때는 let 을 다시 쓰지 않습니다. 이름 = 새값 만 씁니다.
// let 은 "새로 만든다"는 뜻이라 처음 한 번만 씁니다.

// ✏️ 직접 해보기 1 — count 라는 변수에 3을 담고 출력한 뒤,
//                    5로 바꿔서 다시 출력해 보세요.


// ── 섹션 2: const — 바뀌지 않는 값 ──

const shopName = "우리편의점";
console.log(shopName);
// 출력: 우리편의점

// const 로 만든 변수는 값을 바꿀 수 없습니다.
// 아래 주석을 풀고 실행하면 TypeError 가 납니다.
// shopName = "다른편의점";
// 실수: Assignment to constant variable.
//       const 는 "이 값은 안 바뀝니다"라고 약속하는 것입니다.

// 그럼 언제 무엇을 쓸까요?
//   기본은 const 로 만듭니다.
//   "이건 나중에 바뀌겠는데?" 싶을 때만 let 으로 바꿉니다.
// 이렇게 하면 실수로 값이 바뀌는 사고를 컴퓨터가 대신 막아 줍니다.

// ✏️ 직접 해보기 2 — const 로 taxRate 에 0.1 을 담고 출력해 보세요.


// ── 섹션 3: 변수를 계산에 쓰기 ──

const riceBallPrice = 1200;
const drinkPrice = 1800;

console.log(riceBallPrice + drinkPrice);
// 출력: 3000

// 계산 결과도 변수에 담을 수 있습니다.
const total = riceBallPrice + drinkPrice;
console.log("합계", total, "원");
// 출력: 합계 3000 원

// 여기서 riceBallPrice 값을 1200 한 곳만 고치면
// total 도 자동으로 따라 바뀝니다. 이것이 변수를 쓰는 이유입니다.

// ✏️ 직접 해보기 3 — 라떼 4500원, 케이크 6000원을 각각 변수에 담고
//                    합계를 출력해 보세요.


// ── 섹션 4: 이름 짓는 규칙 ──

// [지켜야 하는 규칙 — 어기면 에러]
//   1. 숫자로 시작할 수 없습니다.
//   2. 띄어쓰기를 넣을 수 없습니다.
//   3. let, const 같은 예약어는 이름으로 쓸 수 없습니다.

// const 2ndPrice = 100;      // 실수: 숫자로 시작 → SyntaxError
// const my price = 100;      // 실수: 띄어쓰기 → SyntaxError
// const let = 100;           // 실수: 예약어 → SyntaxError

// [지키면 좋은 약속 — 안 지켜도 돌아가지만 안 지키면 욕먹습니다]
//   1. 무엇이 담겼는지 알 수 있는 이름을 씁니다.
const userAge = 20; // 좋음
const a = 20; // 나쁨 — 20이 뭔지 알 수 없음
console.log(userAge, a);
// 출력: 20 20

//   2. 두 단어 이상이면 뒷 단어의 첫 글자를 대문자로 씁니다. (카멜 표기법)
const userName = "김민준"; // userName  (O)
// const username = "김민준";   // 이것도 되지만 읽기 불편
// const user_name = "김민준";  // 파이썬 스타일. JS에서는 잘 안 씁니다
console.log(userName);
// 출력: 김민준

//   3. 대소문자를 구별합니다. userName 과 username 은 다른 변수입니다.

//   4. 영문자, 숫자, _ , $ 로만 짓습니다.
//      한글로도 만들 수는 있고 문법상 에러도 아닙니다. 그런데도 안 쓰는 이유는,
//      나중에 배울 React·서버 코드가 전부 영어 이름이라 지금부터 습관을 들이는 것입니다.
//      (주석과 화면에 보이는 글자는 계속 한글로 씁니다)


// ── 섹션 5: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] 만들기 전에 사용 → ReferenceError
// console.log(notMadeYet);
// const notMadeYet = 10;
// 실수: 변수는 만든 다음 줄부터 쓸 수 있습니다.

// [실수 2] 같은 이름을 두 번 만들기 → SyntaxError
// const price2 = 100;
// const price2 = 200;
// 실수: 값을 바꾸고 싶은 거라면 let 으로 만들고 price2 = 200; 이라고만 씁니다.

// [실수 3] let 없이 처음부터 이름만 쓰기
// score = 90;
// 실수: 지금은 우연히 돌아가지만, 어디에도 없던 변수가 몰래 만들어져
//       나중에 찾기 힘든 버그가 됩니다. 반드시 const 나 let 을 붙이세요.

// [실수 4] = 를 "같다"로 착각
// 수학에서 = 는 "같다"지만, 프로그래밍에서 = 는 "오른쪽 값을 왼쪽에 넣어라"입니다.
let x = 5;
x = x + 1; // "x에 x+1을 넣어라" → 6
console.log(x);
// 출력: 6
// 수학이었다면 x = x + 1 은 말이 안 되는 식입니다.


// ── 정리 ──

// 1. let 이름 = 값;    → 나중에 바꿀 수 있는 변수
// 2. const 이름 = 값;  → 바꿀 수 없는 변수. 기본은 const 를 쓴다.
// 3. = 는 "같다"가 아니라 "넣어라"
// 4. 이름은 영어 카멜 표기법(userName), 무엇이 담겼는지 알 수 있게



// ============================================================
// 02단원 · 개념 01 — 산술 연산자: 계산하기
// ------------------------------------------------------------
// 실행: node 개념01_산술연산자.js
// ============================================================
//
// 01단원에서는 값을 담고 보여 주기만 했습니다.
// 하지만 프로그램이 하는 일의 대부분은 '계산'입니다.
//   장바구니 총액, 할인가, 평균 점수, 남은 시간, 몇 페이지인지...
// 계산에 쓰는 기호를 산술 연산자라고 합니다.
//
//     +   더하기
//     -   빼기
//     *   곱하기      (× 가 아니라 별표)
//     /   나누기      (÷ 가 아니라 슬래시)
//     %   나머지      (이건 처음 볼 겁니다)
//     **  거듭제곱


// ── 섹션 1: 사칙연산 ──

console.log(7 + 3);
// 출력: 10
console.log(7 - 3);
// 출력: 4
console.log(7 * 3);
// 출력: 21
console.log(7 / 3);
// 출력: 2.3333333333333335

// 나누기 결과에 주의하세요. 초등학교 때처럼 "몫 3, 나머지 1" 로 나뉘지 않습니다.
// 자바스크립트의 / 는
// 소수까지 그대로 나옵니다. 몫만 필요하면 따로 처리해야 합니다. (섹션 4)

// 변수를 넣어도 똑같습니다.
const price = 4500;
const count = 3;
console.log(price * count);
// 출력: 13500

// ✏️ 직접 해보기 1 — 라떼 4500원 2잔과 케이크 6000원 1개의 총액을 출력해 보세요.


// ── 섹션 2: % — 나머지 ──

// % 는 "나누고 남은 것"입니다. 백분율(퍼센트)이 아닙니다.
console.log(10 % 3);
// 출력: 1
// 10 ÷ 3 = 3 ... 나머지 1

console.log(10 % 5);
// 출력: 0
// 딱 나누어떨어지면 나머지가 0입니다.

// 나머지는 이런 데 씁니다.
// [쓰임 1] 짝수/홀수 판별 — 2로 나눈 나머지가 0이면 짝수
console.log(8 % 2);
// 출력: 0
console.log(7 % 2);
// 출력: 1

// [쓰임 2] 초를 분과 초로 나누기
const totalSeconds = 125;
console.log(totalSeconds % 60);
// 출력: 5
// 125초 = 2분 5초 → 남는 초가 5

// [쓰임 3] 여러 개를 순서대로 돌려 쓰기 (0,1,2,0,1,2...)
console.log(0 % 3, 1 % 3, 2 % 3, 3 % 3, 4 % 3);
// 출력: 0 1 2 0 1

// ✏️ 직접 해보기 2 — 17을 5로 나눈 나머지를 출력해 보세요.


// ── 섹션 3: ** — 거듭제곱 ──

console.log(2 ** 3);
// 출력: 8
// 2 × 2 × 2

console.log(10 ** 2);
// 출력: 100

// 별표 하나(*)와 둘(**)은 완전히 다릅니다.
console.log(2 * 3, 2 ** 3);
// 출력: 6 8

// ✏️ 직접 해보기 3 — 한 변이 5인 정사각형의 넓이를 ** 로 구해 출력해 보세요.


// ── 섹션 4: 몫 구하기와 소수 다듬기 ──

// / 는 소수까지 나오므로, 몫만 필요하면 소수점을 버립니다.
console.log(7 / 2);
// 출력: 3.5

// 여기서 Math 가 처음 나옵니다.
// Math 는 자바스크립트가 미리 만들어 둔 '계산 도구 상자' 의 이름입니다.
// 우리가 만든 것이 아니라 처음부터 들어 있습니다.
// 상자 안의 도구를 꺼낼 때 01단원에서 배운 점( . )을 씁니다.
//
//   Math . floor ( 7 / 2 )
//   ────  ─────  ─────────
//   도구상자  도구   재료
//
// 도구에게 일을 시킬 때는 괄호를 붙이고, 그 안에 재료를 넣습니다.
// (.length 처럼 괄호 없이 쓰는 것도 있습니다. 괄호가 붙는 것은
//  "일을 시키는 것", 안 붙는 것은 "이미 가지고 있는 값" 이라고 보면 대체로 맞습니다)

// Math.floor( ) : 소수점 아래를 버림 (내림)
console.log(Math.floor(7 / 2));
// 출력: 3

// Math.ceil( ) : 무조건 올림
console.log(Math.ceil(7 / 2));
// 출력: 4

// Math.round( ) : 반올림
console.log(Math.round(3.4));
// 출력: 3
console.log(Math.round(3.5));
// 출력: 4

// .toFixed(자릿수) : 소수점 아래 자릿수를 정해서 다듬기
console.log((3.14159).toFixed(2));
// 출력: 3.14

// [주의] toFixed 의 결과는 숫자가 아니라 문자열입니다!
console.log(typeof (3.14159).toFixed(2));
// 출력: string
// 계산에 다시 쓰려면 Number( ) 로 되돌려야 합니다.
console.log(Number((3.14159).toFixed(2)), typeof Number((3.14159).toFixed(2)));
// 출력: 3.14 number

// 125초를 "2분 5초"로 나누는 완성형
const sec = 125;
console.log(Math.floor(sec / 60), "분", sec % 60, "초");
// 출력: 2 분 5 초
// 몫은 Math.floor(/), 나머지는 % — 이 조합을 자주 씁니다.

// ✏️ 직접 해보기 4 — 200초가 몇 분 몇 초인지 출력해 보세요.


// ── 섹션 5: 계산 순서 ──

// 수학과 똑같습니다. * / % 를 + - 보다 먼저 계산합니다.
console.log(2 + 3 * 4);
// 출력: 14
// 3*4=12 를 먼저 하고 2를 더합니다. (20 이 아닙니다)

// 괄호로 순서를 바꿀 수 있습니다.
console.log((2 + 3) * 4);
// 출력: 20

// 헷갈리면 괄호를 쓰세요. 괄호는 많이 써도 손해가 없습니다.
const basePrice = 12900;
const discount = 2000;
const taxRate = 0.1;
console.log((basePrice - discount) * (1 + taxRate));
// 출력: 11990.000000000002
// 10900 × 1.1 은 11990 이어야 하는데 뒤에 이상한 꼬리가 붙었습니다.
// 소수 오차 때문입니다. 돈 계산은 이렇게 마무리합니다.
console.log(Math.round((basePrice - discount) * (1 + taxRate)));
// 출력: 11990

// ✏️ 직접 해보기 5 — (5 + 5) 나누기 2 를 계산해 출력해 보세요.


// ── 섹션 6: 특이한 결과들 ──

// 0으로 나누면 에러가 아니라 Infinity(무한대)가 나옵니다.
console.log(5 / 0);
// 출력: Infinity

console.log(-5 / 0);
// 출력: -Infinity

// 0을 0으로 나누면 NaN 입니다.
console.log(0 / 0);
// 출력: NaN

// 소수 계산은 아주 작은 오차가 생깁니다. (01단원에서 봤죠)
console.log(0.1 + 0.2);
// 출력: 0.30000000000000004

// 돈처럼 정확해야 하는 값은 '원' 단위 정수로 다루거나,
// 마지막에 Math.round 나 toFixed 로 다듬습니다.
console.log((0.1 + 0.2).toFixed(1));
// 출력: 0.3


// ── 섹션 7: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] × ÷ 기호 사용 → SyntaxError
// console.log(3 × 4);
// 실수: 곱하기는 * , 나누기는 / 입니다. 수학 기호는 쓸 수 없습니다.

// [실수 2] % 를 퍼센트로 착각
console.log(50 % 100);
// 출력: 50
// 실수: "50퍼센트"가 아니라 "50을 100으로 나눈 나머지"입니다.
//       퍼센트 계산은 곱하기로 합니다.
console.log(200 * 0.5);
// 출력: 100

// [실수 3] 문자열에 + 를 써 놓고 덧셈이라고 생각하기
const inputA = "10";
console.log(inputA + 5);
// 출력: 105
// 실수: 문자열이면 이어붙이기입니다. Number(inputA) + 5 로 고쳐야 합니다.

// [실수 4] toFixed 결과를 숫자로 착각
const fixed = (10.567).toFixed(1);
console.log(fixed + 1);
// 출력: 10.61
// 실수: fixed 는 문자열 "10.6" 이라 이어붙었습니다.
console.log(Number(fixed) + 1);
// 출력: 11.6


// ── 정리 ──

// 1. + - * / % **  — 곱하기는 * , 나누기는 / , 나머지는 %
// 2. / 는 소수까지 나온다. 몫만 필요하면 Math.floor(a / b)
// 3. Math.floor(내림) / Math.ceil(올림) / Math.round(반올림)
// 4. toFixed 의 결과는 문자열이다.
// 5. 계산 순서는 수학과 같다. 헷갈리면 괄호를 쓴다.



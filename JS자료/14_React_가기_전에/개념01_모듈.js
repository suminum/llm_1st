//
// 지금까지는 파일 하나에 전부 담았습니다.
// 13단원 종합03이 300줄이 넘었죠. 실무 프로젝트는 수만 줄입니다.
// 한 파일에 다 넣으면 아무도 못 읽습니다.
//
// 그래서 파일을 나누고, 필요한 것만 서로 꺼내 씁니다.
//   내보내기 : export
//   가져오기 : import
//
// 이것이 React 를 배울 때 가장 먼저 만나는 문법입니다.
// React 파일은 예외 없이 첫 줄이 import 로 시작합니다.
//
// ── 시작하기 전에: package.json ──
//
// 이 폴더에 package.json 이라는 파일이 하나 있습니다. 열어 보면 두 줄뿐입니다.
//
//     { "type": "module" }
//
// "이 폴더의 .js 파일들은 모듈 문법(import/export)을 씁니다" 라는 표시입니다.
// 이게 없으면 node 가 경고를 냅니다.
// 실무 프로젝트에도 이 파일이 항상 있습니다. 지금은 이 정도만 알면 됩니다.

// ── 섹션 1: 이름을 지정해서 가져오기 ──

// 중괄호 안에 '가져올 이름'을 적습니다. 이름은 내보낸 쪽과 똑같아야 합니다.
import { TAX_RATE, addTax } from "./도구모음.js";

console.log(TAX_RATE);
// 출력: 0.1

console.log(addTax(10000));
// 출력: 11000

// 읽는 법
//     import { 가져올것 } from "./어느파일.js";
//              ────────         ─────────────
//              중괄호 안에        경로. ./ 로 시작하고 .js 까지 씁니다
//
// import 는 파일 맨 위에 모아 씁니다. 자바스크립트가 먼저 읽기 때문입니다.

// ✏️ 직접 해보기 1 — 위 import 줄에 formatWon 을 추가로 가져와서
//                    console.log(formatWon(11000)) 을 찍어 보세요.

// ── 섹션 2: 필요한 것만 골라 온다 ──

// 도구모음.js 에는 addTax 말고도 여러 개가 있습니다.
// 그중 지금 쓸 것만 가져오면 됩니다. 안 가져온 것은 없는 것과 같습니다.
//
//     console.log(peek);
//     → ReferenceError: peek is not defined
//       (도구모음.js 에 있지만 여기서 import 하지 않았으니까요)
//
// 안 내보낸 것(SECRET)은 아예 가져올 수 없습니다.
//
//     import { SECRET } from "./도구모음.js";
//     → SyntaxError: does not provide an export named 'SECRET'
//
// export 를 붙인 것만 '공개' 됩니다. 나머지는 그 파일 안의 비밀입니다.

// ✏️ 직접 해보기 2 — 도구모음.js 를 열어 보고,
//                    export 가 붙은 것과 안 붙은 것을 각각 찾아보세요.

// ── 섹션 3: 이름 바꿔서 가져오기 (as) ──

// 이미 같은 이름의 변수가 있거나, 이름이 마음에 안 들 때 씁니다.
import { formatWon as won } from "./도구모음.js";

console.log(won(25000));
// 출력: 25,000원

// 09단원의 구조분해 이름 바꾸기와 방향이 반대입니다. 헷갈리지 마세요.
//     구조분해 : const { name: 새이름 } = 객체;    ← 콜론, 원래이름이 왼쪽
//     import   : import { name as 새이름 } from ... ← as,  원래이름이 왼쪽
//
// 왼쪽이 원래 이름인 것은 같습니다. 기호만 다릅니다.

// ✏️ 직접 해보기 3 — addTax 를 세금붙이기 라는 이름으로 가져와 써 보세요.

// ── 섹션 4: export default — 대표 하나 ──

// default 로 내보낸 것은 중괄호 없이 가져옵니다.
// 그리고 이름을 내 마음대로 지어도 됩니다.
import greet from "./도구모음.js";

console.log(greet("김민준"));
// 출력: 김민준님 안녕하세요

// 도구모음.js 에서는 greet 이라는 이름이었지만, 아무 이름이나 됩니다.
// default 는 파일에 하나뿐이라 헷갈릴 일이 없기 때문입니다.

// 둘을 같이 쓸 수도 있습니다. default 가 앞, 중괄호가 뒤입니다.
//
//     import greet, { addTax } from "./도구모음.js";
//
// React 에서 매일 보게 될 모양입니다.
//
//     import React, { useState } from "react";
//            ─────   ──────────
//            default   이름 지정
//
// 여기서 "react" 는 ./ 가 없습니다. 우리가 만든 파일이 아니라
// 남이 만들어 놓은 것을 내려받아 쓰기 때문입니다. (React 과정에서 배웁니다)

// ✏️ 직접 해보기 4 — 위 import 줄의 greet 을 인사 라는 이름으로 바꿔도
//                    잘 되는지 확인해 보세요.

// ── 섹션 5: 실제로 어떻게 나누나 ──

// 정답은 "같이 바뀌는 것끼리 한 파일에" 입니다.
//
//     계산기.js     세금·할인·합계 계산
//     화면.js       화면 그리기
//     데이터.js     서버에서 받아오기
//
// 13단원 종합03을 이렇게 나눠 보면 이렇게 됩니다.
//
//     할일데이터.js   todos 배열과 추가·삭제·토글 함수
//     화면그리기.js   render, updateStatus
//     main.js        둘을 가져와 이벤트를 붙이는 곳
//
// 파일이 늘어나는 게 아니라, 한 파일이 짧아지는 것입니다.
// 나중에 고칠 때 "어디를 고쳐야 하지?" 를 안 헤매게 됩니다.

// ── 섹션 6: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.

// [실수 1] 확장자를 빼먹음 → 에러
// import { addTax } from "./도구모음";
// 실수: Cannot find module ... 브라우저와 node 모두 .js 까지 적어야 합니다.
//       (React 에서는 도구가 알아서 붙여 줘서 생략합니다. 지금은 꼭 적으세요)

// [실수 2] ./ 를 빼먹음 → 에러
// import { addTax } from "도구모음.js";
// 실수: ./ 가 없으면 "내려받은 남의 코드" 를 찾습니다. 내 파일은 ./ 로 시작합니다.

// [실수 3] default 를 중괄호로 감쌈 → SyntaxError
// import { greet } from "./도구모음.js";
// 실수: default 는 중괄호 없이 가져옵니다. 중괄호는 이름 지정한 것만.

// [실수 4] 이름을 틀리게 씀 → SyntaxError
// import { addtax } from "./도구모음.js";
// 실수: 대소문자까지 정확히 같아야 합니다. addTax 입니다.

// [실수 5] import 를 함수 안에 씀 → SyntaxError
//   function load() {
//     import { addTax } from "./도구모음.js";
//   }
// 실수: import 는 파일 맨 바깥, 맨 위에만 쓸 수 있습니다.

// ── 정리 ──

// 1. export 를 붙인 것만 밖에서 가져다 쓸 수 있다.
// 2. import { 이름 } from "./파일.js";  — 중괄호, ./ , .js 세 가지를 꼭 지킨다.
// 3. as 로 이름을 바꿔서 가져올 수 있다.
// 4. export default 는 파일당 하나. 중괄호 없이, 아무 이름으로나 가져온다.
// 5. import 는 파일 맨 위에 모아 쓴다.
// 6. 이 폴더의 package.json 한 줄이 "모듈 문법을 쓴다" 는 표시다.


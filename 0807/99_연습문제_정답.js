// ═══ 문제 1 정답 ═══ if / else
console.log("===== 문제 1 =====");
{
  const mathScore = 85;
  if (mathScore > 80) {
    console.log("우수 학생 명단에 올랐습니다"); // 출력: 우수 학생 명단에 올랐습니다
  } else {
    console.log("다음 시험에서 더 힘내 봅시다");
  }
  // 해설 ①: if/else 는 "둘 중 반드시 하나만" 실행됩니다. 둘 다 실행되거나 둘 다 안 되는 경우는 없습니다.
  //   그래서 else 를 쓰면 "나머지 전부"가 자동으로 처리됩니다. mathScore <= 80 이라고 다시 쓸 필요가 없습니다.
  //
  // 해설 ②: 소괄호 안에는 반드시 true/false 로 판정되는 식이 들어갑니다.
  //   if (mathScore) 처럼 값만 넣으면 85 는 "참으로 취급"되어 항상 통과합니다 — 의도한 조건이 아닙니다.
  //
  // 해설 ③: 자주 나오는 실수 두 가지
  //   - if (mathScore = 85) → = 하나는 "비교"가 아니라 "대입"입니다. 값이 덮어써지고 늘 통과합니다.
  //   - if (mathScore > 80); → 끝에 세미콜론을 찍으면 if 가 거기서 끝나 버려, 아래 블록이 조건과 무관하게 실행됩니다.
  //     둘 다 에러가 나지 않아서 찾기 어렵습니다. 조건문이 이상하면 이 둘부터 확인하세요.
}

// ═══ 문제 2 정답 ═══ else if 다중 조건
console.log("===== 문제 2 =====");
{
  const examScore = 88;
  if (examScore >= 95) {
    console.log("A등급 - 최우수");
  } else if (examScore >= 85) {
    console.log("B등급 - 우수"); // 출력: B등급 - 우수
  } else if (examScore >= 70) {
    console.log("C등급 - 보통");
  } else {
    console.log("D등급 - 노력 필요");
  }
  // 해설 ①: else if 는 위에서부터 검사하다가 "처음 true 가 되는 하나"에서 멈춥니다.
  //   88점은 >= 85 에서 걸리므로 그 아래 >= 70 은 아예 검사조차 하지 않습니다.
  //
  // 해설 ②: 그래서 각 조건에 "그리고 95 미만"을 붙일 필요가 없습니다.
  //   >= 85 줄까지 내려왔다는 것 자체가 이미 "95 미만"이라는 뜻이기 때문입니다.
  //   (examScore >= 85 && examScore < 95) 라고 쓴 학생이 많은데, 틀리진 않지만 중복입니다.
  //
  // 해설 ③: 순서가 곧 로직입니다 — >= 70 을 맨 위로 올리면 88점도, 100점도 전부 C등급이 됩니다.
  //   에러는 안 나고 결과만 조용히 틀립니다. 이것이 else if 에서 가장 자주 나는 사고입니다.
  //   ⇒ 규칙: 범위가 "좁은 것 = 값이 큰 것"부터 위에 놓습니다.
  //
  // 해설 ④: 마지막 else 에는 조건이 없습니다. "앞의 조건에 하나도 안 걸린 나머지 전부"라는 뜻입니다.
  //   else 를 빼면 70점 미만일 때 아무것도 출력되지 않습니다 — 화면이 비면 이걸 먼저 의심하세요.
}

// ═══ 문제 3 정답 ═══ switch
console.log("===== 문제 3 =====");
{
  const subjectCode = 3;
  switch (subjectCode) {
    case 1:
      console.log("국어 시간");
      break;
    case 2:
      console.log("수학 시간");
      break;
    case 3:
      console.log("체육 시간 - 체육복 준비"); // 출력: 체육 시간 - 체육복 준비
      break;
    default:
      console.log("알 수 없는 코드");
      break;
  }
  // 해설 ①: switch 는 "값 하나를 여러 후보와 대조"할 때 씁니다.
  //   지금은 subjectCode 가 1이냐 2냐 3이냐만 봅니다. 이럴 때 else if 를 세 번 쓰면
  //   subjectCode 라는 이름이 계속 반복되는데, switch 는 소괄호에 한 번만 씁니다.
  //   반대로 "점수 >= 85" 처럼 범위를 따지는 조건은 switch 로 못 씁니다. 그건 else if 몫입니다.
  //
  // 해설 ②: case 는 === 로 비교합니다. 타입까지 봅니다.
  //   화면 입력값처럼 "3"(문자열)이 들어오면 case 3: 에 걸리지 않고 default 로 빠집니다.
  //   숫자로 비교할 생각이라면 switch (Number(subjectCode)) 로 먼저 바꿔야 합니다.
  //
  // 해설 ③: break 를 빼면 왜 아래로 흘러가는가 —
  //   switch 는 "일치하는 case 를 찾아 그 지점으로 점프"할 뿐, 거기서 멈추라는 뜻은 없습니다.
  //   break 가 "여기서 나가라"입니다. 없으면 만나는 코드를 계속 실행합니다.
  //   case 3 에서 break 를 빼면 "체육 시간"과 "알 수 없는 코드"가 함께 출력됩니다. 직접 지워 보세요.
  //
  // 해설 ④: default 는 else 자리입니다. 맨 아래에 두는 것이 관례이고, 마지막이라도 break 를 붙여 둡니다.
  //   나중에 case 를 아래에 추가할 때 사고를 막아 줍니다.
}

// ═══ 문제 4 정답 ═══ 삼항 연산자
console.log("===== 문제 4 =====");
{
  const wrongCount = 3;
  const currentHour = 22;
  const testResult = wrongCount === 0 ? "통과" : "재시험"; // 조건 ? 참일 때 : 거짓일 때
  console.log(`채점 결과: ${testResult}`); // 출력: 채점 결과: 재시험
  const periodName = currentHour >= 18 ? "야간 자습" : "정규 수업";
  console.log(`현재 일과: ${periodName}`); // 출력: 현재 일과: 야간 자습
  // 해설 ①: 삼항 연산자와 if/else 의 결정적 차이 —
  //   if/else 는 "실행"하는 문장이고, 삼항 연산자는 "값"이 됩니다.
  //   값이니까 = 오른쪽에 놓아 변수에 담을 수 있습니다. if 는 그렇게 못 합니다.
  //     ✅ const r = 조건 ? "통과" : "재시험";
  //     ❌ const r = if (조건) ...   ← 문법 오류
  //
  // 해설 ②: 그래서 판단 기준은 "짧아서"가 아니라 "값을 고르는 일인가"입니다.
  //   값 하나를 고른다 → 삼항. 여러 줄을 실행하고 출력까지 한다 → if/else.
  //   삼항 안에 console.log 를 넣는 학생이 있는데, 되긴 하지만 읽기 어려워집니다.
  //
  // 해설 ③: 물음표 앞은 반드시 true/false 가 되는 식입니다.
  //   wrongCount === 0 을 wrongCount = 0 으로 잘못 쓰면 값이 0으로 덮어써지고 늘 "재시험"이 됩니다.
  //
  // 해설 ④: 삼항을 겹쳐 쓰는 것(a ? b : c ? d : e)은 문법상 되지만 읽기가 급격히 어려워집니다.
  //   갈래가 셋 이상이면 else if 로 돌아가세요. 짧은 코드가 늘 좋은 코드는 아닙니다.
}

// ═══ 문제 5 정답 ═══ for 문 누적 합
console.log("===== 문제 5 =====");
{
  const mealCounts = [120, 135, 110, 150, 125];
  let weekTotal = 0; // 합계 변수는 반복문 "밖"에! (안에 선언하면 매번 0으로 초기화됨)
  for (let i = 0; i < mealCounts.length; i++) {
    weekTotal += mealCounts[i]; // 인덱스로 요소에 접근해 누적
  }
  console.log(`주간 총 급식 인원: ${weekTotal}명`); // 출력: 주간 총 급식 인원: 640명
  console.log(`하루 평균 급식 인원: ${weekTotal / mealCounts.length}명`); // 출력: 하루 평균 급식 인원: 128명
  // 해설 ①: 누적은 "그릇을 밖에 두고, 안에서 계속 담는" 구조입니다.
  //   weekTotal 을 for 안에 선언하면 매 회차 새 그릇이 만들어져 0으로 돌아갑니다.
  //   "합계가 마지막 값만 나온다"는 증상이 나오면 100% 이 실수입니다. 9일차 최다 실수입니다.
  //
  // 해설 ②: for 의 세 칸이 각각 언제 실행되는지 —
  //   let i = 0     → 딱 한 번, 시작할 때만
  //   i < length    → 매 회차 "시작 전"에 검사 (거짓이면 그 자리에서 반복 종료)
  //   i++           → 매 회차 "끝난 뒤"에 실행
  //   그래서 i 는 0,1,2,3,4 까지만 돌고 5에서 조건이 거짓이 되어 멈춥니다.
  //
  // 해설 ③: 왜 i <= length 가 아니라 i < length 인가 —
  //   길이가 5면 인덱스는 0~4 입니다. <= 로 쓰면 없는 mealCounts[5] 에 접근해 undefined 가 나오고,
  //   숫자에 undefined 를 더하면 합계가 통째로 NaN 이 됩니다. 에러는 안 납니다.
  //
  // 해설 ④: 5 라고 직접 쓰지 않고 mealCounts.length 를 쓴 이유 —
  //   나중에 급식 데이터가 6일치로 늘어나도 이 코드는 고칠 데가 없습니다.
  //   반대로 5 를 하드코딩해 두면 데이터가 늘 때마다 코드를 찾아다니며 고쳐야 하고, 꼭 하나를 빠뜨립니다.
  //
  // 계산: 120 + 135 + 110 + 150 + 125 = 640, 640 / 5 = 128.
}

// ═══ 문제 6 정답 ═══ while + break
console.log("===== 문제 6 =====");
{
  let classPoints = 0;
  let addCount = 0;
  while (true) {
    classPoints += 40; // 한 번에 40점 적립
    addCount++;
    if (classPoints >= 200) {
      break; // 목표에 도달하면 즉시 종료
    }
  }
  console.log(`적립 횟수: ${addCount}회`); // 출력: 적립 횟수: 5회
  console.log(`최종 점수: ${classPoints}점`); // 출력: 최종 점수: 200점
  // 해설 ①: 왜 for 가 아니라 while 인가 —
  //   "몇 번 반복할지"를 미리 모르기 때문입니다. 40점씩 몇 번을 더해야 200이 될지는 돌려 봐야 압니다.
  //   횟수를 알면 for, 조건이 끝을 정하면 while. 이것이 둘을 고르는 유일한 기준입니다.
  //
  // 해설 ②: while (true) 는 "조건은 나중에 안에서 판단하겠다"는 뜻입니다.
  //   소괄호가 항상 참이므로 반복을 끝내는 유일한 출구는 break 하나뿐입니다.
  //   ⚠️ 그래서 while (true) 를 쓸 때는 "break 에 반드시 도달하는가"를 눈으로 확인해야 합니다.
  //   여기서 classPoints += 40 을 빼먹으면 점수가 영원히 0이라 프로그램이 멈추지 않습니다.
  //   (무한 루프에 빠졌다면 터미널에서 Ctrl + C 로 강제 종료하세요. 당황하지 않아도 됩니다.)
  //
  // 해설 ③: 순서가 결과를 바꿉니다 — 지금은 "더하고 → 세고 → 검사"입니다.
  //   검사를 맨 위로 올리면 200이 된 회차의 addCount++ 가 실행되지 않아 답이 4회로 나옵니다.
  //   반복문 안에서는 "무엇을 먼저 하는가"가 곧 결과입니다.
  //
  // 해설 ④: break 는 if 안에 있지만 끝내는 것은 if 가 아니라 while 입니다.
  //   break 는 언제나 "자기를 감싼 가장 가까운 반복문"을 끝냅니다. if 는 반복문이 아닙니다.
  //
  // 계산: 40, 80, 120, 160, 200 으로 5회 만에 200 이상이 되어 break.
}

// ═══ 문제 7 정답 ═══ [도전] 시험 점수 분석
console.log("===== 문제 7 =====");
{
  const scores = [72, 81, -1, 85, 77, -1, 83];
  let validCount = 0;
  let highCount = 0;
  let maxScore = 0;
  for (let i = 0; i < scores.length; i++) {
    if (scores[i] === -1) {
      continue; // 결시 -> 이번 차례의 나머지를 건너뛰고 다음 학생으로
    }
    validCount++;
    if (scores[i] > 80) {
      highCount++;
    }
    if (scores[i] > maxScore) {
      maxScore = scores[i]; // 지금까지의 최고값보다 크면 교체
    }
  }
  console.log(`응시 인원: ${validCount}명`); // 출력: 응시 인원: 5명
  console.log(`80점 초과: ${highCount}명`); // 출력: 80점 초과: 3명
  console.log(`최고 점수: ${maxScore}점`); // 출력: 최고 점수: 85점
  // 해설 ①: continue 는 "이번 차례만" 건너뜁니다. 반복 자체는 계속됩니다.
  //   그래서 -1 을 만나면 그 아래 세 줄(validCount++, highCount, maxScore)이 통째로 건너뛰어지고
  //   결시 학생은 어떤 집계에도 섞이지 않습니다. break 를 쓰면 첫 -1 에서 분석이 끝나 버립니다.
  //
  // 해설 ②: 최고값 찾기는 "지금까지의 챔피언"을 변수 하나에 들고 다니며 도전자와 비교하는 방식입니다.
  //   비교가 끝나야 챔피언이 확정되므로 maxScore 는 반드시 반복문 밖에 선언합니다.
  //
  // 해설 ③: 왜 maxScore 를 0 에서 시작했는가 —
  //   점수는 0 이상이라 어떤 실제 점수든 0 보다 크기 때문입니다.
  //   ⚠️ 이건 이 문제에서만 통하는 방법입니다. 기온처럼 음수가 나올 수 있는 데이터라면
  //   0 으로 시작하면 영하 값이 하나도 못 이겨서 최고값이 엉뚱하게 0 이 됩니다.
  //   그럴 땐 "배열의 첫 요소"로 시작해야 안전합니다 (심화2 문제 1 에서 다시 다룹니다).
  //   여기서는 첫 요소가 -1(결시)일 수도 있어서 오히려 0 시작이 맞습니다.
  //
  // 계산: 응시 5명(72, 81, 85, 77, 83), 그중 80점 초과는 3명(81, 85, 83), 최고 점수는 85점.
}

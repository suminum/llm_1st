// ── 실습: 13의 배수면서 홀수인 숫자 찾기 (for 문) ──────────────
console.log("===== 실습: 13의 배수면서 홀수인 숫자 찾기 =====");
// 문제: 10000 까지의 숫자 중에서 13의 배수면서 홀수인 숫자를 찾아 봅시다!
//   (응용: 브라우저에서는 10000 대신 prompt로 입력받은 수를 쓰면 됩니다)
// Step 1: for로 1부터 10000까지 반복
// Step 2: 나머지 %로 "13의 배수"와 "홀수" 두 조건을 만들고 &&로 결합
for (let n = 1; n <= 10000; n++) {
  if (n % 13 === 0 && n % 2 === 1) {
    console.log(n);
  }
}
// 출력: 13
// 출력: 39
// ...(중략: 13부터 9997까지 총 385개)...
// 출력: 9997

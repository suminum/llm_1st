// ── 실습: 2 또는 5의 배수 총합 ──────────────
console.log("===== 실습: 2 또는 5의 배수 총합 =====");
// 문제: 0 ~ 100 의 숫자 중에서 2 또는 5의 배수 총합을 구하시오!
//   힌트: 나머지 연산자 % 를 사용 (5 % 3 = 2)
// Step 1: 합계 변수를 반복문 밖에 준비
// 반복문 "안"에 let multipleSum = 0; 을 쓰면 매 회차마다 0으로 초기화되어
// 누적이 전혀 안 됩니다. 누적 변수는 항상 반복문 밖에서 한 번만 선언하세요.
let multipleSum = 0;
// Step 2: 2의 배수 또는(||) 5의 배수면 누적
for (let n = 0; n <= 100; n++) {
  if (n % 2 === 0 || n % 5 === 0) {
    multipleSum += n;
  }
}
console.log("2 또는 5의 배수 총합:", multipleSum);  // 출력: 2 또는 5의 배수 총합: 3050

// ── 실습: 오전 오후 판별 (삼항 연산자) ──────────────
console.log("===== 실습: 오전 오후 판별 =====");
// 문제: 삼항 연산자로 지금이 오전인지 오후인지 콘솔창에 출력해 보세요.
//   new Date().getHours() 는 0~23 까지의 숫자를 반환 (0 = 자정, 12 = 정오)
// Step 1: 현재 시각(0~23) 구하기
let now = new Date().getHours();
// 읽는 순서: new Date()로 "지금 이 순간"을 만들고 → .getHours()로 시(時)만 꺼냄
// 실행할 때마다 값이 달라지므로, 결과가 매번 같지 않은 것이 정상입니다.

// Step 2: 삼항 연산자 - 조건식 ? 참인 경우 : 거짓인 경우
now < 12 ? console.log("지금은 오전입니다") : console.log("지금은 오후입니다");
// └조건    └true면 이것 실행           └false면 이것 실행
// ? 는 "~라면", : 는 "아니면"으로 읽으면 문장이 됩니다.
// if/else로 쓰면 5줄인 것을 1줄로 줄인 것 — 동작은 완전히 같습니다.
// 출력: 지금은 오전입니다 (12시 이후에 실행하면 "지금은 오후입니다")

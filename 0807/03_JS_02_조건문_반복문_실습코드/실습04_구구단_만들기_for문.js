// ── 실습: 구구단 만들기 (for 문) ──────────────
console.log("===== 실습: 구구단 만들기 (for 문) =====");
// 문제: for 문을 이용해서 구구단을 만들어 봅시다!
//   힌트: 중첩 반복문을 사용하면 "단 x 곱하는 수 = 결과" 형태로 출력할 수 있습니다.
// Step 1: 바깥 for = 단 (2~9)
// Step 2: 안쪽 for = 곱하는 수 (1~9)
// Step 3: 템플릿 리터럴로 출력 형태 맞추기
for (let dan = 2; dan <= 9; dan++) {   // 2단부터 9단까지 → 8번 반복
  for (let n = 1; n <= 9; n++) {       // 각 단마다 1~9 → 9번 반복
    console.log(`${dan} x ${n} = ${dan * n}`);
    //           └단   └곱하는 수  └결과는 ${} 안에서 바로 계산
  }
}
// 총 8 x 9 = 72줄. 안쪽 반복이 끝나야 바깥 dan이 1 증가해 다음 단으로 넘어갑니다.
// 1단(1x1=1 …)은 의미가 없어 2부터, 구구단이라 9까지 — 시작·끝 값에도 이유가 있습니다.
// 출력: 2 x 1 = 2
// 출력: 2 x 2 = 4
// ...(중략)...
// 출력: 9 x 9 = 81  (2단~9단 총 72줄)

// ── [추가 실습] 장학금 판정 (보너스 — 빨리 끝냈다면 도전해 보세요) ──
console.log("===== [추가 실습] 장학금 판정 =====");
// 문제: avgScore(평균 점수) 값에 따라 판정을 출력하세요.
//   100 이상: 전액 장학금 / 90 이상: 반액 장학금 / 80 이상: 장려 장학금 / 60 이상: 통과 / 그 외: 재수강 대상
//   (연령대 실습과 같은 구조 - 좁은 범위=높은 값부터 검사!)
// Step 1: 평균 점수 변수 선언
const avgScore = 92;
// Step 2: 높은 점수(좁은 범위)부터 순서대로 검사
// 마지막 else에 조건이 없는 이유: 위 네 조건에 모두 걸리지 않은 나머지 전부(60 미만)이므로
// else if (avgScore < 60) 이라고 다시 쓸 필요가 없습니다.
if (avgScore >= 100) {
  console.log("전액 장학금");
} else if (avgScore >= 90) {
  console.log("반액 장학금 - 축하합니다");  // 출력: 반액 장학금 - 축하합니다
} else if (avgScore >= 80) {
  console.log("장려 장학금");
} else if (avgScore >= 60) {
  console.log("통과");
} else {
  console.log("재수강 대상");
}

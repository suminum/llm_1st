// Step 순서대로 따라가며 확인하세요.
// node 실습01_연령대_판정.js 로 실행하며 결과를 확인합니다.

// ── 실습: 연령대 판정 (if 문) ──────────────
console.log("===== 실습: 연령대 판정 =====");
// 문제: if 문을 이용해서 console 창에 연령대별 단어를 출력해 봅시다.
//   age 변수 선언
//   age 가 20 이상: 성인 / 17 이상: 고등학생 / 14 이상: 중학생
//   age 가 8 이상: 초등학생 / 0 이상: 유아
// Step 1: age 변수 선언
const age = 15;
// Step 2: 좁은 범위(높은 나이)부터 순서대로 검사 - 처음 true인 블록 하나만 실행
// 15살이 어떻게 걸러지는지 따라가 보세요:
//   age >= 20 → false / age >= 17 → false / age >= 14 → true! 여기서 멈춤
// 만약 순서를 뒤집어 age >= 0 을 맨 위에 두면 모든 나이가 "유아"로 나옵니다 —
// 0 이상은 누구나 참이라 첫 줄에서 걸려 버리기 때문입니다.
if (age >= 20) {
  console.log("성인");
} else if (age >= 17) {
  console.log("고등학생");
} else if (age >= 14) {
  console.log("중학생");  // 출력: 중학생
} else if (age >= 8) {
  console.log("초등학생");
} else if (age >= 0) {
  console.log("유아");
}

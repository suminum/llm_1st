//   for 문 또는 while 문 어떤 것을 사용해도 좋습니다. 중첩 반복문을 활용해 보세요.
//   (앞 실습에서 for 문을 썼으니 이번에는 while 문 버전으로!)
// Step 1: 바깥 변수 i = 단, 안쪽 변수 j = 곱하는 수
let i = 2, j = 1;
// Step 2: 중첩 while - 안쪽 반복이 끝나면 j를 1로 되돌리는 것이 핵심
while (i < 10) {
  while (j < 10) {
    console.log(i, "x", j, "=", i * j);
    j++;              // 안쪽 증감 — 없으면 j가 1에 머물러 무한 루프
  }
  i++;                // 안쪽이 끝난 뒤에야 다음 단으로
  j = 1;              // ★ 핵심: j를 1로 되돌리기
  //                     이 줄이 없으면 j가 10인 채로 남아 3단부터는
  //                     안쪽 while 조건(j < 10)이 처음부터 거짓이라 2단만 출력됩니다.
}
// for 문과 비교해 보세요 — for는 (초기화; 조건; 증감)이 한 줄에 모여 있어서

// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션14_continue.js 로 실행하며 결과를 확인합니다.

// ── 섹션 14: continue - 이번 회차만 건너뛰기 ──────────────
console.log("===== 섹션 14: continue =====");
// 앞 섹션의 break와 짝으로 외우세요:
//   break    = 반복문을 완전히 나감      (극장에서 퇴장)
//   continue = 이번 회차만 건너뛰고 계속 (이번 곡만 스킵하고 다음 곡으로)
// [기본] 현재 회차의 나머지를 건너뛰고 다음 회차로 진행 (반복문이 끝나는 게 아님)
let oddSum = 0;
for (let i = 0; i < 100; i++) {
  if (i % 2 === 0) {
    continue;  // 짝수면 아래 누적을 건너뜀
  }
  oddSum += i;
}
console.log("0~99 홀수 합:", oddSum);  // 출력: 0~99 홀수 합: 2500
// 주의: break/continue 모두 중첩 반복문에서는 가장 안쪽 반복문에만 영향

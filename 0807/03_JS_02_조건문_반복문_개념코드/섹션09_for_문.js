// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션09_for_문.js 로 실행하며 결과를 확인합니다.

// ── 섹션 9: for 문 ──────────────
console.log("===== 섹션 9: for 문 =====");
// [기본] 동작 순서: 초기화(한 번) -> 조건 평가 -> 블록 실행 -> 증감 -> 조건 평가 -> ...
// 소괄호 안은 세미콜론으로 나뉜 세 부분입니다 (쉼표가 아닙니다):
//   let i = 0  → 초기화: 시작 값. 딱 한 번만 실행
//   i < 3      → 조건:   매번 검사해서 참일 때만 블록을 실행
//   i++        → 증감:   블록이 끝날 때마다 실행 (i를 1 증가)
// 비유 — 계단 오르기: ①몇 층에서 출발할지 ②몇 층까지 갈지 ③한 번에 몇 칸씩 오를지.
// 셋 중 하나만 틀려도 엉뚱한 층에 도착하거나 영원히 계단을 오르게 됩니다.
// 놓치기 쉬운 점: 증감은 블록보다 "나중"입니다. 블록을 한 번 실행하고 나서 i가 올라갑니다.
for (let i = 0; i < 3; i++) {
  // i는 0, 1, 2로 바뀝니다 (3이 되는 순간 조건이 거짓이라 멈춤) → 총 3번 반복
  console.log("인사를", i + 1, "번째 드립니다!");  // i+1을 쓴 이유: i가 0부터라 사람이 읽기 좋게 보정
}
// 출력: 인사를 1 번째 드립니다!
// 출력: 인사를 2 번째 드립니다!
// 출력: 인사를 3 번째 드립니다!
// i는 index(색인)의 i입니다. 0부터 시작하는 이유는 8일차에 배운 배열 인덱스가 0부터라
// 짝을 맞추기 위해서입니다. 그래서 화면에 보이는 번호(1,2,3)와 내부 번호(0,1,2)가
// 1씩 차이 나고, 위처럼 i + 1로 보정하게 됩니다 — 앞으로 계속 마주칠 상황입니다.
// 사용 시점: 반복 횟수가 명확할 때, 배열 인덱스 기반 순회
// 실수: for (let i = 0; i < 3; i--)  // 조건에서 멀어지는 증감 -> 무한 루프!

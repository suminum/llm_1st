// ── 섹션 12: while 문 ──────────────
console.log("===== 섹션 12: while 문 =====");
// for와 나눠 쓰는 기준:
//   반복 횟수를 미리 알 때   → for   (배열 10개 순회, 구구단 9번)
//   조건이 만족될 때까지     → while (사용자가 그만둘 때까지, 목표 금액을 넘길 때까지)
// for는 초기화·조건·증감이 한 줄에 모여 있지만, while은 흩어져 있어 빠뜨리기 쉽습니다.
// [기본] 조건이 참인 동안 반복 - 증감식이 기본 포함되어 있지 않아 직접 챙겨야 함
let greet = 0;
while (greet < 3) {
  console.log("인사를", greet + 1, "번째 드립니다!");
  greet++;  // 이 줄이 없으면 무한 루프!
}
// 출력: 인사를 1 번째 드립니다!
// 출력: 인사를 2 번째 드립니다!
// 출력: 인사를 3 번째 드립니다!
// 실수: while (greet < 3) { console.log(greet); }  // greet이 변하지 않아 무한 루프 -> 탭이 멈춤
// 무한루프 체크리스트: 1) 조건이 false가 될 수 있는가? 2) 증감이 올바른 방향인가?

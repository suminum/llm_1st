// ── 섹션 8: 삼항 연산자 ──────────────
console.log("===== 섹션 8: 삼항 연산자 =====");
// [기본] if-else를 한 줄로: 조건식 ? 참인 경우 : 거짓인 경우;
let inputName = "mike";
if (inputName === "mike") {
  console.log("맞았어요");  // 출력: 맞았어요
} else {
  console.log("틀렸어요");
}
// [축약] 위 if-else와 같은 동작을 한 줄로
inputName === "mike" ? console.log("맞았어요") : console.log("틀렸어요");  // 출력: 맞았어요
// [다른 방법] 결과값을 변수에 담을 때 특히 유용
const grade = 95 >= 90 ? "합격" : "불합격";
//            └조건        └참일 때 └거짓일 때 — if는 값을 돌려주지 않아 이렇게 쓸 수 없습니다
console.log(grade);  // 출력: 합격
// 쓰는 기준: "둘 중 하나를 골라 변수에 담을 때"만. 실행할 코드가 여러 줄이면 if를 쓰세요.
// 실수: 삼항 안에 삼항을 또 넣기 — 짧아 보여도 읽기 어려워집니다. 그럴 땐 else if로.

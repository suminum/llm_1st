// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션03_조건식_만들기_비교_논리_연산자.js 로 실행하며 결과를 확인합니다.

// ── 섹션 3: 조건식 만들기 - 비교 · 논리 연산자 ──────────────
console.log("===== 섹션 3: 조건식 만들기 - 비교 · 논리 연산자 =====");
// if 소괄호 안은 최종적으로 true 아니면 false 하나로 계산됩니다.
// 조건이 여러 개일 때 그것들을 하나로 합치는 도구가 논리 연산자입니다.
// [기본] OR (||) - 하나라도 true면 통과
let userName = "뽀로로";
let age = 18;
if (userName === "뽀로로" || age > 19) {
  //  └ true              └ false      →  true || false  →  true
  //  ||는 세로 막대 두 개 (백스페이스 아래 \ 와 같은 키를 Shift와 함께)
  console.log("통과");  // 출력: 통과
} else {
  console.log("돌아가");
}
// [기본] AND (&&) - 둘 다 true여야 통과
if (userName === "뽀로로" && age > 19) {
  //  └ true              └ false      →  true && false  →  false
  //  조건이 같아도 연산자 하나만 바뀌면 결과가 뒤집힙니다.
  console.log("통과");
} else {
  console.log("돌아가");  // 출력: 돌아가
}
// 헷갈릴 때: OR은 "느슨하게"(하나만 맞아도 OK), AND는 "빡빡하게"(다 맞아야 OK)
// [기본] NOT (!) - boolean 반전
let isAdult = age > 19;   // 18 > 19 → false 가 변수에 저장됨
if (!isAdult) {           // !false → true 이므로 블록 실행
  //  느낌표는 "~가 아니라면"으로 읽으세요 — "성인이 아니라면"
  console.log("미성년자입니다.");  // 출력: 미성년자입니다.
}
// 실수: if (age = 20)  // = 는 할당이라 항상 참이 됨 -> 비교는 반드시 === 사용
// 오늘 최대 지뢰입니다. 두 가지 일이 동시에 벌어집니다:
//   ① age가 진짜로 20으로 바뀝니다 (원래 값이 날아감)
//   ② 그 결과 20이 조건 자리에 들어가 항상 참이 됩니다
// 에러가 안 나기 때문에 발견이 늦습니다.
// 외울 문장: 값을 넣는 건 = , 값을 묻는 건 ===

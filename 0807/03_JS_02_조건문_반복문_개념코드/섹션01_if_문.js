// 03_JS_02_조건문_반복문 개념코드 — 섹션 1. if 문 (JavaScript)
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션01_if_문.js 로 실행하며 결과를 확인합니다.

// ── 섹션 1: if 문 ──────────────
console.log("===== 섹션 1: if 문 =====");
// 어제까지 코드는 위에서 아래로 한 줄도 빠짐없이 실행됐습니다.
// 오늘부터는 "상황에 따라 건너뛰는" 갈림길을 만듭니다.
// if 소괄호 안은 8일차에 배운 boolean(true/false)이 들어갈 자리입니다.
// [기본] 조건이 참(true)일 때만 블록 { } 안의 문장을 실행
let temp = 85;
if (temp > 80) {          // 85 > 80 을 먼저 계산 → true → 중괄호 안 실행
  //  중괄호 { }는 "여기부터 여기까지가 한 묶음"이라는 표시입니다.
  console.log("온도 경고!");  // 출력: 온도 경고!
}
// 조건이 거짓이면 중괄호 안을 통째로 건너뛰고 아래로 내려갑니다 (에러가 아닙니다).

// [다른 방법] 변수 자체가 true/false로 판별 가능하면 변수만 조건으로 사용
let isPresent = true;
if (isPresent) {          // 이미 true라서 비교할 필요가 없음
  //  if (isPresent === true) 라고 써도 되지만 군더더기입니다.
  //  그래서 boolean 변수 이름을 is~, has~ 로 지으면 조건문이 문장처럼 읽힙니다.
  console.log("출석 완료");  // 출력: 출석 완료
}
// 실수: if (temp > 80);  // 조건 뒤에 세미콜론을 붙이면 블록이 분리되어 항상 실행됨

// ── 섹션 5: if 중첩 ──────────────
console.log("===== 섹션 5: if 중첩 =====");
// && 로 합치는 것과 무엇이 다른가:
//   isSubmitted && reportScore < 80  → 조건을 한 번에 판단 (제출 안 했을 때 아무 반응 없음)
//   중첩                              → 단계별로 판단 (제출 여부를 먼저 거른 뒤 점수를 봄)
// "먼저 확인할 것이 있고, 통과한 것만 다음 단계로" 보낼 때 중첩을 씁니다.
// [기본] if 문 안에 또 다른 if 문을 넣을 수 있음 (중첩 조건문)
let isSubmitted = true;
let reportScore = 65;
if (isSubmitted) {              // 1단계: 제출했는가? (안 했으면 점수는 볼 필요도 없음)
  if (reportScore < 80) {       // 2단계: 제출한 사람만 점수 확인
    console.log("보충 과제 대상");  // 출력: 보충 과제 대상
  } else {
    console.log("통과 - 우수 리포트");
  }
}
// 안쪽 if의 else는 "바깥 if도 참이고 안쪽 if만 거짓일 때"입니다 —
// 제출을 안 한 사람은 여기까지 오지도 못한다는 점에 주의하세요.
// 주의: 중첩이 깊어지면 읽기 어려움 -> 다음 섹션의 "중첩 펼치기" 패턴으로 해결

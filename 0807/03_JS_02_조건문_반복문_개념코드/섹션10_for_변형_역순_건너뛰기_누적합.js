// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션10_for_변형_역순_건너뛰기_누적합.js 로 실행하며 결과를 확인합니다.

// ── 섹션 10: for 변형 - 역순 · 건너뛰기 · 누적 합 ──────────────
console.log("===== 섹션 10: for 변형 =====");
// 앞 섹션의 for는 0에서 시작해 1씩 늘었지만, 세 부분을 바꾸면 다르게 돌릴 수 있습니다.
// 바꿀 때 반드시 세 곳을 함께 손봐야 합니다 — 하나만 바꾸면 무한 루프가 됩니다.
// [기본] i-- 로 역순 반복
for (let i = 3; i >= 1; i--) {
  //     └큰 수에서 시작  └부등호 방향도 뒤집기  └줄이기
  //     세 곳이 모두 "줄어드는 방향"으로 일치해야 합니다.
  //     i >= 1 을 i <= 1 로 잘못 쓰면 처음부터 거짓이라 한 번도 안 돕니다.
  console.log("카운트다운:", i);
}
// 출력: 카운트다운: 3
// 출력: 카운트다운: 2
// 출력: 카운트다운: 1
// [기본] i += 2 로 2씩 증가
for (let i = 0; i <= 6; i += 2) {
  console.log("짝수:", i);
}
// 출력: 짝수: 0
// 출력: 짝수: 2
// 출력: 짝수: 4
// 출력: 짝수: 6
// [기본] 누적 합 - 합계 변수는 반복문 밖에 let으로, 안에서 += 로 누적
let sum = 0;              // 시작값 0 — 아직 아무것도 안 더한 상태
for (let i = 1; i <= 10; i++) {
  sum += i;               // sum = sum + i. 회차마다 sum이 커집니다:
                          //   1회차: 0+1=1  2회차: 1+2=3  3회차: 3+3=6 … 10회차: 45+10=55
}
console.log("1~10 합계:", sum);  // 출력: 1~10 합계: 55
// 누적 패턴은 세 줄 세트로 외우세요: ① 밖에서 0으로 시작 ② 안에서 += ③ 끝난 뒤 사용
// 곱셈을 누적할 때는 시작값을 1로 둡니다 (0으로 두면 무엇을 곱해도 0이 되므로).
// 실수: 합계 변수를 반복문 "안"에 선언하면 매번 0으로 초기화되어 누적이 안 됨

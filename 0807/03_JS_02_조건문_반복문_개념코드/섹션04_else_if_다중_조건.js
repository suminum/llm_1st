// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션04_else_if_다중_조건.js 로 실행하며 결과를 확인합니다.

// ── 섹션 4: else if - 다중 조건 ──────────────
console.log("===== 섹션 4: else if - 다중 조건 =====");
// 핵심: else if는 "위 조건이 전부 거짓일 때만" 검사받습니다.
// 그래서 아래로 내려갈수록 조건이 자동으로 좁아집니다 —
// 두 번째 줄의 score >= 70 은 사실상 "70 이상이면서 90 미만"이라는 뜻입니다.
// (그래서 90 미만이라는 조건을 따로 쓰지 않아도 됩니다)
// [기본] 위에서부터 순서대로 검사 -> 처음 true가 되는 블록 하나만 실행
let score = 78;
if (score >= 90) {         // ① 78 >= 90 → false, 다음으로
  console.log("A등급");
} else if (score >= 70) {  // ② 78 >= 70 → true! 여기 실행하고 나머지는 검사조차 안 함
  console.log("B등급");  // 출력: B등급
} else {                   // ③ 위가 전부 거짓일 때만 (= 70 미만)
  console.log("C등급");
}
// 실수: score >= 70 을 먼저 검사하면 95점도 B등급이 됨 -> 좁은 범위(높은 점수)부터 검사!
// 이유: 95는 70 이상도 참이라 첫 줄에서 걸려 버리고, 아래 A등급 조건은 볼 기회조차 없습니다.
// 등급·요금처럼 구간을 나눌 때는 항상 "가장 까다로운 조건부터" 씁니다.
//
// 비유 — 체를 겹쳐 놓기: 구멍이 가장 작은 체(= 가장 높은 점수)를 맨 위에 둬야
// 큰 알갱이가 먼저 걸러집니다. 큰 체를 위에 두면 전부 거기서 걸려 버립니다.
//
// ★ if 를 여러 개 나열하는 것과는 완전히 다릅니다:
//   if (score >= 90) { ... }        ← 각각 따로 검사됨
//   if (score >= 70) { ... }          95점이면 두 줄 다 참이라 "A등급"과 "B등급"이 모두 출력
//   else if 는 "앞에서 안 걸렸을 때만" 검사하므로 딱 하나만 실행됩니다.
//   등급처럼 하나만 골라야 하는 상황에서는 반드시 else if 를 쓰세요.

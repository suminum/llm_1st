// ── 섹션 11: 중첩 for - 구구단 ──────────────
console.log("===== 섹션 11: 중첩 for =====");
// 시계로 비유하면 바깥이 분침, 안쪽이 초침입니다.
// 분침이 1칸 갈 동안 초침은 한 바퀴를 다 돕니다.
// [기본] 바깥 반복(단)이 한 번 돌 때마다 안쪽 반복(곱하는 수)이 끝까지 돎
for (let dan = 2; dan <= 3; dan++) {      // 바깥: 2단, 3단 (2번 반복)
  for (let n = 1; n <= 3; n++) {          // 안쪽: 1~3 (바깥이 돌 때마다 처음부터 3번)
    console.log(`${dan} x ${n} = ${dan * n}`);
  }
}
// 총 실행 횟수 = 바깥 2번 x 안쪽 3번 = 6줄 (아래 출력과 개수를 맞춰 보세요)
// 변수 이름을 dan, n처럼 뜻이 있는 말로 지으면 i, j보다 헷갈리지 않습니다
// 출력: 2 x 1 = 2
// 출력: 2 x 2 = 4
// 출력: 2 x 3 = 6
// 출력: 3 x 1 = 3
// 출력: 3 x 2 = 6

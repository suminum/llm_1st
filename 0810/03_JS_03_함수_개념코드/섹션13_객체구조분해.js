// ── 섹션 13: 객체 구조 분해 ──────────────
console.log("===== 섹션 13: 객체 구조 분해 =====");
{
  // 배열 구조 분해는 "순서"로 짝지었지만, 객체는 "이름"으로 짝짓습니다.
  // 그래서 중괄호 안의 변수 이름이 객체의 key와 정확히 같아야 합니다 (순서는 상관없음).
  // [기본] 키 이름으로 매핑 -> 순서와 무관
  const product = { name: "이온 음료", price: 1200 };
  const { name, price } = product;
  //      └key와 같은 이름이어야 함. { price, name } 으로 순서를 바꿔 써도 결과는 같음
  console.log(name, price); // 출력: 이온 음료 1200

  // [다른 방법] 함수 매개변수에서 바로 구조 분해
  function printProduct({ name, price }) {
    //                  └ 객체를 통째로 받되, 받는 즉시 풀어서 씀
    //                    이렇게 하면 함수 안에서 product.name 대신 name으로 짧게 쓸 수 있고,
    //                    함수 선언만 봐도 "이 함수는 name과 price를 쓰는구나"가 드러납니다.
    console.log(name + ": " + price + "원");
  }
  printProduct(product); // 출력: 이온 음료: 1200원
  // 14일차 axios 응답에서 const { data } = res 형태로 계속 만나게 됩니다.
  // 반복문과 함께 쓰는 형태도 자주 나옵니다 — 배열 안 객체를 돌면서 바로 풀어 쓰기:
  //   for (const { name, price } of products) { … }
  //   (연습문제에서 이 형태가 나오니 눈에 익혀 두세요)

  // 실수: const { title } = product;  // 없는 키 이름을 쓰면 undefined (에러가 아니라서 더 위험)
}

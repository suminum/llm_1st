// 03_JS_03_함수 개념코드 — 섹션 12. 배열 구조 분해
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션12_배열구조분해.js 로 실행하며 결과를 확인합니다.

// ── 섹션 12: 배열 구조 분해 ──────────────
console.log("===== 섹션 12: 배열 구조 분해 =====");
{
  // 구조 분해 = "묶여 있는 것을 풀어서 각각의 변수에 담기".
  // 예전 방식이라면 이렇게 세 줄을 써야 했습니다:
  //   const lat = coords[0];  const lng = coords[1];  const alt = coords[2];
  // 왼쪽에 대괄호를 쓰면 그 세 줄을 한 줄로 줄일 수 있습니다.
  // [기본] 배열 요소를 순서대로 개별 변수에 담기
  const coords = [37.5665, 126.978, 100];
  const [lat, lng, alt] = coords;
  //     └0번  └1번  └2번  — 이름은 내가 자유롭게 짓되, 짝은 "순서"로 맞춰집니다
  console.log(lat, lng); // 출력: 37.5665 126.978

  // [다른 방법] 건너뛰기 - 쉼표로 위치를 건너뜀
  const nums = [1, 2, 3, 4, 5];
  const [first, , third] = nums;
  console.log(first, third); // 출력: 1 3

  // [다른 방법] 나머지 패턴 - 남은 요소를 배열로 모음
  const [head, ...tail] = nums;
  console.log(head, tail); // 출력: 1 [ 2, 3, 4, 5 ]

  // [다른 방법] 값 교환 - 임시 변수 없이
  let a = 1,
    b = 2;
  [a, b] = [b, a];
  // 오른쪽 [b, a]가 먼저 [2, 1]로 계산되고, 그 값이 왼쪽 a와 b에 순서대로 들어갑니다.
  // 예전에는 임시 변수가 꼭 필요했습니다: let tmp = a; a = b; b = tmp;
  console.log(a, b); // 출력: 2 1
}

// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션03_매개변수와인자.js 로 실행하며 결과를 확인합니다.

// ── 섹션 3: 매개변수와 인자 ──────────────
console.log("===== 섹션 3: 매개변수와 인자 =====");
{
  // 용어 정리 — 같은 자리를 부르는 두 이름입니다:
  //   매개변수(parameter) = 함수를 "만들 때" 적는 빈칸 이름   → function add(a, b)
  //   인자(argument)      = 함수를 "부를 때" 넣는 실제 값     → add(3, 5)
  // 자판기로 비유하면 매개변수는 투입구에 붙은 라벨, 인자는 실제로 넣는 동전입니다.
  // 라벨은 만들 때 한 번 정하고, 동전은 누를 때마다 달라집니다.
  // [기본] 매개변수는 순서대로 전달됨
  function add(a, b) {
    return a + b;
  }
  console.log(add(3, 5)); // 출력: 8
  //              └3이 a에, 5가 b에 — 이름이 아니라 "순서"로 짝지어집니다.
  //              그래서 add(5, 3)으로 바꿔 넣으면 a와 b의 값도 바뀝니다.

  // 인자를 덜 전달하면 undefined가 됨
  console.log(add(3)); // 출력: NaN
  // b가 undefined -> 3 + undefined = NaN
  // 다른 언어라면 "인자 개수가 안 맞다"고 에러를 내지만 JS는 그냥 넘어갑니다.
  // 그래서 NaN이 나오면 인자를 빠뜨리지 않았는지부터 확인하세요.
  // (빠질 수 있는 인자에 기본값을 주는 방법은 다음 섹션에서 배웁니다)

  // 실수: add(3, 5, 7)  // 남는 인자 7은 조용히 무시됨(에러 아님) -> 개수를 맞추는 습관
}

// 03_JS_03_함수 개념코드 — 섹션 15. 스프레드·나머지 매개변수
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션15_스프레드나머지매개변수.js 로 실행하며 결과를 확인합니다.

// ── 섹션 15: 스프레드·나머지 매개변수 ──────────────
console.log("===== 섹션 15: 스프레드·나머지 매개변수 =====");
{
  // 점 세 개(...)가 두 곳에서 정반대로 쓰입니다 — 위치로 구분하세요:
  //   함수를 "부를 때"  → 스프레드   : 배열을 펼쳐서 인자 여러 개로 (묶음 → 낱개)
  //   함수를 "만들 때"  → 나머지 매개변수 : 인자 여러 개를 배열로 (낱개 → 묶음)
  // [기본] 스프레드: 배열 -> 개별 인자로 펼치기
  const scores = [85, 92, 78, 95];
  console.log(Math.max(...scores)); // 출력: 95
  // Math.max는 Math.max(85, 92, 78, 95) 처럼 낱개로 받도록 만들어져 있습니다.
  // ...를 붙이면 배열이 낱개로 펼쳐져 그 형태에 맞춰집니다.

  // [기본] 나머지 매개변수: 인자들 -> 배열로 모으기
  function sumAll(...nums) {
    //          └ 몇 개가 오든 전부 nums라는 배열 하나에 담김
    //            sumAll(1,2) 든 sumAll(1,2,3,4,5) 든 함수를 고칠 필요가 없습니다
    let total = 0;
    for (const n of nums) {
      total += n; // 모인 배열을 for...of로 하나씩 꺼내 합산 (오늘 내장메소드 시간에 배움)
    }
    return total;
  }
  console.log(sumAll(1, 2, 3, 4, 5)); // 출력: 15

  // 실수: console.log(Math.max(scores));  // 배열을 그대로 넣으면 NaN -> ...으로 펼쳐야 함
}

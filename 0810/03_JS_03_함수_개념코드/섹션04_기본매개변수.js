// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션04_기본매개변수.js 로 실행하며 결과를 확인합니다.

// ── 섹션 4: 기본 매개변수 ──────────────
console.log("===== 섹션 4: 기본 매개변수 =====");
{
  // 앞 섹션에서 인자를 빠뜨리면 undefined가 되어 NaN이 났습니다.
  // "대부분 같은 값을 쓰는" 인자라면 미리 기본값을 정해 두면 됩니다.
  // [기본] 인자가 없으면 기본값이 사용됨
  function applyDiscount(price, rate = 0.1) {
    //                          └ "안 넘겨주면 0.1로 치겠다" (기본 할인율 10%)
    return price * (1 - rate);
    //             └ 할인 후 비율. 10% 할인이면 0.9를 곱하는 것이라 1 - rate
  }
  console.log(applyDiscount(50000)); // 출력: 45000
  //                        └rate를 안 넘김 → 0.1 사용 → 50000 x 0.9
  console.log(applyDiscount(50000, 0.2)); // 출력: 40000
  //                               └넘기면 기본값을 밀어냄 → 50000 x 0.8

  // 실수: function bad(rate = 0.1, price) {...}  // 기본값 매개변수는 뒤쪽에 두는 것이 원칙
  // 이유: 인자는 순서로 짝지어지므로, 앞자리를 건너뛰고 뒷자리만 넘길 방법이 없습니다.
  //       bad(50000)이라고 쓰면 50000이 rate 자리에 들어가 버립니다.
}

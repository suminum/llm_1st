// ── 섹션 8: 화살표 함수와 this ──────────────
console.log("===== 섹션 8: 화살표 함수와 this =====");
{
  // 이 섹션에는 처음 보는 말이 두 개 나옵니다. 순서대로 하나씩 봅니다.
  //
  // ① 메소드 = 객체 안에 들어간 함수
  //    8일차에 객체를 만들 때는 안에 값·배열·객체만 넣었습니다.
  //        const cat = { name: "나비", age: 1 };
  //    그 자리에 함수를 넣어도 됩니다. 이렇게 객체 안에 들어간 함수를 "메소드"라고 부릅니다.
  //        const cat = { name: "나비", speak: function () { ... } };
  //    부를 때는 값을 꺼낼 때처럼 점을 찍고, 함수니까 뒤에 소괄호를 붙입니다 → cat.speak()
  //    새 문법이 아니라 "객체 + 함수", 이미 배운 둘을 합친 것뿐입니다.
  //
  // ② this = 메소드 안에서 "나를 갖고 있는 객체"를 가리키는 말
  //    메소드 안에서 같은 객체의 다른 값을 꺼내 쓰고 싶을 때 필요합니다.
  //    아래 report 메소드 안의 this는 tracker입니다. 그래서 this.name 은 tracker.name 입니다.
  //    this에는 규칙이 더 있지만 오늘은 이 한 줄이면 충분합니다. 정식으로는 한참 뒤에 배웁니다.

  // [기본] 객체 메소드는 일반 함수로 -> this가 객체를 가리킴
  const tracker = {
    name: "아침 걷기",
    report: function () {          // 객체 안에 들어간 함수 = 메소드
      return this.name + " 기록 중";  // tracker.report()로 불렸으니 this = tracker
    },
  };
  console.log(tracker.report()); // 출력: 아침 걷기 기록 중
  // this.name 자리에 tracker.name 이라고 이름을 직접 써도 결과는 똑같습니다.
  // 그래도 this를 쓰는 이유: 객체 이름(tracker)이 바뀌어도 안쪽 코드를 고칠 일이 없습니다.

  // 실수: report: () => this.name + " 기록 중"
  // 섹션 7에서 배운 화살표 함수로 바꾼 경우입니다. 화살표 함수는 자기 this를 갖지 않습니다.
  // 그래서 this가 tracker를 못 가리키고 -> "undefined 기록 중" 이 나옵니다. 에러는 안 납니다.
  //
  // ★ 오늘 가져갈 것은 이 한 줄입니다.
  //    객체 메소드는 일반 함수(function), 콜백은 화살표 함수.
  //    ※ "콜백"은 바로 다음 섹션 9에서 배웁니다. 지금은 이름만 스쳐 두세요.
}

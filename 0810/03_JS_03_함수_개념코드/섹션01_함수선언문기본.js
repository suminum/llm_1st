// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션01_함수선언문기본.js 로 실행하며 결과를 확인합니다.

// ── 섹션 1: 함수 선언문 기본 ──────────────
console.log("===== 섹션 1: 함수 선언문 기본 =====");
{
  // 함수 = 자주 쓰는 코드 묶음에 이름을 붙여 두고 필요할 때마다 불러 쓰는 것.
  // 인사말을 100명에게 하려면 코드를 100번 복사하는 대신 함수를 100번 부르면 됩니다.
  // 게다가 문구를 바꿀 일이 생겨도 함수 안 한 곳만 고치면 끝납니다.
  // [기본] function 키워드로 이름 있는 함수를 정의
  function greet(name) {          // name = 매개변수. 부를 때마다 달라지는 자리
    const msg = "안녕하세요, " + name + "님!";
    return msg;                   // return = 결과를 부른 쪽으로 돌려줌 (없으면 undefined)
  }
  const result = greet("김철수"); // 호출: 함수명(인자)
  //                    └인자 = 매개변수 자리에 실제로 넣는 값
  // 정의와 호출은 다른 일입니다.
  //   정의 = 기계를 조립해 두는 것 (위의 function greet …)
  //   호출 = 그 기계의 버튼을 누르는 것 (greet("김철수"))
  // 조립만 해 두면 아무 일도 안 일어납니다 — 실행했는데 출력이 없으면 호출을 빠뜨린 것입니다.
  // ★ 괄호가 버튼입니다. greet 라고만 쓰면 기계 자체를 들고 온 것이고,
  //   greet() 라고 써야 실행됩니다 (아래 실수 참고).
  console.log(result); // 출력: 안녕하세요, 김철수님!

  // [다른 방법] 템플릿 리터럴로 문자열 만들기
  function greet2(name) {
    return `안녕하세요, ${name}님!`;
  }
  console.log(greet2("이영희")); // 출력: 안녕하세요, 이영희님!

  // 실수: console.log(greet);  // 괄호 없이 쓰면 호출이 아니라 함수 자체가 출력됨
  //       → [Function: greet] 이 찍힙니다. 섹션 9의 콜백에서는 이 성질을 일부러 이용합니다.
  // 이름 짓기: 함수는 "무엇을 한다"이므로 동사로 시작합니다 (greet, add, checkSteps).
  //   오늘 실습·연습문제의 함수 이름이 전부 이 규칙입니다.
}

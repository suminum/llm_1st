// 03_JS_03_함수 개념코드 — 섹션 9. 콜백 함수
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션09_콜백함수.js 로 실행하며 결과를 확인합니다.

// ── 섹션 9: 콜백 함수 ──────────────
console.log("===== 섹션 9: 콜백 함수 =====");
{
  // 섹션 5에서 확인한 것: 함수도 "값"이다.
  //     const sameHi = sayHi;   ← 괄호 없이 함수 자체를 다른 변수에 담았습니다.
  // 값이라면 변수에 담는 것 말고 "함수의 인자로 넘기는 것"도 됩니다.
  // 이렇게 남에게 넘겨준 함수를 콜백(callback)이라고 부릅니다.
  //
  // 이 섹션에서 쓸 함수를 먼저 하나 만듭니다.
  // n번 반복하되, 매번 "무엇을 할지"는 넘겨받은 함수에게 맡깁니다.
  function repeatRun(n, callback) {
    for (let i = 1; i <= n; i++) {
      callback(i); // ★ 넘겨받은 함수를 여기서 부릅니다. i 를 넣어 주면서.
    }
  }
  // repeatRun 안에는 출력 문구가 한 글자도 없다는 점을 확인하세요.
  // "몇 번 돌지"는 repeatRun 이 알고, "무엇을 할지"는 부르는 쪽이 정합니다.

  // ── [1단계] 이름 있는 함수를 넘긴다 ──────────────
  function printLap(i) {
    console.log(i + "바퀴 완주");
  }
  repeatRun(3, printLap); // ★ printLap 뒤에 괄호가 없습니다!
  // 출력: 1바퀴 완주
  // 출력: 2바퀴 완주
  // 출력: 3바퀴 완주
  //
  // 섹션 1의 "괄호가 버튼"이 여기서 회수됩니다.
  //     printLap    → 기계 자체를 건네준 것 (아직 안 눌림)
  //     printLap()  → 버튼을 눌러 버린 것 (결과가 건네짐)
  // 콜백은 기계를 건네주는 것이므로 괄호를 붙이지 않습니다.

  // ── [2단계] 이름을 떼고 그 자리에서 만든다 (익명 함수) ──────────────
  // printLap 은 repeatRun 에 넘기려고 만든 함수라 다른 데서 쓸 일이 없습니다.
  // 이름을 지어 줄 필요가 없으면 넘기는 자리에서 바로 만듭니다.
  repeatRun(3, function (i) {
    console.log(i + "바퀴 완주");
  });
  // 출력: 1바퀴 완주
  // 출력: 2바퀴 완주
  // 출력: 3바퀴 완주   ← 1단계와 결과가 같습니다
  // 1단계 코드와 나란히 비교해 보세요. function 뒤의 이름 printLap 만 사라졌습니다.

  // ── [3단계] 화살표 함수로 줄인다 ──────────────
  repeatRun(3, (i) => console.log(i + "바퀴 완주"));
  // 출력: 1바퀴 완주
  // 출력: 2바퀴 완주
  // 출력: 3바퀴 완주   ← 역시 같습니다
  // 섹션 7의 축약 순서 그대로입니다: function 지우고 => 붙이기 → 중괄호 지우기.
  // 실무 코드와 오후 내장메소드는 대부분 이 3단계 형태로 나옵니다.
  // 1·2단계를 안 거치고 3단계만 보면 갑자기 어려워 보이지만, 셋은 완전히 같은 코드입니다.

  // ── ★ 여기서 반드시 막힙니다: 그 i 는 누가 넣어 주나요? ──────────────
  // (i) => ... 의 i 를 우리는 선언한 적도, 값을 넣은 적도 없습니다.
  // 넣어 주는 쪽은 repeatRun 입니다. 위쪽 callback(i) 가 바로 그 줄입니다.
  //
  //     repeatRun 안 :  callback(i)     ← 값을 "주는" 쪽   (i 는 1, 2, 3)
  //     우리가 쓴 것  :  (i) => ...      ← 값을 "받는" 쪽
  //
  // 지금까지 함수는 우리가 만들고 우리가 불렀습니다.
  // 콜백은 우리가 만들고 "남이" 부릅니다. 방향이 반대라 헷갈리는 것이 당연합니다.
  // 비유: 택배 기사에게 전화번호를 맡기는 것.
  //       전화를 지금 거는 게 아니라 번호(함수)를 맡기고, 거는 시점은 기사가 정합니다.
  //       "몇 동 몇 호입니다" 하고 알려 주는 내용도 기사가 정합니다 — 그게 i 입니다.

  // ── ★ 받는 이름은 내가 마음대로 지어도 됩니다 ──────────────
  repeatRun(2, (lap) => console.log(lap + "바퀴 완주"));
  // 출력: 1바퀴 완주
  // 출력: 2바퀴 완주
  repeatRun(2, (x) => console.log(x + "바퀴 완주"));
  // 출력: 1바퀴 완주
  // 출력: 2바퀴 완주
  // repeatRun 은 "첫 번째 자리에 숫자를 넣어 준다"만 정해져 있고,
  // 그 값을 무슨 이름으로 받을지는 받는 쪽 자유입니다.
  // 오후에 배울 forEach 의 numbers.forEach((number) => ...) 도 똑같습니다.
  // number 라고 써야 하는 문법이 아닙니다 — n 이든 무엇이든 됩니다.

  // ── [값을 돌려주는 콜백] 오후로 넘어가는 다리 ──────────────
  // 지금까지 콜백은 console.log 만 했고 아무것도 돌려주지 않았습니다.
  // 콜백이 return 을 하면, 넘겨받은 쪽이 그 값을 보고 판단할 수 있습니다.
  // 아래 recordLaps 는 "어떤 바퀴가 기록감인지"를 넘겨받은 함수에게 물어봅니다.
  function recordLaps(n, isGood) {
    for (let i = 1; i <= n; i++) {
      if (isGood(i)) {
        // ★ 콜백이 "돌려준" true/false 를 여기서 씁니다
        console.log(i + "바퀴 - 기록!");
      }
    }
  }
  recordLaps(6, (i) => i % 2 === 0); // 짝수 바퀴만
  // 출력: 2바퀴 - 기록!
  // 출력: 4바퀴 - 기록!
  // 출력: 6바퀴 - 기록!
  recordLaps(6, (i) => i >= 5); // 5바퀴부터
  // 출력: 5바퀴 - 기록!
  // 출력: 6바퀴 - 기록!
  //
  // 콜백 (i) => i % 2 === 0 에는 console.log 가 없습니다. true/false 를 돌려줄 뿐입니다.
  // 섹션 7의 축약형(중괄호와 return 을 함께 생략)이 여기서 쓰였습니다.
  //     (i) => i % 2 === 0        는
  //     (i) => { return i % 2 === 0; }   와 완전히 같습니다.
  // recordLaps 는 한 줄도 안 고치고 "무엇이 기록감인가"만 바꿔 끼웠다는 점을 보세요.
  //
  // ★ 오후에 배울 filter 가 정확히 이 구조입니다.
  //     arr.filter((a) => a > 3)   ← 콜백이 돌려준 true/false 를 보고 filter 가 골라 냅니다.
  //   map 은 콜백이 돌려준 "값"으로 새 배열을 만듭니다.
  //     arr.map((b) => b + 3)
  //   오후 내내 함수를 인자로 넘깁니다. 오전의 이 섹션이 그 전제입니다.

  // ── 실수 모음 ──────────────
  // 실수: repeatRun(3, printLap());
  //   괄호를 붙이면 printLap 이 먼저 실행되고 그 결과(undefined)가 넘어갑니다.
  //   함수가 아닌 값이 넘어갔으니 callback(i) 에서 TypeError: callback is not a function.
  //
  // 실수: repeatRun(3, console.log("완주"));
  //   같은 실수입니다. "완주"가 딱 한 번 찍힌 뒤 TypeError 가 납니다.
  //   3번 찍고 싶었다면  repeatRun(3, () => console.log("완주"))  라고 써야 합니다.
  //
  // 실수: repeatRun(3, (i) => { i + "바퀴"; });
  //   중괄호를 쓰면서 return 을 안 썼습니다. 에러도 안 나고 아무것도 출력되지 않습니다.
  //   섹션 7의 "중괄호는 남기고 return 만 빠뜨린 경우"가 여기서 또 나옵니다.
}

// 03_JS_03_함수 개념코드 — 섹션 5. 함수 표현식
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션05_함수표현식.js 로 실행하며 결과를 확인합니다.

// ── 섹션 5: 함수 표현식 ──────────────
console.log("===== 섹션 5: 함수 표현식 =====");
{
  // 섹션 1에서 함수를 이렇게 만들었습니다:  function 이름() { ... }   <- 함수 "선언문"
  // 만드는 방법이 하나 더 있습니다. 변수에 담는 방법입니다.  <- 함수 "표현식"
  //
  // 왜 두 가지나 있을까요? 여기서 JS의 중요한 성질 하나가 나옵니다.
  // JS에서 함수는 "값"입니다. 숫자 5나 문자열 "안녕"과 같은 취급을 받습니다.
  //   숫자를 변수에 담듯이   const n = 5;
  //   함수도 변수에 담을 수 있습니다   const f = function () { ... };
  // 값이라는 말은 곧 이런 것들이 가능하다는 뜻입니다:
  //   ① 변수에 담기   ② 다른 함수에 넘기기   ③ 함수가 함수를 돌려주기
  // ②가 섹션 9의 콜백, ③이 섹션 10의 클로저입니다. 오늘 오후의 뿌리가 이 한 줄입니다.

  // [기본] 변수에 함수를 값처럼 할당
  const sayHi = function (name) {   // function 뒤에 이름이 없습니다 — 이런 걸 "익명 함수"라 합니다
    console.log("Hi, " + name);     // 이름이 필요 없는 이유: 변수 sayHi가 이름 역할을 대신하니까요
  };                                // ← 세미콜론! const x = 5; 처럼 "할당문"이라서 필요합니다
  sayHi("박민수"); // 출력: Hi, 박민수
  // 부르는 방법은 선언문과 똑같습니다. sayHi(...) — 만든 방법만 다르지 쓰는 법은 같습니다.

  // 두 방식을 나란히 놓으면:
  //   선언문   function sayHi(name) { ... }        세미콜론 없음
  //   표현식   const sayHi = function (name) {...}; 세미콜론 있음
  // 차이는 하나 더 있는데, 그게 다음 섹션 6(호이스팅)의 주제입니다.

  // 함수도 값 -> 다른 변수에 담을 수 있음
  const sameHi = sayHi;   // 괄호가 없다는 점에 주목 — 호출이 아니라 "함수 자체"를 복사
  //             sayHi()  라고 썼다면 실행 결과(undefined)가 담겼을 것입니다.
  // 괄호의 유무가 이 자료 전체에서 가장 자주 실수하는 지점입니다. 한 문장으로 외우세요:
  //   괄호를 붙이면 "지금 실행", 안 붙이면 "함수 그 자체".
  sameHi("정수진"); // 출력: Hi, 정수진  (같은 함수를 다른 이름으로 부른 것)
  // 함수를 복사한 게 아니라 같은 함수에 이름표를 하나 더 붙인 것입니다.
  // 섹션 11 addEventListener에서 함수를 넘길 때 이 규칙이 그대로 다시 나옵니다.

  // 실수: const f = function (name) { ... }  // 끝에 세미콜론(;) 누락 주의 - 할당문이기 때문
  // 실수: const sameHi = sayHi();  // 괄호를 붙이면 실행 결과가 담깁니다 -> sameHi는 undefined
  //       그 뒤 sameHi("정수진") 을 부르면 TypeError: sameHi is not a function
}

// 03_JS_03_함수 개념코드 — 섹션 6. 호이스팅 - 선언문 vs 표현식
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션06_호이스팅.js 로 실행하며 결과를 확인합니다.

// ── 섹션 6: 호이스팅 - 선언문 vs 표현식 ──────────────
console.log("===== 섹션 6: 호이스팅 =====");
{
  // 호이스팅(hoisting)은 "끌어올리기"라는 뜻입니다.
  // JS는 코드를 실행하기 전에 파일을 한 번 쭉 훑어보면서
  // function 으로 만든 함수들을 미리 찾아 등록해 둡니다.
  // 그래서 아래쪽에 적어 둔 함수를 위쪽에서 불러도 이미 등록돼 있어 잘 동작합니다.
  // 실제로 코드가 위로 옮겨지는 건 아니고, "미리 알고 있다"고 이해하면 충분합니다.

  // [기본] 함수 선언문은 위로 끌어올려짐 -> 선언보다 먼저 호출 가능
  console.log(hoisted()); // 출력: 선언문은 미리 호출 가능
  // 부르는 줄이 만드는 줄보다 "위"에 있습니다. 그런데도 에러가 안 납니다.

  function hoisted() {
    return "선언문은 미리 호출 가능";
  }

  // 실수: notYet();  // 함수 표현식은 호이스팅 X -> 할당 전에 호출하면 ReferenceError
  // 정확한 메시지: ReferenceError: Cannot access 'notYet' before initialization
  //   ("초기화되기 전에는 notYet에 접근할 수 없다")
  // 왜 다를까요? 표현식은 함수를 만드는 게 아니라 "const 변수에 값을 넣는 일"입니다.
  // 변수는 대입하는 줄에 도달해야 값이 들어갑니다. 그 전에는 이름만 있고 알맹이가 없습니다.
  // 즉 끌어올려지는 것은 "function 으로 만든 함수"뿐이고, const/let 변수는 해당이 없습니다.
  const notYet = function () {
    return "표현식은 할당 후에만 호출 가능";
  };
  console.log(notYet()); // 출력: 표현식은 할당 후에만 호출 가능
  // 이 줄은 대입이 끝난 뒤라 정상입니다.

  // 결론: "선언문은 미리 불러도 되니 편하다"가 아니라,
  //       코드를 위에서 아래로 읽었을 때 순서가 맞도록 "정의 먼저, 호출 나중"으로 쓰세요.
  //       호이스팅은 활용할 기능이 아니라 "알아 둬야 버그를 이해할 수 있는" 동작입니다.
  //
  // 이걸 왜 배우나: 나중에 "분명히 함수를 만들었는데 없다고 나오는" 상황을 만납니다.
  // 그때 원인이 대개 이것입니다. 화살표 함수(섹션 7)도 const에 담으므로 표현식과 똑같이
  // 동작합니다 — 요즘 코드는 화살표 함수가 기본이라 이 규칙을 더 자주 만나게 됩니다.
}

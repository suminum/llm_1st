// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션02_return과실행흐름.js 로 실행하며 결과를 확인합니다.

// ── 섹션 2: return과 실행 흐름 ──────────────
console.log("===== 섹션 2: return과 실행 흐름 =====");
{
  // return은 두 가지 일을 동시에 합니다: ① 값을 돌려준다 ② 함수를 끝낸다
  // ②를 잊기 쉬운데, 이것 덕분에 else 없이도 갈래를 나눌 수 있습니다.
  // [기본] return을 만나면 값을 돌려주고 즉시 종료
  function checkSteps(steps) {
    if (steps >= 10000) {
      return "만보 달성"; // 여기서 함수가 끝남 — 아래 줄로 내려가지 않음
    }
    // 여기까지 왔다는 건 위 if가 거짓이었다는 뜻이라 else를 쓸 필요가 없습니다.
    return "아직 부족";
    // console.log("실행 안 됨"); // return 이후 코드는 실행되지 않음
  }
  // 반복문의 break가 반복을 끊는다면, return은 함수 전체를 끊습니다.
  // 이 형태를 early return이라고 부릅니다 —
  // 9일차의 "중첩 펼치기"(예외를 위에서 먼저 쳐내기)가 함수로 옮겨온 것입니다.
  console.log(checkSteps(12000)); // 출력: 만보 달성
  console.log(checkSteps(6500)); // 출력: 아직 부족

  // [기본] return 없이 끝나면 undefined 반환
  function noReturn() {
    const x = 1 + 1; // 계산만 하고 돌려주지 않음
    // 함수 안에서 만든 x는 함수가 끝나면 사라집니다.
    // return으로 밖에 건네주지 않으면 계산한 보람이 없습니다.
  }
  console.log(noReturn()); // 출력: undefined
  // 믹서기가 돌긴 돌았는데 주스를 안 따라 준 것입니다. 계산했다 ≠ 돌려줬다.
  //
  // console.log 와 return 의 차이를 여기서 확실히 갈라 두세요:
  //   console.log  화면에 보여주고 끝. 그 값을 다른 곳에서 쓸 수 없습니다.
  //   return       값을 밖으로 넘겨줘서 변수에 담거나 다시 계산할 수 있게 합니다.
  // 함수를 짤 때 자문하세요: "이 함수는 일을 할 뿐인가(출력·화면 변경),
  // 아니면 결과를 돌려줘야 하는가(계산)?" 후자면 return이 반드시 있어야 합니다.

  // 실수: const v = checkSteps;  // 호출하지 않고 담으면 결과값이 아니라 함수가 담김
}

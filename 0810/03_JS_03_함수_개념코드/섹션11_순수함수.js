// 03_JS_03_함수 개념코드 — 섹션 11. 순수 함수
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션11_순수함수.js 로 실행하며 결과를 확인합니다.

// ── 섹션 11: 순수 함수 ──────────────
console.log("===== 섹션 11: 순수 함수 =====");
{
  // "순수하다"는 두 가지 뜻입니다:
  //   ① 같은 재료를 넣으면 언제나 같은 결과 (자판기처럼)
  //   ② 밖의 것을 건드리지 않음 (전역 변수 변경, 화면 수정, 파일 저장 등이 없음)
  // 왜 좋은가: 버그가 났을 때 그 함수만 보면 원인을 알 수 있습니다.
  // 밖의 값을 건드리는 함수는 "어디서 언제 불렸는지"까지 추적해야 합니다.
  // [기본] 같은 입력 -> 항상 같은 출력, 외부 상태를 바꾸지 않음
  const sumTwo = (a, b) => a + b;   // 재료는 a, b뿐이고 결과는 return이 전부
  console.log(sumTwo(2, 3)); // 출력: 5
  console.log(sumTwo(2, 3)); // 출력: 5  (몇 번을 불러도 결과가 같음)
  // 반대 예: new Date()나 Math.random()을 쓰는 함수는 부를 때마다 결과가 달라 순수하지 않습니다.
  // 오늘 수준의 실천 지침 한 줄:
  //   "계산은 함수 안에서 하고 return으로 내보내고, 출력(console.log)은 밖에서 한다."
  // 이렇게 나눠 두면 같은 계산 함수를 화면 출력에도, 파일 저장에도 재사용할 수 있습니다.

  // 실수: 외부 변수를 바꾸는 함수 (사이드 이펙트)
  // let total = 0;
  // function addToTotal(n) { total += n; }  // 결과가 외부 상태에 따라 달라짐 -> 순수 함수 아님
  // 데이터 처리 로직은 순수 함수로, 사이드 이펙트는 분리하는 것이 좋은 설계
}

// 읽는 순서: 조건 → Step 1 → Step 2 → Step 3 → 자주 하는 실수
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 추가실습03_걸음수집계.js 로 실행하며 결과를 확인합니다.

// ── [추가 실습] 걸음 수 집계 - 나머지 매개변수와 클로저 (보너스 — 빨리 끝냈다면 도전해 보세요) ──
// 조건: 1) 날짜 개수와 상관없이 걸음 수 합계를 구하는 sumAll(...nums)
//       2) 스프레드로 가장 많이 걸은 날의 값 구하기
//       3) 클로저로 목표 달성일 카운터 만들기
//
// ★ 오늘 자료 중 가장 어렵습니다. 한 번에 이해 안 되는 게 정상이니 천천히 보세요.
//   Step 1과 Step 2는 똑같이 점 세 개(...)를 쓰는데 방향이 반대입니다. 거기가 핵심입니다.
console.log("===== [추가 실습] 걸음 수 집계 =====");
{
  const daily = [8200, 9500, 12000, 10300]; // 요일별 하루 걸음 수

  // Step 1: 나머지 매개변수 - 인자들을 배열로 모아 for...of로 합산
  // 매개변수 자리의 ... 은 "모으기"입니다.
  //   sumAll(1, 2, 3) 이라고 부르면 → nums 는 [1, 2, 3] 이 됩니다.
  //   몇 개를 넣든 전부 하나의 배열로 묶어 줍니다. 그래서 "날짜 개수와 상관없이"가 가능합니다.
  // 이게 없다면 (a, b, c, d) 처럼 자리를 미리 정해야 하고, 5일치가 오면 함수를 고쳐야 합니다.
  const sumAll = (...nums) => {
    let total = 0; // 누적할 그릇. 반드시 반복문 "밖"에서 0으로 시작합니다.
    //              안에 두면 매 회차마다 0으로 초기화되어 마지막 값만 남습니다.
    for (const n of nums) {
      // for...of 는 "배열에서 값을 하나씩 꺼내 n에 담아라"라는 뜻입니다.
      // 인덱스(0, 1, 2…)를 쓸 일이 없을 때 가장 짧고 읽기 쉽습니다.
      total += n; // total = total + n 과 같은 뜻
    }
    return total;
  };
  console.log(sumAll(...daily)); // 출력: 40000
  // 여기서 daily 앞의 ... 은 반대로 "펼치기"입니다.
  //   sumAll(...daily) 는 sumAll(8200, 9500, 12000, 10300) 이라고 쓴 것과 같습니다.
  //   배열째로 sumAll(daily) 라고 주면 nums 는 [[8200, ...]] 처럼 배열 속 배열이 되어 버립니다.
  // 정리: 함수를 "만들 때"의 ... = 흩어진 값을 모으기 / 함수를 "부를 때"의 ... = 배열을 펼치기.

  // Step 2: 스프레드 - 배열을 개별 인자로 펼쳐 최댓값 구하기
  // Math.max 는 Math.max(3, 7, 5) 처럼 값을 따로따로 받도록 만들어진 함수입니다.
  // 배열을 통째로 주면(Math.max(daily)) 숫자가 아니라서 NaN 이 나옵니다.
  // 그래서 ... 로 펼쳐서 넘깁니다 — Step 1 마지막 줄과 완전히 같은 원리입니다.
  console.log(Math.max(...daily)); // 출력: 12000

  // Step 3: 클로저 - count를 기억하는 목표 달성일 카운터
  // 보통 함수는 실행이 끝나면 안에서 만든 변수가 사라집니다.
  // 그런데 "함수 안에서 함수를 만들어 밖으로 내보내면", 그 안쪽 함수는
  // 자기가 태어난 자리의 변수를 계속 붙들고 있습니다. 이것을 클로저라고 합니다.
  const createGoalCounter = () => {
    let count = 0; // 반환된 함수만 접근 가능
    //                밖에서 count 라고 직접 쓸 수 없습니다 — 실수로 건드릴 수 없게 숨긴 것입니다.
    return () => ++count; // 이 이름 없는 함수가 count 를 기억한 채 밖으로 나갑니다
    //                       ++count 는 "1 올린 뒤 그 값을 내놓기"입니다.
    //                       count++ 라고 쓰면 "올리기 전 값"을 내놓아 결과가 하나씩 밀립니다.
  };
  const addGoalDay = createGoalCounter();
  // 이 시점에 createGoalCounter 는 이미 끝났지만, count 는 사라지지 않았습니다.
  // addGoalDay 가 그 count 를 붙들고 있기 때문입니다.
  addGoalDay(); // count 가 1이 됨 (console.log 로 감싸지 않았으므로 화면에는 안 보임)
  addGoalDay(); // count 가 2가 됨
  console.log(addGoalDay()); // 출력: 3
  // 부를 때마다 0에서 다시 시작하지 않고 이어서 올라가는 것 — 이것이 클로저의 전부입니다.
}

// ── 자주 하는 실수 ──────────────────────────────────────────
// 실수: console.log(sumAll(daily));
//       → 펼치지 않고 배열째 넘긴 경우. nums 가 [[8200, 9500, 12000, 10300]] 이 되어
//         0 + 배열 이 문자열로 이어 붙어 "08200,9500,12000,10300" 같은 결과가 나옵니다.
//
// 실수: const sumAll = (...nums) => { for (const n of nums) { let total = 0; total += n; } return total; }
//       → 누적 그릇을 반복문 안에 둔 경우. 매 회차 0으로 되돌아가고,
//         게다가 total 이 반복문 블록 안에서만 살아 있어 return 자리에서 에러가 납니다.
//
// 실수: const createGoalCounter = () => { let count = 0; return count + 1; };
//       → 함수가 아니라 숫자를 돌려준 경우. addGoalDay 에 1이 담겨 addGoalDay() 가 에러입니다.
//         클로저는 "값"이 아니라 "함수"를 내보내야 성립합니다.
//
// 실수: return () => count++;
//       → 출력이 3이 아니라 2가 됩니다. count++ 는 올리기 "전" 값을 내놓기 때문입니다.
//         세 번째 호출 시점의 count 는 2였고, 값을 내놓은 뒤에 3이 됩니다.
//
// 실수: const a = createGoalCounter(); const b = createGoalCounter();
//       → a 와 b 는 각자 자기만의 count 를 가집니다. 부를 때마다 새 그릇이 생기기 때문입니다.
//         a() 를 세 번 불러도 b() 는 여전히 1부터 시작합니다. 이건 실수라기보다 꼭 알아야 할 성질입니다.

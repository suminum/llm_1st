// 03_JS_03_함수 실습 정답코드 — 함수 만들기 2: square() - 함수 표현식
// 읽는 순서: 문제 → Step 1 → Step 2 → Step 3 → 자주 하는 실수
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 실습02_square_함수표현식.js 로 실행하며 결과를 확인합니다.

// ── 함수 만들기 2: square() - 함수 표현식 ──────────────────────
// 조건: 매개변수로 하나의 숫자를 입력받기
//       입력받은 수의 제곱을 콘솔창에 출력하는 함수를 함수 표현식으로 정의
//
// 실습 1과 무엇이 다른가 — 두 가지가 다릅니다. 둘 다 오늘의 핵심입니다.
//   ① 만드는 방법이 다름 : function multifly(){}  vs  const square = function(){}
//   ② 결과를 다루는 방법이 다름 : return 으로 돌려주기  vs  함수 안에서 직접 출력하기
console.log("===== 함수 만들기 2: square() =====");
{
  // Step 1: 변수에 함수를 할당 (함수 표현식)
  // 실습 1은 "함수를 선언"했고, 여기서는 "함수를 만들어 변수에 담습니다".
  //   const square = function (n) { ... };
  //         └변수 이름   └이름 없는 함수(값처럼 취급됨)
  // JS에서 함수는 숫자·문자열처럼 변수에 담을 수 있는 "값"입니다. 이 점이 낯설지만 중요합니다.
  // 끝에 세미콜론(;)이 붙는 이유: 이 줄은 함수 선언이 아니라 const 대입문이기 때문입니다.
  const square = function (n) {
    // Step 2: 반환이 아니라 콘솔 출력
    // 실습 1의 multifly 는 return 으로 값을 "돌려줬고",
    // 이 square 는 함수 안에서 직접 화면에 "찍고" 끝냅니다. 돌려주는 값은 없습니다.
    // 그래서 square(4) 자체는 화면에 16을 찍지만, 그 결과를 변수에 담으면 undefined 입니다.
    console.log(n * n);
  };

  // Step 3: 테스트
  square(4); // 출력: 16
  square(11); // 출력: 121
  square(5); // 출력: 25
  // 실습 1에서는 console.log(multifly(3, 7)) 처럼 console.log 로 감쌌는데
  // 여기서는 square(4) 만 적는 것에 주목하세요. 출력은 이미 함수 안에서 하고 있으니까요.
}

// ── 자주 하는 실수 ──────────────────────────────────────────
// 실수: console.log(square(4));
//       → 16 과 undefined 가 둘 다 찍힙니다.
//         함수 안의 console.log 가 16을 찍고, square 는 돌려주는 값이 없어 undefined 를 내놓기 때문입니다.
//         "출력하는 함수"를 또 출력하려 하면 이렇게 됩니다.
//
// 실수: const result = square(4);  console.log(result * 2);
//       → undefined * 2 라서 NaN 이 나옵니다.
//         계산 결과를 이어서 쓰고 싶다면 console.log 가 아니라 return 을 써야 합니다.
//         출력용 함수와 계산용 함수는 쓰임이 다릅니다.
//
// 실수: square(4);
//       const square = function (n) { console.log(n * n); };
//       → 함수 표현식은 "선언보다 먼저 부르면" 에러입니다 (ReferenceError).
//         실습 1의 function 선언문은 미리 끌어올려져(호이스팅) 먼저 불러도 되지만,
//         const 에 담은 함수는 그 줄을 지나야 비로소 존재합니다. 둘의 가장 큰 실무 차이입니다.
//
// 실수: const square = function (n) { console.log(n * n) }
//       → 맨 끝 세미콜론 누락. 지금은 대개 그냥 동작하지만,
//         다음 줄이 (나 [ 로 시작하면 두 줄이 한 문장으로 붙어 버려 엉뚱한 에러가 납니다.

// 읽는 순서: 조건 → Step 1 → Step 2 → Step 3 → 자주 하는 실수
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 추가실습01_미세먼지확인함수.js 로 실행하며 결과를 확인합니다.

// ── [추가 실습] 걷기 전 미세먼지 확인 함수 (보너스 — 빨리 끝냈다면 도전해 보세요) ──
// 조건: 장소명·미세먼지 수치를 받아 판정 결과 문자열을 반환 (기준 수치는 기본 매개변수 80)
console.log("===== [추가 실습] 걷기 전 미세먼지 확인 =====");
{
  // Step 1: 화살표 함수 + 기본 매개변수(limit = 80)
  // 화살표 함수는 function 을 짧게 쓰는 다른 표기법입니다. 하는 일은 같습니다.
  //   const f = function (a) { ... }   ←→   const f = (a) => { ... }
  //   function 이라는 글자가 사라지고 매개변수 뒤에 => 가 붙었습니다.
  //
  // limit = 80 은 "기본 매개변수"입니다.
  //   부를 때 세 번째 값을 안 주면 limit 에 자동으로 80이 들어갑니다.
  //   대부분 80을 쓰지만 가끔 다른 기준도 쓰고 싶을 때, 매번 80을 적지 않아도 되게 해 줍니다.
  //   기본값이 있는 매개변수는 반드시 뒤쪽에 둡니다 — 앞에 두면 어느 자리를 생략한 건지 알 수 없습니다.
  const checkDust = (place, dust, limit = 80) => {
    // Step 2: 기준 초과면 "실내 운동 권장", 아니면 "걷기 좋음"을 조기 return
    // 여기서 else 를 쓰지 않은 것에 주목하세요.
    // return 은 그 자리에서 함수를 끝내므로, 위 조건이 참이면 아래 줄까지 갈 일이 없습니다.
    // 이렇게 "걸리면 바로 내보내는" 방식을 조기 return(early return)이라고 합니다.
    // 조건이 여러 개로 늘어나도 들여쓰기가 깊어지지 않아 읽기 쉬워집니다.
    if (dust > limit) {
      return `${place}: 실내 운동 권장 (미세먼지 ${dust})`;
    }
    return `${place}: 걷기 좋음 (미세먼지 ${dust})`;
  };
  // Step 3: 기본값 사용 / 기준 수치 변경 테스트
  console.log(checkDust("한강공원", 95)); // 출력: 한강공원: 실내 운동 권장 (미세먼지 95)
  // 95 > 80(기본값) 이라 첫 번째 return 에서 끝납니다.
  console.log(checkDust("동네 산책로", 70)); // 출력: 동네 산책로: 걷기 좋음 (미세먼지 70)
  // 70 > 80 이 거짓이라 if 를 그냥 지나쳐 두 번째 return 이 실행됩니다.
  console.log(checkDust("호수공원", 70, 60)); // 출력: 호수공원: 실내 운동 권장 (미세먼지 70)
  // 같은 70인데 결과가 반대입니다 — 기준을 60으로 직접 넘겨 기본값 80을 덮어썼기 때문입니다.
  // 세 줄을 나란히 놓고 보면 "기본값이 있다 / 없다"가 무슨 뜻인지 한눈에 들어옵니다.
}


//         "한강공원"이 limit 에 들어가 버립니다. 기본값은 항상 뒤쪽에 둡니다.
//
// 실수: console.log(checkDust("호수공원", "70", 60));
//       → 수치를 따옴표로 감싸 문자열로 넘긴 경우. "70" > 60 은 JS가 알아서 숫자로 바꿔 주지만,
//         이런 자동 변환에 기대면 언젠가 반드시 틀립니다. 숫자는 숫자로 넘기세요.

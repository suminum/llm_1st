//         if (dust > limit) `${place}: 실내 운동 권장`;
//       };
//       → return 을 빼먹은 경우. 문자열을 만들기만 하고 돌려주지 않아 undefined 가 나옵니다.
//         화살표 함수라도 중괄호 { } 를 쓰면 return 은 직접 써야 합니다.
//
// 실수: const checkDust = (place, dust, limit = 80) => { return `${place}` }
//       vs const checkDust = (place) => `${place}`;
//       → 중괄호를 아예 안 쓰면 그 식의 결과가 자동으로 return 됩니다(암묵적 반환).
//         중괄호를 쓰는 순간 자동 반환은 사라집니다. 이 둘을 섞으면 undefined 의 원인이 됩니다.

// 03_JS_03_함수 실습 정답코드 — 함수 만들기 1: multifly() - 함수 선언문
// 읽는 순서: 문제 → Step 1 → Step 2 → Step 3 → 자주 하는 실수
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 실습01_multifly_함수선언문.js 로 실행하며 결과를 확인합니다.

// ── 함수 만들기 1: multifly() - 함수 선언문 ────────────────────
// 조건: 매개변수로 두 개의 숫자를 입력받기
//       두 인자의 곱을 "반환"하는 함수를 함수 선언문 형식으로 정의
// (함수 이름 multifly는 PPT 표기 그대로 사용합니다)
//
// 함수가 왜 필요한가:
//   지금까지는 계산이 필요할 때마다 그 자리에 식을 직접 썼습니다.
//   같은 계산을 열 군데에서 하면 같은 식을 열 번 써야 하고,
//   식이 틀렸을 때 열 군데를 전부 고쳐야 합니다.
//   함수는 "이 작업에 이름을 붙여 한 번만 적어 두고, 필요할 때 이름을 부르는" 장치입니다.
console.log("===== 함수 만들기 1: multifly() =====");
{
  // 이 중괄호 { } 는 문법이 아니라 파일 정리용입니다.
  // 실습 파일마다 같은 이름의 변수를 써도 서로 부딪히지 않게 울타리를 친 것입니다.
  // 수업에서 따라 칠 때는 이 중괄호 없이 안쪽 내용만 적어도 똑같이 동작합니다.

  // Step 1: function 키워드로 함수 선언
  // 읽는 순서: function(만들겠다) → multifly(이름) → (a, b)(받을 값의 자리) → { }(할 일)
  //   a, b 를 "매개변수"라고 합니다 — 아직 값이 없는 빈 자리, 이름표일 뿐입니다.
  //   나중에 multifly(3, 7) 이라고 부르면 그때 a에 3, b에 7이 들어갑니다.
  //   이때 실제로 넣은 3, 7 은 "인자"라고 부릅니다. (자리 = 매개변수 / 값 = 인자)
  function multifly(a, b) {
    // Step 2: 두 인자의 곱을 return
    // return 은 두 가지 일을 동시에 합니다.
    //   ① 계산한 값을 함수를 부른 자리로 돌려보낸다
    //   ② 그 즉시 함수를 끝낸다 (아래에 코드가 더 있어도 실행되지 않음)
    // 그래서 아래 multifly(3, 7) 은 함수 호출이 끝나고 나면 그 자리에 21이 남습니다.
    return a * b;
  }
  // 여기까지는 "만들어 두기"만 한 것입니다. 아직 아무 계산도 일어나지 않았습니다.
  // 요리법을 적어 둔 것과 실제로 요리하는 것이 다른 일인 것과 같습니다.

  // Step 3: 테스트
  // 이름 뒤에 괄호를 붙여야 비로소 실행됩니다 — 괄호가 "지금 실행해라"라는 신호입니다.
  console.log(multifly(3, 7)); // 출력: 21
  // 계산 순서: multifly(3, 7) 이 먼저 실행되어 21이 되고 → console.log(21) 이 실행됨
  console.log(multifly(2, 2)); // 출력: 4
  // 같은 함수를 값만 바꿔 몇 번이든 다시 쓸 수 있습니다. 이것이 함수를 쓰는 이유입니다.
}

// ── 자주 하는 실수 ──────────────────────────────────────────
// 실수: console.log(multifly);
//       → 괄호가 없으면 실행이 아니라 "함수 자체"를 찍습니다. [Function: multifly] 가 출력됩니다.
//         괄호 = 실행 신호. 이 실수는 앞으로도 계속 나옵니다.
//
// 실수: function multifly(a, b) { a * b; }
//       → return 을 빼먹은 경우. 계산은 했지만 돌려주지 않아 결과가 undefined 가 됩니다.
//         "곱하기는 했는데 결과를 손에 안 쥐고 나온" 상태입니다.
//
// 실수: function multifly(a, b) { return a * b; console.log("끝"); }
//       → return 아래 줄은 절대 실행되지 않습니다. return 은 함수를 그 자리에서 끝냅니다.
//
// 실수: console.log(multifly(3));
//       → 인자를 하나만 주면 b 는 값이 없어 undefined 가 되고, 3 * undefined 는 NaN 입니다.
//         NaN(Not a Number)이 보이면 "숫자가 아닌 것으로 계산했다"는 신호입니다.

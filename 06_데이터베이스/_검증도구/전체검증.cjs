// ============================================================
// _검증도구/전체검증.cjs — 자료 전체를 한 번에 훑는다
// ------------------------------------------------------------
// 사용:
//   node _검증도구/전체검증.cjs
//   npm run 검증
//
//   node _검증도구/전체검증.cjs 04_Express_시작하기   ← 한 단원만
//
// 하는 일:
//   ① 출력검증   `// 출력:` 주석 ↔ 진짜 node 실행 결과
//   ② 정합성     자료 안의 규칙을 스스로 어기지 않았는지
//
//
// ★ "다 됐다" 라고 말하기 전에 반드시 이걸 돌립니다.
//   사람 눈으로는 안 잡힙니다.
// ============================================================

const path = require("path");
const cp = require("child_process");

const 도구폴더 = __dirname;
const 넘어온것 = process.argv.slice(2);

const 단계들 = [
  { 이름: "출력 대조", 파일: "출력검증.cjs" },
  { 이름: "정합성 검사", 파일: "정합성검사.cjs" },
];

let 전체실패 = 0;
let 전체건너뜀 = 0;
const 요약 = [];

for (const 단계 of 단계들) {
  console.log(`\n\n${"=".repeat(60)}`);
  console.log(`  ${단계.이름}`);
  console.log("=".repeat(60));

  // ★ process.execPath — 지금 이 도구를 돌린 것과 **같은 node** 로 돌립니다.
  //   "node" 라고만 쓰면 PATH 의 다른 버전이 잡혀서 결과가 달라집니다.
  const 결과 = cp.spawnSync(process.execPath, [path.join(도구폴더, 단계.파일), ...넘어온것], {
    stdio: "inherit",
  });

  // ★ 2 는 "건너뜀" 입니다. 통과와 구분해서 보여 줍니다.
  //   건너뛴 걸 "이상 없음" 이라고 하면, 검사가 안 돌았는데 돈 줄 압니다.
  const 건너뜀 = 결과.status === 2;
  const 실패 = 결과.status !== 0 && !건너뜀;
  if (실패) 전체실패 += 1;
  if (건너뜀) 전체건너뜀 += 1;

  요약.push({ 이름: 단계.이름, 실패, 건너뜀 });
}

console.log(`\n\n${"#".repeat(60)}`);
console.log("  전체 결과");
console.log("#".repeat(60));

for (const 줄 of 요약) {
  const 표시 = 줄.실패 ? "✗ 문제 있음" : 줄.건너뜀 ? "－ 건너뜀  " : "○ 이상 없음";
  console.log(`  ${표시}  ${줄.이름}`);
}

if (전체실패 === 0 && 전체건너뜀 === 0) {
  console.log("\n  전부 통과했습니다.");

} else if (전체실패 === 0) {
  console.log(`\n  통과했습니다. 다만 ${전체건너뜀}개 단계를 **건너뛰었습니다.**`);
  console.log("  건너뛴 단계는 검사를 한 게 아닙니다. 위에 이유가 적혀 있습니다.");

} else {
  console.log(`\n  ${전체실패}개 단계에서 문제가 나왔습니다. 위 내용을 확인하세요.`);
  if (전체건너뜀 > 0) console.log(`  그리고 ${전체건너뜀}개 단계를 건너뛰었습니다.`);
}

process.exit(전체실패 > 0 ? 1 : 0);

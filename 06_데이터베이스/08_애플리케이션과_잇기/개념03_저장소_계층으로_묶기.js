// 트랜잭션 껍데기. 앱 전체에서 이것 하나만 씁니다.
async function 트랜잭션(할일) {
  const 연결 = await 풀.connect();

  try {
    await 연결.query("BEGIN");
    const 값 = await 할일(연결);      // ★ 빌린 연결을 그대로 넘깁니다
    await 연결.query("COMMIT");
    return 값;
  } catch (에러) {
    await 연결.query("ROLLBACK");
    throw 에러;
  } finally {
    연결.release();                    // ★ 개념02 의 그 줄입니다
  }
}


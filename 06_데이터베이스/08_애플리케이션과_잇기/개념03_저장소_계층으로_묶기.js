// DB 의 한 줄을 우리 앱이 쓰는 모양으로 바꿉니다.
function 설비로만들기(줄) {
  return {
    번호: 줄.설비번호,
    이름: 줄.이름,
    라인: 줄.라인,
    가동중: 줄.상태 === "가동",
  };
}

const 설비저장소 = {
  async 목록(실행자, { 라인 } = {}) {
    const 결과 = 라인
      ? await 실행자.query(
          "SELECT 설비번호, 이름, 라인, 상태 FROM 설비 WHERE 라인 = $1 ORDER BY 설비번호",
          [라인],
        )
      : await 실행자.query("SELECT 설비번호, 이름, 라인, 상태 FROM 설비 ORDER BY 설비번호");

    return 결과.rows.map(설비로만들기);
  },

  async 하나(실행자, 번호) {
    const 결과 = await 실행자.query(
      "SELECT 설비번호, 이름, 라인, 상태 FROM 설비 WHERE 설비번호 = $1",
      [번호],
    );

    // ★ 못 찾으면 `null` 입니다. `undefined` 가 아닙니다. (섹션 3 에서 이유를 봅니다)
    return 결과.rows.length === 0 ? null : 설비로만들기(결과.rows[0]);
  },

  async 추가(실행자, { 번호, 이름, 라인 }) {
    const 결과 = await 실행자.query(
      `INSERT INTO 설비 (설비번호, 이름, 라인)
       VALUES ($1, $2, $3)
       RETURNING 설비번호, 이름, 라인, 상태`,
      [번호, 이름, 라인],
    );

    return 설비로만들기(결과.rows[0]);
  },

  async 상태바꾸기(실행자, 번호, 새상태) {
    const 결과 = await 실행자.query(
      `UPDATE 설비 SET 상태 = $2
       WHERE 설비번호 = $1
       RETURNING 설비번호, 이름, 라인, 상태`,
      [번호, 새상태],
    );

    // ★★ `rowCount` 가 0 이면 그 설비가 없는 것입니다.
    //   여기서 안 잡으면 "수정했습니다" 라고 응답해 놓고 아무것도 안 바뀝니다.
    return 결과.rowCount === 0 ? null : 설비로만들기(결과.rows[0]);
  },

  async 삭제(실행자, 번호) {
    const 결과 = await 실행자.query("DELETE FROM 설비 WHERE 설비번호 = $1", [번호]);

    return 결과.rowCount === 1;   // 지웠으면 true, 없었으면 false
  },
};


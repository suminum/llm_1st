// 출력: 어느 제약인가: 설비_pkey

// ★★ 이 메시지를 사용자에게 그대로 보여 주면 안 됩니다.
//   사용자는 `설비_pkey` 가 뭔지 모르고, 표 이름과 제약 이름이 밖으로 새어 나갑니다.
//   저장소에서 **우리 말**로 바꿔서 올립니다.

class 규칙위반 extends Error {
  constructor(메시지, 무엇) {
    super(메시지);
    this.name = "규칙위반";
    this.무엇 = 무엇;
  }
}

설비저장소.안전하게추가 = async function (실행자, 설비) {
  try {
    return await 설비저장소.추가(실행자, 설비);
  } catch (에러) {
    if (에러.code === "23505") {
      throw new 규칙위반("이미 있는 설비번호입니다", 설비.번호);
    }

    if (에러.code === "23502") {
      throw new 규칙위반(`${에러.column} 은(는) 비울 수 없습니다`, 에러.column);
    }

    throw 에러;   // ★ 모르는 에러는 손대지 말고 그대로 올립니다
  }
};


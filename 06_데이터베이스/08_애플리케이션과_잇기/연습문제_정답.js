// 설비번호로 한 대를 찾습니다.
//   · 있으면 { 번호, 이름, 라인 } 을 돌려주세요 (칸 이름을 바꿉니다)
//   · ★ 없으면 `null` 을 돌려주세요. `undefined` 가 아닙니다

async function 설비하나(실행자, 설비번호) {
  const 결과 = await 실행자.query(
    "SELECT 설비번호, 이름, 라인 FROM 설비 WHERE 설비번호 = $1",
    [설비번호],
  );

  if (결과.rows.length === 0) return null;

  const 줄 = 결과.rows[0];

  return { 번호: 줄.설비번호, 이름: 줄.이름, 라인: 줄.라인 };
}

// ── 왜 ──
//
// ① **`rows[0]` 을 그냥 돌려주면 안 됩니다.**
//   없을 때 `undefined` 가 나오는데, `JSON.stringify` 는 `undefined` 인 키를
//   **통째로 빼 버립니다.**
//
//     JSON.stringify({ 설비: undefined })  → "{}"
//     JSON.stringify({ 설비: null })       → '{"설비":null}'
//
//   앞은 "그런 걸 물어본 적 없다" 처럼 읽히고, 뒤는 "찾아봤는데 없다" 입니다.
//   API 를 쓰는 쪽에서는 완전히 다른 뜻입니다. `null` 로 통일하세요.
//
// ② **`SELECT *` 를 쓰지 않았습니다.**
//   지금은 칸이 여섯 개인데 셋만 골랐습니다.
//   나중에 `비밀번호해시` 같은 칸이 추가돼도 **아무 일도 안 일어납니다.**
//   `SELECT *` 였다면 그날부터 API 응답에 딸려 나갑니다.
//
// ③ **칸 이름을 바꿔서 내보냈습니다.** (`설비번호` → `번호`)
//   DB 의 칸 이름이 앱 전체로 새어 나가지 않습니다.
//   나중에 칸 이름을 바꿔도 **이 함수만** 고치면 됩니다.

await 문제(7, "저장소 — 하나 조회하기", async () => {
  const 있는것 = await 설비하나(풀, "EQ-001");
  const 없는것 = await 설비하나(풀, "EQ-999");

  return (
    없는것 === null &&
    있는것 !== null &&
    있는것.번호 === "EQ-001" &&
    있는것.이름 === "컨베이어 1호" &&
    있는것.라인 === "A" &&
    Object.keys(있는것).length === 3
  );
});


// ============================================================
// 8. 저장소 — 없는 줄을 고쳤을 때
// ============================================================
//
// 상태를 바꿉니다.
//   · 바꿨으면 바뀐 설비 객체 { 번호, 상태 } 를 돌려주세요
//   · ★ 그 설비가 없으면 `null` 을 돌려주세요 (rowCount 를 보세요)
//
// 이걸 안 하면 "수정했습니다" 라고 200 을 주고 화면은 안 바뀝니다.

async function 상태바꾸기(실행자, 설비번호, 새상태) {
  const 결과 = await 실행자.query(
    "UPDATE 설비 SET 상태 = $2 WHERE 설비번호 = $1 RETURNING 설비번호, 상태",
    [설비번호, 새상태],
  );

  if (결과.rowCount === 0) return null;

  return { 번호: 결과.rows[0].설비번호, 상태: 결과.rows[0].상태 };
}

// ── 왜 ──
//
// ★★ **없는 줄을 UPDATE 해도 에러가 안 납니다.** `rowCount` 만 0 입니다.
//
//   그래서 확인하지 않으면 이렇게 됩니다.
//
//     PATCH /equipments/EQ-999  →  200 OK  {"메시지":"수정되었습니다"}
//
//   사용자는 성공했다고 믿고, 화면은 안 바뀝니다.
//   "저장이 안 돼요" 라는 문의가 들어오는데 로그에는 에러가 없습니다.
//
//   `rowCount === 0` 이면 `null` 을 돌려주고, 라우트에서 404 를 주세요.
//
// ★ `RETURNING` 을 쓰면 **고친 뒤의 값**을 한 번에 받습니다.
//   `UPDATE` 하고 다시 `SELECT` 하면 쿼리가 두 번이고,
//   그 사이에 남이 또 고칠 수도 있습니다. (07단원의 경합)
//   `RETURNING` 은 MySQL 에는 없습니다. Postgres 의 무기입니다.
//
// ★ `rowCount` 가 2 이상이면 **WHERE 가 잘못된 것**입니다.
//   기본키로 찾는데 2가 나오면 그때는 던지는 편이 낫습니다.

await 문제(8, "저장소 — 없는 줄을 고쳤을 때", async () => {
  const 바뀐것 = await 상태바꾸기(풀, "EQ-002", "가동");
  const 없는것 = await 상태바꾸기(풀, "EQ-999", "가동");

  await 풀.query("UPDATE 설비 SET 상태 = '정지' WHERE 설비번호 = 'EQ-002'");

  return 없는것 === null && 바뀐것 !== null && 바뀐것.번호 === "EQ-002" && 바뀐것.상태 === "가동";
});


// ============================================================
// 9. 에러 코드를 도메인 말로
// ============================================================
//
// 이미 있는 설비번호를 또 넣으면 `23505` 가 납니다.
// 그 에러를 잡아서 `Error("이미 있는 설비번호입니다")` 로 바꿔 던지세요.
// ★ 다른 코드의 에러는 **손대지 말고 그대로** 던져야 합니다.

async function 설비추가(실행자, { 번호, 이름, 라인 }) {
  try {
    const 결과 = await 실행자.query(
      "INSERT INTO 설비 (설비번호, 이름, 라인) VALUES ($1, $2, $3) RETURNING 설비번호",
      [번호, 이름, 라인],
    );

    return { 번호: 결과.rows[0].설비번호 };
  } catch (에러) {
    if (에러.code === "23505") {
      throw new Error("이미 있는 설비번호입니다");
    }

    throw 에러;   // ★ 모르는 에러는 손대지 말고 그대로 올립니다
  }
}

// ── 왜 ──
//
// ① **날것 메시지를 사용자에게 보여 주면 안 됩니다.**
//
//     duplicate key value violates unique constraint "설비_pkey"
//
//   사용자는 못 알아듣고, 공격자는 표 이름과 제약 이름을 알게 됩니다.
//   그리고 나중에 제약 이름을 바꾸면 화면 문구가 같이 바뀝니다.
//
// ② ★★ **모르는 에러를 삼키면 안 됩니다.**
//   `catch` 안에서 무조건 "이미 있는 설비번호입니다" 를 던지면,
//   `이름` 이 NULL 이라 난 `23502` 도 "이미 있는 설비번호" 가 됩니다.
//   그럼 아무도 진짜 원인을 못 찾습니다. 이 문제의 세 번째 검사가 그것입니다.
//
//   조건에 안 맞으면 **원래 에러를 그대로** 던지세요.
//
// ③ ★★★ **미리 SELECT 로 확인하면 안 됩니다.**
//
//     const 있나 = await 실행자.query("SELECT 1 FROM 설비 WHERE 설비번호 = $1", [번호]);
//     if (있나.rowCount > 0) throw new Error("이미 있는 설비번호입니다");
//     await 실행자.query("INSERT ...");
//
//   확인과 INSERT **사이에** 남이 넣을 수 있습니다. 그러면 INSERT 가 터집니다.
//   혼자 테스트하면 절대 안 납니다. 사람이 몰릴 때만 납니다.
//   `23505` 를 잡는 쪽이 **유일하게 정확한** 방법입니다. (07단원의 경합)

await 문제(9, "에러 코드를 도메인 말로", async () => {
  const 새것 = await 설비추가(풀, { 번호: "EQ-100", 이름: "새설비", 라인: "C" });

  const 중복 = await 설비추가(풀, { 번호: "EQ-100", 이름: "또새설비", 라인: "C" })
    .then(() => "성공")
    .catch((에러) => 에러.message);

  const 낫널 = await 설비추가(풀, { 번호: "EQ-101", 이름: null, 라인: "C" })
    .then(() => "성공")
    .catch((에러) => 에러.code);

  await 풀.query("DELETE FROM 설비 WHERE 설비번호 IN ('EQ-100', 'EQ-101')");

  return 새것 !== null && 중복 === "이미 있는 설비번호입니다" && 낫널 === "23502";
});



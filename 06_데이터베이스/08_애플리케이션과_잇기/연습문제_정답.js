// 5. NUMERIC 을 제대로 더하기
// ============================================================
//
// `도입가` 는 NUMERIC 이라 자바스크립트에 **문자열**로 옵니다.
// 그냥 더하면 글자가 이어 붙습니다.
//
// 설비 세 대의 도입가 합계를 **숫자**로 돌려주세요. (정답: 5580001)

async function 도입가합계(실행자) {
  // 방법 ①: DB 에서 더하고 숫자로 바꿔 받습니다 (권장)
  const 결과 = await 실행자.query("SELECT sum(도입가) AS 합 FROM 설비");

  return Number(결과.rows[0].합);
}

// 방법 ②: 자바스크립트에서 더한다면 반드시 Number 로 바꾼 뒤에 더합니다.
//
//   const 줄들 = (await 실행자.query("SELECT 도입가 FROM 설비")).rows;
//   return 줄들.reduce((합, 줄) => 합 + Number(줄.도입가), 0);
//
// ── 왜 ──
//
// `NUMERIC` 은 `pg` 에서 **문자열**로 옵니다. `sum()` 의 결과도 문자열입니다.
// (`sum(NUMERIC)` 은 `NUMERIC` 이니까요)
//
// 그래서 `Number(...)` 를 안 붙이면 이렇게 됩니다.
//
//   줄들.reduce((합, 줄) => 합 + 줄.도입가, 0)
//   → 0 + "1200000.50"          = "01200000.50"
//   → "01200000.50" + "3400000.25" = "01200000.503400000.25"
//
// **에러가 안 납니다.** 화면에 이상한 숫자가 나올 뿐입니다.
// 금액이라면 몇 달 뒤에 발견됩니다.
//
// ★ 왜 문자열로 주나
//   `NUMERIC` 은 자릿수 제한이 없습니다. 자바스크립트 `number` 로는 못 담습니다.
//   드라이버가 마음대로 바꾸면 **조용히 값이 망가집니다.** 그래서 판단을 넘긴 것입니다.
//
// ★★ 돈이라면 `Number` 도 완전하지 않습니다. (`0.1 + 0.2 !== 0.3`)
//   가장 안전한 것은 **DB 안에서 NUMERIC 으로 계산**해서 결과만 받는 것입니다.
//   자바스크립트에서 다뤄야 한다면 원 단위 정수로 바꿔서 다루세요.

await 문제(5, "NUMERIC 을 제대로 더하기", async () => {
  const 합 = await 도입가합계(풀);
  return typeof 합 === "number" && Math.abs(합 - 5580001) < 0.001;
});



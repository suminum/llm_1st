// 6. DATE 를 날짜 글자로 (시간대 함정 피하기)
// ============================================================
//
// EQ-001 의 설치일은 2026-03-02 입니다.
// 그런데 `설치일.toISOString().slice(0, 10)` 을 하면 한국에서는 2026-03-01 이 나옵니다.
//
// "2026-03-02" 를 정확히 돌려주세요.
// ★ 힌트: SQL 쪽에서 글자로 만들어 받으면 시간대를 안 탑니다.

async function 설치일글자(실행자, 설비번호) {
  const 결과 = await 실행자.query(
    "SELECT to_char(설치일, 'YYYY-MM-DD') AS 날 FROM 설비 WHERE 설비번호 = $1",
    [설비번호],
  );

  return 결과.rows.length === 0 ? null : 결과.rows[0].날;
}

// ── 왜 ──
//
// `pg` 는 `DATE` 를 **그 기계의 로컬 자정**으로 만든 `Date` 로 줍니다.
//
//   DB 값        : 2026-03-02
//   JS 값 (한국)  : Mon Mar 02 2026 00:00:00 GMT+0900
//   toISOString(): 2026-03-01T15:00:00.000Z    ← ★ 하루 밀렸습니다
//
// `toISOString().slice(0, 10)` 은 그래서 **2026-03-01** 을 줍니다.
//
// ★★ 최악인 점은 **UTC 서버에서는 안 밀린다**는 것입니다.
//   한국 노트북에서만 틀리고 CI 에서는 통과합니다. 재현이 어렵습니다.
//   시간대가 UTC 서쪽(미국 등)이면 하루 **뒤로** 밀립니다.
//
// ★ 해결책 세 가지
//   ① `to_char(칸, 'YYYY-MM-DD')` 로 SQL 에서 글자를 만듭니다 — 가장 확실합니다
//   ② 파서를 바꿉니다 — `pg.types.setTypeParser(1082, (글자) => 글자)`
//   ③ 로컬 기준으로 직접 조립합니다 — `getFullYear()/getMonth()+1/getDate()`
//
// ★ `TIMESTAMPTZ` 는 이 문제가 없습니다. 시각까지 정확히 옵니다.
//   문제가 되는 것은 **시각이 없는 `DATE`** 입니다.

await 문제(6, "DATE 를 날짜 글자로", async () =>
  (await 설치일글자(풀, "EQ-001")) === "2026-03-02" &&
  (await 설치일글자(풀, "EQ-002")) === "2026-04-11",
);



// 출력?: 몇 배 느린가: 18 배

console.log("결과는 똑같은가:", (await 엔플러스원()).length === (await 조인한번()).length);
// 출력: 결과는 똑같은가: true

// ★★★ 같은 화면인데 **쿼리가 101번 대 1번**입니다.
//
//   그리고 이건 **같은 노트북 안**에서 잰 값입니다.
//   서버와 DB 가 다른 기계면 쿼리 한 번마다 왕복 지연이 붙습니다.
//   왕복이 1밀리초라면 101번은 그것만으로 100밀리초가 더 붙습니다.
//   클라우드에서 흔한 값입니다.
//
// ★ 이름이 왜 N+1 인가
//   목록을 가져오는 **1번** + 각 줄마다 **N번**. 그래서 N+1 입니다.
//
// ★★ 무서운 점은 **작은 데이터에서는 안 보인다**는 것입니다.
//   개발할 때 설비가 3대면 4번입니다. 빠릅니다. 아무 문제 없어 보입니다.
//   운영에서 설비가 5000대가 되면 5001번이 됩니다. 그때 처음 압니다.
//
// ★ 그리고 이건 **ORM 만의 문제가 아닙니다.** 개념03 의 저장소로도 똑같이 납니다.
//
//     for (const 설비 of 설비들) {
//       설비.점검 = await 점검저장소.목록(풀, 설비.번호);   // ← 여기가 N+1 입니다
//     }
//
//   저장소 함수를 예쁘게 만들어 두면 for 문 안에서 부르고 싶어집니다.
//   그게 함정입니다.


// ── 섹션 4: ORM 도 고칠 방법을 줍니다 ──

// 좋은 ORM 은 관계를 **한 번에 가져오는** 방법을 제공합니다.
//
//   // Prisma
//   const 설비들 = await prisma.설비.findMany({
//     include: { 점검기록: true },        // ★ 이 한 줄이 N+1 을 없앱니다
//   });
//
//   // TypeORM
//   const 설비들 = await 저장소.find({ relations: ["점검기록"] });
//
//   // Drizzle
//   const 설비들 = await db.query.설비.findMany({ with: { 점검기록: true } });
//
// ★ Prisma 는 `include` 를 쓰면 대개 **쿼리 2번**을 보냅니다.
//   위에서 잰 `ANY 두 번` 과 같은 방식입니다. JOIN 보다 줄 수가 적어서 유리할 때도 있습니다.
//
// ★★ 그런데 문제는 **`include` 를 안 쓰면 조용히 N+1 이 된다**는 것입니다.
//   에러가 안 납니다. 경고도 없습니다. 그냥 느려집니다.
//   그래서 **나가는 SQL 을 볼 줄 알아야** 합니다.
//
//   Prisma:   new PrismaClient({ log: ["query"] })
//   TypeORM:  createDataSource({ logging: true })
//   Drizzle:  drizzle(연결, { logger: true })
//
//   ★ 개발할 때 이 로그를 **켜 두세요.** 화면 한 번에 쿼리가 몇 번 나가는지
//     눈으로 보면 N+1 은 그 자리에서 잡힙니다.

// 우리 코드에서도 같은 것을 해 봅니다. 쿼리를 세는 것만으로 잡힙니다.

쿼리횟수 = 0;
await 엔플러스원();
const 나쁜쿼리수 = 쿼리횟수;

쿼리횟수 = 0;
await 두번에();
const 좋은쿼리수 = 쿼리횟수;

console.log("화면 한 번에 나간 쿼리:", 나쁜쿼리수, "→", 좋은쿼리수);
// 출력: 화면 한 번에 나간 쿼리: 101 → 2

console.log("쿼리 수가 데이터 개수에 비례하나 (나쁜 신호):", 나쁜쿼리수 > 50);
// 출력: 쿼리 수가 데이터 개수에 비례하나 (나쁜 신호): true

// ★★ 판단 기준은 간단합니다.
//   **쿼리 개수가 데이터 개수에 따라 늘어나면 N+1 입니다.**
//   설비가 100대일 때 101번, 200대일 때 201번이면 확실합니다.


// ── 섹션 5: 어려운 쿼리는 결국 SQL 로 씁니다 ──

// ORM 은 단순한 CRUD 에서 빛납니다. 조금만 어려워지면 막힙니다.
//
//   · 라인별로 최근 점검 결과 하나씩만 (윈도우 함수)
//   · 여러 단계로 묶은 집계
//   · `WITH RECURSIVE`
//   · `INSERT ... ON CONFLICT DO UPDATE`
//   · `EXPLAIN` 을 보면서 힌트를 조정하는 일
//
// 이런 것은 ORM 문법으로 쓰면 오히려 더 어렵고, 나가는 SQL 이 느려집니다.
//
// ★ 그래서 **모든 ORM 에는 탈출구가 있습니다.**
//
//   // Prisma

// 실제로 어려운 쿼리 하나를 SQL 로 써 봅니다. "라인별 최근 점검 하나씩" 입니다.

const 라인별최근 = await 연결.query(`
  SELECT 라인, 설비번호, 결과, 점검일
  FROM (
    SELECT 설비.라인, 설비.설비번호, 점검기록.결과, 점검기록.점검일,
           row_number() OVER (PARTITION BY 설비.라인 ORDER BY 점검기록.점검일 DESC, 설비.설비번호) AS 순위
    FROM 설비
    JOIN 점검기록 ON 점검기록.설비번호 = 설비.설비번호
  ) AS 매긴것
  WHERE 순위 = 1
  ORDER BY 라인
`);

for (const 줄 of 라인별최근.rows) {
  console.log(`${줄.라인}라인 최근 점검 — ${줄.설비번호} · ${줄.결과}`);
}

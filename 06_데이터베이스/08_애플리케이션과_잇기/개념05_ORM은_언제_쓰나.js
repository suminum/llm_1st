//      생 SQL 은 문자열이라 오타를 **실행해 봐야** 압니다. 이 차이가 큽니다.
//
//   ② 스키마와 마이그레이션이 한 곳에
//      스키마 파일을 고치면 마이그레이션을 만들어 줍니다. (개념04 를 대신해 줍니다)
//
//   ③ 관계를 따라가기
//      `설비.점검기록` 처럼 점을 찍어 들어갑니다. JOIN 을 안 써도 됩니다.
//
//   ④ 반복이 줄어듭니다
//      CRUD 다섯 개를 매번 손으로 쓰지 않습니다. 개념03 의 저장소를 반쯤 만들어 줍니다.
//
//   ⑤ DB 를 바꾸기 쉽습니다 — ★ 이건 반쯤만 사실입니다
//      단순한 쿼리는 그렇습니다. 어려운 쿼리는 어차피 DB 마다 다르게 씁니다.
//
// 그런데 ③이 바로 다음 섹션의 함정으로 이어집니다.


// ── 섹션 3: ★★★ N+1 — 진짜로 만들어 봅니다 ──

// 화면 하나를 만든다고 합시다. **설비 목록과 각 설비의 점검기록.**
//
// ORM 으로 쓰면 아주 자연스럽게 이렇게 씁니다.
//
//   const 설비들 = await prisma.설비.findMany();
//   for (const 설비 of 설비들) {
//     설비.점검 = await prisma.점검기록.findMany({ where: { 설비번호: 설비.설비번호 } });
//   }
//
// 읽기 좋습니다. 그리고 **101번 조회합니다.**
//
// 같은 동작을 생 SQL 로 흉내 내서 재 봅니다. ORM 이 안에서 하는 일 그대로입니다.

async function 엔플러스원() {
  const 설비들 = (await 연결.query("SELECT 설비번호, 이름 FROM 설비")).rows;

  for (const 설비 of 설비들) {
    설비.점검 = (await 연결.query(
      "SELECT 결과, 점검일 FROM 점검기록 WHERE 설비번호 = $1",
      [설비.설비번호],
    )).rows;
  }

  return 설비들;
}

async function 조인한번() {
  const 줄들 = (await 연결.query(`
    SELECT 설비.설비번호, 설비.이름, 점검기록.결과, 점검기록.점검일
    FROM 설비
    LEFT JOIN 점검기록 ON 점검기록.설비번호 = 설비.설비번호
    ORDER BY 설비.설비번호
  `)).rows;

  // 줄들을 설비별로 묶습니다. ORM 이 안에서 해 주는 일입니다.
  const 모음 = new Map();

  for (const 줄 of 줄들) {
    if (!모음.has(줄.설비번호)) {
      모음.set(줄.설비번호, { 설비번호: 줄.설비번호, 이름: 줄.이름, 점검: [] });
    }

    if (줄.결과 !== null) 모음.get(줄.설비번호).점검.push({ 결과: 줄.결과, 점검일: 줄.점검일 });
  }

  return [...모음.values()];
}

async function 두번에() {
  const 설비들 = (await 연결.query("SELECT 설비번호, 이름 FROM 설비")).rows;
  const 번호들 = 설비들.map((설비) => 설비.설비번호);

  // ★ IN 대신 `= ANY($1)` 을 씁니다. 배열 하나를 파라미터로 넘길 수 있습니다.
  const 기록들 = (await 연결.query(
    "SELECT 설비번호, 결과, 점검일 FROM 점검기록 WHERE 설비번호 = ANY($1)",
    [번호들],
  )).rows;

  const 모음 = new Map(설비들.map((설비) => [설비.설비번호, { ...설비, 점검: [] }]));

  for (const 줄 of 기록들) 모음.get(줄.설비번호).점검.push({ 결과: 줄.결과, 점검일: 줄.점검일 });

  return [...모음.values()];
}

async function 재기(할일, 횟수 = 5) {
  const 잰것 = [];
  let 쿼리 = 0;

  for (let 회차 = 0; 회차 < 횟수; 회차 += 1) {
    쿼리횟수 = 0;
    const 시작 = performance.now();
    await 할일();
    잰것.push(performance.now() - 시작);
    쿼리 = 쿼리횟수;
  }

  return { ms: 중앙값(잰것), 쿼리 };
}

const 느린것 = await 재기(엔플러스원);
const 조인 = await 재기(조인한번);
const 두번 = await 재기(두번에);

console.log(`N+1 방식 : ${느린것.ms.toFixed(1)} ms · 쿼리 ${느린것.쿼리}번`);
// 출력?: N+1 방식 : 53.9 ms · 쿼리 101번


// ── 섹션 1: 손으로 고치면 왜 안 되나 ──

// 급해서 psql 을 열고 이렇게 칩니다.
//
//   ALTER TABLE 설비 ADD COLUMN 담당자 TEXT;
//
// 그날은 잘 돌아갑니다. 다음 주에 이런 일이 벌어집니다.
//
//   · 새로 들어온 사람이 저장소를 받아 띄웠는데 `담당자` 칸이 없어서 터집니다
//   · 스테이징 서버에는 있고 운영 서버에는 없습니다. 누가 언제 쳤는지 모릅니다
//   · 되돌리려는데 뭘 쳤는지 기억이 안 납니다
//   · 두 사람이 각자 다른 이름의 칸을 만들었습니다 (`담당자` / `관리자`)
//
// ★★ 핵심은 이것입니다. **스키마는 코드입니다.**
//   코드는 저장소에 넣고, 리뷰하고, 순서대로 적용합니다.
//   손으로 친 것은 코드가 아닙니다. 기록이 없기 때문입니다.
//
// 그래서 두 가지를 만듭니다.
//
//   ① 번호가 붙은 변경 파일들 —  001_설비표.sql, 002_점검기록표.sql, ...
//   ② 어디까지 적용했는지 적는 표 — `_마이그레이션`
//
// 이게 전부입니다. 유명한 도구들도 이 두 가지를 합니다.


// ── 섹션 2: 변경 파일을 만듭니다 ──

// 진짜 프로젝트라면 `migrations/` 폴더에 손으로 만들어 둡니다.
// 여기서는 실습이라 임시 폴더에 코드로 만들겠습니다.

const 이사폴더 = fs.mkdtempSync(path.join(os.tmpdir(), "db자료-08-"));

const 변경파일들 = {
  "001_설비표.sql": `
    CREATE TABLE 설비 (
      설비번호 TEXT PRIMARY KEY,
      이름     TEXT NOT NULL,
      라인     TEXT NOT NULL
    );
  `,
  "002_점검기록표.sql": `
    CREATE TABLE 점검기록 (
      번호     SERIAL PRIMARY KEY,
      설비번호 TEXT NOT NULL REFERENCES 설비(설비번호),
      결과     TEXT NOT NULL,
      점검시각 TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX 점검기록_설비번호_색인 ON 점검기록 (설비번호);
  `,
  "003_설비에_상태칸.sql": `
    ALTER TABLE 설비 ADD COLUMN 상태 TEXT NOT NULL DEFAULT '정지';
  `,
};

for (const [이름, 내용] of Object.entries(변경파일들)) {
  fs.writeFileSync(path.join(이사폴더, 이름), 내용.trim() + "\n");
}

console.log("변경 파일:", fs.readdirSync(이사폴더).sort().join(", "));
// 출력: 변경 파일: 001_설비표.sql, 002_점검기록표.sql, 003_설비에_상태칸.sql

// ★ 이름 짓는 규칙
//   · 앞에 **자리를 맞춘 번호**를 붙입니다. `1_` 이 아니라 `001_` 입니다
//     그래야 글자 순서 = 적용 순서가 됩니다. (`10_` 이 `2_` 보다 앞에 오는 사고를 막습니다)
//   · 뒤에는 **무엇을 하는지** 적습니다. `003_수정.sql` 은 아무 정보가 없습니다
//   · 번호 대신 `20260826103000_...` 처럼 시각을 쓰는 팀도 많습니다
//     여러 명이 동시에 만들 때 번호가 겹치지 않아서 그렇게 합니다
//
// ★★★ **한 번 적용한 파일은 절대 고치지 않습니다.**
//   내 노트북에는 고친 게 적용되고, 운영에는 옛것이 적용된 채로 남습니다.
//   고칠 일이 있으면 **새 번호로** 파일을 하나 더 만듭니다.


// ── 섹션 3: ★★ 마이그레이션 도구를 직접 만듭니다 ──

// 하는 일은 네 줄로 요약됩니다.
//
//   ① 적용 기록 표가 없으면 만든다
//   ② 폴더의 .sql 파일을 이름 순으로 읽는다
//   ③ 이미 적용한 것은 건너뛴다
//   ④ 나머지를 **하나씩 트랜잭션 안에서** 적용하고 기록을 남긴다

const 기록표 = "_마이그레이션";

async function 마이그레이션돌리기(연결, 폴더, { 조용히 = false } = {}) {
  // ① 기록 표
  await 연결.query(`
    CREATE TABLE IF NOT EXISTS ${기록표} (
      이름     TEXT PRIMARY KEY,
      적용시각 TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `);

  // ★★ 서버가 여러 대면 배포할 때 **동시에** 이 코드가 돕니다.
  //   둘 다 같은 파일을 적용하려 들면 표가 두 번 만들어지거나 에러가 납니다.
  //   Postgres 의 권고 잠금(advisory lock)으로 한 명씩만 들어오게 막습니다.
  //   숫자는 아무거나 정하면 됩니다. 우리 팀 안에서만 안 겹치면 됩니다.
  await 연결.query("SELECT pg_advisory_lock($1)", [880801]);

  try {
    // ② 이미 적용한 것
    const 적용됨 = new Set(
      (await 연결.query(`SELECT 이름 FROM ${기록표}`)).rows.map((줄) => 줄.이름),
    );

    // ③ 폴더의 파일 목록 (이름 순)
    const 파일들 = fs.readdirSync(폴더).filter((이름) => 이름.endsWith(".sql")).sort();

    const 한것 = [];

    for (const 이름 of 파일들) {
      if (적용됨.has(이름)) {
        if (!조용히) console.log(`  건너뜀 ${이름}`);
        continue;
      }

      const 내용 = fs.readFileSync(path.join(폴더, 이름), "utf8");

      // ④ ★★ 한 파일 = 한 트랜잭션.
      //   중간에 실패하면 그 파일이 한 일이 **통째로** 없던 일이 됩니다.
      await 연결.query("BEGIN");

      try {
        await 연결.query(내용);
        await 연결.query(`INSERT INTO ${기록표} (이름) VALUES ($1)`, [이름]);
        await 연결.query("COMMIT");
      } catch (에러) {
        await 연결.query("ROLLBACK");

        // ★ 어느 파일에서 터졌는지 반드시 알려 줘야 합니다.
        //   원래 코드도 같이 달아 둡니다. 부르는 쪽이 판단할 수 있게요.
        throw Object.assign(new Error(`${이름} 적용 실패 — ${에러.message}`), {
          code: 에러.code,
          파일: 이름,
        });
      }

      한것.push(이름);
      if (!조용히) console.log(`  적용함 ${이름}`);
    }

    return 한것;
  } finally {
    await 연결.query("SELECT pg_advisory_unlock($1)", [880801]);
  }
}

console.log("── 처음 돌립니다 ──");
// 출력: ── 처음 돌립니다 ──

const 첫번째 = await 마이그레이션돌리기(연결, 이사폴더);
// 출력:   적용함 001_설비표.sql
// 출력:   적용함 002_점검기록표.sql
// 출력:   적용함 003_설비에_상태칸.sql

console.log("적용한 개수:", 첫번째.length);

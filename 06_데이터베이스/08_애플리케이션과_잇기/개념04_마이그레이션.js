// 지금까지 표를 만들 때 이렇게 했습니다.
//
//   await 연결.query("DROP TABLE IF EXISTS 설비");
//   await 연결.query("CREATE TABLE 설비 (...)");
//
// 실습이니까 됩니다. 운영에서는 `DROP TABLE` 이 곧 사고입니다.
//
// 진짜 서비스에서는 **표가 이미 있고, 그 안에 자료가 들어 있는 채로**
// 칸을 하나 더 붙이거나 색인을 하나 더 만들어야 합니다.
// 그 일을 안전하게 하는 방법이 마이그레이션(migration)입니다.
//
// 이 파일에서 할 것:
//
//   ① 스키마를 손으로 고치면 무슨 일이 나나
//   ② 마이그레이션 도구를 **직접 만듭니다** (100줄이면 됩니다)
//   ③ ★ Postgres 는 `CREATE TABLE` 도 롤백됩니다 — 실제로 확인합니다
//   ④ 되돌리기(down)를 만들 것인가
//   ⑤ ★★ 배포 중에 옛 코드와 새 코드가 같이 돕니다 — 그때 안전한 순서


console.log("── 새 파일을 하나 얹고 돌립니다 ──");
// 출력: ── 새 파일을 하나 얹고 돌립니다 ──

const 세번째 = await 마이그레이션돌리기(연결, 이사폴더, { 조용히: true });

console.log("이번에 적용한 것:", 세번째.join(", "));
// 출력: 이번에 적용한 것: 004_설비에_담당자칸.sql

const 기록 = await 연결.query(`SELECT 이름 FROM ${기록표} ORDER BY 이름`);

console.log("기록 표의 내용:", 기록.rows.map((줄) => 줄.이름).join(" · "));
// 출력: 기록 표의 내용: 001_설비표.sql · 002_점검기록표.sql · 003_설비에_상태칸.sql · 004_설비에_담당자칸.sql

// ★ 이게 마이그레이션 도구의 전부입니다. 100줄이 안 됩니다.
//
// ★ 진짜 도구들이 더 하는 것
//   · 파일 내용의 해시를 같이 저장해서 **이미 적용한 파일이 바뀌면** 경고합니다
//   · `down` 을 지원합니다 (섹션 5)
//   · 잠금이 안 풀린 채 죽었을 때 손으로 풀 수 있게 해 줍니다
//   · 아직 안 적용된 것이 있으면 목록만 보여 주는 `status` 명령이 있습니다


// ── 섹션 4: ★★ 실패하면 어떻게 되나 ──

// 일부러 틀린 파일을 하나 넣어 봅니다.

fs.writeFileSync(
  path.join(이사폴더, "005_틀린것.sql"),
  // 검증무시: 일부러 실패시키는 SQL 입니다
  "CREATE TABLE 새표 (번호 INT);\nALTER TABLE 없는표 ADD COLUMN 뭔가 TEXT;\n",
);

const 실패 = await 마이그레이션돌리기(연결, 이사폴더, { 조용히: true })
  .then(() => null)
  .catch((에러) => 에러);

console.log("어느 파일에서:", 실패.파일, "· 코드:", 실패.code);
// 출력: 어느 파일에서: 005_틀린것.sql · 코드: 42P01

const 새표있나 = (await 연결.query("SELECT to_regclass('단원08_이사.새표') AS 있나")).rows[0].있나;

console.log("앞부분의 CREATE TABLE 이 남았나:", 새표있나 !== null);
// 출력: 앞부분의 CREATE TABLE 이 남았나: false

const 기록에있나 = (await 연결.query(
  `SELECT count(*)::int AS 건수 FROM ${기록표} WHERE 이름 = '005_틀린것.sql'`,
)).rows[0].건수;

console.log("기록 표에 남았나:", 기록에있나 === 1);
// 출력: 기록 표에 남았나: false

// ★★★ 여기가 PostgreSQL 의 큰 장점입니다.
//
//   `005_틀린것.sql` 은 두 문장입니다.
//   첫 문장(`CREATE TABLE 새표`)은 **성공했습니다.**
//   두 번째에서 터졌고, `ROLLBACK` 이 첫 문장까지 되돌렸습니다.
//
//   그래서 **반쯤 적용된 상태가 없습니다.** 파일을 고치고 다시 돌리면 됩니다.

// 좀 더 또렷하게 확인해 봅니다. 표를 만들고 롤백합니다.

await 연결.query("BEGIN");
await 연결.query("CREATE TABLE 사라질표 (번호 INT)");

const 안에서 = (await 연결.query("SELECT to_regclass('단원08_이사.사라질표') AS 있나")).rows[0].있나;

await 연결.query("ROLLBACK");

const 밖에서 = (await 연결.query("SELECT to_regclass('단원08_이사.사라질표') AS 있나")).rows[0].있나;

console.log("트랜잭션 안에서 표가 보이나:", 안에서 !== null);
// 출력: 트랜잭션 안에서 표가 보이나: true

console.log("롤백한 뒤에도 남아 있나:", 밖에서 !== null);
// 출력: 롤백한 뒤에도 남아 있나: false

// ── MySQL 은 여기가 다릅니다 ──
//
//   ★★ MySQL 은 `CREATE TABLE` 같은 스키마 변경(DDL)을 만나면
//     **그 자리에서 자동으로 커밋합니다.** `ROLLBACK` 을 해도 표가 남습니다.
//
//   그래서 MySQL 에서는 마이그레이션이 중간에 실패하면
//   **반쯤 적용된 상태**가 그대로 남습니다. 손으로 치워야 합니다.
//   그래서 MySQL 쪽 도구들은 파일 하나에 한 문장만 넣기를 권합니다.
//
//   ★ 09단원에서 둘 다 띄워 놓고 직접 확인합니다.

// 실패한 파일은 치우고 이어 갑니다.
fs.rmSync(path.join(이사폴더, "005_틀린것.sql"));


// ── 섹션 5: 되돌리기(down)를 만들 것인가 ──

// 많은 도구가 파일 하나에 `up` 과 `down` 을 같이 쓰게 해 줍니다.
//
//   -- up
//   ALTER TABLE 설비 ADD COLUMN 담당자 TEXT;
//   -- down
//   ALTER TABLE 설비 DROP COLUMN 담당자;
//
// ★ 실무에서는 `down` 을 **거의 안 씁니다.** 이유가 분명합니다.
//

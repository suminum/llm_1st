// 문제 3 — 총 시간으로 줄 세우기
// ============================================================
//
// pg_stat_statements 를 흉내 낸 배열입니다.
// **서버 시간을 제일 많이 잡아먹는** 쿼리의 `이름` 을 돌려주세요.
//
// ★ 주의: 평균이 긴 것이 아니라 **총 시간**이 긴 것입니다.

const 쿼리통계 = [
  { 이름: "목록조회", 호출: 500000, 평균ms: 0.4 },
  { 이름: "월간집계", 호출: 12, 평균ms: 900 },
  { 이름: "상세조회", 호출: 80000, 평균ms: 1.1 },
];

function 진짜범인(통계) {
  return [...통계].sort((가, 나) => 나.호출 * 나.평균ms - 가.호출 * 가.평균ms)[0].이름;
}

// ★★★ 이 문제가 개념02 의 전부입니다. 숫자를 직접 보세요.
//
//   이름        호출        평균     총 시간
//   ─────────────────────────────────────────────
//   목록조회    500,000    0.4ms    200,000ms  ← ★ 범인
//   상세조회     80,000    1.1ms     88,000ms
//   월간집계         12    900ms      10,800ms
//
//   눈에 띄는 것은 **월간집계**입니다. 한 번에 0.9초니까요.
//   그런데 서버 시간의 **2퍼센트**밖에 안 씁니다.
//
//   목록조회는 0.4ms 입니다. 아무도 느리다고 생각 안 합니다.
//   그런데 서버 시간의 **67퍼센트**를 씁니다. 월간집계의 18배입니다.
//
// ★★ 그래서 pg_stat_statements 는 이렇게 봅니다.
//
//     ORDER BY total_exec_time DESC     ← ✓
//     ORDER BY mean_exec_time DESC      ← ✗ 배치 쿼리만 나옵니다
//
// ★ 그리고 **고치는 방법이 다릅니다.**
//   목록조회를 색인으로 0.4ms → 0.2ms 로 만들면 10만ms 를 아낍니다. 좋습니다.
//   그런데 더 좋은 것은 **50만 번 부르는 것을 줄이는 것**입니다.
//   대개 08단원의 N+1 입니다. 목록 하나 그리는데 줄마다 쿼리를 날리는 것이죠.
//   그걸 한 번의 JOIN 으로 바꾸면 50만 번이 1000번이 됩니다.



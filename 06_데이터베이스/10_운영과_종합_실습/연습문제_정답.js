// ============================================================
// 문제 13 — [도전] 색인 없는 외래키 찾기
// ============================================================
//
// 외래키를 걸었는데 그 칸에 색인이 없는 곳을 찾는 SQL 을 쓰세요.
// `단원10_정답` 스키마만 봅니다.
//
// 돌려줄 칸: `표` 와 `칸`
//
// 힌트: pg_constraint (contype='f', conkey[1] 이 첫 칸)
//       pg_index 에 indrelid 가 같고 indkey[0] = conkey[1] 인 것이 없으면 색인 없음
//       pg_attribute 로 칸 번호를 이름으로 바꿉니다

const 색인없는외래키찾기 = `
  SELECT t.relname::text AS 표, a.attname::text AS 칸
  FROM pg_constraint c
  JOIN pg_class t ON t.oid = c.conrelid
  JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
  WHERE c.contype = 'f'
    AND c.connamespace = '${스키마}'::regnamespace
    AND NOT EXISTS (
      SELECT 1 FROM pg_index i
      WHERE i.indrelid = c.conrelid AND i.indkey[0] = c.conkey[1]
    )
  ORDER BY 표, 칸
`;

// ★ 카탈로그 표들이 무엇인지부터
//
//   pg_constraint   제약들. `contype='f'` 가 외래키입니다
//                   `conrelid` = 자식 표, `conkey` = 자식 쪽 칸 번호 배열
//   pg_class        표·색인 같은 것들. `relname` 이 이름입니다
//   pg_attribute    칸들. `attnum` 이 번호, `attname` 이 이름입니다
//   pg_index        색인들. `indkey` 가 색인이 걸린 칸 번호 배열입니다
//
// ★★ `indkey[0] = conkey[1]` 이 핵심입니다. 번호가 헷갈립니다.
//   `conkey` 는 **1부터** 세는 SQL 배열이라 첫 칸이 `conkey[1]` 입니다.
//   `indkey` 는 **0부터** 세는 내부 벡터라 첫 칸이 `indkey[0]` 입니다.
//   둘 다 "첫 번째 칸" 을 가리킵니다.
//
// ★★★ 왜 **첫 칸**만 보나 — 06단원의 복합 색인 규칙 때문입니다.
//   색인 `(라인코드, 생산일)` 은 `라인코드` 만으로 찾을 때도 쓸 수 있습니다.
//   왼쪽부터 쓰니까요. 그래서 외래키 칸이 **색인의 첫 칸이기만 하면** 됩니다.
//   개념05 에서 `생산실적.라인코드` 가 안 걸린 이유가 이것입니다.
//   복합 기본키 `(라인코드, 생산일)` 의 첫 칸이었으니까요.
//
// ★★ 왜 이게 중요한가 — 색인이 없으면 이렇게 됩니다.
//
//     DELETE FROM 라인 WHERE 라인코드 = 'D';
//
//   Postgres 는 "이 라인을 쓰는 설비가 있나" 를 확인해야 합니다.
//   색인이 없으면 **설비 표를 통째로 훑습니다.** 그동안 잠금도 쥡니다.
//   설비가 1000만 건이면 라인 하나 지우는 데 몇십 초가 걸립니다.
//
// ★ 기본키와 UNIQUE 에는 색인이 **자동으로** 생깁니다.
//   외래키에는 **안 생깁니다.** 이게 실무에서 제일 흔한 누락입니다.


// ============================================================
// 문제 14 — [도전] 코드 점검 도구
// ============================================================
//
// 소스 코드 문자열을 받아서 위험한 줄을 찾아 주는 함수를 만드세요.
//
// 찾을 것 두 가지
//   ① `SELECT *`                    → 종류 "별표"
//   ② 템플릿 문자열로 이어 붙인 SQL   → 종류 "이어붙임"
//      (SELECT/INSERT/UPDATE/DELETE 가 있는 줄에 `${` 가 있으면)
//
// 돌려줄 것: `{ 줄번호, 종류 }` 객체의 배열. 줄번호는 1부터 셉니다.
// 한 줄에 둘 다 있으면 두 개를 담습니다. 순서는 ① 다음 ② 입니다.

function 코드점검(소스) {
  const 찾은것 = [];

  소스.split("\n").forEach((줄, 자리) => {
    const 줄번호 = 자리 + 1;

    // ① SELECT * — 대소문자를 가리지 않게 `i`, 공백은 하나 이상이라 `\s+`
    if (/select\s+\*/i.test(줄)) {
      찾은것.push({ 줄번호, 종류: "별표" });
    }

    // ② 템플릿 문자열로 이어 붙인 SQL
    if (/(select|insert|update|delete)/i.test(줄) && 줄.includes("${")) {
      찾은것.push({ 줄번호, 종류: "이어붙임" });
    }
  });

  return 찾은것;
}

// ★ 왜 이 두 가지를 잡나
//
// ── ① `SELECT *` 가 왜 나쁜가 ──
//

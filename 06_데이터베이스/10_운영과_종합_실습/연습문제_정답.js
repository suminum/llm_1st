//
// `단원10_정답` 스키마에서 **죽은 줄이 1000개를 넘는** 표를 찾는 SQL 을 쓰세요.
// 돌려줄 칸: `표` (표 이름)
//
// 힌트: pg_stat_user_tables 의 schemaname, relname, n_dead_tup

const 부푼표찾기 = `
  SELECT relname::text AS 표
  FROM pg_stat_user_tables
  WHERE schemaname = '${스키마}' AND n_dead_tup > 1000
  ORDER BY 표
`;

// ★ `pg_stat_user_tables` 에서 꼭 볼 칸들입니다.
//
//   n_live_tup         산 줄 (대략)
//   n_dead_tup         ★ 죽은 줄 — 청소해야 할 것
//   last_vacuum        마지막으로 **손으로** 돌린 시각
//   last_autovacuum    마지막으로 **알아서** 돈 시각
//   last_analyze / last_autoanalyze   통계를 언제 모았나
//
// ★★ 이 숫자들은 **대략**이고 **늦게** 옵니다.
//   통계는 따로 모아서 나중에 반영됩니다.
//   그래서 채점 코드가 `ANALYZE` 를 돌리고 채워질 때까지 몇 번 다시 봅니다.
//   이 자료를 만들 때도 바로 읽었다가 0 이 나와서 헤맸습니다.
//
// ★★★ 운영에서 진짜 쓰는 질의는 **비율**로 봅니다. 절대 개수는 표마다 의미가 달라서요.
//
//     SELECT relname,
//            n_live_tup, n_dead_tup,
//            round(n_dead_tup * 100.0 / NULLIF(n_live_tup + n_dead_tup, 0), 1) AS 죽은비율,
//            last_autovacuum
//     FROM pg_stat_user_tables
//     WHERE n_dead_tup > 10000
//     ORDER BY n_dead_tup DESC
//     LIMIT 20;
//
//   `NULLIF(..., 0)` 은 **0 으로 나누기를 막는 것**입니다. 빈 표에서 터지지 않게요.
//
// ★ 죽은 줄이 많은데 `last_autovacuum` 이 오래됐다면

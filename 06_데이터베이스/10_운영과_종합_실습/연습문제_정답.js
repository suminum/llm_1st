// `pg_stat_activity` 에서 **지금 실행 중이면서 1초 넘게 돌고 있는** 세션을 찾는
// SQL 을 쓰세요. `application_name` 이 'unit10-answervictim' 인 것만 봅니다.
//
// 돌려줄 칸: `문장` 하나 (query 의 앞 20글자)
//
// 힌트: state = 'active', now() - query_start > interval '1 second'
//       left(query, 20) AS 문장

const 돌고있는것찾기 = `
  SELECT left(query, 20) AS 문장
  FROM pg_stat_activity
  WHERE application_name = 'unit10-answervictim'
    AND state = 'active'
    AND now() - query_start > interval '1 second'
`;

// ★ 세 조건이 다 필요합니다.
//
//   application_name = '...'                 ★ 이 DB 는 다른 단원도 같이 씁니다.
//                                            내 것만 봐야 합니다
//   state = 'active'                         지금 **진짜 일하는 중**인 것만
//   now() - query_start > interval '1 second'  1초 넘게 돌고 있는 것만
//
// ★★ `state` 를 안 걸면 놀고 있는 연결까지 다 나옵니다.
//   연결 풀을 쓰면 `idle` 이 수십 개씩 떠 있습니다. 그건 정상입니다. (08단원)

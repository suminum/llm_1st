// 출력: 한 줄이 설명하는 주제 개수: 4

// ★★ 한 줄이 **네 가지**를 동시에 설명합니다.
//   그래서 설비 이름 하나만 고치려 해도 점검 줄까지 건드리게 됩니다. 나눌 자리는 이 경계입니다.

// ── 함수 종속 ──
// ★ **무엇을 알면 무엇이 정해지는가.** 이게 전부입니다.
//   설비이름을 알면 도입년도가 정해집니다 → 설비이름 → 도입년도.
//   기호 놀이 대신 **데이터로 확인**합니다. 왼쪽으로 묶어 오른쪽이 몇 가지인지 세면 됩니다.
const 설비종속 = await db.query(`
  SELECT 설비이름, count(DISTINCT 설비도입년도)::int AS 가짓수
  FROM 점검대장 GROUP BY 설비이름 ORDER BY 설비이름
`);
for (const 줄 of 설비종속.rows) console.log(`${줄.설비이름} → 도입년도 ${줄.가짓수}가지`);
// 출력: 검사기 1호 → 도입년도 1가지
// 출력: 용접로봇 1호 → 도입년도 1가지
// 출력: 컨베이어 1호 → 도입년도 1가지
// 출력: 포장기 1호 → 도입년도 1가지
// 출력: 프레스 1호 → 도입년도 1가지
console.log("설비이름을 알면 도입년도가 하나로 정해지나:", 설비종속.rows.every((줄) => 줄.가짓수 === 1));
// 출력: 설비이름을 알면 도입년도가 하나로 정해지나: true

// 반대로 **안 정해지는 것**도 봐야 합니다. 라인코드로 묶어 봅니다.
const 라인종속 = await db.query(`
  SELECT 라인코드,
         count(DISTINCT 라인이름)::int AS 라인이름가짓수,
         count(DISTINCT 설비이름)::int AS 설비이름가짓수
  FROM 점검대장 GROUP BY 라인코드 ORDER BY 라인코드
`);
for (const 줄 of 라인종속.rows) console.log(`${줄.라인코드} → 라인이름 ${줄.라인이름가짓수}가지 · 설비이름 ${줄.설비이름가짓수}가지`);
// 출력: A → 라인이름 1가지 · 설비이름 2가지
// 출력: B → 라인이름 1가지 · 설비이름 2가지
// 출력: C → 라인이름 1가지 · 설비이름 1가지
console.log("라인코드 → 라인이름 인가:", 라인종속.rows.every((줄) => 줄.라인이름가짓수 === 1));
// 출력: 라인코드 → 라인이름 인가: true
console.log("라인코드 → 설비이름 인가:", 라인종속.rows.every((줄) => 줄.설비이름가짓수 === 1));
// 출력: 라인코드 → 설비이름 인가: false

// ★ A라인에 설비가 두 가지라 "라인코드 → 설비이름" 은 성립하지 않습니다.
//   성립하는 것만 모으면 그게 나눌 표의 밑그림입니다.
//     설비번호 → 설비이름, 도입년도 / 라인코드 → 라인이름, 라인동 / 사번 → 이름, 연락처

// ── 섹션 2: ★ 제1정규형 — 한 칸에 여러 값을 넣지 않기 ──

// "컨베이어는 A라인에도 B라인에도 걸쳐 있어요. 둘 다 적어 주세요."
// 가장 쉬운 답은 콤마로 잇는 것입니다. 실제로 아주 많이 봅니다.
await db.exec(`
  CREATE TABLE 설비_나쁨 (번호 INT PRIMARY KEY, 이름 TEXT NOT NULL, 라인목록 TEXT NOT NULL);
  INSERT INTO 설비_나쁨 VALUES
    (1,'컨베이어','A,B'), (2,'프레스','B'), (3,'용접로봇','A,BC'), (4,'검사기','BC'), (5,'포장기','C');
`);

// ★ 'BC' 는 오타가 아닙니다. **BC 라인**이라는 다른 라인입니다. 현장 코드에는 흔합니다.
// 이제 "B라인 설비를 찾아 주세요" 를 해 봅니다. 칸에 값이 여러 개니 = 로는 못 찾습니다.

// 검증무시: 일부러 틀린 조회입니다
const 오탐 = await db.query("SELECT 번호, 이름, 라인목록 FROM 설비_나쁨 WHERE 라인목록 LIKE '%B%' ORDER BY 번호");
for (const 줄 of 오탐.rows) console.log(`걸림: ${줄.번호}번 ${줄.이름} — 라인목록 '${줄.라인목록}'`);
// 출력: 걸림: 1번 컨베이어 — 라인목록 'A,B'
// 출력: 걸림: 2번 프레스 — 라인목록 'B'
// 출력: 걸림: 3번 용접로봇 — 라인목록 'A,BC'
// 출력: 걸림: 4번 검사기 — 라인목록 'BC'
const 진짜B = 오탐.rows.filter((줄) => 줄.라인목록.split(",").includes("B"));
const 가짜B = 오탐.rows.filter((줄) => !줄.라인목록.split(",").includes("B"));

console.log("LIKE 로 걸린 개수:", 오탐.rows.length);
// 출력: LIKE 로 걸린 개수: 4
console.log("실제 B라인 개수:", 진짜B.length);
// 출력: 실제 B라인 개수: 2
console.log("B라인이 아닌데 걸린 번호:", 가짜B.map((줄) => 줄.번호).join(", "));
// 출력: B라인이 아닌데 걸린 번호: 3, 4

// ★★★ 3번('A,BC') 과 4번('BC') 은 **B라인이 아닌데 걸렸습니다.**
//   LIKE '%B%' 는 "B 라는 글자가 어딘가 있으면" 입니다. 'BC' 안에도 B 가 있습니다.
//   **한 칸에 값을 여러 개 넣은 순간부터 정확히 찾을 방법이 없어진 것**입니다.
//   에러도 안 납니다. 틀린 목록이 조용히 나옵니다.
// ★ 그 밖에 못 하는 것 — **개수를 못 세고, 정렬을 못 하고, 외래키를 못 겁니다.** 걸어 봅니다.
await db.exec(`
  CREATE TABLE 라인_간이 (라인코드 TEXT PRIMARY KEY);
  INSERT INTO 라인_간이 VALUES ('A'), ('B'), ('BC'), ('C');
`);
try {
  // 검증무시: 콤마 목록에는 외래키를 못 겁니다
  await db.exec("ALTER TABLE 설비_나쁨 ADD FOREIGN KEY (라인목록) REFERENCES 라인_간이(라인코드);");
  console.log("외래키가 걸렸습니다");
} catch (에러) {
  console.log("외래키 걸기 실패:", 에러.code);
}
// 출력: 외래키 걸기 실패: 23503

// 'A,B' 라는 라인코드는 라인 표에 없으니 거부당합니다.
// ★★ 즉 **없는 라인을 적어도 아무도 못 막는 상태**입니다.
// 고치는 법은 간단합니다. **칸을 늘리지 말고 줄을 늘립니다.**
await db.exec(`
  CREATE TABLE 설비라인 (
    설비번호 INT NOT NULL,
    라인코드 TEXT NOT NULL REFERENCES 라인_간이(라인코드),
    PRIMARY KEY (설비번호, 라인코드)
  );
  INSERT INTO 설비라인 VALUES (1,'A'), (1,'B'), (2,'B'), (3,'A'), (3,'BC'), (4,'BC'), (5,'C');
`);

const 정확 = await db.query("SELECT 설비번호 FROM 설비라인 WHERE 라인코드 = $1 ORDER BY 설비번호", ["B"]);
console.log("라인코드 = 'B' 로 걸린 번호:", 정확.rows.map((줄) => 줄.설비번호).join(", "));
// 출력: 라인코드 = 'B' 로 걸린 번호: 1, 2
console.log("오탐이 사라졌나:", 정확.rows.length === 진짜B.length);
// 출력: 오탐이 사라졌나: true

// LIKE 로는 못 하던 **개수 세기**도 이제 됩니다.
const 라인개수 = await db.query("SELECT 설비번호, count(*)::int AS 라인수 FROM 설비라인 GROUP BY 설비번호 ORDER BY 설비번호");
for (const 줄 of 라인개수.rows) console.log(`설비 ${줄.설비번호}번 → 라인 ${줄.라인수}개`);
// 출력: 설비 1번 → 라인 2개
// 출력: 설비 2번 → 라인 1개
// 출력: 설비 3번 → 라인 2개
// 출력: 설비 4번 → 라인 1개
// 출력: 설비 5번 → 라인 1개

// ★ 여기에 이름을 붙입니다. **한 칸에는 값 하나. 이것을 제1정규형(1NF) 이라고 합니다.**
// ★ TEXT[] 나 JSONB 는 어떤가 — **예외가 있습니다. 개념05 에서 다룹니다.**

// ── 섹션 3: ★ 제2정규형 — 기본키 일부에만 딸린 칸 떼어내기 ──

// ★★ 2정규형 문제는 **기본키가 칸 두 개 이상일 때만** 생깁니다.
//   기본키가 칸 하나면 볼 필요도 없습니다. 이미 2정규형입니다.
// 기본키가 (설비번호, 점검일) 인 점검 표를 만들어 봅니다.
await db.exec(`
  CREATE TABLE 점검_1차 (
    설비번호 INT NOT NULL, 점검일 DATE NOT NULL,
    설비이름 TEXT NOT NULL, 설비도입년도 INT NOT NULL, 결과 TEXT NOT NULL,
    PRIMARY KEY (설비번호, 점검일)
  );
  INSERT INTO 점검_1차 VALUES
    (1,'2024-01-05','컨베이어 1호',2015,'정상'), (1,'2024-02-05','컨베이어 1호',2015,'정상'),
    (1,'2024-03-05','컨베이어 1호',2015,'주의'), (2,'2024-01-12','프레스 1호',2019,'정상'),
    (2,'2024-02-12','프레스 1호',2019,'정상'),   (3,'2024-01-20','용접로봇 1호',2021,'정상'),
    (3,'2024-02-20','용접로봇 1호',2021,'주의'), (4,'2024-01-25','검사기 1호',2018,'정상'),
    (5,'2024-02-28','포장기 1호',2022,'정상');
`);

// 칸마다 물어봅니다. **기본키 전체가 있어야 정해지는가?**
//   결과     — (설비번호, 점검일) 둘 다 있어야 정해집니다. 정상입니다
//   설비이름 — 설비번호만 알면 정해집니다. 점검일은 필요 없습니다 ★
//   설비도입년도 — 역시 설비번호만 알면 정해집니다 ★
// 기본키의 **일부**에만 딸린 것. 이걸 **부분 종속** 이라고 합니다.
const 부분종속 = await db.query(`
  SELECT 설비번호, count(DISTINCT 설비이름)::int AS 이름가짓수, count(*)::int AS 줄수
  FROM 점검_1차 GROUP BY 설비번호 ORDER BY 설비번호
`);

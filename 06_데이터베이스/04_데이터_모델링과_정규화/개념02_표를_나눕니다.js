// 출력: · 라인 — 라인코드 · 라인이름 · 라인동
// 출력: · 사람 — 담당자사번 · 담당자이름 · 담당자연락처
// 출력: · 점검 — 점검번호 · 점검일 · 결과 · 점수 · 점검내용

// 출력: 점검대장 칸 수: 13

// 이 13개 칸을 "무엇을 설명하는 칸인가" 로 묶으면 이렇게 갈립니다.
const 주제별칸 = [
  ["설비", "설비이름 · 설비도입년도"],
  ["라인", "라인코드 · 라인이름 · 라인동"],
  ["사람", "담당자사번 · 담당자이름 · 담당자연락처"],
  ["점검", "점검번호 · 점검일 · 결과 · 점수 · 점검내용"],
];

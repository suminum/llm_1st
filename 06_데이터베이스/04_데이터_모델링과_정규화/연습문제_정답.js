// ★ 다섯 가지 정책
//   RESTRICT    자식이 있으면 부모 삭제를 즉시 막습니다
//   NO ACTION   자식이 있으면 막습니다 (기본값). RESTRICT 와 거의 같습니다
//   CASCADE     부모를 지우면 자식도 같이 지웁니다
//   SET NULL    자식의 그 칸을 NULL 로 바꿉니다
//   SET DEFAULT 자식의 그 칸을 DEFAULT 값으로 바꿉니다
//
// ★★★ 여기가 핵심입니다. SQLSTATE 가 서로 다릅니다.
//     ON DELETE RESTRICT  위반 →  23001
//     ON DELETE NO ACTION 위반 →  23503
//   외래키니까 당연히 23503 이겠거니 하고 적으면 틀립니다. 돌려 보지 않으면 절대 모릅니다.
//   에러 코드로 분기하는 코드를 짜다가 이걸로 반나절씩 날립니다.
//
// ★★ 둘의 진짜 차이는 미룰 수 있느냐입니다.
//   DEFERRABLE INITIALLY DEFERRED 를 걸면 NO ACTION 은 **트랜잭션 끝까지 미뤄져 통과**하고,
//   RESTRICT 는 미뤄도 **그 자리에서 막힙니다.** (트랜잭션은 07단원에서 제대로 합니다)
//
// ★★ CASCADE 는 편한 만큼 위험합니다.
//   라인을 지우면 설비가, 그 설비의 점검기록이 줄줄이 따라갑니다.
//   DELETE 한 줄에 몇 만 줄이 사라질 수 있고 되돌릴 수 없습니다.
//   무엇이 딸려 나가는지 모르면 걸지 마세요.
//
// ★ SET DEFAULT 에는 함정이 하나 더 있습니다. 기본값이 **부모 표에 없으면** 23503 입니다.
//   기본값이 '미상' 이면 부모 표에 '미상' 줄을 미리 넣어 두어야 합니다.
//
// ★★★ 정답이 여럿입니다 — (나)를 SET NULL 로 해도 맞습니다.
//   "설비를 폐기해도 점검 이력은 감사 때문에 남긴다" 는 현장이 많습니다.
//   그러면 SET NULL 이거나, 아예 안 지우고 폐기여부 칸을 두는 논리 삭제를 씁니다.
//   무엇을 기준으로 고르는가: **자식이 부모 없이도 의미가 있는가.**
//   장바구니에 담긴 물건은 의미가 없습니다 → CASCADE.
//   매출 전표는 담당자가 퇴사해도 의미가 있습니다 → SET NULL.



//
// ★★ 흔한 오답 ② — 한 줄만 고치기 (WHERE 점검번호 = 1)
//   화면에서 "김반장 정보 수정" 을 눌러 저장하면 딱 이 모양이 됩니다.
//   같은 사번에 연락처가 두 가지가 되고, 어느 쪽이 맞는지 아무도 모릅니다.

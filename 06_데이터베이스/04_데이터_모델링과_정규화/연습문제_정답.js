const 문제13 = `
  CREATE TABLE 점검배정 (
    설비번호 INT  NOT NULL REFERENCES 설비대장(설비번호) ON DELETE RESTRICT,
    사번     INT  NOT NULL REFERENCES 사원(사번)        ON DELETE CASCADE,
    배정일   DATE NOT NULL,
    역할     TEXT NOT NULL,
    PRIMARY KEY (설비번호, 사번, 배정일)
  );

  INSERT INTO 점검배정 (설비번호, 사번, 배정일, 역할) VALUES
    (4, 101, '2024-04-01', '주담당'),
    (4, 101, '2024-04-08', '주담당'),
    (4, 105, '2024-04-05', '보조');
`;

await 채점(13, "[도전] 중간 표에 추가 정보를 붙이기", async () => {
  await db.exec(문제13);

  const 코드받기 = async (문장) => {
    try {
      await db.query(문장);
      return null;
    } catch (에러) {
      return 에러.code;
    }
  };

  const 처음 = await db.query("SELECT count(*)::int AS 건수 FROM 점검배정");
  const 같은날중복 = await 코드받기("INSERT INTO 점검배정 VALUES (4, 101, '2024-04-01', '보조')");

  await db.query("DELETE FROM 사원 WHERE 사번 = 105");
  const 지운뒤 = await db.query("SELECT count(*)::int AS 건수 FROM 점검배정");

  const 설비삭제 = await 코드받기("DELETE FROM 설비대장 WHERE 설비번호 = 4");

  return (
    처음.rows[0].건수 === 3 && 같은날중복 === "23505" &&
    지운뒤.rows[0].건수 === 2 && 설비삭제 === "23001"
  );
});
// 출력: 13. [도전] 중간 표에 추가 정보를 붙이기 — ✅ 통과

// ★★★ 흔한 오답 — 기본키를 (설비번호, 사번) 으로 잡기
//   10번이 그랬으니 여기도 그럴 것 같습니다. 그런데 둘째 줄에서 23505 가 납니다.
//     (4, 101, '2024-04-01')  들어감
//     (4, 101, '2024-04-08')  ← 같은 짝이라 막힘
//   김반장이 같은 설비를 다음 주에 또 맡는 것은 지극히 정상입니다.
//
//   ★ 중간 표에 추가 정보가 붙으면 **그 정보가 키에 들어가야 하는지** 반드시 따집니다.
//   질문은 하나입니다. "같은 짝이 여러 번 나올 수 있는가."
//     못 나온다 → 짝만 키 (사원자격)
//     나올 수 있다 → 무엇이 다르면 다른 줄인지 그 칸을 키에 넣습니다 (배정일)
//
// ★ 역할은 왜 키에 안 넣었나
//   요구사항이 "같은 날 같은 사람이 같은 설비에 두 번 배정되면 안 된다" 였습니다.
//   역할까지 키에 넣으면 같은 날 주담당으로도 보조로도 배정할 수 있게 됩니다.
//   ★ **키에 칸을 더 넣는 것은 규칙을 푸는 일**입니다. 조이는 일이 아닙니다.
//
// ★ ON DELETE 두 개를 다르게 건 이유
//   사번 → CASCADE    : 배정은 사람에게 딸린 예정표라 사람이 없으면 의미가 없습니다
//   설비번호 → RESTRICT : 배정이 남은 설비를 실수로 지우면 예정이 통째로 날아갑니다
//   ★ 같은 표 안에서도 방향마다 정책이 다를 수 있습니다. 6번의 기준을 방향별로 적용하세요.
//
// ★ 실측으로 확인한 것 — 사원 105 를 지우니 배정이 3줄에서 2줄이 되었습니다(CASCADE).
//   설비 4 를 지우려니 23001 로 막혔습니다. RESTRICT 라서 23503 이 아닙니다. (6번 참고)
//
// ★★★ 정답이 여럿입니다.
//   ① 대리키 방식 — 배정번호 SERIAL PRIMARY KEY + UNIQUE (설비번호, 사번, 배정일)
//      규칙은 똑같이 지켜집니다. 배정마다 첨부파일을 붙이는 식으로 다른 표가 이 줄을
//      가리켜야 할 때 편합니다.
//   ② 기간 방식 — 시작일 · 종료일 을 두고 "이 기간 동안 맡는다" 로 봅니다.
//      날짜별로 줄이 안 쌓여 훨씬 가볍습니다. 대신 기간이 겹치는 것을 막기가 까다롭습니다.
//      (EXCLUDE 제약과 범위 타입으로 막습니다. 여기서는 이름만 알아 두세요)
//   ③ 역할을 별도 표로 빼는 방식 — 역할이 두 가지로 고정이면 지금이 낫습니다.
//      역할마다 설명·권한이 붙는다면 역할 표를 만들고 외래키로 겁니다.
//      기준: **그 값이 다른 사실을 데리고 다니는가.** 데리고 다니면 표로 뺍니다.
//
//   ★ 채점 코드는 하나만 통과시킵니다. ①②③ 전부 현장에서 쓰는 진짜 설계입니다.
//     설계를 고를 때 물어볼 것은 언제나 둘뿐입니다.
//     "무엇 하나가 한 줄인가" 와 "같은 것이 두 번 나와도 되는가."



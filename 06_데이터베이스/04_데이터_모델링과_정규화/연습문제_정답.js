async function B라인작업자() {
  await db.exec(`
    CREATE TABLE 작업자라인_1정규형 (
      사번     INT  NOT NULL,
      라인코드 TEXT NOT NULL,
      PRIMARY KEY (사번, 라인코드)
    );

    INSERT INTO 작업자라인_1정규형 (사번, 라인코드)
    SELECT 사번, unnest(string_to_array(라인목록, ',')) FROM 작업자라인;
  `);

  const 결과 = await db.query(
    "SELECT 사번 FROM 작업자라인_1정규형 WHERE 라인코드 = $1 ORDER BY 사번",
    ["B"],
  );

  return 결과.rows.map((줄) => 줄.사번);
}

await 채점(3, "한 칸에 값을 여러 개 넣으면", async () => {
  const 사번들 = await B라인작업자();
  const 줄수 = await db.query("SELECT count(*)::int AS 건수 FROM 작업자라인_1정규형");
  const 오탐 = await db.query("SELECT count(*)::int AS 건수 FROM 작업자라인 WHERE 라인목록 LIKE '%B%'");
  return (
    Array.isArray(사번들) &&
    사번들.join(",") === "101,102" &&
    줄수.rows[0].건수 === 7 &&
    오탐.rows[0].건수 === 4
  );
});
// 출력:  3. 한 칸에 값을 여러 개 넣으면 — ✅ 통과

// ★ 제1정규형은 "한 칸에 값 하나" 입니다.
//   'A,B' 는 값 하나가 아니라 값 둘을 글자로 이어 붙인 것입니다.
//   데이터베이스는 이걸 그냥 긴 글자로만 봅니다. 안에 뭐가 들었는지 모릅니다.
//
// ★★ 흔한 오답 ① — LIKE 를 더 정교하게 만들기
//     WHERE 라인목록 LIKE '%B%'  → 4명 (오탐 2명)
//     WHERE 라인목록 = 'B' OR LIKE 'B,%' OR LIKE '%,B' OR LIKE '%,B,%'  → 맞긴 맞습니다
//   두 번째가 바로 **정규화를 안 해서 치르는 대가**입니다. 조건이 네 개로 늘었고,
//   라인 이름에 쉼표가 하나라도 들어가면 다시 깨집니다.
//   그리고 앞에 % 가 붙은 LIKE 는 색인을 못 씁니다. 10만 줄이면 10만 줄을 다 훑습니다.
//
// ★★ 흔한 오답 ② — 라인1·라인2·라인3 처럼 칸을 늘리기
//   네 번째 라인이 생기면 표 구조를 고쳐야 하고, 찾을 때도 칸 셋을 다 봐야 합니다.
//   이것도 1정규형 위반입니다.
//
// ★ unnest(string_to_array(...)) 는 쉼표로 나눠 여러 줄로 펴 줍니다.
//   손으로 일곱 줄을 적어 넣어도 정답입니다. 결과가 같으면 됩니다.
//
// ★★★ 정답이 여럿입니다 — 배열 칸(TEXT[])과 JSONB 도 현장에서 씁니다. GIN 색인도 됩니다.
//   기준 하나면 됩니다. **그 값으로 다른 표를 잇는가.**
//   라인코드는 라인 표를 가리키는 값인데 배열 안에는 외래키를 걸 수 없습니다.
//   반대로 '태그' 처럼 아무 표도 안 가리키면 배열이 편합니다. (개념05 에서 JSONB 를 봅니다)



const 결과들 = [];

async function 채점(번호, 제목, 검사) {
  let 통과 = false;

  try {
    통과 = (await 검사()) === true;
  } catch {
    통과 = false;
  }

  결과들.push(통과);
  console.log(`${String(번호).padStart(2)}. ${제목} — ${통과 ? "✅ 통과" : "❌ 아직"}`);
}

const 다듬기 = (값) => String(값 ?? "").replace(/\s+/g, "").toUpperCase();
const 같은목록 = (내답, 정답) =>
  Array.isArray(내답) &&
  내답.length === 정답.length &&
  내답.every((값, 자리) => 다듬기(값) === 다듬기(정답[자리]));



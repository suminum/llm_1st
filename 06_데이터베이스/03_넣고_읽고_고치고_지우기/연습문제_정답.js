async function 다음쪽(마지막id, 개수) {
  const 결과 =
    마지막id === null
      ? await db.query("SELECT id FROM 점검기록 ORDER BY id LIMIT $1", [개수])
      : await db.query("SELECT id FROM 점검기록 WHERE id > $1 ORDER BY id LIMIT $2", [마지막id, 개수]);

  const ids = 결과.rows.map((줄) => 줄.id);

  return { ids, 다음: ids.length > 0 ? ids[ids.length - 1] : null };
}


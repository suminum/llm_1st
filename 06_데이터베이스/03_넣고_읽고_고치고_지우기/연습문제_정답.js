async function 설비검색(검색어) {
  const 결과 = await db.query(
    "SELECT 이름 FROM 설비 WHERE 이름 ILIKE $1 ORDER BY id",
    [`%${검색어}%`],
  );

  return 결과.rows.map((줄) => 줄.이름);
}

await 채점(6, "LIKE 로 검색하기", async () => {
  const 찾은것 = await 설비검색("cnc");
  const 없는것 = await 설비검색("zzz");
  return 찾은것.join(",") === "CNC 선반 1호" && 없는것.length === 0;
});
// 출력:  6. LIKE 로 검색하기 — ✅ 통과

// ★ % 는 **값 쪽**에 붙였습니다.
//   `ILIKE '%' || $1 || '%'` 처럼 SQL 안에서 이어도 되지만,
//   자바스크립트에서 `%${검색어}%` 로 만들어 넘기는 편이 읽기 좋습니다.
//   어느 쪽이든 **검색어 자체는 파라미터**라는 점이 중요합니다.
//
// ★★ LIKE 는 대소문자를 가리고 ILIKE 는 안 가립니다.
//   'cnc' 로 'CNC 선반 1호' 를 찾으려면 ILIKE 여야 합니다.
//   한글에는 대소문자가 없어서 한글만 찾을 때는 둘이 같습니다.
//
// ★★ 사용자가 % 나 _ 를 치면 와일드카드가 됩니다.
//   '95%' 로 검색하면 '95' 로 시작하는 것이 전부 걸립니다.
//   막으려면 값에서 \\ % _ 앞에 백슬래시를 붙여 주세요. (개념02 섹션 3)
//
// ★ 앞에 % 가 붙은 LIKE 는 색인을 못 씁니다.
//   10만 건이면 10만 건을 전부 훑습니다. 06단원에서 왜 그런지 봅니다.



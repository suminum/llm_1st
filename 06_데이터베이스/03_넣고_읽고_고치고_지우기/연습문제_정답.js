// 출력:  4. WHERE 와 IN — ✅ 통과

// ★ IN 대신 OR 로 써도 결과는 같습니다.
//     WHERE 상태 = '점검' OR 상태 = '고장'
//   값이 셋 넷으로 늘면 IN 이 훨씬 읽기 좋습니다. 괄호 실수도 안 납니다.
//
// ★★ 목록에 NULL 이 섞이면 조심하세요.
//   `상태 NOT IN ('점검', NULL)` 은 **언제나 0건**입니다. 에러도 안 납니다.
//   'NULL 이 아닌가?' 의 답이 '모른다' 라서 모든 줄이 탈락합니다.
//   NOT IN 을 쓸 때는 목록에 NULL 이 없는지 반드시 확인하세요.
//
// ★ SELECT * 가 아니라 이름만 골랐습니다.
//   안 쓰는 칸을 실어 나르지 않고, 표에 칸이 늘어도 응답이 안 바뀝니다.
//
// ★ 값이 프로그램에서 온다면 파라미터로 넘깁니다.
//     WHERE 상태 = ANY($1)   ← 배열을 그대로 넘길 수 있습니다



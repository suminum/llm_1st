// 출력: 11. UPSERT — ✅ 통과

// ★ EXCLUDED 가 무엇인가
//   **"넣으려다 부딪힌 그 값들"** 이 담긴 가상의 줄입니다.
//
//     일일생산.수량   → 이미 표에 들어 있던 값   (100)
//     EXCLUDED.수량   → 이번에 넣으려던 값       (30)
//
//   그래서 `일일생산.수량 + EXCLUDED.수량` 이 "쌓기" 가 됩니다.
//   `EXCLUDED.수량` 만 쓰면 "덮어쓰기" 가 됩니다. 요구사항에 따라 고르세요.
//
// ★★ 왜 SELECT 로 확인하고 INSERT/UPDATE 를 나누면 안 되나
//     ① SELECT 로 있는지 본다  → 없다
//     ② 그 사이에 남이 넣는다
//     ③ INSERT 한다            → 23505 중복 에러
//   ①과 ③ 사이의 틈은 반드시 생깁니다. 01단원에서 파일로 겪은 그 문제와 같습니다.
//   ON CONFLICT 는 이걸 **한 문장 안에서** 처리해서 틈을 없앱니다.
//
// ★ ON CONFLICT 괄호에는 UNIQUE 나 PRIMARY KEY 가 걸린 칸만 쓸 수 있습니다.
//   여기서는 PRIMARY KEY (설비명, 날짜) 라서 그 두 칸을 적었습니다.
//   아무 칸이나 적으면 42P10 에러가 납니다.
//
// ★ 중복이면 그냥 넘어가고 싶으면 DO NOTHING 을 씁니다.
//   에러가 안 나고 affectedRows 가 0 입니다. 같은 요청이 두 번 와도 안전합니다.



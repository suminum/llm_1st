async function 생산기록(설비명, 날짜, 수량) {
  const 결과 = await db.query(
    `INSERT INTO 일일생산 (설비명, 날짜, 수량)
     VALUES ($1, $2, $3)
     ON CONFLICT (설비명, 날짜)
     DO UPDATE SET 수량 = 일일생산.수량 + EXCLUDED.수량
     RETURNING 수량`,
    [설비명, 날짜, 수량],
  );

  return 결과.rows[0].수량;
}


const 문제5 = `
  SELECT count(*)::int AS 건수
  FROM 설비
  WHERE 담당자 IS NULL
`;

await 채점(5, "NULL 찾기", async () => {
  const 결과 = await db.query(문제5);
  const 기대 = await db.query("SELECT count(*)::int AS 건수 FROM 설비 WHERE 담당자 IS NULL");
  return 결과.rows[0]?.건수 === 기대.rows[0].건수 && 기대.rows[0].건수 > 0;
});
// 출력:  5. NULL 찾기 — ✅ 통과

// ★★★ `담당자 = NULL` 로 쓰면 **에러가 아니라 0건**입니다.
//   NULL 은 "값이 없다" 가 아니라 "모른다" 입니다.
//   모르는 것끼리 같은지 물으면 답도 "모른다" 이고, 참이 아니니 그 줄은 안 나옵니다.
//   에러가 났으면 금방 고쳤을 텐데, 조용히 0건이라 한참 뒤에 발견됩니다.
//
// ★ 빈 글자('')와 NULL 도 다릅니다.
//   담당자 = '' 는 "빈 글자가 들어 있다", 담당자 IS NULL 은 "아무것도 없다" 입니다.
//   표를 설계할 때 둘 중 하나로 정하고 섞어 쓰지 마세요.
//
// ★ ::int 를 붙인 이유
//   count(*) 는 BIGINT 라서 자바스크립트에 **bigint** 로 옵니다.
//   그대로 두면 JSON.stringify 가 터지고, === 2 비교도 false 가 됩니다.
//   ::int 로 바꾸면 number 로 옵니다. (02단원에서 다뤘습니다)



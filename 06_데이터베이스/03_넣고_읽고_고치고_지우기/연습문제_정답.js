const 문제8 = `
  SELECT 이름, 2026 - 도입연도 AS 사용연수
  FROM 설비
  WHERE 도입연도 IS NOT NULL
  ORDER BY 사용연수 DESC, id
  LIMIT 2
`;

await 채점(8, "별칭과 계산 칸", async () => {
  const 결과 = await db.query(문제8);
  const 줄들 = 결과.rows.map((줄) => `${줄.이름}:${줄.사용연수}`).join(",");
  return 줄들 === "CNC 선반 1호:9,프레스 1호:8";
});
// 출력:  8. 별칭과 계산 칸 — ✅ 통과

// ★★ 별칭은 ORDER BY 에서는 쓰이고 WHERE 에서는 안 쓰입니다.
//   실행 순서가 이렇기 때문입니다.
//
//     FROM → WHERE → GROUP BY → SELECT → ORDER BY → LIMIT
//
//   WHERE 를 볼 때는 사용연수라는 이름이 아직 안 만들어져 있습니다.
//   WHERE 에서 걸러야 하면 계산식을 그대로 쓰세요.
//     WHERE 2026 - 도입연도 > 5
//
// ★ 도입연도가 NULL 인 줄을 왜 뺐나
//   2026 - NULL 은 NULL 입니다. 그리고 DESC 정렬에서 NULL 은 **맨 앞**입니다.
//   그러면 도입연도를 모르는 설비가 "가장 오래된 설비" 로 화면 맨 위에 뜹니다.
//   WHERE 로 빼거나 ORDER BY … DESC NULLS LAST 를 쓰세요.
//
// ★ 별칭에 띄어쓰기나 특수문자를 쓰려면 큰따옴표가 필요합니다.
//   AS "사용 연수" 처럼요. 작은따옴표는 값이라서 안 됩니다.



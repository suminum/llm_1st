async function 설비추가(이름, 도입연도) {
  const 결과 = await db.query(
    `INSERT INTO 설비 (이름, 라인, 도입연도)
     VALUES ($1, 'C', $2)
     RETURNING id, 이름`,
    [이름, 도입연도],
  );

  return 결과.rows[0];
}

await 채점(3, "RETURNING 으로 id 받기", async () => {
  const 돌아온것 = await 설비추가("레이저 커터 1호", 2020);
  const 확인 = await db.query("SELECT id FROM 설비 WHERE 이름 = '레이저 커터 1호'");
  return typeof 돌아온것?.id === "number" && 돌아온것.id === 확인.rows[0]?.id;
});
// 출력:  3. RETURNING 으로 id 받기 — ✅ 통과

// ★ RETURNING 이 없으면 어떻게 해야 하나
//   INSERT 한 뒤 `SELECT max(id) FROM 설비` 로 찾고 싶어집니다. 이게 위험합니다.
//   내가 넣은 직후에 남이 하나 더 넣으면, max(id) 는 **남의 줄**을 가리킵니다.
//   그 id 로 점검기록을 만들면 엉뚱한 설비에 붙습니다.
//
//   RETURNING 은 "이 INSERT 가 만든 줄" 을 돌려줍니다. 남의 줄이 섞일 수가 없습니다.
//   그리고 왕복이 한 번입니다.
//
// ★★ MySQL 8.4 에는 RETURNING 이 없습니다. LAST_INSERT_ID() 를 따로 부릅니다.
//   여러 줄을 넣으면 **첫 줄의 id** 만 줍니다. 09단원에서 비교합니다.
//
// ★ 파라미터를 쓴 이유
//   설비 이름은 사람이 입력합니다. 이어 붙이면 그대로 인젝션 통로가 됩니다.
//   값이 하나뿐이어도 예외 없이 파라미터로 보냅니다.



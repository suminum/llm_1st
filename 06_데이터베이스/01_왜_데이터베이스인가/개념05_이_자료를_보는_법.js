// 출력: 겹쳤나: false

// ★★ `Promise.all` 로 **동시에** 던졌는데 **줄을 서서** 처리됐습니다.
//   '가' 가 완전히 끝난 다음에 '나' 가 시작했습니다.
//
//   연결이 하나뿐이라 그렇습니다. 겹칠 수가 없습니다.

const 순서 = [];

await Promise.all([
  db.transaction(async (거래) => {
    순서.push("가 시작");
    await 거래.query("SELECT pg_sleep(0.05)");
    순서.push("가 끝");
  }),
  db.transaction(async (거래) => {
    순서.push("나 시작");
    await 거래.query("SELECT pg_sleep(0.05)");
    순서.push("나 끝");
  }),
]);

console.log("두 거래의 실행 순서:", 순서.join(" → "));
// 출력: 두 거래의 실행 순서: 가 시작 → 가 끝 → 나 시작 → 나 끝


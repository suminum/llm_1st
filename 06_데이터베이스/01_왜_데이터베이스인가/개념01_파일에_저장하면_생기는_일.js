// 설비 40000번의 상태를 '정지' 로 바꾸겠습니다. **딱 한 글자** 바뀝니다.

function 재기(횟수, 할일) {
  const 잰것 = [];

  for (let 회차 = 0; 회차 < 횟수; 회차 += 1) {
    const 시작 = performance.now();
    할일(회차);
    잰것.push(performance.now() - 시작);
  }

  // 중앙값을 씁니다. 평균은 어쩌다 한 번 느린 것에 크게 흔들립니다.
  return 잰것.sort((가, 나) => 가 - 나)[Math.floor(횟수 / 2)];
}


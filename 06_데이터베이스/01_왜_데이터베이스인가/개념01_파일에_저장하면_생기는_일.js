async function 느긋하게추가(값) {
  const 목록 = 설비읽기();

  // ★ 읽고 쓰는 사이의 '틈' 입니다.
  //   진짜 서버에서는 이 틈이 저절로 생깁니다.
  //   네트워크를 기다리거나, 다른 요청이 끼어들거나, 디스크를 기다립니다.
  //   여기서는 그 틈을 1밀리초로 흉내 냅니다.
  await new Promise((resolve) => setTimeout(resolve, 1));

  목록.push(값);
  설비쓰기(목록);
}


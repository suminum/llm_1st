function 설비읽기() {
  return JSON.parse(fs.readFileSync(설비파일, "utf8"));
}

function 설비쓰기(목록) {
  fs.writeFileSync(설비파일, JSON.stringify(목록));
}

function 설비추가(이름, 라인) {
  const 목록 = 설비읽기();
  const 새번호 = 목록.length === 0 ? 1 : Math.max(...목록.map((설비) => 설비.id)) + 1;

  목록.push({ id: 새번호, 이름, 라인, 상태: "정지" });
  설비쓰기(목록);

  return 새번호;
}


// ── 문제 11 — query 인가 exec 인가 ──

답.문제11 = "exec";

// ★ `db.query()` 에 두 문장을 넣으면 이렇게 납니다.
//     [42601] cannot insert multiple commands into a prepared statement
//
// ★★ 왜일까요? query 는 문장을 **준비된 문장(prepared statement)** 으로 만듭니다.
//   값이 들어갈 자리($1, $2)를 미리 뚫어 놓고 값은 따로 보내는 방식입니다.
//   그래야 값이 SQL 문법으로 해석되지 않아 인젝션이 막힙니다.
//   그런데 준비된 문장은 **한 번에 하나**만 만들 수 있습니다.
//
// ★★★ 그래서 규칙이 이렇게 갈립니다.
//     `db.exec()`   여러 문장 O · **$1 못 씀** · 표 만들기·실습 데이터 넣기용
//     `db.query()`  한 문장만  · $1 씀        · **사용자 값이 들어가는 모든 곳**
//
//   ★ 값이 들어가면 무조건 query + $1 입니다. 예외는 없습니다.
//     exec 로 사용자 값을 보내면 인젝션이 뚫립니다. 08단원에서 진짜로 뚫어 봅니다.
//
// ── MySQL 은 여기가 다릅니다 ──
//   · 자리 표시가 `$1` 이 아니라 `?` 입니다  ★ 자세한 비교는 09단원


// ── 문제 12 [도전] — 묶고, 거르고, 타입까지 맞추기 ──

답.문제12 = `
  SELECT   라인,
           count(*)::int               AS 건수,
           round(avg(소요분), 1)::float AS 평균분
  FROM     점검기록
  GROUP BY 라인
  HAVING   count(*) >= 2
  ORDER BY 라인
`;

// ★ 답: A — 3건 43.3 / B — 2건 42.5 / C — 2건 47.5
//
// ★★★ **이 문제의 함정은 `::float` 입니다.**
//   `round(avg(소요분), 1)` 의 타입은 **NUMERIC** 이고,
//   NUMERIC 은 자바스크립트로 올 때 **문자열**이 됩니다. `"43.3"` 처럼요.
//
//     "43.3" === 43.3  → false
//     "43.3" + 1       → "43.31"   ← 숫자가 아니라 이어 붙습니다
//
//   왜 문자열일까요? NUMERIC 은 **정확한 십진 소수**입니다.
//   자바스크립트의 number 는 이진 부동소수점이라 정확히 담을 수 없습니다.
//   (0.1 + 0.2 가 0.30000000000000004 가 되는 그 문제입니다)
//   그래서 드라이버가 "정확도를 깨뜨리느니 문자열로 주겠다" 고 하는 것입니다.
//
//   ★★ **돈 계산에서는 절대 `::float` 를 붙이지 마세요.**
//     여기서는 채점 편의로 숫자를 요구했지만,
//     금액·수량은 문자열로 받아 정확한 십진 계산으로 다뤄야 합니다. 02단원에서 합니다.
//
// ★ `HAVING count(*) >= 2` 에서 `count(*)` 를 또 썼습니다. 별칭은 못 쓰니까요.
//   이 데이터에서는 HAVING 이 아무것도 안 버리지만, 그래도 붙여야 합니다.
//   "지금 결과가 같으니 빼도 된다" 는 위험한 생각입니다.



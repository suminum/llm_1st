// 출력: PostgreSQL (관계형) — 새 프로젝트의 기본값. 기능이 가장 많고 표준을 잘 지킴
// 출력: MySQL (관계형) — 국내 SI·제조·공공에 가장 많음. MariaDB 도 사실상 같은 부류
// 출력: SQLite (관계형) — 파일 하나가 데이터베이스 전부. 모바일 앱·데스크톱 앱·시험용
// 출력: MongoDB (문서형) — 생김새가 자주 바뀌는 데이터. 스키마를 미리 못 정할 때
// 출력: Redis (키-값) — 세션·캐시·순위표. 메모리에 두어 아주 빠름. 꺼지면 사라질 수 있음

// ★ 현장 기준으로 한 줄씩 더 붙이면 이렇습니다.
//
//   PostgreSQL  "뭘 쓸지 모르겠으면 이걸 쓰세요" 가 요즘 답입니다.
//               JSONB·전문검색·지리정보까지 하나로 됩니다.
//   MySQL       이미 돌고 있는 시스템이 압도적으로 많습니다.
//               운영해 본 사람도 많고, 자료도 많고, 관리 도구도 많습니다.
//   SQLite      서버가 없습니다. 프로그램 안에 들어갑니다.
//               휴대폰 앱 데이터는 거의 다 이겁니다. 동시 쓰기는 약합니다.
//   MongoDB     "스키마가 없어서 편하다" 로 시작했다가
//               나중에 "누가 이 칸 이름을 오타 냈지" 로 고생하는 경우가 많습니다.
//   Redis       진짜 데이터를 여기에만 두면 안 됩니다. 캐시로 쓰세요.


// ── 섹션 4: ★ 이 자료가 PostgreSQL 을 고른 이유 ──

// 세 가지입니다. 하나씩 정직하게 적습니다.
//
//   ① 표준 SQL 을 가장 잘 지킵니다
//      여기서 배운 문장이 다른 데이터베이스에서도 거의 그대로 통합니다.
//      반대로 MySQL 에서만 되는 문법을 먼저 배우면 나중에 고생합니다.
//
//   ② **틀리면 바로 에러를 냅니다**
//      이게 배우는 사람에게 가장 큽니다. 아래에서 직접 봅니다.
//
//   ③ 새로 시작하는 프로젝트가 많이 고릅니다
//      최근 개발자 설문에서 PostgreSQL 이 가장 많이 쓰이는 데이터베이스로 나옵니다.
//      새 프로젝트에서는 격차가 더 큽니다.

// ★★ ② 를 재 봅니다. 일부러 이상한 것을 넣어 봅니다.

await db.exec(`
  CREATE TABLE 점검 (
    id     SERIAL PRIMARY KEY,
    점검자 VARCHAR(5),
    점검일 DATE,
    소요분 INT
  )
`);

const 이상한것들 = [
  ["칸 길이를 넘김", "INSERT INTO 점검 (점검자) VALUES ('김반장님과이반장님')"],
  ["없는 날짜", "INSERT INTO 점검 (점검일) VALUES ('2024-02-31')"],
  ["숫자 칸에 글자", "INSERT INTO 점검 (소요분) VALUES ('삼십분')"],
  ["0 으로 나눔", "SELECT 100 / 0"],
  ["묶지 않은 칸", "SELECT 점검자, 소요분 FROM 점검 GROUP BY 점검자"],
];

for (const [무엇, 문장] of 이상한것들) {
  try {
    await db.query(문장);
    console.log(`${무엇} → 통과했습니다 (?!)`);
  } catch (에러) {
    console.log(`${무엇} → 거절 [${에러.code}]`);
  }
}
// 출력: 칸 길이를 넘김 → 거절 [22001]
// 출력: 없는 날짜 → 거절 [22008]
// 출력: 숫자 칸에 글자 → 거절 [22P02]
// 출력: 0 으로 나눔 → 거절 [22012]
// 출력: 묶지 않은 칸 → 거절 [42803]

// ★★★ **다섯 개 전부 거절했습니다.**
//
//   MySQL 은 설정에 따라 이 중 몇 가지를 **조용히 넘어갑니다.**
//   (요즘 버전은 기본값이 엄격해졌지만, 현장의 오래된 서버는 그렇지 않습니다)
//
//     칸 길이를 넘김  → 잘라서 넣습니다. 경고만 뜹니다
//     없는 날짜      → '0000-00-00' 으로 넣습니다
//     0 으로 나눔    → NULL 을 돌려줍니다. 에러가 아닙니다
//     묶지 않은 칸   → 아무 줄이나 하나 골라서 보여 줍니다
//
//   ★ 배우는 사람에게 이게 왜 나쁠까요?
//     **틀린 줄 모르고 넘어갑니다.**
//     "김반장님과이반장님" 을 넣었는데 "김반장님과" 만 들어가 있고,
//     그걸 몇 달 뒤에 발견합니다. 개념01 의 조용한 버그와 똑같습니다.
//
//   ★ 09단원에서 MySQL 을 진짜로 띄워 놓고 위 다섯 개를 그대로 해 봅니다.
//     어느 것이 통과하는지 직접 보시게 됩니다.
//
// ── MySQL 은 여기가 다릅니다 ──
//   · 위 다섯 가지의 처리가 sql_mode 설정에 따라 달라집니다
//   · SERIAL 대신 AUTO_INCREMENT 를 씁니다
//   ★ 자세한 비교는 09단원에서 둘 다 띄워 놓고 합니다


// ── 섹션 5: ★ 그런데 국내 현장은 MySQL 이 훨씬 많습니다 ──

// 이건 반드시 짚고 넘어가야 합니다.
//
//   · **SI·SM 프로젝트** — 발주처 표준이 MySQL 이나 MariaDB 인 곳이 많습니다
//   · **제조·공장 시스템(MES/ERP)** — 오래 돌던 것이 그대로 있습니다
//   · **공공기관** — 국산 DBMS 나 MariaDB 를 쓰는 곳이 많습니다
//   · **대기업 기간계** — Oracle 이 아직 많습니다
//
// 그러니까 "PostgreSQL 이 요즘 대세" 라는 말과
// "내가 취업해서 만질 것도 PostgreSQL" 은 **다른 이야기**입니다.
//
// ★ 그래서 이 자료는 09단원 하나를 통째로 MySQL 비교에 씁니다.
//   Docker 로 PostgreSQL 과 MySQL 을 **동시에 띄워 놓고**
//   같은 SQL 을 양쪽에 넣어 보면서 무엇이 다른지 봅니다.
//
// ★★ 그리고 각 단원 중간중간에 이런 표시가 나옵니다.
//     "── MySQL 은 여기가 다릅니다 ──"
//   지금 당장 외우지 마세요. 09단원에서 다시 모아서 봅니다.


// ── 섹션 6: ★ PostgreSQL 은 문서형 흉내도 냅니다 ──

// "그럼 JSON 을 넣고 싶으면 MongoDB 를 따로 써야 하나요?"
// 아닙니다. 섹션 1 의 ② 가 이미 PostgreSQL 이었습니다. JSONB 라고 합니다.

// JSON 안의 값으로 찾을 수 있습니다.

const 제조사찾기 = await db.query(
  "SELECT 이름, 사양->>'제조사' AS 제조사 FROM 설비_문서 ORDER BY id",
);

console.log(JSON.stringify(제조사찾기.rows));
// 출력: [{"이름":"컨베이어 1호","제조사":"한성기계"},{"이름":"프레스 1호","제조사":"대동프레스"}]

// ★ `->>` 는 "이 키의 값을 **글자로** 꺼내라" 입니다.
//   `->` 는 "JSON 인 채로 꺼내라" 입니다. 화살표 개수가 다릅니다.

// 조건으로도 찾습니다.

const 한성 = await db.query(`SELECT 이름 FROM 설비_문서 WHERE 사양 @> '{"제조사":"한성기계"}'`);

console.log("한성기계 설비:", JSON.stringify(한성.rows));
// 출력: 한성기계 설비: [{"이름":"컨베이어 1호"}]

// `@>` 는 "이걸 품고 있느냐" 입니다.

// 없는 키를 꺼내면 어떻게 될까요?


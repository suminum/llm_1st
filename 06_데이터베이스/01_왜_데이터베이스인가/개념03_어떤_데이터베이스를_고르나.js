// 개념02 에서 "데이터베이스를 쓰면 이렇게 달라진다" 를 재 봤습니다.
// 그럼 어떤 데이터베이스를 쓸까요?
//
// 여기서 흔히 하는 실수가 있습니다.
// **제품 이름부터 고르는 것**입니다. "요즘 뭐 쓰나요?" 하고요.
//
// 순서가 거꾸로입니다. 먼저 **모양**을 고르고, 그 다음에 제품을 고릅니다.
// 모양은 크게 셋입니다.
//
//   ① 관계형 — 표. 칸을 미리 정해 둡니다
//   ② 문서형 — JSON. 문서마다 생김새가 달라도 됩니다
//   ③ 키-값  — 열쇠 하나로 값 하나. 그것뿐입니다
//
// 이 파일에서 셋을 **같은 데이터로** 만들어 보고, 무엇이 다른지 봅니다.
// 그리고 이 자료가 PostgreSQL 을 고른 이유를 정직하게 적습니다.

import { PGlite } from "@electric-sql/pglite";

const db = await PGlite.create();


// ── 섹션 1: 같은 데이터를 세 가지 모양으로 ──

// 설비 두 대를 넣습니다. 컨베이어와 프레스입니다.
// 그런데 두 대는 **사양이 다릅니다.** 컨베이어는 속도가, 프레스는 압력이 중요합니다.
// 이 "다름" 을 세 모양이 어떻게 다루는지 보시면 됩니다.


// ① 관계형 — 칸을 미리 정합니다

await db.exec(`
  CREATE TABLE 설비_표 (
    id     INT  PRIMARY KEY,
    이름   TEXT NOT NULL,
    라인   TEXT NOT NULL,
    최대속도 INT,
    압력톤  INT
  )
`);

await db.exec(`
  INSERT INTO 설비_표 VALUES
    (1, '컨베이어 1호', 'A', 120, NULL),
    (2, '프레스 1호',  'B', NULL, 250)
`);

const 표결과 = await db.query("SELECT * FROM 설비_표 ORDER BY id");

console.log("① 관계형:", JSON.stringify(표결과.rows));
// 출력: ① 관계형: [{"id":1,"이름":"컨베이어 1호","라인":"A","최대속도":120,"압력톤":null},{"id":2,"이름":"프레스 1호","라인":"B","최대속도":null,"압력톤":250}]

// ★ 보이시나요? **빈 칸(null)이 생깁니다.**
//   컨베이어에는 압력톤이 없고, 프레스에는 최대속도가 없습니다.
//   설비 종류가 20가지면 칸이 60개가 되고 대부분이 null 이 됩니다.
//   이걸 제대로 푸는 법은 04단원(모델링)에서 합니다.
//
//   ★ 대신 얻는 것: **칸이 정해져 있습니다.**
//     오타 난 칸 이름은 넣는 순간 거절당합니다. 나중에 보겠습니다.


// ② 문서형 — 생김새가 달라도 됩니다

await db.exec(`
  CREATE TABLE 설비_문서 (
    id   INT  PRIMARY KEY,
    이름 TEXT NOT NULL,
    사양 JSONB
  )
`);

await db.query("INSERT INTO 설비_문서 VALUES ($1, $2, $3)", [
  1,
  "컨베이어 1호",
  JSON.stringify({ 제조사: "한성기계", 최대속도: 120, 옵션: ["가변속", "역회전"] }),
]);

await db.query("INSERT INTO 설비_문서 VALUES ($1, $2, $3)", [
  2,
  "프레스 1호",
  JSON.stringify({ 제조사: "대동프레스", 압력톤: 250 }),
]);

const 문서결과 = await db.query("SELECT * FROM 설비_문서 ORDER BY id");

console.log("② 문서형:", JSON.stringify(문서결과.rows));
// 출력: ② 문서형: [{"id":1,"이름":"컨베이어 1호","사양":{"옵션":["가변속","역회전"],"제조사":"한성기계","최대속도":120}},{"id":2,"이름":"프레스 1호","사양":{"압력톤":250,"제조사":"대동프레스"}}]

// ★ null 이 없습니다. 있는 것만 넣었습니다.
//   그리고 컨베이어에는 `옵션` 이라는 배열까지 들어 있습니다.
//   프레스에는 그런 게 없습니다. 그래도 괜찮습니다.
//
// ★★ 그런데 **넣은 순서대로 안 나옵니다.**
//   `{제조사, 최대속도, 옵션}` 순으로 넣었는데 `{옵션, 제조사, 최대속도}` 로 나왔습니다.
//   JSONB 는 읽기 빠른 형태로 바꿔서 저장하기 때문에 키 순서가 안 지켜집니다.
//   **순서에 의존하는 코드를 쓰면 안 됩니다.** 이건 나중에 진짜로 사고가 납니다.


// ③ 키-값 — 열쇠 하나에 값 하나

await db.exec(`
  CREATE TABLE 설정 (
    열쇠 TEXT PRIMARY KEY,
    값   TEXT NOT NULL
  )
`);

await db.exec(`
  INSERT INTO 설정 VALUES
    ('라인A_목표수량', '1200'),
    ('라인A_담당',    '김반장'),
    ('점검주기_일',    '30')
`);

const 하나 = await db.query("SELECT 값 FROM 설정 WHERE 열쇠 = $1", ["라인A_담당"]);

console.log("③ 키-값:", 하나.rows[0].값);
// 출력: ③ 키-값: 김반장

// ★ 열쇠로 찾는 것 **하나만** 잘합니다. 대신 아주 빠릅니다.
//   "담당이 김반장인 라인을 전부 찾아라" 는 못 합니다. 값으로는 못 찾습니다.
//   Redis 가 이 모양입니다. 메모리에만 두어서 더 빠릅니다.



// 순위를 매기는 함수는 셋입니다. 같은 데이터로 나란히 보세요.

await 돌려보기("ROW_NUMBER 로 매기면", `
  SELECT 점검번호, 점수, ROW_NUMBER() OVER (ORDER BY 점수 DESC NULLS LAST, 점검번호) AS 순위
  FROM 점검기록 WHERE 설비번호 IN (1, 2)
  ORDER BY 순위
`);
// 출력:   ROW_NUMBER 로 매기면: 7줄 · 1,92,1 | 4,90,2 | 2,88,3 | 7,88,4 | 3,71,5 | 5,65,6 | 6,48,7

await 돌려보기("DENSE_RANK 로 매기면", `
  SELECT 점검번호, 점수, DENSE_RANK() OVER (ORDER BY 점수 DESC NULLS LAST) AS 순위
  FROM 점검기록 WHERE 설비번호 IN (1, 2)
  ORDER BY 순위, 점검번호
`);
// 출력:   DENSE_RANK 로 매기면: 7줄 · 1,92,1 | 4,90,2 | 2,88,3 | 7,88,3 | 3,71,4 | 5,65,5 | 6,48,6

// 88점짜리 두 건(2번·7번)을 보세요.
//
//   ROW_NUMBER   3, 4   동점을 **무시하고** 그냥 번호를 붙입니다
//   RANK         3, 3   동점은 같은 순위. 다음은 4위를 **건너뛰고** 5위
//   DENSE_RANK   3, 3   동점은 같은 순위. 다음은 **건너뛰지 않고** 4위
//
// ★ 어느 것이 맞느냐가 아니라 **무엇을 세느냐**의 문제입니다.
//   "몇 등이냐" 를 사람이 이해하는 방식은 보통 RANK 입니다 (공동 3위 다음은 5위).
//   "서로 다른 등급이 몇 개냐" 를 보려면 DENSE_RANK 입니다.
//   "그냥 줄 번호" 가 필요하면 ROW_NUMBER 입니다.
//
// ★★ `ROW_NUMBER` 를 쓸 때는 **동점을 가를 칸을 반드시** ORDER BY 에 넣으세요.
//   위 예제에도 `, 점검번호` 가 들어 있습니다.
//   안 넣으면 2번과 7번 중 누가 3위인지 정해지지 않아 **실행할 때마다 답이 달라질 수 있습니다.**
//
// ★ `NULLS LAST` 를 붙인 이유:
//   Postgres 는 `ORDER BY ... DESC` 일 때 NULL 을 **맨 앞**에 둡니다.
//   점수가 없는 점검이 1위가 되어 버립니다. 여기서는 설비 1·2만 봐서 NULL 이 없지만,
//   습관을 들여 두는 편이 안전합니다.


// ============================================================
// 정답 13 — [도전] 설비마다 점수 상위 2건
// ============================================================

await 정답확인(
  "[도전] 설비마다 점수 상위 2건",
  "1,1,92 | 1,4,90 | 2,7,88 | 2,5,65 | 3,8,95 | 3,11,90 | 4,14,88 | 4,15,69",
  `
    SELECT 설비번호, 점검번호, 점수
    FROM (
      SELECT 설비번호, 점검번호, 점수,
             ROW_NUMBER() OVER (
               PARTITION BY 설비번호
               ORDER BY 점수 DESC NULLS LAST, 점검번호
             ) AS 순위
      FROM 점검기록
    ) AS 매긴것
    WHERE 순위 <= 2
    ORDER BY 설비번호, 순위
  `,
);
// 출력: 13. [도전] 설비마다 점수 상위 2건 — 정답

// ── 왜 그런가 ──
//
// 이건 실무에서 가장 자주 필요한 모양입니다.
// "고객마다 최근 주문 3건", "라인마다 불량 상위 5개" 전부 같은 꼴입니다.
//
// 세 걸음입니다.
//
//   ① `PARTITION BY 설비번호` 로 **설비마다 따로** 창을 엽니다
//   ② 그 안에서 `ORDER BY 점수 DESC` 로 줄을 세우고 `ROW_NUMBER()` 로 번호를 붙입니다
//   ③ 그 결과를 **한 겹 감싸서** `WHERE 순위 <= 2` 로 거릅니다
//
// ★★ ③에서 감싸는 것이 핵심입니다. 안 감싸면 안 됩니다:
//
//     SELECT ... FROM 점검기록
//     WHERE ROW_NUMBER() OVER (...) <= 2      ← 에러
//     → window functions are not allowed in WHERE (42P20)
//
//   실행 순서 때문입니다.
//
//     FROM → WHERE → GROUP BY → HAVING → **윈도우 함수** → SELECT → ORDER BY → LIMIT
//
//   WHERE 가 돌 때는 순위가 아직 계산되기 전입니다. 없는 값으로는 거를 수 없습니다.
//   그래서 순위까지 다 계산된 결과를 **새 표처럼 만들어 두고** 그 위에서 거릅니다.
//
// ★ `LIMIT 2` 로는 절대 안 됩니다. 전체에서 2건이 나옵니다:

await 돌려보기("LIMIT 2 로 하면", `
  SELECT 설비번호, 점검번호, 점수
  FROM 점검기록
  ORDER BY 점수 DESC NULLS LAST, 점검번호
  LIMIT 2
`);
// 출력:   LIMIT 2 로 하면: 2줄 · 3,8,95 | 1,1,92

// ★ CTE 로 쓰면 더 읽기 좋습니다. 결과는 같습니다:

await 돌려보기("CTE 로 쓰면", `
  WITH 매긴것 AS (
    SELECT 설비번호, 점검번호, 점수,
           ROW_NUMBER() OVER (PARTITION BY 설비번호 ORDER BY 점수 DESC NULLS LAST, 점검번호) AS 순위
    FROM 점검기록
  )
  SELECT 설비번호, 점검번호, 점수 FROM 매긴것 WHERE 순위 <= 2 ORDER BY 설비번호, 순위
`);
// 출력:   CTE 로 쓰면: 8줄 · 1,1,92 | 1,4,90 | 2,7,88 | 2,5,65 | 3,8,95 | 3,11,90 | 4,14,88 | 4,15,69

// ★ 설비 4번을 보세요. 점검 13번은 점수가 NULL 이라 `NULLS LAST` 로 맨 뒤에 갔습니다.
//   그래서 14번(88점)과 15번(69점)이 뽑혔습니다. NULLS LAST 를 빼면 13번이 1위가 됩니다.
//
// ★ `ROW_NUMBER` 대신 `RANK` 를 쓰면 동점일 때 **2건보다 많이** 나올 수 있습니다.
//   "정확히 2건" 이 필요하면 ROW_NUMBER, "공동 2위까지 전부" 가 필요하면 RANK 입니다.


// ============================================================
// 정답 14 — [도전] 점검 간격 구하기
// ============================================================

await 정답확인(
  "[도전] 점검 간격 구하기",
  "8,3,NULL | 9,3,31 | 10,3,30 | 11,3,32 | 12,3,31",
  `
    SELECT 점검번호,
           설비번호,
           점검일 - LAG(점검일) OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 간격
    FROM 점검기록
    WHERE 설비번호 = 3
    ORDER BY 점검일
  `,
);
// 출력: 14. [도전] 점검 간격 구하기 — 정답

// ── 왜 그런가 ──
//
// `LAG(칸)` 은 **같은 창 안에서 한 줄 앞의 값**을 가져옵니다.
// `ORDER BY 점검일` 이 "앞" 이 무엇인지 정해 줍니다.
//
//   점검일        LAG(점검일)    빼면
//   2024-01-20    NULL           NULL   ← 앞이 없습니다
//   2024-02-20    2024-01-20     31
//   2024-03-21    2024-02-20     30
//   2024-04-22    2024-03-21     32
//   2024-05-23    2024-04-22     31
//
// ★ `DATE - DATE` 는 **정수(일수)** 를 돌려줍니다. INTERVAL 이 아닙니다.
//   자바스크립트로도 `number` 로 옵니다.
//
// ★ 첫 줄이 NULL 인 게 싫으면 `LAG(점검일, 1, 기준일)` 처럼 기본값을 줄 수 있습니다.
//   하지만 여기서는 NULL 이 정직합니다. "앞 점검이 없다" 는 사실 그대로니까요.
//
// ★ `PARTITION BY 설비번호` 를 빼면 어떻게 될까요?
//   설비가 섞여서, 3번 설비의 첫 점검이 2번 설비의 마지막 점검과 비교됩니다.
//   지금은 `WHERE 설비번호 = 3` 이라 티가 안 나지만, 전체를 볼 때는 반드시 필요합니다.
//
// ★ 개념02 에서 이걸 SELF JOIN 으로 하려면 "바로 앞 줄" 을 찾는 조건이 꽤 복잡했습니다.
//   윈도우 함수로는 한 줄입니다. 이게 윈도우 함수를 쓰는 이유입니다.



// 정답 15 — [도전] 계층 훑기
// ============================================================

await 정답확인(
  "[도전] 계층 훑기",
  "3,가공2라인 > 용접공정 > 용접로봇 1호 | 3,가공2라인 > 용접공정 > 용접로봇 2호 | 3,가공2라인 > 절삭공정 > 선반 1호 | 3,조립1라인 > 검사공정 > 검사기 1호 | 3,조립1라인 > 조립공정 > 프레스 1호 | 3,조립1라인 > 투입공정 > 컨베이어 1호",
  `
    WITH RECURSIVE 훑기 AS (
      SELECT 번호, 이름, 1 AS 깊이, 이름::TEXT AS 경로
      FROM 조직
      WHERE 상위번호 IS NULL

      UNION ALL

      SELECT 아래.번호, 아래.이름, 위.깊이 + 1, 위.경로 || ' > ' || 아래.이름
      FROM 조직 아래
      JOIN 훑기 위 ON 아래.상위번호 = 위.번호
      WHERE 위.깊이 < 5
    )
    SELECT 깊이, 경로
    FROM 훑기
    WHERE 깊이 = 3
    ORDER BY 경로
  `,
);
// 출력: 15. [도전] 계층 훑기 — 정답

// ── 왜 그런가 ──
//
// `WITH RECURSIVE` 는 두 부분으로 되어 있습니다. 가운데의 `UNION ALL` 이 경계입니다.
//
//   ① **기준줄** — 맨 위(상위번호가 NULL 인 것)를 고릅니다. 여기가 시작점입니다.
//   ② **재귀줄** — 방금 찾은 것들(`훑기`)의 자식을 찾습니다.
//
// 어떻게 도는지 보세요.
//
//   1회차: 기준줄이 조립1라인, 가공2라인 을 만듭니다        (깊이 1, 2줄)
//   2회차: 그 둘의 자식인 공정 5개를 찾습니다               (깊이 2, 5줄)
//   3회차: 공정들의 자식인 설비 6개를 찾습니다               (깊이 3, 6줄)
//   4회차: 설비의 자식은 없습니다 → **아무것도 안 나옵니다 → 멈춥니다**
//
// ★ 멈추는 조건은 "더 나올 게 없을 때" 입니다. 자동입니다.
//   문제는 **순환 참조**입니다. A의 상위가 B, B의 상위가 A 라면 영원히 돕니다.
//   그래서 `WHERE 위.깊이 < 5` 같은 안전장치를 겁니다.
//   Postgres 14 부터는 `CYCLE 번호 SET 순환 USING 지나온길` 로 더 깔끔하게 막을 수 있습니다.
//
// ★ `이름::TEXT` 로 캐스팅한 이유:
//   기준줄과 재귀줄은 **칸의 타입이 정확히 같아야** 합니다.
//   `이름` 은 TEXT 인데, `경로 || ' > ' || 이름` 도 TEXT 라 사실 여기서는 없어도 됩니다.
//   그런데 칸을 `VARCHAR(50)` 으로 만든 표에서는 길이가 안 맞아 에러가 납니다.
//   습관적으로 `::TEXT` 를 붙여 두면 안전합니다.
//
// ★ `UNION ALL` 이지 `UNION` 이 아닙니다.
//   `UNION` 은 중복을 제거하느라 매번 전체를 비교합니다. 느립니다.
//   계층을 훑을 때는 같은 줄이 두 번 나올 일이 없으니 `UNION ALL` 이 맞습니다.
//
// ★ `ORDER BY 경로` 로 정렬했습니다. 재귀 결과의 순서는 **보장되지 않습니다.**
//   깊이 순으로 나올 것 같지만, 그건 우연입니다. 순서가 필요하면 반드시 ORDER BY 를 쓰세요.



await 돌려보기("COUNT(*) 로 세면", `
  SELECT s.이름, COUNT(*) AS 점검건수
  FROM 설비 s
  LEFT JOIN 점검기록 p ON s.설비번호 = p.설비번호
  GROUP BY s.설비번호, s.이름
  ORDER BY s.설비번호
`);

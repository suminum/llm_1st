// [실수 5] "점수 높은 순" 인데 점수 없는 줄이 1위로 올라왔습니다
//   Postgres 는 DESC 정렬에서 NULL 을 앞에 둡니다(NULLS FIRST 가 기본).
//   ★ ORDER BY 점수 DESC NULLS LAST 라고 적으세요. 창 안과 쿼리 끝 둘 다 고쳐야 합니다.
//
// [실수 6] 그룹마다 N개를 LIMIT 으로 뽑으려 했습니다
//   LIMIT 2 는 결과 전체에서 2줄입니다. 설비마다 2줄이 아닙니다.

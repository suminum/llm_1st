// ============================================================
// 섹션 1 — GROUP BY 는 줄을 접고, 윈도우는 줄을 남깁니다
// ============================================================
// 같은 것을 두 방식으로 구해 보겠습니다. "설비마다 평균 점수" 입니다.

// ① GROUP BY — 설비 하나가 한 줄이 됩니다
const 접은것 = await db.query(
  `SELECT 설비번호, ROUND(AVG(점수), 1) AS 평균
   FROM 점검기록 GROUP BY 설비번호 ORDER BY 설비번호`);

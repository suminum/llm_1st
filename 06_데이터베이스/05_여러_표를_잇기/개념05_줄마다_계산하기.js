// ── 자주 하는 실수 ──
//
// [실수 1] WHERE 에 윈도우 함수를 썼습니다
//   WHERE ROW_NUMBER() OVER (...) <= 2 → 42P20 에러입니다. WHERE 는 윈도우보다 먼저 돕니다.
//   ★ 서브쿼리나 CTE 로 한 번 감싼 뒤 바깥에서 거세요. HAVING 도 마찬가지로 안 됩니다.
//
// [실수 2] LAST_VALUE 가 마지막 값인 줄 알았습니다

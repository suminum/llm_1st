// 출력: · 점검8 · 점수 95 · 순위 3
// ★★ 점수가 없는 두 건이 1위가 됐습니다. 진짜 1등인 95점이 3위로 밀렸습니다. "점수 높은 순" 인데
//    점수 없는 줄이 맨 위에 옵니다. NULLS LAST 로 고칩니다. (ASC 는 기본이 NULLS LAST 라 반대)

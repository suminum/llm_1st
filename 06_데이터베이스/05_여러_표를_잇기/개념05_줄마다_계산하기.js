// ============================================================
// 정리
// ============================================================
//                   GROUP BY                   윈도우 함수 OVER(...)
//   ─────────────  ─────────────────────────  ──────────────────────────
//   줄 수           묶은 개수만큼 줄어듦       입력 줄 수 그대로
//   개별 값         사라짐                     그대로 남음
//   묶는 말         GROUP BY 칸                PARTITION BY 칸
//   조건 거는 곳    HAVING                     바깥으로 감싼 뒤 WHERE (SELECT 안에서만 씀)
//
//   순위 세 함수 — 점수가 90, 90, 88 일 때
//   ROW_NUMBER()   1, 2, 3   동점 없음. 순서는 tie-breaker 로 직접 정할 것
//   RANK()         1, 1, 3   동점 뒤가 건너뜀
//   DENSE_RANK()   1, 1, 2   동점 뒤가 안 건너뜀
//
//   프레임 기본값 — OVER 안에 뭐가 있느냐로 정해집니다
//   ORDER BY 없음        창 전체 (전체 합·전체 평균)
//   ORDER BY 있음        RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW → 누적
//   ROWS  n PRECEDING    줄 수로 셈 (이동 평균은 보통 이것)
//   RANGE n PRECEDING    값으로 셈. 동점은 한 덩어리
//
//   실행 순서 — 윈도우는 한참 뒤입니다
//   FROM → WHERE → GROUP BY → HAVING → 윈도우 함수 → SELECT → ORDER BY


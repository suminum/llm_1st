// ★ 점검기록 15줄이 4줄이 됐습니다. 개별 점검은 사라졌습니다. 설비5(포장기 1호)는 점검기록이
//   없어서 아예 안 나옵니다. 개념02 의 LEFT JOIN 이야기입니다.
// ★ ROUND(AVG(...), 1) 은 NUMERIC 이라 JS 로 문자열로 옵니다. "85.3" 이지 85.3 이 아닙니다.

// ② 윈도우 함수 — 줄은 그대로, 옆에 칸만 붙습니다
const 안접은것 = await db.query(
  `SELECT 점검번호, 설비번호, 점수,
          ROUND(AVG(점수) OVER (PARTITION BY 설비번호), 1) AS 설비평균
   FROM 점검기록 ORDER BY 점검번호`);
console.log("[② 윈도우] 줄 수:", 안접은것.rows.length);
// 출력: [② 윈도우] 줄 수: 15
for (const 줄 of 안접은것.rows.slice(0, 5))   // 앞 5줄만 봅니다
  console.log(`· 점검${줄.점검번호} · 설비${줄.설비번호} · 점수 ${값(줄.점수)} · 설비평균 ${줄.설비평균}`);
// 출력: · 점검1 · 설비1 · 점수 92 · 설비평균 85.3
// 출력: · 점검2 · 설비1 · 점수 88 · 설비평균 85.3
// 출력: · 점검3 · 설비1 · 점수 71 · 설비평균 85.3
// 출력: · 점검4 · 설비1 · 점수 90 · 설비평균 85.3
// 출력: · 점검5 · 설비2 · 점수 65 · 설비평균 67.0
// ★★ 같은 AVG(점수) 인데 결과 줄 수가 4 와 15 로 다릅니다. GROUP BY 는 "접어서 하나로",
//    윈도우는 "옆에 붙이기" 입니다. 윈도우 함수는 줄을 절대 없애지 않습니다. 칸이 하나 늘 뿐입니다.

// ③ 그래서 "그 설비 평균보다 높은 점검" 을 한 쿼리로 씁니다
//    ★ WHERE 에는 윈도우 함수를 못 씁니다(섹션 4). 서브쿼리로 한 번 감쌉니다.
const 평균초과 = await db.query(`
  SELECT 점검번호, 설비번호, 점수, ROUND(설비평균, 1) AS 설비평균
  FROM (
    SELECT 점검번호, 설비번호, 점수,
           AVG(점수) OVER (PARTITION BY 설비번호) AS 설비평균
    FROM 점검기록
  ) 붙인표
  WHERE 점수 > 설비평균 ORDER BY 점검번호
`);
console.log("[③ 설비 평균보다 높은 점검] 줄 수:", 평균초과.rows.length);
// 출력: [③ 설비 평균보다 높은 점검] 줄 수: 7
for (const 줄 of 평균초과.rows) console.log(`· 점검${줄.점검번호} · 설비${줄.설비번호} · ${줄.점수} > ${줄.설비평균}`);
// 출력: · 점검1 · 설비1 · 92 > 85.3
// 출력: · 점검2 · 설비1 · 88 > 85.3
// 출력: · 점검4 · 설비1 · 90 > 85.3
// 출력: · 점검7 · 설비2 · 88 > 67.0
// 출력: · 점검8 · 설비3 · 95 > 77.8
// 출력: · 점검11 · 설비3 · 90 > 77.8
// 출력: · 점검14 · 설비4 · 88 > 78.5

// ④ 윈도우 없이 하려면 — 평균을 GROUP BY 로 따로 구해서 원래 표에 다시 이어야 합니다
const 옛날방식 = await db.query(`
  SELECT 점.점검번호 FROM 점검기록 점
  JOIN (SELECT 설비번호, AVG(점수) AS 평균 FROM 점검기록 GROUP BY 설비번호) 평
    ON 평.설비번호 = 점.설비번호
  WHERE 점.점수 > 평.평균 ORDER BY 점.점검번호
`);
console.log("[④ GROUP BY + JOIN] 결과 줄 수가 ③과 같은가:", 옛날방식.rows.length === 평균초과.rows.length);
// 출력: [④ GROUP BY + JOIN] 결과 줄 수가 ③과 같은가: true
// ★ 답은 같습니다. 그런데 ④는 점검기록을 두 번 읽고 JOIN 을 한 번 더 합니다. 윈도우는 한 번만 읽습니다.

// ============================================================
// 섹션 2 — OVER (PARTITION BY ... ORDER BY ...)
// ============================================================
// OVER 괄호 안이 "창(window)" 의 정의입니다. 이 줄에서 어디까지를 볼 것인가입니다.

// ① OVER () — 괄호가 비면 표 전체가 한 창입니다
const 전체창 = await db.query(
  `SELECT 점검번호, 점수, ROUND(AVG(점수) OVER (), 1) AS 전체평균
   FROM 점검기록 ORDER BY 점검번호 LIMIT 3`);
for (const 줄 of 전체창.rows) console.log(`· 점검${줄.점검번호} · 점수 ${줄.점수} · 전체평균 ${줄.전체평균}`);
// 출력: · 점검1 · 점수 92 · 전체평균 77.7
// 출력: · 점검2 · 점수 88 · 전체평균 77.7
// 출력: · 점검3 · 점수 71 · 전체평균 77.7

// ② PARTITION BY — 창을 나눕니다. 묶는 뜻은 GROUP BY 와 같지만 줄은 안 접습니다.
//    섹션 1 ②에서 이미 썼습니다.

// ③ ★★ OVER 안에 ORDER BY 를 넣으면 집계의 뜻이 바뀝니다
//    안 넣으면 "창 전체의 합", 넣으면 "처음부터 지금 줄까지의 합" 이 됩니다.
const 합비교 = await db.query(`
  SELECT 점검일, 점수,
         SUM(점수) OVER (PARTITION BY 설비번호)                 AS 설비합,
         SUM(점수) OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 누적합
  FROM 점검기록 WHERE 설비번호 = 1 ORDER BY 점검일
`);
for (const 줄 of 합비교.rows) console.log(`· ${날짜(줄.점검일)} · 점수 ${줄.점수} · 설비합 ${줄.설비합} · 누적합 ${줄.누적합}`);
// 출력: · 2024-01-05 · 점수 92 · 설비합 341 · 누적합 92
// 출력: · 2024-02-05 · 점수 88 · 설비합 341 · 누적합 180
// 출력: · 2024-03-06 · 점수 71 · 설비합 341 · 누적합 251
// 출력: · 2024-04-05 · 점수 90 · 설비합 341 · 누적합 341
// ★★ 설비합은 네 줄 모두 341 로 같습니다. 누적합은 92 → 180 → 251 → 341 로 자랍니다.
//    ORDER BY 한 마디 차이인데 뜻이 완전히 다릅니다. 이유는 "프레임" 입니다. 섹션 6에서 봅니다.

// ④ 같은 창을 여러 번 쓸 때는 WINDOW 절로 이름을 붙입니다
const 이름붙인창 = await db.query(`
  SELECT 점검번호, 점수,
         ROUND(AVG(점수) OVER 설비창, 1) AS 평균, MAX(점수) OVER 설비창 AS 최고,
         COUNT(점수) OVER 설비창 AS 점수있는건수, COUNT(*) OVER 설비창 AS 전체건수
  FROM 점검기록 WHERE 설비번호 = 3
  WINDOW 설비창 AS (PARTITION BY 설비번호)
  ORDER BY 점검번호 LIMIT 3
`);
for (const 줄 of 이름붙인창.rows)
  console.log(`· 점검${줄.점검번호} · 점수 ${값(줄.점수)} · 평균 ${줄.평균} · 최고 ${줄.최고} · 점수있는건수 ${줄.점수있는건수} · 전체건수 ${줄.전체건수}`);
// 출력: · 점검8 · 점수 95 · 평균 77.8 · 최고 95 · 점수있는건수 4 · 전체건수 5
// 출력: · 점검9 · 점수 (없음) · 평균 77.8 · 최고 95 · 점수있는건수 4 · 전체건수 5
// 출력: · 점검10 · 점수 74 · 평균 77.8 · 최고 95 · 점수있는건수 4 · 전체건수 5
// ★ 설비3 은 5줄인데 점수있는건수(COUNT(점수))는 4 입니다. 점검9 의 점수가 NULL 이라서 그렇습니다.
//   COUNT(*) 는 줄을, COUNT(칸) 은 NULL 아닌 값을 셉니다. 개념03 에서 본 그대로입니다.
// ★ COUNT 의 SQL 타입은 BIGINT 입니다. 그런데 PGlite 는 안전하게 담기는 크기면 number 로,
//   넘어가면 bigint 로 줍니다. 지금은 5 라서 number 지만 줄이 쌓이면 바뀝니다. (개념01 에서 재현합니다)
console.log("COUNT 결과의 자바스크립트 타입:", typeof 이름붙인창.rows[0].전체건수);
// 출력: COUNT 결과의 자바스크립트 타입: number
console.log("숫자로 쓰려면 Number() 로 바꿉니다:", Number(이름붙인창.rows[0].전체건수) + 1);
// 출력: 숫자로 쓰려면 Number() 로 바꿉니다: 6

// ── MySQL 은 여기가 다릅니다 ──
//   · MySQL 은 8.0 부터 윈도우 함수가 있습니다. 5.7 에는 없어서 변수(@)로 흉내 내야 했습니다
//   ★ 자세한 비교는 09단원에서 둘 다 띄워 놓고 합니다

// ============================================================
// 섹션 3 — ROW_NUMBER / RANK / DENSE_RANK
// ============================================================
// 순위를 매기는 함수가 셋 있습니다. 동점일 때 행동이 다릅니다.
// 이 표에는 동점이 일부러 들어 있습니다. 90점이 2건, 88점이 3건입니다.

const 순위셋 = await db.query(`
  SELECT 점검번호, 점수,
         ROW_NUMBER() OVER (ORDER BY 점수 DESC NULLS LAST, 점검번호) AS 행번호,
         RANK()       OVER (ORDER BY 점수 DESC NULLS LAST)           AS 순위,
         DENSE_RANK() OVER (ORDER BY 점수 DESC NULLS LAST)           AS 촘촘순위
  FROM 점검기록 ORDER BY 점수 DESC NULLS LAST, 점검번호
`);
for (const 줄 of 순위셋.rows.slice(0, 9))   // 위 9줄만 봅니다
  console.log(`· 점검${줄.점검번호} · 점수 ${값(줄.점수)} · 행번호 ${줄.행번호} · 순위 ${줄.순위} · 촘촘순위 ${줄.촘촘순위}`);
// 출력: · 점검8 · 점수 95 · 행번호 1 · 순위 1 · 촘촘순위 1
// 출력: · 점검1 · 점수 92 · 행번호 2 · 순위 2 · 촘촘순위 2
// 출력: · 점검4 · 점수 90 · 행번호 3 · 순위 3 · 촘촘순위 3
// 출력: · 점검11 · 점수 90 · 행번호 4 · 순위 3 · 촘촘순위 3
// 출력: · 점검2 · 점수 88 · 행번호 5 · 순위 5 · 촘촘순위 4
// 출력: · 점검7 · 점수 88 · 행번호 6 · 순위 5 · 촘촘순위 4
// 출력: · 점검14 · 점수 88 · 행번호 7 · 순위 5 · 촘촘순위 4
// 출력: · 점검10 · 점수 74 · 행번호 8 · 순위 8 · 촘촘순위 5
// 출력: · 점검3 · 점수 71 · 행번호 9 · 순위 9 · 촘촘순위 6
// ★ 90점 두 줄, 88점 세 줄을 보세요.

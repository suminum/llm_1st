// ============================================================
// 섹션 5 — LAG / LEAD (이전 줄 · 다음 줄 보기)
// ============================================================
// LAG 는 창 안에서 "한 줄 위" 값을, LEAD 는 "한 줄 아래" 값을 지금 줄 옆에 붙여 줍니다.
// ★ 개념02 에서 SELF JOIN 으로 "직전 점검" 을 찾으려면 조건이 꽤 까다로웠습니다. LAG 는 한 마디입니다.

const 간격 = await db.query(`
  SELECT 설비번호, 점검일,
         LAG(점검일) OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 이전점검일,
         점검일 - LAG(점검일) OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 며칠만에
  FROM 점검기록 WHERE 설비번호 IN (1, 4) ORDER BY 설비번호, 점검일
`);
for (const 줄 of 간격.rows)
  console.log(`· 설비${줄.설비번호} · ${날짜(줄.점검일)} · 이전 ${날짜(줄.이전점검일)} · ${값(줄.며칠만에)}일만에`);
// 출력: · 설비1 · 2024-01-05 · 이전 (없음) · (없음)일만에
// 출력: · 설비1 · 2024-02-05 · 이전 2024-01-05 · 31일만에
// 출력: · 설비1 · 2024-03-06 · 이전 2024-02-05 · 30일만에
// 출력: · 설비1 · 2024-04-05 · 이전 2024-03-06 · 30일만에
// 출력: · 설비4 · 2024-01-28 · 이전 (없음) · (없음)일만에
// 출력: · 설비4 · 2024-03-29 · 이전 2024-01-28 · 61일만에
// 출력: · 설비4 · 2024-05-30 · 이전 2024-03-29 · 62일만에
// ★ DATE 끼리 빼면 Postgres 는 "며칠" 이라는 정수를 줍니다. 설비4 는 두 달씩 벌어져 있습니다.
// ★ 각 설비의 첫 줄은 이전 값이 없어 NULL 입니다. PARTITION 이 바뀌면 LAG 도 다시 비었습니다.
//   기본값을 주고 싶으면 세 번째 인자를 씁니다: LAG(칸, 몇칸위, 기본값)
const 앞뒤 = await db.query(`
  SELECT 점검번호, 점수,
         LAG(점수)        OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 이전점수,
         LAG(점수, 1, 0)  OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 이전점수기본0,
         LEAD(점수)       OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 다음점수,
         점수 - LAG(점수) OVER (PARTITION BY 설비번호 ORDER BY 점검일) AS 점수변화
  FROM 점검기록 WHERE 설비번호 = 3 ORDER BY 점검일
`);
for (const 줄 of 앞뒤.rows)
  console.log(`· 점검${줄.점검번호} · 점수 ${값(줄.점수)} · 이전 ${값(줄.이전점수)} · 이전(기본0) ${값(줄.이전점수기본0)} · 다음 ${값(줄.다음점수)} · 변화 ${값(줄.점수변화)}`);
// 출력: · 점검8 · 점수 95 · 이전 (없음) · 이전(기본0) 0 · 다음 (없음) · 변화 (없음)
// 출력: · 점검9 · 점수 (없음) · 이전 95 · 이전(기본0) 95 · 다음 74 · 변화 (없음)
// 출력: · 점검10 · 점수 74 · 이전 (없음) · 이전(기본0) (없음) · 다음 90 · 변화 (없음)
// 출력: · 점검11 · 점수 90 · 이전 74 · 이전(기본0) 74 · 다음 52 · 변화 16
// 출력: · 점검12 · 점수 52 · 이전 90 · 이전(기본0) 90 · 다음 (없음) · 변화 -38
// ★★ 점검10 을 보세요. 이전(기본0)이 0 이 아니라 (없음) 입니다. 기본값은 "위에 줄이 아예 없을 때"
//    만 씁니다. 위에 줄은 있는데 그 값이 NULL 이면 NULL 그대로입니다.
// ★ 그래서 점수변화도 NULL 이 두 번 나옵니다. NULL 이 섞인 뺄셈은 결과도 NULL 입니다.

// ============================================================
// 섹션 6 — 누적 합계와 이동 평균 (프레임)
// ============================================================
// 창 안에서 "지금 줄 기준으로 어디부터 어디까지" 를 정하는 것이 프레임(frame)입니다.

const 누적 = await db.query(`
  SELECT 라인코드, 생산일, 수량,
         SUM(수량) OVER (PARTITION BY 라인코드 ORDER BY 생산일) AS 누적수량,
         ROUND(AVG(수량) OVER (PARTITION BY 라인코드 ORDER BY 생산일
                               ROWS BETWEEN 2 PRECEDING AND CURRENT ROW), 1) AS 사흘평균
  FROM 생산실적 ORDER BY 라인코드, 생산일
`);
for (const 줄 of 누적.rows.slice(0, 10))   // 라인 A 8줄 + 라인 B 앞 2줄
  console.log(`· ${줄.라인코드} · ${날짜(줄.생산일)} · 수량 ${줄.수량} · 누적 ${줄.누적수량} · 3일평균 ${줄.사흘평균}`);
// 출력: · A · 2024-06-01 · 수량 10 · 누적 10 · 3일평균 10.0
// 출력: · A · 2024-06-02 · 수량 20 · 누적 30 · 3일평균 15.0
// 출력: · A · 2024-06-03 · 수량 30 · 누적 60 · 3일평균 20.0
// 출력: · A · 2024-06-04 · 수량 20 · 누적 80 · 3일평균 23.3
// 출력: · A · 2024-06-05 · 수량 40 · 누적 120 · 3일평균 30.0
// 출력: · A · 2024-06-06 · 수량 20 · 누적 140 · 3일평균 26.7
// 출력: · A · 2024-06-07 · 수량 50 · 누적 190 · 3일평균 36.7
// 출력: · A · 2024-06-08 · 수량 30 · 누적 220 · 3일평균 33.3
// 출력: · B · 2024-06-01 · 수량 5 · 누적 5 · 3일평균 5.0
// 출력: · B · 2024-06-02 · 수량 15 · 누적 20 · 3일평균 10.0
// ★ 라인 A 의 누적: 10 → 30 → 60 → 80 → 120 → 140 → 190 → 220. 손으로 더해도 맞습니다.
// ★ 라인 B 로 넘어가면 누적이 5 부터 다시 시작합니다. PARTITION 이 바뀌면 창도 새로 열립니다.
// ★ 3일평균 첫 줄은 자기 값, 둘째 줄은 두 개 평균입니다.
//   ROWS BETWEEN 2 PRECEDING AND CURRENT ROW = "위로 두 줄 + 나 자신" 입니다.
//
// ★★ ORDER BY 만 쓰고 프레임을 안 적으면 기본값은 RANGE BETWEEN UNBOUNDED PRECEDING AND
//    CURRENT ROW ("창 시작부터 지금 줄까지") 입니다. 그래서 섹션 2 ③ 에서 SUM 이 누적이 됐습니다.
//    ORDER BY 도 없으면 창 전체가 프레임입니다. 그때는 합이 하나로 고정됐습니다.
// ★★ ROWS 와 RANGE 는 세는 단위가 다릅니다. ROWS = 줄 수, RANGE = ORDER BY 한 칸의 "값".
//    값이 같은 줄들은 RANGE 에서 한 덩어리입니다. 그래서 동점이 있으면 결과가 달라집니다.
const 줄과값 = await db.query(`
  SELECT 수량,
         SUM(수량) OVER (ORDER BY 수량 ROWS  BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS 줄기준,
         SUM(수량) OVER (ORDER BY 수량 RANGE BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS 값기준
  FROM 생산실적 WHERE 라인코드 = 'A' ORDER BY 수량, 줄기준
`);
for (const 줄 of 줄과값.rows) console.log(`· 수량 ${줄.수량} · ROWS ${줄.줄기준} · RANGE ${줄.값기준}`);
// 출력: · 수량 10 · ROWS 10 · RANGE 10
// 출력: · 수량 20 · ROWS 30 · RANGE 70
// 출력: · 수량 20 · ROWS 50 · RANGE 70
// 출력: · 수량 20 · ROWS 70 · RANGE 70
// 출력: · 수량 30 · ROWS 100 · RANGE 130
// 출력: · 수량 30 · ROWS 130 · RANGE 130
// 출력: · 수량 40 · ROWS 170 · RANGE 170
// 출력: · 수량 50 · ROWS 220 · RANGE 220
// ★★ 수량 20 짜리 세 줄을 보세요. ROWS 는 30 · 50 · 70 으로 한 줄씩 더해 갑니다.
//    RANGE 는 셋 다 70 입니다. "20 이하인 값 전부" 를 한꺼번에 보기 때문입니다.
// ★ 줄 단위로 세려면 ROWS 라고 반드시 적으세요. 안 적으면 RANGE 라 동점이 뭉개집니다.
//   ROWS 는 같은 값끼리의 앞뒤가 안 정해져서, 위에서는 ORDER BY 수량, 줄기준 으로 고정했습니다.

// ============================================================
// 섹션 7 — ★★ FIRST_VALUE 는 되는데 LAST_VALUE 는 안 되는 이유
// ============================================================

const 첫끝 = await db.query(`
  SELECT 생산일, 수량,
         FIRST_VALUE(수량) OVER (PARTITION BY 라인코드 ORDER BY 생산일) AS 첫값,
         LAST_VALUE(수량)  OVER (PARTITION BY 라인코드 ORDER BY 생산일) AS 끝값_그냥,
         LAST_VALUE(수량)  OVER (PARTITION BY 라인코드 ORDER BY 생산일
                                 ROWS BETWEEN UNBOUNDED PRECEDING
                                          AND UNBOUNDED FOLLOWING) AS 끝값_프레임명시
  FROM 생산실적 WHERE 라인코드 = 'A' ORDER BY 생산일 LIMIT 5
`);
for (const 줄 of 첫끝.rows)
  console.log(`· ${날짜(줄.생산일)} · 수량 ${줄.수량} · 첫값 ${줄.첫값} · 끝값(그냥) ${줄.끝값_그냥} · 끝값(프레임명시) ${줄.끝값_프레임명시}`);
// 출력: · 2024-06-01 · 수량 10 · 첫값 10 · 끝값(그냥) 10 · 끝값(프레임명시) 30

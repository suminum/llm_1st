//
// ★★★ ROW_NUMBER 는 동점일 때 "어느 줄이 먼저인지" 를 스스로 정하지 않습니다. ORDER BY 점수 DESC
//     만 쓰면 88점 세 줄의 앞뒤가 실행할 때마다 달라질 수 있습니다. 그래서 위 쿼리는 ORDER BY 에

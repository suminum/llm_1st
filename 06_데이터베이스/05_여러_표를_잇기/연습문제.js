// ── 채점 도구 ──
//
// 결과를 한 줄짜리 글자로 눌러서 기대값과 그대로 비교합니다.
//   · NULL 은 "NULL" 로
//   · DATE 는 "2024-01-05" 로   (Date 객체로 오기 때문에 다듬습니다)
//   · BIGINT(COUNT 결과) 는 "15" 로
//   · 칸 사이는 쉼표, 줄 사이는 " | "

function 값글자(값) {
  if (값 === null) return "NULL";
  if (값 instanceof Date) return 값.toISOString().slice(0, 10);
  return String(값);
}

function 눌러쓰기(줄들) {
  return 줄들.map((줄) => Object.values(줄).map(값글자).join(",")).join(" | ");
}

const 문제 = [];

async function 채점(번호) {
  const { 제목, 답, 기대 } = 문제[번호 - 1];

  if (답.includes("TODO")) {
    console.log(`${번호}. ${제목} — 아직 안 풀었습니다`);
    return;
  }

  let 내것;

  try {
    내것 = 눌러쓰기((await db.query(답)).rows);
  } catch (에러) {
    console.log(`${번호}. ${제목} — SQL 에러 (${에러.code})`);
    return;
  }

  if (내것 === 기대) {
    맞힌수 += 1;
    console.log(`${번호}. ${제목} — 정답`);
  } else {
    console.log(`${번호}. ${제목} — 오답`);
  }
}



// ── 섹션 2: ★ 디스크에서 읽는 단위는 '쪽(page)' 입니다 ──

// 데이터베이스는 줄 단위로 읽지 않습니다. **쪽(page)** 단위로 읽습니다.
// PostgreSQL 의 한 쪽은 **8KB(8192바이트)** 입니다.
//
//   ┌──────── 8KB 한 쪽 ────────┐
//   │ 머리말 │ 줄포인터 →→→     │
//   │                           │
//   │        (빈 공간)          │
//   │                           │
//   │   ←←← 줄  줄  줄  줄      │
//   └───────────────────────────┘
//
// 한 줄이 100바이트쯤이면 한 쪽에 70~80줄이 들어갑니다.
// 표의 통계는 pg_class 라는 시스템 표에 들어 있습니다.

async function 표통계(이름) {
  return (
    await db.query(
      `SELECT relpages AS 쪽수, reltuples::bigint AS 줄수, pg_relation_size(oid) AS 바이트
       FROM pg_class WHERE relname = $1`,
      [이름],
    )
  ).rows[0];
}

const 통계전 = await 표통계("점검기록");

console.log(`통계를 모으기 전: ${통계전.쪽수} 쪽 / ${통계전.줄수} 줄`);
// 출력?: 통계를 모으기 전: 0 쪽 / -1 줄

// ★★ 0 쪽에 -1 줄이라고 나옵니다. 20만 건을 넣었는데요.
//   **통계를 아직 안 모았기 때문입니다.** -1 은 "모른다" 는 뜻입니다.
//
//   플래너는 이 통계를 보고 계획을 세웁니다.
//   통계가 없으면 계획이 틀립니다. 그래서 데이터를 크게 넣은 뒤에는
//   **ANALYZE** 를 돌려 줘야 합니다. (개념02 에서 그 대가를 실측합니다)

await db.exec("ANALYZE 점검기록");

const 통계후 = await 표통계("점검기록");

console.log(`ANALYZE 후: ${통계후.쪽수} 쪽 / ${통계후.줄수} 줄 / ${(Number(통계후.바이트) / 1024 / 1024).toFixed(1)} MB`);
// 출력?: ANALYZE 후: 2642 쪽 / 200000 줄 / 20.6 MB

console.log("한 쪽에 들어간 줄 수:", Math.round(200000 / 통계후.쪽수));
// 출력?: 한 쪽에 들어간 줄 수: 76

console.log("쪽 하나가 8KB 인가:", Number(통계후.바이트) / 통계후.쪽수 === 8192);
// 출력: 쪽 하나가 8KB 인가: true

// ★★ 이 숫자를 기억해 두세요. 이 표는 **2642 쪽**입니다.
//   앞으로 "몇 쪽을 읽었나" 가 이 단원의 판단 기준이 됩니다.
//   "빠르다/느리다" 는 기계마다 다르지만, 읽은 쪽 수는 어디서나 같습니다.


// ── 섹션 3: 설비 하나의 기록을 찾습니다 ──

// 설비 12345번의 점검기록만 보고 싶습니다. 20만 건 중 열 건입니다.

const 색인없이ms = await 재기(7, () =>
  db.query("SELECT * FROM 점검기록 WHERE 설비번호 = $1", [12345]),
);

console.log(`설비 한 대의 기록 찾기: ${색인없이ms.toFixed(1)} ms`);
// 출력?: 설비 한 대의 기록 찾기: 20.1 ms

// 20ms. 눈으로는 빠릅니다. 그런데 이렇게 생각해 보세요.
//
//   현장 대시보드가 설비 50대를 한 화면에 보여 준다면 → 50 × 20ms = 1초
//   그 화면을 20명이 동시에 본다면 → 서버는 1초에 1000번 이 질의를 합니다
//
// ★ 문제는 20ms 라는 값이 아니라 **왜 20ms 나 걸리는가** 입니다.
//   열 건 찾자고 무엇을 한 걸까요? 물어봅시다.


// ── 섹션 4: ★ EXPLAIN — 데이터베이스에게 "어떻게 할 거냐" 고 묻기 ──

// SQL 은 **무엇을** 원하는지만 씁니다. **어떻게** 찾을지는 안 씁니다.
// 그 '어떻게' 를 정하는 것이 **플래너(planner)** 입니다.
//
// EXPLAIN 을 앞에 붙이면 플래너가 세운 계획을 보여 줍니다. 질의는 실행하지 않습니다.

console.log(await 계획("SELECT * FROM 점검기록 WHERE 설비번호 = 12345"));
// 출력?: Seq Scan on "점검기록"  (cost=0.00..5142.00 rows=10 width=72)
// 출력?:   Filter: ("설비번호" = 12345)

// 한 줄씩 읽습니다.
//
//   Seq Scan on "점검기록"
//     → **순차 훑기(Sequential Scan)**. 표를 처음부터 끝까지 한 줄도 안 빼고 읽습니다.
//
//   cost=0.00..5142.00
//     → 플래너가 매긴 **비용 점수**입니다. 밀리초가 아닙니다. 단위 없는 상대값입니다.
//        앞의 0.00 은 '첫 줄이 나오기까지', 뒤의 값은 '끝까지'.
//
//   rows=10
//     → 열 줄쯤 나올 거라는 **추정**입니다. 세어 본 게 아니라 통계로 짐작한 값입니다.
//
//   width=72
//     → 한 줄이 평균 72바이트라는 뜻입니다. (가져올 칸만 셉니다)
//
//   Filter: ("설비번호" = 12345)
//     → 다 읽으면서 이 조건으로 거릅니다.
//
// ★★ 정리하면: **20만 줄을 전부 읽어서 199,990 줄을 버리고 10 줄을 남깁니다.**
//
//   전화번호부에서 "김철수" 를 찾는데 1쪽부터 마지막 쪽까지 넘겨 보는 것과 같습니다.
//   찾기는 찾습니다. 시간이 걸릴 뿐입니다.

// EXPLAIN 뒤에 ANALYZE 를 붙이면 **진짜로 실행해서** 실제 값까지 보여 줍니다.
// (자세한 것은 개념03 에서 합니다)

const 실제계획 = await 계획("SELECT * FROM 점검기록 WHERE 설비번호 = 12345", "(ANALYZE)");

console.log(실제계획);
// 출력?: Seq Scan on "점검기록"  (cost=0.00..5142.00 rows=10 width=72) (actual time=1.336..19.307 rows=10.00 loops=1)
// 출력?:   Filter: ("설비번호" = 12345)
// 출력?:   Rows Removed by Filter: 199990
// 출력?:   Buffers: shared hit=2642
// 출력?: Planning Time: 0.064 ms
// 출력?: Execution Time: 19.438 ms

// ★ `Rows Removed by Filter: 199990` — 짐작이 아니라 실제로 버린 줄 수입니다.
//   199,990 줄을 읽고 버렸습니다. 이 한 줄이 이 단원의 출발점입니다.
//
// ★ `Buffers: shared hit=2642` — 읽은 쪽 수입니다.
//   PostgreSQL 18 부터는 EXPLAIN ANALYZE 에 이 줄이 **자동으로** 나옵니다.
//   (예전 버전에서는 `EXPLAIN (ANALYZE, BUFFERS)` 라고 써야 했습니다)
//
//   hit  = 메모리에 이미 있어서 바로 쓴 쪽
//   read = 디스크에서 새로 읽어 온 쪽

const 읽은쪽 = 실제계획.match(/Buffers: shared (?:hit=(\d+))?\s?(?:read=(\d+))?/);
const 읽은쪽수 = Number(읽은쪽[1] || 0) + Number(읽은쪽[2] || 0);

console.log("읽은 쪽 수:", 읽은쪽수, "/ 표 전체 쪽 수:", 통계후.쪽수);
// 출력?: 읽은 쪽 수: 2642 / 표 전체 쪽 수: 2642

console.log("표에 있는 쪽을 하나도 안 빼고 다 읽었나:", 읽은쪽수 === 통계후.쪽수);
// 출력: 표에 있는 쪽을 하나도 안 빼고 다 읽었나: true

// ★★ 10줄 찾자고 2642 쪽(20.6MB)을 전부 읽었습니다.
//   필요한 데이터는 10 × 72 = 720 바이트입니다. **3만 배** 를 읽었습니다.


// ── 섹션 5: ★ 데이터가 늘면 그대로 느려집니다 ──

// 20만 건에서 20ms 라면 200만 건에서는 얼마일까요? 재 봅니다.
// 규모를 바꿔 가며 같은 질의를 돌립니다.

await db.exec("CREATE TABLE 규모실험 (id SERIAL PRIMARY KEY, 설비번호 INT NOT NULL, 상태 TEXT NOT NULL)");

const 규모결과 = [];

for (const 건수 of [10000, 50000, 100000, 200000]) {
  await db.exec("TRUNCATE 규모실험 RESTART IDENTITY");
  await db.exec(`
    INSERT INTO 규모실험 (설비번호, 상태)
    SELECT (i % 20000) + 1, (ARRAY['정상','주의','고장'])[(i % 3) + 1]
    FROM generate_series(1, ${건수}) AS i
  `);
  await db.exec("ANALYZE 규모실험");

  const ms = await 재기(7, () => db.query("SELECT count(*) FROM 규모실험 WHERE 설비번호 = $1", [777]));
  const 쪽 = (await 표통계("규모실험")).쪽수;

  규모결과.push({ 건수, ms, 쪽 });
  console.log(`${건수.toLocaleString()} 건 · ${쪽} 쪽 · ${ms.toFixed(2)} ms`);
}
// 출력?: 10,000 건 · 55 쪽 · 1.29 ms
// 출력?: 50,000 건 · 271 쪽 · 4.93 ms
// 출력?: 100,000 건 · 541 쪽 · 9.29 ms
// 출력?: 200,000 건 · 1082 쪽 · 17.93 ms

const 첫째 = 규모결과[0];
const 마지막 = 규모결과[3];

console.log(`건수는 ${(마지막.건수 / 첫째.건수).toFixed(0)}배, 쪽 수는 ${(마지막.쪽 / 첫째.쪽).toFixed(1)}배, 시간은 ${(마지막.ms / 첫째.ms).toFixed(1)}배`);
// 출력?: 건수는 20배, 쪽 수는 19.7배, 시간은 13.9배

console.log("건수 20배에 시간도 10배 넘게 늘었나:", 마지막.ms / 첫째.ms > 10);
// 출력: 건수 20배에 시간도 10배 넘게 늘었나: true

console.log("쪽 수가 건수만큼 늘었나:", 마지막.쪽 / 첫째.쪽 > 15);
// 출력: 쪽 수가 건수만큼 늘었나: true

// ★★ 이걸 "선형으로 느려진다" 고 합니다. O(n) 입니다.
//
//   건수가 20배 → 읽어야 할 쪽이 20배 → 시간도 대충 20배.
//   당연합니다. 다 읽으니까요.
//
//   문제는 이게 **절대 좋아지지 않는다** 는 것입니다.
//   서버를 두 배 좋은 걸로 바꿔도 데이터가 두 배 되면 원위치입니다.
//
// ★ 반대로 색인은 O(log n) 입니다.
//   건수가 20배 늘어도 읽는 쪽 수는 **한두 쪽** 늘어납니다.
//   왜 그런지는 개념02 에서 B-tree 를 그려 가며 봅니다.


// ── 섹션 6: ★ 그런데 Seq Scan 이 항상 나쁜 건 아닙니다 ──

// 여기서 초보자가 가장 많이 오해합니다.
//
//   "EXPLAIN 에 Seq Scan 이 보이면 잘못된 거다"  ← **틀렸습니다.**
//
// Seq Scan 이 **더 빠른 경우**가 분명히 있습니다. 두 가지를 재 봅니다.


// ① 표가 작을 때

await db.exec(`
  CREATE TABLE 라인표 (id SERIAL PRIMARY KEY, 코드 TEXT NOT NULL, 이름 TEXT NOT NULL);
  INSERT INTO 라인표 (코드, 이름)
  SELECT 'L' || i, i || '번 라인' FROM generate_series(1, 40) AS i;
  CREATE INDEX 라인표_코드 ON 라인표 (코드);
  ANALYZE 라인표;
`);

console.log(await 계획("SELECT * FROM 라인표 WHERE 코드 = 'L25'"));
// 출력?: Seq Scan on "라인표"  (cost=0.00..1.50 rows=1 width=19)
// 출력?:   Filter: ("코드" = 'L25'::text)

console.log("색인을 만들어 뒀는데 Seq Scan 인가:", (await 계획("SELECT * FROM 라인표 WHERE 코드 = 'L25'")).includes("Seq Scan"));
// 출력: 색인을 만들어 뒀는데 Seq Scan 인가: true

// ★ 색인이 있는데도 안 씁니다. 플래너가 일부러 안 쓴 것입니다.
//
//   40줄짜리 표는 **한 쪽**에 다 들어갑니다.
//   색인을 쓰면 색인 쪽 + 표 쪽 = 최소 두 쪽을 읽어야 합니다.
//   그냥 한 쪽 읽고 훑는 게 더 쌉니다. 플래너가 옳습니다.


// ② 표의 대부분을 읽을 때

await db.exec("CREATE INDEX 규모_상태 ON 규모실험 (상태); ANALYZE 규모실험;");

console.log(await 계획("SELECT count(*) FROM 규모실험 WHERE 상태 <> '없음'"));
// 출력?: Aggregate  (cost=4082.00..4082.01 rows=1 width=8)
// 출력?:   ->  Seq Scan on "규모실험"  (cost=0.00..3582.00 rows=200000 width=0)
// 출력?:         Filter: ("상태" <> '없음'::text)

console.log(await 계획("SELECT count(*) FROM 규모실험 WHERE 상태 = '고장'"));
// 출력?: Aggregate  (cost=2821.65..2821.66 rows=1 width=8)
// 출력?:   ->  Bitmap Heap Scan on "규모실험"  (cost=743.15..2655.56 rows=66433 width=0)
// 출력?:         Recheck Cond: ("상태" = '고장'::text)
// 출력?:         ->  Bitmap Index Scan on "규모_상태"  (cost=0.00..726.54 rows=66433 width=0)
// 출력?:               Index Cond: ("상태" = '고장'::text)

// 위는 전체(100%)를 읽으니 Seq Scan, 아래는 1/3 만 읽으니 색인을 씁니다.
// 실제로 재 보면 어떨까요. 색인을 억지로 쓰게 해서 비교합니다.

// ★ enable_seqscan 은 **실습용 스위치**입니다.
//   플래너에게 "순차 훑기는 되도록 쓰지 마" 라고 알려 줍니다.
//   운영 코드에 쓰면 안 됩니다. 계획을 비교해 볼 때만 씁니다.

const 전체를읽는질의 = "SELECT count(*) FROM 규모실험 WHERE 상태 <> '없음'";

const 훑기ms = await 재기(5, () => db.query(전체를읽는질의));

await db.exec("SET enable_seqscan = off");
const 강제계획 = await 계획(전체를읽는질의);
const 색인강제ms = await 재기(5, () => db.query(전체를읽는질의));
await db.exec("SET enable_seqscan = on");

console.log(`전부 읽을 때 — 순차 훑기 ${훑기ms.toFixed(1)} ms / 색인 강제 ${색인강제ms.toFixed(1)} ms`);
// 출력?: 전부 읽을 때 — 순차 훑기 34.5 ms / 색인 강제 49.8 ms

console.log("색인을 강제한 계획에 Seq Scan 이 없나:", !강제계획.includes("Seq Scan on"));
// 출력: 색인을 강제한 계획에 Seq Scan 이 없나: true

console.log("순차 훑기가 더 빠른가:", 훑기ms < 색인강제ms);
// 출력: 순차 훑기가 더 빠른가: true

// ★★★ **표의 대부분을 읽을 거면 순차 훑기가 이깁니다.**
//
//   색인은 "찾아가서 → 표를 다시 본다" 를 줄마다 반복합니다.
//   표의 90% 를 볼 거면 그 왕복이 순서대로 쭉 읽는 것보다 비쌉니다.
//   디스크는 **순서대로 읽는 것**을 훨씬 잘합니다.
//
//   그래서 플래너의 판단 기준은 "색인이 있나" 가 아니라
//   **"몇 퍼센트를 읽을 건가"** 입니다. 대략 5~10% 를 넘으면 순차 훑기로 기웁니다.



// ── MySQL 은 여기가 다릅니다 ──
//
//   · EXPLAIN 은 있지만 출력이 표 모양이라 완전히 다르게 생겼습니다
//   · `EXPLAIN ANALYZE` 는 MySQL 8.0.18 부터입니다. 그 전 버전에는 없습니다
//   · 쪽(page) 크기가 기본 **16KB** 입니다. PostgreSQL 은 8KB 입니다
//   · generate_series 가 없습니다. 재귀 CTE 로 흉내 냅니다
//   ★ 자세한 비교는 09단원에서 둘 다 띄워 놓고 합니다


// ============================================================
// 정리 — 왜 느린가
// ============================================================
//
//   본 것                     무엇을 뜻하나
//   ────────────────────────────────────────────────────────────────
//   Seq Scan                  표를 처음부터 끝까지 다 읽는다
//   Rows Removed by Filter    읽고 나서 버린 줄 수. 이게 크면 낭비다
//   cost=0.00..5142.00        플래너의 비용 점수. 밀리초가 아니다
//   rows=10                   짐작한 결과 줄 수. 통계에서 나온다
//   Buffers: shared hit=2642  실제로 읽은 쪽 수
//   relpages / 8KB            디스크는 줄이 아니라 '쪽' 단위로 읽는다
//
//   재 본 것                   결과
//   ────────────────────────────────────────────────────────────────
//   20만 건 조건 검색           2642 쪽을 전부 읽음 (필요한 건 10줄)
//   건수 20배                  쪽 수 20배, 시간도 10배 이상 — 선형으로 느려짐
//   40줄짜리 표                색인이 있어도 Seq Scan 이 이김
//   표의 100% 를 읽을 때        순차 훑기가 색인보다 빠름
//   ANALYZE 안 한 표            relpages 가 0, reltuples 가 -1
//
// ★★ Seq Scan 은 죄가 아닙니다. **필요 없는 Seq Scan** 이 죄입니다.
//   10줄 찾자고 20만 줄을 읽는 것 — 그것만 고치면 됩니다.



console.log("두 칸 다 주면:", 노드들(await 계획("SELECT * FROM 점검기록 WHERE 설비번호 = 500 AND 라인 = 'A'")));
// 출력: 두 칸 다 주면: Bitmap Heap Scan / Bitmap Index Scan


// ── 섹션 2: ★★★ 칸 순서가 결정적입니다 ──

// 지금 색인은 `(설비번호, 라인)` 입니다. 앞칸만 주는 것과 뒷칸만 주는 것을 비교합니다.

const 앞칸만 = await 계획("SELECT * FROM 점검기록 WHERE 설비번호 = 500");
const 뒷칸만 = await 계획("SELECT * FROM 점검기록 WHERE 라인 = 'A'");

console.log("앞칸(설비번호)만 주면:", 노드들(앞칸만));
// 출력: 앞칸(설비번호)만 주면: Bitmap Heap Scan / Bitmap Index Scan

console.log("뒷칸(라인)만 주면:", 노드들(뒷칸만));
// 출력: 뒷칸(라인)만 주면: Seq Scan

console.log("앞칸만 줬을 때 색인을 썼나:", 앞칸만.includes("점검_설비_라인"));
// 출력: 앞칸만 줬을 때 색인을 썼나: true

console.log("뒷칸만 줬을 때 색인을 썼나:", 뒷칸만.includes("점검_설비_라인"));
// 출력: 뒷칸만 줬을 때 색인을 썼나: false

// ★★★ **같은 색인인데 앞칸으로 찾으면 쓰이고, 뒷칸으로 찾으면 안 쓰입니다.**
//
// ★ 전화번호부를 생각하세요.
//
//   전화번호부는 (성, 이름) 순서로 정렬돼 있습니다.
//
//     "김" 씨를 찾아라        → 됩니다. 김 씨 구역으로 바로 갑니다
//     "김철수" 를 찾아라       → 됩니다. 김 씨 구역에서 철수를 찾습니다
//     "철수" 를 찾아라         → **안 됩니다.** 이 철수가 김철수인지 박철수인지 모르니
//                              처음부터 끝까지 다 봐야 합니다
//
//   복합 색인도 똑같습니다. **왼쪽부터 이어지는 만큼만 쓸 수 있습니다.**
//   이걸 "왼쪽 접두사 규칙(leftmost prefix)" 이라고 합니다.
//
//     (설비번호, 라인, 상태) 색인이 있을 때
//       WHERE 설비번호=?                   → 쓸 수 있음
//       WHERE 설비번호=? AND 라인=?         → 쓸 수 있음
//       WHERE 설비번호=? AND 라인=? AND 상태=? → 전부 쓸 수 있음
//       WHERE 라인=?                       → 못 씀
//       WHERE 라인=? AND 상태=?             → 못 씀
//       WHERE 설비번호=? AND 상태=?         → 설비번호까지만 쓰고 상태는 걸러냄


// ── 섹션 3: ★★ 그런데 요즘은 반쯤 쓰이기도 합니다 (PostgreSQL 18) ──

// 위에서 "뒷칸만 주면 못 쓴다" 고 했습니다. **항상 그런 건 아닙니다.**
// 순서를 뒤집어서 `(라인, 설비번호)` 로 만들고 뒷칸(설비번호)만 줘 봅니다.

await db.exec("DROP INDEX 점검_설비_라인");
await db.exec("CREATE INDEX 점검_라인_설비 ON 점검기록 (라인, 설비번호)");
await db.exec("ANALYZE 점검기록");

const 건너뛰기 = await 계획("SELECT * FROM 점검기록 WHERE 설비번호 = 500", "(ANALYZE)");

console.log("(라인, 설비번호) 색인에 뒷칸만 줬을 때 색인을 쓰나:", 건너뛰기.includes("점검_라인_설비"));
// 출력: (라인, 설비번호) 색인에 뒷칸만 줬을 때 색인을 쓰나: true

console.log("무슨 방법으로:", 노드들(건너뛰기));
// 출력?: 무슨 방법으로: Index Scan

console.log(건너뛰기.split("\n").filter((줄) => /Index Cond|Index Searches/.test(줄)).map((줄) => 줄.trim()).join(" | "));
// 출력: Index Cond: ("설비번호" = 500) | Index Searches: 9

// ★★ `Index Searches: 9` 를 보세요. 색인을 **아홉 번** 뒤졌습니다.
//
//   PostgreSQL 18 에 **건너뛰기 스캔(skip scan)** 이 들어왔습니다.
//   앞칸(라인)의 값이 A, B, C, D 네 가지뿐이니까
//   "A 구역에서 500 찾고, B 구역에서 500 찾고..." 를 반복한 것입니다.
//
//   전화번호부로 치면 성이 네 개뿐일 때 "김 철수, 이 철수, 박 철수, 최 철수" 를
//   각각 찾아보는 것입니다. (구역 경계를 확인하는 몫까지 더해 아홉 번이 됐습니다)
//   성이 5000개면 못 합니다.
//
// ★ 그래서 섹션 2 에서는 안 쓰였던 것입니다.
//   `(설비번호, 라인)` 의 앞칸 설비번호는 값이 **20000가지**입니다.
//   2만 번 건너뛰느니 그냥 표를 훑는 게 쌉니다. 플래너가 옳습니다.
//
// ★★★ **그래도 순서 규칙은 그대로 지키세요.**
//   건너뛰기 스캔은 "운이 좋으면 살려 주는 안전망" 이지 설계 원칙이 아닙니다.
//   제대로 된 순서로 만든 색인과 견줘 봅니다.

const 이상적 = "SELECT * FROM 점검기록 WHERE 설비번호 = 500";

const 뒤집힌쪽수 = 색인쪽수(await 계획(이상적, "(ANALYZE)"));

await db.exec("DROP INDEX 점검_라인_설비");
await db.exec("CREATE INDEX 점검_설비_라인 ON 점검기록 (설비번호, 라인)");
await db.exec("ANALYZE 점검기록");
await db.query(이상적);

const 제대로쪽수 = 색인쪽수(await 계획(이상적, "(ANALYZE)"));

console.log(`색인이 읽은 쪽 — (라인,설비번호) ${뒤집힌쪽수} 쪽 / (설비번호,라인) ${제대로쪽수} 쪽`);
// 출력?: 색인이 읽은 쪽 — (라인,설비번호) 28 쪽 / (설비번호,라인) 2 쪽

console.log("순서를 제대로 준 쪽이 덜 읽나:", 제대로쪽수 < 뒤집힌쪽수);
// 출력: 순서를 제대로 준 쪽이 덜 읽나: true


// ── 섹션 4: ★★ 순서를 정하는 규칙 — 등호 먼저, 범위 나중 ──

// 조건이 `라인 = 'A'` (등호) 와 `점검일 BETWEEN ...` (범위) 두 개일 때
// 어느 칸을 앞에 둬야 할까요? 재 봅니다.

const 섞인질의 = `
  SELECT count(*) FROM 점검기록
  WHERE 라인 = 'A' AND 점검일 BETWEEN DATE '2024-03-01' AND DATE '2024-03-31'`;

const 순서결과 = [];

for (const [설명, 칸들] of [["등호 먼저 (라인, 점검일)", "라인, 점검일"], ["범위 먼저 (점검일, 라인)", "점검일, 라인"]]) {
  await db.exec(`CREATE INDEX 순서실험 ON 점검기록 (${칸들})`);
  await db.exec("ANALYZE 점검기록");
  await db.query(섞인질의);                                  // 예열

  const 쪽 = 색인쪽수(await 계획(섞인질의, "(ANALYZE)"));

  순서결과.push({ 설명, 쪽 });
  console.log(`${설명} → 색인에서 ${쪽} 쪽`);

  await db.exec("DROP INDEX 순서실험");
}
// 출력?: 등호 먼저 (라인, 점검일) → 색인에서 6 쪽
// 출력?: 범위 먼저 (점검일, 라인) → 색인에서 18 쪽

console.log("등호를 앞에 둔 쪽이 덜 읽나:", 순서결과[0].쪽 < 순서결과[1].쪽);
// 출력: 등호를 앞에 둔 쪽이 덜 읽나: true

// ★★ 왜 그런가.
//
//   색인은 정렬된 목록입니다. **범위 조건을 만나는 순간 그 뒤 칸은 정렬이 깨집니다.**
//
//   (라인, 점검일) 로 만들면:
//     라인 = 'A' 인 구역으로 점프  →  그 안에서 점검일이 정렬돼 있음  →  3월 구간만 딱 읽음
//
//   (점검일, 라인) 로 만들면:
//     3월 구간으로 점프  →  그 안에 A·B·C·D 가 섞여 있음  →  전부 읽고 A 만 골라냄
//
// ★★★ **규칙: 등호(=, IN) 조건 칸을 앞에, 범위(>, <, BETWEEN, LIKE 'x%') 칸을 뒤에.**
//   그리고 등호 칸이 여러 개면 **값 종류가 많은 칸을 앞에** 두는 게 대체로 낫습니다.
//   (많이 걸러지는 칸을 먼저 쓰면 뒤에서 볼 게 적어집니다)
//
//   그리고 마지막 규칙: **정렬(ORDER BY)에 쓰는 칸은 맨 뒤에.** 섹션 8 에서 봅니다.


// ── 섹션 5: ★ 부분 색인 — 필요한 줄만 색인합니다 ──

// 현장 화면 대부분은 "고장 난 것" 만 봅니다. 정상 기록은 안 봅니다.
// 그런데 색인은 20만 줄을 전부 담고 있습니다. 3분의 1만 담으면 안 될까요?
//
//   CREATE INDEX ... ON 표 (칸) WHERE 조건;
//
// 조건에 맞는 줄만 색인에 넣습니다. 이걸 **부분 색인(partial index)** 이라고 합니다.

await db.exec("CREATE INDEX 점검_점검일_전체 ON 점검기록 (점검일)");
await db.exec("CREATE INDEX 점검_고장만 ON 점검기록 (점검일) WHERE 상태 = '고장'");
await db.exec("ANALYZE 점검기록");

const 색인크기 = (
  await db.query(`
    SELECT pg_relation_size('점검_점검일_전체') AS 전체, pg_relation_size('점검_고장만') AS 부분
  `)
).rows[0];

console.log(`전체 색인 ${메가(색인크기.전체)} / 고장만 담은 부분 색인 ${메가(색인크기.부분)}`);
// 출력?: 전체 색인 1.45 MB / 고장만 담은 부분 색인 0.46 MB

console.log("부분 색인이 더 작은가:", Number(색인크기.부분) < Number(색인크기.전체));
// 출력: 부분 색인이 더 작은가: true

const 고장질의 = "SELECT * FROM 점검기록 WHERE 상태 = '고장' AND 점검일 = DATE '2024-03-01'";

console.log("고장 조회에 무엇을 골랐나:", (await 계획(고장질의)).includes("점검_고장만") ? "부분 색인" : "다른 것");
// 출력: 고장 조회에 무엇을 골랐나: 부분 색인

// ★★ 부분 색인의 좋은 점
//
//   ① 작습니다 → 메모리 캐시를 덜 먹고, 뒤지는 깊이도 얕습니다
//   ② **조건에 안 맞는 줄을 넣거나 고칠 때는 색인을 안 건드립니다** → 쓰기가 덜 느려집니다
//
//   현장에서 잘 맞는 곳:
//     · 상태가 '진행중' 인 주문만 (끝난 주문은 안 봄)
//     · 삭제표시 = false 인 줄만 (지운 건 안 봄)
//     · 오류 로그만 (전체 로그의 0.1%)
//
// ★ 주의: **질의의 조건이 색인의 WHERE 를 포함해야** 쓰입니다.
//   `WHERE 상태 = '고장'` 을 안 쓰면 이 색인은 못 씁니다.

console.log("조건을 빼면 부분 색인을 쓰나:", (await 계획("SELECT * FROM 점검기록 WHERE 점검일 = DATE '2024-03-01'")).includes("점검_고장만"));
// 출력: 조건을 빼면 부분 색인을 쓰나: false

await db.exec("DROP INDEX 점검_점검일_전체");



const 결과 = [];

async function 계획(sql, 옵션 = "") {
  return (await db.query(`EXPLAIN ${옵션} ${sql}`)).rows.map((줄) => 줄["QUERY PLAN"]).join("\n");
}

async function 채점(번호, 제목, 답, 검사) {
  const 비었나 = 답 === null || 답 === undefined || (typeof 답 === "string" && 답.trim() === "");

  if (비었나) {
    결과.push(false);
    console.log(`${번호}. ${제목} — 아직 안 풀었습니다`);
    return;
  }

  try {
    const 통과 = await 검사(답);
    결과.push(통과 === true);
    console.log(`${번호}. ${제목} — ${통과 === true ? "통과" : "틀렸습니다"}`);
  } catch (에러) {
    결과.push(false);
    console.log(`${번호}. ${제목} — 에러가 났습니다 (${에러.code ?? "?"})`);
  }
}



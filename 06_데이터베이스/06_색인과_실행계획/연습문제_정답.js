const 답1 = "CREATE INDEX 점검_점검자 ON 점검기록 (점검자)";

await 채점(1, "점검자에 색인 만들기", 답1, async (sql) => {
  await db.exec(sql);
  await db.exec("ANALYZE 점검기록");
  const 계획글 = await 계획("SELECT * FROM 점검기록 WHERE 점검자 = '점검원7'");
  return 계획글.includes("점검_점검자");
});
// 출력: 1. 점검자에 색인 만들기 — 통과

// ★ 왜
//   `CREATE INDEX 이름 ON 표 (칸)` 이 전부입니다.
//   이름을 안 주면 PostgreSQL 이 `점검기록_점검자_idx` 로 지어 줍니다. 그것도 됩니다.
//   그런데 **회사에서는 이름 규칙을 정해 두는 게 낫습니다.**
//   나중에 "이 색인 지워도 되나?" 를 판단할 때 이름만 보고 알아야 하기 때문입니다.
//
// ★ 만든 뒤에 ANALYZE 를 한 이유
//   색인을 만들면 그 색인의 통계도 새로 필요합니다.
//   `CREATE INDEX` 는 색인 자체 통계는 만들어 주지만,
//   대량 작업 뒤에는 습관적으로 ANALYZE 를 붙이는 게 안전합니다.
//
// ★ 자주 하는 실수
//   `CREATE INDEX ON 점검기록 점검자` — 괄호를 빼면 문법 에러(42601)입니다.


// ============================================================
// 정답 2 — Seq Scan 인지 확인하기
// ============================================================

const 답2 = "Seq Scan";

await 채점(2, "어떤 스캔이 나오나", 답2, async (이름) => {
  const 계획글 = await 계획("SELECT * FROM 점검기록 WHERE 비고 = '없음'");
  return 계획글.split("\n")[0].startsWith(이름.trim());
});
// 출력: 2. 어떤 스캔이 나오나 — 통과

// ★ 왜
//   `비고` 칸에는 색인이 없습니다. 그러니 표를 처음부터 끝까지 읽는 수밖에 없습니다.
//   그게 Seq Scan(순차 훑기)입니다.
//
// ★ 여기서 놓치기 쉬운 것
//   "Seq Scan 이 나왔으니 색인을 걸어야겠다" 는 **자동 반응이 아닙니다.**
//   개념01 섹션 6 에서 봤듯이, 표가 작거나 대부분을 읽는 질의라면 Seq Scan 이 옳습니다.
//   봐야 할 것은 `Rows Removed by Filter` 입니다.
//   그 값이 결과 줄 수보다 훨씬 크면 그때 색인을 생각합니다.


// ============================================================
// 정답 3 — 외래키에 색인 걸기
// ============================================================

const 답3 = "CREATE INDEX 점검_설비번호 ON 점검기록 (설비번호)";

await 채점(3, "외래키에 색인 걸기", 답3, async (sql) => {
  await db.exec(sql);
  await db.exec("ANALYZE 점검기록");
  const 계획글 = await 계획("SELECT * FROM 점검기록 WHERE 설비번호 = 777");
  return 계획글.includes("점검_설비번호") && !계획글.includes("Seq Scan");
});
// 출력: 3. 외래키에 색인 걸기 — 통과

// ★ 왜 이게 중요한가 (개념02 섹션 9)
//   `REFERENCES 설비(id)` 라고 썼다고 색인이 생기지 않습니다.
//   기본키 쪽(설비.id)에는 자동으로 생기지만 **참조하는 쪽에는 안 생깁니다.**
//
//   문제가 두 군데서 터집니다.
//
//   ① 조인이 느립니다
//      `설비 JOIN 점검기록 ON 점검기록.설비번호 = 설비.id` 는 거의 모든 화면에서 씁니다
//
//   ② **부모를 지울 때** 자식 표를 통째로 훑습니다
//      `DELETE FROM 설비 WHERE id = 777` 을 하면 PostgreSQL 은
//      "이 설비를 참조하는 점검기록이 있나" 를 확인해야 합니다.
//      색인이 없으면 20만 줄을 다 봅니다. 자식이 1000만 건이면 그대로 멈춥니다.
//
// ★ MySQL 은 다릅니다
//   InnoDB 는 외래키를 만들면 색인을 **자동으로** 만들어 줍니다.
//   그래서 MySQL 하다 온 사람이 PostgreSQL 에서 특히 많이 당합니다.


// ============================================================
// 정답 4 — 복합 색인의 칸 순서
// ============================================================

const 답4 = "CREATE INDEX 점검_복합 ON 점검기록 (상태, 점검일)";

await 채점(4, "복합 색인 순서", 답4, async (sql) => {
  await db.exec(sql);
  await db.exec("ANALYZE 점검기록");

  const 계획글 = await 계획(
    `SELECT * FROM 점검기록
     WHERE 상태 = '고장' AND 점검일 BETWEEN DATE '2024-03-01' AND DATE '2024-03-31'`,
  );

  const 색인조건 = 계획글.split("\n").filter((줄) => 줄.includes("Index Cond")).join(" ");
  return 계획글.includes("점검_복합") && 색인조건.includes("상태") && 색인조건.includes("점검일");
});
// 출력: 4. 복합 색인 순서 — 통과

// ★ 왜 (상태, 점검일) 이고 (점검일, 상태) 가 아닌가
//
//   **등호 조건을 앞에, 범위 조건을 뒤에.** 이게 규칙입니다.
//
//   색인은 정렬된 목록입니다. (상태, 점검일) 로 만들면 이렇게 정렬됩니다.
//
//     고장 · 2024-01-01
//     고장 · 2024-01-02
//     ...
//     고장 · 2024-12-31
//     정상 · 2024-01-01
//     ...
//
//   `상태 = '고장'` 으로 '고장' 구역에 점프하면,
//   **그 구역 안이 점검일로 정렬돼 있습니다.** 3월 구간만 딱 읽으면 끝입니다.
//
//   반대로 (점검일, 상태) 로 만들면 이렇습니다.
//
//     2024-01-01 · 고장
//     2024-01-01 · 정상
//     2024-01-01 · 주의
//     2024-01-02 · 고장
//     ...
//
//   3월 구간으로 점프하면 그 안에 고장·정상·주의가 **섞여 있습니다.**
//   3월치를 전부 읽고 고장만 골라내야 합니다.
//
// ★ 개념04 섹션 4 에서 실제로 재 봤습니다. 색인에서 읽는 쪽 수가 3배쯤 차이 났습니다.
//
// ★ 정리하면 순서 정하는 규칙은 셋입니다.
//   ① 등호(=, IN) 조건 칸을 앞에
//   ② 등호끼리는 값 종류가 많은 칸(많이 걸러지는 칸)을 앞에
//   ③ 범위 조건과 ORDER BY 칸은 뒤에


// ============================================================
// 정답 5 — 부분 색인
// ============================================================

const 답5 = "CREATE INDEX 점검_고장부분 ON 점검기록 (점검일) WHERE 상태 = '고장'";

await 채점(5, "부분 색인", 답5, async (sql) => {
  await db.exec(sql);
  await db.exec("CREATE INDEX 비교용_전체 ON 점검기록 (점검일)");
  await db.exec("ANALYZE 점검기록");

  const 크기 = (
    await db.query("SELECT pg_relation_size('점검_고장부분') AS 부분, pg_relation_size('비교용_전체') AS 전체")
  ).rows[0];

  const 계획글 = await 계획("SELECT * FROM 점검기록 WHERE 상태 = '고장' AND 점검일 = DATE '2024-03-01'");

  await db.exec("DROP INDEX 비교용_전체");

  return 계획글.includes("점검_고장부분") && Number(크기.부분) < Number(크기.전체) / 2;
});
// 출력: 5. 부분 색인 — 통과

// ★ 왜
//   `WHERE 상태 = '고장'` 이 붙으면 **고장인 줄만** 색인에 들어갑니다.
//   전체의 3분의 1이니 색인도 3분의 1 크기가 됩니다.
//
// ★ 좋은 점 두 가지
//   ① 작습니다 → 메모리 캐시를 덜 먹고 뒤지는 깊이도 얕습니다
//   ② **정상·주의 기록을 넣거나 고칠 때는 이 색인을 안 건드립니다**
//      → INSERT 가 덜 느려집니다. 전체 색인이라면 매번 써야 합니다
//
// ★ 반드시 지켜야 할 것
//   질의에도 `WHERE 상태 = '고장'` 이 있어야 씁니다.
//   `SELECT * FROM 점검기록 WHERE 점검일 = ...` 만 하면 이 색인은 못 씁니다.
//   플래너가 "이 색인에 그 줄이 들어 있다는 보장이 없다" 고 판단하기 때문입니다.
//
// ★ 현장에서 잘 맞는 곳
//     · 상태가 '진행중' 인 주문만 (끝난 주문은 목록에 안 나옴)
//     · 삭제표시 = false 인 줄만
//     · 오류 로그만 (전체 로그의 0.1%)
//
// ★ MySQL 에는 부분 색인이 없습니다. PostgreSQL 만 있습니다.


// ============================================================
// 정답 6 — 표현식 색인
// ============================================================

const 답6 = "CREATE INDEX 설비_소문자이름 ON 설비 (lower(이름))";

await 채점(6, "표현식 색인", 답6, async (sql) => {
  await db.exec(sql);
  await db.exec("ANALYZE 설비");
  const 계획글 = await 계획("SELECT * FROM 설비 WHERE lower(이름) = '설비777'");
  return 계획글.includes("설비_소문자이름");
});
// 출력: 6. 표현식 색인 — 통과

// ★ 왜 그냥 (이름) 색인으로는 안 되나
//   색인 안에는 `설비777` 이라는 **저장된 값 그대로** 들어 있습니다.
//   `lower(설비777)` 은 색인 어디에도 없습니다.
//   색인은 정렬된 목록인데, 함수를 씌우면 그 정렬이 소용없어집니다.
//
//   `lower(이름)` 으로 색인을 만들면 **함수를 씌운 결과가 정렬돼서** 들어갑니다.
//   그러면 `WHERE lower(이름) = ...` 을 그대로 찾을 수 있습니다.
//
// ★ 반드시 지켜야 할 것: 질의의 표현식과 **글자 그대로** 같아야 합니다
//     색인 lower(이름)  ←  질의 lower(이름)          쓰임
//     색인 lower(이름)  ←  질의 upper(이름)          안 쓰임
//     색인 lower(이름)  ←  질의 lower(trim(이름))    안 쓰임
//     색인 lower(이름)  ←  질의 이름                 안 쓰임
//
// ★ 함수가 IMMUTABLE 이어야 합니다
//   같은 입력이면 언제나 같은 출력이 나와야 색인에 담을 수 있습니다.
//   `now()` 나 시간대에 따라 달라지는 함수로는 색인을 못 만듭니다.
//   (`timestamptz` 를 `date` 로 바꾸는 것이 대표적으로 막히는 경우입니다)
//
// ★ 쓸 데가 많습니다
//     CREATE INDEX ON 회원 (lower(전자우편));           -- 대소문자 무시 로그인
//     CREATE INDEX ON 주문 (date_trunc('day', 시각));   -- 날짜별 집계
//     CREATE INDEX ON 설비 ((설정 ->> '제조사'));        -- JSONB 안의 값


// ============================================================
// 정답 7 — 커버링 색인으로 Index Only Scan 만들기
// ============================================================

const 답7 = "CREATE INDEX 점검_커버 ON 점검기록 (설비번호) INCLUDE (상태)";

await 채점(7, "Index Only Scan 만들기", 답7, async (sql) => {
  await db.exec(sql);
  await db.exec("VACUUM ANALYZE 점검기록");
  const 계획글 = await 계획("SELECT 설비번호, 상태 FROM 점검기록 WHERE 설비번호 = 777", "(ANALYZE)");
  return 계획글.includes("Index Only Scan") && 계획글.includes("Heap Fetches: 0");
});
// 출력: 7. Index Only Scan 만들기 — 통과

// ★ `CREATE INDEX 점검_커버 ON 점검기록 (설비번호, 상태)` 도 통과합니다.
//   둘 다 "필요한 칸이 색인 안에 다 있다" 는 조건을 채웁니다.
//
//   차이는 이렇습니다.
//     (설비번호, 상태)            상태로도 **찾을 수** 있습니다. 정렬 순서에 들어갑니다
//     (설비번호) INCLUDE (상태)   상태는 얹혀만 있습니다. **꺼내는 데만** 씁니다
//
//   찾는 조건에 안 쓰는 칸은 INCLUDE 가 낫습니다.
//   색인이 조금 더 작고, UNIQUE 색인에 얹을 때 유일성 판정에 영향을 안 줍니다.
//
// ★★ **VACUUM 이 핵심입니다.**
//   색인에는 "이 줄이 지금 보여도 되는 줄인지" 가 안 적혀 있습니다.
//   누가 지웠는데 아직 정리가 안 된 줄일 수도 있으니까요.
//   그래서 PostgreSQL 은 **가시성 지도(visibility map)** 를 따로 봅니다.
//   그 지도를 채우는 것이 VACUUM 입니다.
//
//   VACUUM 을 안 하면 커버링 색인을 만들어도 `Bitmap Heap Scan` 이 나옵니다.
//   개념03 섹션 5 에서 실제로 확인했습니다.
//
// ★ `Heap Fetches` 를 꼭 보세요
//   Index Only Scan 이라고 나와도 Heap Fetches 가 크면 반쪽짜리입니다.
//   결국 표를 그만큼 본 것입니다. autovacuum 이 안 따라오고 있다는 뜻입니다.


// ============================================================
// 정답 8 — 형변환 때문에 죽은 색인 살리기
// ============================================================

const 답8 = "SELECT * FROM 점검기록 WHERE 설비번호 = 777";

await 채점(8, "형변환 때문에 죽은 색인 살리기", 답8, async (sql) => {
  const 계획글 = await 계획(sql);
  const 줄수 = (await db.query(sql)).rows.length;
  return !계획글.includes("Seq Scan") && 줄수 === 10;
});
// 출력: 8. 형변환 때문에 죽은 색인 살리기 — 통과

// ★ 왜 `설비번호::text = '777'` 은 색인을 못 쓰나

// ★ 왜 (상태, 점검일 DESC) 인가
//
//   ① `상태 = '고장'` 은 등호 조건 → 앞에
//   ② `ORDER BY 점검일 DESC` 는 정렬 → 뒤에
//
//   그러면 색인이 이렇게 정렬됩니다.
//
//     고장 · 2024-12-31

const 진단질의 = "SELECT count(*) FROM 점검기록 WHERE 점검자 = '점검원7' AND 소속반 = '반7'";

async function 짐작과실제() {
  const 계획글 = await 계획(진단질의, "(ANALYZE)");
  const 줄 = 계획글.split("\n").find((한줄) => /Scan on/.test(한줄) && /actual/.test(한줄));

  return {
    짐작: Number(줄.match(/rows=(\d+) width/)[1]),
    실제: Number(줄.match(/rows=([\d.]+) loops/)[1]),
    계획: 계획글,
  };
}


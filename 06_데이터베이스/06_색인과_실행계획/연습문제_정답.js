//
// ★ DESC 를 안 붙여도 대개 됩니다
//   `(상태, 점검일)` 오름차순 색인이어도 PostgreSQL 은 **색인을 거꾸로 읽을 수 있습니다.**
//   계획에 `Index Scan Backward` 라고 나옵니다.
//
//   ★ 문제는 방향이 섞일 때입니다.

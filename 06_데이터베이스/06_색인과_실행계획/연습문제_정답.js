//
// ★ 색인이 없으면 무슨 일이 생기나
//   6만 6천 줄을 전부 읽어서 정렬하고, 그중 20줄만 씁니다.
//   계획에 `Sort` 노드가 보이고 그 밑에 `Seq Scan` 이 있습니다.
//   개념04 섹션 8 에서 재 봤을 때 수백 배 차이가 났습니다.
//
// ★★ `ORDER BY ... LIMIT` 은 색인 효과가 가장 극적으로 나는 곳입니다.

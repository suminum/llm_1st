import { PGlite } from "@electric-sql/pglite";

const db = await PGlite.create();

await db.exec(`
  CREATE TABLE 설비 (
    id       SERIAL PRIMARY KEY,
    이름     TEXT NOT NULL,
    라인     TEXT NOT NULL,
    관리번호 TEXT NOT NULL
  );
  INSERT INTO 설비 (이름, 라인, 관리번호)
  SELECT '설비' || i, (ARRAY['A','B','C','D'])[(i % 4) + 1], lpad(i::text, 8, '0')
  FROM generate_series(1, 20000) AS i;

  CREATE TABLE 점검기록 (
    id       SERIAL PRIMARY KEY,
    설비번호 INT  NOT NULL REFERENCES 설비(id),
    상태     TEXT NOT NULL,
    점검자   TEXT NOT NULL,
    소속반   TEXT NOT NULL,
    점검일   DATE NOT NULL,
    비고     TEXT
  );
  INSERT INTO 점검기록 (설비번호, 상태, 점검자, 소속반, 점검일, 비고)
  SELECT (i % 20000) + 1,
         (ARRAY['정상','주의','고장'])[(i % 3) + 1],
         '점검원' || ((i % 50) + 1),
         '반' || ((i % 50) + 1),
         DATE '2024-01-01' + ((i % 365) || ' days')::interval,
         '특이사항 없음. 기록번호 ' || i
  FROM generate_series(1, 200000) AS i;
  ANALYZE;
`);

const 결과 = [];

async function 계획(sql, 옵션 = "") {
  return (await db.query(`EXPLAIN ${옵션} ${sql}`)).rows.map((줄) => 줄["QUERY PLAN"]).join("\n");
}

async function 채점(번호, 제목, 답, 검사) {
  const 비었나 = 답 === null || 답 === undefined || (typeof 답 === "string" && 답.trim() === "");

  if (비었나) {
    결과.push(false);
    console.log(`${번호}. ${제목} — 아직 안 풀었습니다`);
    return;
  }

  try {
    const 통과 = await 검사(답);
    결과.push(통과 === true);
    console.log(`${번호}. ${제목} — ${통과 === true ? "통과" : "틀렸습니다"}`);
  } catch (에러) {
    결과.push(false);
    console.log(`${번호}. ${제목} — 에러가 났습니다 (${에러.code ?? "?"})`);
  }
}



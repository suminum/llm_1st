async function 재시도하며(연결, 할일, 최대시도 = 5) {
  for (let 시도 = 1; 시도 <= 최대시도; 시도 += 1) {
    try {
      await 연결.query("BEGIN");
      const 결과 = await 할일(연결);
      await 연결.query("COMMIT");
      return { 결과, 시도 };
    } catch (에러) {
      // ★ 반드시 롤백합니다. 안 하면 연결이 오염된 채 남습니다(개념01 섹션5).
      try {
        await 연결.query("ROLLBACK");
      } catch {
        // 이미 서버가 롤백했으면 여기서 할 일이 없습니다
      }

      // ★ 다시 해도 소용없는 에러(문법 오류, 제약 위반)는 바로 던집니다.
      //   무조건 재시도하면 같은 에러를 다섯 번 내고 5배 느려질 뿐입니다.
      if (!다시해볼만한코드.has(에러.code) || 시도 === 최대시도) throw 에러;

      // ★★ 기다리는 시간을 점점 늘리고(지수 백오프), 무작위로 흔듭니다(지터).
      //   똑같이 기다리면 둘이 동시에 다시 시작해서 또 부딪힙니다.
      //   ★ 상한을 두세요. 안 두면 10번째 재시도에서 5초를 기다리게 됩니다.
      await 잠깐(Math.min(200, 10 * 2 ** (시도 - 1)) + Math.random() * 20);
    }
  }
}


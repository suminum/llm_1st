async function 문제6(연결, 뺄수량) {
  const 결과 = await 연결.query(
    "UPDATE 답_재고 SET 수량 = 수량 - $1 WHERE 부품번호 = 1 AND 수량 >= $1",
    [뺄수량],
  );

  return 결과.rowCount === 1;
}

// ★ 핵심은 두 가지입니다.
//   ① 조건을 **WHERE 안에** 넣었습니다. 확인과 수정이 한 문장입니다.
//      "SELECT 로 확인하고 UPDATE" 는 그 사이에 남이 다 가져갈 수 있습니다.
//   ② **rowCount 를 봤습니다.**
//      조건이 안 맞으면 0줄이 고쳐집니다. **에러가 안 납니다.**
//      안 보고 넘어가면 재고가 없는데 "출고 완료" 를 답하게 됩니다.
//
//   ★★ 왜 음수가 안 되나 — 남이 먼저 커밋했으면 내 UPDATE 는 잠금이 풀린 뒤
//      값을 다시 읽고 `수량 >= $1` 을 **다시 확인**해서 안 맞으면 건너뜁니다.


// ============================================================
// 정답 7 — 비관적 잠금
// ============================================================

async function 문제7(연결) {
  await 연결.query("BEGIN");

  // ★ FOR UPDATE 여섯 글자가 전부입니다.
  const 지금 = (await 연결.query("SELECT 수량 FROM 답_재고 WHERE 부품번호 = 1 FOR UPDATE")).rows[0].수량;

  await 잠깐(3);

  await 연결.query("UPDATE 답_재고 SET 수량 = $1 WHERE 부품번호 = 1", [지금 + 1]);
  await 연결.query("COMMIT");
}

// ★ FOR UPDATE 가 없으면 열 명이 전부 같은 값을 읽고 같은 값을 씁니다.
//   붙이면 첫 사람이 커밋할 때까지 나머지 아홉 명이 SELECT 에서 멈춥니다.
//   깨어난 사람은 **바뀐 값**을 읽습니다.
//
//   ★★ BEGIN 이 없으면 의미가 없습니다. 자동 커밋이면 SELECT 가 끝나는 순간 풀립니다.
//   ★ 대가: 열 명이 한 줄로 섭니다. 잠깐(3) 이 100ms 라면 열 명이 1초를 씁니다.
//     그래서 **잠금을 쥔 동안에는 최소한의 일만** 하세요.


// ============================================================
// 정답 8 — 낙관적 잠금
// ============================================================

async function 문제8(연결) {
  for (let 시도 = 1; 시도 <= 100; 시도 += 1) {
    const 읽은것 = (await 연결.query("SELECT 수량, 버전 FROM 답_재고 WHERE 부품번호 = 1")).rows[0];

    const 결과 = await 연결.query(
      "UPDATE 답_재고 SET 수량 = $1, 버전 = 버전 + 1 WHERE 부품번호 = 1 AND 버전 = $2",
      [읽은것.수량 + 1, 읽은것.버전],
    );

    if (결과.rowCount === 1) return 시도; // 성공
    // rowCount 가 0 이면 내가 읽은 뒤 남이 먼저 고친 것입니다. 다시 읽고 다시 합니다.
  }

  throw new Error("100번 시도했는데 실패");
}

// ★ 버전 칸이 하는 일
//   "내가 읽었을 때의 버전이 아직 그대로일 때만 써라" 는 조건입니다.
//   남이 먼저 썼으면 버전이 올라가 있으므로 내 UPDATE 는 0줄을 고칩니다.
//   그러면 처음부터 다시 합니다.
//
//   ★ 잠그지 않으니 기다림이 없습니다. 대신 **헛일**이 생깁니다.
//     개념02 섹션8 에서 20명이 한 줄에 몰렸을 때 헛시도가 130회였습니다.
//
//   ★★ 언제 쓰나 — 충돌이 드물 때, 그리고 **화면이 오래 열려 있을 때**.
//     수정 폼을 열고 5분 뒤에 저장하는 경우를 생각해 보세요. FOR UPDATE 로
//     5분을 잠글 수는 없습니다. 버전 칸이면 잠그지 않고도
//     "그사이 다른 사용자가 수정했습니다" 를 알려 줍니다.
//
//   ★ 수정시각(updated_at)으로도 하지만, 같은 밀리초에 두 번 고치면 못 잡습니다.


// ============================================================
// 정답 9 — 반복 불가 읽기 막기
// ============================================================

async function 문제9(연결, 사이에할일) {
  await 연결.query("BEGIN ISOLATION LEVEL REPEATABLE READ");

  const 첫번째 = (await 연결.query("SELECT 수량 FROM 답_재고 WHERE 부품번호 = 1")).rows[0].수량;
  await 사이에할일();
  const 두번째 = (await 연결.query("SELECT 수량 FROM 답_재고 WHERE 부품번호 = 1")).rows[0].수량;

  await 연결.query("COMMIT");
  return { 첫번째, 두번째 };
}

// ★ 왜 REPEATABLE READ 인가
//   기본값 READ COMMITTED 는 **문장마다** 새로 사진을 찍습니다.
//   그래서 문장 사이에 남이 커밋하면 다음 문장은 새 값을 봅니다.
//
//   REPEATABLE READ 는 **트랜잭션의 첫 문장에서 찍은 사진 한 장**을 끝까지 봅니다.
//   남이 뭘 하든 내 사진은 안 바뀝니다.
//
//   ★ 사진은 BEGIN 이 아니라 **첫 문장**에서 찍힙니다(개념03 섹션8).
//   ★★ 대가: 내가 본 줄을 남이 먼저 고치면 내 UPDATE 가 40001 로 거부됩니다.
//     읽기만 하면 괜찮지만 쓰기까지 한다면 재시도 코드가 필요합니다(정답 14).
//   ★ 언제 쓰나: 월말 정산, 대사 작업, 여러 표를 한 시점 기준으로 읽는 보고서.



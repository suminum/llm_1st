async function 문제13(연결, 부품번호들) {
  await 연결.query("BEGIN");

  // ★ 이 한 줄이 답입니다. 잠그기 전에 **정렬**합니다.
  const 순서대로 = [...부품번호들].sort((하나, 둘) => 하나 - 둘);

  for (const 번호 of 순서대로) {
    await 연결.query("UPDATE 답_재고 SET 수량 = 수량 - 1 WHERE 부품번호 = $1", [번호]);
    await 잠깐(60);
  }

  await 연결.query("COMMIT");
}

// ★ 왜 정렬만으로 데드락이 사라지나
//   데드락은 **잠그는 순서가 서로 다를 때**만 생깁니다(개념05 섹션2).
//   모두가 작은 번호부터 잡으면 고리가 안 만들어집니다.
//
//   두 번째 사람은 1번에서 기다립니다. 첫 번째가 커밋하면 1번, 2번을 차례로 잡습니다.
//   **기다림은 있지만 서로 기다리지는 않습니다.**
//
//   ★★ [...부품번호들] 로 복사한 것에 주의하세요.
//     sort() 는 원본 배열을 **제자리에서** 바꿉니다.
//     부르는 쪽의 배열을 몰래 바꿔 버리면 나중에 이상한 버그가 납니다.
//
//   ★ 순서를 맞추는 방법: 항상 기본키 오름차순, 표에도 순서 정하기,
//     한 문장으로 잠그기(WHERE 번호 IN (...) ORDER BY 번호 FOR UPDATE).
//
//   ★★★ 그래도 데드락은 완전히 사라지지 않습니다.
//     외래키, 트리거, UNIQUE INSERT 로도 납니다(개념05 섹션5).
//     그래서 정답 14 가 반드시 함께 있어야 합니다.



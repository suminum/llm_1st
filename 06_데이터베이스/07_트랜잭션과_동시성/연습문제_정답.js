async function 문제10(연결, 일꾼이름) {
  await 연결.query("BEGIN");

  const 집기 = await 연결.query(`
    SELECT 번호 FROM 답_큐
    WHERE 상태 = '대기'
    ORDER BY 번호
    LIMIT 1
    FOR UPDATE SKIP LOCKED
  `);

  if (집기.rowCount === 0) {
    await 연결.query("COMMIT");
    return null;
  }

  const 번호 = 집기.rows[0].번호;
  await 잠깐(5);
  await 연결.query("UPDATE 답_큐 SET 상태 = '완료', 처리자 = $1 WHERE 번호 = $2", [일꾼이름, 번호]);
  await 연결.query("COMMIT");
  return 번호;
}

// ★ FOR UPDATE 와 SKIP LOCKED 가 각각 하는 일이 다릅니다.
//   FOR UPDATE    → 내가 집은 줄을 남이 못 집게 잠급니다 (중복 처리를 막습니다)

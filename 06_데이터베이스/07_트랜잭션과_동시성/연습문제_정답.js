async function 연결여럿(개수, 할일) {
  const 연결들 = [];

  for (let 자리 = 0; 자리 < 개수; 자리 += 1) 연결들.push(await 새연결());

  try {
    return await 할일(연결들);
  } finally {
    for (const 연결 of 연결들) await 연결.end().catch(() => {});
  }
}


async function 문제1(연결) {
  await 연결.query("BEGIN");
  await 연결.query("UPDATE 답_설비 SET 상태 = '폐기' WHERE 번호 = 1");

  const 내가본것 = (await 연결.query("SELECT 상태 FROM 답_설비 WHERE 번호 = 1")).rows[0].상태;

  await 연결.query("ROLLBACK");
  return 내가본것;
}

// ★ 왜 이렇게 되나
//   UPDATE 직후에 읽으면 '폐기' 입니다. 아직 커밋을 안 했는데도요.
//   **내 트랜잭션 안에서는 내가 한 변경이 보입니다.** 남에게만 안 보입니다.
//   그래서 "고치고 → 읽고 → 판단" 하는 코드가 트랜잭션 안에서 정상 동작합니다.
//
//   ★ 되돌리기는 테스트에서 유용합니다. 각 테스트를 BEGIN 으로 시작하고
//     ROLLBACK 으로 끝내면 정리 코드 없이 매번 깨끗한 상태에서 시작합니다.


// ============================================================
// 정답 2 — 자동 커밋
// ============================================================

async function 문제2(연결) {
  // BEGIN 을 안 씁니다. 이 UPDATE 는 그 자체로 하나의 트랜잭션입니다.
  await 연결.query("UPDATE 답_재고 SET 수량 = 50 WHERE 부품번호 = 1");

  try {
    await 연결.query("SELECT * FROM 없는표"); // 42P01
  } catch {
    // 이 에러는 앞의 UPDATE 와 아무 상관이 없습니다
  }
}

// ★ 왜 UPDATE 가 살아남나
//   BEGIN 을 안 썼으므로 UPDATE 는 보내는 순간 시작하고 **끝나는 순간 커밋**됩니다.
//   그 다음에 난 에러는 이미 끝난 트랜잭션을 되돌릴 수 없습니다.
//
//   ★★ 개념01 섹션1 의 함정이 이것입니다. "설비 지우고 → 점검기록 지우고 →
//     대장에 넣고" 를 BEGIN 없이 하면 세 번째가 실패해도 앞의 둘은 이미 커밋돼
//     있습니다. 반쯤 된 상태가 됩니다.
//
//   ★ BEGIN 을 썼다면? 에러 뒤로 트랜잭션이 오염돼(25P02) COMMIT 도 롤백됩니다.
//     **BEGIN 하나로 결과가 정반대가 됩니다.**


// ============================================================
// 정답 3 — 오염된 트랜잭션 되살리기
// ============================================================

async function 문제3(연결) {
  await 연결.query("BEGIN");

  try {
    await 연결.query("SELECT * FROM 없는표");
  } catch {
    // ★ 이 한 줄이 답입니다.
    await 연결.query("ROLLBACK");
  }
}

// ★ 왜 ROLLBACK 이 필요한가
//   트랜잭션 안에서 에러가 나면 그 트랜잭션은 **오염(aborted)** 됩니다.
//   그 뒤로는 SELECT 1 조차 25P02 로 거부됩니다.
//   오염을 푸는 방법은 딱 둘입니다. ROLLBACK 하거나, ROLLBACK TO SAVEPOINT 하거나.
//   (COMMIT 을 보내도 되지만, 그건 롤백으로 처리됩니다)
//
//   ★★★ 이걸 안 하면 오염된 연결이 풀로 돌아갑니다. 다음 요청이 그 연결을 받아
//     **아무 잘못 없이 25P02 로 죽습니다.** 로그에는 전혀 다른 코드가 찍힙니다.
//     그래서 트랜잭션은 반드시 감싼 함수로 쓰세요(개념01 섹션7).


// ============================================================
// 정답 4 — SAVEPOINT
// ============================================================

async function 문제4(연결) {
  await 연결.query("BEGIN");
  await 연결.query("INSERT INTO 답_점검 (설비번호, 내용) VALUES (1, '정상 1')");

  await 연결.query("SAVEPOINT 여기까지는_확실");

  try {
    await 연결.query("INSERT INTO 답_점검 (설비번호, 내용) VALUES (99, '잘못')"); // 23503
  } catch {
    // ★ 세이브포인트로 되돌리면 오염이 **풀립니다.** 그 뒤로 다시 일할 수 있습니다.
    await 연결.query("ROLLBACK TO SAVEPOINT 여기까지는_확실");
  }

  await 연결.query("INSERT INTO 답_점검 (설비번호, 내용) VALUES (2, '정상 2')");
  await 연결.query("COMMIT");
}

// ★ 왜 '정상 1' 은 살아남나
//   ROLLBACK TO SAVEPOINT 는 **세이브포인트를 찍은 뒤에 한 일만** 되돌립니다.
//   그 앞에서 한 '정상 1' 은 그대로 남습니다.
//
//   ★ 정답 3 의 ROLLBACK 과 다른 점
//     ROLLBACK        — 트랜잭션 전체를 버립니다
//     ROLLBACK TO SP  — 일부만 버리고 트랜잭션은 계속 살립니다
//
//   ★★ 남발하지 마세요. 세이브포인트 하나가 내부 트랜잭션 하나입니다.
//     "건별 실패를 허용해야 한다" 는 요구가 진짜 있을 때만 쓰세요.



async function 낙관적으로(사람) {
  for (let 시도 = 1; 시도 <= 100; 시도 += 1) {
    const 읽은것 = (await 사람.query("SELECT 수량, 버전 FROM 재고 WHERE 부품번호 = 1")).rows[0];

    await new Promise((끝) => setTimeout(끝, 1));

    const 결과 = await 사람.query(
      "UPDATE 재고 SET 수량 = $1, 버전 = 버전 + 1 WHERE 부품번호 = 1 AND 버전 = $2",
      [읽은것.수량 + 1, 읽은것.버전],
    );

    if (결과.rowCount === 1) return 시도; // 성공
    // rowCount 가 0 이면 남이 먼저 고쳤습니다. 다시 읽고 다시 합니다.
  }

  throw new Error("100번 시도했는데도 실패했습니다");
}


async function 비교준비(줄수) {
  await 주연결.query("TRUNCATE 비교시험");
  await 주연결.query("INSERT INTO 비교시험 SELECT g, 0, 0 FROM generate_series(1, $1) g", [줄수]);
}

async function 비교재기(방식, 줄수) {
  await 비교준비(줄수);

  let 재시도 = 0;
  const 시작 = performance.now();

  await Promise.all(
    사람들.map(async (사람, 자리) => {
      const 대상 = (자리 % 줄수) + 1;

      if (방식 === "비관적") {
        await 사람.query("BEGIN");
        const 지금 = (await 사람.query("SELECT 수량 FROM 비교시험 WHERE 번호 = $1 FOR UPDATE", [대상])).rows[0].수량;
        await 사람.query("UPDATE 비교시험 SET 수량 = $1 WHERE 번호 = $2", [지금 + 1, 대상]);
        await 사람.query("COMMIT");
        return;
      }

      for (let 시도 = 1; 시도 <= 100; 시도 += 1) {
        const 읽은것 = (await 사람.query("SELECT 수량, 버전 FROM 비교시험 WHERE 번호 = $1", [대상])).rows[0];
        const 결과 = await 사람.query(
          "UPDATE 비교시험 SET 수량 = $1, 버전 = 버전 + 1 WHERE 번호 = $2 AND 버전 = $3",
          [읽은것.수량 + 1, 대상, 읽은것.버전],
        );
        if (결과.rowCount === 1) return;
        재시도 += 1;
      }
    }),
  );

  const 걸린ms = performance.now() - 시작;
  const 합계 = Number(await 한값("SELECT sum(수량) FROM 비교시험"));

  return { 걸린ms, 합계, 재시도 };
}

// 중앙값을 씁니다. 한 번 재고 판단하면 안 됩니다.
async function 다섯번재기(방식, 줄수) {
  const 잰것 = [];
  for (let 회차 = 0; 회차 < 5; 회차 += 1) 잰것.push(await 비교재기(방식, 줄수));
  잰것.sort((가, 나) => 가.걸린ms - 나.걸린ms);
  return 잰것[2];
}


// ── 섹션 2: ★★★ 트랜잭션을 써도 사라집니다 ──

// 이번엔 INSERT 가 아니라 **UPDATE** 입니다.
// 부품 재고를 20명이 한 개씩 채워 넣습니다. 0 에서 시작해 20 이 돼야 합니다.
// 코드는 아주 흔한 모양입니다. ① 지금 수량을 읽고 ② JS 에서 +1 하고 ③ 그 값을 씁니다.
// 트랜잭션도 제대로 씁니다. BEGIN 하고 COMMIT 합니다.

async function 읽고_더하고_쓰기(사람) {
  await 사람.query("BEGIN");

  const 지금 = (await 사람.query("SELECT 수량 FROM 재고 WHERE 부품번호 = 1")).rows[0].수량;

  // 읽고 쓰는 사이의 틈입니다. 파일 실험과 똑같습니다.
  await new Promise((끝) => setTimeout(끝, 5));

  await 사람.query("UPDATE 재고 SET 수량 = $1 WHERE 부품번호 = 1", [지금 + 1]);
  await 사람.query("COMMIT");
}

async function 재고초기화() {
  await 주연결.query("TRUNCATE 재고");
  await 주연결.query("INSERT INTO 재고 VALUES (1, '베어링 6203', 0, 0)");
}


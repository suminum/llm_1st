// 출력?: 몇 건이나 사라졌나 (첫 회): 19 건

// ★★★ BEGIN 도 했고 COMMIT 도 했는데 사라졌습니다.
//   에러는 하나도 안 났습니다. 20명 전부 "저장했습니다" 소리를 들었습니다.
//   01단원의 파일 실험과 **똑같은 일** 이 벌어졌습니다.
//
//   이걸 **갱신 손실(lost update)** 이라고 합니다.


// ── 섹션 3: 왜 사라지나 ──

// 20명은 많으니 두 명으로 줄여서 그려 봅니다. 수량은 0 에서 시작합니다.
//
//   시각   김반장                      이반장                     DB 의 수량
//   ─────────────────────────────────────────────────────────────────────
//    1     BEGIN                                                     0
//    2     SELECT 수량 → 0                                           0
//    3                                 BEGIN                         0
//    4                                 SELECT 수량 → 0               0
//    5     UPDATE 수량 = 0+1 = 1                                     0 (아직 안 보임)
//    6     COMMIT                                                    1
//    7                                 UPDATE 수량 = 0+1 = 1         1
//    8                                 COMMIT                        1  ← 2 가 아닙니다
//
// 두 사람 다 **0 을 읽었습니다.** 둘 다 1 을 썼습니다. 결과는 1 입니다.
// 이반장의 작업은 흔적도 없이 사라졌습니다.
//
// ★ 트랜잭션이 왜 못 막았나
//   트랜잭션이 보장하는 것은 "내 문장들이 전부 되거나 전부 안 되거나" 뿐입니다.
//   김반장 것도 전부 됐고 이반장 것도 전부 됐습니다. **둘 다 성공했습니다.**
//   문제는 **읽은 값이 쓸 때까지 그대로일 거라고 믿은 것** 입니다.
//   그건 트랜잭션이 약속한 적 없는 일입니다.
//
// ★★ 이 버그의 무서운 점
//   혼자 눌러 보면 절대 안 나고, 테스트에서도 거의 안 나고, 로그에 아무것도 안 남고,
//   손님이 많아질수록 자주 납니다.
//   재고, 잔액, 포인트, 조회수, 좋아요 — 전부 이 버그의 단골입니다.


// ── 섹션 4: 해법 ① 원자적 UPDATE — 읽지 말고 DB 에게 시키세요 ──

// 가장 간단하고 가장 빠릅니다. 그리고 대부분의 경우 이걸로 끝납니다.
//
//   나쁨:  SELECT 수량 → JS 에서 +1 → UPDATE 수량 = 21
//   좋음:  UPDATE 재고 SET 수량 = 수량 + 1
//
// 오른쪽은 값을 자바스크립트로 가져오지 않습니다. DB 안에서 읽고 더하고 씁니다.

async function 원자적으로(사람) {
  await 사람.query("UPDATE 재고 SET 수량 = 수량 + 1 WHERE 부품번호 = 1");
}

const 원자결과 = [];

for (let 회차 = 1; 회차 <= 3; 회차 += 1) {
  await 재고초기화();
  await Promise.all(사람들.map(원자적으로));
  원자결과.push(Number(await 한값("SELECT 수량 FROM 재고 WHERE 부품번호 = 1")));
}

console.log(`원자적 UPDATE → 결과 (3회):`, 원자결과.join(", "));
// 출력: 원자적 UPDATE → 결과 (3회): 20, 20, 20

console.log("20 이 됐나:", 원자결과.every((값) => 값 === 사람수));
// 출력: 20 이 됐나: true

// ★ 왜 이건 되나 — 잠금이 자동으로 걸립니다
//   UPDATE 는 그 줄에 잠금을 걸고 커밋할 때까지 안 놓습니다.
//   남의 UPDATE 는 그 앞에서 기다렸다가, 풀리면 **새 값을 다시 읽어서** 더합니다.
//   이 "다시 읽는다" 를 직접 확인해 봅니다.

await 재고초기화();
await 주연결.query("UPDATE 재고 SET 수량 = 100 WHERE 부품번호 = 1");

const 가 = 사람들[0];
const 나 = 사람들[1];

await 가.query("BEGIN");
await 가.query("UPDATE 재고 SET 수량 = 수량 - 5 WHERE 부품번호 = 1"); // 100 → 95, 잠금을 쥡니다

// 나는 여기서 막힙니다. await 하지 않고 띄워만 둡니다.
const 나의작업 = 나.query("UPDATE 재고 SET 수량 = 수량 - 3 WHERE 부품번호 = 1");

await new Promise((끝) => setTimeout(끝, 200)); // 나가 확실히 막히도록 잠깐 둡니다
await 가.query("COMMIT"); // 잠금을 놓습니다
await 나의작업; // 이제 나가 진행됩니다

console.log("100 에서 5 빼고 3 뺀 결과:", await 한값("SELECT 수량 FROM 재고 WHERE 부품번호 = 1"));
// 출력: 100 에서 5 빼고 3 뺀 결과: 92

// ★★ 92 입니다. 97 이 아닙니다.
//   나는 처음에 100 을 보고 있었습니다. 그런데 기다렸다 풀리고 나서
//   **95 를 다시 읽어서** 3 을 뺐습니다. 그래서 92 입니다.
//   이 "잠금이 풀리면 다시 읽는" 동작을 Postgres 는 자동으로 해 줍니다.


// ── 섹션 5: ★ 원자적 UPDATE 의 함정 — 조건이 붙으면 다릅니다 ──

// 재고가 모자라면 빼면 안 됩니다. 조건을 붙입니다.
//
//   UPDATE 재고 SET 수량 = 수량 - 3 WHERE 부품번호 = 1 AND 수량 >= 3
//
// 이건 안전할까요? 확인해 봅니다.

await 재고초기화();
await 주연결.query("UPDATE 재고 SET 수량 = 100 WHERE 부품번호 = 1");

await 가.query("BEGIN");
await 가.query("UPDATE 재고 SET 수량 = 0 WHERE 부품번호 = 1"); // 가가 재고를 다 씁니다

const 나의시도 = 나.query("UPDATE 재고 SET 수량 = 수량 - 3 WHERE 부품번호 = 1 AND 수량 >= 3");

await new Promise((끝) => setTimeout(끝, 200));
await 가.query("COMMIT");

const 나의결과 = await 나의시도;

console.log("나가 실제로 고친 줄 수:", 나의결과.rowCount);
// 출력: 나가 실제로 고친 줄 수: 0

console.log("최종 수량:", await 한값("SELECT 수량 FROM 재고 WHERE 부품번호 = 1"));
// 출력: 최종 수량: 0

// ★★★ 수량이 -3 이 되지 않았습니다. 조건을 **다시 확인** 했기 때문입니다.
//
//   나는 100 을 보고 시작했지만, 잠금이 풀린 뒤 0 을 다시 읽었고
//   `수량 >= 3` 이 이제 거짓이라 **그 줄을 건너뛰었습니다.**
//
//   ★ 그래서 rowCount 를 반드시 보세요. 0 이면 "재고가 모자라 못 뺐다" 는 뜻입니다.
//     안 보고 넘어가면 손님에게 "출고 완료" 라고 답하게 됩니다.
//
//     const 결과 = await 연결.query("UPDATE ... AND 수량 >= $1", [주문수]);
//     if (결과.rowCount === 0) throw new Error("재고 부족");
//
// ★ 이 한 줄짜리 패턴이 실무에서 재고 차감의 정석입니다.
//   SELECT 로 확인하고 UPDATE 하지 마세요. 그 사이에 남이 다 가져갑니다.


// ── 섹션 6: 해법 ② SELECT ... FOR UPDATE — 비관적 잠금 ──

// 원자적 UPDATE 로 안 되는 경우가 있습니다.
//   · 읽은 값으로 자바스크립트에서 복잡한 계산을 해야 할 때
//   · 여러 표를 읽어서 판단한 뒤 써야 할 때
//
// 그럴 때는 **읽을 때부터 줄을 잡아 둡니다.** SELECT 뒤에 FOR UPDATE 를 붙입니다.
//
//   SELECT 수량 FROM 재고 WHERE 부품번호 = 1 FOR UPDATE
//   → 이 줄을 커밋할 때까지 아무도 못 고칩니다. 남은 여기서 기다립니다.
//
// "남이 고칠 것이라고 미리 걱정하고 미리 막는다" 고 해서 **비관적 잠금** 이라고 합니다.

async function 비관적으로(사람) {
  await 사람.query("BEGIN");

  const 지금 = (await 사람.query("SELECT 수량 FROM 재고 WHERE 부품번호 = 1 FOR UPDATE")).rows[0].수량;

  await new Promise((끝) => setTimeout(끝, 1)); // 계산하는 시간이라고 칩시다

  await 사람.query("UPDATE 재고 SET 수량 = $1 WHERE 부품번호 = 1", [지금 + 1]);
  await 사람.query("COMMIT");
}


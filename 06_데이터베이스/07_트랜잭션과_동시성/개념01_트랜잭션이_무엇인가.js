// 실무에서 트랜잭션은 거의 항상 이 모양입니다. 이 틀을 외우세요.

async function 트랜잭션으로(연결, 할일) {
  await 연결.query("BEGIN");

  try {
    const 결과 = await 할일(연결);
    await 연결.query("COMMIT");
    return 결과;
  } catch (에러) {
    // ★★ 여기가 핵심입니다. 실패하면 반드시 되돌립니다.
    //   ROLLBACK 자체도 실패할 수 있으니(연결이 끊긴 경우) 감싸 둡니다.
    try {
      await 연결.query("ROLLBACK");
    } catch {
      // 이미 연결이 끊겼으면 서버가 알아서 롤백합니다. 여기서 할 일은 없습니다.
    }

    throw 에러; // ★ 삼키지 마세요. 부르는 쪽이 실패를 알아야 합니다
  }
}


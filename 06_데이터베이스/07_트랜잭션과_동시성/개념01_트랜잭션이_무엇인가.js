// 실행: node 개념01_트랜잭션이_무엇인가.js
//
// ★ 이 파일은 Docker 가 필요합니다.  docker compose up -d
// ============================================================
//
// 01단원에서 파일 저장이 못 하는 것 다섯 가지를 봤습니다.
// 그중 두 번째가 이것이었습니다.
//
//   "중간 실패를 못 되돌림 — 설비를 지우다 중간에 죽으면 점검기록만 남습니다"
//
// 이 단원은 그것을 풉니다.
//
// 설비 하나를 폐기하는 일은 **한 문장이 아닙니다.**
//
//   ① 그 설비의 점검기록을 정리한다
//   ② 설비 목록에서 지운다
//   ③ 폐기대장에 남긴다
//
// 세 문장입니다. 그런데 현실에서 이건 **하나의 일** 입니다.
// ①만 되고 ②③이 안 되면, 점검기록만 날아간 채 설비는 그대로 남습니다.
// 아무도 모릅니다. 몇 달 뒤에 "이 설비 점검 기록이 왜 없죠?" 로 발견됩니다.
//
// 트랜잭션은 이 세 문장을 **전부 되거나 전부 안 되게** 묶는 장치입니다.
//
// ★ 왜 06단원까지는 이걸 안 했나
//   PGlite 는 연결이 하나뿐입니다. 트랜잭션은 혼자서도 배울 수 있지만,
//   다음 개념부터 나오는 동시성은 연결이 둘 이상이어야 합니다.
//   그래서 07단원부터 Docker 로 진짜 PostgreSQL 서버를 씁니다.

import pg from "pg";

const 접속정보 = {
  host: "127.0.0.1",
  port: 5434, // ★ 5432 가 아닙니다. 이미 깔린 DB 와 안 부딪히게 비켜 놨습니다
  user: "factory",
  password: "secret",
  database: "factory_db",
};

// ★ Docker 가 안 떠 있으면 여기서 붙지 못합니다. 그때는 안내하고 곱게 끝냅니다.
let 연결;

try {
  연결 = new pg.Client(접속정보);
  await 연결.connect();
} catch (에러) {
  console.log("Docker Postgres 에 못 붙었습니다. 먼저 이걸 실행하세요:"); // 검증무시: Docker 가 없을 때만 나오는 안내입니다
  console.log("  docker compose up -d"); // 검증무시:
  console.log(`  (원인: ${에러.message})`); // 검증무시:
  process.exit(0);
}

// ★★ 07~10단원이 같은 데이터베이스를 씁니다.
//   단원끼리 표 이름이 부딪히지 않게 각 단원이 **자기 스키마**를 씁니다.
//   스키마(schema)는 표를 담는 폴더라고 생각하면 됩니다.
await 연결.query("CREATE SCHEMA IF NOT EXISTS 단원07");
await 연결.query("SET search_path TO 단원07");

// 여러 번 돌려도 같은 결과가 나오게 매번 새로 만듭니다.
await 연결.query("DROP TABLE IF EXISTS 폐기대장, 점검기록, 설비 CASCADE");

await 연결.query(`
  CREATE TABLE 설비 (
    번호 INT PRIMARY KEY,
    이름 TEXT NOT NULL,
    라인 TEXT NOT NULL,
    상태 TEXT NOT NULL DEFAULT '가동'
  )
`);

await 연결.query(`
  CREATE TABLE 점검기록 (
    번호 SERIAL PRIMARY KEY,
    설비번호 INT NOT NULL REFERENCES 설비(번호),
    내용 TEXT NOT NULL
  )
`);

await 연결.query(`
  CREATE TABLE 폐기대장 (
    번호 SERIAL PRIMARY KEY,
    설비이름 TEXT NOT NULL,
    사유 TEXT NOT NULL
  )
`);

await 연결.query(`
  INSERT INTO 설비 VALUES
    (1, '컨베이어 1호', 'A', '가동'),
    (2, '프레스 1호', 'B', '가동'),
    (3, '용접로봇 1호', 'C', '정지')
`);

await 연결.query(`
  INSERT INTO 점검기록 (설비번호, 내용) VALUES
    (1, '벨트 장력 점검'), (1, '모터 소음 확인'), (2, '유압 누유 점검')
`);

// 자주 쓸 것들을 짧은 함수로 만들어 둡니다.
const 한값 = async (문장, 값들 = []) => Object.values((await 연결.query(문장, 값들)).rows[0])[0];
const 설비수 = () => 한값("SELECT count(*) FROM 설비");
const 점검수 = () => 한값("SELECT count(*) FROM 점검기록");
const 대장수 = () => 한값("SELECT count(*) FROM 폐기대장");

console.log(`설비 ${await 설비수()}대 · 점검기록 ${await 점검수()}건 · 폐기대장 ${await 대장수()}건`);
// 출력: 설비 3대 · 점검기록 3건 · 폐기대장 0건

// ★ count(*) 가 문자열로 옵니다. 숫자가 아닙니다.
//   Postgres 의 count 는 BIGINT 인데, BIGINT 를 number 로 바꾸면 큰 수에서 값이 깨집니다.
//   그래서 드라이버가 안전하게 문자열로 줍니다. 계산하려면 Number() 로 바꾸세요.


// ── 섹션 1: ★ 트랜잭션 없이 폐기해 봅니다 ──

// 설비 1번(컨베이어 1호)을 폐기합니다. 세 문장입니다.
// 그런데 ③에서 실수를 합니다. 사유를 안 넣었습니다.

try {
  await 연결.query("DELETE FROM 점검기록 WHERE 설비번호 = 1"); // ① 점검기록 정리
  await 연결.query("DELETE FROM 설비 WHERE 번호 = 1"); // ② 설비 지우기
  await 연결.query("INSERT INTO 폐기대장 (설비이름) VALUES ('컨베이어 1호')"); // ③ 사유를 빠뜨렸습니다
} catch (에러) {
  console.log(`③ 에서 실패: ${에러.code} ${에러.message}`);
  // 출력: ③ 에서 실패: 23502 null value in column "사유" of relation "폐기대장" violates not-null constraint
}

console.log(`남은 것 — 설비 ${await 설비수()}대 · 점검기록 ${await 점검수()}건 · 폐기대장 ${await 대장수()}건`);
// 출력: 남은 것 — 설비 2대 · 점검기록 1건 · 폐기대장 0건

// ★★★ 이게 최악의 상태입니다.
//
//   설비는 지워졌습니다.         (되돌릴 수 없습니다)
//   점검기록도 지워졌습니다.     (되돌릴 수 없습니다)
//   폐기대장에는 없습니다.       (이 설비가 왜 사라졌는지 아무 기록이 없습니다)
//
//   ①②는 됐고 ③만 안 됐습니다. **반쯤 된 상태** 입니다.
//   에러 메시지는 ③ 이야기만 하지, ①②를 되돌려 주지 않습니다.
//
//   ★ 코드로 되돌리면 되지 않나요?
//     catch 안에서 다시 INSERT 하면 됩니다. 그런데
//       · 되돌리는 코드 자체가 실패하면?
//       · 되돌리는 중에 프로세스가 죽으면?
//       · SERIAL 로 매긴 점검기록 번호는 어떻게 되살리나요?
//     결국 데이터베이스가 해 줘야 합니다.

// 원상복구하고 다시 시작합니다.
await 연결.query("INSERT INTO 설비 VALUES (1, '컨베이어 1호', 'A', '가동')");
await 연결.query("INSERT INTO 점검기록 (설비번호, 내용) VALUES (1, '벨트 장력 점검'), (1, '모터 소음 확인')");


// ── 섹션 2: BEGIN · COMMIT · ROLLBACK ──

// 트랜잭션은 세 마디로 끝납니다.
//
//   BEGIN     여기서부터 한 덩어리
//   COMMIT    전부 확정
//   ROLLBACK  전부 없던 일로
//
// 같은 실수를 트랜잭션 안에서 해 봅니다.

await 연결.query("BEGIN");

try {
  await 연결.query("DELETE FROM 점검기록 WHERE 설비번호 = 1");
  await 연결.query("DELETE FROM 설비 WHERE 번호 = 1");
  await 연결.query("INSERT INTO 폐기대장 (설비이름) VALUES ('컨베이어 1호')"); // 또 빠뜨립니다
  await 연결.query("COMMIT");
} catch (에러) {
  console.log(`실패했으니 되돌립니다: ${에러.code}`);
  // 출력: 실패했으니 되돌립니다: 23502
  await 연결.query("ROLLBACK");
}

console.log(`되돌린 뒤 — 설비 ${await 설비수()}대 · 점검기록 ${await 점검수()}건 · 폐기대장 ${await 대장수()}건`);
// 출력: 되돌린 뒤 — 설비 3대 · 점검기록 3건 · 폐기대장 0건

// ★★ 아무것도 안 바뀌었습니다. 처음 그대로입니다.
//   DELETE 두 개가 분명히 성공했는데도 남아 있습니다.
//   트랜잭션 안에서 한 일은 COMMIT 전까지는 **아직 일어나지 않은 일** 입니다.

// 이번엔 제대로 해 봅니다.

await 연결.query("BEGIN");
await 연결.query("DELETE FROM 점검기록 WHERE 설비번호 = 1");
await 연결.query("DELETE FROM 설비 WHERE 번호 = 1");
await 연결.query("INSERT INTO 폐기대장 (설비이름, 사유) VALUES ('컨베이어 1호', '노후')");
await 연결.query("COMMIT");

console.log(`제대로 폐기 — 설비 ${await 설비수()}대 · 점검기록 ${await 점검수()}건 · 폐기대장 ${await 대장수()}건`);
// 출력: 제대로 폐기 — 설비 2대 · 점검기록 1건 · 폐기대장 1건

// 세 문장이 **전부** 됐습니다. 이제 되돌릴 수 없습니다. 그게 COMMIT 입니다.


// ── 섹션 3: ★ BEGIN 을 안 쓰면 — 자동 커밋 ──

// "그럼 지금까지 06단원에서 쓴 문장들은 트랜잭션이 아니었나요?"
// 아닙니다. **전부 트랜잭션이었습니다.**
//
//   ★ BEGIN 없이 보낸 문장은 그 문장 하나가 통째로 하나의 트랜잭션입니다.
//     보내는 순간 시작하고, 끝나는 순간 커밋합니다. 이걸 자동 커밋이라고 합니다.
//
// 그래서 UPDATE 한 줄이 반만 되는 일은 없습니다.
// 문제는 **여러 문장을 묶고 싶을 때** 생깁니다.
//
// 옆에서 지켜볼 두 번째 연결을 하나 만듭니다.

const 옆사람 = new pg.Client(접속정보);
await 옆사람.connect();
await 옆사람.query("SET search_path TO 단원07");

const 옆에서본상태 = async () =>
  (await 옆사람.query("SELECT 상태 FROM 설비 WHERE 번호 = 2")).rows[0].상태;

// 먼저 BEGIN 없이 바꿔 봅니다.
await 연결.query("UPDATE 설비 SET 상태 = '점검중' WHERE 번호 = 2");
console.log("BEGIN 없이 바꾼 직후, 옆사람 눈에는:", await 옆에서본상태());
// 출력: BEGIN 없이 바꾼 직후, 옆사람 눈에는: 점검중

// 이번엔 BEGIN 안에서 바꿉니다.
await 연결.query("BEGIN");
await 연결.query("UPDATE 설비 SET 상태 = '고장' WHERE 번호 = 2");

console.log("트랜잭션 안, 나에게는:", (await 연결.query("SELECT 상태 FROM 설비 WHERE 번호 = 2")).rows[0].상태);
// 출력: 트랜잭션 안, 나에게는: 고장

console.log("트랜잭션 안, 옆사람 눈에는:", await 옆에서본상태());
// 출력: 트랜잭션 안, 옆사람 눈에는: 점검중

await 연결.query("ROLLBACK");

console.log("롤백한 뒤, 나에게도:", (await 연결.query("SELECT 상태 FROM 설비 WHERE 번호 = 2")).rows[0].상태);
// 출력: 롤백한 뒤, 나에게도: 점검중

// ★★ 커밋하지 않은 변경은 **나만 보입니다.**
//   내 화면에서는 이미 '고장' 인데, 남의 화면에서는 아직 '점검중' 입니다.
//   이 성질에 이름이 붙어 있습니다. **격리성** 입니다. 개념03 에서 자세히 봅니다.


// ── 섹션 4: ACID 를 외우지 말고 눌러 봅니다 ──

// 트랜잭션의 성질을 네 글자로 줄여 ACID 라고 부릅니다.
// 시험에는 나오지만 외워도 쓸모가 없습니다. 하나씩 실제로 확인합니다.

// ── A · 원자성(Atomicity) — 전부 되거나 전부 안 되거나 ──
// 섹션 2 에서 이미 봤습니다. 다시 한 번 짧게 확인합니다.

const 폐기전설비수 = Number(await 설비수());

await 연결.query("BEGIN");
await 연결.query("DELETE FROM 설비 WHERE 번호 = 3");
await 연결.query("ROLLBACK");

console.log("A · 지웠다 되돌린 뒤 설비 수가 그대로인가:", Number(await 설비수()) === 폐기전설비수);
// 출력: A · 지웠다 되돌린 뒤 설비 수가 그대로인가: true

// ── C · 일관성(Consistency) — 규칙을 어긴 채로는 커밋이 안 됩니다 ──
// 설비 2번에는 점검기록이 달려 있습니다. 외래키가 막습니다.

await 연결.query("BEGIN");

try {
  await 연결.query("DELETE FROM 설비 WHERE 번호 = 2");
  await 연결.query("COMMIT");
  console.log("C · 지워졌습니다"); // 검증무시: 여기까지 오면 외래키가 없다는 뜻입니다
} catch (에러) {
  console.log(`C · 규칙이 막았습니다: ${에러.code} — ${에러.detail}`);
  // 출력: C · 규칙이 막았습니다: 23503 — Key (번호)=(2) is still referenced from table "점검기록".
  await 연결.query("ROLLBACK");
}

// ★ 04단원에서 만든 외래키가 여기서 일합니다.
//   제약이 없으면 트랜잭션이 있어도 이상한 데이터가 그대로 커밋됩니다.
//   **트랜잭션은 규칙을 지켜 주지 않습니다. 규칙을 어기면 막아 줄 뿐입니다.**

// ── I · 격리성(Isolation) — 남의 미완성이 나에게 안 보입니다 ──
// 섹션 3 에서 봤습니다. 커밋 전에는 옆사람에게 '점검중' 으로 보였습니다.

await 연결.query("BEGIN");
await 연결.query("UPDATE 설비 SET 이름 = '없는이름' WHERE 번호 = 2");
const 남에게보이나 = (await 옆사람.query("SELECT 이름 FROM 설비 WHERE 번호 = 2")).rows[0].이름;
await 연결.query("ROLLBACK");

console.log("I · 커밋 전 변경이 남에게 보이나:", 남에게보이나 === "없는이름");
// 출력: I · 커밋 전 변경이 남에게 보이나: false

// ── D · 지속성(Durability) — 커밋한 것은 살아남습니다 ──
// 연결을 끊고 새로 붙어도 남아 있어야 합니다. 프로세스가 죽었다 살아난 셈입니다.

await 연결.query("BEGIN");
await 연결.query("UPDATE 설비 SET 상태 = '폐기예정' WHERE 번호 = 3");
await 연결.query("COMMIT");

await 옆사람.end(); // 연결을 진짜로 끊습니다

const 새사람 = new pg.Client(접속정보);
await 새사람.connect();
await 새사람.query("SET search_path TO 단원07");

const 살아남았나 = (await 새사람.query("SELECT 상태 FROM 설비 WHERE 번호 = 3")).rows[0].상태;
console.log("D · 연결을 끊었다 새로 붙어도 남아 있나:", 살아남았나);
// 출력: D · 연결을 끊었다 새로 붙어도 남아 있나: 폐기예정

// ★ 지속성은 "커밋했다고 대답했으면 정전이 나도 남는다" 는 약속입니다.
//   Postgres 는 데이터 파일을 고치기 **전에** 변경 내역을 WAL 이라는 기록장에 먼저 씁니다.
//   그래서 갑자기 꺼져도 다시 켤 때 WAL 을 읽어 복구합니다. 10단원에서 다시 봅니다.


// ── 섹션 5: ★★ 에러가 난 트랜잭션은 그 뒤로 아무것도 못 합니다 ──

// 여기서 사람들이 가장 많이 넘어집니다.

await 연결.query("BEGIN");

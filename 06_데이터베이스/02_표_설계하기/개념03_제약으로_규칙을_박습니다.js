//     그냥 ADD CONSTRAINT 를 하면 표 전체를 훑는 동안 **표가 잠깁니다.**
//     NOT VALID 로 먼저 걸고, 한가한 시간에 VALIDATE 하는 게 정석입니다.
//
// ── MySQL 은 여기가 다릅니다 ──
//   · CHECK 는 MySQL 8.0.16 부터 진짜로 동작합니다. 그 전 버전은 **무시했습니다**

// 개념02 에서 타입이 첫 번째 문지기라고 했습니다.
// 그런데 타입만으로는 부족합니다.
//
//   라인 TEXT   →  'A' 도 되고 '999' 도 되고 '' 도 됩니다
//   상태 TEXT   →  '가동' 도 되고 '가둥' 도 됩니다
//   설비번호 INT →  비워 둬도 되고, 같은 번호가 열 개 있어도 됩니다
//
// 이걸 막는 것이 **제약(constraint)** 입니다.
//
// ★ 이 개념의 핵심 메시지는 하나입니다.
//
//     제약을 걸면 **애플리케이션 코드가 줄어듭니다.**
//
//   "DB 는 저장만 하고 검사는 코드에서" 라고 생각하기 쉽습니다.
//   그러면 검사 코드를 곳곳에 복사하게 되고, 언젠가 한 군데를 빠뜨립니다.
//   그날부터 쓰레기 데이터가 들어옵니다. 그리고 아무도 모릅니다.

import { PGlite } from "@electric-sql/pglite";

const db = await PGlite.create();


// ── 섹션 1: 제약이 없으면 무엇이 들어오나 ──

// 진짜로 넣어 봅니다. 하나도 안 막힙니다.

await db.exec(`
  CREATE TABLE 느슨한설비 (
    설비번호 INT,
    이름 TEXT,
    라인 TEXT,
    상태 TEXT,
    도입일 DATE
  );
`);

await db.exec(`
  INSERT INTO 느슨한설비 VALUES
    (1, '컨베이어 1호', 'A', '가동', '2020-01-05'),
    (1, '컨베이어 1호', 'A', '가동', '2020-01-05'),
    (NULL, NULL, '999', '가둥', NULL),
    (3, '', '', ' ', '1899-01-01');
`);

const 쓰레기 = (await db.query(`
  SELECT 설비번호, 이름, 라인, 상태 FROM 느슨한설비 ORDER BY 설비번호 NULLS LAST, 이름
`)).rows;

for (const 줄 of 쓰레기) {
  console.log(JSON.stringify(줄));
}
// 출력: {"설비번호":1,"이름":"컨베이어 1호","라인":"A","상태":"가동"}
// 출력: {"설비번호":1,"이름":"컨베이어 1호","라인":"A","상태":"가동"}
// 출력: {"설비번호":3,"이름":"","라인":"","상태":" "}
// 출력: {"설비번호":null,"이름":null,"라인":"999","상태":"가둥"}

// ★★★ 네 줄 전부 문제가 있습니다.
//
//   · 1번이 두 번 — 같은 설비가 두 대인지, 실수로 두 번 넣은 건지 알 수 없습니다
//   · 3번은 이름이 **빈 문자열** — 화면에 아무것도 안 나옵니다
//   · 3번의 상태는 **공백 한 칸** — `상태 === '가동'` 도 아니고 빈 문자열도 아닙니다
//   · NULL 줄은 번호도 이름도 없습니다 — 지울 수도 없습니다 (뭘로 찾나요?)
//   · 라인 '999' 는 존재하지 않는 라인입니다
//   · '가둥' 은 오타입니다. 상태별 집계에서 이것만 빠집니다
//
// ★ 이 데이터는 **한 달 뒤에 발견됩니다.** 그때는 이미 수만 건이 섞여 있습니다.
//   그리고 어느 게 진짜인지 아무도 모릅니다.


// ── 섹션 2: ★ 같은 검사를 코드로 하면 vs 제약으로 하면 ──

// 위 데이터를 막는 검사 코드를 자바스크립트로 써 봅니다.

const 라인목록 = ["A", "B", "C"];
const 상태목록 = ["가동", "정지", "점검", "고장"];

function 설비검사(설비, 이미있는번호, 이미있는이름) {
  if (설비.설비번호 === null || 설비.설비번호 === undefined) return "설비번호는 필수입니다";
  if (!Number.isInteger(설비.설비번호)) return "설비번호는 정수여야 합니다";
  if (이미있는번호.has(설비.설비번호)) return "이미 있는 설비번호입니다";

  if (typeof 설비.이름 !== "string" || 설비.이름.trim() === "") return "이름은 필수입니다";
  if (설비.이름.length > 20) return "이름이 너무 깁니다";
  if (이미있는이름.has(설비.이름)) return "이미 있는 이름입니다";

  if (!라인목록.includes(설비.라인)) return "라인은 A, B, C 중 하나여야 합니다";
  if (!상태목록.includes(설비.상태)) return "상태 값이 올바르지 않습니다";
  if (설비.가격 !== null && 설비.가격 !== undefined && Number(설비.가격) <= 0) return "가격은 0보다 커야 합니다";

  return null;
}

console.log("검사 함수 줄 수: 약 15줄");
// 출력: 검사 함수 줄 수: 약 15줄

// ★ 문제는 줄 수가 아닙니다. **이 함수를 부르는 걸 잊는 순간 뚫린다**는 것입니다.
//
//   · 관리자 화면에서 넣을 때 → 부름
//   · 엑셀 일괄 등록에서 → 깜빡함
//   · 배치 스크립트에서 → 몰랐음
//   · 개발자가 psql 로 직접 → 당연히 안 부름
//
//   그리고 `이미있는번호` 를 미리 조회해 오는 것도 **경쟁 조건**이 있습니다.
//   두 사람이 동시에 같은 번호를 넣으면 둘 다 "없네" 하고 통과합니다.
//   01단원 섹션 2 에서 본 그 문제입니다.
//
// ★★ 같은 규칙을 제약으로 쓰면 이렇습니다.

await db.exec(`
  CREATE TABLE 설비 (
    설비번호 INT      PRIMARY KEY,
    이름     TEXT     NOT NULL UNIQUE CHECK (char_length(이름) BETWEEN 1 AND 20),
    라인     TEXT     NOT NULL CHECK (라인 IN ('A','B','C')),
    상태     TEXT     NOT NULL DEFAULT '정지'
                     CONSTRAINT 상태_확인 CHECK (상태 IN ('가동','정지','점검','고장')),
    도입일   DATE     NOT NULL DEFAULT CURRENT_DATE,
    가격     NUMERIC(12,2) CHECK (가격 > 0)
  );
`);

console.log("제약으로 쓴 줄 수: 8줄 (표 정의에 포함)");
// 출력: 제약으로 쓴 줄 수: 8줄 (표 정의에 포함)

// ★★★ 그리고 이건 **누가 어떤 경로로 넣든** 통합니다.
//   관리자 화면이든, 배치든, psql 이든, 동시에 열 명이 들어와도 뚫리지 않습니다.
//   `이미있는번호` 를 미리 조회할 필요도 없습니다. DB 가 원자적으로 처리합니다.
//
// ★ 그렇다고 자바스크립트 검사를 없애라는 말이 아닙니다.
//   화면에서 "이름을 입력하세요" 를 바로 띄우려면 앞단 검사가 필요합니다.
//
//   앞단 검사  = **친절**을 위한 것 (빠른 안내)
//   제약       = **정확**을 위한 것 (마지막 방어선)
//
//   앞단 검사는 빠뜨려도 데이터는 안전합니다. 제약을 빠뜨리면 안전하지 않습니다.
//   ★ 그래서 **제약이 먼저**입니다.


// ── 섹션 3: 하나씩 걸어 봅니다 ──

const 넣기 = async (설명, sql, 값들) => {
  try {
    await db.query(sql, 값들);
    console.log(`${설명} — 들어감`);
  } catch (에러) {
    console.log(`${설명} — ${에러.code} ${에러.constraint ?? "(이름없음)"}`);
  }
};

await 넣기("정상", `INSERT INTO 설비 (설비번호,이름,라인) VALUES (1,'컨베이어 1호','A')`);
// 출력: 정상 — 들어감

await 넣기("이름이 NULL", `INSERT INTO 설비 (설비번호,이름,라인) VALUES (2,NULL,'A')`);
// 출력: 이름이 NULL — 23502 (이름없음)

await 넣기("이름 중복", `INSERT INTO 설비 (설비번호,이름,라인) VALUES (2,'컨베이어 1호','A')`);
// 출력: 이름 중복 — 23505 설비_이름_key

await 넣기("설비번호 중복", `INSERT INTO 설비 (설비번호,이름,라인) VALUES (1,'프레스 1호','A')`);
// 출력: 설비번호 중복 — 23505 설비_pkey

await 넣기("라인이 999", `INSERT INTO 설비 (설비번호,이름,라인) VALUES (3,'프레스 1호','999')`);
// 출력: 라인이 999 — 23514 설비_라인_check

await 넣기("상태 오타 '가둥'", `INSERT INTO 설비 (설비번호,이름,라인,상태) VALUES (4,'용접로봇 1호','B','가둥')`);
// 출력: 상태 오타 '가둥' — 23514 상태_확인

await 넣기("이름이 빈 문자열", `INSERT INTO 설비 (설비번호,이름,라인) VALUES (5,'','C')`);
// 출력: 이름이 빈 문자열 — 23514 설비_이름_check

await 넣기("가격이 음수", `INSERT INTO 설비 (설비번호,이름,라인,가격) VALUES (6,'절단기 1호','C',-100)`);
// 출력: 가격이 음수 — 23514 설비_가격_check

// ★ 섹션 1 의 쓰레기가 **전부 막혔습니다.** 자바스크립트 코드는 한 줄도 안 썼습니다.


// ── 섹션 4: 제약 다섯 가지 ──

// ① NOT NULL — 비워 둘 수 없다
//
//     이름 TEXT NOT NULL
//
//   ★ 가장 자주 쓰고, 가장 자주 빠뜨립니다.
//     의심스러우면 **일단 NOT NULL 을 걸고**, 정말 모를 수 있는 값만 푸세요.
//     나중에 푸는 것은 쉽고, 나중에 거는 것은 어렵습니다. (섹션 7 에서 봅니다)
//
// ② UNIQUE — 같은 값이 두 번 오면 안 된다
//
//     이름 TEXT UNIQUE
//     UNIQUE (라인, 이름)      ← 두 칸을 묶어서도 됩니다
//
//   ★★ UNIQUE 는 **NULL 을 여러 개 허용합니다.** 개념05 에서 실측합니다
//
// ③ CHECK — 이 조건이 참이어야 한다
//
//     CHECK (라인 IN ('A','B','C'))
//     CHECK (가격 > 0)
//     CHECK (종료일 >= 시작일)              ← 칸끼리 비교도 됩니다
//     CHECK (char_length(이름) BETWEEN 1 AND 20)
//
// ④ DEFAULT — 안 적으면 이 값을 넣어라
//
//     상태 TEXT NOT NULL DEFAULT '정지'
//     등록시각 TIMESTAMPTZ NOT NULL DEFAULT now()
//
// ⑤ PRIMARY KEY — 이 줄을 가리키는 번호
//
//     설비번호 INT PRIMARY KEY     ← NOT NULL + UNIQUE 를 한꺼번에
//
//   개념04 에서 따로 다룹니다. 여기서는 "NOT NULL + UNIQUE" 로만 알아 두세요.
//
// ★ DEFAULT 를 확인해 봅니다. 상태와 도입일을 안 적었는데 채워졌습니다.

const 기본값들 = (await db.query(`SELECT 상태, 도입일::text AS 도입일 FROM 설비 WHERE 설비번호 = 1`)).rows[0];
console.log("안 적은 상태:", 기본값들.상태);
// 출력: 안 적은 상태: 정지
console.log("안 적은 도입일:", 기본값들.도입일);
// 출력?: 안 적은 도입일: 2026-08-26
console.log("도입일이 오늘인가:", 기본값들.도입일 === new Date().toLocaleDateString("en-CA"));
// 출력: 도입일이 오늘인가: true

// ★★ 함정: **NULL 을 직접 적으면 DEFAULT 가 안 먹습니다.**

await db.exec(`CREATE TABLE 기본값시험 (a TEXT DEFAULT '정지')`);
await db.exec(`INSERT INTO 기본값시험 DEFAULT VALUES`);
await db.exec(`INSERT INTO 기본값시험 (a) VALUES (NULL)`);

const 둘 = (await db.query(`SELECT a FROM 기본값시험 ORDER BY a NULLS LAST`)).rows;
console.log("안 적었을 때:", JSON.stringify(둘[0].a), "· NULL 을 적었을 때:", JSON.stringify(둘[1].a));
// 출력: 안 적었을 때: "정지" · NULL 을 적었을 때: null

// ★ 자바스크립트에서 `{ 상태: null }` 을 그대로 넘기면 DEFAULT 를 지나칩니다.
//   `undefined` 를 넘겨서 그 칸을 아예 빼거나, NOT NULL 을 같이 걸어 두세요.
//   ★ 그래서 DEFAULT 는 거의 항상 **NOT NULL 과 짝으로** 씁니다.


// ── 섹션 5: CHECK 와 NULL — ★ 여기서 많이 틀립니다 ──

await db.exec(`CREATE TABLE 널시험 (가격 NUMERIC CHECK (가격 > 0))`);

await 넣기("가격 100", `INSERT INTO 널시험 VALUES (100)`);
// 출력: 가격 100 — 들어감
await 넣기("가격 -1", `INSERT INTO 널시험 VALUES (-1)`);
// 출력: 가격 -1 — 23514 널시험_가격_check
await 넣기("가격 NULL", `INSERT INTO 널시험 VALUES (NULL)`);
// 출력: 가격 NULL — 들어감

// ★★★ NULL 이 통과했습니다. `NULL > 0` 이 거짓이 아니라 **모름(UNKNOWN)** 이기 때문입니다.
//   CHECK 는 "거짓일 때만" 막습니다. 모름은 통과시킵니다.
//
//   그래서 **CHECK 는 NULL 을 막지 않습니다.**
//   비워 두면 안 되는 칸이면 `NOT NULL` 을 따로 걸어야 합니다.
//
//   이 3값 논리는 개념05 에서 제대로 팝니다. 지금은 이것만 기억하세요.
//     **CHECK 와 NOT NULL 은 서로 다른 일을 합니다.**


// ── 섹션 6: ★ 이름 붙인 제약 — 에러를 사용자에게 보여 주려면 ──

// 위에서 이름 없이 만든 제약은 Postgres 가 알아서 이름을 붙였습니다.

const 제약들 = await db.query(`
  SELECT conname, contype, pg_get_constraintdef(oid) AS 정의
  FROM pg_constraint WHERE conrelid = '설비'::regclass AND contype IN ('c','u','p')
  ORDER BY contype, conname
`);

for (const 제약 of 제약들.rows) {
  console.log(`[${제약.contype}] ${제약.conname}`);
}
// 출력: [c] 상태_확인
// 출력: [c] 설비_가격_check
// 출력: [c] 설비_라인_check
// 출력: [c] 설비_이름_check
// 출력: [p] 설비_pkey
// 출력: [u] 설비_이름_key

// ★ contype: c = CHECK, p = PRIMARY KEY, u = UNIQUE, f = 외래키(04단원)
//
// ★★ `상태_확인` 만 우리가 붙인 이름입니다. 나머지는 자동 생성입니다.
//   자동 이름 규칙: `표_칸_check` / `표_칸_key` / `표_pkey`
//
//   자동 이름도 쓸 수는 있습니다. 그런데 **칸 이름을 바꾸면 제약 이름은 안 바뀝니다.**
//   그러면 코드의 `if (e.constraint === "설비_라인_check")` 가 조용히 헛돕니다.
//
//   ★ 사용자에게 메시지를 보여 줄 제약은 **이름을 직접 붙이세요.**
//
// 이제 에러를 사용자 말로 바꿔 봅니다. 이게 제약을 쓰는 진짜 이유입니다.

const 메시지 = {
  설비_pkey: "이미 등록된 설비번호입니다.",
  설비_이름_key: "같은 이름의 설비가 이미 있습니다.",
  설비_라인_check: "라인은 A, B, C 중에서 고르세요.",
  상태_확인: "상태는 가동 · 정지 · 점검 · 고장 중 하나여야 합니다.",
  설비_이름_check: "이름은 1자 이상 20자 이하여야 합니다.",
  설비_가격_check: "가격은 0보다 커야 합니다.",
};

function 사람말로(에러) {
  if (에러.code === "23502") return `${에러.column} 은(는) 반드시 입력해야 합니다.`;
  if (메시지[에러.constraint]) return 메시지[에러.constraint];
  if (에러.code === "22P02") return "숫자를 넣어야 할 칸에 글자가 들어왔습니다.";
  return "저장하지 못했습니다. 입력을 확인해 주세요.";
}

const 보여주기 = async (sql) => {
  try {
    await db.query(sql);
    console.log("저장했습니다");
  } catch (에러) {
    console.log(사람말로(에러));
  }
};

await 보여주기(`INSERT INTO 설비 (설비번호,이름,라인) VALUES (7,NULL,'A')`);
// 출력: 이름 은(는) 반드시 입력해야 합니다.

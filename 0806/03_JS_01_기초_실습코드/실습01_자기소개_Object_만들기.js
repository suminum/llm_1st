// ── 실습: 자기소개 Object 만들기 ──────────────
console.log("===== 실습: 자기소개 Object 만들기 =====");
// 문제: 각자를 소개할 수 있는 Object 형태의 변수를 선언하고,
//       지금까지 배운 데이터(문자열·숫자·불린·배열)를 사용하여
//       자신을 소개하는 console.log를 만드세요.
// Step 1: 여러 자료형을 담은 자기소개 객체 선언 (각자 자신의 정보로!)
// 이 실습의 목적: 오늘 배운 자료형 네 가지를 한 객체 안에 모두 담아 보는 것.
// 값의 종류에 따라 따옴표·괄호가 달라지는 데 주목하세요.
const me = {
  name: "김철수",                    // String  — 글자라서 따옴표
  age: 25,                           // Number  — 숫자라서 따옴표 없음 ("25"면 글자가 됨)
  isStudent: true,                   // Boolean — true/false는 따옴표 없는 예약어
  hobbies: ["등산", "게임", "독서"], // Array   — 여러 개라서 대괄호로 묶음
};
// 객체 안에 배열이 들어갈 수 있다는 점이 핵심입니다.
// 실무 데이터는 대부분 이런 중첩 구조입니다 (12일차 JSON에서 그대로 다시 만납니다).
// Step 2: 객체 전체와 개별 값 확인 (점 표기법)
console.log(me);
// 출력: {
// 출력:   name: '김철수',
// 출력:   age: 25,
// 출력:   isStudent: true,
// 출력:   hobbies: [ '등산', '게임', '독서' ]
// 출력: }
// Step 3: 템플릿 리터럴로 소개 문구 완성
console.log(`안녕하세요, 저는 ${me.age}살 ${me.name}입니다.`);
// 출력: 안녕하세요, 저는 25살 김철수입니다.
console.log(`취미는 ${me.hobbies[0]}이고, 학생 여부는 ${me.isStudent}입니다.`);
// 출력: 취미는 등산이고, 학생 여부는 true입니다.
// me.hobbies[0] 읽는 순서: me에서 hobbies 배열을 꺼내고 → 그 배열의 0번째를 꺼냄
// 점(.)은 객체에서 이름으로, 대괄호([])는 배열에서 순서로 — 두 문법이 이어져 있습니다.

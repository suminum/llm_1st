// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션07_Number_숫자.js 로 실행하며 결과를 확인합니다.

// ── 섹션 7: Number 숫자 ──────────────
console.log("===== 섹션 7: Number 숫자 =====");
// 다른 언어(Java, C 등)는 정수용 int, 실수용 double을 따로 씁니다.
// JS는 그 구분이 없어서 정수든 소수든 전부 number 하나입니다 — 배우기는 편하지만,
// 그 대신 10 / 3 이 3으로 안 잘리고 3.3333... 이 됩니다 (섹션 13 참고).
// [기본] 정수와 실수를 구분하지 않는 하나의 숫자 타입
let count = 123;         // 따옴표가 없다는 점에 주목 — "123"은 글자, 123은 숫자
let opacity = 0.7;
console.log(count);      // 출력: 123
console.log(opacity);    // 출력: 0.7

// [다른 방법] 특수값: 계산 불가 NaN / 0으로 나누면 Infinity
console.log("abc" * 2);  // 출력: NaN (숫자로 계산할 수 없음)
// NaN = Not a Number("숫자가 아님"). 에러로 멈추지 않고 NaN이라는 값을 돌려주는 게 함정입니다.
// 계산 결과가 NaN이면 "어딘가에서 글자를 숫자처럼 계산했다"는 신호 —
// 대개 입력값을 Number()로 변환하지 않은 것이 원인입니다 (섹션 12).
console.log(1 / 0);      // 출력: Infinity
// 수학에서는 정의할 수 없지만 JS는 "무한대"라는 값을 돌려줍니다. 이것도 에러가 아닙니다.

// [기본] 따옴표 하나로 완전히 다른 값이 됩니다
console.log(123 + 1);      // 출력: 124    숫자라서 더해짐
console.log("123" + 1);    // 출력: 1231   글자라서 이어 붙음
// 화면 입력창에서 받은 값은 숫자를 쳐도 항상 문자열입니다.
// 그래서 계산 전에 숫자로 바꿔야 하고, 그 방법이 섹션 12(형 변환)입니다.

// [다른 방법] NaN인지 확인하기 — 특이하게도 === 로는 못 잡습니다
console.log(NaN === NaN);       // 출력: false  (자기 자신과도 같지 않은 유일한 값)
console.log(Number.isNaN(NaN)); // 출력: true   확인은 이 함수로 합니다

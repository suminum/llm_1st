// ── 섹션 13: 산술 연산자 ──────────────
console.log("===== 섹션 13: 산술 연산자 =====");
// 앞 섹션(형 변환)에서 미리 쓴 + - / 를 여기서 정식으로 정리합니다.
// 1 + "2" 가 왜 "12"였는지도 여기까지 오면 완전히 이해됩니다 —
// + 는 원래 숫자를 더하는 기호인데, 한쪽이 문자열이면 "이어 붙이기"로 뜻이 바뀌기 때문입니다.
// [기본] 6가지 기본 산술 연산자: + - * / % **
console.log(7 + 3);   // 출력: 10
console.log(7 - 3);   // 출력: 4
console.log(7 * 3);   // 출력: 21  (곱하기는 x 가 아니라 별표 *)

console.log(10 / 3);  // 출력: 3.3333333333333335
// 나눗셈이 딱 떨어지지 않습니다. JS에는 "정수 타입"이 따로 없어서
// 10 / 3 을 3으로 잘라 주지 않고 소수점까지 계산합니다.
// 게다가 컴퓨터는 소수를 2진수로 근사 저장해서 ...35 같은 꼬리가 붙습니다.
// (0.1 + 0.2 가 0.30000000000000004 로 나오는 것도 같은 이유)
// 몫만 필요하면 Math.floor(10 / 3) → 3 을 씁니다.
// 실무 한 줄: 이 오차 때문에 돈 계산에 소수를 그대로 쓰면 안 됩니다.
//   금액은 원 단위 정수로 다루거나 전용 라이브러리를 씁니다.

console.log(10 % 3);  // 출력: 1 (나머지)
// % 는 "나누고 남은 것". 10 안에 3이 3번 들어가고 1이 남습니다.
// 나머지는 "몇으로 나누든 0 ~ (그 수-1) 사이"라서, 값을 일정 범위로 가두는 데 씁니다.
//   시계: 25시 % 24 → 1시   /  요일: 10일째 % 7 → 3번째 요일

console.log(2 ** 8);  // 출력: 256 (거듭제곱)
// ** 는 별표 두 개. 2 ** 8 = 2를 8번 곱하기 = 2x2x2x2x2x2x2x2 = 256
// (2 * 8 = 16 과 헷갈리지 않도록 주의)

// [다른 방법] 나머지 %의 실용적 활용 - 홀수·짝수 판별
// 어떤 수든 2로 나눈 나머지는 0 아니면 1뿐입니다 → 짝수·홀수 판별의 표준 공식
console.log(4 % 2 === 0);  // 출력: true (짝수)   4를 2로 나누면 남는 게 없음
console.log(7 % 2 === 0);  // 출력: false (홀수)  7을 2로 나누면 1이 남음
// 응용: n % 3 === 0 이면 3의 배수, n % 5 === 0 이면 5의 배수 (9일차 실습에서 사용)
// 4일차에 쓴 CSS의 nth-child(even / odd)와 같은 발상입니다 —
// 표의 줄무늬를 만들 때 CSS가 속으로 하던 일을 이제 우리가 직접 하는 것입니다.

// ── 섹션 2: 주석과 표기법 ──────────────
console.log("===== 섹션 2: 주석과 표기법 =====");
// 주석 = 컴퓨터는 무시하고 사람만 읽는 줄. 두 가지 용도로 씁니다:
//   ① 설명 남기기  ② 코드를 지우지 않고 잠깐 꺼 두기 (디버깅할 때 계속 씁니다)
// 단축키 Ctrl + / (Mac은 Cmd + /) — 커서를 놓고 누르면 그 줄이 켜졌다 꺼졌다 합니다.
// 여러 줄을 드래그하고 누르면 한 번에 처리됩니다. 2일차 HTML에서 쓰던 그 단축키입니다.
// [기본] 한 줄 주석은 // 로 시작
/*
 * 여러 줄 주석은 이렇게 감쌉니다.
 * # 메모1
 * # 메모2
 */
// 변수 이름은 띄어쓰기를 쓸 수 없어서(user name ✕), 단어를 붙이는 규칙이 필요합니다.
// 그 규칙이 표기법이고, 언어마다·용도마다 관습이 다릅니다.
let userName = "홍길동";  // camelCase: JS 변수·함수의 기본 표기
//  └ 첫 단어는 소문자, 다음 단어부터 첫 글자를 대문자로 (userName, maxCount)
//    가운데가 낙타 등처럼 솟았다고 해서 낙타(camel) 표기법
const MAX_COUNT = 100;    // 대문자 snake_case: 상수 표기 (다른 개발자도 한눈에 알 수 있게)
//    └ 전부 대문자 + 밑줄로 연결. 대문자만 봐도 "바뀌지 않는 값"임을 알 수 있음
console.log(userName, MAX_COUNT); // 출력: 홍길동 100
// 규칙을 지켜도 안 지켜도 코드는 똑같이 돌아갑니다.
// 지키는 이유는 "사람이 읽기 위해서" — 협업할 때 이름만 보고 역할을 짐작할 수 있습니다.
// 실수: let my-name = "홍길동";  // dash-case(하이픈)는 JS 변수명 불가 - HTML/CSS 클래스·파일명용
// 실수: let 1stName = "홍길동";  // 첫 글자는 숫자가 될 수 없음
// 실수: let let = "예약어";      // 예약어(let, if 등)는 변수 이름으로 사용 불가
// 참고: PascalCase(UserProfile)는 클래스·생성자 함수에 사용

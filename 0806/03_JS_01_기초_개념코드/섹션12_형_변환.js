// ── 섹션 12: 형 변환 ──────────────
console.log("===== 섹션 12: 형 변환 =====");
// ※ 이 섹션은 + - * / 를 써서 설명합니다. 연산자는 다음 섹션(13~15)에서 정식으로 배웁니다.
//   지금은 "계산기와 같은 기호"라고만 알고 넘어가면 됩니다.
//
// 형 변환 = 자료형을 바꾸는 것. JS는 타입이 안 맞아도 에러를 내지 않고
// "알아서 맞춰 주는" 언어라서, 도움이 될 때도 있지만 조용히 틀린 답을 주기도 합니다.
// [기본] 암묵적 형변환 - 타입이 다르면 JS가 자동 변환 (양날의 검!)
console.log(1 + "2");             // 출력: 12 (숫자+문자 -> 문자열 연결)
// + 는 두 가지 뜻(더하기·이어붙이기)이 있어서, 한쪽이 문자열이면 이어붙이기가 이깁니다.
// 1이 "1"로 바뀌어 "1" + "2" = "12" — 3이 아닙니다!
console.log("10" - 5);            // 출력: 5 (문자-숫자 -> 숫자로 변환 후 계산)
// - 는 뺄셈이라는 뜻 하나뿐이라 "10"을 숫자 10으로 바꿔서 계산합니다.
// 즉 + 만 유독 다르게 동작합니다 — 이 비대칭이 초보자를 가장 많이 괴롭힙니다.
console.log(true + 1);            // 출력: 2 (true는 1, false는 0으로 변환)
// [기본] 명시적 형변환 - 개발자가 직접 변환 (권장)
console.log(String(123));         // 출력: 123 (문자열 "123"이 됨)
console.log(Number("123") + 1);   // 출력: 124
console.log(Number("abcdefg"));   // 출력: NaN (숫자로 바꿀 수 없음)
// [다른 방법] parseInt / parseFloat / Boolean
console.log(parseInt("42px"));      // 출력: 42 (정수만 추출)
console.log(parseFloat("3.14kg"));  // 출력: 3.14 (실수만 추출)
// ★ Number()와의 차이를 여기서 확실히 하고 넘어가세요:
//     Number("42px")   →  NaN   (전체가 숫자여야 함 — 하나라도 글자가 섞이면 실패)
//     parseInt("42px") →  42    (앞에서부터 숫자만 뽑고 나머지는 버림)
//   그래서 "42px" 같은 CSS 값을 다룰 때는 parseInt를 씁니다.
//   반대로 "숫자만 들어와야 한다"를 검사하고 싶으면 Number()가 맞습니다(NaN이면 잘못된 입력).
console.log(Boolean(0));            // 출력: false
// 실수: ("80" + "50") / 2  // "8050" / 2 = 4025 -> 계산 전에 Number()로 변환해야 함

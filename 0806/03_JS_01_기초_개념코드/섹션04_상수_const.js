// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션04_상수_const.js 로 실행하며 결과를 확인합니다.

// ── 섹션 4: 상수 const (그리고 var를 피하는 이유) ──────────────
console.log("===== 섹션 4: 상수 const =====");
// [기본] const는 재할당 불가 - "이 값은 변하지 않는다"는 의도를 코드에 명시
const PI = 3.14;
console.log(PI);     // 출력: 3.14
// 이름을 대문자로 쓴 이유: 섹션 2에서 배운 상수 표기 관례입니다.
// 문법이 강제하는 건 아니지만, 대문자만 봐도 "안 바뀌는 값"임을 알 수 있습니다.

// 실수: PI = 3.15;             // TypeError: Assignment to constant variable.
//       "상수에 대입했다"는 뜻입니다. 에러 메시지가 원인을 그대로 말해 줍니다.
// 실수: const WIDTH;           // const는 선언 시 반드시 값을 초기화해야 함
// 실수: var name = "홍길동"; var name = "나비";  // var는 재선언을 허용해 덮어쓰기 버그 유발 -> 사용 금지
// [다른 방법] const 배열·객체의 "내부"는 변경 가능 (메모리 주소만 고정)
// 헷갈리는 지점입니다. const가 잠그는 것은 "값"이 아니라 "연결"입니다.
// 집 주소를 적은 쪽지로 비유하면 —
//   const는 쪽지에 적힌 주소를 못 바꾸게 할 뿐, 그 집 안의 가구는 얼마든지 옮길 수 있습니다.
//   colors = ["blue"]  ✕ 다른 집 주소로 교체 → 금지
//   colors.push("blue") ○ 같은 집 안에 물건 추가 → 허용
const colors = ["red"];
colors.push("blue");  // 내용 추가는 허용 (push 같은 "메서드"는 10일차 — 지금은 '추가 명령' 정도로)
console.log(colors);  // 출력: [ 'red', 'blue' ]
// 선택 원칙: 기본은 const -> 값이 반드시 바뀌면 let -> var는 사용하지 않음
// 실제 코드의 8~9할이 const입니다. 반복문 카운터처럼 정말 바뀌는 것만 let을 씁니다.
// const를 기본으로 쓰는 이유 두 가지:
//   ① "이 값은 안 바뀐다"가 코드에 적혀 있으면 읽는 사람이 그만큼 덜 의심해도 됩니다
//   ② 실수로 덮어쓰는 사고를 컴퓨터가 대신 막아 줍니다 (위 TypeError)

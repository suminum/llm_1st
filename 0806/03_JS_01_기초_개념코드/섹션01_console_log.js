// 03_JS_01_기초 개념코드 — 섹션 1. console.log — 값을 출력하는 기본 도구 (JavaScript)
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션01_console_log.js 로 실행하며 결과를 확인합니다.

// ── 섹션 1: console.log — 값을 출력하는 기본 도구 ──────────────
console.log("===== 섹션 1: console.log =====");
// HTML은 쓰면 화면에 보였지만, JS는 계산만 하고 아무것도 보여 주지 않습니다.
// 그래서 "지금 값이 뭔지" 눈으로 확인하려면 출력 명령이 따로 필요합니다.
//   console = 개발자용 출력 창 / log = 기록하다
//   확인하는 곳: 브라우저는 F12 → Console 탭, 터미널은 node 파일명
// [기본] 괄호 안의 값을 콘솔에 출력 (경력 10년 개발자도 가장 많이 쓰는 도구)
console.log(42);                 // 출력: 42
console.log(3 + 5);              // 출력: 8
// 괄호 안을 "먼저 계산한 뒤" 그 결과를 출력합니다 — 3+5 라는 글자가 아니라 8이 찍힘

// [축약/다른 방법] 쉼표로 여러 값을 동시에 출력 - 이름과 값을 함께 보면 디버깅에 유용
console.log("이름:", "김철수");  // 출력: 이름: 김철수
console.log("나이:", 25, "세");  // 출력: 나이: 25 세
// 쉼표로 이으면 사이에 공백이 자동으로 들어갑니다 (+로 이으면 공백을 직접 넣어야 함)
// 값만 덜렁 찍으면 나중에 그게 뭐였는지 모르니, 앞에 이름표를 붙이는 습관을 들이세요
// [다른 방법] 변수도 그대로 넣습니다 — 값이 든 상자를 열어 안의 것을 찍습니다
let today = "금요일";
console.log(today);          // 출력: 금요일   (today라는 글자가 아니라 안의 값)
console.log("today");        // 출력: today    (따옴표를 붙이면 글자 그대로)
// 이 차이가 오늘 내내 나옵니다. 따옴표 = 글자 그 자체, 따옴표 없음 = 변수를 찾아라.


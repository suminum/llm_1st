// ── 섹션 6: 템플릿 리터럴 ──────────────
console.log("===== 섹션 6: 템플릿 리터럴 =====");
// 예전 방식과 비교해 보세요:
//   productName + " 현재 재고: " + stockCount + "개"   ← + 와 따옴표를 번갈아 세야 함
//   `${productName} 현재 재고: ${stockCount}개`         ← 완성된 문장 그대로 읽힘
// 백틱(`)은 키보드 숫자 1 왼쪽, Esc 아래에 있습니다 (작은따옴표 '가 아닙니다)
// ★ 한/영이 "한글" 상태면 백틱이 안 찍힙니다. 안 눌린다 싶으면 영문으로 바꾸세요.
//   결과가 이상하면 맨 앞 글자가 백틱인지부터 확인합니다.
// [기본] 백틱(`)으로 감싸고 ${변수} 로 문자열 안에 변수를 직접 끼워 넣기
let productName = "불고기 도시락";
let stockCount = 72;
console.log(`${productName} 현재 재고: ${stockCount}개`);  // 출력: 불고기 도시락 현재 재고: 72개
// [다른 방법] ${} 안에는 계산식도 넣을 수 있음
console.log(`3개 입고 후 재고: ${stockCount + 3}개`);      // 출력: 3개 입고 후 재고: 75개
// [다른 방법] 백틱의 두 번째 기능 — 줄바꿈을 그대로 씁니다 (\n 없이)
const receipt = `상품: ${productName}
재고: ${stockCount}개
확인일: 오늘`;
console.log(receipt);
// 출력: 상품: 불고기 도시락
// 출력: 재고: 72개
// 출력: 확인일: 오늘
// 일반 따옴표는 줄을 바꾸면 에러가 납니다. 백틱만 여러 줄을 그대로 담을 수 있습니다.
// 11일차에 HTML을 통째로 만들어 넣을 때 이 기능을 씁니다.


// ── 섹션 3: 변수 let ──────────────
console.log("===== 섹션 3: 변수 let =====");
// 변수 = 값에 이름표를 붙여 둔 상자. 넣어 두고 나중에 이름으로 꺼내 씁니다.
// 왜 필요한가: 재고 72개를 코드 여기저기에 72라고 직접 적어 두면
// 재고가 바뀔 때 그 자리를 전부 찾아 고쳐야 합니다.
// 상자에 담아 이름으로 부르면 상자 하나만 고치면 끝납니다.
// (4일차 CSS에서 인라인 스타일을 100군데 고쳐야 했던 것과 똑같은 이유입니다)
// [기본] 선언: 저장 공간을 만드는 것 / 할당: 그 공간에 값을 넣는 것
let score = 80;      // 선언과 동시에 할당
//  └이름  └값
//  let  = 나중에 값이 바뀔 수 있는 것에 사용 (점수, 잔액, 카운터 …)
//  const = 한 번 정하면 안 바뀌는 것에 사용 (섹션 4)
//  → 실무 습관: 일단 const로 쓰고, 바꿔야 할 때만 let으로 바꿉니다
console.log(score);  // 출력: 80
score = 95;          // 재할당 가능 - 조건에 따라 바뀌는 값에 사용
console.log(score);  // 출력: 95
// [다른 방법] 선언만 먼저 하고 나중에 할당해도 됨
let bonus;
console.log(bonus);  // 출력: undefined (값을 넣기 전엔 자동으로 undefined)
bonus = 10;
console.log(bonus);  // 출력: 10
// 재할당하면 이전 값은 사라집니다. 두 값을 다 쓰려면 변수를 두 개 만들어야 합니다.

// [기본] 변수끼리 대입하기 — 값이 복사됩니다
let a = 10;
let b = a;      // a의 "값"이 b로 복사됨 (a와 b가 연결된 게 아닙니다)
a = 99;         // a만 바꿔도
console.log(a, b);  // 출력: 99 10   b는 그대로


// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션15_비교_논리_연산자.js 로 실행하며 결과를 확인합니다.

// ── 섹션 15: 비교 · 논리 연산자 ──────────────
console.log("===== 섹션 15: 비교 · 논리 연산자 =====");
// [기본] 크기 비교 > < >= <= - 결과는 항상 boolean
let age = 18;
console.log(age >= 18);  // 출력: true   >= 는 "크거나 같다" (=이 뒤에 옵니다. =>가 아닙니다)
console.log(age > 19);   // 출력: false
console.log(age < 20);   // 출력: true
console.log(age <= 17);  // 출력: false
// 여섯 개를 한 번에 정리하면:
//   >  <  >=  <=   크기 비교
//   === !==        같은가 / 다른가  (다음 줄부터)
// [기본] == 는 값만, === 는 값+자료형까지 비교 -> 항상 === / !== 사용!
console.log(1 == "1");   // 출력: true (타입을 자동 변환 후 비교 - 위험)
// == 는 "타입이 다르면 맞춰 보고 판단"합니다. 섹션 12의 암묵적 형변환이 여기서도 일어납니다.
console.log(1 === "1");  // 출력: false (타입이 달라 즉시 false)
// === 는 "타입부터 다르면 볼 것도 없이 false". 등호 개수가 하나 늘면 조건이 엄격해진다고 외우세요.
console.log(0 == false); // 출력: true (== 의 함정)
console.log(1 !== "1");  // 출력: true  !== 는 "값이나 타입이 다르다" — === 의 반대
// 부정은 느낌표를 앞에 붙입니다: === 의 반대는 !== , == 의 반대는 != (이것도 쓰지 않습니다)
// 왜 위험한가: 사용자가 0을 입력한 것과 아무것도 안 고른 것을 == 는 같다고 판단합니다.
// 실무에서 == 를 쓸 일은 사실상 없습니다 — 무조건 === 를 쓰세요.
// [기본] && (모두 true) / || (하나라도 true) / ! (반전)
let visitor = "뽀로로";
console.log(visitor === "뽀로로" && age > 19);  // 출력: false (AND: 둘 다 참이어야 true)
console.log(visitor === "뽀로로" || age > 19);  // 출력: true (OR: 하나만 참이어도 true)
console.log(!true);                             // 출력: false
// 실수: if (age = 20)  // = 하나는 비교가 아니라 할당 -> 반드시 === 사용

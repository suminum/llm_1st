// 03_JS_01_기초 개념코드 — 섹션 5. String 문자열 (JavaScript)
// 읽는 순서: [기본] → [축약/다른 방법] → 실수 예시
// "실수:" 로 시작하는 줄은 일부러 틀리게 쓴 예입니다 (실행되지 않게 주석 처리).
// node 섹션05_String_문자열.js 로 실행하며 결과를 확인합니다.

// ── 섹션 5: String 문자열 ──────────────
console.log("===== 섹션 5: String 문자열 =====");
// 문자열 = "글자로 다루는 값". 따옴표로 감싸는 이유는
// 홍길동이 "변수 이름"인지 "글자 그대로"인지 JS가 구분해야 하기 때문입니다.
//   myName   → 변수를 찾음
//   "myName" → 글자 여섯 개
// [기본] 작은따옴표(') / 큰따옴표(") / 백틱(`) 세 가지 - 기능은 동일
let myName = '홍길동';
let email = "gildong@naver.com";
console.log(myName);             // 출력: 홍길동
console.log(email);              // 출력: gildong@naver.com
// 셋 중 무엇을 쓸까 — 결과는 같지만 골라 쓰면 편한 상황이 있습니다:
//   "It's me"        작은따옴표가 글자로 들어가야 하면 큰따옴표로 감싸기
//   '그는 "네"라고'   큰따옴표가 글자로 들어가야 하면 작은따옴표로 감싸기
//   백틱(`)          변수를 끼워 넣거나 줄바꿈이 필요할 때 (섹션 6에서 배움)

// [다른 방법] + 연산자로 문자열 연결
console.log("안녕, " + myName);  // 출력: 안녕, 홍길동
// 숫자에서의 + 는 더하기지만, 문자열에서의 + 는 "이어 붙이기"입니다.
// "안녕, " 끝의 공백을 직접 넣어 준 점에 주목 — 안 넣으면 "안녕,홍길동"이 됩니다.
// [기본] 숫자를 따옴표로 감싸면 숫자가 아니라 글자가 됩니다
let zipCode = "06236";      // 우편번호·전화번호·주민번호는 계산할 값이 아니라 글자입니다
console.log(zipCode);       // 출력: 06236   (숫자 6236이었다면 앞의 0이 사라졌겠죠)
// 판단 기준: 더하기·빼기를 할 값이면 숫자, 아니면 문자열로 담습니다.

// [기본] 따옴표 안에서 특별한 뜻을 갖는 기호 — 역슬래시(\)로 알려 줍니다
console.log("줄을\n바꿉니다");        // \n = 여기서 줄 바꿈
// 출력: 줄을
// 출력: 바꿉니다
console.log("그는 \"네\"라고 했다");  // \" = 큰따옴표를 글자로
// 출력: 그는 "네"라고 했다
// 역슬래시는 키보드 백스페이스 왼쪽(한글 자판에서는 ₩ 로 보이기도 합니다).

// 실수: let word = '문자열";  // 여는 따옴표와 닫는 따옴표가 다르면 SyntaxError
//   에러 메시지가 엉뚱한 줄을 가리킬 수 있습니다 — 따옴표가 안 닫히면
//   JS가 그 뒤를 전부 문자열로 읽어 버리기 때문입니다. 색이 이상해지면 따옴표부터 보세요.

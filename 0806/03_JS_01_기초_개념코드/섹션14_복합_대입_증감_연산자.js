// ── 섹션 14: 복합 대입 · 증감 연산자 ──────────────
console.log("===== 섹션 14: 복합 대입 · 증감 연산자 =====");
// 먼저 num = num + 5 라는 줄을 이해해야 합니다.
// 수학의 등호(=)가 아니라 "오른쪽을 계산해서 왼쪽에 넣어라"는 명령입니다.
//   ① 오른쪽 num + 5 를 먼저 계산 (10 + 5 = 15)
//   ② 그 결과를 다시 num에 넣음
// 그래서 num = num + 1 같은 식이 성립합니다 (수학이라면 말이 안 되는 식이죠).
// [기본] num = num + 5 를 줄여서 num += 5 (- * / 도 동일)
let num = 10;
num += 5;          // num = num + 5 와 완전히 같은 뜻 — 변수 이름을 두 번 안 써도 됨
console.log(num);  // 출력: 15
num -= 3;
console.log(num);  // 출력: 12
num *= 2;
console.log(num);  // 출력: 24
num /= 4;
console.log(num);  // 출력: 6
// ++ 는 1 증가, -- 는 1 감소. 반복문 카운터에 주로 씁니다.
// 붙이는 위치에 따라 "언제 올리느냐"가 갈립니다 — 번호표 창구로 비유하면:
//   후위 a++ : 지금 번호를 손님에게 주고 나서, 다음 번호로 넘김
//   전위 ++a : 먼저 다음 번호로 넘기고, 그 번호를 손님에게 줌
//   둘 다 결국 번호는 1 올라가지만, "손님이 받은 번호"가 다릅니다.
// [기본] 후위 a++ : 현재값 반환 후 1 증가 / 전위 ++a : 1 증가 후 반환
let a1 = 10;
let a2 = 10;
let result1 = a1++;        // result1에 10을 먼저 담고, 그 다음 a1이 11이 됨
console.log(result1, a1);  // 출력: 10 11   ← 받은 번호는 10, 창구는 11
let result2 = ++a2;        // a2를 11로 먼저 올리고, 그 값을 result2에 담음
console.log(result2, a2);  // 출력: 11 11   ← 받은 번호도 11, 창구도 11
// 실수: 후위/전위를 식 안에서 섞어 쓰면 헷갈림 -> 단독 줄에서는 num++ 만 써도 충분

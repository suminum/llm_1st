// ── 섹션 3: 안 치우면 어떻게 되나 ──

// 말로 하면 잘 안 와닿습니다. 직접 봅시다.
// 똑같은 타이머를 두 개 만듭니다. 하나는 정리 함수가 있고, 하나는 없습니다.

// [정리 함수가 있는 타이머]
function SafeTimer() {
  const [count, setCount] = useState(0);

  useEffect(() => {
    console.log("[안전한 타이머] 켰습니다");
    // 콘솔: [안전한 타이머] 켰습니다

    let safety = 0; // 학생 PC 를 지키기 위한 안전장치입니다 (아래 설명)

    const id = setInterval(() => {
      //타이머 생성
      safety += 1;
      console.log("[안전한 타이머] " + safety + "번째 신호");
      // 콘솔: [안전한 타이머] 1번째 신호

      setCount(safety);

      if (safety >= 12) {
        clearInterval(id);
        console.log("[안전한 타이머] 안전장치 — 6초가 지나 스스로 멈췄습니다");
      }
    }, 500);

    return () => {
      clearInterval(id);
      console.log("[안전한 타이머] 정리 함수 — 껐습니다");
      // 콘솔: [안전한 타이머] 정리 함수 — 껐습니다
    };
  }, []);

  return <p className="output">안전한 타이머: {count}번째 신호까지 받음</p>;
}

// [정리 함수가 없는 타이머] — 일부러 빠뜨렸습니다
function LeakyTimer() {
  const [count, setCount] = useState(0);

  useEffect(() => {
    console.log("[새는 타이머] 켰습니다 — 정리 함수가 없습니다");
    // 콘솔: [새는 타이머] 켰습니다 — 정리 함수가 없습니다

    let safety = 0;

    const id = setInterval(() => {
      safety += 1;
      console.log(
        "[새는 타이머] " + safety + "번째 신호 — 화면에서 지워도 계속 나옵니다",
      );
      // 콘솔: [새는 타이머] 1번째 신호 — 화면에서 지워도 계속 나옵니다

      setCount(safety);

      // ★ 안전장치 ★
      // 진짜 새는 코드라면 이 줄이 없어서 영원히 돕니다.
      // 그러면 여러분 브라우저가 점점 무거워지므로, 6초 뒤 스스로 멈추게 해 두었습니다.
      // 이 줄이 없다고 상상하면서 아래 설명을 읽으세요.
      if (safety >= 12) {
        clearInterval(id);
        console.log("[새는 타이머] 안전장치 — 6초가 지나 스스로 멈췄습니다");
      }
    }, 500);

    // return 이 없습니다. 그래서 이 타이머는 아무도 안 꺼 줍니다.
  }, []);

  return <p className="output">새는 타이머: {count}번째 신호까지 받음</p>;
}

function LeakDemo() {
  const [showLeaky, setShowLeaky] = useState(true);
  const [showSafe, setShowSafe] = useState(true);

  return (
    <div className="demo">
      <h3>② 정리 함수가 있는 타이머 vs 없는 타이머</h3>

      {showSafe && <SafeTimer />}
      {showLeaky && <LeakyTimer />}
      {/* 화면: 안전한 타이머: 0번째 신호까지 받음 / 새는 타이머: 0번째 신호까지 받음 */}

      <button onClick={() => setShowSafe(!showSafe)}>
        {showSafe ? "안전한 타이머 숨기기" : "안전한 타이머 보이기"}
      </button>
      <button onClick={() => setShowLeaky(!showLeaky)}>
        {showLeaky ? "새는 타이머 숨기기" : "새는 타이머 보이기"}
      </button>
    </div>
  );
}


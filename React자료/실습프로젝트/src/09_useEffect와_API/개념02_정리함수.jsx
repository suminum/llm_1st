//
// StrictMode 는 "엄격 모드" 라는 뜻입니다. 개발 중에만 켜지는 검사 도구입니다.
// 이것이 켜져 있으면 React 가 컴포넌트를 이렇게 다룹니다.
//
//     화면에 붙인다        → useEffect 실행
//     곧바로 떼어 낸다     → 정리 함수 실행
//     다시 붙인다          → useEffect 다시 실행
//
// 그래서 콘솔에 effect 로그가 두 번 찍힙니다. 정상입니다.
//
// [왜 이런 짓을 하나]
//   정리 함수를 제대로 썼는지 대신 검사해 주는 것입니다.
//   제대로 썼다면 붙였다 뗐다 다시 붙여도 결과가 똑같습니다.
//   안 썼다면 타이머가 두 개 생기고, 요청이 두 번 나가고, 구독이 두 개 쌓입니다.
//   그 차이가 콘솔에 바로 드러납니다.
//
//   즉 두 번 실행은 버그가 아니라 '건강검진' 입니다.
//   실제 사용자에게 배포할 때(npm run build) StrictMode 검사는 사라지고 한 번만 실행됩니다.
//
// [컴포넌트 본문도 두 번 실행됩니다]
//   개념01에서 "① 함수 본문" 이 두 줄씩 찍힌 이유가 이것입니다.
//   컴포넌트 함수가 '같은 입력이면 같은 화면' 을 돌려주는지 검사하려고 두 번 부릅니다.
//   그래서 컴포넌트 본문에서 부작용(요청 보내기·타이머 켜기)을 하면 두 배로 벌어집니다.
//   개념01에서 "본문에서 하지 말고 useEffect 에서 하라" 고 한 이유가 여기서 드러납니다.
//
// [두 번 도는 것은 처음 나타날 때뿐입니다]
//   값이 바뀌어 effect 가 다시 도는 경우에는 한 번씩만 실행됩니다.
//   아래 데모의 버튼으로 직접 확인하세요.
//
// [이 자료의 표기 약속]
//   자료의 // 콘솔: 에는 한 번만 적혀 있습니다.
//   실제 콘솔에 두 줄씩 보이는 것이 정상이라고 생각하세요.
//
// [끄고 싶다면]
//   main.jsx 의 <StrictMode> 를 지우면 두 번 실행이 없어집니다.
//   하지만 지우지 마세요. 두 번 실행이 불편하다는 것은
//   대개 정리 함수가 빠졌다는 신호입니다. 신호를 끄는 것으로는 아무것도 안 고쳐집니다.

function StrictModeDemo() {
  const [tick, setTick] = useState(0);

  useEffect(() => {
    //페이지 다그리고 나서 실행할 함수를 넣어주면 됨
    console.log("① effect 실행 — tick 은 " + tick);
    // 콘솔: ① effect 실행 — tick 은 0
    // 콘솔: ① effect 실행 — tick 은 1

    return () => {
      console.log("② 정리 함수 실행 — tick 은 " + tick); //페이지에서 벗어나는 순간 실행할 함수를 넣어줌
      // 콘솔: ② 정리 함수 실행 — tick 은 0
    };
  }, [tick]);

  return (
    <div className="demo">
      <h3>① 두 번 실행되는 것 직접 보기</h3>
      <p className="output">tick: {tick}</p>
      {/* 화면: tick: 0 */}
      <button onClick={() => setTick(tick + 1)}>tick +1</button>
    </div>
  );
}


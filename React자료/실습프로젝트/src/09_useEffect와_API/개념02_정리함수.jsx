// 하지만 window 나 document 처럼 컴포넌트 바깥 물건에 붙인 것은 React 가 모릅니다.
// 우리가 붙였으니 우리가 떼야 합니다.

function SubscribeDemo() {
  // 처음 값은 지금 창 너비로 시작합니다.
  const [width, setWidth] = useState(window.innerWidth);

  useEffect(() => {
    function handleResize() {
      setWidth(window.innerWidth);
    }

    window.addEventListener("resize", handleResize);
    console.log("[구독] window 의 resize 를 구독했습니다");
    // 콘솔: [구독] window 의 resize 를 구독했습니다

    return () => {
      // 붙일 때와 똑같은 함수를 넘겨야 떼어집니다 (JS자료 11단원)
      window.removeEventListener("resize", handleResize);
      console.log("[구독] resize 구독을 해제했습니다");
      // 콘솔: [구독] resize 구독을 해제했습니다
    };
  }, []);

  return (
    <div className="demo">
      <h3>④ 창 크기 구독하기</h3>
      <p className="output">지금 창 높이: {window.innerHeight}px</p>
      {/* 화면: 지금 창 너비: 1280px  ← 숫자는 여러분 창 크기에 따라 다릅니다 */}
    </div>
  );
}


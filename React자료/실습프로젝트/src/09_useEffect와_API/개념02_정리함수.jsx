// ── 섹션 5: 이벤트 구독도 정리 대상 ──

// 타이머 말고도 정리해야 하는 것이 있습니다. 대표적인 것이 이벤트 구독입니다.
// JS자료 11단원에서 배운 addEventListener 입니다.
//
// 컴포넌트 안의 버튼에 붙이는 onClick 은 정리할 필요가 없습니다.
// 그 버튼이 사라지면 React 가 알아서 떼어 줍니다.

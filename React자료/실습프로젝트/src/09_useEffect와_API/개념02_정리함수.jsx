// ── 섹션 4: 값이 바뀔 때도 정리된다 ──

// 정리 함수는 컴포넌트가 사라질 때만 불리는 것이 아닙니다.
// 의존성 배열의 값이 바뀌어 effect 를 '다시' 실행할 때도 먼저 불립니다.
//
//     지난번 effect 의 정리 함수 실행  →  새 effect 실행
//
// 순서가 이렇게 되어 있어서, 옛날 타이머가 새 타이머와 겹치는 일이 없습니다.
// 아래 데모에서 속도를 바꿔 보면 콘솔에 그 순서가 그대로 나옵니다.

function SpeedTimerDemo() {
  const [delay, setDelay] = useState(500);
  const [count, setCount] = useState(0);

  useEffect(() => {
    console.log("[속도 데모] " + delay + "밀리초 타이머 시작");
    // 콘솔: [속도 데모] 500밀리초 타이머 시작
    // 콘솔: [속도 데모] 1000밀리초 타이머 시작

    let safety = 0;

    const id = setInterval(() => {
      safety += 1;
      setCount((prev) => prev + 1); // 04단원 개념05의 함수형 갱신입니다
      if (safety >= 12) clearInterval(id);
    }, delay);

    return () => {
      clearInterval(id);
      console.log("[속도 데모] " + delay + "밀리초 타이머 정리");
      // 콘솔: [속도 데모] 500밀리초 타이머 정리
    };
  }, [delay]); // delay 가 바뀌면 치우고 다시 켭니다

  return (
    <div className="demo">
      <h3>③ 속도를 바꾸면 치우고 다시 켭니다</h3>
      <p className="output">
        간격 {delay}밀리초 / 신호 {count}번
      </p>
      {/* 화면: 간격 500밀리초 / 신호 0번 */}
      <button onClick={() => setDelay(delay === 500 ? 1000 : 500)}>
        간격 바꾸기 (500 ↔ 1000)
      </button>
    </div>
  );
}


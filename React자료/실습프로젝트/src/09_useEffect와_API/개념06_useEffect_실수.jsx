// ── 섹션 1: 무한 루프 ──

// useEffect 로 낼 수 있는 사고 중 가장 큰 것입니다.
// 만드는 방법은 아주 간단합니다. 두 가지만 겹치면 됩니다.
//
//   ① effect 안에서 state 를 바꾼다
//   ② 그 state 가 의존성 배열에 들어 있다 (또는 의존성 배열이 아예 없다)
//
// 그러면 이렇게 돕니다.
//
//     effect 실행 → state 바뀜 → 화면 다시 그림 → 의존성이 달라짐
//     → effect 실행 → state 바뀜 → 화면 다시 그림 → ...
//
// 멈출 이유가 없습니다. 초당 수백 번씩 돕니다.
// 콘솔이 순식간에 수만 줄이 되고, 노트북 팬이 돌기 시작합니다.
//
// 아래 데모는 그 상황을 그대로 만들되, 다섯 번만 돌고 멈추게 해 두었습니다.

const LOOP_LIMIT = 5;

function InfiniteLoopDemo() {
  const [started, setStarted] = useState(false);
  const [count, setCount] = useState(0);

  useEffect(() => {
    // [안전장치 1] 버튼을 눌러야 시작합니다
    if (!started) return;

    // [안전장치 2] 다섯 번 돌면 멈춥니다
    if (count >= LOOP_LIMIT) {
      console.log(`[무한 루프] 상한 ${LOOP_LIMIT}에 닿아 멈췄습니다`);
      // 콘솔: [무한 루프] 상한 5에 닿아 멈췄습니다
      return;
    }

    // 여기가 문제의 두 줄입니다.
    console.log(`[무한 루프] ${count + 1}번째 실행 — 또 state 를 바꿉니다`);
    // 콘솔: [무한 루프] 1번째 실행 — 또 state 를 바꿉니다
    // 콘솔: [무한 루프] 5번째 실행 — 또 state 를 바꿉니다

    setCount(count + 1); // ← effect 안에서 state 를 바꾸고
  }, [started, count]); // ← 그 state 가 의존성에 들어 있습니다

  return (
    <div className="demo">
      <h3>① 무한 루프 (다섯 번만 돌고 멈춥니다)</h3>
      <p className="output">
        {started ? `${count}번 돌았습니다` : "아직 시작하지 않았습니다"}
      </p>
      {/* 화면: 아직 시작하지 않았습니다 */}
      <button onClick={() => setStarted(true)}>무한 루프 시작</button>
      {/* 화면(누르면): 5번 돌았습니다 */}
      <button
        onClick={() => {
          setStarted(false);
          setCount(0);
        }}
      >
        처음으로
      </button>
    </div>
  );
}


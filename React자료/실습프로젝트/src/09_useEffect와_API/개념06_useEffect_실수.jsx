// ── 섹션 3: 계산하면 될 값을 effect 로 만들기 ──

// 07단원 개념05에서 "계산할 수 있는 값은 state 로 두지 말라" 고 배웠습니다.
// useEffect 를 배우고 나면 그 금지를 어기기가 훨씬 쉬워집니다.
// "총액 state 를 두고 effect 로 맞춰 주면 되겠네" 하는 생각이 자연스럽게 들거든요.
//
// 아래 데모에 두 방식을 나란히 두었습니다.

const COFFEE_PRICE = 4000; // 아메리카노 한 잔

function DerivedStateDemo() {
  const [count, setCount] = useState(2);

  // [나쁜 방법] 총액을 state 로 두고 effect 로 맞춥니다
  const [badTotal, setBadTotal] = useState(0);

  useEffect(() => {
    setBadTotal(COFFEE_PRICE * count);
    console.log(
      `[파생 state] effect 가 총액을 다시 계산했습니다: ${COFFEE_PRICE * count}`,
    );
    // 콘솔: [파생 state] effect 가 총액을 다시 계산했습니다: 8000
    // 콘솔:ㅊ [파생 state] effect 가 총액을 다시 계산했습니다: 12000
  }, [count]); //예외적으로 처음 렌더링할 때도 한 번 실행돼.

  // [좋은 방법] 그냥 계산합니다. 한 줄입니다.
  const goodTotal = COFFEE_PRICE * count;

  console.log(
    `[화면 그리는 중] 나쁜 총액 ${badTotal} / 좋은 총액 ${goodTotal}`,
  );
  // 콘솔: [화면 그리는 중] 나쁜 총액 0 / 좋은 총액 8000
  // 콘솔: [화면 그리는 중] 나쁜 총액 8000 / 좋은 총액 8000
  // 콘솔: [화면 그리는 중] 나쁜 총액 8000 / 좋은 총액 12000
  // 콘솔: [화면 그리는 중] 나쁜 총액 12000 / 좋은 총액 12000

  return (
    <div className="demo">
      <h3>③ 총액은 계산하면 되는 값입니다</h3>
      <p className="output">
        아메리카노 {count}잔 — 나쁜 총액 {badTotal}원 / 좋은 총액 {goodTotal}원
      </p>
      {/* 화면: 아메리카노 2잔 — 나쁜 총액 8000원 / 좋은 총액 8000원 */}
      <button onClick={() => setCount(count + 1)}>한 잔 더</button>
      {/* 화면(누르면): 아메리카노 3잔 — 나쁜 총액 12000원 / 좋은 총액 12000원 */}
    </div>
  );
}

// 콘솔을 보면 나쁜 방법이 왜 나쁜지 그대로 드러납니다.
//
//   [화면 그리는 중] 나쁜 총액 0 / 좋은 총액 8000        ← 첫 화면. 나쁜 쪽은 아직 0원
//   [파생 state] effect 가 총액을 다시 계산했습니다: 8000
//   [화면 그리는 중] 나쁜 총액 8000 / 좋은 총액 8000     ← 이제야 맞았습니다
//
// 화면이 두 번 그려졌습니다. 그리고 그 사이에 잠깐 0원이 화면에 나갔습니다.
// [한 잔 더] 를 눌러도 똑같습니다. 잠깐 12000원과 8000원이 함께 보입니다.
//
// [나쁜 방법의 문제 세 가지]
//   1) 한 박자 늦습니다. 잠깐이지만 어긋난 값이 진짜로 화면에 나갑니다.
//   2) 화면을 두 번 그립니다. 한 번이면 될 일입니다.
//   3) 어긋날 수 있습니다. 나중에 다른 곳에서 count 만 바꾸고
//      badTotal 을 안 고치면 둘이 영영 안 맞습니다.
//
// [판단 기준]
//   지금 있는 값으로 계산해 낼 수 있으면 state 로 두지 않습니다. 그냥 계산합니다.
//   계산이 무거워서 걱정된다면 10단원의 useMemo 를 배운 뒤에 생각하세요.
//   대부분은 걱정할 필요가 없습니다. 곱셈 한 번은 아무것도 아닙니다.

// ✏️ 직접 해보기 3 — 나쁜 총액을 화면에서 빼고, badTotal state 와 그 useEffect 도
//                    통째로 지워 보세요. 화면이 달라집니까?

// ── 섹션 4: 이벤트로 하면 될 일을 effect 로 하기 ──

// 판단이 헷갈리는 마지막 경우입니다.
//
//     [effect 로 할 일]   화면에 보이는 것만으로 일어나야 하는 일
//                        예) 이 화면이 열렸으니 글 목록을 받아온다
//                            이 화면이 열렸으니 타이머를 켠다
//
//     [이벤트로 할 일]    사용자가 무언가를 했기 때문에 일어나는 일
//                        예) 담기 버튼을 눌렀으니 장바구니에 넣는다
//                            보내기 버튼을 눌렀으니 서버로 보낸다
//
// 구분하는 질문은 이것입니다.
//
//     "화면이 그냥 떠 있기만 해도 이 일이 일어나야 하나?"
//
// 그렇다면 effect, 아니라면 이벤트 핸들러입니다.
//
// [흔히 보는 잘못된 모양]
//
//     const [submitted, setSubmitted] = useState(false);
//
//     useEffect(() => {
//       if (submitted) {
//         서버로보내기();
//       }
//     }, [submitted]);
//
//     <button onClick={() => setSubmitted(true)}>보내기</button>
//
// 돌아가기는 합니다. 그런데 state 하나가 괜히 늘었고,
// 코드를 읽는 사람은 "보내기" 를 찾으려고 두 곳을 오가야 합니다.
// 게다가 submitted 를 false 로 되돌리는 것을 잊으면 두 번째 클릭이 안 먹습니다.
//
// 아래처럼 한 곳에 두면 끝입니다.

function EventNotEffectDemo() {
  const [cart, setCart] = useState([]);

  // 사용자가 눌렀기 때문에 일어나는 일 → 여기에 씁니다
  function handleAdd() {
    const nextCart = [...cart, "아메리카노"];
    setCart(nextCart);

    console.log(`[이벤트에서] 담기 처리 완료 — 지금 ${nextCart.length}개`);
    // 콘솔: [이벤트에서] 담기 처리 완료 — 지금 1개
  }

  return (
    <div className="demo">
      <h3>④ 누른 결과는 이벤트 핸들러에서</h3>
      <p className="output">장바구니: {cart.length}개</p>
      {/* 화면: 장바구니: 0개 */}
      <button onClick={handleAdd}>아메리카노 담기</button>
      {/* 화면(누르면): 장바구니: 1개 */}
    </div>
  );
}

// [왜 nextCart 를 따로 만들었나]
//   setCart(nextCart) 를 부른 다음 줄에서 cart.length 를 읽으면 옛날 값이 나옵니다.
//   04단원 개념05에서 배운 그대로입니다. state 는 즉시 바뀌지 않습니다.
//   그래서 새 배열을 변수에 담아 두고 그것을 씁니다.
//
// [useEffect 를 안 써도 된다는 것이 이상하게 느껴진다면]
//   useEffect 는 "화면과 바깥세상을 맞추는" 도구입니다.

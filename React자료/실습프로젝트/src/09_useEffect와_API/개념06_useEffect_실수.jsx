// ── 섹션 2: 의존성 빠뜨리기 ──

// 무한 루프가 무서워서 의존성 배열을 무조건 [] 로 두는 사람이 많습니다.
// 그러면 반대쪽 문제가 생깁니다. effect 가 옛날 값을 계속 들고 있습니다.
//
// effect 안의 코드는 '그 effect 가 실행된 때' 의 값을 그대로 붙잡고 있습니다.
// 다시 실행되지 않으면 값도 영원히 그대로입니다.
// 이렇게 낡아 버린 값을 오래된 값(stale value)이라고 부릅니다.
//
// 아래 데모에서 A 와 B 를 비교해 보세요.

function StaleValueDemo() {
  const [price, setPrice] = useState(4000); // 아메리카노

  // [A] price 를 쓰면서 의존성에는 안 넣었습니다
  useEffect(() => {
    console.log(`A) 의존성 [] — 이때 본 price 는 ${price}원`);
    // 콘솔: A) 의존성 [] — 이때 본 price 는 4000원
  }, []);

  // [B] 제대로 넣었습니다
  useEffect(() => {
    console.log(`B) 의존성 [price] — 지금 price 는 ${price}원`);
    // 콘솔: B) 의존성 [price] — 지금 price 는 4000원
    // 콘솔: B) 의존성 [price] — 지금 price 는 4500원
  }, [price]);

  return (
    <div className="demo">
      <h3>② 의존성을 빠뜨리면 옛날 값을 봅니다</h3>
      <p className="output">지금 가격: {price}원</p>
      {/* 화면: 지금 가격: 4000원 */}
      <button onClick={() => setPrice(price === 4000 ? 4500 : 4000)}>
        아메리카노 ↔ 라떼 (4000 ↔ 4500)
      </button>
      {/* 화면(누르면): 지금 가격: 4500원 */}
    </div>
  );
}


function NewArrayDepsDemo() {
  const [tick, setTick] = useState(0);

  // 이 배열은 컴포넌트가 다시 그려질 때마다 '새로' 만들어집니다.
  // 안에 든 글자는 같지만, 새 배열이라 지난번 배열과 같은 물건이 아닙니다.
  // (JS자료 09단원에서 배운 그것입니다. ["a"] === ["a"] 는 false 입니다)
  const menu = ["아메리카노", "라떼"];

  useEffect(() => {
    console.log("[실수 4] menu 를 의존성에 넣었는데 또 실행됐습니다");
    // 콘솔: [실수 4] menu 를 의존성에 넣었는데 또 실행됐습니다
  }, [menu]); // ← 지켜보라고 넣었지만 매번 다른 배열이라 매번 실행됩니다

  return (
    <div className="demo">
      <h3>④ [실수 4] 의존성에 넣었는데 소용이 없는 경우</h3>
      <p className="output">다시 그린 횟수: {tick}</p>
      <button onClick={() => setTick(tick + 1)}>다시 그리기</button>
    </div>
  );
}

// 버튼을 누를 때마다 위 줄이 콘솔에 또 찍힙니다.
// menu 의 내용은 한 번도 안 바뀌었는데 말입니다.
// React 는 배열 안을 들여다보지 않고 "같은 물건인가" 만 봅니다.
// 매번 새로 만든 배열은 매번 다른 물건이라 매번 실행됩니다.
//
// 지금 단계의 해결책은 간단합니다.
//   ① 그 값이 진짜 필요 없으면 의존성에서 빼거나
//   ② 배열·객체 자체가 아니라 그 안의 값(menu.length 같은 것)을 넣습니다.
// 컴포넌트 밖으로 빼는 방법도 있습니다. 위 menu 는 state 가 아니니 파일 위쪽으로 옮겨도 됩니다.

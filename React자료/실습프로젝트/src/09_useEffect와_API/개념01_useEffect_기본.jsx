// ── 섹션 3: 의존성 배열 세 가지 ──

// 위 데모의 useEffect 는 다시 그릴 때마다 매번 실행됐습니다.
// 그런데 대부분은 그러면 안 됩니다.
// 서버에서 목록을 받아오는 일이 화면을 그릴 때마다 나가면 요청이 폭주합니다.
//
// 그래서 useEffect 는 두 번째 자리에 '의존성 배열' 을 받습니다.
//
//     useEffect(() => { 할 일 }, [지켜볼 값]);
//
// "이 배열 안의 값이 지난번과 다를 때만 실행해 줘" 라는 뜻입니다.
// 쓰는 방법이 딱 세 가지입니다.
//
//   [A] 배열을 아예 안 씀     useEffect(() => {...});          → 다시 그릴 때마다 매번
//   [B] 빈 배열              useEffect(() => {...}, []);       → 처음 한 번만
//   [C] 값을 넣은 배열        useEffect(() => {...}, [count]);  → count 가 바뀌었을 때만
//
// [B] 가 왜 '한 번만' 인지 생각해 보면 규칙이 저절로 이해됩니다.
// 빈 배열은 지켜볼 값이 하나도 없다는 뜻입니다. 그러니 달라질 것도 없습니다.
// 그래서 처음 화면에 나타날 때 한 번 실행되고 끝입니다.
//
// 아래 데모에서 A · B · C 를 나란히 켜 두고 직접 세어 봅니다.

function DepsDemo() {
  const [count, setCount] = useState(0);
  const [color, setColor] = useState("파랑");

  // [A] 배열을 안 씀 — 다시 그릴 때마다
  useEffect(() => {
    console.log("A) 배열 없음 —다시그릴때마다 실행");
    // 콘솔: A) 배열 없음 — 실행
  });

  // [B] 빈 배열 — 처음 한 번만
  useEffect(() => {
    console.log("B) [] —처음 한번만 실행");
    // 콘솔: B) [] — 실행
  }, []);

  // [C] [count] — count 가 바뀌었을 때만
  useEffect(() => {
    console.log(`C) [count] — 바뀌었을떄 실행 (count 는 ${count})`);
    // 콘솔: C) [count] — 실행 (count 는 0)
    // 콘솔: C) [count] — 실행 (count 는 1)
  }, [color]);

  return (
    <div className="demo">
      <h3>② 의존성 배열 세 가지를 나란히</h3>
      <p className="output">
        count: {count} / color: {color}
      </p>
      {/* 화면: count: 0 / color: 파랑 */}
      <button onClick={() => setCount(count + 1)}>숫자 +1</button>
      <button onClick={() => setColor(color === "파랑" ? "빨강" : "파랑")}>
        색 바꾸기
      </button>
    </div>
  );
}


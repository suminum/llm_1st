// ── 섹션 1: 지금까지의 방식 — state 로 화면 갈아 끼우기 ──

// 아래는 05단원까지 배운 것만으로 만든 화면 전환입니다.
// 버튼을 누르면 page 가 바뀌고, page 에 따라 다른 문단이 그려집니다.
// 새로 배운 것은 하나도 없습니다. 무엇이 부족한지만 보면 됩니다.

function StateWayDemo() {
  const [page, setPage] = useState("home");

  function showPage(name) {
    setPage(name);
    console.log("[state 방식] 화면만 바꿨습니다. 주소는 그대로입니다.");
    // 콘솔: [state 방식] 화면만 바꿨습니다. 주소는 그대로입니다.
  }

  return (
    <div className="demo">
      <h3>① 지금까지의 방식 — state 로 갈아 끼우기</h3>

      <button onClick={() => showPage("home")}>홈</button>
      <button onClick={() => showPage("about")}>소개</button>
      <button onClick={() => showPage("menu")}>메뉴</button>

      <div className="output">
        {page === "home" && <p>홈 — 어서 오세요. 오늘도 좋은 하루 되세요.</p>}
        {page === "about" && <p>소개 — 2020년에 문을 연 작은 카페입니다.</p>}
        {page === "menu" && (
          <p>메뉴 — 아메리카노 4000원 / 라떼 4500원 / 케이크 6000원</p>
        )}
      </div>

      <p>
        화면은 잘 바뀝니다. 그런데 <strong>브라우저 주소창을 보세요.</strong> 한
        글자도 안 바뀝니다.
      </p>
    </div>
  );
}


// ── 섹션 2: <Link> 로 이동하면 무슨 일이 일어나나 ──

// <Link to="/r2/menu"> 를 누르면 이렇게 됩니다.
//
//   1. Link 가 브라우저의 기본 동작(페이지 새로 받기)을 막습니다.

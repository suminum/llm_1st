// ── 섹션 3: 두 방식을 나란히 재 보기 ──

// 아래 데모 ① 에 두 종류의 링크를 나란히 두었습니다. 가는 주소는 똑같습니다.
//
//   파란 글씨 = <Link to="...">      React 가 처리합니다
//   빨간 글씨 = <a href="...">       브라우저가 처리합니다
//
// 재 보는 것이 세 가지입니다.
//
//   [1] 왼쪽 메뉴   <Link> → 이 예제 그대로   /  <a> → 맨 위 예제로 바뀜
//   [2] 카운터      <Link> → 숫자 그대로     /  <a> → 돌아와 보면 0
//   [3] 콘솔 로그   <Link> → 안 찍힘         /  <a> → 돌아오면 맨 위 줄이 다시 찍힘
//
// [1]이 가장 먼저 눈에 띕니다. 빨간 링크를 누르면 이 예제가 화면에서 사라집니다.
// 왼쪽 메뉴에서 이 예제를 다시 고르면 [2]와 [3]을 확인할 수 있습니다.
//
// [3]이 가장 확실한 증거입니다. 파일 맨 위의 console.log 는 컴포넌트 밖에 있어서
// 브라우저가 이 파일을 '처음 읽을 때' 만 실행됩니다.
// 그래서 <Link> 로 아무리 왔다 갔다 해도 다시 안 찍힙니다.
// 심지어 왼쪽 메뉴에서 다른 예제로 갔다가 돌아와도 안 찍힙니다. 이미 읽어 둔 파일이니까요.
// 그런데 <a> 로 이동한 뒤에는 다시 찍힙니다. 파일을 처음부터 다시 읽었다는 뜻입니다.


// ── 섹션 6: 자주 하는 실수 ──

// ⚠️ [SyntaxError] 라고 적힌 것은 주석을 풀지 말고 눈으로만 보세요.
//    풀면 파일 전체가 멈춰서 화면이 통째로 비어 버립니다. 다시 // 를 붙이면 돌아옵니다.

// [실수 1] Link 에 href 를 쓴다  — [조용히 틀림]
//
//     <Link href="/r2/menu">메뉴</Link>
//
// 실수: 에러가 안 납니다. 글자는 그대로 나오고 눌러도 아무 일이 안 일어납니다.
//       Link 가 아는 이름은 to 입니다. href 는 모르는 이름이라 그냥 무시합니다.
//       "눌러도 반응이 없다" 면 to 인지 href 인지부터 보세요.

// [실수 2] a 를 그대로 두고 Link 로 안 바꾼다  — [조용히 틀림]
//
//     <a href="/r2/menu">메뉴</a>
//
// 실수: 화면은 잘 나옵니다. 그래서 다 됐다고 생각하기 쉽습니다.
//       하지만 누를 때마다 앱이 처음부터 다시 시작합니다.
//       장바구니에 담아 둔 것이 사라지고, 화면이 깜빡이고, 느립니다.
//       이 파일의 데모 ① 이 바로 그 차이를 재 보는 것입니다.

// [실수 3] BrowserRouter 밖에서 Link 를 쓴다  — [런타임 에러]
//
//     <div>
//       <Link to="/r2">홈</Link>
//     </div>
//     <BrowserRouter>...</BrowserRouter>
//
// 실수: 화면이 빨간 에러 상자가 됩니다.
//       "useHref() may be used only in the context of a <Router> component" 라고 나옵니다.
//       Link 는 지금 주소를 알아야 동작하는데, 알려 줄 사람이 밖에는 없습니다.

// [실수 4] NavLink 의 className 에 함수 대신 값을 넣는다  — [조용히 틀림]
//
//     <NavLink to="/r2/menu" className={isActive ? "on" : ""}>메뉴</NavLink>
//
// 실수: isActive 라는 변수는 이 자리에 없습니다. 바깥에 없으면 에러가 나고,
//       우연히 같은 이름의 변수가 있으면 에러도 없이 늘 같은 값이 됩니다.
//       isActive 는 NavLink 가 함수를 부르면서 넘겨 주는 값입니다.
//       그래서 className={({ isActive }) => ...} 처럼 함수로 받아야 합니다.

// [실수 5] Link 를 닫지 않는다  — [SyntaxError]
//
//     <Link to="/r2">홈
//

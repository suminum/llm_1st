// 개념01에서 주소를 바꾸는 데 <Link> 를 썼습니다.
// 그때는 "누르면 저 주소로 가는 것" 이라고만 하고 넘어갔습니다.
//
// 그런데 주소를 바꾸는 방법은 이미 하나 알고 있습니다. HTML 의 <a> 입니다.
//
//     <a href="/r2/menu">메뉴</a>
//     <Link to="/r2/menu">메뉴</Link>
//
// 둘 다 누르면 /r2/menu 로 갑니다. 화면도 똑같이 나옵니다.
// 그러면 왜 <Link> 를 따로 쓸까요? 눈으로 보이는 결과가 같으니 말로만 들으면
// 와닿지 않습니다. 이 파일에서는 그 차이를 직접 재 봅니다.
//
// 재는 방법은 이렇습니다. 화면에 카운터를 하나 두었습니다.
// 이 카운터는 state 입니다. state 는 페이지가 새로 시작하면 처음 값으로 돌아갑니다.
// 그러니 카운터를 올려 둔 뒤 링크를 눌러 보면 됩니다.
// 숫자가 남아 있으면 페이지가 그대로인 것이고, 0이 되면 새로 시작한 것입니다.
//
// ★ 이 자료만의 사정: 진짜 앱은 BrowserRouter 를 앱 맨 바깥에 한 번만 둡니다.
//   이 자료는 왼쪽 메뉴로 예제를 골라 보는 구조라서 파일마다 하나씩 두었습니다.
//   그리고 파일마다 주소 앞머리가 다릅니다. 이 파일은 /r2 입니다.


// ── 섹션 4: NavLink — 지금 보고 있는 메뉴 표시하기 ──

// 메뉴가 여러 개면 "지금 어디를 보고 있는지" 를 표시해 주는 것이 친절합니다.
// Link 로도 할 수 있지만, 지금 주소를 직접 꺼내서 비교해야 합니다.
// NavLink 는 그 비교를 대신 해 줍니다.
//
//     <NavLink to="/r2/menu" className={({ isActive }) => (isActive ? "on" : "")}>
//       메뉴
//     </NavLink>
//
// NavLink 는 className 자리에 문자열 대신 함수를 넣을 수 있습니다.
// React 가 그 함수를 부르면서 { isActive: true } 같은 객체를 넘겨 줍니다.
// isActive 는 "지금 주소가 이 링크의 주소와 맞는가" 입니다.
// 위 코드는 03단원에서 배운 매개변수 자리 구조분해로 그 값을 바로 꺼낸 것입니다.
//
// 여기서 쓴 "on" 은 이 자료의 공용 CSS 에 있는 클래스입니다(파란 배경 + 흰 글자).
// 08단원 개념05에서 본 그 index.css 안에 들어 있습니다.
//
// [end 를 꼭 기억하세요]
// NavLink 는 기본적으로 '주소가 이 to 로 시작하면' 켜진 것으로 봅니다.
// 그래서 to="/r2" 인 홈 링크는 /r2/menu 에서도 켜져 버립니다.
// end 를 붙이면 '딱 이 주소일 때만' 으로 바뀝니다.
//
//     <NavLink to="/r2" end>홈</NavLink>
//
// end 는 값을 안 적었습니다. 02단원에서 배운 불리언 속성이라 적으면 true 입니다.

function NavLinkDemo() {
  // 함수로 넣기 때문에 이렇게 따로 빼서 이름을 붙여 둘 수도 있습니다.
  function markActive({ isActive }) {
    return isActive ? "on" : "";
  }

  return (
    <div className="demo">
      <h3>② NavLink — 보고 있는 곳에 색이 들어옵니다</h3>

      <nav>
        <NavLink to="/r2" end className={markActive}>
          홈
        </NavLink>{" "}
        |{" "}
        <NavLink to="/r2/menu" className={markActive}>
          메뉴
        </NavLink>{" "}
        |{" "}
        <NavLink to="/r2/notice" className={markActive}>
          공지
        </NavLink>
      </nav>

      <div className="output">
        <Routes>
          <Route path="/r2" element={<p>지금 화면: 홈</p>} />
          <Route path="/r2/menu" element={<p>지금 화면: 메뉴</p>} />
          <Route path="/r2/notice" element={<p>지금 화면: 공지</p>} />
          <Route path="*" element={<p>지금 화면: 없음</p>} />
        </Routes>
      </div>

      <p>
        데모 ① 과 ② 는 같은 BrowserRouter 안에 있습니다. 그래서 어느 쪽 링크를 눌러도 두
        상자가 함께 바뀝니다. 주소 하나가 화면 여러 곳을 동시에 정하는 것입니다.
      </p>
    </div>
  );
}


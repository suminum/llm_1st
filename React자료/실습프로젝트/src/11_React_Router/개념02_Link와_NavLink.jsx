// ── 섹션 5: 그러면 <a> 는 언제 쓰나 ──

// <Link> 는 '이 앱 안의 주소' 로 갈 때만 쓸 수 있습니다.
// 앱 밖으로 나가는 주소, 즉 다른 사이트로 갈 때는 <a> 가 맞습니다.
//
//     <a href="https://reactrouter.com">리액트 라우터 공식 문서</a>
//
// 다른 사이트는 우리 Routes 에 등록할 수 없습니다. 등록해 봐야 그런 화면이 없습니다.
// 이때 <Link to="https://reactrouter.com"> 라고 쓰면 어떻게 될까요?
// 주소창이 http://localhost:5199/https://reactrouter.com 처럼 이상해집니다.
// Link 는 그 글자를 '우리 앱 안의 주소' 로 취급하기 때문입니다.
//
// 정리하면 이렇습니다.
//
//   우리 앱 안의 주소  → <Link> 또는 <NavLink>
//   다른 사이트 주소   → <a href="https://...">
//   파일 내려받기      → <a href="...파일주소" download>
//
// 아래 데모 ③ 의 링크에는 target="_blank" 를 붙였습니다.
// 새 탭에서 열라는 뜻입니다. 지금 보던 것을 잃지 않아서 편합니다.

function OutsideLinkDemo() {
  return (
    <div className="demo">
      <h3>③ 밖으로 나가는 링크</h3>
      <p>
        <a href="https://reactrouter.com" target="_blank" rel="noreferrer">
          리액트 라우터 공식 문서 (새 탭에서 열립니다)
        </a>
      </p>
      <p>
        이런 링크는 Routes 에 등록할 수 없습니다. 우리 앱의 화면이 아니기 때문입니다.
      </p>
    </div>
  );
}


//
// 화면이 깜빡이지 않는 것도 같은 이유입니다.
// 눌러 보면 <a> 는 화면이 한 번 하얘졌다 돌아오고, <Link> 는 글자만 바뀝니다.

// ✏️ 직접 해보기 2 — 데모 ① 에서 [+1] 을 세 번 눌러 카운터를 3으로 만드세요.

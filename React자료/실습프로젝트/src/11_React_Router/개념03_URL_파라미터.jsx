const sampleId = "2"; // useParams 가 주는 값과 같은 모양입니다

console.log(typeof sampleId);
// 콘솔: string

console.log(sampleId === 2);
// 콘솔: false

console.log(Number(sampleId) === 2);
// 콘솔: true

// menuItems 의 id 는 숫자 1, 2, 3, 4 입니다.
// 그러니 문자열 "2" 로 찾으면 영영 못 찾습니다.
//
//     menuItems.find((item) => item.id === id)          // "2" 와 2 를 비교 → undefined
//     menuItems.find((item) => item.id === Number(id))  // 2 와 2 를 비교 → 라떼
//
// 이 실수는 에러를 내지 않습니다. 그냥 '못 찾았다' 가 될 뿐입니다.
// 그래서 "링크는 맞는데 상세가 안 나온다" 로 나타납니다. 아래 데모에서 직접 보세요.

function MenuDetail() {
  const params = useParams();
  const { id } = params; // params.id 와 같습니다
  const a = { a: 1, b: 2, c: 3 };
  const { d, e, f } = a;
  console.log(d, e, f);//여기서 React나 JavaScript가 순서대로 대응시키는 게 아니라, 이름으로 찾는다.
  //결과 :undefined undefined undefined

  // 틀린 방법 — 문자열과 숫자를 === 로 비교합니다
  const wrongFound = menuItems.find((item) => item.id === id);

  // 맞는 방법 — 숫자로 바꿔서 비교합니다
  const found = menuItems.find((item) => item.id === Number(id));

  return (
    <div>
      <h4>상세 화면</h4>

      <p>
        useParams() 가 준 것: <strong>{JSON.stringify(params)}</strong>
        {/* JSON.stringify 는 값을 글자로 바꿔 보여 줍니다. JS자료 12단원에서 썼습니다. */}
        {/* 화면: {"id":"2"} — 2 에 따옴표가 붙어 있습니다. 문자열이라는 뜻입니다. */}
      </p>

      <p>
        id 의 타입: <strong>{typeof id}</strong> / id === 2 의 결과:{" "}
        <strong>{String(id === 2)}</strong>
        {/* String(...) 으로 감싼 이유: JSX 는 true/false 를 화면에 안 그립니다(05단원). */}
        {/* 화면: id 의 타입: string / id === 2 의 결과: false */}
      </p>

      <p>
        문자열 그대로 찾은 결과:{" "}
        <strong>{wrongFound ? wrongFound.name : "못 찾았습니다"}</strong>
      </p>

      <p>
        Number() 로 바꿔 찾은 결과:{" "}
        <strong>
          {found ? found.name + " " + found.price + "원" : "못 찾았습니다"}
        </strong>
      </p>

      <p>
        <Link to="/r3/menu">← 목록으로</Link>
      </p>
    </div>
  );
}


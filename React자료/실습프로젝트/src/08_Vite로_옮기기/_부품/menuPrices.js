// 아래는 전부 '이름 있는 export' 입니다.
// export 를 만드는 자리마다 하나씩 붙였습니다. 개수 제한이 없습니다.
export const americanoPrice = 4000;
export const lattePrice = 4500;
export const cakePrice = 6000;

// 값뿐 아니라 함수도 내보낼 수 있습니다.
export function formatPrice(price) {
  return `${price}원`;
}

// export 를 안 붙인 것은 이 파일 밖으로 나가지 않습니다.
// 아래 값은 파일 안에서만 쓰는 것이라 일부러 안 붙였습니다.
const shopName = "동네 카페";

export function shopLabel() {
  // 밖에서는 shopName 을 못 보지만, 같은 파일 안이라 여기서는 잘 보입니다.
  return `${shopName} 메뉴판`;
}

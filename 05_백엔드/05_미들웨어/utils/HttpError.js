// ============================================================
// utils/HttpError.js — 상태코드가 붙은 에러 만들기
// ------------------------------------------------------------
// 여러 파일에서 쓰니까 여기로 뺐습니다.
// ============================================================

function HttpError(코드, 메시지) {
  const 에러 = new Error(메시지);
  에러.status = 코드;
  return 에러;
}

module.exports = { HttpError };


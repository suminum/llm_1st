//   "숫자로 바꾸는 걸 잊어버릴 수가 없는" 구조가 됩니다.
//
// ★ 다만 이름이 정확히 맞아야 합니다.
//   app.param("id", ...) 는 :id 에만 걸립니다. :logId 에는 안 걸립니다.

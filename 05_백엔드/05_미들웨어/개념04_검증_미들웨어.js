// ── 섹션 3: 경로 파라미터를 미리 다듬기 (app.param) ──

// req.params.id 를 Number 로 바꾸는 코드도 라우트마다 반복됩니다.
// Express 에는 "이 이름의 파라미터가 오면 먼저 이 함수를 실행해라" 가 있습니다.

app.param("id", (req, res, next, 값) => {
  // ★ 인자가 네 개입니다. 마지막이 그 파라미터의 값입니다.
  const 번호 = Number(값);

  if (!Number.isInteger(번호)) {
    return next(HttpError(400, "번호는 숫자여야 합니다"));
  }

  req.번호 = 번호; // 숫자로 바꿔서 붙여 둡니다
  next();
});

app.get("/things/:id", (req, res) => {
  res.json({
    원본: req.params.id,
    번호: req.번호,
    타입: typeof req.번호,
  });
});

// 확인: GET /things/12
// 응답: 200 {"원본":"12","번호":12,"타입":"number"}

// 확인: GET /things/abc
// 응답: 400 {"error":"번호는 숫자여야 합니다"}

app.delete("/things/:id", (req, res) => {
  // 여기도 :id 라서 위 app.param 이 먼저 실행됩니다. 다시 안 써도 됩니다.
  res.json({ 지움: req.번호 });
});

// 확인: DELETE /things/7

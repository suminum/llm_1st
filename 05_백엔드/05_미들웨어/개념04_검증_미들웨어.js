const express = require("express");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

function HttpError(코드, 메시지) {
  const 에러 = new Error(메시지);
  에러.status = 코드;
  return 에러;
}


// ── 섹션 1: 가장 단순한 검증 미들웨어 ──

// 필수 값 이름들을 받아서, 그것들이 본문에 있는지 확인하는 미들웨어를 만듭니다.

function 필수값(...키들) {
  // ★ ...키들 은 "인자를 몇 개 주든 배열로 받겠다" 는 뜻입니다. (JS자료 09단원)
  //   필수값("name", "line")  →  키들 은 ["name", "line"]

  return (req, res, next) => {
    const 본문 = req.body || {};
    const 빠진것 = 키들.filter((키) => 본문[키] === undefined || 본문[키] === "");

    if (빠진것.length > 0) {
      throw HttpError(400, `${빠진것.join(", ")} 을(를) 넣어 주세요`);
    }

    next();
  };
}

app.post("/notes", 필수값("title", "content"), (req, res) => {
  // 여기 왔다는 것은 title 과 content 가 반드시 있다는 뜻입니다.
  res.status(201).json({ title: req.body.title, content: req.body.content });
});


// ★ 라우트가 두 줄이 되었습니다.
//   검증은 미들웨어가, 라우트는 응답만 담당합니다.
//
// ★ === undefined 로 확인한 이유
//   !본문[키] 로 쓰면 숫자 0 과 빈 글자를 '없는 것' 으로 봅니다.
//   수량: 0 을 보냈는데 "수량을 넣어 주세요" 가 나오면 이것 때문입니다.
//   빈 글자는 따로 걸러 냈습니다. 0 은 통과시킵니다.


// ── 섹션 2: 규칙을 표로 적는 검증기 ──

// 필수 말고도 확인할 게 많습니다.
//   타입이 맞나 / 길이가 적당한가 / 정해진 값 중 하나인가 / 범위 안인가
//
// 이걸 if 로 다 쓰면 또 길어집니다. '규칙 표' 를 만들어 넘기는 방식으로 만듭니다.

function 한줄검사(규칙, 값) {
  // 값이 없을 때
  if (값 === undefined || 값 === "") {
    return 규칙.필수 ? "필수입니다" : null; // 필수가 아니면 통과
  }

  if (규칙.타입 && typeof 값 !== 규칙.타입) {
    return `${규칙.타입} 이어야 합니다 (지금은 ${typeof 값})`;
  }

  if (규칙.허용 && !규칙.허용.includes(값)) {
    return `${규칙.허용.join(", ")} 중 하나여야 합니다`;
  }

  if (규칙.최소길이 !== undefined && 값.length < 규칙.최소길이) {
    return `${규칙.최소길이}글자 이상이어야 합니다`;
  }

  if (규칙.최대길이 !== undefined && 값.length > 규칙.최대길이) {
    return `${규칙.최대길이}글자 이하여야 합니다`;
  }

  if (규칙.최소 !== undefined && 값 < 규칙.최소) {
    return `${규칙.최소} 이상이어야 합니다`;
  }

  if (규칙.최대 !== undefined && 값 > 규칙.최대) {
    return `${규칙.최대} 이하여야 합니다`;
  }

  return null; // 문제 없음
}

function 검증(규칙들) {
  return (req, res, next) => {
    const 본문 = req.body || {};
    const 항목 = [];

    for (const 규칙 of 규칙들) {
      const 이유 = 한줄검사(규칙, 본문[규칙.키]);

      if (이유) {
        항목.push({ 키: 규칙.키, 이유 });
      }
    }

    if (항목.length > 0) {
      return res.status(400).json({ error: "입력값이 올바르지 않습니다", 항목 });
    }

    next();
  };
}


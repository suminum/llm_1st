// ── 자주 하는 실수 ──

// [실수 1] !값 으로 필수를 확인
//   숫자 0 과 빈 글자를 '없는 것' 으로 봅니다.
//   수량 0, 온도 0 을 다루는 순간 버그가 됩니다.

// [실수 2] 검증 미들웨어가 next() 를 안 부름
//   통과했는데도 요청이 멈춥니다. 성공 갈래에도 next() 를 꼭 넣으세요.

// [실수 3] 미들웨어를 만들면서 괄호를 빼먹음
//   app.post("/notes", 필수값, ...)   ← 만드는 함수를 그대로 넘김
//   app.post("/notes", 필수값("title"), ...)   ← 맞습니다

// [실수 4] 검증을 라우트 안에서 다시 함
//   미들웨어가 이미 걸렀는데 또 확인하면 코드만 길어집니다.
//   "여기 왔으면 통과한 것" 이라고 믿으세요.

// [실수 5] 프론트에서 검사하니 서버는 안 함
//   Postman 한 번이면 뚫립니다. 서버 검증은 선택이 아닙니다.

// [실수 6] app.param 의 이름을 라우트와 다르게 씀
//   app.param("id") 는 :id 에만 걸립니다. :equipmentId 에는 안 걸립니다.
//   조용히 안 걸려서 "왜 숫자가 아니지?" 로 헤매게 됩니다.


// ── 정리 ──

// 1. 값이 제대로 왔는지 보는 일은 라우트 밖으로 뺀다. 라우트는 할 일만 하게 둔다.
// 2. 필수 확인에 !값 을 쓰면 안 된다. 0 과 "" 까지 없는 것으로 쳐 버린다.
//    === undefined 처럼 정확히 본다.
// 3. 검증 미들웨어도 통과했으면 next() 를 불러야 한다. 안 부르면 거기서 멈춘다.
// 4. 규칙을 표로 적어 두면 검증기 하나로 여러 라우트를 덮을 수 있다.
// 5. app.param 으로 경로 파라미터를 미리 다듬어 두면 라우트마다 Number 로 바꿀 일이 없다.
//    이름은 라우트의 :이름 과 똑같이 써야 불린다.

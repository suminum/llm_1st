//       끄려면 Ctrl + C
//
// ★ 이 파일은 터미널을 함께 보면서 해야 합니다.
//   응답보다 터미널에 찍히는 내용이 더 중요합니다.
// ============================================================
//
// 실무 서버에 거의 항상 들어가는 미들웨어 네 가지를 직접 만듭니다.
//
//   ① 요청 기록 남기기
//   ② 응답까지 걸린 시간 재기
//   ③ 요청마다 번호 붙이기
//   ④ 응답에 헤더 붙이기

const express = require("express");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());


// ── 섹션 1: 요청 기록 남기기 ──

// 서버가 무슨 요청을 받았는지 안 남기면, 문제가 생겼을 때 아무것도 알 수 없습니다.
// "어제 오후에 에러가 났대요" 라는 말만 듣고 원인을 찾아야 합니다.

app.use((req, res, next) => {
  const 시각 = new Date().toISOString(); // 2026-08-13T05:12:33.123Z 모양
  console.log(`${시각}  ${req.method} ${req.originalUrl}`);
  next();
});

// ★ req.url 이 아니라 req.originalUrl 을 썼습니다.
//
//   req.url          미들웨어 위치에 따라 앞부분이 잘려 있을 수 있습니다
//   req.originalUrl  브라우저가 보낸 주소 그대로입니다
//
//   app.use("/admin", ...) 안에서는 req.url 이 "/users" 로만 보입니다.
//   기록에는 "/admin/users" 를 남겨야 하니 originalUrl 이 맞습니다.
//
// ★ toISOString 을 쓴 이유
//   컴퓨터마다 시간 표기가 다르면 기록을 모아서 볼 수가 없습니다.
//   ISO 형식은 어디서나 같은 모양이라 정렬도 됩니다.
//   끝의 Z 는 세계 표준시(UTC)라는 뜻입니다. 한국 시간보다 9시간 이릅니다.


// ── 섹션 2: 걸린 시간 재기 ──

// "어느 주소가 느린가" 를 알아야 고칠 곳을 찾을 수 있습니다.
//
// ★ 문제가 하나 있습니다.
//   미들웨어는 '응답을 보내기 전' 에 실행됩니다.
//   그런데 걸린 시간은 '응답을 보낸 뒤' 에야 알 수 있습니다.
//   여기서 시간을 재고 next() 를 부르면, 그 뒤로는 우리 손을 떠납니다.
//
//   그래서 "응답이 끝나면 알려 줘" 를 res 에 부탁해 둡니다.

app.use((req, res, next) => {
  const 시작 = Date.now();

  // res 도 이벤트를 낼 수 있습니다. finish 는 '응답을 다 보냈다' 는 뜻입니다.
  res.on("finish", () => {
    const 걸린시간 = Date.now() - 시작;
    console.log(`   └ ${res.statusCode} — ${걸린시간}ms`);
  });

  next();
});

// 11단원(JS자료)의 addEventListener 와 같은 모양입니다.
// "이 일이 생기면 이 함수를 실행해 줘" 입니다.
//
// ★ res.on("finish") 안에서는 응답을 보낼 수 없습니다.
//   이미 다 보낸 뒤니까요. 기록만 남길 수 있습니다.

app.get("/slow", async (req, res) => {
  await new Promise((resolve) => setTimeout(resolve, 200));
  res.json({ 설명: "일부러 0.2초 기다렸습니다. 터미널의 ms 를 보세요" });
});

// 확인: GET /slow
// 응답: 200 {"설명":"일부러 0.2초 기다렸습니다. 터미널의 ms 를 보세요"}

app.get("/fast", (req, res) => {
  res.json({ 설명: "바로 응답합니다" });
});

// 확인: GET /fast
// 응답: 200 {"설명":"바로 응답합니다"}

// 두 주소를 눌러 보고 터미널의 ms 를 비교하세요.
// /slow 는 200ms 언저리, /fast 는 0~2ms 가 나옵니다.


// ── 섹션 3: 요청마다 번호 붙이기 ──

// 서버는 여러 요청을 동시에 처리합니다.
// 기록이 뒤섞이면 "이 줄과 저 줄이 같은 요청인가?" 를 알 수 없습니다.
// 그래서 요청마다 번호를 붙입니다.

let 요청번호 = 0;

app.use((req, res, next) => {
  요청번호 += 1;
  req.요청번호 = 요청번호; // ★ req 에 붙여 두면 아래 어디서든 쓸 수 있습니다
  next();
});

app.get("/request-id", (req, res) => {
  console.log(`   └ 이 요청의 번호는 ${req.요청번호} 입니다`);

  res.json({
    타입: typeof req.요청번호,
    번호가붙었나: req.요청번호 > 0,
  });
});

// 확인: GET /request-id
// 응답: 200 {"타입":"number","번호가붙었나":true}

// 번호 자체는 요청을 몇 번 보냈느냐에 따라 달라집니다.
// 그래서 여기서는 '붙었는지' 만 확인했습니다. 실제 번호는 터미널에서 보세요.
//
// ★ 실무에서는 숫자 대신 무작위 글자를 씁니다.
//   서버를 여러 대 돌리면 번호가 겹치기 때문입니다.
//     req.요청번호 = crypto.randomUUID();
//   crypto 는 Node 내장 모듈입니다. require("crypto") 로 가져옵니다.


// ── 섹션 4: 응답에 헤더 붙이기 ──

app.use((req, res, next) => {
  res.set("X-Request-Id", String(req.요청번호));//응답의 헤더(header)에 정보를 추가하는 거야.
  //헤더는 요청이나 응답에 대한 부가 정보를 전달하는 공간이라고 생각하면 돼.요청 응답 각각 헤더 바디 주소url 이 있는데
  //아래 코드는 응답res  붙이는거임 
  //Host: localhost:3000
// Content-Type: application/json
// X-Request-Id: 123
  res.set("X-App-Name", "equipment-api"); // ★ 영어여야 합니다. 아래 설명을 보세요
  next();
});

app.get("/header-echo", (req, res) => {
  // res.get 으로 내가 붙인 헤더를 다시 읽어 볼 수 있습니다.
  res.json({
    붙였나: res.get("X-Request-Id") !== undefined,
    앱이름: res.get("X-App-Name"),
  });
});

// 확인: GET /header-echo
// 응답: 200 {"붙였나":true,"앱이름":"equipment-api"}

// ★ X- 로 시작하는 이름
//   표준에 없는, 우리가 만든 헤더라는 표시입니다. 관례입니다.
//   요청 번호를 헤더로 돌려주면, 사용자가 "이 번호로 문의합니다" 라고 할 수 있습니다.
//   그 번호로 서버 기록을 찾으면 무슨 일이 있었는지 바로 알 수 있습니다.
//
// ★ 헤더는 응답을 보내기 '전' 에만 붙일 수 있습니다.
//   res.json 뒤에 res.set 을 부르면 에러가 납니다.
//   그래서 이 미들웨어가 라우트보다 위에 있습니다.


// ── 섹션 4-2: ★★ 헤더 값에 한글을 넣으면 서버가 500 을 냅니다 ──

app.get("/header-korean", (req, res) => {
  let 던진에러 = null;

  try {
    res.set("X-Test", "설비관리");  // 검증무시: 일부러 터지는 예를 살려 둔 것
  } catch (에러) {
    던진에러 = 에러;
  }

  res.json({
    한글헤더가되나: 던진에러 === null,
    에러이름: 던진에러 ? 던진에러.name : null,
    에러코드: 던진에러 ? 던진에러.code : null,
  });
});

// 확인: GET /header-korean
// 응답: 200 {"한글헤더가되나":false,"에러이름":"TypeError","에러코드":"ERR_INVALID_CHAR"}

// 에러 메시지는 이렇습니다.
//   TypeError: Invalid character in header content ["X-Test"]
//
// 왜 안 되나
//   HTTP 헤더는 영어와 숫자, 몇몇 기호만 담을 수 있게 정해져 있습니다.
//   아주 오래전에 만들어진 약속이라 한글이 들어갈 자리가 없습니다.
//   본문(body)은 아무 글자나 담을 수 있습니다. 헤더만 그렇습니다.
//
// 개념01 에서 본 것과 같은 이야기입니다. 정리하면
//
//   라우트 주소   한글 ✗   (조용히 404)
//   헤더 이름·값  한글 ✗   (500 으로 터짐)
//   쿼리 값       한글 ○
//   경로 파라미터 한글 ○
//   본문(JSON)    한글 ○
//   응답 본문     한글 ○
//
// ★ 이 실수는 try/catch 로 감싸지 않으면 500 이 됩니다.
//   미들웨어에서 이러면 그 서버의 '모든 요청' 이 500 이 됩니다.
//   실제로 이 파일을 처음 만들 때 그렇게 됐습니다.
//
// 꼭 한글을 헤더로 보내야 한다면 인코딩해서 보냅니다.
//   res.set("X-App-Name", encodeURIComponent("설비관리API"));
//   → X-App-Name: %EC%84%A4%EB%B9%84%EA%B4%80%EB%A6%ACAPI
//   받는 쪽에서 decodeURIComponent 로 되돌립니다.
//   번거로우니 웬만하면 본문에 담으세요.


// ── 섹션 5: ★ req.query 는 고칠 수 없습니다 (Express 5) ──

app.use((req, res, next) => {
  // 검색어 앞뒤 공백을 없애 두려고 이렇게 써 봅니다.
  if (typeof req.query.q === "string") {
    req.query.q = req.query.q.trim(); // ← 아무 일도 안 일어납니다
  }
  next();
});

app.get("/search", (req, res) => {
  res.json({
    받은값: req.query.q,
    공백이지워졌나: req.query.q === "표준",
  });
});

// 확인: GET /search?q=%20%20표준%20%20
// 응답: 200 {"받은값":"  표준  ","공백이지워졌나":false}

// ★★ 에러가 안 났는데 값도 안 바뀌었습니다.
//
//   Express 5 에서 req.query 는 '읽을 때마다 새로 만들어지는 값' 입니다.
//   우리가 바꾼 것은 그 순간 만들어진 복사본이고,
//   라우트에서 다시 읽으면 또 새로 만들어집니다. 고친 게 사라집니다.
//
//   req.query = {...} 로 통째로 바꿔도 마찬가지입니다. 조용히 무시됩니다.
//   (Express 4 에서는 바뀌었습니다. 그래서 옛날 코드가 여기서 깨집니다)
//
//   에러가 안 나기 때문에 이건 정말 찾기 어렵습니다.
//   "분명히 trim 했는데 왜 공백이 남아 있지?" 로 한참 헤매게 됩니다.
//
// 그럼 어떻게 하나 — 다른 이름에 담습니다.

app.use((req, res, next) => {
  req.정리된쿼리 = {};//새로운 객체공간 만들어서 

  for (const 키 of Object.keys(req.query)) {
    const 값 = req.query[키]; //키값 해당하는 값을 순환하며 새공가넹 넣음 
    req.정리된쿼리[키] = typeof 값 === "string" ? 값.trim() : 값;
    //Express의 일반적인 req.query에서는 쿼리 값이 보통 문자열로 들어오지만 혹심 모르니깐 삼항연산자
  }

  next();
});

app.get("/search2", (req, res) => {
  res.json({
    원본: req.query.q,
    정리됨: req.정리된쿼리.q,
  });
});

// 확인: GET /search2?q=%20%20표준%20%20
// 응답: 200 {"원본":"  표준  ","정리됨":"표준"}

// req 에 새 이름으로 붙이는 것은 잘 됩니다. 우리가 만든 속성이니까요.
// 못 바꾸는 것은 Express 가 관리하는 req.query 뿐입니다.
//
// ★ req.params 와 req.body 는 바꿀 수 있나
//   req.body 는 우리가 만든 것이나 마찬가지라 바꿔도 됩니다.
//   req.params 도 바뀌긴 하지만, 헷갈리니 건드리지 마세요.
//   "받은 것은 읽기만, 바꾼 것은 새 이름으로" 를 규칙으로 삼으면 안전합니다.


// ── 섹션 6: 미들웨어를 함수로 빼서 이름 붙이기 ──

// 지금까지는 app.use 안에 함수를 바로 적었습니다.
// 밖으로 빼면 이름이 생겨서 읽기 좋아지고, 다른 파일에서도 쓸 수 있습니다.

function 느린요청경고(기준ms) {
  // ★ 미들웨어를 '만들어 주는' 함수입니다.
  //   옵션을 받아서 미들웨어를 돌려줍니다. express.json({...}) 과 같은 모양입니다.
  return function (req, res, next) {
    const 시작 = Date.now();

    res.on("finish", () => {
      const 걸린시간 = Date.now() - 시작;
      if (걸린시간 > 기준ms) {
        console.log(`   └ ★ 느립니다: ${req.originalUrl} — ${걸린시간}ms`);
      }
    });

    next();
  };
}

app.use(느린요청경고(100)); // 100ms 를 넘으면 경고


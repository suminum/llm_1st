const 작업지시규칙 = [
  { 키: "title", 필수: true, 타입: "string", 최소길이: 2, 최대길이: 30 },
  { 키: "line", 필수: true, 허용: ["A", "B", "C"] },
  { 키: "priority", 필수: false, 타입: "number", 최소: 1, 최대: 5 },
];

function 전체검증(규칙들, 데이터) {
  const 항목 = [];

  for (const 규칙 of 규칙들) {
    const 이유 = 한줄검사(규칙, 데이터[규칙.키]);

    if (이유) {
      항목.push({ 키: 규칙.키, 이유 });
    }
  }

  return 항목;
}

function 결과찍기(제목, 데이터) {
  const 항목 = 전체검증(작업지시규칙, 데이터);

  if (항목.length === 0) {
    console.log(`${제목}: 통과`);
    return;
  }

  항목.forEach((하나) => console.log(`${제목}: ${하나.키} — ${하나.이유}`));
}


// ───── 문제 3 ─────
function 역할판단(사용자, 허용역할들) {
  if (!사용자) {
    return 401; // 누구인지 모름
  }

  if (!허용역할들.includes(사용자.role)) {
    return 403; // 누군지는 알지만 자격이 없음
  }

  return 200;
}

console.log(역할판단(null, ["admin"]));
// 출력: 401
console.log(역할판단({ role: "user" }, ["admin"]));
// 출력: 403
console.log(역할판단({ role: "admin" }, ["admin"]));
// 출력: 200
console.log(역할판단({ role: "manager" }, ["admin", "manager"]));
// 출력: 200
//
// ★ 401 과 403 을 가르는 것은 '사용자가 있느냐' 하나뿐입니다.
//   사용자가 없으면 자격을 따질 수조차 없습니다. 그래서 401 이 먼저입니다.
//
// ★ 허용역할들 을 배열로 받은 이유
//   역할이 하나만 될 거라고 가정하면, manager 가 생겼을 때 함수를 또 만들어야 합니다.
//   배열로 받으면 역할이 몇 개로 늘어도 그대로 씁니다.


// ───── 문제 4 ─────
function 증표읽기(헤더값) {
  if (!헤더값) {
    return null; // 헤더 자체가 없음
  }

  const [방식, 키] = 헤더값.split(" ");

  if (방식 !== "Bearer" || !키) {
    return null; // 형식이 틀림
  }

  return 키;
}

console.log(증표읽기(undefined));
// 출력: null
console.log(증표읽기("key-user-1"));
// 출력: null
console.log(증표읽기("Bearer"));
// 출력: null
console.log(증표읽기("Bearer key-user-1"));
// 출력: key-user-1
//
// ★ "Bearer" 만 왔을 때
//   split(" ") 결과가 ["Bearer"] 라서 키가 undefined 입니다.
//   !키 로 걸러 내지 않으면 undefined 를 그대로 돌려주게 됩니다.
//   그러면 사용자 목록에서 undefined 로 찾게 되어, 결국 401 이 되긴 합니다.
//   되긴 하지만 "형식이 틀림" 과 "키가 틀림" 은 다른 문제입니다.
//
// ★ 이 함수는 401 인지 아닌지만 판단합니다
//   "키가 진짜 있는 키인가" 는 사용자 목록을 봐야 알 수 있습니다.
//   함수 하나가 한 가지만 하게 나눠 두면 시험하기 쉽습니다.



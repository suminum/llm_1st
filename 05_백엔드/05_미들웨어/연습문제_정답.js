// Express 5 에서 req.query 를 고칠 수 없는 이유
//
// 무슨 일이 일어나나:
//   req.query.q = "고친값" 이라고 써도 에러가 안 납니다.
//   그런데 라우트에서 다시 읽으면 원래 값이 나옵니다. 고친 게 사라집니다.
//
// 왜 그런가:
//   Express 5 에서 req.query 는 '읽을 때마다 주소를 다시 분석해 만드는 값' 입니다.
//   내가 고친 것은 그 순간 만들어진 것이고, 다음에 읽으면 또 새로 만들어집니다.
//
// 왜 위험한가:
//   에러가 안 나기 때문입니다.
//   "분명히 trim 했는데 왜 공백이 남아 있지?" 로 한참 헤매게 됩니다.
//   Express 4 에서는 됐기 때문에, 옛날 코드를 옮길 때 조용히 깨집니다.
//
// 어떻게 하나:
//   새 이름에 담습니다.  req.정리된쿼리 = { ... }
//   req 에 내가 만든 속성을 붙이는 것은 잘 됩니다.
//
// 규칙으로 정리하면:
//   받은 것(req.query, req.params)은 읽기만 하고,
//   바꾼 것은 새 이름으로 붙인다.

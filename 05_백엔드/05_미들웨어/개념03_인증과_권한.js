// 같은 코드를 서른 번 쓸 수는 없습니다.
// 미들웨어 하나를 앞에 세워 두면 됩니다.
//
// ★ 여기서 만드는 것은 '흉내' 입니다.
//   진짜 로그인(비밀번호·토큰·만료시간)은 PART 4 의 11단원에서 배웁니다.
//   지금은 "미들웨어로 막는다" 는 구조만 익힙니다.

const express = require("express");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

function HttpError(코드, 메시지) {
  const 에러 = new Error(메시지);
  에러.status = 코드;
  return 에러;
}


// ── 섹션 1: 인증과 권한은 다릅니다 ──

// 두 단어가 비슷해 보이지만 완전히 다른 질문입니다.
//
//   인증(Authentication)   너 누구니?          →  아니면 401
//   권한(Authorization)    너 이거 해도 되니?   →  아니면 403
//
// 회사 건물로 비유하면
//   401  출입증이 없어서 로비도 못 들어감
//   403  출입증은 있는데 서버실 문이 안 열림
//
// ★ 이 둘을 바꿔 쓰면 상대가 엉뚱한 곳을 고칩니다.
//   401 을 받으면 "다시 로그인해야겠다" 고 생각합니다.
//   403 을 받으면 "관리자에게 권한을 달라고 해야겠다" 고 생각합니다.
//   403 이어야 하는데 401 을 주면, 로그인만 계속 다시 하게 됩니다.


// ── 섹션 2: 가짜 사용자 목록 ──

// 진짜 서버라면 데이터베이스에서 찾습니다. 지금은 객체에 적어 둡니다.

const 키별사용자 = {
  "key-user-1": { name: "김민준", role: "user" },
  "key-admin-1": { name: "이서연", role: "admin" },
};


// ── 섹션 3: 인증 미들웨어 ──

function 인증(req, res, next) {
  // 로그인 증표는 Authorization 헤더에 담아 보내는 것이 약속입니다.
  const 헤더값 = req.get("Authorization");

  if (!헤더값) {
    throw HttpError(401, "로그인이 필요합니다");
  }

  // "Bearer key-user-1" 모양입니다. 앞의 Bearer 는 '이 증표를 가진 자' 라는 뜻입니다.
  const [방식, 키] = 헤더값.split(" ");

  if (방식 !== "Bearer" || !키) {
    throw HttpError(401, "Authorization 형식이 올바르지 않습니다");
  }

  const 사용자 = 키별사용자[키];

  if (!사용자) {
    throw HttpError(401, "증표가 올바르지 않습니다");
  }

  // ★ 여기가 핵심입니다.
  //   찾아낸 사용자를 req 에 붙여 둡니다.
  //   이제 아래 모든 라우트가 req.user 를 그냥 꺼내 쓸 수 있습니다.
  req.user = 사용자;

  next();
}

// ★ 왜 헤더에 담나
//   쿼리(?key=...)에 담으면 서버 접속 기록과 브라우저 방문 기록에 남습니다.
//   링크를 복사해 보내면 증표까지 딸려 갑니다.
//   헤더는 기록에 안 남습니다. 비밀은 헤더나 본문에 담으세요.


// ── 섹션 4: 권한 미들웨어 ──

function 관리자만(req, res, next) {
  // 이 미들웨어는 인증 뒤에 와야 합니다. req.user 가 있어야 하니까요.
  if (req.user.role !== "admin") {
    throw HttpError(403, "관리자만 할 수 있습니다");
  }

  next();
}

// ★ 인증과 권한을 왜 따로 만드나
//   합쳐 두면 "로그인만 하면 되는 주소" 에서도 관리자 검사를 하게 됩니다.
//   하나씩 나눠 두면 필요한 것만 골라 붙일 수 있습니다.
//
//     app.get("/me", 인증, ...)                    로그인만
//     app.delete("/users/:id", 인증, 관리자만, ...)  로그인 + 관리자


// ── 섹션 5: 아무나 볼 수 있는 주소 ──

app.get("/public", (req, res) => {
  res.json({ 설명: "누구나 볼 수 있습니다" });
});

// 확인: GET /public
// 응답: 200 {"설명":"누구나 볼 수 있습니다"}

// 미들웨어를 안 붙였으니 증표 없이도 됩니다.


// ── 섹션 6: 로그인해야 볼 수 있는 주소 ──

app.get("/me", 인증, (req, res) => {
  res.json({ 이름: req.user.name, 역할: req.user.role });
});

// 확인: GET /me
// 응답: 401 {"error":"로그인이 필요합니다"}

// 확인: GET /me [Authorization: key-user-1]
// 응답: 401 {"error":"Authorization 형식이 올바르지 않습니다"}

// (Bearer 없이 키만 보낸 경우입니다. 형식이 틀렸습니다)

// 확인: GET /me [Authorization: Bearer no-such-key]
// 응답: 401 {"error":"증표가 올바르지 않습니다"}

// ★ 시험용 키를 전부 영어로 쓴 이유
//   헤더 값에는 한글을 담을 수 없습니다. 개념02 섹션 4-2 에서 본 그대로입니다.
//   보낼 때도 마찬가지라, 한글 증표를 만들면 요청 자체가 안 나갑니다.
//   증표·키·토큰은 언제나 영어와 숫자로 만드세요.

// 확인: GET /me [Authorization: Bearer key-user-1]
// 응답: 200 {"이름":"김민준","역할":"user"}

// 확인: GET /me [Authorization: Bearer key-admin-1]
// 응답: 200 {"이름":"이서연","역할":"admin"}

// ★ 라우트 안에는 인증 코드가 한 줄도 없습니다.
//   "req.user 는 이미 있다" 고 믿고 쓰면 됩니다.
//   미들웨어가 없으면 여기까지 못 오니까요.


// ── 섹션 7: 관리자만 할 수 있는 일 ──

app.delete("/users/:id", 인증, 관리자만, (req, res) => {
  res.json({ 지운사람: req.params.id, 지시한사람: req.user.name });
});

// 확인: DELETE /users/7
// 응답: 401 {"error":"로그인이 필요합니다"}

// 확인: DELETE /users/7 [Authorization: Bearer key-user-1]
// 응답: 403 {"error":"관리자만 할 수 있습니다"}

// 확인: DELETE /users/7 [Authorization: Bearer key-admin-1]
// 응답: 200 {"지운사람":"7","지시한사람":"이서연"}

// ★ 세 줄을 나란히 보세요.
//   증표 없음        → 401  (너 누구니)
//   증표는 있으나 user → 403  (누군지 알겠는데 안 돼)
//   증표가 admin      → 200  (통과)
//
//   이 세 갈래가 인증·권한의 전부입니다.


// ── 섹션 8: 여러 라우트에 한꺼번에 붙이기 ──

// 라우트마다 인증 을 적는 것도 금방 지겨워집니다.
// /admin 아래 전체를 한 번에 막을 수 있습니다.

app.use("/admin", 인증, 관리자만);

app.get("/admin/stats", (req, res) => {
  res.json({ 통계: "관리자만 봅니다", 보는사람: req.user.name });
});

app.get("/admin/logs", (req, res) => {
  res.json({ 기록: "여기도 관리자만" });
});

// 확인: GET /admin/stats
// 응답: 401 {"error":"로그인이 필요합니다"}

// 확인: GET /admin/stats [Authorization: Bearer key-user-1]
// 응답: 403 {"error":"관리자만 할 수 있습니다"}

// 확인: GET /admin/stats [Authorization: Bearer key-admin-1]
// 응답: 200 {"통계":"관리자만 봅니다","보는사람":"이서연"}

// 확인: GET /admin/logs [Authorization: Bearer key-admin-1]
// 응답: 200 {"기록":"여기도 관리자만"}

// app.use 에 미들웨어를 여러 개 넘길 수 있습니다. 순서대로 실행됩니다.
//
// ★★ 이 방식의 진짜 장점
//   나중에 /admin/users 를 새로 만들 때, 인증을 붙이는 걸 '잊어버릴 수가 없습니다'.
//   이미 위에서 통째로 막아 뒀으니까요.
//
//   라우트마다 붙이는 방식은 하나만 빠뜨려도 구멍이 됩니다.
//   보안은 "빠뜨릴 수 없게 만드는 것" 이 요령입니다.


// ── 섹션 9: 순서를 틀리면 ──

// 관리자만 을 인증 보다 먼저 두면 어떻게 될까요?
//
//   app.use("/admin", 관리자만, 인증);
//
// 관리자만 안에서 req.user.role 을 읽는데 req.user 가 아직 없습니다.
//   → TypeError: Cannot read properties of undefined (reading 'role')
//   → 500 입니다. 401 이어야 하는데요.
//
// 미들웨어는 '앞에서 만든 것을 뒤에서 쓴다' 는 관계가 있습니다.
// 순서를 함부로 바꾸면 안 됩니다.
//
// ★ 방어적으로 만들려면 관리자만 안에서 이렇게 확인할 수 있습니다.
//
//     if (!req.user) throw HttpError(401, "로그인이 필요합니다");
//
//   순서를 잘못 짜도 500 대신 401 이 나갑니다.
//   "앞 미들웨어가 제대로 돌았는지" 를 확인하는 습관은 좋습니다.


app.use((req, res) => {
  res.status(404).json({ error: "그런 주소가 없습니다" });
});

app.use((err, req, res, next) => {
  console.error(`[에러] ${req.method} ${req.path} — ${err.message}`);
  const 코드 = err.status || 500;
  res.status(코드).json({ error: 코드 === 500 ? "서버에서 문제가 생겼습니다" : err.message });
});


app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}/public`);
});



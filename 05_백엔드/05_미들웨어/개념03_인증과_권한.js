//   2. 주소칸 아래의 Headers 탭을 누릅니다
//   3. Key 에      Authorization
//      Value 에    Bearer key-user-1
//   4. Send
//
// 또는 Authorization 탭에서 Type 을 Bearer Token 으로 고르고
// Token 칸에 key-user-1 만 넣어도 됩니다. Postman 이 Bearer 를 붙여 줍니다.
//
// 눌러 볼 것
//
//   GET    /public                            증표 없이 → 200
//   GET    /me                                증표 없이 → 401
//   GET    /me          key-user-1            → 200 김민준
//   DELETE /users/7     key-user-1            → 403
//   DELETE /users/7     key-admin-1           → 200
//   GET    /admin/stats key-user-1            → 403
//   GET    /admin/stats key-admin-1           → 200
//
// 401 과 403 이 언제 갈리는지 손으로 확인하는 것이 목적입니다.



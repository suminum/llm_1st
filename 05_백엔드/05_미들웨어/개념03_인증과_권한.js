// 직접 해 볼 것
// ============================================================
//
// ✏️ 직접 해보기 1 — 키별사용자 에 자기 이름으로 사용자를 하나 추가하고
//                    그 키로 /me 를 불러 보세요.
//
// ✏️ 직접 해보기 2 — 역할이 "manager" 인 사용자를 추가하고,
//                    "user 는 안 되고 manager 와 admin 은 되는" 미들웨어를 만들어 보세요.
//                    (힌트: ["manager", "admin"].includes(req.user.role))
//
// ✏️ 직접 해보기 3 — 섹션 8의 app.use("/admin", 인증, 관리자만) 에서
//                    관리자만 을 빼 보세요. user 키로 /admin/stats 가 되나요?
//                    (확인했으면 되돌리세요)
//
// ✏️ 직접 해보기 4 — 섹션 9 처럼 순서를 바꿔 보고 500 이 나는 것을 확인하세요.
//                    그다음 관리자만 안에 req.user 확인을 넣어
//                    401 이 나오게 고쳐 보세요.
//
// ✏️ 직접 해보기 5 — 인증 미들웨어에서 req.user 대신 req.사용자 라는 이름을 써 보세요.
//                    잘 되나요? 그런데 왜 다들 req.user 라고 쓸까요?
//                    (힌트: 남이 만든 미들웨어를 가져다 쓸 때 이름이 맞아야 합니다)
//
// ✏️ 직접 해보기 6 — /me 를 부를 때마다 터미널에 누가 불렀는지 남겨 보세요.
//                    개념02 의 기록 미들웨어에 req.user 를 더하면 됩니다.
//                    (힌트: 기록 미들웨어가 인증보다 위에 있으면 req.user 가 아직 없습니다)


// ── 자주 하는 실수 ──

// [실수 1] 401 과 403 을 바꿔 씀
//   증표가 없거나 틀림 → 401
//   증표는 맞는데 자격이 모자람 → 403
//   받는 쪽이 무엇을 고쳐야 할지가 달라집니다.

// [실수 2] 권한 미들웨어를 인증보다 먼저 둠
//   req.user 가 아직 없어서 500 이 납니다.

// [실수 3] 라우트마다 인증을 붙이다가 하나를 빠뜨림
//   그 하나가 구멍이 됩니다. app.use 로 통째로 막는 편이 안전합니다.

// [실수 4] 증표를 쿼리에 담음
//   /me?key=key-admin-1 은 서버 기록에 그대로 남습니다.
//   헤더에 담으세요.

// [실수 5] 헤더 이름을 대문자로 직접 찾음
//   req.headers["Authorization"] 은 undefined 입니다.
//   req.get("Authorization") 을 쓰면 대소문자를 안 가립니다.

// [실수 6] split(" ") 결과를 확인 안 함
//   "Bearer" 만 보내면 키가 undefined 입니다.
//   그대로 객체에서 찾으면 undefined 가 나와 401 이 되긴 하지만,
//   형식이 틀린 것과 키가 틀린 것은 다른 문제입니다. 나눠서 답하세요.


// ── 정리 ──

// 1. 인증은 "누구냐", 권한은 "그걸 해도 되냐" 다. 다른 일이다.
// 2. 상태코드도 다르다. 누구인지 모르면 401, 누구인지는 아는데 자격이 없으면 403 이다.
// 3. 순서가 정해져 있다. 인증 다음에 권한이다.
//    뒤집으면 누구인지도 모르는 채로 자격을 따지게 된다.
// 4. 라우트마다 하나씩 붙이면 언젠가 하나를 빠뜨린다. 구간에 한꺼번에 거는 편이 안전하다.
// 5. 증표는 쿼리에 담지 않는다. 주소는 기록에 그대로 남는다. 헤더에 담는다.
// 6. 헤더는 req.get("Authorization") 으로 꺼낸다. 소문자로 직접 찾지 않는다.
// 7. split(" ") 결과는 확인하고 쓴다. 형식이 다르게 오면 undefined 가 나온다.

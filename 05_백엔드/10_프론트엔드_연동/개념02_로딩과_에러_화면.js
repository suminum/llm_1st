// [실수 7] 화면에서 막았으니 서버는 안 막아도 된다고 생각
//   화면 잠금은 실수를 막을 뿐입니다. Postman 으로는 그냥 뚫립니다.


// ── 정리 ──

// 1. 화면에는 네 가지 상태가 있다 — 로딩 중 · 성공 · 빈 결과 · 에러.
//    넷 다 그려야 한다. 성공만 그리면 나머지 셋에서 화면이 멈춘 것처럼 보인다.
// 2. 빈 결과는 에러가 아니다. "없습니다" 를 보여 준다.
// 3. 로딩을 안 보여 주면 사용자는 눌렀는지 아닌지 모르고 또 누른다.
// 4. 에러를 콘솔에만 찍으면 사용자는 아무것도 모른다. 화면에 띄운다.
// 5. 에러를 띄웠으면 다시 시도할 방법도 준다. 새로고침하라고 하지 않는다.
// 6. 버튼은 요청이 나가는 동안 잠근다. 푸는 것은 finally 에 둔다.
//    성공에만 두면 실패했을 때 영영 잠긴 채로 남는다.
// 7. 늦게 온 응답이 최신 화면을 덮어쓸 수 있다.
//    요청마다 번호를 붙여 두고 마지막 것만 그린다.
// 8. 화면에서 막았다고 서버 검증을 빼면 안 된다. 화면을 거치지 않는 요청이 있다.

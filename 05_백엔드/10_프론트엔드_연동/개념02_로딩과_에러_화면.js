//   ① 로딩 중
//   ② 성공
//   ③ 실패
//   ④ 성공했는데 결과가 없음     ← 이걸 제일 많이 빠뜨립니다
//
// ④를 빠뜨리면 빈 화면이 나옵니다.
// 사용자는 "고장났나?" 하고 새로고침만 계속합니다.

const express = require("express");
const path = require("path");

const app = express();
const PORT = Number(process.env.PORT) || 3000;

app.use(express.json());
app.use(express.static(path.join(__dirname, "public")));

app.get("/", (req, res) => res.redirect("/02_로딩과에러.html"));

// 확인: GET /02_로딩과에러.html
// 응답: 200


const 설비들 = [
  { id: 1, name: "컨베이어 1호", line: "A", status: "가동" },
  { id: 2, name: "프레스 1호", line: "B", status: "정지" },
];

let 받은횟수 = 0;

const 잠깐 = (ms) => new Promise((r) => setTimeout(r, ms));


// ── 섹션 1: 네 가지 상태를 만들어 주는 API ──

app.get("/api/v1/equipments", async (req, res) => {
  if (req.query.count) 받은횟수 += 1;

  // 일부러 늦추기 (로딩 화면을 보려고)
  if (req.query.delay) await 잠깐(Number(req.query.delay));

  // 일부러 실패하기
  if (req.query.fail) {
    return res.status(500).json({
      error: { code: "INTERNAL_ERROR", message: "서버에서 문제가 생겼습니다" },
    });
  }

  const 결과 = req.query.line ? 설비들.filter((설비) => 설비.line === req.query.line) : 설비들;

  res.json({ data: 결과, meta: { total: 결과.length } });
});

// 확인: GET /api/v1/equipments
// 응답: 200 {"data":[{"id":1,"name":"컨베이어 1호","line":"A","status":"가동"},{"id":2,"name":"프레스 1호","line":"B","status":"정지"}],"meta":{"total":2}}

// 확인: GET /api/v1/equipments?line=Z
// 응답: 200 {"data":[],"meta":{"total":0}}

// 확인: GET /api/v1/equipments?fail=1
// 응답: 500 {"error":{"code":"INTERNAL_ERROR","message":"서버에서 문제가 생겼습니다"}}

app.post("/api/v1/count/reset", (req, res) => {
  받은횟수 = 0;
  res.json({ data: { 횟수: 0 } });
});

// 확인: POST /api/v1/count/reset
// 응답: 200 {"data":{"횟수":0}}

// ★ 버튼을 누를 때마다 0 으로 되돌립니다.
//   그래야 "이번에 몇 번 나갔나" 를 그대로 볼 수 있습니다.

app.get("/api/v1/count", (req, res) => {
  res.json({ data: { 횟수: 받은횟수 } });
});

app.get("/api/v1/label", async (req, res) => {
  if (req.query.delay) await 잠깐(Number(req.query.delay));
  res.json({ data: { label: req.query.label ?? "-" } });
});

// 확인: GET /api/v1/label?label=시험
// 응답: 200 {"data":{"label":"시험"}}


// ── 섹션 2: 화면으로 확인 ──

// 화면: 02_로딩과에러.html  #정상

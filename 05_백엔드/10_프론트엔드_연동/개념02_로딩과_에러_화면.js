// 화면: 02_로딩과에러.html  #느림
// 보임: #목록칸  컨베이어 1호

// ★ 2초 걸리는 요청입니다. 화면검증이 기다렸다가 확인합니다.
//   브라우저로 직접 눌러 보면 그동안 "불러오는 중..." 이 보입니다.


// ── 섹션 3: 버튼 잠그기 ──

// 화면: 02_로딩과에러.html  #안잠금
// 보임: #횟수  3

// 화면: 02_로딩과에러.html  #잠금
// 보임: #횟수  1

// ★★ 서버가 받은 횟수가 다릅니다. 3번과 1번입니다.
//
//   느린 요청 중에 버튼을 또 누를 수 있으면, 같은 요청이 여러 번 나갑니다.
//   조회면 서버만 힘들고 끝이지만, '등록' 이면 데이터가 세 개 만들어집니다.
//
//   결제 버튼이라면? 세 번 결제됩니다. 실제로 나는 사고입니다.
//
// ★ 잠금 해제는 반드시 finally 에서
//     try { await 보내기(); } finally { 버튼.disabled = false; }
//   catch 에만 쓰면 성공했을 때 안 풀리고,
//   try 끝에만 쓰면 실패했을 때 안 풀립니다. 버튼이 영영 안 눌립니다.
//
// ★ 서버도 막아야 합니다
//   화면 잠금은 '실수' 를 막을 뿐입니다.
//   Postman 으로는 얼마든지 여러 번 보낼 수 있습니다.
//   중요한 요청은 서버에서도 중복을 막아야 합니다. (08단원 CORS 와 같은 이야기입니다)


// ── 섹션 4: ★ 늦게 온 응답이 덮어쓰는 문제 ──

// 화면: 02_로딩과에러.html  #경쟁안막음
// 보임: #경쟁칸  느린 응답

// 화면: 02_로딩과에러.html  #경쟁막음
// 보임: #경쟁칸  빠른 응답

// ★★★ 같은 순서로 두 요청을 보냈는데 결과가 다릅니다.
//
//   안 막으면
//     느린 요청(800ms) 보냄 → 빠른 요청(100ms) 보냄
//     100ms 뒤 "빠른 응답" 이 화면에 나옴
//     800ms 뒤 "느린 응답" 이 도착해서 덮어씀        ← 옛날 결과가 이김
//
//   막으면
//     요청마다 번호를 붙여 두고, 마지막 번호가 아니면 결과를 버립니다.
//     "빠른 응답" 이 남습니다.
//
// ★ 이게 언제 진짜로 일어나나
//   검색창에 글자를 칠 때마다 요청을 보내는 화면을 떠올리세요.
//
//     "설" 을 치면 → 요청 A (결과가 많아서 느림)
//     "설비" 를 치면 → 요청 B (결과가 적어서 빠름)
//
//   B 가 먼저 도착해 화면을 그렸는데, A 가 나중에 도착해 덮어씁니다.
//   검색창에는 "설비" 가 적혀 있는데 목록은 "설" 의 결과입니다.
//
//   사용자는 "검색이 이상해요" 라고 합니다. 개발자는 재현을 못 합니다.
//   네트워크가 빠른 사무실에서는 잘 안 나기 때문입니다.
//
// ★ 막는 법 세 가지
//   ① 요청 번호를 붙여 마지막 것만 반영 (지금 방식. 가장 간단합니다)
//   ② AbortController 로 앞 요청을 취소
//   ③ 입력이 멈춘 뒤에 보내기 (디바운스). 요청 수 자체를 줄입니다
//
//   ①과 ③을 함께 쓰는 것이 흔합니다.


app.use((req, res) => {
  res.status(404).json({ error: { code: "ROUTE_NOT_FOUND", message: "그런 주소가 없습니다" } });
});

app.use((err, req, res, next) => {
  console.error(`[에러] ${req.method} ${req.path} — ${err.message}`);
  res.status(500).json({ error: { code: "INTERNAL_ERROR", message: "서버에서 문제가 생겼습니다" } });
});


app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}`);
});



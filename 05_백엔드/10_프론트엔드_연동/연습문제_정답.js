// ───── 문제 4·5 ───── (기다려야 하므로 async 안에서)
function 디바운스(함수, 시간) {
  let 타이머 = null;

  return (...인자들) => {
    clearTimeout(타이머);
    타이머 = setTimeout(() => 함수(...인자들), 시간);
  };
}

function 마지막만반영() {
  let 마지막번호 = 0;

  return async (일, 반영) => {
    마지막번호 += 1;
    const 내번호 = 마지막번호;

    const 결과 = await 일();

    // 내가 마지막 요청이 아니면 버립니다.
    if (내번호 !== 마지막번호) return false;

    반영(결과);
    return true;
  };
}

const 잠깐 = (ms) => new Promise((r) => setTimeout(r, ms));

async function main() {
  // ── 문제 4 ──
  let 부른횟수 = 0;
  let 마지막글자 = "";

  const 검색보내기 = 디바운스((글자) => {
    부른횟수 += 1;
    마지막글자 = 글자;
  }, 100);

  // "설비관리" 를 한 글자씩 치는 것을 흉내 냅니다.
  for (const 글자 of ["설", "설비", "설비관", "설비관리"]) {
    검색보내기(글자);
    await 잠깐(20);
  }

  await 잠깐(200); // 타이머가 돌 시간

  console.log(`디바운스: ${부른횟수}번 실행, 마지막 글자 "${마지막글자}"`);
  // 출력: 디바운스: 1번 실행, 마지막 글자 "설비관리"
  //
  // ★ 네 번 쳤는데 요청은 한 번입니다.
  //   글자를 칠 때마다 보내면 요청이 네 배가 되고,
  //   늦게 온 응답 문제(문제 5)까지 함께 옵니다.

  // ── 문제 5 ──
  const 반영하기 = 마지막만반영();
  let 화면 = "";

  const 느린것 = 반영하기(
    async () => {
      await 잠깐(80);
      return "느린 응답";
    },
    (값) => (화면 = 값)
  );

  const 빠른것 = 반영하기(
    async () => {
      await 잠깐(10);
      return "빠른 응답";
    },
    (값) => (화면 = 값)
  );

  const [느린결과, 빠른결과] = await Promise.all([느린것, 빠른것]);

  console.log(`느린 것 반영됨: ${느린결과}`);
  // 출력: 느린 것 반영됨: false
  console.log(`빠른 것 반영됨: ${빠른결과}`);
  // 출력: 빠른 것 반영됨: true
  console.log(`화면: ${화면}`);
  // 출력: 화면: 빠른 응답
  //
  // ★★ 느린 것을 먼저 보냈는데도 화면에는 빠른 것이 남았습니다.
  //
  //   막지 않았다면 순서가 이렇습니다.
  //     10ms 뒤  "빠른 응답" 이 화면에 나옴
  //     80ms 뒤  "느린 응답" 이 도착해 덮어씀    ← 옛날 결과가 이김
  //
  //   요청마다 번호를 붙여 두고 마지막 번호가 아니면 버리면 됩니다.
  //
  // ★ 이게 검색창에서 진짜로 일어납니다.
  //   "설" 의 결과(느림)가 "설비관리" 의 결과(빠름)를 덮어씁니다.
  //   검색창에는 "설비관리" 가 적혀 있는데 목록은 "설" 의 결과입니다.
  //   네트워크가 빠른 사무실에서는 재현이 잘 안 돼서 더 어렵습니다.
}

main();



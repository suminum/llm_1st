// 화면 검증과 서버 검증
//
// 화면 검증이 하는 일:
//   사용자를 편하게 합니다. 서버에 다녀오기 전에 알려 주니 빠릅니다.
//   required, minlength 같은 HTML 속성으로도 됩니다.
//
// 서버 검증이 하는 일:
//   진짜 방어선입니다.
//   Postman·curl 로 보내면 화면을 통째로 건너뜁니다. (05단원 개념04)
//
// 화면 검증만 하면:
//   Postman 한 번이면 뚫립니다. 이름이 없는 설비, 라인이 Z 인 설비가 만들어집니다.
//
// 서버 검증만 하면:
//   동작은 안전합니다. 다만 사용자가 답답합니다.
//   글자를 다 치고 버튼을 눌러야 "2글자 이상" 을 알게 됩니다.
//
// 규칙이 두 곳에 생기는 문제:
//   화면에도 "2글자 이상" 을 적으면, 서버 규칙이 바뀔 때 화면도 고쳐야 합니다.
//   한쪽만 고치면 어긋납니다.
//   "화면에서는 되는데 저장이 안 돼요" 또는 그 반대가 됩니다.
//
// 이 자료가 고른 방법:
//   규칙은 서버에만 둡니다.
//   화면은 서버가 준 details 를 칸마다 붙여 주기만 합니다.
//   규칙이 한 곳에 있으니 어긋날 일이 없습니다.
//
//   실무에서는 required 같은 가벼운 것만 화면에 두고,
//   진짜 규칙은 서버에 두는 방식을 많이 씁니다.
//   또는 규칙을 한 곳에 적어 두고 화면과 서버가 함께 쓰기도 합니다. (TS + zod)

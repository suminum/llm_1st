function 주소만들기(기준, 상태) {
  const 쿼리 = new URLSearchParams();

  쿼리.set("page", 상태.page);
  쿼리.set("limit", 상태.limit);

  // ★ 빈 값은 아예 안 넣습니다. ?q= 를 보내면 서버가 '빈 검색어' 를 받습니다.
  if (상태.sort) 쿼리.set("sort", 상태.sort);
  if (상태.q) 쿼리.set("q", 상태.q);
  if (상태.line) 쿼리.set("line", 상태.line);

  return `${기준}?${쿼리.toString()}`;
}


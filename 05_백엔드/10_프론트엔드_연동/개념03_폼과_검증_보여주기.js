// 06단원에서 검증 실패를 이렇게 돌려주기로 했습니다.
//
//   { "error": { "code": "VALIDATION_FAILED",
//                "message": "입력값이 올바르지 않습니다",
//                "details": [ { "키": "name", "이유": "2글자 이상이어야 합니다" } ] } }
//
// details 를 왜 넣었는지가 이 파일에서 드러납니다.
// message 만 있으면 "입력값이 올바르지 않습니다" 하나만 띄우게 됩니다.
// 사용자는 어느 칸이 틀렸는지 모릅니다.

const express = require("express");
const path = require("path");

const app = express();
const PORT = Number(process.env.PORT) || 3000;

app.use(express.json());
app.use(express.static(path.join(__dirname, "public")));

app.get("/", (req, res) => res.redirect("/03_폼.html"));

// 확인: GET /03_폼.html
// 응답: 200


let 설비들 = [];
let 다음번호 = 1;

const 라인값들 = ["A", "B", "C"];


// ── 섹션 1: 서버는 06단원 형식 그대로 ──

app.get("/api/v1/equipments", (req, res) => {
  res.json({ data: 설비들 });
});

// 확인: GET /api/v1/equipments
// 응답: 200 {"data":[]}

app.post("/api/v1/equipments", (req, res) => {
  const { name, line } = req.body || {};
  const 항목 = [];

  if (!name) 항목.push({ 키: "name", 이유: "필수입니다" });
  else if (name.length < 2) 항목.push({ 키: "name", 이유: "2글자 이상이어야 합니다" });
  else if (name.length > 20) 항목.push({ 키: "name", 이유: "20글자 이하여야 합니다" });

  if (!line) 항목.push({ 키: "line", 이유: "필수입니다" });
  else if (!라인값들.includes(line))
    항목.push({ 키: "line", 이유: "A, B, C 중 하나여야 합니다" });

  if (항목.length > 0) {
    return res.status(400).json({
      error: { code: "VALIDATION_FAILED", message: "입력값이 올바르지 않습니다", details: 항목 },
    });
  }

  if (설비들.some((설비) => 설비.name === name)) {
    return res.status(409).json({
      error: { code: "DUPLICATED", message: "이미 있는 설비 이름입니다" },
    });
  }

  const 새설비 = { id: 다음번호, name, line, status: "정지" };
  다음번호 += 1;
  설비들.push(새설비);

  res.status(201).json({ data: 새설비 });
});

// 확인: POST /api/v1/equipments {"name":"용","line":"Z"}
// 응답: 400 {"error":{"code":"VALIDATION_FAILED","message":"입력값이 올바르지 않습니다","details":[{"키":"name","이유":"2글자 이상이어야 합니다"},{"키":"line","이유":"A, B, C 중 하나여야 합니다"}]}}

// 확인: POST /api/v1/equipments {"name":"컨베이어 1호","line":"A"}
// 응답: 201 {"data":{"id":1,"name":"컨베이어 1호","line":"A","status":"정지"}}

// 확인: POST /api/v1/equipments {"name":"컨베이어 1호","line":"B"}
// 응답: 409 {"error":{"code":"DUPLICATED","message":"이미 있는 설비 이름입니다"}}


// ── 섹션 2: 화면으로 확인 ──

// 비운 채로 보내면 두 칸 모두에 오류가 붙습니다.
// 화면: 03_폼.html  #보내기
// 보임: #오류-name  필수입니다
// 보임: #오류-line  필수입니다

// ★★ 오류가 '칸 아래' 에 각각 붙었습니다.
//   message 만 썼다면 "입력값이 올바르지 않습니다" 하나뿐이었을 것입니다.
//   사용자는 무엇을 고쳐야 할지 몰라 아무거나 바꿔 보게 됩니다.


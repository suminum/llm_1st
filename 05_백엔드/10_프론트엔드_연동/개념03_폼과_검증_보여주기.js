// 입력: #name=컨베이어 1호  #line=A
// 보임: #알림  등록했습니다
// 보임: #목록  컨베이어 1호

// ★ 성공하면 폼을 비웁니다 (폼.reset).
//   안 비우면 사용자가 같은 것을 또 등록하기 쉽습니다.

// 같은 이름을 또 등록하면 409 가 name 칸에 붙습니다.
// 한 번 등록하고, 화면을 새로 열어 같은 이름으로 또 보냅니다.
// (서버는 켜져 있는 동안 앞의 등록을 기억하고 있습니다)
// 화면: 03_폼.html  #보내기
// 입력: #name=프레스 1호  #line=B
// 보임: #알림  등록했습니다

// 화면: 03_폼.html  #보내기
// 입력: #name=프레스 1호  #line=B
// 보임: #오류-name  이미 있는 설비 이름입니다

// ★★ 여기가 재미있는 부분입니다.
//   409 DUPLICATED 에는 details 가 없습니다. message 만 있습니다.
//   그런데 화면은 그걸 name 칸에 붙였습니다.
//
//   "이름 중복은 name 칸 문제다" 라는 것을 화면이 알기 때문입니다.
//   서버가 모든 것을 알려 줄 필요는 없습니다.
//   code 로 갈래를 나누고, 화면이 어디에 보여 줄지 정하면 됩니다.
//
//   이게 06단원에서 code 를 따로 둔 이유입니다.
//   message 글자로 판단했다면 서버가 맞춤법만 고쳐도 깨졌을 것입니다.

// 오류가 난 뒤 제대로 고쳐 보내면 지난 오류가 사라져야 합니다.
// 빈 채로 한 번 보내고(오류), 값을 채워 다시 보냅니다(성공).
// 화면: 03_폼.html  #보내기 >> 입력(#name=검사기 1호) >> 입력(#line=C) >> #보내기
// 보임: #오류-name  !필수입니다
// 보임: #알림  등록했습니다

// ★ 첫 번째 줄의 ! 는 '없어야 한다' 는 뜻입니다.
//   첫 번째 클릭에서 "필수입니다" 가 붙었고,
//   두 번째 클릭 전에 값을 넣었으니 그 오류는 사라져야 합니다.
//
//   오류지우기() 를 안 부르면 고친 칸에도 옛날 오류가 남아 있습니다.
//   "다 고쳤는데 왜 빨간 글씨가 있지?" 하고 헤매게 됩니다.


app.use((req, res) => {
  res.status(404).json({ error: { code: "ROUTE_NOT_FOUND", message: "그런 주소가 없습니다" } });
});

app.use((err, req, res, next) => {
  console.error(`[에러] ${req.method} ${req.path} — ${err.message}`);
  res.status(500).json({ error: { code: "INTERNAL_ERROR", message: "서버에서 문제가 생겼습니다" } });
});


app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}`);
});



function 쪽정보(query) {
  let page = Number(query.page);
  let limit = Number(query.limit);

  if (!Number.isInteger(page) || page < 1) page = 1;
  if (!Number.isInteger(limit) || limit < 1) limit = 10;
  if (limit > 100) limit = 100;

  return { page, limit };
}

function 정렬조건(sort) {
  if (!sort) return [];

  return sort
    .split(",")
    .map((조각) => 조각.trim())
    .filter(Boolean)
    .map((조각) =>
      조각.startsWith("-") ? { 키: 조각.slice(1), 방향: -1 } : { 키: 조각, 방향: 1 }
    );
}

function 비교하기(a, b, 조건들) {
  for (const { 키, 방향 } of 조건들) {
    const 왼쪽 = a[키];
    const 오른쪽 = b[키];

    if (typeof 왼쪽 === "string" && typeof 오른쪽 === "string") {
      const 결과 = 왼쪽.localeCompare(오른쪽, "ko", { numeric: true });
      if (결과 !== 0) return 결과 * 방향;
      continue;
    }

    if (왼쪽 < 오른쪽) return -1 * 방향;
    if (왼쪽 > 오른쪽) return 1 * 방향;
  }

  return 0;
}

app.get("/api/v1/equipments", (req, res) => {
  const q = (req.query.q ?? "").trim().toLowerCase();
  const { line } = req.query;

  let 결과 = 설비목록();

  if (q) {
    결과 = 결과.filter((설비) =>
      ["name", "line", "status"].some((키) => String(설비[키]).toLowerCase().includes(q))
    );
  }

  if (line) 결과 = 결과.filter((설비) => 설비.line === line);

  const 조건들 = 정렬조건(req.query.sort);
  if (조건들.length > 0) 결과 = [...결과].sort((a, b) => 비교하기(a, b, 조건들));

  const total = 결과.length; // ★ 자르기 전에 셉니다 (06단원 개념03)
  const { page, limit } = 쪽정보(req.query);
  const 시작 = (page - 1) * limit;

  res.json({
    data: 결과.slice(시작, 시작 + limit),
    meta: { page, limit, total, totalPages: Math.ceil(total / limit) },
  });
});


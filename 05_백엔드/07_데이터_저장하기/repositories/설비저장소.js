// "데이터를 어디에 어떻게 저장하는가" 를 이 파일 하나에 가둡니다.
// ============================================================
//
// ★★ 이 파일의 규칙 — 여기에는 HTTP 가 없습니다.
//
//   req, res 를 쓰지 않습니다
//   상태코드를 모릅니다 (404 를 내지 않습니다)
//   못 찾으면 null 을 돌려줄 뿐입니다
//
//   왜 그럴까요?
//   이 파일은 "설비 데이터를 다루는 법" 만 압니다.
//   그걸 웹으로 서비스할지, 명령줄 도구로 만들지, 배치 작업으로 돌릴지는
//   이 파일이 알 바가 아닙니다.
//
//   나중에 "매일 밤 설비 목록을 엑셀로 뽑는 프로그램" 을 만든다면
//   이 파일을 그대로 가져다 쓸 수 있습니다. Express 없이도요.

const fs = require("fs");
const path = require("path");

// .. 로 한 칸 올라갔다가 data 로 내려갑니다.
const 파일경로 = path.join(__dirname, "..", "data", "설비.json");

// 폴더가 없으면 만듭니다.
fs.mkdirSync(path.dirname(파일경로), { recursive: true });


// ── 안에서만 쓰는 함수 (내보내지 않습니다) ──

async function 읽기() {
  try {
    const 글자 = await fs.promises.readFile(파일경로, "utf-8");
    return JSON.parse(글자);
  } catch (에러) {
    if (에러.code === "ENOENT") return [];
    throw 에러;
  }
}

async function 쓰기(목록) {
  await fs.promises.writeFile(파일경로, JSON.stringify(목록, null, 2), "utf-8");
}

// ★ 읽기 와 쓰기 는 module.exports 에 없습니다.
//   밖에서 마음대로 파일을 만지면 이 파일에 가둔 의미가 없어집니다.
//   "안에서만 쓰는 것" 과 "밖에 내주는 것" 을 나누는 것이 중요합니다.
//   (01단원 계산기.js 에서 SECRET_KEY 를 안 내보낸 것과 같은 이야기입니다)


// ── 밖에 내주는 것 ──

async function 전부() {
  return 읽기();
}

async function 하나(id) {
  const 목록 = await 읽기();
  return 목록.find((설비) => 설비.id === id) ?? null;
}

// ★ 못 찾으면 null 입니다. undefined 가 아닙니다.
//   find 는 undefined 를 주는데, 일부러 null 로 바꿨습니다.
//
//   undefined  "그런 걸 물어본 적 없다" 는 느낌
//   null       "찾아봤는데 없더라" 는 느낌
//
//   여기서는 분명히 찾아봤습니다. 그래서 null 이 맞습니다.
//   중요한 건 '하나로 정하고 지키는 것' 입니다.

async function 추가(값) {
  const 목록 = await 읽기();

  const 다음번호 = 목록.length === 0 ? 1 : Math.max(...목록.map((설비) => 설비.id)) + 1;
  const 새설비 = { id: 다음번호, ...값 };

  목록.push(새설비);
  await 쓰기(목록);

  return 새설비;
}

// ★ id 를 저장소가 정합니다.
//   밖에서 id 를 정해서 넘기면 겹칠 수 있습니다.
//   "번호는 저장하는 쪽이 붙인다" 가 규칙입니다.
//
// ★ { id: 다음번호, ...값 } 의 순서
//   id 를 앞에 두면 JSON 에서도 id 가 먼저 나옵니다. 보기 좋습니다.
//   ...값 을 앞에 두면 값 안에 id 가 있을 때 그게 이겨 버립니다.
//   id 를 앞에 두면 뒤엣것이 이기니까... 반대입니다. 주의하세요.
//
//     { id: 1, ...{ id: 99 } }  →  { id: 99 }   ← 뒤엣것이 이깁니다
//
//   확실히 하려면 값에서 id 를 빼고 넘기거나, 아래처럼 씁니다.
//     { ...값, id: 다음번호 }

async function 수정(id, 바꿀것) {
  const 목록 = await 읽기();
  const 자리 = 목록.findIndex((설비) => 설비.id === id);

  if (자리 === -1) return null; // 없으면 null

  // 온 것만 덮어씁니다. id 는 못 바꾸게 마지막에 다시 넣습니다.
  목록[자리] = { ...목록[자리], ...바꿀것, id };

  await 쓰기(목록);
  return 목록[자리];
}

// ★ findIndex 는 못 찾으면 -1 입니다. undefined 가 아닙니다.
//   if (!자리) 로 쓰면 안 됩니다. 0번 자리가 falsy 라서 걸립니다.
//   반드시 === -1 로 확인하세요. 아주 흔한 실수입니다.
//
// ★ 맨 뒤의 id 가 하는 일
//   바꿀것 에 id 가 들어 있어도 원래 id 로 되돌립니다.
//   누가 { id: 999 } 를 보내도 번호가 안 바뀝니다.

async function 삭제(id) {
  const 목록 = await 읽기();
  const 남길것 = 목록.filter((설비) => 설비.id !== id);

  if (남길것.length === 목록.length) return false; // 지운 게 없음

  await 쓰기(남길것);
  return true;
}

// ★ 개수를 비교해서 "정말 지웠는지" 를 알려 줍니다.
//   그냥 true 를 돌려주면, 없는 걸 지우라고 해도 성공처럼 보입니다.
//   부르는 쪽이 404 를 낼지 204 를 낼지 정할 수 있어야 합니다.

// 수업용입니다. 진짜 서버에는 이런 게 있으면 안 됩니다.
async function 초기화(목록) {
  await 쓰기(목록);
}

module.exports = { 전부, 하나, 추가, 수정, 삭제, 초기화 };



// ============================================================
// services/점검기록서비스.js — 점검기록의 업무 규칙
// ------------------------------------------------------------
// 네 파일 중 여기만 '새로 생각' 이 필요했습니다.
// 나머지는 설비 것을 복사해서 이름만 바꿨습니다.
// ============================================================

const 점검기록저장소 = require("../repositories/점검기록저장소");
const 설비저장소 = require("../repositories/설비저장소");
const { 에러 } = require("../utils/AppError");

const 결과값들 = ["정상", "이상"];


// ★ 서비스가 저장소를 두 개 봅니다.
//   점검기록을 다루려면 "그 설비가 있는가" 를 알아야 하기 때문입니다.
//   같은 층끼리(서비스 ↔ 서비스)도, 아래층 여러 개도 볼 수 있습니다.
//   금지된 것은 아래층이 위층을 보는 것뿐입니다.

async function 설비확인(equipmentId) {
  const 설비 = await 설비저장소.하나(equipmentId);

  if (설비 === null) {
    throw 에러.없음("설비");
  }

  return 설비;
}


async function 목록(equipmentId) {
  // equipmentId 가 없으면 전부, 있으면 그 설비 것만
  if (equipmentId === undefined) {
    return 점검기록저장소.전부();
  }

  // ── 규칙 ①: 없는 설비의 기록을 물으면 404 ──
  //
  // 이게 없으면 "그런 설비 없는데요" 대신 "기록이 0건입니다" 가 나갑니다.
  // 요청한 쪽은 설비 번호를 잘못 쓴 줄 모르고 계속 헤맵니다.
  await 설비확인(equipmentId);

  return 점검기록저장소.설비별(equipmentId);
}


async function 하나(id) {
  const 기록 = await 점검기록저장소.하나(id);

  if (기록 === null) {
    throw 에러.없음("점검기록");
  }

  return 기록;
}


async function 등록(값) {
  // ── 규칙 ②에 들어가기 전: equipmentId 가 숫자여야 한다 ──
  //
  // 컨트롤러의 Number(equipmentId) 는 값이 없으면 NaN 을 만듭니다.
  // NaN 을 그대로 설비확인에 넘기면 "입력을 빠뜨렸다"(400) 가
  // "설비를 찾을 수 없다"(404) 로 잘못 보고됩니다. 다른 문제는 다르게 알려야 합니다.
  if (!Number.isInteger(값.equipmentId)) {
    throw 에러.검증실패([{ 키: "equipmentId", 이유: "숫자여야 합니다" }]);
  }

  // ── 규칙 ②: 그 설비가 실제로 있어야 한다 ──
  //
  // 저장소는 이걸 못 막습니다. equipmentId 가 숫자인지만 알 뿐입니다.
  // "실제로 있는 설비여야 한다" 는 업무 규칙입니다.
  const 설비 = await 설비확인(값.equipmentId);

  // ── 규칙 ③: 결과와 담당자를 제대로 받아야 한다 ──
  const 항목 = [];

  if (!결과값들.includes(값.result)) {
    항목.push({ 키: "result", 이유: `${결과값들.join(", ")} 중 하나여야 합니다` });
  }

  if (!값.담당자) {
    항목.push({ 키: "담당자", 이유: "필수입니다" });
  }

  if (항목.length > 0) {
    throw 에러.검증실패(항목);
  }

  const 새기록 = await 점검기록저장소.추가({
    equipmentId: 값.equipmentId,
    result: 값.result,
    담당자: 값.담당자,
  });

  // ── 규칙 ④: 결과가 '이상' 이면 설비를 점검중으로 바꾼다 ──
  //
  // ★★ 이게 서비스 층이 있는 이유를 가장 잘 보여 주는 규칙입니다.
  //
  //   기록 하나를 남겼을 뿐인데 다른 자원의 상태가 바뀝니다.
  //   저장소는 자기 파일만 압니다. 이런 걸 못 합니다.
  //   컨트롤러에 쓰면, 다른 입구(관리자 도구·배치)에서는 안 지켜집니다.
  if (값.result === "이상" && 설비.status !== "점검중") {
    await 설비저장소.수정(값.equipmentId, { status: "점검중" });
  }

  return 새기록;
}


async function 삭제(id) {
  await 하나(id); // 없으면 여기서 404

  // ── 규칙 ⑤: 기록을 지워도 설비 상태는 되돌리지 않는다 ──
  //
  // "잘못 입력해서 지웠다" 와 "설비가 정상으로 돌아왔다" 는 다른 일입니다.
  // 되돌리려면 설비 상태를 따로 바꿔야 합니다.
  //
  // ★ 이건 정답이 하나가 아닙니다. 회사마다 다르게 정합니다.
  //   중요한 건 정하고, 한 곳에 적어 두고, 문서에 남기는 것입니다.
  await 점검기록저장소.삭제(id);
}


module.exports = { 목록, 하나, 등록, 삭제 };


// ============================================================
// 점검기록의 업무 규칙 다섯 가지
// ============================================================
//
//   ① 없는 설비의 기록을 물으면 404 (0건이 아닙니다)
//   ② 없는 설비에는 기록을 남길 수 없다
//   ③ result 는 정상/이상, 담당자는 필수
//   ④ result 가 '이상' 이면 설비가 점검중이 된다
//   ⑤ 기록을 지워도 설비 상태는 안 되돌린다
//
// ①과 ②가 같은 확인(설비확인)을 씁니다.
// 같은 규칙을 두 번 쓰지 않으려고 함수로 뺐습니다.
//
// ④가 이 파일에서 가장 중요합니다.
// "다른 자원까지 함께 바꾸는 일" 은 서비스 층만 할 수 있습니다.
//
// ★ 여기에 숨은 위험이 하나 있습니다
//   기록을 저장한 뒤 설비 수정에서 실패하면?
//   기록은 남고 설비는 안 바뀐 어중간한 상태가 됩니다.
//
//   "둘 다 되거나 둘 다 안 되거나" 를 보장하려면 트랜잭션이 필요합니다.
//   파일 저장으로는 못 합니다. 데이터베이스가 필요한 이유 중 하나입니다.

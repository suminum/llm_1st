// ── 섹션 4: 해결 ① 줄 세우기 ──

// 동시에 하지 못하게 막습니다. 한 번에 한 명씩 차례로 하게 합니다.

let 대기줄 = Promise.resolve();

function 줄서서(작업) {
  // 앞사람이 끝난 뒤에 시작하도록 이어 붙입니다.
  const 다음 = 대기줄.then(작업, 작업);

  // 앞사람이 실패해도 줄이 끊기면 안 되니 에러를 삼킨 것을 대기줄로 삼습니다.
  대기줄 = 다음.catch(() => {});

  return 다음;
}

// ★ 이 여섯 줄이 하는 일
//   대기줄 은 "지금까지 걸린 일들이 끝나는 시점" 을 가리키는 약속입니다.
//   새 작업이 오면 그 뒤에 붙입니다. 자연스럽게 한 줄로 세워집니다.
//
// ★ .then(작업, 작업) 에 작업을 두 번 쓴 이유
//   첫 번째는 성공했을 때, 두 번째는 실패했을 때입니다.
//   앞사람이 실패했다고 내 차례가 안 오면 안 되니 둘 다 넣었습니다.

app.post("/race-queue", async (req, res) => {
  await 쓰기([]);

  await Promise.all(
    Array.from({ length: 20 }, (_, i) => 줄서서(() => 그냥추가({ name: `설비${i}` })))
  );

  const 결과 = await 읽기();

  res.json({
    시도: 20,
    실제저장됨: 결과.length,
    사라진것: 20 - 결과.length,
  });
});

// 확인: POST /race-queue
// 응답: 200 {"시도":20,"실제저장됨":20,"사라진것":0}

// ★ 20건이 전부 저장됐습니다.
//
//   달라진 것은 딱 하나입니다. 동시에 안 하고 차례로 했습니다.

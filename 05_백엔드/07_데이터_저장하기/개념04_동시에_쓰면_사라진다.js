//   문제                        해결                      남는 한계
//   ─────────────────────────────────────────────────────────────
//   동시에 쓰면 덮어씀          줄 세우기                  프로세스가 여러 개면 소용없음
//   쓰다가 죽으면 깨짐          임시 파일 + rename         -
//   전부 읽고 전부 씀           -                          데이터가 늘면 답이 없음

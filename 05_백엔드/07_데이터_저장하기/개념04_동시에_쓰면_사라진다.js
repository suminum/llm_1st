//   되돌릴 수 없음              -                          트랜잭션이 필요함
//
// ★ 파일 저장을 써도 되는 경우
//   · 쓰는 사람이 사실상 한 명 (관리자 도구, 개인 프로젝트)
//   · 데이터가 적고 잘 안 바뀜 (설정 파일, 목록 데이터)
//   · 읽기가 대부분이고 쓰기는 아주 가끔
//
// ★ 절대 쓰면 안 되는 경우

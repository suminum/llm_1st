//
//   요청A   읽기[]  ─────────────  쓰기[A]
//   요청B      읽기[]  ──────────────  쓰기[B]      ← A 를 덮어씀
//   요청C         읽기[]  ───────────────  쓰기[C]  ← B 를 덮어씀
//                                                     결과: [C] 하나
//
// ★ 02단원 개념03 의 '일꾼 한 명' 이 여기서 반대로 문제가 됩니다.
//   일꾼이 한 명이라 동시에 두 줄이 실행되지는 않습니다.
//   그런데 await 에서 일을 놓고 다른 손님에게 갑니다.
//   놓았다가 다시 잡는 사이에 세상이 바뀌어 있는 것입니다.

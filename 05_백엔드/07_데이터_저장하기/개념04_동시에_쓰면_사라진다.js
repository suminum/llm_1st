const express = require("express");
const fs = require("fs");
const path = require("path");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

const 파일경로 = path.join(__dirname, "data", "동시성.json");
fs.mkdirSync(path.dirname(파일경로), { recursive: true });


// ── 섹션 1: 지금까지 쓰던 방식 ──

async function 읽기() {
  try {
    return JSON.parse(await fs.promises.readFile(파일경로, "utf-8"));
  } catch (에러) {
    if (에러.code === "ENOENT") return [];
    throw 에러;
  }
}

async function 쓰기(목록) {
  await fs.promises.writeFile(파일경로, JSON.stringify(목록, null, 2), "utf-8");
}

// ★ 읽다가 깨진 횟수를 세어 둡니다. 왜 필요한지는 섹션 2-2 에서 봅니다.
let 읽다깨진횟수 = 0;

async function 그냥추가(값) {
  let 목록;

  try {
    목록 = await 읽기(); // ①
  } catch (에러) {
    // 다른 요청이 파일을 쓰는 도중이라 반쯤 쓰인 것을 읽었습니다.
    읽다깨진횟수 += 1;
    목록 = [];
  }

  const id = 목록.length === 0 ? 1 : Math.max(...목록.map((x) => x.id)) + 1;
  목록.push({ id, ...값 });
  await 쓰기(목록); // ②
}

// 지금까지 만든 것과 똑같습니다. 아무 문제 없어 보입니다.
// Postman 으로 하나씩 눌러 보면 정말 잘 됩니다.
//
// ★ try/catch 는 원래 없던 것입니다.
//   이 파일을 만들면서 /race 가 가끔 500 을 내길래 붙였습니다.
//   무슨 일이었는지는 섹션 2-2 에서 설명합니다.


// ── 섹션 2: ★ 20명이 동시에 등록하면 ──

app.post("/race", async (req, res) => {
  await 쓰기([]); // 빈 상태에서 시작
  읽다깨진횟수 = 0;

  // 20개를 '동시에' 추가합니다. 20명이 같은 순간에 등록 버튼을 누른 것입니다.
  await Promise.all(
    Array.from({ length: 20 }, (_, i) => 그냥추가({ name: `설비${i}` }))
  );

  const 결과 = await 읽기();

  console.log(`   /race — 읽다가 깨진 횟수: ${읽다깨진횟수}`);

  res.json({
    시도: 20,
    실제저장됨: 결과.length,
    사라진것: 20 - 결과.length,
  });
});


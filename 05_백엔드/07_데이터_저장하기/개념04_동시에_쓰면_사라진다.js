//   사람이 늘수록 점점 느려집니다.
//
//   그래도 데이터가 사라지는 것보다는 낫습니다.
//   "느린 것" 과 "틀린 것" 중에는 언제나 느린 쪽을 고릅니다.


// ── 섹션 5: 해결 ② 쓰다가 죽어도 안 깨지게 ──

// 섹션 2-2 의 '찢긴 읽기' 를 제대로 고칩니다.
// 그리고 더 큰 문제 하나도 함께 해결됩니다.
//
//   writeFile 은 파일을 먼저 비우고 새 내용을 씁니다.
//   비운 직후에 서버가 죽거나 전원이 나가면?
//   파일이 반쯤 쓰인 채로 남습니다. JSON 이 깨져서 아예 못 읽습니다.
//   데이터 전체가 날아갑니다. 다시 켜도 복구가 안 됩니다.
//
//   찢긴 읽기는 '가끔 한 요청이 실패' 하는 것이지만,
//   이건 '데이터 전체가 사라지는' 사고입니다.
//
// 그래서 이렇게 씁니다.
//
//   ① 임시 파일에 전부 쓴다
//   ② 다 쓰이면 원래 이름으로 바꾼다 (rename)
//
// 이름 바꾸기는 '한순간에' 일어납니다. 반쯤 바뀌는 일이 없습니다.
// 그래서 파일은 언제나 '옛날 것 전체' 이거나 '새것 전체' 입니다.

async function 안전하게쓰기(목록) {
  const 임시경로 = 파일경로 + ".tmp";

  await fs.promises.writeFile(임시경로, JSON.stringify(목록, null, 2), "utf-8");
  await fs.promises.rename(임시경로, 파일경로);
}

async function 안전추가(값) {
  const 목록 = await 읽기();
  const id = 목록.length === 0 ? 1 : Math.max(...목록.map((x) => x.id)) + 1;
  목록.push({ id, ...값 });
  await 안전하게쓰기(목록);
}

app.post("/safe", async (req, res) => {
  await 안전하게쓰기([]);

  await Promise.all(
    Array.from({ length: 20 }, (_, i) => 줄서서(() => 안전추가({ name: `설비${i}` })))
  );

  const 결과 = await 읽기();
  const 임시파일남았나 = fs.existsSync(파일경로 + ".tmp");

  res.json({ 저장됨: 결과.length, 임시파일남았나 });
});

// 확인: POST /safe
// 응답: 200 {"저장됨":20,"임시파일남았나":false}

// ★ 임시 파일이 안 남았습니다. rename 이 옮겨 갔기 때문입니다.
//
// ★ 이 방법을 원자적 쓰기(atomic write)라고 합니다.
//   '원자' 는 더 쪼갤 수 없다는 뜻입니다. 반쯤 되는 일이 없습니다.
//
// ★ 주의 — 임시 파일은 같은 디스크에 두세요
//   이름 바꾸기는 같은 디스크(파일시스템) 안에서만 됩니다.
//   다른 디스크로 rename 하면 EXDEV 에러가 나며 실패합니다.
//   (mv 명령이 다른 디스크로도 되는 것은, 그때 복사 + 삭제로 대신해 주기 때문입니다.
//    rename 자체가 그러는 게 아닙니다)
//   그래서 파일경로 + ".tmp" 처럼 바로 옆에 만듭니다.



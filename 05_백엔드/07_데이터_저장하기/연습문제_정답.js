//   반쯤 쓰인 글자를 읽습니다. JSON.parse 가 SyntaxError 를 냅니다.
//   이걸 '찢긴 읽기' 라고 합니다. 가끔만 일어나서 재현이 아주 어렵습니다.
//
// 어떻게 고치나:
//   ① 임시 파일에 전부 쓴다      writeFile(파일 + ".tmp", ...)
//   ② 원래 이름으로 바꾼다       rename(파일 + ".tmp", 파일)
//
// 왜 이게 안전한가:
//   이름 바꾸기는 한순간에 일어납니다. 반쯤 바뀌는 일이 없습니다.
//   그래서 파일은 언제나 '옛날 것 전체' 이거나 '새것 전체' 입니다.
//   중간 상태가 존재하지 않습니다.
//
// 주의할 점:
//   임시 파일은 같은 디스크(같은 폴더 옆)에 만드세요.
//   rename 은 같은 디스크 안에서만 되고, 다른 디스크로는 EXDEV 에러로 실패합니다.
//   (mv 명령은 그때 복사 + 삭제로 대신해 줍니다. rename 이 그러는 게 아닙니다)



// 규칙 ②: 같은 이름은 못 만든다
// 확인: POST /api/v1/equipments {"name":"프레스 1호","line":"C"}
// 응답: 409 {"error":{"code":"DUPLICATED","message":"이미 있는 설비 이름입니다"}}


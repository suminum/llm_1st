// 확인: PATCH /api/v1/equipments/3 {"status":"가동"}
// 응답: 200 {"data":{"id":3,"name":"검사기 1호","line":"A","status":"가동"}}

// 정지를 거치니 가동이 됩니다. 순서를 강제하는 규칙이 동작합니다.

// 규칙 ⑤: 가동 중인 설비는 못 지운다
// 확인: DELETE /api/v1/equipments/3
// 응답: 409 {"error":{"code":"CONFLICT","message":"가동 중인 설비는 삭제할 수 없습니다. 먼저 정지시키세요"}}

// 확인: PATCH /api/v1/equipments/3 {"status":"정지"}
// 응답: 200 {"data":{"id":3,"name":"검사기 1호","line":"A","status":"정지"}}

// 확인: DELETE /api/v1/equipments/3
// 응답: 204

// ★★ 여기가 이 단원의 핵심입니다.
//
//   위 다섯 가지 규칙은 전부 services/설비서비스.js 한 파일에 적혀 있습니다.
//   컨트롤러에도, 라우트에도, 저장소에도 없습니다.
//
//   "이 시스템의 규칙이 뭐예요?" 라는 질문에
//   "services 폴더를 보세요" 라고 답할 수 있습니다.
//
//   규칙이 여기저기 흩어져 있으면 그 질문에 아무도 답을 못 합니다.


// ── 섹션 4: 404 와 에러 처리기 ──

app.use((req, res, next) => {
  next(에러.주소없음());
});

// 확인: GET /없는주소
// 응답: 404 {"error":{"code":"ROUTE_NOT_FOUND","message":"그런 주소가 없습니다"}}

app.use((err, req, res, next) => {
  console.error(`[에러] ${req.method} ${req.path} — ${err.name}: ${err.message}`);

  if (err.type === "entity.parse.failed") {
    return res.status(400).json({ error: { code: "INVALID_JSON", message: "JSON 형식이 아닙니다" } });
  }

  if (err instanceof AppError) {
    const 몸통 = { code: err.code, message: err.message };
    if (err.details !== undefined) 몸통.details = err.details;
    return res.status(err.status).json({ error: 몸통 });
  }

  res.status(500).json({ error: { code: "INTERNAL_ERROR", message: "서버에서 문제가 생겼습니다" } });
});

// ★ 에러 처리기는 조립하는 이 파일에 둡니다.
//   "에러를 어떤 모양으로 내보낼지" 는 서비스가 아니라 서버 전체의 결정입니다.



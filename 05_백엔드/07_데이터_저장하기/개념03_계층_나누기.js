// 서비스가 보낸 값을 안 쓰고 무조건 "정지" 로 넣기 때문입니다.

// 규칙 ④: 점검중 → 가동 은 바로 못 간다
// 확인: PATCH /api/v1/equipments/3 {"status":"가동"}

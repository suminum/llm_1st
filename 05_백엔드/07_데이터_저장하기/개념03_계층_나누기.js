// ── 자주 하는 실수 ──

// [실수 1] 서비스에서 req 나 res 를 씀
//   그 순간 서비스가 웹 전용이 됩니다. 다른 곳에서 못 씁니다.

// [실수 2] 컨트롤러에 업무 규칙을 씀
//   같은 규칙이 필요한 다른 입구가 생기면 복사하게 됩니다.
//   그리고 한쪽만 고쳐집니다.

// [실수 3] 저장소가 서비스를 부름
//   서로 물고 물리는 관계가 됩니다. 화살표는 한쪽으로만.

// [실수 4] 라우트에 컨트롤러를 괄호와 함께 넘김
//   설비컨트롤러.목록() 은 지금 실행합니다. 서버 켜자마자 에러가 납니다.

// [실수 5] 층을 나눠 놓고 컨트롤러가 저장소를 직접 부름
//   서비스를 건너뛰면 업무 규칙이 안 지켜집니다.
//   "가동 중이면 못 지운다" 를 통과해 버립니다.

// [실수 6] 작은 프로젝트에 억지로 다 나눔
//   파일 20개에 코드가 5줄씩 들어 있으면 오히려 못 읽습니다.
//   나누는 건 커진 뒤에 해도 늦지 않습니다.


// ── 정리 ──

// 1. 층을 셋으로 나눈다. 컨트롤러(요청·응답) · 서비스(업무 규칙) · 저장소(읽고 쓰기).
// 2. 부르는 방향은 한쪽이다. 컨트롤러 → 서비스 → 저장소.
//    저장소가 서비스를 부르면 고리가 생겨서 풀 수 없게 된다.
// 3. 서비스에서 req 나 res 를 쓰지 않는다. 쓰는 순간 서버 없이 시험할 수 없다.
// 4. 업무 규칙은 서비스에 둔다. 컨트롤러에 쓰면 같은 규칙을 여러 곳에 또 쓰게 된다.
// 5. 층을 나눠 놓고 컨트롤러가 저장소를 직접 부르면 나눈 뜻이 없어진다.
// 6. 라우트에는 컨트롤러 함수를 괄호 없이 넘긴다. 붙이면 그 자리에서 실행돼 버린다.
// 7. 작은 프로젝트에 억지로 다 나누지 않는다. 파일만 늘고 읽기 어려워진다.
//    나눌 이유가 생겼을 때 나눈다.
// 8. 404 처리기와 에러 처리기는 여기서도 맨 아래다.

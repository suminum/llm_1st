const express = require("express");
const fs = require("fs");
const path = require("path");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());


// ── 섹션 1: 저장할 파일 위치 정하기 ──

// ★ __dirname 을 꼭 쓰세요. (02단원 개념01)
//   "data/설비.json" 이라고만 쓰면 '터미널이 열려 있는 위치' 기준이 됩니다.
//   다른 폴더에서 node 로 실행하면 엉뚱한 데를 찾거나 만듭니다.
const 데이터폴더 = path.join(__dirname, "data");
const 설비파일 = path.join(데이터폴더, "설비.json");

// 폴더가 없으면 만듭니다. 첫 실행 때 반드시 필요합니다.
fs.mkdirSync(데이터폴더, { recursive: true });


// ── 섹션 2: 읽기 — 파일이 없을 수도 있습니다 ──

async function 불러오기() {
  try {
    const 글자 = await fs.promises.readFile(설비파일, "utf-8");
    return JSON.parse(글자);
  } catch (에러) {
    if (에러.code === "ENOENT") {
      return []; // 아직 파일이 없으면 빈 목록으로 시작합니다
    }
    throw 에러; // 그 밖의 에러는 숨기지 않습니다
  }
}

// ★★ ENOENT 만 골라서 처리하는 것이 중요합니다.
//
//   catch 로 전부 잡아서 [] 를 돌려주면 어떻게 될까요?
//   JSON 이 깨져 있어도, 권한이 없어도, 조용히 "데이터가 없습니다" 가 됩니다.
//   데이터가 멀쩡히 파일에 있는데 화면에는 아무것도 안 나옵니다.
//   그런데 에러도 안 나니 원인을 찾을 수가 없습니다.
//
//   "없는 것" 과 "못 읽는 것" 은 완전히 다릅니다.
//   없는 것만 [] 로 처리하고, 나머지는 그대로 터뜨리세요.


// ── 섹션 3: 쓰기 ──

async function 저장하기(목록) {
  await fs.promises.writeFile(설비파일, JSON.stringify(목록, null, 2), "utf-8");
}

// ★ JSON.stringify(목록, null, 2) 의 2
//   줄바꿈과 들여쓰기를 넣어 줍니다. 사람이 파일을 열어 볼 수 있습니다.
//   없으면 한 줄로 쭉 이어져서 읽을 수가 없습니다.
//
//   대신 파일이 조금 커집니다. 데이터가 아주 많으면 빼기도 합니다.
//   지금은 눈으로 확인하는 게 더 중요하니 넣습니다.
//
// ★ "utf-8" 을 빼먹으면
//   쓸 때는 괜찮은데 읽을 때 Buffer 가 나옵니다. (02단원 개념02)


// ── 섹션 4: 켤 때 초기값 넣기 ──

// 이 파일은 수업용이라, 켤 때마다 같은 상태에서 시작하게 합니다.
// 진짜 서버라면 이러면 안 됩니다. 기존 데이터가 날아갑니다.
const 처음데이터 = [
  { id: 1, name: "컨베이어 1호", line: "A", status: "가동" },
  { id: 2, name: "프레스 1호", line: "B", status: "정지" },
];

fs.writeFileSync(설비파일, JSON.stringify(처음데이터, null, 2), "utf-8");

// ★ 여기서만 동기(writeFileSync)를 씁니다.
//   서버가 켜지기 전, 요청을 받기 전이라 아무도 안 기다립니다.
//   '시작할 때 한 번' 은 동기여도 괜찮습니다.
//   요청을 처리하는 중에는 절대 안 됩니다. 섹션 7 에서 봅니다.


// ── 섹션 5: 읽고 → 고치고 → 쓰기 ──

app.get("/equipments", async (req, res) => {
  const 목록 = await 불러오기();
  res.json({ data: 목록 });
});

// 확인: GET /equipments
// 응답: 200 {"data":[{"id":1,"name":"컨베이어 1호","line":"A","status":"가동"},{"id":2,"name":"프레스 1호","line":"B","status":"정지"}]}

app.post("/equipments", async (req, res) => {
  const { name, line } = req.body || {};

  if (!name || !line) {
    return res.status(400).json({ error: "name 과 line 이 필요합니다" });
  }

  // ① 읽고
  const 목록 = await 불러오기();

  // ② 고치고
  const 다음번호 = 목록.length === 0 ? 1 : Math.max(...목록.map((설비) => 설비.id)) + 1;
  const 새설비 = { id: 다음번호, name, line, status: "정지" };
  목록.push(새설비);

  // ③ 쓰기
  await 저장하기(목록);

  res.status(201).json({ data: 새설비 });
});

// 확인: POST /equipments {"name":"용접로봇 1호","line":"C"}
// 응답: 201 {"data":{"id":3,"name":"용접로봇 1호","line":"C","status":"정지"}}

// 확인: GET /equipments
// 응답: 200 {"data":[{"id":1,"name":"컨베이어 1호","line":"A","status":"가동"},{"id":2,"name":"프레스 1호","line":"B","status":"정지"},{"id":3,"name":"용접로봇 1호","line":"C","status":"정지"}]}

// ★★ '읽고 → 고치고 → 쓰기' 가 파일 저장의 기본 모양입니다.
//   메모리에 있을 때는 목록.push 한 줄이면 끝이었습니다.
//   파일은 통째로 읽고 통째로 다시 써야 합니다.
//
//   설비가 10만 개면 하나 추가하려고 10만 개를 읽고 10만 개를 씁니다.
//   이게 파일 저장의 한계입니다. 개념05 에서 정리합니다.

// ★ 다음 번호를 Math.max 로 구하는 이유
//   목록.length + 1 로 하면 안 됩니다.
//   3개 중 2번을 지우면 [1, 3] 이 되는데, length + 1 은 3 입니다. 겹칩니다.
//   지금 있는 번호 중 제일 큰 것 + 1 이 안전합니다.
//
//   ...목록.map(...) 은 배열을 인자들로 펼치는 것입니다. (JS자료 09단원)
//   Math.max([1,2,3]) 은 NaN 입니다. Math.max(1,2,3) 이어야 합니다.
//
//   목록이 비어 있으면 Math.max() 가 -Infinity 라서 따로 처리했습니다.


app.delete("/equipments/:id", async (req, res) => {
  const 번호 = Number(req.params.id);
  const 목록 = await 불러오기();

  const 있나 = 목록.some((설비) => 설비.id === 번호);
  if (!있나) {
    return res.status(404).json({ error: "설비를 찾을 수 없습니다" });
  }

  await 저장하기(목록.filter((설비) => 설비.id !== 번호));

  res.sendStatus(204);
});

// 확인: DELETE /equipments/3
// 응답: 204

// 확인: GET /equipments

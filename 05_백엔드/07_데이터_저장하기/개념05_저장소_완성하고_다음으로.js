app.post("/race", async (req, res) => {
  await 저장소.초기화([]);

  await Promise.all(
    Array.from({ length: 20 }, (_, i) => 저장소.추가({ name: `설비${i}`, line: "A" }))
  );

  const 결과 = await 저장소.전부();

  // 번호가 겹치지 않았는지도 확인합니다.
  const 번호들 = 결과.map((설비) => 설비.id);
  const 겹친번호 = 번호들.length !== new Set(번호들).size;

  res.json({ 시도: 20, 저장됨: 결과.length, 번호가겹쳤나: 겹친번호 });
});

// 확인: POST /race
// 응답: 200 {"시도":20,"저장됨":20,"번호가겹쳤나":false}


const 글가 = "│ 4 │ 이상 소음·진동 │ 주의 │ 하부 미세 소음 │";
const 글나 = "오늘 점검했고 이상 없었습니다.";

function 표형인가(글) {
  const 표문자 = (글.match(/[│┌┐└┘├┤┬┴┼─]/g) ?? []).length;
  return 표문자 >= 5;
}

console.log(표형인가(글가));
// 출력: true
console.log(표형인가(글나));
// 출력: false
// `?? []` 가 중요합니다. match 는 못 찾으면 null 을 돌려줍니다.
// null.length 를 읽으면 터집니다.
//
// ★ 글가에는 │ 가 5개 있습니다. 딱 기준에 걸립니다.
//   기준을 6으로 올렸으면 false 가 됐을 것입니다.
//
// ★★★ 이 문제를 만들면서 실제로 한 번 틀렸습니다.
//   처음에는 "│ 1 │ 유압유 누유 │ 양호 │" 를 예제로 썼습니다. │ 가 **4개**입니다.
//   기준이 5라서 false 가 나왔는데, 기대 출력은 true 라고 적어 뒀습니다.
//   돌려 보고 알았습니다.
//
//   ★ 경계값(5)을 기준으로 쓰면서 예제를 눈대중으로 고르면 이렇게 됩니다.

// ── 자주 하는 실수 ──

// [실수 1] 에러 처리기 인자를 세 개로 씀
//   (err, req, res) 로 쓰면 Express 가 알아보지 못합니다.
//   next 를 안 쓰더라도 네 개를 다 적으세요.

// [실수 2] 404 처리기를 라우트 위에 씀
//   모든 요청이 404 가 됩니다. 라우트는 실행조차 안 됩니다.

// [실수 3] 응답 뒤에 return 을 안 붙임
//   에러 처리기 안에서 특히 위험합니다. 400 을 보내고 500 을 또 보내려 합니다.
//   → Cannot set headers after they are sent to the client

// [실수 4] 500 에 err.message 를 그대로 담음
//   내부 사정이 밖으로 새어 나갑니다. 500 은 뭉뚱그려 답하세요.

// [실수 5] 터미널에 아무것도 안 남김
//   응답만 예쁘게 만들고 console.error 를 안 쓰면
//   나중에 "500 이 났다" 는 것만 알고 원인을 못 찾습니다.

// [실수 6] Express 4 처럼 라우트마다 try/catch 를 두름
//   Express 5 에서는 필요 없습니다. 코드만 길어집니다.
//   다만 '에러를 잡아서 다른 에러로 바꿔 던질 때' 는 여전히 씁니다.


// ── 정리 ──

// 1. 잘될 때만 생각하고 만든 서버는 실무에서 하루도 못 버틴다.
//    에러 처리를 얼마나 챙겼는지가 초보와 중급을 가른다.
// 2. 순서가 정해져 있다. 라우트들 → 404 처리기 → 에러 처리기 순이고 바꿀 수 없다.
// 3. 404 처리기를 라우트보다 위에 두면 전부 404 가 된다.
// 4. 에러 처리기는 인자가 네 개다. (err, req, res, next).
//    세 개로 쓰면 Express 가 에러 처리기로 안 보고 그냥 미들웨어로 본다.
// 5. 내가 만든 에러는 던지거나 next(err) 로 넘긴다. 넘기면 에러 처리기가 받는다.
// 6. Express 5 는 async 함수 안에서 난 에러도 알아서 에러 처리기로 보낸다.
//    4 처럼 라우트마다 try/catch 를 두를 필요가 없다.

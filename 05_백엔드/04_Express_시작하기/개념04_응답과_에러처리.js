//
// 그래서 API 서버는 404 도 직접 만듭니다.
// ★ 반드시 '모든 라우트 아래' 에 적어야 합니다. 위에 적으면 전부 404 가 됩니다.
//
// 이 파일에서는 아래쪽 섹션 6 에 있습니다. 거기서 다시 봅니다.


// ── 섹션 3: 에러가 나면 어떻게 되나 ──

app.get("/boom-sync", (req, res) => {
  // 일부러 터뜨립니다. 실무에서는 오타나 undefined 때문에 저절로 납니다.
  const 없는것 = undefined;
  res.json(없는것.속성); // TypeError
});

// 확인: GET /boom-sync
// 응답: 500 {"error":"서버에서 문제가 생겼습니다"}

// 라우트 안에서 에러가 나면 Express 가 잡아서 '에러 처리기' 로 보냅니다.
// 서버는 죽지 않습니다. 그 요청 하나만 500 이 되고 다음 요청은 정상입니다.
//
// ★ 03단원의 맨손 서버였다면 여기서 서버가 통째로 죽었습니다.
//   Express 를 쓰는 큰 이유 중 하나입니다.

app.get("/boom-async", async (req, res) => {
  await new Promise((resolve) => setTimeout(resolve, 10));
  throw new Error("비동기 안에서 터졌습니다");
});

// 확인: GET /boom-async
// 응답: 500 {"error":"서버에서 문제가 생겼습니다"}

// ★★ 이게 Express 5 의 가장 큰 선물입니다.
//
//   Express 4 에서는 async 함수 안의 에러를 못 잡았습니다.
//   응답이 영원히 안 오고 브라우저가 계속 돌았습니다.
//   그래서 라우트마다 이렇게 감싸야 했습니다.
//
//     app.get("/x", async (req, res, next) => {
//       try { ... } catch (err) { next(err); }
//     });
//
//   Express 5 는 알아서 잡아 줍니다. try/catch 를 안 써도 됩니다.
//   옛날 블로그에 try/catch 가 잔뜩 있는 이유가 이것입니다.


// ── 섹션 4: 내가 만든 에러 던지기 ──

// 상태코드를 붙인 에러를 만드는 작은 도구입니다.
// 이런 걸 하나 만들어 두면 라우트가 아주 깔끔해집니다.

function HttpError(코드, 메시지) {
  const 에러 = new Error(메시지);
  에러.status = 코드; // 에러 객체에 속성을 더 붙일 수 있습니다
  return 에러;
}

const 문서들 = [
  { id: 1, title: "작업표준서" },
  { id: 2, title: "검사성적서" },
];

app.get("/documents/:id", (req, res) => {
  const 번호 = Number(req.params.id);

  if (!Number.isInteger(번호)) {
    throw HttpError(400, "번호는 숫자여야 합니다");
  }

  const 문서 = 문서들.find((문서) => 문서.id === 번호);

  if (!문서) {
    throw HttpError(404, `${번호}번 문서가 없습니다`);
  }

  res.json(문서);
});

// 확인: GET /documents/1
// 응답: 200 {"id":1,"title":"작업표준서"}

// 확인: GET /documents/abc
// 응답: 400 {"error":"번호는 숫자여야 합니다"}

// 확인: GET /documents/99
// 응답: 404 {"error":"99번 문서가 없습니다"}

// ★ throw 를 쓰니 라우트가 짧아졌습니다.
//   res.status(404).json({ error: ... }) 를 매번 쓰는 것과 비교해 보세요.
//   "무엇이 잘못됐는지" 만 말하고, "어떻게 응답할지" 는 에러 처리기에 맡깁니다.
//
//   응답 모양이 바뀌면 에러 처리기 한 곳만 고치면 됩니다.
//   라우트가 서른 개여도 마찬가지입니다.


// ── 섹션 5: next 로 넘기기 ──

app.get("/next-error", (req, res, next) => {
  // throw 대신 next(에러) 를 써도 똑같습니다.
  next(HttpError(403, "권한이 없습니다"));
});

// 확인: GET /next-error
// 응답: 403 {"error":"권한이 없습니다"}

// throw 와 next(에러) 중 무엇을 쓰나
//   보통은 throw 가 짧고 읽기 좋습니다.
//   콜백 '안' 에서 에러가 났을 때는 throw 가 안 통합니다. 그때 next 를 씁니다.
//
//     fs.readFile("x.txt", (err, data) => {
//       if (err) return next(err);   ← 여기서 throw 하면 Express 가 못 잡습니다
//       ...
//     });
//
//   fs.promises 와 await 를 쓰면 이런 일이 없습니다. 그래서 promises 를 씁니다.


// ── 섹션 6: 못 찾은 주소 (라우트 다음, 에러 처리기 앞) ──

// 여기까지 내려왔다는 것은 위의 어떤 라우트에도 안 걸렸다는 뜻입니다.
// 주소를 안 적었으니 '모든 요청' 이 여기로 옵니다.

// ★ req.path 는 인코딩된 그대로입니다. 한글이 %EC%97%86... 으로 보입니다.
//   기록으로 남길 때 읽을 수가 없으니 되돌려 줍니다.
function 읽기좋은주소(경로) {
  try {
    return decodeURIComponent(경로);
  } catch {
    // %ZZ 처럼 망가진 글자가 오면 decodeURIComponent 는 URIError 를 던집니다.
    // 여기서 안 막으면 '없는 주소' 하나 때문에 500 이 납니다.
    return 경로;
  }
}

app.use((req, res) => {
  res.status(404).json({
    error: "그런 주소가 없습니다",
    요청: `${req.method} ${읽기좋은주소(req.path)}`,
  });
});

// 확인: GET /없는주소
// 응답: 404 {"error":"그런 주소가 없습니다","요청":"GET /없는주소"}

// 확인: PATCH /ok
// 응답: 404 {"error":"그런 주소가 없습니다","요청":"PATCH /ok"}

// ★★ req.path 를 그냥 쓰면 이렇게 나옵니다.
//
//     "요청": "GET /%EC%97%86%EB%8A%94%EC%A3%BC%EC%86%8C"
//
//   개념01 섹션 8 에서 본 퍼센트 인코딩입니다.
//   Express 는 라우트를 이 상태로 비교하기 때문에 되돌리지 않습니다.
//   (req.params 와 req.query 는 되돌려 줍니다. 이 둘만 예외입니다)
//
//   사람이 읽을 기록에 넣을 때만 decodeURIComponent 로 되돌리세요.
//   그리고 반드시 try/catch 로 감싸세요. 이건 진짜로 터지는 함수입니다.
//
// ★ 두 번째 확인을 보세요. /ok 는 있는 주소인데 PATCH 는 안 만들었습니다.
//   405 가 더 정확하지만 Express 는 404 를 줍니다.
//   405 가 필요하면 app.route 나 app.all 로 직접 만들어야 합니다.


// ── 섹션 7: 에러 처리기 (가장 마지막) ──

// ★★ 인자가 '네 개' 입니다. 이게 에러 처리기의 표시입니다.
//   Express 는 인자 개수를 세어서 "아, 이건 에러용이구나" 하고 구별합니다.
//   next 를 안 써도 반드시 적어야 합니다. 빼면 그냥 미들웨어가 되어 버립니다.

app.use((err, req, res, next) => {
  // ① 터미널에는 전부 남깁니다. 원인을 찾으려면 이게 있어야 합니다.
  console.error(`[에러] ${req.method} ${req.path} — ${err.message}`);

  // ② 본문이 깨진 JSON 이면 express.json() 이 이 에러를 만듭니다.
  if (err.type === "entity.parse.failed") {
    return res.status(400).json({ error: "JSON 형식이 아닙니다" });
  }

  // ③ 내가 만든 에러면 status 가 붙어 있습니다.
  const 코드 = err.status || 500;

  // ④ 500 일 때는 자세한 내용을 밖으로 내보내지 않습니다.
  if (코드 === 500) {
    return res.status(500).json({ error: "서버에서 문제가 생겼습니다" });
  }

  res.status(코드).json({ error: err.message });
});

// 확인: POST /documents {깨진:JSON}
// 응답: 400 {"error":"JSON 형식이 아닙니다"}

// ★ ④번이 중요합니다 — 왜 500 의 내용을 숨기나
//
//   에러 메시지에는 파일 경로, 테이블 이름, 쿼리문이 그대로 들어 있습니다.
//   그걸 그대로 돌려주면 공격하려는 사람에게 지도를 그려 주는 셈입니다.
//
//     "Cannot read properties of undefined (reading 'password')"
//     "connect ECONNREFUSED 10.0.1.23:5432"
//
//   400·404 는 '보낸 쪽이 고칠 수 있는 것' 이라 알려 주는 게 맞습니다.
//   500 은 '내 잘못' 이라 상대가 알아도 할 수 있는 게 없습니다.
//
//   대신 터미널에는 전부 남깁니다. 그래야 내가 고칠 수 있습니다.
//   운영 서버에서는 이 기록을 파일로 남깁니다. PART 4 에서 합니다.
//
// ★ Express 기본 에러 처리기는 어떤가
//   우리가 이 app.use 를 안 적어도 Express 가 500 을 돌려주긴 합니다.
//   그런데 개발 중에는 에러 스택 전체를 HTML 로 그대로 보여 줍니다.
//   NODE_ENV=production 으로 켜면 "Internal Server Error" 만 나옵니다.
//   어차피 JSON 으로 주고 싶으니 직접 만드는 게 낫습니다.


app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}/ok`);
});



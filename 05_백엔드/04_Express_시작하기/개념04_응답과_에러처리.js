const express = require("express");

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());


// ── 섹션 1: 응답을 보내는 방법들 ──

app.get("/ok", (req, res) => {
  res.json({ message: "잘 됐습니다" });
});

// 확인: GET /ok
// 응답: 200 {"message":"잘 됐습니다"}

app.get("/created", (req, res) => {
  // 만들었으면 201, 그리고 만든 것이 어디 있는지 Location 으로 알려 줍니다.
  res.status(201).location("/documents/3").json({ id: 3 });
});

// 확인: GET /created
// 응답: 201 {"id":3}

app.get("/no-content", (req, res) => {
  res.sendStatus(204); // 내용 없이 상태코드만
});

// 확인: GET /no-content
// 응답: 204

app.get("/custom-header", (req, res) => {
  // 헤더를 직접 붙일 수도 있습니다.
  res.set("X-App-Version", "1.0.0");
  res.json({ ok: true });
});

// 확인: GET /custom-header
// 응답: 200 {"ok":true}

// 정리
//
//   res.json(객체)          JSON 으로 보냅니다. API 는 이것만 쓰면 됩니다
//   res.status(코드)        코드만 정합니다. 뒤에 .json 등이 와야 합니다
//   res.sendStatus(코드)    코드만 보내고 끝냅니다
//   res.location(주소)      Location 헤더를 붙입니다
//   res.set(이름, 값)       아무 헤더나 붙입니다
//   res.send(글자)          글자를 그대로 보냅니다 (HTML 페이지 등)
//
// 전부 res 를 다시 돌려주기 때문에 점으로 이어 붙일 수 있습니다.
//   res.status(201).location("/x/3").json({ ... })



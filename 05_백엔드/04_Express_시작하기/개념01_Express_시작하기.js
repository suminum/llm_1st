// ── 섹션 1: Express 는 무엇인가 ──

// Express 는 Node 의 http 모듈을 감싼 '도구' 입니다.
// 새로운 언어도, 새로운 서버도 아닙니다. 여전히 안에서는 http 가 돕니다.
//
// 그래서 03단원에서 배운 것이 하나도 안 버려집니다.
// 요청·응답·상태코드·헤더는 그대로입니다. 쓰는 방법만 짧아집니다.
//
//   http     "요청이 오면 이 함수 하나가 다 처리해라"
//   Express  "이 주소로 이 방법의 요청이 오면 이 함수를 불러라"
//
// 이 차이 하나가 전부입니다.


// ── 섹션 2: 설치 ──

// Express 는 내장 모듈이 아닙니다. npm 으로 받아야 합니다. (01단원 개념03)
//
//   npm install express
//
// 이 자료는 맨 위 폴더(백엔드자료)에 이미 설치해 두었습니다.
// Node 는 require 할 때 node_modules 를 위쪽 폴더로 계속 거슬러 올라가며 찾습니다.
// 그래서 04단원 폴더 안에 node_modules 가 없어도 잘 찾습니다.
//
// 여러분이 새 프로젝트를 만들 때는 이렇게 합니다.
//
//   mkdir 내프로젝트
//   cd 내프로젝트
//   npm init -y
//   npm install express

const express = require("express");

// require 의 결과가 '함수' 입니다. 그래서 불러서 앱을 만듭니다.
const app = express();

const PORT = process.env.PORT || 3000;


// ── 섹션 3: 가장 작은 서버 ──

// 03단원의 이 코드가
//
//   const server = http.createServer((req, res) => {
//     const 주소 = new URL(req.url, `http://${req.headers.host}`);
//     if (주소.pathname === "/") {
//       res.writeHead(200, { "Content-Type": "text/plain; charset=utf-8" });
//       res.end("안녕하세요");
//       return;
//     }
//     ...
//   });
//
// 이렇게 줄어듭니다.

app.get("/", (req, res) => {
  res.send("안녕하세요. Express 입니다.");
});

// 확인: GET /
// 응답: 200 안녕하세요. Express 입니다.

// 한 줄씩 뜯어봅니다.
//
//   app.get(...)              GET 요청만 받겠다
//   "/"                       이 주소로 올 때만
//   (req, res) => { ... }     그때 이 함수를 실행해라
//   res.send("...")           이 글자를 돌려줘라
//
// writeHead 가 사라졌습니다. Content-Type 도, charset 도, return 도 없습니다.
// Express 가 알아서 붙여 줍니다.
//
// ★ 이렇게 '주소와 함수를 짝지어 등록하는 것' 을 라우팅(routing)이라고 합니다.
//   길 안내라는 뜻입니다. "이 주소로 온 요청은 이쪽으로 보내라" 입니다.


// ── 섹션 4: JSON 돌려주기 ──

app.get("/health", (req, res) => {
  res.json({ status: "ok" });
});

// 확인: GET /health
// 응답: 200 {"status":"ok"}

// res.json 하나로 세 가지가 한꺼번에 됩니다.
//
//   ① JSON.stringify 를 대신 해 줍니다
//   ② Content-Type: application/json 을 붙여 줍니다
//   ③ charset=utf-8 까지 붙여 줍니다   ← 한글이 안 깨집니다
//
// 03단원의 이 세 줄이
//   res.writeHead(200, { "Content-Type": "application/json; charset=utf-8" });
//   res.end(JSON.stringify({ status: "ok" }));
//   return;
// 한 줄이 되었습니다.

app.get("/documents", (req, res) => {
  res.json([
    { id: 1, title: "작업표준서" },
    { id: 2, title: "검사성적서" },
  ]);
});

// 확인: GET /documents
// 응답: 200 [{"id":1,"title":"작업표준서"},{"id":2,"title":"검사성적서"}]

// 배열도 그대로 넣으면 됩니다.


// ── 섹션 5: send 와 json 의 차이 ──

app.get("/send-text", (req, res) => {
  res.send("그냥 글자입니다");
});

// 확인: GET /send-text
// 응답: 200 그냥 글자입니다

app.get("/send-object", (req, res) => {
  res.send({ a: 1 }); // 객체를 넣으면 res.json 과 똑같이 동작합니다
});

// 확인: GET /send-object
// 응답: 200 {"a":1}

// 정리하면
//
//   res.send(글자)   → text/html 로 보냅니다
//   res.send(객체)   → json 으로 보냅니다 (res.json 을 대신 불러 줍니다)
//   res.json(객체)   → 언제나 json 으로 보냅니다
//
// ★ API 를 만들 때는 res.json 만 쓰세요.
//   send 는 상황에 따라 달라져서, 읽는 사람이 결과를 예측하기 어렵습니다.
//   "여기는 JSON 을 준다" 를 코드로 분명히 말하는 편이 낫습니다.


// ── 섹션 6: 상태코드 붙이기 ──

app.get("/created", (req, res) => {
  res.status(201).json({ id: 3, message: "만들었습니다" });
});

// 확인: GET /created
// 응답: 201 {"id":3,"message":"만들었습니다"}

// res.status(201) 은 상태코드만 정해 두고 자기 자신을 돌려줍니다.
// 그래서 뒤에 .json(...) 을 이어 붙일 수 있습니다. 이걸 체이닝이라고 합니다.
//
//   res.status(201).json({ ... })
//        ↑ 코드만 정함    ↑ 실제로 보냄
//
// status 만 부르고 끝내면 아무것도 안 보내집니다. 브라우저가 계속 기다립니다.
// 반드시 뒤에 json / send / end 중 하나가 와야 합니다.
//
// 내용 없이 상태코드만 보낼 때는 sendStatus 를 씁니다.

app.get("/no-content", (req, res) => {
  res.sendStatus(204);
});

// 확인: GET /no-content
// 응답: 204

// res.status(204) 와 res.sendStatus(204) 는 다릅니다. 이름이 비슷해서 자주 헷갈립니다.
//   res.status(204)      코드만 정하고 아직 안 보냄 (뒤에 .json 등이 와야 함)
//   res.sendStatus(204)  코드를 정하고 바로 보냄 (여기서 끝)


// ── 섹션 7: 등록한 순서대로 찾습니다 ──

// Express 는 요청이 오면 위에서부터 차례로 내려오며 맞는 것을 찾습니다.
// 처음 맞는 것 하나를 실행하고 멈춥니다.

app.get("/order", (req, res) => {
  res.send("첫 번째");
});

app.get("/order", (req, res) => {
  res.send("두 번째"); // 여기까지 오지 않습니다
});

// 확인: GET /order
// 응답: 200 첫 번째

// ★ 이 성질 때문에 생기는 사고가 있습니다.
//   "모든 주소" 를 받는 규칙을 맨 위에 적으면, 그 아래 것들이 전부 무시됩니다.
//   넓은 규칙은 항상 아래, 좁은 규칙은 위에 두세요. 개념02 에서 자세히 봅니다.


// ── 섹션 8: ★ 주소에 한글을 쓰면 안 됩니다 ──

// 아래 라우트는 아무리 해도 걸리지 않습니다. 등록은 됐는데 실행이 안 됩니다.

app.get("/한글주소", (req, res) => {  // 검증무시: 일부러 안 되는 예를 살려 둔 것
  res.send("여기는 절대 실행되지 않습니다");
});

// 확인: GET /한글주소
// 응답: 404

// 왜 그럴까요?
//
//   브라우저는 주소에 한글이 있으면 보내기 전에 암호 같은 글자로 바꿉니다.
//   이걸 퍼센트 인코딩이라고 합니다.
//
//     내가 친 주소      /한글주소
//     실제로 나가는 것  /%ED%95%9C%EA%B8%80%EC%A3%BC%EC%86%8C
//
//   Express 는 이 '바뀐 글자' 를 그대로 놓고 라우트와 비교합니다.
//   "/한글주소" 와 "/%ED%95%9C..." 는 당연히 다릅니다. 그래서 404 입니다.
//
//   브라우저 주소창에는 /한글주소 라고 예쁘게 보이니까
//   "분명 주소는 맞는데 왜 404 지?" 하고 한참 헤매게 됩니다.
//
// 그래서 규칙이 하나 생깁니다.
//
//   ★ 라우트 주소는 영어 소문자와 하이픈(-)만 씁니다.
//     /documents  /equipment-logs  /users/:id
//
//   한글은 '값' 에만 씁니다. 값은 Express 가 알아서 되돌려 줍니다.
//     /documents?type=표준   →  req.query.type 은 "표준" 으로 잘 들어옵니다
//     /search/작업표준서      →  req.params 도 잘 들어옵니다 (개념02)
//
//   03단원에서는 이 문제가 없었습니다.
//   우리가 URL 로 분석해서 pathname 을 꺼내 썼기 때문입니다.
//   그때는 Node 가 알아서 되돌려 준 글자를 비교했습니다.
//
// 이 파일에서도 처음에는 /만들었다치고, /내용없음 처럼 한글로 썼다가
// 전부 404 가 나서 영어로 바꿨습니다. 정말 흔한 사고입니다.


// ── 섹션 9: 없는 주소는 Express 가 알아서 404 ──

// 03단원에서는 맨 아래에 404 를 직접 적었습니다.
// Express 는 아무 규칙에도 안 걸리면 알아서 404 를 줍니다. 안 적어도 됩니다.

// 확인: GET /없는주소
// 응답: 404

// ★ 그런데 그 404 의 내용은 HTML 입니다.
//
//     <!DOCTYPE html> ... <pre>Cannot GET /없는주소</pre> ...
//
//   브라우저로 보면 괜찮지만, JSON 을 기대하던 프론트엔드는
//   "JSON 인 줄 알았는데 HTML 이 왔다" 며 에러를 냅니다.
//
//   그래서 API 서버는 404 도 JSON 으로 직접 만들어 줍니다. 개념04 에서 합니다.


// ── 섹션 10: 서버 켜기 ──

app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}`);
});

// http 의 server.listen 과 완전히 같습니다.
// createServer 를 우리가 안 불렀을 뿐, Express 가 안에서 대신 부릅니다.


// ============================================================
// 같은 서버, 두 가지 방법
// ============================================================
//
//                              http        Express
//   서버 만들기                createServer    express()
//   주소 나누기                if 문           app.get("/주소", ...)
//   메서드 나누기              if (req.method) app.get / app.post ...
//   JSON 보내기                writeHead + stringify + end     res.json(...)
//   상태코드                   writeHead(201, ...)             res.status(201)
//   한글 안 깨지게             charset=utf-8 직접 붙이기        자동
//   응답 뒤 return             반드시 필요                     안 해도 됨*
//   없는 주소                  맨 아래에 직접                  자동 404
//
//   * 라우트 함수 하나가 끝나면 Express 가 다음으로 안 넘어갑니다.
//     그래도 res.json 뒤에 코드가 더 있으면 그건 실행됩니다.
//     실수를 막으려면 return res.json(...) 처럼 붙이는 습관이 좋습니다.


// ============================================================
// 직접 해 볼 것
// ============================================================
//
// 서버를 켜고 브라우저에서 아래를 열어 보세요.
//
//   http://localhost:3000/
//   http://localhost:3000/health
//   http://localhost:3000/documents
//   http://localhost:3000/created
//   http://localhost:3000/없는주소       ← HTML 404 를 눈으로 확인
//   http://localhost:3000/한글주소       ← 라우트를 만들었는데도 404
//
// ✏️ 직접 해보기 1 — /about 을 만들어 자기소개를 res.json 으로 돌려주세요.
//
// ✏️ 직접 해보기 2 — 섹션 7 의 두 /order 중 위엣것을 지우고 다시 켜 보세요.
//                    이번에는 무엇이 나오나요?
//
// ✏️ 직접 해보기 3 — res.status(201) 만 쓰고 .json(...) 을 지워 보세요.
//                    브라우저가 어떻게 되나요? 왜 그럴까요?
//                    (확인했으면 반드시 되돌리세요)
//
// ✏️ 직접 해보기 4 — 03단원 개념03 파일과 이 파일을 나란히 열어 보세요.
//                    같은 일을 하는 부분끼리 짝지어 보고, 줄 수를 세어 보세요.
//
// ✏️ 직접 해보기 5 — /한글주소 를 브라우저 F12 → Network 탭을 켜 놓고 열어 보세요.
//                    요청 목록에서 실제로 나간 주소가 어떻게 생겼는지 확인하세요.
//                    그다음 라우트를 "/korean" 으로 바꾸고 다시 켜서 되는지 보세요.


// ── 자주 하는 실수 ──

// [실수 1] express() 를 안 부름
//   const app = express;        ← 괄호가 없습니다
//   → TypeError: app.get is not a function
//   express 는 '앱을 만들어 주는 함수' 입니다. 불러야 앱이 나옵니다.

// [실수 2] app.get 을 listen 아래에 씀
//   listen 아래에 적어도 동작은 합니다. 하지만 읽기 어려워집니다.
//   라우트는 전부 위에, listen 은 맨 마지막에 두세요. 관례입니다.

// [실수 3] 응답을 두 번 보냄
//   res.json({ a: 1 });
//   res.json({ b: 2 });
//   → Error: Cannot set headers after they are sent to the client
//   03단원과 똑같은 에러입니다. return 을 붙이면 막을 수 있습니다.

// [실수 4] res.send 와 res.json 을 섞어 씀
//   틀린 건 아니지만, 어떤 주소는 문자열을 어떤 주소는 객체를 주게 됩니다.
//   프론트에서 받는 코드가 주소마다 달라져야 합니다. json 으로 통일하세요.

// [실수 5] Cannot find module 'express'
//   npm install express 를 안 했거나, 다른 폴더에서 실행한 것입니다.
//   이 자료는 백엔드자료 폴더 아래에서 실행해야 찾을 수 있습니다.

// [실수 6] 파일을 고치고 새로고침만 함
//   03단원과 똑같습니다. 서버를 다시 켜야 합니다.
//   개념05 에서 이걸 자동으로 해 주는 nodemon 을 씁니다.

// [실수 7] 라우트 주소를 한글로 씀
//   app.get("/설비목록", ...) 은 등록은 되지만 절대 실행되지 않습니다.
//   에러도 안 나고 그냥 404 만 나와서 원인을 찾기 아주 어렵습니다.
//   주소는 영어로, 한글은 값에만. (섹션 8)


// ── 정리 ──

// 1. Express 는 03단원에서 손으로 하던 네 가지를 대신해 준다.
//    갈래 나누기 · 응답 만들기 · 주소에서 값 꺼내기 · 본문 읽기.
// 2. npm i express 로 받고, express() 로 app 을 만들고, app.listen 으로 켠다.
// 3. app.get("/주소", (req, res) => ...) 하나가 03단원의 if 한 덩어리를 대신한다.
// 4. res.json 은 객체를 알아서 글자로 바꾸고 Content-Type 까지 붙여 준다.
//    JSON.stringify 도 writeHead 도 직접 쓰지 않는다.
// 5. res.send 는 넣는 것에 따라 달라진다. 글자면 text/html, 객체면 json 이다.
//    API 는 res.json 으로 통일하는 편이 헷갈리지 않는다.
// 6. 상태코드는 res.status(201).json(...) 처럼 앞에 붙인다.
//    status 만 쓰고 끝내면 응답이 안 나가서 브라우저가 계속 기다린다.
// 7. 라우트는 등록한 순서대로 찾는다. 먼저 걸리는 것이 이긴다.
// 8. 주소에 한글을 쓰면 안 된다. 에러도 없이 404 만 나서 원인을 찾기 아주 어렵다.
//    주소는 영어로, 한글은 값에만.
// 9. 없는 주소는 Express 가 알아서 404 를 준다. 03단원에서 손으로 하던 일이다.

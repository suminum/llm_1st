// ───── 문제 3 ─────
const 라우트들 = ["/orders/:id", "/orders/new", "/orders", "/orders/:id/items"];

function 파라미터수(경로) {
  return (경로.match(/:/g) || []).length;
}

const 등록순서 = [...라우트들].sort((a, b) => 파라미터수(a) - 파라미터수(b));

console.log(등록순서);
// 출력: [ '/orders/new', '/orders', '/orders/:id', '/orders/:id/items' ]
//
// 콜론이 적은 것(구체적인 것)이 먼저 오게 정렬했습니다.
//
// ★ match 는 못 찾으면 null 을 줍니다
//   "/orders".match(/:/g) 는 null 입니다. null.length 는 TypeError 입니다.
//   그래서 || [] 로 받쳐 두었습니다. 빈 배열의 length 는 0 입니다.
//
// ★ [...라우트들] 로 복사한 이유
//   sort 는 원본 배열을 진짜로 바꿔 버립니다.
//   원본을 지키려면 복사본을 정렬해야 합니다. (JS자료 06단원)
//
// ★ 이건 규칙을 이해하기 위한 연습입니다
//   실제로는 정렬 함수를 쓰지 않고, 사람이 코드를 그 순서로 적습니다.
//   "구체적인 것 위, :id 아래" 를 손에 익히는 게 목적입니다.



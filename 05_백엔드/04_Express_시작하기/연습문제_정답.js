// ───── 문제 1 ─────
function 버전5로(경로) {
  return 경로
    .replace(/\/(:[a-zA-Z]+)\?/g, "{/$1}") // /:year?  →  {/:year}
    .replace(/\*$/, "*splat"); // 끝의 *  →  *splat
}

console.log(버전5로("/reports/:year?"));
// 출력: /reports{/:year}
console.log(버전5로("/files/*"));
// 출력: /files/*splat
console.log(버전5로("/documents/:id"));
// 출력: /documents/:id
console.log(버전5로("/a/:b?/c/*"));
// 출력: /a{/:b}/c/*splat
//
// 세 번째는 바꿀 게 없어서 그대로 나옵니다. 이것도 확인해야 합니다.
// "바꿀 게 없는 것을 안 건드리는가" 도 함수가 맞는지 보는 방법입니다.
//
// $1 은 무엇인가
//   괄호로 묶은 부분을 그대로 가져다 쓰는 표시입니다.
//   (:[a-zA-Z]+) 가 ":year" 를 잡았으면 $1 자리에 ":year" 가 들어갑니다.
//
// ★ 이 함수는 연습용입니다. 실제로는 이런 걸 만들 일이 없습니다.
//   블로그 코드를 보고 "아 이건 4 문법이구나" 하고 알아보는 게 목적입니다.



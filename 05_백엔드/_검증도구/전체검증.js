// ============================================================
// _검증도구/전체검증.js — 자료 전체를 한 번에 훑는다
// ------------------------------------------------------------
// 사용:
//   node _검증도구/전체검증.js
//   npm run 검증
//
//   node _검증도구/전체검증.js 04_Express_시작하기   ← 한 단원만
//
// 하는 일:
//   ① 출력검증   `// 출력:` 주석 ↔ 진짜 node 실행 결과
//   ② 서버검증   `// 확인:` 선언 ↔ 진짜 서버에 보낸 요청
//   ③ 화면검증   `// 화면:` 선언 ↔ 진짜 크롬으로 눌러 본 결과
//   ④ 정합성     자료 안의 규칙을 스스로 어기지 않았는지
//   ⑤ 구조 감사  단원마다 짜임새가 같은지 (섹션·✏️·실수·정리·문제 마커)
//
//   ③은 puppeteer-core 가 없으면 조용히 건너뜁니다.
//     npm install --save-dev puppeteer-core
//
//   CORS 확인은 따로 돌립니다. 결과를 사람이 읽고 판단해야 하니까요.
//     node _검증도구/브라우저검증.js
//
// ★ "다 됐다" 라고 말하기 전에 반드시 이걸 돌립니다.
//   사람 눈으로는 안 잡힙니다.
// ============================================================

const path = require("path");
const cp = require("child_process");

const 도구폴더 = __dirname;
const 넘어온것 = process.argv.slice(2);

const 단계들 = [
  { 이름: "출력 대조", 파일: "출력검증.js" },
  { 이름: "서버 요청 대조", 파일: "서버검증.js" },
  { 이름: "화면 대조 (진짜 크롬)", 파일: "화면검증.js" },
  { 이름: "정합성 검사", 파일: "정합성검사.js" },
  { 이름: "구조 감사", 파일: "구조감사.js" },
];

let 전체실패 = 0;
const 요약 = [];

for (const 단계 of 단계들) {
  console.log(`\n\n${"=".repeat(60)}`);
  console.log(`  ${단계.이름}`);
  console.log("=".repeat(60));

  const 결과 = cp.spawnSync("node", [path.join(도구폴더, 단계.파일), ...넘어온것], {
    stdio: "inherit",
  });

  const 실패 = 결과.status !== 0;
  if (실패) 전체실패 += 1;

  요약.push({ 이름: 단계.이름, 실패 });
}

console.log(`\n\n${"#".repeat(60)}`);
console.log("  전체 결과");
console.log("#".repeat(60));

for (const 줄 of 요약) {
  console.log(`  ${줄.실패 ? "✗ 문제 있음" : "○ 이상 없음"}  ${줄.이름}`);
}

if (전체실패 === 0) {
  console.log("\n  전부 통과했습니다.");
  console.log("  브라우저 확인도 하려면:  node _검증도구/브라우저검증.js");
} else {
  console.log(`\n  ${전체실패}개 단계에서 문제가 나왔습니다. 위 내용을 확인하세요.`);
}

process.exit(전체실패 > 0 ? 1 : 0);

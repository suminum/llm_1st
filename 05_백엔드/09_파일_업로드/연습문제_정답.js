function 어긋난것찾기(기록들, 디스크파일들) {
  const 기록이름 = new Set(기록들.map((기록) => 기록.저장이름));
  const 디스크이름 = new Set(디스크파일들);

  return {
    고아파일: 디스크파일들.filter((이름) => !기록이름.has(이름)),
    깨진기록: 기록들.filter((기록) => !디스크이름.has(기록.저장이름)).map((기록) => 기록.id),
  };
}


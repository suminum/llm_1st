const 허용확장자 = [".jpg", ".jpeg", ".png", ".gif", ".pdf"];

function 확장자검사(원본이름) {
  const 되돌린것 = 이름되돌리기(원본이름);
  const 확장자 = path.extname(되돌린것).toLowerCase();

  if (!확장자) return "확장자가 없습니다";
  if (!허용확장자.includes(확장자)) return `${확장자} 는 올릴 수 없습니다`;

  return null; // 통과
}


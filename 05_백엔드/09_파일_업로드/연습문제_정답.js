const 매직넘버 = {
  ".png": [0x89, 0x50, 0x4e, 0x47],
  ".jpg": [0xff, 0xd8, 0xff],
  ".jpeg": [0xff, 0xd8, 0xff],
  ".gif": [0x47, 0x49, 0x46],
  ".pdf": [0x25, 0x50, 0x44, 0x46],
};

function 진짜형식인가(버퍼, 확장자) {
  const 기대 = 매직넘버[확장자];
  if (!기대) return true; // 모르는 형식은 통과

  return 기대.every((바이트, i) => 버퍼[i] === 바이트);
}


//     path.extname("../../.env")  →  ""
//     path.extname(".env")        →  ""
//     path.extname("a.env")       →  ".env"
//
//   점으로 '시작하는' 이름은 확장자가 아니라 '숨김 파일 이름' 으로 봅니다.
//   리눅스에서 .env, .gitignore 처럼 점으로 시작하는 파일이 숨김 파일입니다.

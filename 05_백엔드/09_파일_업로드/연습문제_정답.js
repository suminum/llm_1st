//   업로드 파일 이름    (09단원)  깨져서 도착합니다 (되돌릴 수는 있음)
//   Content-Disposition (09단원)  encodeURIComponent 로 감싸야 합니다
//
// 반대로 한글이 잘 되는 곳:
//   쿼리 값, 경로 파라미터 값, JSON 본문, 폼 필드 값, 응답 본문, 파일 내용
//
// 공통점은 무엇인가:
//   안 되는 것은 전부 '헤더에 실려 가는 것' 입니다.
//   HTTP 헤더는 아주 오래전 약속이라 영어와 숫자만 담을 수 있습니다.
//   본문은 아무 바이트나 담을 수 있어서 한글이 잘 됩니다.
//
// 규칙 한 줄로:
//   이름은 영어로, 값은 한글로.
//   주소·필드 이름·헤더 이름은 우리가 정하는 것이니 영어로 지으면 됩니다.
//   사용자가 넣는 값에만 한글이 들어오고, 그건 대부분 본문에 담깁니다.
//
// 파일 이름은 왜 예외인가:
//   파일 이름은 '값' 인데도 헤더 줄(Content-Disposition)에 실려 옵니다.
//   그래서 깨집니다. 우리가 정하는 게 아니라 사용자가 정하는 값이라
//   영어로 하라고 할 수도 없습니다. 그래서 되돌리기가 필요합니다.

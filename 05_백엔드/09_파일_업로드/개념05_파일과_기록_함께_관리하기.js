// [실수 1] 기록 실패 시 파일을 안 지움
//   아무도 모르는 파일이 쌓입니다. 디스크가 조용히 찹니다.

// [실수 2] 에러를 내기 전에 req.file 을 안 지움
//   400·404 를 낼 때마다 고아 파일이 하나씩 생깁니다.

// [실수 3] 파일을 먼저 지우고 기록을 나중에

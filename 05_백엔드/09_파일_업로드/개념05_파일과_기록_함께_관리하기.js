// ★★★ 마지막 두 줄을 꼭 보세요.
//
//   없는 번호로 교체를 시도했습니다. 404 가 났습니다.
//   그런데 파일은 이미 올라온 뒤였습니다. multer 가 라우트보다 먼저 도니까요.
//
//   그 파일을 안 지웠다면 고아 파일이 하나 늘었을 것입니다.
//   404 를 내기 전에 지웠기 때문에 고아파일수가 0 그대로입니다.
//
// ★ 규칙 하나
//   "req.file 이 있는 상태로 에러를 내려면, 그 전에 파일을 지운다."
//
//   업로드 라우트에서 400·404·403 을 낼 때마다 이걸 확인하세요.
//   빠뜨리기 아주 쉽고, 티가 안 나며, 디스크가 조용히 찹니다.


// ── 섹션 6: 07단원 구조에 얹으면 ──

app.get("/api/v1/layering", (req, res) => {
  res.json({
    data: {
      routes: "upload.single('file') 미들웨어를 여기서 붙입니다",
      controllers: "req.file 에서 값을 꺼내 서비스에 넘깁니다. 이름 되돌리기도 여기서",
      services: "업무 규칙. '한 설비에 사진 5장까지' 같은 것. 실패하면 파일 지우기도 여기서",
      repositories: "기록을 저장합니다. 파일 자체는 안 만집니다",
      "디스크 다루기": "저장소와 나란히 둡니다. 지우기·있나 확인 같은 것",
    },
    주의: "multer 는 routes 에 붙습니다. 라우트가 실행될 때는 이미 저장이 끝나 있습니다.",
  });
});

// 확인: GET /api/v1/layering
// 응답: 200

// ★ 어디에 무엇을 둘지 헷갈릴 때
//
//   "파일 이름을 어떻게 지을까"       → multer 설정 (routes 옆)
//   "한글 이름을 되돌린다"            → controllers (경계에서 값을 다듬음)
//   "한 설비에 5장까지"               → services (업무 규칙)
//   "기록을 남긴다"                   → repositories
//   "실패하면 파일을 지운다"          → services (규칙을 아는 곳이 책임집니다)
//
// ★ 디스크 다루기를 저장소와 나란히 두는 이유
//   나중에 S3 로 바꾸면 이 파일만 갈아 끼우면 됩니다. (PART 4)
//   07단원에서 파일 저장소를 데이터베이스로 바꾸는 것과 같은 이야기입니다.


app.use((req, res) => {
  res.status(404).json({ error: { code: "NOT_FOUND", message: "찾을 수 없습니다" } });
});

app.use((err, req, res, next) => {
  console.error(`[에러] ${req.method} ${req.path} — ${err.name}: ${err.message}`);

  if (err.name === "MulterError") {
    return res.status(400).json({ error: { code: err.code, message: err.message } });
  }

  res.status(500).json({ error: { code: "INTERNAL_ERROR", message: "서버에서 문제가 생겼습니다" } });
});


app.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}/api/v1/files`);
  console.log(`업로드 폴더: ${업로드폴더}`);
});



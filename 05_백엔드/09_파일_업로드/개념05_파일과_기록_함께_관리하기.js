const express = require("express");
const multer = require("multer");
const path = require("path");
const fs = require("fs");

const app = express();
const PORT = Number(process.env.PORT) || 3000;

app.use(express.json());

const 업로드폴더 = path.join(__dirname, "uploads", "관리");
fs.rmSync(업로드폴더, { recursive: true, force: true });
fs.mkdirSync(업로드폴더, { recursive: true });

function 이름되돌리기(이름) {
  return Buffer.from(이름, "latin1").toString("utf8");
}


// ── 섹션 1: 저장소 (07단원 구조) ──

// 진짜라면 데이터베이스입니다. 여기서는 배열로 둡니다.
let 기록들 = [];
let 다음번호 = 1;

const 파일저장소 = {
  전부: () => 기록들.map((기록) => ({ ...기록 })),

  하나: (id) => {
    const 찾은것 = 기록들.find((기록) => 기록.id === id);
    return 찾은것 ? { ...찾은것 } : null;
  },

  추가: (값) => {
    const 새것 = { id: 다음번호, ...값 };
    다음번호 += 1;
    기록들.push(새것);
    return { ...새것 };
  },

  삭제: (id) => {
    const 전 = 기록들.length;
    기록들 = 기록들.filter((기록) => 기록.id !== id);
    return 기록들.length !== 전;
  },
};

// 디스크를 다루는 것도 한곳에 모읍니다.
const 디스크 = {
  경로: (저장이름) => path.join(업로드폴더, 저장이름),

  있나: (저장이름) => fs.existsSync(디스크.경로(저장이름)),

  지우기: async (저장이름) => {
    try {
      await fs.promises.unlink(디스크.경로(저장이름));
      return true;
    } catch (에러) {
      // ★ 이미 없는 파일을 지우려 한 것은 실패가 아닙니다.
      //   "없어야 한다" 는 목표가 이미 이뤄진 상태니까요.
      if (에러.code === "ENOENT") return false;
      throw 에러;
    }
  },

  전부목록: () => fs.readdirSync(업로드폴더),
};


// ── 섹션 2: 올리기 — 순서가 중요합니다 ──

const 저장방식 = multer.diskStorage({
  destination: (req, file, cb) => cb(null, 업로드폴더),
  filename: (req, file, cb) => {
    const 확장자 = path.extname(이름되돌리기(file.originalname)).toLowerCase();
    cb(null, `${Date.now()}-${Math.round(Math.random() * 1e9)}${확장자}`);
  },
});

const 업로드 = multer({ storage: 저장방식, limits: { fileSize: 1024 } });

app.post("/api/v1/files", 업로드.single("file"), async (req, res, next) => {
  if (!req.file) {
    return res.status(400).json({ error: { code: "NO_FILE", message: "파일이 없습니다" } });
  }

  const 원래이름 = 이름되돌리기(req.file.originalname);

  try {
    // ★ 파일은 이미 저장됐습니다. multer 가 라우트보다 먼저 끝냈으니까요.
    //   여기서 기록을 남깁니다.
    const 기록 = 파일저장소.추가({
      저장이름: req.file.filename,
      원래이름,
      크기: req.file.size,
    });

    res.status(201).json({ data: { id: 기록.id, 원래이름: 기록.원래이름 } });
  } catch (에러) {
    // ★★ 기록에 실패하면 방금 저장한 파일을 지웁니다.
    //   안 지우면 '아무도 모르는 파일' 이 디스크에 남습니다.
    await 디스크.지우기(req.file.filename);
    next(에러);
  }
});

// 확인: POST /api/v1/files multipart:@file=작업표준서.pdf:30
// 응답: 201 {"data":{"id":1,"원래이름":"작업표준서.pdf"}}

// 확인: POST /api/v1/files multipart:@file=검사성적서.pdf:40
// 응답: 201 {"data":{"id":2,"원래이름":"검사성적서.pdf"}}

// ★★ try/catch 안의 '되돌리기' 가 이 섹션의 핵심입니다.
//
//   07단원에서 본 '중간 실패' 가 여기서 실제로 일어납니다.
//   파일은 저장됐는데 기록이 안 남으면?
//   그 파일은 영원히 아무도 못 찾습니다. 디스크만 차지합니다.
//
//   데이터베이스라면 트랜잭션으로 묶으면 되는데, 디스크는 그게 안 됩니다.
//   그래서 손으로 되돌려야 합니다. 이런 걸 '보상 처리' 라고 부릅니다.


// ── 섹션 3: 지우기 — 무엇을 먼저 지울까 ──

app.delete("/api/v1/files/:id", async (req, res, next) => {
  const 번호 = Number(req.params.id);
  const 기록 = 파일저장소.하나(번호);

  if (!기록) {
    return res.status(404).json({ error: { code: "NOT_FOUND", message: "파일을 찾을 수 없습니다" } });
  }

  try {
    // ★★ 기록을 '먼저' 지웁니다. 파일은 그다음입니다.
    파일저장소.삭제(번호);
    await 디스크.지우기(기록.저장이름);

    res.sendStatus(204);
  } catch (에러) {
    next(에러);
  }
});

// 확인: DELETE /api/v1/files/2
// 응답: 204

// 확인: DELETE /api/v1/files/2
// 응답: 404 {"error":{"code":"NOT_FOUND","message":"파일을 찾을 수 없습니다"}}

// ★★★ 왜 기록을 먼저 지우나
//
//   두 가지 순서가 있고, 각각 실패했을 때의 결과가 다릅니다.
//
//   ① 파일 먼저 → 기록 나중
//      파일은 지워졌는데 기록이 남습니다.
//      목록에 파일이 보이는데 누르면 깨집니다.
//      → 사용자가 바로 알아채고 문의합니다. 나쁜 경험입니다.
//
//   ② 기록 먼저 → 파일 나중   ★ 이쪽을 고릅니다
//      기록은 지워졌는데 파일이 남습니다.
//      목록에 안 보입니다. 아무도 모릅니다.
//      → 디스크만 조금 차지합니다. 나중에 청소하면 됩니다.
//
//   둘 다 완벽하지 않습니다. 어느 쪽이 '덜 나쁜가' 를 고르는 것입니다.
//   보이지 않는 쓰레기가, 보이는 고장보다 낫습니다.
//
// ★ 이런 판단을 하는 것이 백엔드의 일입니다.
//   "어떻게든 되겠지" 가 아니라 "실패하면 어느 쪽으로 기울게 할까" 를 정합니다.


// ── 섹션 4: 고아 파일 찾기 ──

// 섹션 3의 ②를 골랐으니, 기록 없는 파일이 쌓일 수 있습니다.
// 가끔 청소해 줘야 합니다.

app.get("/api/v1/orphans", (req, res) => {
  const 기록에있는이름 = new Set(파일저장소.전부().map((기록) => 기록.저장이름));
  const 디스크에있는이름 = 디스크.전부목록();

  const 고아파일 = 디스크에있는이름.filter((이름) => !기록에있는이름.has(이름));
  const 깨진기록 = 파일저장소
    .전부()
    .filter((기록) => !디스크.있나(기록.저장이름))
    .map((기록) => 기록.id);

  res.json({
    data: {
      디스크파일수: 디스크에있는이름.length,
      기록수: 기록에있는이름.size,
      고아파일수: 고아파일.length,
      깨진기록: 깨진기록,
    },
  });
});

// 확인: GET /api/v1/orphans
// 응답: 200 {"data":{"디스크파일수":1,"기록수":1,"고아파일수":0,"깨진기록":[]}}

// ★ 지금은 0 입니다. 섹션 3에서 파일까지 잘 지웠기 때문입니다.
//
// ★ Set 을 쓴 이유
//   기록이 만 개고 파일이 만 개면, 배열로 includes 를 쓰면 일억 번 비교합니다.
//   Set 의 has 는 한 번에 찾습니다. 개수가 늘수록 차이가 큽니다.

app.post("/api/v1/orphans/make", (req, res) => {
  // 일부러 고아 파일을 하나 만듭니다. 청소를 시험해 보려고요.
  fs.writeFileSync(path.join(업로드폴더, "버려진파일.pdf"), "아무도 모르는 파일", "utf-8");
  res.status(201).json({ data: { 만듦: "버려진파일.pdf" } });
});

// 확인: POST /api/v1/orphans/make
// 응답: 201 {"data":{"만듦":"버려진파일.pdf"}}

// 확인: GET /api/v1/orphans
// 응답: 200 {"data":{"디스크파일수":2,"기록수":1,"고아파일수":1,"깨진기록":[]}}

app.delete("/api/v1/orphans", async (req, res, next) => {
  const 기록에있는이름 = new Set(파일저장소.전부().map((기록) => 기록.저장이름));
  const 고아파일 = 디스크.전부목록().filter((이름) => !기록에있는이름.has(이름));

  try {
    for (const 이름 of 고아파일) {
      await 디스크.지우기(이름);
    }

    res.json({ data: { 지운수: 고아파일.length } });
  } catch (에러) {
    next(에러);
  }
});

// 확인: DELETE /api/v1/orphans
// 응답: 200 {"data":{"지운수":1}}

// 확인: GET /api/v1/orphans
// 응답: 200 {"data":{"디스크파일수":1,"기록수":1,"고아파일수":0,"깨진기록":[]}}

// ★★ 실제 서비스에서 이걸 그대로 쓰면 안 됩니다.
//
//   지금 막 올라온 파일이 있다고 합시다.
//   multer 가 파일을 다 썼고, 기록은 아직 안 남긴 그 짧은 순간에
//   청소가 돌면 그 파일을 고아로 보고 지웁니다.
//
//   그래서 실무에서는 조건을 하나 더 답니다.
//     "만들어진 지 한 시간이 넘은 것만 지운다"
//
//   fs.statSync(경로).mtimeMs 로 만들어진 시각을 볼 수 있습니다. (02단원 개념04)
//
// ★ 그리고 이런 청소는 요청으로 부르지 않습니다.
//   새벽에 한 번 도는 '예약 작업' 으로 만듭니다. PART 4 에서 배웁니다.


// ── 섹션 5: 바꿔치기 (교체) ──

app.put("/api/v1/files/:id", 업로드.single("file"), async (req, res, next) => {
  const 번호 = Number(req.params.id);
  const 옛기록 = 파일저장소.하나(번호);

  if (!옛기록) {
    // ★ 이미 올라온 새 파일을 지워야 합니다. 안 그러면 고아가 됩니다.
    if (req.file) await 디스크.지우기(req.file.filename);
    return res.status(404).json({ error: { code: "NOT_FOUND", message: "파일을 찾을 수 없습니다" } });
  }

  if (!req.file) {
    return res.status(400).json({ error: { code: "NO_FILE", message: "파일이 없습니다" } });
  }

  try {
    // ① 기록을 새 파일로 바꿉니다
    파일저장소.삭제(번호);
    const 새기록 = 파일저장소.추가({
      저장이름: req.file.filename,
      원래이름: 이름되돌리기(req.file.originalname),
      크기: req.file.size,
    });

    // ② 그다음 옛 파일을 지웁니다
    await 디스크.지우기(옛기록.저장이름);

    res.json({ data: { id: 새기록.id, 원래이름: 새기록.원래이름 } });
  } catch (에러) {
    next(에러);
  }
});


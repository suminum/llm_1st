// [실수 4] 고아 청소에 시간 조건을 안 검
//   방금 올라온 파일을 지워 버립니다.

// [실수 5] 청소를 요청 라우트로만 만듦
//   아무도 안 부르면 영원히 안 돌아갑니다. 예약 작업으로 만드세요.

// [실수 6] ENOENT 를 에러로 취급
//   이미 없는 파일을 지우려 한 것은 성공입니다. 목표가 이미 이뤄졌으니까요.

// [실수 7] 디스크 다루는 코드를 라우트마다 흩어 놓음
//   S3 로 바꿀 때 전부 찾아 고쳐야 합니다. 한곳에 모으세요.


// ── 정리 ──

// 1. 파일과 기록은 둘 다 있어야 짝이 맞는다. 한쪽만 남으면 그때부터 꼬인다.
// 2. 올릴 때 순서는 파일 저장 다음 기록이다.
//    기록에 실패하면 방금 저장한 파일을 반드시 지운다.
// 3. 에러를 내기 전에도 req.file 을 지운다. 검증에 걸려 되돌아가는 길에도 파일은 이미 있다.
// 4. 지울 때는 기록을 먼저 지우고 파일을 나중에 지운다.
//    파일을 먼저 지우면 기록만 남아 '있다고 하는데 없는' 상태가 된다.
// 5. 그래도 어긋난 파일은 생긴다. 기록 없는 파일을 찾아 지우는 청소가 필요하다.
// 6. 청소에는 시간 조건을 건다. 방금 올라와 아직 기록 전인 파일까지 지우면 안 된다.
// 7. 청소를 요청 라우트로만 만들지 않는다. 아무도 안 부르면 영영 안 돈다.
// 8. 파일이 이미 없어서 나는 ENOENT 는 에러가 아니다. 지우려던 것이 없는 것뿐이다.
// 9. 디스크를 다루는 코드는 한곳에 모은다. 라우트마다 흩어 놓으면 한 곳만 고치게 된다.

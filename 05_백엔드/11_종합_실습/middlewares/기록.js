// ============================================================

let 요청번호 = 0;

function 번호붙이기(req, res, next) {
  요청번호 += 1;
  req.요청번호 = 요청번호;
  res.set("X-Request-Id", String(요청번호)); // ★ 값은 반드시 영어·숫자
  next();
}

module.exports = { 번호붙이기 };

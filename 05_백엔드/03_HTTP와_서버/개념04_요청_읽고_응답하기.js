//    req.method · req.url · req.headers 로 그냥 꺼내 쓰면 된다.
// 2. 본문만 다르다. 조각조각 나중에 도착한다.
//    req.on("data") 로 모으고 req.on("end") 에서 끝낸다.
// 3. 그래서 본문은 기다려야 한다. 안 기다리고 쓰면 빈 값이 나온다.
// 4. setEncoding("utf8") 을 미리 불러 두면 조각을 글자로 알아서 바꿔 준다.
// 5. 헤더 이름은 Node 에서 전부 소문자다. req.headers["content-type"] 처럼 쓴다.
// 6. JSON.parse 는 실패할 수 있다. try/catch 없이 쓰면 서버가 통째로 죽는다.
//    형식이 틀린 것은 400 으로 돌려준다.

//   04단원 Express 에서는 이러면 본문이 통째로 안 들어옵니다.

// [실수 6] GET 요청에 본문을 담으려 함
//   Postman 에서는 담아지지만, 브라우저 fetch 는 거부합니다.
//   → TypeError: Request with GET/HEAD method cannot have body
//   GET 으로 값을 보낼 때는 쿼리(?q=...)를 씁니다.



// Postman — POST 를 보내는 도구
// ============================================================
//
// 브라우저 주소창에 주소를 치면 언제나 GET 입니다.
// 주소창에는 "본문을 여기 담아라" 를 적을 칸이 없기 때문입니다.
//
// 그래서 POST 를 시험하려면 도구가 필요합니다. Postman 을 씁니다.
//
//
// ── 설치 ──
//
//   1. https://www.postman.com/downloads 에서 Windows 64-bit 를 받습니다.
//   2. 설치한 뒤 실행합니다.
//   3. 로그인하라고 나옵니다. 오른쪽 아래 작은 글씨의
//      "Skip and go to the app" 을 누르면 로그인 없이 쓸 수 있습니다.
//      (팀으로 공유하려면 가입하면 됩니다. 지금은 필요 없습니다)
//
//
// ── GET 보내 보기 ──
//
//   1. 왼쪽 위 + 버튼 → 새 탭이 생깁니다.
//   2. 주소칸에      http://localhost:3000/echo?이름=김민준&나이=20
//   3. 파란 Send 버튼을 누릅니다.
//   4. 아래쪽에 응답이 나옵니다.
//
//      Body 탭     → 돌려받은 내용
//      Headers 탭  → 돌려받은 헤더
//      오른쪽 위   → 200 OK 와 걸린 시간
//
//
// ── POST 보내 보기 (제일 중요합니다) ──
//
//   1. 주소칸 왼쪽의 GET 을 눌러 POST 로 바꿉니다.
//   2. 주소칸에      http://localhost:3000/memos
//   3. 주소칸 아래 줄에서 Body 탭을 누릅니다.
//   4. raw 를 고릅니다.
//   5. 그 오른쪽 드롭다운을 Text → JSON 으로 바꿉니다.   ★ 자주 빠뜨립니다
//   6. 아래 큰 칸에 이렇게 적습니다.
//
//        { "title": "작업표준서" }
//
//   7. Send.  → 201 과 함께 {"받은제목":"작업표준서","글자수":5} 가 나옵니다.
//
//   5번을 안 하면 Content-Type 이 text/plain 으로 나갑니다.
//   지금 만든 서버는 그래도 동작하지만, 04단원 Express 에서는
//   본문이 통째로 빈 값이 되어 "왜 undefined 지?" 하고 헤매게 됩니다.
//   지금부터 습관을 들이세요.
//
//
// ── 일부러 틀려 보기 ──
//
//   Body 를 아래처럼 바꿔 가며 Send 를 눌러 보세요.
//
//     (아무것도 안 씀)              → 400  본문이 비어 있습니다
//     { title: "따옴표없음" }        → 400  JSON 형식이 아닙니다
//     { "내용": "제목이없음" }        → 400  title 을 넣어 주세요
//     { "title": "작업표준서" }      → 201  정상
//
//   두 번째가 왜 틀렸는지 보세요. JSON 은 속성 이름에도 큰따옴표가 필요합니다.
//   자바스크립트 객체와 생긴 게 비슷해서 정말 자주 틀립니다.
//
//
// ── 다른 도구도 있습니다 ──
//
//   Thunder Client   VS Code 확장. 에디터를 안 벗어나도 됩니다. 가볍습니다.
//   curl             터미널 명령. 서버에 올린 뒤에는 이것밖에 못 쓸 때가 많습니다.
//
//     curl -X POST http://localhost:3000/memos ^
//          -H "Content-Type: application/json" ^
//          -d "{\"title\":\"작업표준서\"}"
//
//     (윈도우 PowerShell 에서는 줄 끝의 ^ 대신 ` 를 씁니다.
//      한 줄로 붙여 쓰면 그런 것 신경 안 써도 됩니다)



// 이번에는 요청 안에 들어 있는 나머지를 전부 꺼내 봅니다.
//
//   ① 메서드   req.method
//   ② 주소     req.url        → 경로 + 쿼리
//   ③ 헤더     req.headers
//   ④ 본문     req.on("data") → ★ 이게 오늘의 핵심입니다
//
// ①②③ 은 요청이 도착하는 순간 이미 다 들어 있습니다. 그냥 꺼내 쓰면 됩니다.
// ④ 만 다릅니다. 본문은 '나중에, 조각조각' 도착합니다. 기다려서 모아야 합니다.

const http = require("http");

const PORT = process.env.PORT || 3000;


// ── 섹션 0: 반복부터 없애고 갑시다 ──

// 개념03 끝에서 불편한 점 네 가지를 봤습니다.
// 그중 ② "경로마다 writeHead 와 JSON.stringify 를 반복한다" 는
// Express 없이도 우리가 직접 고칠 수 있습니다. 함수로 묶으면 됩니다.

function JSON응답(res, 상태코드, 데이터) {
  res.writeHead(상태코드, { "Content-Type": "application/json; charset=utf-8" });
  res.end(JSON.stringify(데이터));
}

// 이제 아래처럼 한 줄로 씁니다.
//
//   JSON응답(res, 200, { status: "ok" });
//
// 세 줄이 한 줄이 되었고, charset=utf-8 을 빠뜨릴 일도 없어졌습니다.
// "같은 코드를 세 번 이상 쓰고 있다" 싶으면 함수로 묶으세요. 서버 코드도 똑같습니다.
//
// 나머지 ①③④ 는 함수로 못 고칩니다. 그래서 Express 가 필요합니다.


// ── 섹션 1: 본문은 왜 한 번에 안 오나 ──

// 본문(body)은 요청에 딸려 오는 '내용물' 입니다.
// 회원가입 폼, 글쓰기 내용, 업로드한 파일이 전부 여기 들어옵니다.
//
// 그런데 Node 는 본문을 통째로 주지 않습니다.
// 조각(chunk)으로 나눠서, 도착하는 대로 하나씩 건네줍니다.
//
// 왜 그럴까요?
//   본문이 항상 작다는 보장이 없기 때문입니다.
//   500MB 짜리 동영상을 올리면, 통째로 주려다가 메모리가 터집니다.
//   조각으로 주면 받는 쪽이 "조금 받고 저장하고, 조금 받고 저장하고" 를 할 수 있습니다.
//
// 이런 방식을 스트림(stream)이라고 부릅니다.
// 물을 양동이째 건네는 게 아니라, 호스로 흘려보내는 것입니다.
//
// 그래서 코드가 이렇게 생겼습니다.
//
//   req.on("data", (조각) => { ... })   ← 조각이 올 때마다 실행
//   req.on("end",  ()     => { ... })   ← 다 왔을 때 딱 한 번 실행
//
// 11단원(JS자료)에서 배운 addEventListener 와 똑같은 모양입니다.
// "무슨 일이 생기면 이 함수를 실행해 줘" 라는 뜻입니다.
// 버튼 클릭 대신 '데이터 도착' 이 그 일입니다.


// ── 섹션 2: 본문 모으는 함수 ──

// 조각을 모아서 하나의 글자로 만들어 돌려주는 함수입니다.
// 이 15줄은 서버를 만들 때 늘 나오는 정형구입니다. 통째로 외워도 됩니다.

function 본문읽기(req) {
  return new Promise((resolve, reject) => {
    let 쌓은글자 = "";

    // ★ 조각을 글자로 알아서 바꿔 달라고 미리 부탁합니다.
    //   이 줄이 없으면 조각이 Buffer(숫자 덩어리)로 오고,
    //   한글이 조각 경계에서 잘려 깨질 수 있습니다.
    req.setEncoding("utf-8");

    req.on("data", (조각) => {
      쌓은글자 += 조각;
    });

    req.on("end", () => {
      resolve(쌓은글자); // 다 모았으니 내놓습니다
    });

    req.on("error", (에러) => {
      reject(에러); // 중간에 연결이 끊긴 경우
    });
  });
}

// 왜 Promise 로 감쌌나
//   본문은 '기다려야' 얻을 수 있습니다. return 으로는 못 돌려줍니다.
//   end 가 언제 올지 모르니까요. (02단원 개념03의 그 이야기입니다)
//
//   Promise 로 감싸 두면 쓰는 쪽에서 이렇게 한 줄이 됩니다.
//
//     const 글자 = await 본문읽기(req);
//
//   콜백 안의 콜백을 안 봐도 되니 훨씬 읽기 편합니다.
//
// resolve 와 reject 는 무엇인가
//   resolve(값)  → await 가 그 값을 받습니다. 성공입니다.
//   reject(에러) → await 자리에서 에러가 납니다. try/catch 로 잡힙니다.
//   하나만 부르면 됩니다. 부르는 순간 그 Promise 는 끝납니다.


const server = http.createServer(async (req, res) => {
  // ★ 콜백 앞에 async 가 붙었습니다.
  //   안에서 await 를 쓰려면 반드시 있어야 합니다.

  console.log(`${req.method} ${req.url}`);

  const 주소 = new URL(req.url, `http://${req.headers.host}`);
  const 경로 = 주소.pathname;


  // ── 섹션 3: 메서드와 쿼리 꺼내 보기 ──

  if (경로 === "/echo") {
    // searchParams 를 그대로 객체로 바꿔 봅니다.
    // Object.fromEntries 는 [키,값] 짝들을 객체로 만들어 줍니다.
    const 쿼리 = Object.fromEntries(주소.searchParams);

    JSON응답(res, 200, {
      method: req.method,
      경로: 경로,
      쿼리: 쿼리,
    });
    return;
  }

  // 확인: GET /echo?이름=김민준&나이=20
  // 응답: 200 {"method":"GET","경로":"/echo","쿼리":{"이름":"김민준","나이":"20"}}

  // 나이가 문자열 "20" 인 것을 보세요. 쿼리는 무엇을 넣든 항상 글자입니다.
  // 숫자로 쓰려면 Number() 로 바꿔야 합니다. (개념01 실수 3)


  // ── 섹션 4: 헤더 읽기 ──

  if (경로 === "/headers") {
    // ★ Node 에서 헤더 이름은 전부 소문자입니다.
    //   브라우저가 User-Agent 라고 보내도 Node 는 user-agent 로 바꿔 담습니다.
    JSON응답(res, 200, {
      "소문자로 찾으면": req.headers["user-agent"] !== undefined,
      "대문자로 찾으면": req.headers["User-Agent"] !== undefined,
    });
    return;
  }

  // 확인: GET /headers
  // 응답: 200 {"소문자로 찾으면":true,"대문자로 찾으면":false}

  // 대문자로 찾으면 false 입니다. 없는 게 아니라 이름이 다른 것입니다.
  // 헤더가 undefined 로 나오면 십중팔구 대소문자 문제입니다.
  //
  // 헤더에는 이런 것들이 들어 있습니다.
  //   host            어느 주소로 들어왔나 (localhost:3000)
  //   user-agent      어떤 프로그램이 보냈나 (크롬인지 Postman 인지)
  //   content-type    본문이 무슨 형식인가 (application/json)
  //   authorization   로그인 증표 — PART 4 에서 씁니다


  // ── 섹션 5: 본문 읽기 ──

  if (경로 === "/memos" && req.method === "POST") {
    const 글자 = await 본문읽기(req); // ← 여기서 기다립니다

    // 본문이 아예 안 왔을 수 있습니다. 빈 글자입니다.
    if (!글자) {
      JSON응답(res, 400, { error: "본문이 비어 있습니다" });
      return;
    }

    // 확인: POST /memos
    // 응답: 400 {"error":"본문이 비어 있습니다"}

    // ── 섹션 6: JSON.parse 는 실패할 수 있습니다 ──

    // 받은 글자가 진짜 JSON 이라는 보장이 없습니다.
    // 남이 보낸 것은 무엇이든 의심해야 합니다.
    let 데이터;
    try {
      데이터 = JSON.parse(글자);
    } catch (에러) {
      // ★ try/catch 를 안 하면 여기서 서버가 통째로 죽습니다.
      JSON응답(res, 400, { error: "JSON 형식이 아닙니다" });
      return;
    }

    // 확인: POST /memos {제목:"따옴표없음"}
    // 응답: 400 {"error":"JSON 형식이 아닙니다"}

    // 형식은 맞는데 필요한 값이 없을 수도 있습니다. 이것도 확인합니다.
    if (!데이터.title) {
      JSON응답(res, 400, { error: "title 을 넣어 주세요" });
      return;
    }

    // 확인: POST /memos {"내용":"제목이없음"}
    // 응답: 400 {"error":"title 을 넣어 주세요"}

    // 여기까지 왔으면 쓸 수 있는 데이터입니다.
    JSON응답(res, 201, {
      받은제목: 데이터.title,
      글자수: 데이터.title.length,
    });
    return;
  }

  // 확인: POST /memos {"title":"작업표준서"}
  // 응답: 201 {"받은제목":"작업표준서","글자수":5}


  // ── 섹션 7: PUT 도 본문 읽는 법은 똑같습니다 ──

  if (경로 === "/memos" && req.method === "PUT") {
    const 글자 = await 본문읽기(req);
    const 데이터 = JSON.parse(글자 || "{}"); // 빈 본문이면 빈 객체로

    JSON응답(res, 200, {
      방법: req.method,
      받은제목: 데이터.title || "(없음)",
    });
    return;
  }

  // 확인: PUT /memos {"title":"수정본"}
  // 응답: 200 {"방법":"PUT","받은제목":"수정본"}

  // POST 든 PUT 이든 PATCH 든 본문 읽는 코드는 완전히 같습니다.
  // 메서드는 '의도' 를 나타낼 뿐, 데이터가 오는 방식은 하나입니다.


  // ── 섹션 8: GET 에는 본문이 없습니다 ──

  if (경로 === "/memos" && req.method === "GET") {
    const 글자 = await 본문읽기(req);

    JSON응답(res, 200, {
      본문길이: 글자.length,
      설명: "GET 에는 본문을 담지 않습니다",
    });
    return;
  }

  // 확인: GET /memos
  // 응답: 200 {"본문길이":0,"설명":"GET 에는 본문을 담지 않습니다"}

  // ★ 중요 — GET 에도 본문읽기 를 부를 수는 있습니다. 멈추지 않습니다.
  //   본문이 없으면 end 가 바로 오고, 빈 글자가 나옵니다.
  //   "await 를 걸면 GET 이 멈추는 것 아닌가?" 하는 걱정은 안 해도 됩니다.


  JSON응답(res, 404, { error: "그런 주소가 없습니다" });

  // 확인: GET /없는주소
  // 응답: 404 {"error":"그런 주소가 없습니다"}
});


server.listen(PORT, () => {
  console.log(`서버가 켜졌습니다.  http://localhost:${PORT}`);
});



// ── 자주 하는 실수 ──

// [실수 1] await 를 쓰면서 async 를 안 붙임
//   http.createServer((req, res) => { await 본문읽기(req) ... })
//   → SyntaxError. 파일이 통째로 안 돌아갑니다.

// ── 섹션 4: v1 과 v2 를 함께 돌리기 ──

const v1 = express.Router();
const v2 = express.Router();

// v1 — 옛날 형식. 배열을 그대로 줍니다.
v1.get("/equipments", (req, res) => {
  // 이 주소는 곧 없앨 예정이라고 알려 줍니다.
  res.set("Deprecation", "true");
  res.set("Sunset", "Wed, 31 Dec 2026 00:00:00 GMT");
  res.set("Link", '</api/v2/equipments>; rel="successor-version"');

  const 목록 = 설비목록()
    .slice(0, 2)
    .map((설비) => ({ id: 설비.id, name: 설비.name }));

  res.json(목록);
});

// v2 — 새 형식. { data, meta } 로 감쌉니다.
v2.get("/equipments", (req, res) => {
  const 전부 = 설비목록();
  const data = 전부.slice(0, 2).map((설비) => ({ id: 설비.id, name: 설비.name }));

  res.json({ data, meta: { page: 1, limit: 2, total: 전부.length, totalPages: 6 } });
});

app.use("/api/v1", v1);
app.use("/api/v2", v2);


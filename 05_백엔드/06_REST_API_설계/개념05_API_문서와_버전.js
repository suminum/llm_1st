// ── 정리 ──

// 1. 문서에는 주소·메서드·받는 값·돌려주는 모양·날 수 있는 에러를 적는다.
// 2. "코드 보면 안다" 는 안 된다. 부르는 쪽이 코드를 못 볼 수도 있다.
// 3. 문서는 코드 옆에 둔다. 멀리 두면 고치는 것을 잊는다.
// 4. 버전은 처음부터 붙이고 시작한다. 나중에 붙이려면 쓰던 곳을 전부 고쳐야 한다.
// 5. 버전을 올리는 때는 '이미 쓰던 것이 깨질 때' 다.
//    필드를 더하는 것은 안 깨지므로 버전을 올리지 않는다.

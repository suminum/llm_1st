// ── 섹션 1: 쪽 번호 정하기 ──

// 쿼리로 받습니다. 없을 수도 있고, 이상한 값이 올 수도 있습니다.

const 기본쪽크기 = 10;
const 최대쪽크기 = 100;

function 쪽정보(query) {
  // Number(undefined) 는 NaN, Number(null) 은 0 입니다. 둘 다 막아야 합니다.
  let page = Number(query.page);
  let limit = Number(query.limit);

  if (!Number.isInteger(page) || page < 1) page = 1;
  if (!Number.isInteger(limit) || limit < 1) limit = 기본쪽크기;

  // ★ 상한을 반드시 두세요
  //   ?limit=999999 로 보내면 결국 전부 주게 됩니다. 페이징한 의미가 없어집니다.
  if (limit > 최대쪽크기) limit = 최대쪽크기;

  return { page, limit };
}

// ★ 왜 잘못된 값을 에러로 안 만들고 기본값으로 바꾸나
//   ?page=abc 는 보통 오타입니다. 400 을 내는 것도 맞지만,
//   목록 조회는 "일단 뭐라도 보여 주는" 편이 쓰기 좋습니다.
//   POST 로 데이터를 만들 때와는 판단이 다릅니다.
//   틀린 값으로 뭔가를 '만드는' 것은 400 이어야 합니다.


// ── 섹션 2: 정렬 조건 읽기 ──

// ?sort=name       이름 오름차순
// ?sort=-id        번호 내림차순 (앞에 - 를 붙이면 반대)
// ?sort=line,-id   라인 오름차순, 같으면 번호 내림차순

function 정렬조건(sort) {
  if (!sort) return [];

  return sort
    .split(",")
    .map((조각) => 조각.trim())
    .filter(Boolean)
    .map((조각) =>
      조각.startsWith("-")
        ? { 키: 조각.slice(1), 방향: -1 }
        : { 키: 조각, 방향: 1 }
    );
}

function 비교하기(a, b, 조건들) {
  for (const { 키, 방향 } of 조건들) {
    const 왼쪽 = a[키];
    const 오른쪽 = b[키];

    // 글자끼리는 localeCompare 로 비교합니다. 이유는 섹션 6-2 에 있습니다.
    // numeric: true 는 "설비2호" 와 "설비10호" 를 숫자로 보게 합니다.
    if (typeof 왼쪽 === "string" && typeof 오른쪽 === "string") {
      const 결과 = 왼쪽.localeCompare(오른쪽, "ko", { numeric: true });
      if (결과 !== 0) return 결과 * 방향;
      continue;
    }

    if (왼쪽 < 오른쪽) return -1 * 방향;
    if (왼쪽 > 오른쪽) return 1 * 방향;
  }

  return 0; // 전부 같으면 순서를 안 바꿉니다
}


// ── 섹션 3: 원하는 속성만 골라 주기 ──

// 목록에서 이름만 필요한 화면도 있습니다.
// 그런데 설비 하나에 속성이 스무 개라면, 열아홉 개를 헛되이 보내는 셈입니다.
//
//   ?fields=id,name   →  { id, name } 만

function 필드고르기(항목, fields) {
  if (!fields) return 항목;

  const 결과 = {};

  for (const 키 of fields.split(",").map((조각) => 조각.trim())) {
    if (키 in 항목) {
      결과[키] = 항목[키];
    }
  }

  return 결과;
}

// ★ 없는 이름을 달라고 하면?
//   그냥 무시합니다. 에러를 낼 수도 있지만,
//   "달라고 한 것 중 있는 것만 준다" 가 다루기 쉽습니다.


// ── 섹션 4: 다 합치기 ──

app.get("/api/v1/equipments", (req, res) => {
  const { page, limit } = 쪽정보(req.query);
  const 조건들 = 정렬조건(req.query.sort);

  let 결과 = 설비목록();

  // ① 정렬을 먼저 합니다
  if (조건들.length > 0) {
    결과 = [...결과].sort((a, b) => 비교하기(a, b, 조건들));
  }

  const total = 결과.length;

  // ② 그다음 자릅니다
  const 시작 = (page - 1) * limit;
  결과 = 결과.slice(시작, 시작 + limit);

  // ③ 마지막에 속성을 고릅니다
  const data = 결과.map((설비) => 필드고르기(설비, req.query.fields));

  res.json({
    data,
    meta: {
      page,
      limit,
      total,
      totalPages: Math.ceil(total / limit),
    },
  });
});


// ── 섹션 6: 정렬 확인 ──

// 확인: GET /api/v1/equipments?sort=-id&limit=3&fields=id
// 응답: 200 {"data":[{"id":12},{"id":11},{"id":10}],"meta":{"page":1,"limit":3,"total":12,"totalPages":4}}

// 확인: GET /api/v1/equipments?sort=line,-id&limit=4&fields=id,line
// 응답: 200 {"data":[{"id":11,"line":"A"},{"id":7,"line":"A"},{"id":2,"line":"A"},{"id":1,"line":"A"}],"meta":{"page":1,"limit":4,"total":12,"totalPages":3}}

// A라인끼리 모이고, 그 안에서 번호가 큰 것부터입니다.
// 조건을 쉼표로 이어 쓰면 "앞엣것이 같을 때 뒤엣것으로" 가 됩니다.

// 확인: GET /api/v1/equipments?sort=name&limit=3&fields=id,name
// 응답: 200 {"data":[{"id":7,"name":"검사기 1호"},{"id":8,"name":"검사기 2호"},{"id":5,"name":"용접로봇 1호"}],"meta":{"page":1,"limit":3,"total":12,"totalPages":4}}

// 검사기 → 용접로봇 → 적재로봇 → 컨베이어 → 포장기 → 프레스 순입니다.
// ㄱ,ㅇ,ㅈ,ㅋ,ㅍ 순서니까 우리가 아는 사전 순서가 맞습니다.

// ★ 정렬을 자르기 '전' 에 하는 이유
//   자르고 정렬하면 그 쪽 안에서만 정렬됩니다.
//   1쪽이 3,1,2 / 2쪽이 6,4,5 처럼 되어 전혀 정렬이 안 된 결과가 나옵니다.
//   순서는 언제나 전체를 기준으로 정하고, 그다음에 자릅니다.


// ── 섹션 6-2: ★ localeCompare 를 꼭 써야 하나 (실제로 재 봤습니다) ──

// 흔히 "한글은 localeCompare 로 정렬해야 한다" 고 합니다. 정말 그럴까요?
// 네 가지 경우를 실제로 정렬해 봤습니다.

app.get("/api/v1/sort-compare", (req, res) => {
  const 묶음 = {
    한글만: ["프레스", "검사기", "용접로봇", "컨베이어"],
    영어대소문자: ["banana", "Apple", "cherry", "Date"],
    한글영어섞임: ["프레스", "Press", "검사기", "ABC"],
    숫자가든이름: ["설비2호", "설비10호", "설비1호"],
  };

  const 결과 = {};

  for (const [제목, 값들] of Object.entries(묶음)) {
    결과[제목] = {
      localeCompare: [...값들].sort((a, b) => a.localeCompare(b, "ko")),
      그냥비교: [...값들].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)),
      numeric켬: [...값들].sort((a, b) => a.localeCompare(b, "ko", { numeric: true })),
    };
  }

  res.json(결과);
});

// 확인: GET /api/v1/sort-compare
// 응답: 200 {"한글만":{"localeCompare":["검사기","용접로봇","컨베이어","프레스"],"그냥비교":["검사기","용접로봇","컨베이어","프레스"],"numeric켬":["검사기","용접로봇","컨베이어","프레스"]},"영어대소문자":{"localeCompare":["Apple","banana","cherry","Date"],"그냥비교":["Apple","Date","banana","cherry"],"numeric켬":["Apple","banana","cherry","Date"]},"한글영어섞임":{"localeCompare":["검사기","프레스","ABC","Press"],"그냥비교":["ABC","Press","검사기","프레스"],"numeric켬":["검사기","프레스","ABC","Press"]},"숫자가든이름":{"localeCompare":["설비10호","설비1호","설비2호"],"그냥비교":["설비10호","설비1호","설비2호"],"numeric켬":["설비1호","설비2호","설비10호"]}}

// 재 본 결과를 정리하면 이렇습니다.
//
//   ① 한글만 있으면 — 두 방법이 완전히 같습니다
//      검사기 / 용접로봇 / 컨베이어 / 프레스
//
//      유니코드에서 완성형 한글(가~힣)이 이미 ㄱㄴㄷ 순서로 배치돼 있기 때문입니다.
//      그래서 그냥 < 로 비교해도 사전 순서가 나옵니다.
//      "한글은 localeCompare 를 꼭 써야 한다" 는 말은 이 경우엔 사실이 아닙니다.
//
//   ② 영어 대소문자가 섞이면 — 달라집니다
//      localeCompare : Apple / banana / cherry / Date   ← 사전 순서
//      그냥 비교      : Apple / Date / banana / cherry   ← 대문자가 전부 먼저
//
//      대문자 A~Z 의 번호가 소문자 a~z 보다 앞이라 이렇게 됩니다.
//      영어가 들어오면 localeCompare 가 필요합니다.
//
//   ③ 한글과 영어가 섞이면 — 어느 쪽이 먼저인지가 달라집니다
//      localeCompare : 한글 먼저
//      그냥 비교      : 영어 먼저
//
//      둘 다 틀린 건 아닙니다. "우리 화면에서 무엇이 먼저여야 하나" 를 정하는 문제입니다.
//
//   ④ 이름에 숫자가 들어가면 — 둘 다 틀립니다 ★
//      설비10호 / 설비1호 / 설비2호
//
//      "1" 다음에 "0" 이 오는지 "호" 가 오는지로 비교하기 때문입니다.
//      글자로만 보면 "10" 이 "2" 보다 앞입니다.
//
//      { numeric: true } 를 주면 숫자 부분을 숫자로 봅니다.
//      설비1호 / 설비2호 / 설비10호  ← 이게 사람이 기대하는 순서입니다
//
// ★ 결론
//   그냥 localeCompare(다른값, "ko", { numeric: true }) 를 쓰세요.
//   한글만 있으면 어차피 결과가 같고, 나머지 경우는 이쪽이 맞습니다.
//   이 파일의 비교하기 함수가 그렇게 되어 있습니다.
//
// ★ 하나 더 — 눈에 안 보이는 함정
//   같은 '가' 인데 컴퓨터가 다르게 보는 경우가 있습니다.
//
//     '가'.normalize("NFD")   →  글자 수가 2 입니다 (ㄱ + ㅏ 로 쪼개짐)
//     쪼갠 것 === '가'         →  false
//     쪼갠 것.localeCompare('가', 'ko')  →  0  (같다고 봅니다)
//
//   맥에서 만든 파일 이름이 이렇게 쪼개진 형태로 옵니다.
//   윈도우에서 만든 것과 === 로 비교하면 다르다고 나옵니다.
//   파일 업로드를 다룰 때 실제로 만나게 됩니다. (09단원)
//   그때는 normalize("NFC") 로 맞춰 놓고 비교합니다.



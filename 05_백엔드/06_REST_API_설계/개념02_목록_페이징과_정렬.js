// [실수 1] limit 에 상한을 안 둠
//   ?limit=999999 하나로 서버가 멈출 수 있습니다. 반드시 상한을 두세요.

// [실수 2] page 를 그대로 믿음
//   ?page=0 이나 ?page=-1 이 오면 slice 가 이상하게 동작합니다.
//   Number 로 바꾸고 범위까지 확인하세요.

// [실수 3] 자르고 나서 정렬
//   그 쪽 안에서만 정렬됩니다. 전체가 뒤죽박죽이 됩니다.

// [실수 4] 정렬 없이 페이징
//   지금은 잘 돌아갑니다. 데이터베이스로 바꾸면 항목이 겹치거나 사라집니다.

// [실수 5] total 을 자른 뒤에 셈
//   결과.slice(...) 뒤에 length 를 세면 항상 limit 이 나옵니다.
//   total 은 반드시 자르기 전에 세세요.

// [실수 6] sort 를 원본 배열에 그대로 씀
//   설비목록().sort(...) 는 원본을 바꿉니다.
//   [...결과].sort(...) 로 복사본을 정렬하세요.


// ── 정리 ──

// 1. 목록은 통째로 주지 않는다. page 와 limit 으로 잘라서 준다.
// 2. limit 에는 반드시 상한을 둔다. 안 두면 limit=999999 한 번에 서버가 넘어간다.
// 3. page 를 그대로 믿지 않는다. 0 도 음수도 글자도 올 수 있다.
// 4. 순서는 정렬 다음 자르기다. 자르고 나서 정렬하면 그 쪽 안에서만 정렬된다.
// 5. total 은 자르기 전에 센다. 자른 뒤에 세면 언제나 limit 이 나온다.
// 6. sort 는 원본 배열을 바꾼다. slice() 로 복사한 뒤 정렬한다.
// 7. 정렬 없는 페이징은 위험하다. 순서가 보장되지 않아
//    같은 항목이 두 쪽에 나오거나 아예 빠질 수 있다.

export const 서버주소 = "http://localhost:4000/api/v1";

// 서버가 켜져 있는지 미리 물어봅니다.
// 안 켜져 있으면 예제마다 빨간 오류 대신 안내를 보여 주려고요.
export async function 서버켜져있나() {
  try {
    const 응답 = await fetch(`${서버주소}/equipments`, {
      signal: AbortSignal.timeout(2000),
    });
    return 응답.ok;
  } catch {
    return false;
  }
}


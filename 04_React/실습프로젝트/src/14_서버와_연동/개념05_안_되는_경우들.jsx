// ── 섹션 4: 답이 뒤바뀝니다 ──

// 검색창처럼 **입력할 때마다 요청**하는 화면에서 생깁니다.
// 먼저 보낸 요청이 나중에 도착할 수 있습니다.

function Section4Demo() {
  const [막을까, set막을까] = useState(false);
  const [보인값, set보인값] = useState("(아직)");
  const [기록, set기록] = useState([]);
  const 최신번호 = useRef(0);

  async function 요청(이름, 늦기) {
    const 내번호 = ++최신번호.current;
    set기록((전) => [...전, `${이름} 보냄 (${늦기}ms)`]);

    try {
      await fetch(`${서버주소}/equipments?slow=${늦기}`);
    } catch {
      return;
    }

    // ★ 내가 마지막 요청이 아니면 결과를 버립니다
    if (막을까 && 내번호 !== 최신번호.current) {
      set기록((전) => [...전, `${이름} 도착 — 낡아서 버림`]);
      return;
    }

    set보인값(이름);
    set기록((전) => [...전, `${이름} 도착 → 화면에 씀`]);
  }

  function 해보기() {
    set기록([]);
    set보인값("(받는 중)");
    최신번호.current = 0;
    요청("느린 것", 1500);
    setTimeout(() => 요청("빠른 것", 200), 100);
  }

  return (
    <div className="demo">
      <h3>④ 먼저 보낸 게 나중에 옵니다</h3>

      <label>
        <input type="checkbox" checked={막을까} onChange={(e) => set막을까(e.target.checked)} />{" "}
        낡은 답 버리기
      </label>

      <div style={{ marginTop: 6 }}>
        <button onClick={해보기}>두 개를 겹쳐 보내기</button>
      </div>

      <div className="output">
        <div>
          <strong>화면에 남은 값: {보인값}</strong>
        </div>
        <pre style={{ margin: "6px 0 0", fontSize: 13 }}>{기록.join("\n")}</pre>
      </div>
    </div>
  );
}


function Section1Demo() {
  const [줄들, set줄들] = useState([]);

  async function 해보기(이름, 주소) {
    let 결과;
    try {
      const 응답 = await fetch(주소);
      const 몸 = await 응답.json().catch(() => ({}));
      결과 = `${이름} → 닿았습니다. 상태 ${응답.status} ${JSON.stringify(몸).slice(0, 40)}`;
    } catch (오류) {
      결과 = `${이름} → 못 닿았습니다. ${오류.name}: ${오류.message}`;
    }
    set줄들((전) => [...전, 결과]);
    console.log(결과);
  }

  return (
    <div className="demo">
      <h3>① 두 갈래로 갈립니다</h3>

      <button onClick={() => 해보기("정상", `${서버주소}/equipments`)}>정상</button>{" "}
      <button onClick={() => 해보기("500", `${서버주소}/equipments?fail=yes`)}>
        서버가 500
      </button>{" "}
      <button onClick={() => 해보기("없는 주소", `${서버주소}/없는곳`)}>없는 주소</button>{" "}
      <button onClick={() => 해보기("안 켜진 포트", "http://localhost:4999/api/v1/equipments")}>
        안 켜진 포트
      </button>{" "}
      <button onClick={() => set줄들([])}>지우기</button>

      <pre className="output">{줄들.join("\n") || "버튼을 눌러 보세요"}</pre>
    </div>
  );
}


function CoffeeCounter() {
  // items 는 '지금 담긴 목록' 이라는 데이터입니다.
  // useState 는 04단원에서 배웁니다. 지금은 '데이터를 담아 두는 것' 정도로 보세요.
  const [items, setItems] = useState([]);

  function handleClick() {
    setItems([...items, "아메리카노"]); // 데이터만 바꿉니다
    console.log("[React 방식] 내가 직접 고친 곳: 0군데 (데이터만 바꿈)");
  }

  // 아래는 "데이터가 이러면 화면은 이렇게 생겼다" 를 적은 것입니다.
  // 화면을 '고치는' 코드가 아니라, 화면을 '그리는' 코드입니다.
  return (
    <div>
      {/* onClick 은 04단원에서 배웁니다. "누르면 이 함수" 라는 뜻입니다. */}
      <button onClick={handleClick}>담기</button>{" "}
      {/* ↑ {" "} 는 '여기 띄어쓰기 한 칸' 이라는 뜻입니다. 02단원에서 배웁니다.
          JSX 는 태그 옆의 줄바꿈을 지워 버려서, 이게 없으면 "담기0개" 로 붙습니다.
          데모 ① 은 HTML 이라 줄바꿈이 그대로 한 칸이 됩니다. 그 차이를 맞춘 것입니다. */}
      <span>{items.length}</span>개
      <ul>
        {items.map((item, index) => (
          <li key={index}>
            {index + 1}번째 {item}
          </li>
        ))}
      </ul>
    </div>
  );
}


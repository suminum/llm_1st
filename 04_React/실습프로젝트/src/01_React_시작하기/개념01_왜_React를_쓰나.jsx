  js자리.innerHTML =
    '<button id="jsBtn">담기</button> ' +
    '<span id="jsCount">0</span>개' +
    '<ul id="jsList"></ul>';

  // ★ 이 파일에서 React 없이 만든 화면은 위 네 줄이 전부입니다.
  //   "이 자리에 이런 태그를 넣어라" 를 내가 직접 적었습니다.

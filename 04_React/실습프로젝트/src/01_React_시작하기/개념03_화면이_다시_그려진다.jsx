그려진뒤("#React초시계", (상자) => {
  const 처음것 = 상자.querySelector("input");

  setTimeout(() => {
    const 지금것 = 상자.querySelector("input");
    console.log("[React] 2초 뒤에도 같은 입력칸인가?", 지금것 === 처음것);
    // 콘솔: [React] 2초 뒤에도 같은 입력칸인가? true
  }, 2000);
});

그려진뒤("#손초시계", (상자) => {
  const 처음것 = 상자.querySelector("input");

  setTimeout(() => {
    const 지금것 = 상자.querySelector("input");
    console.log("[직접] 2초 뒤에도 같은 입력칸인가?", 지금것 === 처음것);
    // 콘솔: [직접] 2초 뒤에도 같은 입력칸인가? false
  }, 2000);
});


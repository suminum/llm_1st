import { useEffect, useState } from "react";
import Summary from "../_ui/Summary.jsx";
import 그려진뒤 from "../_ui/그려진뒤.js";

// ── 섹션 1: React 가 1초마다 다시 그리는 초시계 ──

// 아래가 ① 상자를 만드는 컴포넌트입니다.
// 1초마다 숫자를 하나 올리고, 올린 값으로 화면을 다시 그립니다.

function React초시계() {
  const [초, 초설정] = useState(0); // ← 04단원

  // 1초마다 초설정 을 부릅니다. useEffect 는 09단원에서 배웁니다.
  useEffect(() => {
    const 타이머 = setInterval(() => {
      초설정((지금) => 지금 + 1);
    }, 1000);
    return () => clearInterval(타이머); // 떠날 때 타이머를 끕니다
  }, []);

  // className 은 02단원에서 배웁니다. 화면 모양을 정하는 이름입니다.
  return (
    <div className="output">
      <p>초시계: {초}초</p>
      <p>
        입력칸: <input />
      </p>
    </div>
  );
}

// 1초에 한 번, 화면 설명을 통째로 다시 만들어 넘겼습니다.
// 그러면 화면도 통째로 새로 만들어질까요? 아닙니다.
//
// React 는 새 설명과 직전 설명을 비교합니다.

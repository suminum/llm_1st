// ── 섹션 2: 같은 초시계를 React 없이 직접 그린 것 ──

// 비교 대상을 만듭니다.
// ② 는 React 를 한 줄도 안 씁니다. JS자료 10단원 방식으로 1초마다 다시 그립니다.

let 손초 = 0;

function 손으로그리기() {
  const 상자 = document.querySelector("#손초시계");
  if (!상자) return; // 다른 예제로 옮겨 갔으면 그만둡니다

  // 안을 통째로 새 HTML 로 갈아 끼웁니다
  상자.innerHTML =
    '<div class="output"><p>초시계: ' +
    손초 +
    "초</p><p>입력칸: <input /></p></div>";
}

그려진뒤("#손초시계", () => {
  손초 = 0;
  손으로그리기(); // 첫 화면

  const 타이머 = setInterval(() => {
    손초 = 손초 + 1;
    손으로그리기();

    // 그 자리가 사라졌으면(다른 예제로 옮겨 갔으면) 타이머를 끕니다
    if (!document.querySelector("#손초시계")) clearInterval(타이머);
  }, 1000);
});

// 화면만 보면 ① 과 ② 는 똑같습니다. 숫자가 1초마다 올라갑니다.
// 그런데 ② 의 입력칸에 글자를 쳐 놓고 1초만 기다려 보세요. 글자가 사라집니다.
//
// 이유는 innerHTML 에 있습니다.

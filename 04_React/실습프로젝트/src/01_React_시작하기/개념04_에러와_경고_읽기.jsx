// 에러도 경고도 없이 화면만 이상해지는 경우가 있습니다. 이게 제일 어렵습니다.
// 첫 번째가 이름 문제입니다.

function menu() {
  return <p>아메리카노 4000원</p>;
}

function Menu() {
  return <p>아메리카노 4000원</p>;
}

// 두 함수는 내용이 똑같습니다. 이름의 첫 글자만 다릅니다.
// 그런데 화면은 전혀 다릅니다. 아래 ① 과 ② 를 비교해 보세요.
//
// React 는 태그 이름의 첫 글자로 구별합니다.
//
//   <menu />  소문자로 시작 → "브라우저가 아는 HTML 태그" 로 봅니다
//   <Menu />  대문자로 시작 → "내가 만든 컴포넌트" 로 봅니다
//
// menu 는 실제로 존재하는 HTML 태그입니다. 그래서 에러도 안 납니다.
// 우리가 만든 함수는 아예 불려 보지도 못하고, 빈 <menu> 태그만 그려집니다.
//
// ★ 한글 이름은 대문자 취급을 받습니다.
//   function 메뉴() 로 만들고 <메뉴 /> 라고 쓰면 잘 동작합니다.
//   이 자료가 한글 컴포넌트 이름을 자주 쓰는 이유입니다.


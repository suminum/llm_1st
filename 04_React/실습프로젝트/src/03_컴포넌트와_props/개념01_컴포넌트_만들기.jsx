// ── 섹션 1: 컴포넌트는 화면을 돌려주는 함수입니다 ──

// JS자료 05단원 개념03 에서 함수는 값을 '돌려준다' 고 배웠습니다.

import Summary from "../_ui/Summary.jsx";

function double(n) {
  return n * 2;
}

console.log(double(4));
// 콘솔: 8

// 숫자를 돌려주는 함수를 만들 수 있으니, 문자열을 돌려주는 함수도 만들 수 있고,
// 배열이나 객체를 돌려주는 함수도 만들 수 있었습니다.
//
// 그렇다면 '화면' 을 돌려주는 함수도 만들 수 있습니다.
// 02단원에서 배운 JSX 를 return 하면 됩니다.

function Hello() {
  return <p>안녕하세요, 저는 컴포넌트입니다.</p>;
}

// 이것이 컴포넌트입니다. 새 문법은 한 글자도 없습니다.
// 그냥 함수이고, 돌려주는 값이 JSX 일 뿐입니다.

console.log(typeof Hello);
// 콘솔: function
// ← 컴포넌트라고 불러도 정체는 함수입니다.

// 화면에 그릴 때는 double(4) 처럼 괄호를 붙여 부르지 않습니다.
// 태그처럼 <Hello /> 라고 씁니다.
//
//     root.render(<Hello />);
//
// 이 파일은 맨 아래에서 한 번에 그립니다. 화면 ① 을 보세요.
// 왜 괄호로 부르지 않는지는 섹션 6 [실수 4] 에서 확인합니다.

// ✏️ 직접 해보기 1 — <p>또 만나요</p> 를 돌려주는 Bye 컴포넌트를 만드세요.
//                    (화면에 넣는 것은 직접 해보기 5에서 합니다)

// ── 섹션 2: 이름은 대문자로 시작합니다 ──

// 컴포넌트 이름은 반드시 대문자로 시작합니다.
// "규칙이니 외우세요" 가 아닙니다. React 가 그 글자로 구분하기 때문입니다.
//
// 02단원에서 JSX 가 React.createElement 로 바뀐다고 배웠습니다.
// 바뀐 결과 안을 들여다보면 이유가 바로 보입니다.

const divElement = <div />;

console.log(divElement.type);
// 콘솔: div
console.log(typeof divElement.type);
// 콘솔: string
// ← 'div' 라는 문자열이 들어 있습니다.
//   React 는 이 문자열을 보고 브라우저에게 <div> 태그를 만들라고 시킵니다.

const helloElement = <Hello />;

console.log(typeof helloElement.type);
// 콘솔: function
console.log(helloElement.type === Hello);
// 콘솔: true
// ← 문자열이 아니라 위에서 만든 Hello 함수 그 자체가 들어 있습니다.
//   React 는 이 함수를 대신 불러서, 돌려받은 JSX 를 그립니다.

// 그럼 React 는 둘을 어떻게 구분할까요? 태그 이름의 첫 글자만 봅니다.
//
//   소문자로 시작 → 'div' 처럼 문자열로 넣는다 → HTML 태그
//   대문자로 시작 → 함수 그 자체를 넣는다     → 내가 만든 컴포넌트
//
// HTML 태그 이름은 전부 소문자입니다(div, p, ul, h1 ...).
// 그래서 "대문자로 시작하면 내 것" 이라는 표시가 겹치지 않고 통합니다.

// ✏️ 직접 해보기 2 — const pElement = <p />; 를 만들고
//                    pElement.type 을 콘솔에 찍어 보세요. 무엇이 나올까요?

// ── 섹션 3: 소문자로 쓰면 조용히 이상해집니다 ──

// ★ 이 단원에서 가장 조심해야 할 부분입니다.
//
// 컴포넌트 이름을 소문자로 시작하게 만들면 어떻게 될까요?
// "에러가 나겠지" 싶지만, 에러가 나지 않습니다. 그래서 더 위험합니다.

function menu() {
  return <p>아메리카노 4000원</p>;
}

const menuElement = <menu />;

console.log(menuElement.type);
// 콘솔: menu
console.log(menuElement.type === menu);
// 콘솔: false
// ← 위에서 만든 menu 함수가 아니라 'menu' 라는 문자열이 들어갔습니다.
//   React 는 "menu 라는 HTML 태그를 만들어라" 로 읽었습니다.
//   그래서 menu 함수는 한 번도 불리지 않습니다.

// 화면 ③ 을 보세요. 아메리카노 4000원이 나와야 할 자리가 비어 있습니다.
// F12 → Elements 에서 그 자리를 보면 <menu></menu> 라는 빈 태그가 들어 있습니다.
//
// menu 는 실제로 존재하는 HTML 태그입니다(목록을 담는 태그).
// 그래서 브라우저는 아무 불평 없이 빈 태그를 하나 만들고 끝냅니다.
//
// 그럼 HTML 에 없는 이름이면 어떻게 될까요? 예를 들어 myBox 라면요.
// 그때는 React 가 콘솔에 빨간 경고를 두 줄 띄워 줍니다.
//
//   <myBox /> is using incorrect casing.
//            Use PascalCase for React components, or lowercase for HTML elements.
//   The tag <myBox> is unrecognized in this browser.
//            If you meant to render a React component, start its name with
//            an uppercase letter.
//
// 정리하면 이렇습니다.
//   이름이 HTML 에 없는 태그      → 빨간 경고가 뜬다 (그나마 다행)
//   이름이 HTML 에 있는 태그      → 경고도 없이 조용히 사라진다 (menu, header, section ...)
//
// 화면에서 무언가가 통째로 사라졌는데 에러가 없다면,
// 컴포넌트 이름의 첫 글자부터 확인하세요.

function myBox() {
  return <p>나는 myBox 입니다</p>;
}

// ✏️ 직접 해보기 3 — 아래 LowercaseDemo 안의 {/* <myBox /> */} 에서
//                    주석을 풀고 저장한 뒤 F12 → Console 을 보세요.
//                    위에 적힌 빨간 경고 두 줄이 실제로 나옵니다.
//                    확인했으면 다시 {/* */} 로 감싸 두세요.

function LowercaseDemo() {
  return (
    <div className="demo">
      <h3>③ 소문자로 만든 컴포넌트 — 아무것도 안 보입니다</h3>
      <div className="output">
        <menu />
      </div>
      {/* <myBox /> */}
      <p>위 흰 칸이 비어 있습니다. 에러는 한 줄도 나지 않았습니다.</p>
    </div>
  );
}

// 이름만 대문자로 고치면 바로 됩니다. 다른 곳은 손대지 않았습니다.


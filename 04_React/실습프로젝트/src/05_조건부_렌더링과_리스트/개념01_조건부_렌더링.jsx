function GradeBox() {
  const [point, setPoint] = useState(0);

  // 여기는 return 밖이라 if 를 써도 됩니다.
  let badge; // 아직 아무것도 안 담긴 변수입니다

  if (point >= 100) {
    badge = <p>VIP 회원입니다</p>;
  } else if (point >= 50) {
    badge = <p>일반 회원입니다</p>;
  } else {
    badge = <p>신규 회원입니다</p>;
  }

  // 화면 조각도 그냥 값입니다. 변수에 담아 뒀다가 나중에 꺼내 쓸 수 있습니다.
  return (
    <div className="demo">
      <h3>섹션 3 — 변수에 담아 두기: 갈래가 셋 이상일 때</h3>

      <button onClick={() => setPoint(point + 30)}>30점 적립</button>
      <button onClick={() => setPoint(0)}>점수 초기화</button>

      <div className="output">
        <p>이서연님 · {point}점</p>
        {badge}
      </div>
    </div>
  );
}

function ProfileCard({ user }) {
  // 여기서 걸리면 아래는 실행되지 않습니다.
  if (!user) {
    return <p>불러온 회원이 없습니다</p>;
  }

  // 여기까지 왔다는 것은 user 가 있다는 뜻입니다.
  // 그래서 아래에서는 user 가 있는지 다시 확인할 필요가 없습니다.
  return (
    <div>
      <p>
        {user.name} ({user.age}세)
      </p>
      <p>{user.age >= 19 ? "성인 회원" : "청소년 회원"}</p>
    </div>
  );
}


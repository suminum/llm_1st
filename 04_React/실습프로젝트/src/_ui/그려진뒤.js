// 그려진 뒤에 한 번 — 자료가 미리 만들어 둔 '틀'입니다. 읽지 않아도 됩니다.
// ------------------------------------------------------------
// 왜 필요한가:
//   render 는 "이렇게 그려 주세요" 라는 부탁일 뿐이고, 화면은 아주 잠깐 뒤에
//   만들어집니다. 그래서 코드 바로 다음 줄에서 그 자리를 찾으면 아직 없습니다.
//   (01단원 개념02 섹션 3에서 다루는 그 이야기입니다)
//
//   더블클릭으로 열던 시절에는 setTimeout 100ms 면 충분했습니다. 하지만
//   이 프로젝트는 왼쪽 목록에서 예제를 고를 때 파일을 불러오고 '그 다음에'
//   그리기 때문에, 얼마를 기다리면 되는지 정해 둘 수가 없습니다.
//   그래서 생길 때까지 잠깐씩 확인합니다.
//
// 쓰는 법:
//   import 그려진뒤 from "../_ui/그려진뒤.js";
//   그려진뒤("#root", (자리) => {
//     console.log(자리.innerHTML);
//   });
// ============================================================

export default function 그려진뒤(선택자, 할일, 최대기다림 = 3000) {
  const 간격 = 50;
  let 남은 = Math.ceil(최대기다림 / 간격);

  const 타이머 = setInterval(() => {
    const 자리 = document.querySelector(선택자);
    if (자리) {
      clearInterval(타이머);
      할일(자리);
      return;
    }
    if (--남은 <= 0) {
      clearInterval(타이머);
      // 예제를 고르지 않은 채로 시간이 지난 경우입니다. 조용히 넘어갑니다.
    }
  }, 간격);
}

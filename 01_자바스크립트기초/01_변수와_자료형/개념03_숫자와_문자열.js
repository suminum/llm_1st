// ── 섹션 4: 문자열 이어붙이기 ──

// + 기호로 문자열을 이어 붙일 수 있습니다.
const userName = "김민준";
console.log("안녕하세요, " + userName + "님");
// 출력: 안녕하세요, 김민준님

// 띄어쓰기는 자동으로 안 들어갑니다. 따옴표 안에 직접 넣어야 합니다.
console.log("안녕하세요," + userName);
// 출력: 안녕하세요,김민준

// console.log 의 쉼표( , )와는 다릅니다.
//   쉼표  → 각각을 띄어쓰기로 구분해서 출력 (출력할 때만 쓸 수 있음)
//   더하기 → 하나의 문자열로 합침 (변수에 담을 수 있음)
const greeting = "안녕하세요, " + userName + "님";
console.log(greeting);
// 출력: 안녕하세요, 김민준님

// + 가 길어지면 읽기 어렵습니다. 더 편한 방법(백틱)은 02단원에서 배웁니다.


//                    한 문장으로 출력해 보세요.


// ── 섹션 5: 문자열의 길이 ──

// 여기서 '점( . )' 이 처음 나옵니다. 앞으로 계속 쓰니 지금 한 번 짚고 갑시다.
//
//   값 . 이름
//
// 점은 "이 값이 가지고 있는 것을 꺼내 쓴다" 는 뜻입니다.
// 왼쪽에 있는 값에게 물어보는 것이라고 생각하면 쉽습니다.
//   "안녕하세요".length  →  "너 길이가 몇이야?" 라고 문자열에게 묻는 것
//
// 사실 첫 파일부터 쓰고 있었습니다. console.log 의 점도 같은 것입니다.
//   console 이라는 값에게서 log 를 꺼내 쓴 것이었습니다.

// .length 를 붙이면 글자 수를 알려 줍니다.
const message = "안녕하세요";
console.log(message.length);
// 출력: 5

// 띄어쓰기도 한 글자로 셉니다.
console.log("안녕 하세요".length);
// 출력: 6

// 숫자에는 .length 가 없습니다.
console.log((12345).length);
// 출력: undefined
// (undefined 가 무엇인지는 다음 파일 개념04에서 배웁니다)

// 12345 를 괄호로 감싼 이유가 궁금하셨을 겁니다.
// 숫자에 점을 바로 찍으면( 12345.length ) 자바스크립트가 그 점을
// 소수점으로 착각해서 에러가 납니다. 그래서 괄호로 한 번 묶어 준 것입니다.
// 변수에 담아서 쓰면 괄호가 필요 없습니다.  const n = 12345;  n.length


// ── 섹션 1: typeof — 자료형을 확인하는 법 ──

// typeof 를 앞에 붙이면 그 값의 종류를 글자로 알려 줍니다.
console.log(typeof 1200);
// 출력: number

console.log(typeof "1200");
// 출력: string

// 화면에 보이는 모습은 비슷해도 종류가 다릅니다.
console.log(1200, "1200");
// 출력: 1200 1200

// 그래서 앞으로 "이게 숫자야 글자야?" 헷갈리면 typeof 로 확인하면 됩니다.
// 값과 종류를 같이 찍는 습관을 들이세요.
console.log(1200, typeof 1200);
// 출력: 1200 number

// ✏️ 직접 해보기 1 — "안녕" 의 자료형을 확인해 출력해 보세요.


// ── 섹션 2: number — 숫자 ──

// 정수도, 소수도, 음수도 전부 number 하나입니다.
const count = 3;
const price = 1250.5;
const temperature = -7;

console.log(count, typeof count);
// 출력: 3 number
console.log(price, typeof price);
// 출력: 1250.5 number
console.log(temperature, typeof temperature);
// 출력: -7 number

// 숫자에는 따옴표를 씌우지 않습니다. 쉼표도 넣지 않습니다.
// const wrong = 1,250;   ← 이렇게 쓰면 안 됩니다
const bigNumber = 1250000;
console.log(bigNumber);
// 출력: 1250000

// [알아두기] 소수 계산은 아주 작은 오차가 생깁니다.
console.log(0.1 + 0.2);
// 출력: 0.30000000000000004
// 컴퓨터가 소수를 2진법으로 저장하기 때문입니다. 버그가 아닙니다.
// 돈 계산을 할 때 소수점을 피하고 '원' 단위 정수로 다루는 이유가 이것입니다.


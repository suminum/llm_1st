// ── 섹션 3: string — 문자열 ──

// 따옴표로 감싼 글자를 문자열이라고 합니다. 감싸는 방법은 세 가지입니다.
const a1 = "큰따옴표";
const a2 = '작은따옴표';
const a3 = `백틱`; // 키보드에서 숫자 1 왼쪽, ~ 와 같은 키

console.log(a1, a2, a3);
// 출력: 큰따옴표 작은따옴표 백틱

// 셋 다 자료형은 똑같이 string 입니다.
console.log(typeof a1, typeof a2, typeof a3);
// 출력: string string string

// 따옴표 안에 따옴표를 넣고 싶으면 다른 종류로 감싸면 됩니다.

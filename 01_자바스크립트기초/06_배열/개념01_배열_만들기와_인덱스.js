// ── 섹션 1: 배열 만들기 ──

const students = ["김민준", "이서연", "박지훈"];
console.log(students);
// 출력: [ '김민준', '이서연', '박지훈' ]

// 숫자 배열도 됩니다.
const scores = [90, 85, 70];
console.log(scores);
// 출력: [ 90, 85, 70 ]

// 빈 배열로 시작할 수도 있습니다. 나중에 채워 넣을 때 씁니다.
const emptyList = [];
console.log(emptyList);
// 출력: []

// 자료형을 섞어도 됩니다. (다만 실무에서는 같은 종류만 넣는 게 좋습니다)
const mixed = ["김민준", 20, true];
console.log(mixed);
// 출력: [ '김민준', 20, true ]

// 배열의 자료형은 object 입니다. 값 하나가 아니라 값들의 묶음이니까요.
console.log(typeof students);
// 출력: object

// 배열인지 확인하려면 Array.isArray 를 씁니다.
console.log(Array.isArray(students));
// 출력: true

// ✏️ 직접 해보기 1 — 좋아하는 음식 3개를 담은 배열을 만들어 출력해 보세요.


// ── 섹션 2: 인덱스 — 몇 번째인지 ──

// 배열의 각 자리에는 번호가 붙어 있습니다. 이 번호를 인덱스라고 합니다.
// 중요한 것은 0부터 시작한다는 점입니다.
//
//     students = [ "김민준", "이서연", "박지훈" ]
//     인덱스        0        1        2

console.log(students[0]);
// 출력: 김민준
console.log(students[1]);
// 출력: 이서연
console.log(students[2]);
// 출력: 박지훈

// "첫 번째"가 0번인 게 이상하죠? 이유가 있습니다.
// 컴퓨터는 인덱스를 "맨 앞에서 몇 칸 떨어져 있나" 로 셉니다.
// 첫 번째 값은 맨 앞에서 0칸 떨어져 있어서 0번입니다.
// 프로그래밍 전반의 약속이니 익숙해지세요.

// 없는 인덱스를 꺼내면 에러가 아니라 undefined 입니다.
console.log(students[3]);
// 출력: undefined
// 에러가 안 나기 때문에 "왜 undefined 가 나오지?" 하고 헤매게 됩니다.

// ✏️ 직접 해보기 2 — 위에서 만든 음식 배열의 두 번째 값을 출력해 보세요.


// ── 섹션 3: length — 몇 개인지 ──

console.log(students.length);
// 출력: 3

console.log(emptyList.length);
// 출력: 0

// 인덱스는 0부터인데 개수는 1부터 셉니다. 그래서 항상 이렇게 됩니다.
//     마지막 인덱스 = length - 1
console.log(students[students.length - 1]);
// 출력: 박지훈

// 이건 개수가 몇 개든 항상 마지막을 가리킵니다.
const longList = ["a", "b", "c", "d", "e"];
console.log(longList[longList.length - 1]);
// 출력: e

// 최근에 생긴 더 편한 방법도 있습니다.
console.log(longList.at(-1));
// 출력: e
console.log(longList.at(-2));
// 출력: d
// at(-1) 은 뒤에서 첫 번째라는 뜻입니다.

// ✏️ 직접 해보기 3 — 음식 배열의 개수와 마지막 값을 출력해 보세요.


// ── 섹션 4: 값 바꾸기 ──

const menu = ["아메리카노", "라떼", "케이크"];

menu[1] = "카푸치노";
console.log(menu);
// 출력: [ '아메리카노', '카푸치노', '케이크' ]

// const 로 만들었는데 왜 바뀔까요?
// const 는 "menu 라는 이름이 다른 배열을 가리키지 못하게" 막는 것입니다.
// 배열 '안의 내용'은 바꿀 수 있습니다.

// 이건 안 됩니다.
// menu = ["새 배열"];
// 실수: TypeError: Assignment to constant variable.

// 그래서 배열은 대부분 const 로 만듭니다. 내용은 어차피 바꿀 수 있으니까요.

// 없는 자리에 값을 넣으면 배열이 늘어납니다.
menu[5] = "쿠키";
console.log(menu);
// 출력: [ '아메리카노', '카푸치노', '케이크', <2 empty items>, '쿠키' ]
console.log(menu.length);
// 출력: 6
// 중간에 빈 자리가 생겨 버립니다. 이렇게 넣지 말고 push 를 쓰세요. (개념02)

// ✏️ 직접 해보기 4 — 음식 배열의 첫 번째 값을 다른 음식으로 바꿔 보세요.


// ── 섹션 5: 배열 안의 배열 ──

// 배열 안에 배열을 넣을 수 있습니다. 표(행과 열)를 표현할 때 씁니다.
const classScores = [
  [90, 85, 70], // 1모둠
  [60, 95, 88], // 2모둠
];

console.log(classScores[0]);
// 출력: [ 90, 85, 70 ]

// 대괄호를 두 번 붙이면 안쪽 값까지 꺼냅니다.
console.log(classScores[0][1]);
// 출력: 85
// classScores[0] 이 [90, 85, 70] 이고, 그중 [1] 이 85 입니다.

console.log(classScores[1][2]);
// 출력: 88

// ✏️ 직접 해보기 5 — 2모둠의 첫 번째 점수를 출력해 보세요.


// ── 섹션 6: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] 인덱스를 1부터라고 생각하기
const fruits = ["사과", "바나나", "포도"];
console.log(fruits[1]);
// 출력: 바나나
// 실수: "첫 번째"를 꺼내려고 [1] 을 쓰면 두 번째가 나옵니다.

// [실수 2] length 를 인덱스로 쓰기
console.log(fruits[fruits.length]);
// 출력: undefined
// 실수: length 는 3인데 인덱스는 0,1,2 뿐입니다. length - 1 이어야 합니다.

// [실수 3] length 를 함수처럼 부르기 → TypeError
// console.log(fruits.length());
// 실수: length 는 괄호를 붙이지 않습니다. push() 같은 것과 헷갈리지 마세요.

// [실수 4] 대괄호 대신 중괄호
// const wrong = {"사과", "바나나"};
// 실수: SyntaxError. 중괄호는 07단원에서 배울 객체입니다. 배열은 대괄호입니다.

// [실수 5] 배열끼리 === 로 비교
console.log([1, 2] === [1, 2]);
// 출력: false
// 실수: 내용이 같아도 '다른 배열'이라 false 입니다.
//       배열은 값이 아니라 '어디에 있는지'로 비교되기 때문입니다.
//
//       왜 그런지 그림으로 봐 두세요. 앞으로 여러 번 나옵니다.
//
//         숫자·글자를 담을 때 — 변수 안에 '값' 이 그대로 들어갑니다
//           const a = 10;        a ┌────┐
//                                  │ 10 │
//                                  └────┘
//
//         배열·객체를 담을 때 — 변수 안에는 '주소' 만 들어갑니다
//           const b = [1, 2];    b ┌────┐        ┌─────────┐
//                                  │ 주소 │ ────→ │ [1, 2]  │
//                                  └────┘        └─────────┘
//
//       집 주소를 적어 준 것이지 집을 새로 지어 준 게 아닙니다.
//       === 는 주소끼리 비교하므로, 똑같이 생긴 집이 두 채 있어도 주소가 달라 false 입니다.
//       거꾸로 주소가 같으면 한쪽에서 물건을 넣었을 때 다른 쪽에서도 그게 보입니다.
//       (07단원 개념02, 09단원 개념03에서 이 그림을 다시 씁니다)



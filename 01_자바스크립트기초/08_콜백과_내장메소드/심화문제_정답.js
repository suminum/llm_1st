// ───── 심화 1 ─────
const products = [
  { name: "아메리카노", category: "음료" },
  { name: "라떼", category: "음료" },
  { name: "케이크", category: "디저트" },
  { name: "쿠키", category: "디저트" },
  { name: "샌드위치", category: "식사" },
];

const countByCategory = products.reduce((acc, product) => {
  if (acc[product.category]) {
    acc[product.category] += 1;
  } else {
    acc[product.category] = 1;
  }
  return acc; // ★ 이걸 빼면 다음 바퀴의 acc 가 undefined 가 됩니다
}, {});

console.log(countByCategory);
// 출력: { '음료': 2, '디저트': 2, '식사': 1 }

// 한 바퀴씩 따라가 보면
//
//   바퀴  product         acc 시작              하는 일           acc 끝
//    1    아메리카노(음료)  {}                   음료 없음 → 1     { 음료: 1 }
//    2    라떼(음료)       { 음료: 1 }           음료 있음 → +1    { 음료: 2 }
//    3    케이크(디저트)    { 음료: 2 }           디저트 없음 → 1   { 음료: 2, 디저트: 1 }
//    4    쿠키(디저트)      { 음료: 2, 디저트: 1 } 디저트 있음 → +1  { 음료: 2, 디저트: 2 }
//    5    샌드위치(식사)    ...                  식사 없음 → 1     { ..., 식사: 1 }
//
// reduce 의 시작값이 왜 {} 인가
//   합계를 구할 때는 0 으로 시작했습니다. 여기서는 '객체를 쌓아 가는' 것이라
//   빈 객체로 시작합니다. "무엇을 만들 것인가" 가 시작값을 정합니다.
//
// 07단원 심화 2와 비교해 보세요
//   거기서는 for 문 + 빈 객체로 똑같은 일을 했습니다.
//   reduce 는 "빈 객체를 만들고 돌면서 채운다" 를 한 덩어리로 묶은 것뿐입니다.
//   새로운 마법이 아닙니다. 이걸 알면 reduce 가 훨씬 덜 무섭습니다.
//
// 더 짧게 쓰는 법 (실무에서 자주 보입니다)
//   acc[key] = (acc[key] || 0) + 1;
//   "있으면 그 값, 없으면 0" 을 || 로 처리한 것입니다. (02단원)


// ───── 심화 2 ─────
const students = [
  { name: "김민준", score: 90 },
  { name: "이서연", score: 55 },
  { name: "박지훈", score: 78 },
  { name: "최유진", score: 95 },
];

console.log(
  students
    .filter((s) => s.score >= 60)
    .sort((a, b) => b.score - a.score)
    .map((s) => `${s.name}(${s.score})`)
    .join(", ")
);
// 출력: 최유진(95), 김민준(90), 박지훈(78)

console.log("원본 첫 번째:", students[0].name);
// 출력: 원본 첫 번째: 김민준

// 순서가 중요합니다
//   filter 를 먼저 해야 정렬할 것이 줄어듭니다.
//   map 을 먼저 하면 문자열이 되어 버려서 score 로 정렬할 수 없습니다.
//   "거르고 → 줄 세우고 → 모양 바꾸고 → 이어 붙인다" 가 자연스러운 순서입니다.
//
// 왜 원본이 안 바뀌었나
//   sort 는 원본을 바꾸는 메소드입니다. (개념06)
//   그런데 여기서 sort 가 받은 것은 students 가 아니라
//   filter 가 방금 만든 '새 배열' 입니다. 그래서 students 는 무사합니다.
//
//   만약 students.sort(...) 로 시작했다면 원본이 뒤섞였을 겁니다.
//   그때는 students.slice().sort(...) 로 복사부터 해야 합니다.
//
// b.score - a.score 인 이유
//   빼기 순서가 방향입니다. a - b 면 오름차순, b - a 면 내림차순.
//   "높은 순" 이니 b 를 앞에 씁니다.


// ───── 심화 3 ─────
const items = [
  { name: "케이크", price: 6000, stock: 2 },
  { name: "아메리카노", price: 4000, stock: 5 },
  { name: "라떼", price: 4000, stock: 3 },
  { name: "쿠키", price: 3000, stock: 5 },
];

const sorted = items.slice().sort((a, b) => {
  const priceDiff = a.price - b.price; // 가격 오름차순

  if (priceDiff !== 0) {
    return priceDiff; // 가격이 다르면 그것으로 결정
  }

  return b.stock - a.stock; // 가격이 같을 때만 재고 내림차순
});

sorted.forEach((item) => {
  console.log(`${item.name} ${item.price}원 재고${item.stock}개`);
});
// 출력: 쿠키 3000원 재고5개
// 출력: 아메리카노 4000원 재고5개
// 출력: 라떼 4000원 재고3개
// 출력: 케이크 6000원 재고2개

// 기준이 두 개일 때의 정석입니다
//   ① 첫 기준으로 비교한다
//   ② 결과가 0 이 아니면(순서가 정해졌으면) 그걸 그대로 돌려준다
//   ③ 0 이면(같으면) 두 번째 기준으로 다시 비교해 돌려준다
//
//   기준이 세 개여도 같습니다. if 를 하나 더 넣으면 됩니다.
//
// 한 줄로 쓰는 법도 있습니다
//   .sort((a, b) => a.price - b.price || b.stock - a.stock)
//
//   앞이 0 이면 falsy 라서 || 가 뒤를 내놓습니다. (02단원 단축 평가)
//   짧지만 처음 보면 무슨 뜻인지 알기 어렵습니다.
//   실무 코드에서 이 모양을 보면 "아, 두 번째 기준이구나" 하고 읽으시면 됩니다.
//
// 왜 slice() 로 복사했나
//   sort 는 원본을 바꿉니다. 여기서는 items 를 그대로 두려고 복사했습니다.
//   심화 2와 달리 앞에 filter 가 없어서, 복사를 안 하면 원본이 뒤섞입니다.

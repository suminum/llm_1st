// (값이 문자열이면 셋의 결과가 달라집니다. 섹션 6 [실수 4]에서 확인합니다)

// ✏️ 직접 해보기 3 — like 에 0을 담고, ++ 를 세 번 써서 3이 되게 만든 뒤 출력해 보세요.


// ── 섹션 4: ++ 를 앞에 붙일 때와 뒤에 붙일 때 ──

// 변수의 값만 바꿀 때는 앞뒤 어디에 붙여도 결과가 같습니다.
// 하지만 "그 자리에서 바로 사용"하면 달라집니다.

// [뒤에 붙이기 — 후위] 먼저 쓰고, 그다음 증가
let a = 5;
console.log(a++);
// 출력: 5
// ↑ 5를 먼저 내보내고, 그 뒤에 6이 됩니다
console.log(a);
// 출력: 6

// [앞에 붙이기 — 전위] 먼저 증가하고, 그다음 씀
let b = 5;
console.log(++b);
// 출력: 6
// ↑ 먼저 6으로 만들고, 그 6을 내보냅니다
console.log(b);
// 출력: 6

// 둘 다 최종 값은 6으로 같습니다. 다른 건 '그 줄에서 나온 값'뿐입니다.

// 헷갈리죠? 그래서 실무에서는 이렇게 씁니다.
//   → 값을 쓰면서 동시에 증가시키지 마세요. 줄을 나누면 헷갈릴 일이 없습니다.
let c = 5;
console.log(c);
// 출력: 5
c++; // 그다음 줄에서 따로 증가
console.log(c);
// 출력: 6


// ── 섹션 1: = 는 "같다"가 아니라 "넣어라" ──

// 다시 한 번 강조합니다. = 는 오른쪽 값을 왼쪽 변수에 넣으라는 명령입니다.
let total = 100;
console.log(total);
// 출력: 100

// 그래서 이런 식이 성립합니다. 수학이었다면 말이 안 되는 식입니다.
total = total + 50;
console.log(total);
// 출력: 150
// 읽는 법: "지금 total(100)에 50을 더해서, 그 결과를 다시 total에 넣어라"

// ✏️ 직접 해보기 1 — score 에 70을 담고, 여기에 15를 더해서 다시 담은 뒤 출력해 보세요.


// ── 섹션 2: += -= *= /= %= — 줄여 쓰기 ──

// total = total + 50; 은 total 을 두 번 쓰니 길고 오타가 나기 쉽습니다.
// 그래서 이렇게 줄여 씁니다.

let cart = 100;

// [기본]
cart = cart + 50;
console.log(cart);
// 출력: 150

// [줄여쓰기] 위와 완전히 같은 뜻입니다.
cart += 50;
console.log(cart);
// 출력: 200

cart -= 30;
console.log(cart);
// 출력: 170

cart *= 2;
console.log(cart);
// 출력: 340

cart /= 4;
console.log(cart);
// 출력: 85

cart %= 7;
console.log(cart);
// 출력: 1
// 85 ÷ 7 = 12 ... 나머지 1

// 문자열에도 += 를 쓸 수 있습니다. 이어붙이기가 됩니다.
let message = "안녕";
message += "하세요";
console.log(message);
// 출력: 안녕하세요


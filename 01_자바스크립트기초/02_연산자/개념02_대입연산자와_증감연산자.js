// ── 섹션 3: ++ 와 -- — 1씩 늘리고 줄이기 ──

// 1을 더하는 일이 워낙 잦아서 전용 기호가 있습니다.
let visitor = 5;

visitor++; // visitor += 1 과 같습니다
console.log(visitor);
// 출력: 6

visitor--; // visitor -= 1 과 같습니다
console.log(visitor);
// 출력: 5

// 값이 숫자일 때 세 가지는 전부 같은 뜻입니다.

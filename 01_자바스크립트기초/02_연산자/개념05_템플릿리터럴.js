// 지금까지 문자열에 변수를 끼워 넣을 때 + 를 썼습니다.
// 짧을 땐 괜찮지만 길어지면 금방 지옥이 됩니다.
// 그래서 나온 게 백틱( ` )을 쓰는 템플릿 리터럴입니다.
// ('리터럴' 은 코드에 값을 그대로 적어 넣은 것을 부르는 말입니다.
//  "안녕" 도 1200 도 전부 리터럴입니다. 어려운 말이 아닙니다)


// ── 섹션 1: + 방식의 불편함 ──

const userName = "김민준";
const userAge = 20;
const city = "부산";

// [기본] + 로 이어붙이기
console.log("안녕하세요, " + userName + "님. 나이는 " + userAge + "세, 사는 곳은 " + city + "입니다.");
// 출력: 안녕하세요, 김민준님. 나이는 20세, 사는 곳은 부산입니다.

// 잘 나오긴 합니다. 하지만
//   - 따옴표와 + 가 번갈아 나와서 눈이 아픕니다
//   - 띄어쓰기를 어디에 넣었는지 세기 어렵습니다
//   - + 하나만 빠뜨려도 에러입니다


// ── 섹션 2: 백틱과 ${ } ──

// 백틱은 키보드 숫자 1 왼쪽, 물결(~)과 같은 키입니다.
// 백틱으로 감싼 문자열 안에서는 ${변수이름} 으로 값을 바로 끼워 넣습니다.

console.log(`안녕하세요, ${userName}님. 나이는 ${userAge}세, 사는 곳은 ${city}입니다.`);
// 출력: 안녕하세요, 김민준님. 나이는 20세, 사는 곳은 부산입니다.

// 결과는 위와 똑같은데 훨씬 읽기 쉽습니다.
// 문장이 문장 그대로 보이고, 값이 들어갈 자리만 ${ } 로 뚫려 있습니다.

// 짧은 것도 봅시다.
const price = 4500;
console.log(`라떼는 ${price}원입니다`);
// 출력: 라떼는 4500원입니다

// 변수가 없어도 백틱을 쓸 수 있습니다. 그냥 문자열입니다.
console.log(`그냥 문자열`);
// 출력: 그냥 문자열

// 자료형도 그대로 string 입니다.
console.log(typeof `안녕`);
// 출력: string

// ✏️ 직접 해보기 1 — 백틱을 써서 "부산 여행 가자" 를 출력해 보세요. (city 변수 사용)


// ── 섹션 3: ${ } 안에는 계산식도 들어간다 ──

// 변수 이름만 넣을 수 있는 게 아닙니다. 값이 나오는 식이면 뭐든 됩니다.
const itemPrice = 4500;
const itemCount = 3;

console.log(`총액: ${itemPrice * itemCount}원`);
// 출력: 총액: 13500원

// 비교식도 됩니다. (결과인 true/false 가 글자로 들어갑니다)
console.log(`성인인가? ${userAge >= 19}`);
// 출력: 성인인가? true

// 다른 값을 바로 만들어 넣을 수도 있습니다.
console.log(`내년이면 ${userAge + 1}살`);
// 출력: 내년이면 21살

// 다만 ${ } 안이 길어지면 오히려 읽기 나빠집니다.
// 계산은 미리 변수에 담고, ${ } 에는 변수만 넣는 편이 좋습니다.
const totalPrice = itemPrice * itemCount;
console.log(`총액: ${totalPrice}원`);
// 출력: 총액: 13500원

// ✏️ 직접 해보기 2 — 가로 8, 세로 5 인 직사각형의 넓이를 백틱 안에서 계산해
//                    "넓이는 40 입니다" 로 출력해 보세요.


// ── 섹션 4: 여러 줄 문자열 ──

// 작은따옴표·큰따옴표는 줄을 바꾸면 에러가 납니다.
// 백틱은 엔터를 친 그대로 줄바꿈이 됩니다.

const receipt = `주문 내역
- 라떼 4500원
- 케이크 6000원`;

console.log(receipt);
// 출력: 주문 내역
// 출력: - 라떼 4500원
// 출력: - 케이크 6000원

// 들여쓰기도 그대로 들어가니 주의하세요.
// 코드를 예쁘게 맞추려고 넣은 공백까지 출력에 포함됩니다.

// 변수와 섞어도 됩니다.
const orderName = "김민준";
const orderTotal = 10500;
console.log(`${orderName}님 주문서
합계: ${orderTotal}원
감사합니다`);
// 출력: 김민준님 주문서
// 출력: 합계: 10500원
// 출력: 감사합니다

// ✏️ 직접 해보기 3 — 자기 이름과 좋아하는 음식을 두 줄로 출력해 보세요.


// ── 섹션 5: 백틱 안에서 따옴표 쓰기 ──

// 백틱 안에서는 " 와 ' 를 그냥 쓸 수 있습니다. 신경 쓸 게 없습니다.
console.log(`그는 "안녕"이라고 말하며 '손'을 흔들었다`);
// 출력: 그는 "안녕"이라고 말하며 '손'을 흔들었다

// 백틱 자체를 넣고 싶다면 앞에 역슬래시(\)를 붙입니다. (드문 경우입니다)
console.log(`백틱은 \` 이렇게 생겼습니다`);
// 출력: 백틱은 ` 이렇게 생겼습니다


// ── 섹션 6: 언제 무엇을 쓸까 ──

// 실무 기준은 간단합니다.
//   변수를 끼워 넣거나 줄을 바꾼다  →  백틱
//   그냥 고정된 글자 하나           →  작은따옴표나 큰따옴표
//
// 헷갈리면 그냥 백틱을 쓰세요. 손해 볼 게 없습니다.

const label = "합계"; // 고정 글자 — 따옴표
console.log(`${label}: ${totalPrice}원`); // 조합 — 백틱
// 출력: 합계: 13500원


// ── 섹션 7: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] 백틱 대신 작은따옴표를 쓰기
const wrong1 = '가격은 ${price}원';
console.log(wrong1);
// 출력: 가격은 ${price}원
// 실수: ${ } 가 그대로 글자로 나옵니다. 에러가 안 나서 더 헷갈립니다.
//       ${ } 를 쓰려면 반드시 백틱이어야 합니다.

// [실수 2] $ 를 빠뜨리기
console.log(`가격은 {price}원`);
// 출력: 가격은 {price}원
// 실수: 중괄호만 쓰면 그냥 글자입니다. $ 가 있어야 합니다.

// [실수 3] 백틱을 작은따옴표로 착각해서 닫기 → SyntaxError
// console.log(`안녕');
// 실수: 백틱으로 열었으면 백틱으로 닫아야 합니다.
//       글꼴에 따라 ` 와 ' 가 비슷해 보이니 주의하세요.

// [실수 4] ${ } 안에 세미콜론이나 문장 넣기 → SyntaxError
// console.log(`값: ${const x = 1;}`);
// 실수: ${ } 안에는 '값이 되는 식'만 들어갑니다.
//       변수 만들기나 문장은 넣을 수 없습니다.


// ── 정리 ──

// 1. 백틱 ` ` 안에서 ${변수} 로 값을 끼워 넣는다.
// 2. ${ } 안에는 계산식·비교식도 들어간다. 단, 길어지면 변수로 빼라.
// 3. 백틱은 엔터를 친 그대로 여러 줄이 된다.
// 4. 백틱 안에서는 " 와 ' 를 그냥 써도 된다.
// 5. 작은따옴표에 ${ } 를 쓰면 글자 그대로 나온다. 에러도 안 난다.



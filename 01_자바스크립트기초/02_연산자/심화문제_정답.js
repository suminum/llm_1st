// ───── 심화 1 ─────
console.log(0.1 + 0.2);
// 출력: 0.30000000000000004
console.log(0.1 + 0.2 === 0.3);
// 출력: false
console.log(Math.round((0.1 + 0.2) * 100) / 100);
// 출력: 0.3
console.log(Math.round((0.1 + 0.2) * 100) / 100 === 0.3);
// 출력: true

// 왜 이렇게 하나
//   0.30000000000000004 × 100 = 30.000000000000004
//   Math.round 로 반올림하면 딱 30 (정수)
//   30 / 100 = 0.3  (정수를 나눈 것이라 오차가 안 생깁니다)
//
//   핵심은 "소수끼리 직접 비교하지 않는다" 입니다.
//   정수로 만들어 비교하거나, 아예 처음부터 정수로 다룹니다.
//
// 실무에서 돈을 다루는 방법
//   1200.50 원 대신 120050 (전 단위 정수) 로 저장하고,
//   화면에 보여 줄 때만 100 으로 나눕니다.
//   그러면 오차가 아예 안 생깁니다.


// ───── 심화 2 ─────
console.log(0 == "");
// 출력: true
console.log(0 === "");
// 출력: false
console.log(null == undefined);
// 출력: true
console.log(null === undefined);
// 출력: false
console.log(NaN === NaN);
// 출력: false

// 1번이 왜 true 인가
//   == 는 자료형이 다르면 '한쪽을 바꿔서' 비교합니다.
//   빈 문자열 "" 을 숫자로 바꾸면 0 입니다. (01단원 심화 1에서 확인했죠)
//   그래서 0 == 0 이 되어 true 가 됩니다.
//
//   === 는 자료형부터 봅니다. number 와 string 은 애초에 다르니 false 입니다.
//
// 3번이 true 인 것은 언어가 그렇게 정한 것입니다.
//   "값이 없다" 를 뜻하는 둘을 같은 것으로 쳐 줍니다.
//   이것만은 == 가 편해서 실무에서도 가끔 씁니다.
//     if (value == null)  →  null 이거나 undefined 면
//
// 5번 — NaN 은 자기 자신과도 같지 않습니다
//   NaN 은 "숫자가 아님" 이라는 뜻이지 특정 값이 아닙니다.
//   "계산 실패" 가 두 번 있었다고 그 둘이 같은 실패는 아니죠.
//   그래서 NaN 인지 확인할 때는 === 를 쓸 수 없습니다.
//   Number.isNaN(값) 을 씁니다.

console.log(Number.isNaN(NaN));
// 출력: true


// ───── 심화 3 ─────
const count = 0;
const nickname = "";

console.log(`[${count || 100}]`);
// 출력: [100]
console.log(`[${count ?? 100}]`);
// 출력: [0]
console.log(`[${nickname || "손님"}]`);
// 출력: [손님]
console.log(`[${nickname ?? "손님"}]`);
// 출력: []

// 차이는 딱 하나입니다.
//
//   ||  왼쪽이 falsy 면 오른쪽    (0, "", null, undefined, NaN, false 전부)
//   ??  왼쪽이 null/undefined 면 오른쪽  (그 둘만)
//
// 그래서 0 과 빈 문자열에서 갈립니다.
//
// 어느 쪽을 써야 하나
//   장바구니 개수, 좋아요 수, 점수처럼 0 이 '진짜 값' 이면 ?? 를 씁니다.
//   || 를 쓰면 0 인데도 기본값으로 바뀌어 버립니다. 찾기 어려운 버그입니다.
//
//     const 개수 = 담은개수 || 1;   ← 0개 담았는데 1개로 바뀜 (버그)
//     const 개수 = 담은개수 ?? 1;   ← 0개는 0개 그대로 (맞음)
//
//   반대로 "빈 칸이면 기본 이름" 처럼 빈 문자열도 걸러야 하면 || 가 맞습니다.

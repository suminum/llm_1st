// 3. 문자열끼리 비교하면 사전 순. "10" < "9" 가 true 다.
// 4. 크기를 비교할 값이 입력창에서 왔다면 먼저 Number( ) 로 바꾼다.
// 5. 10 < x < 30 은 틀린 코드다. && 로 이어야 한다.



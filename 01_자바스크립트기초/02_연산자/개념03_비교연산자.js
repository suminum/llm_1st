// ── 섹션 6: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// [실수 1] = 와 === 를 헷갈리기
let count = 5;
count = 3; // "3을 넣어라"  ← 비교가 아닙니다
console.log(count);
// 출력: 3
// 비교하려면 count === 3 이라고 써야 합니다.
console.log(count === 3);
// 출력: true

// [실수 2] => 로 잘못 쓰기 → SyntaxError
// console.log(10 => 5);
// 실수: 이상은 >= 입니다. = 가 뒤에 옵니다.

// [실수 3] 범위를 수학처럼 쓰기
const temp = 25;
console.log(10 < temp < 30);
// 출력: true
// 실수: 맞은 것처럼 보이지만 우연입니다.
//       10 < 25 → true 가 되고, 그다음 true < 30 을 계산합니다.
//       true 는 숫자로 1이라 1 < 30 → true 입니다.
console.log(10 < 100 < 30);
// 출력: true
// 100은 30보다 큰데도 true 가 나옵니다. 완전히 틀린 코드입니다.
// 범위는 && 로 이어야 합니다. (다음 파일 개념04)

// [실수 4] 소수 비교
console.log(0.1 + 0.2 === 0.3);
// 출력: false
// 실수: 소수 오차 때문입니다. 소수는 === 로 비교하지 마세요.


// ── 정리 ──

// 1. > < >= <=  — '이상/이하'와 '초과/미만'을 구별할 것

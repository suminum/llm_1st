// 두 값을 견주어 보고 true / false 를 내놓는 기호들입니다.
// 03단원 조건문("만약 ~라면")의 재료가 되므로 아주 중요합니다.
//
//     >   보다 크다
//     <   보다 작다
//     >=  크거나 같다 (이상)
//     <=  작거나 같다 (이하)
//     === 같다
//     !== 다르다


// ── 섹션 1: 크기 비교 ──

console.log(10 > 5);
// 출력: true
console.log(10 < 5);
// 출력: false

// '이상'과 '초과'를 구별하세요. 실무 버그의 단골입니다.
console.log(10 >= 10);
// 출력: true
console.log(10 > 10);
// 출력: false

console.log(10 <= 10);
// 출력: true

// 기호 순서에 주의하세요. => 가 아니라 >= 입니다.
// (=> 는 나중에 배울 화살표 함수의 기호입니다)

const age = 20;
console.log(age >= 19);
// 출력: true

// ✏️ 직접 해보기 1 — 재고가 3개일 때 "5개 이상 남았는가"를 판단해 출력해 보세요.


// ── 섹션 2: === 같다 / !== 다르다 ──

console.log(5 === 5);
// 출력: true
console.log(5 === 3);
// 출력: false

console.log(5 !== 3);
// 출력: true
console.log(5 !== 5);
// 출력: false

// = 기호가 몇 개인지가 전부 다른 뜻입니다. 이것만은 꼭 구별하세요.
//     =    넣어라    (대입)
//     ==   같으냐?   (느슨한 비교 — 쓰지 마세요, 섹션 3)
//     ===  같으냐?   (엄격한 비교 — 항상 이걸 쓰세요)

const menu = "아메리카노";
console.log(menu === "아메리카노");
// 출력: true
console.log(menu === "라떼");
// 출력: false

// 문자열은 한 글자라도 다르면 false 입니다. 띄어쓰기도 글자입니다.
console.log("아메리카노" === "아메리카노 ");
// 출력: false

// ✏️ 직접 해보기 2 — 아이디가 "admin" 인지 비교한 결과를 출력해 보세요.


// ── 섹션 3: == 를 쓰면 안 되는 이유 ──

// == 는 자료형이 달라도 "대충 비슷하면" true 를 줍니다.
console.log("5" == 5);
// 출력: true
// 문자열 "5" 와 숫자 5 를 같다고 합니다.

console.log("5" === 5);
// 출력: false
// === 는 자료형까지 봅니다. 이게 맞는 동작입니다.

// == 의 이상한 결과들을 보세요.
console.log(0 == false);
// 출력: true
console.log("" == false);
// 출력: true
console.log("0" == false);
// 출력: true
console.log(null == undefined);
// 출력: true

// 반면 === 는 예상대로 동작합니다.
console.log(0 === false);
// 출력: false
console.log("" === false);
// 출력: false
console.log(null === undefined);
// 출력: false

// 결론: 비교는 언제나 === 와 !== 로 하세요.
// == 는 "이런 게 있다" 정도만 알아 두면 됩니다. 남의 코드에서 만날 수는 있으니까요.

// ✏️ 직접 해보기 3 — "0" == 0 과 "0" === 0 을 각각 출력해 비교해 보세요.


// ── 섹션 4: 문자열끼리 비교하면 사전 순 ──

// 문자열에 > < 를 쓰면 사전(순서)으로 비교합니다.
console.log("apple" < "banana");
// 출력: true
// a 가 b 보다 앞이라서 apple 이 '작습니다'

console.log("가" < "나");
// 출력: true

// [함정] 대문자가 소문자보다 앞입니다.
console.log("Z" < "a");
// 출력: true

// [큰 함정] 숫자처럼 생긴 문자열은 숫자로 비교되지 않습니다.
console.log("10" < "9");
// 출력: true
// "1" 과 "9" 를 한 글자씩 비교해서 1이 앞이라 "10"이 작다고 나옵니다.

console.log(10 < 9);
// 출력: false
// 숫자로 비교하면 당연히 false 입니다.

// 그래서 입력창에서 받은 값을 크기 비교하기 전에는
// 반드시 Number( ) 로 바꿔야 합니다. (01단원 개념05)
const inputAge = "9"; // 입력창에서 온 값
console.log(Number(inputAge) < 10);
// 출력: true

// ✏️ 직접 해보기 4 — "100" > "99" 와 100 > 99 를 각각 출력해 비교해 보세요.


// ── 섹션 5: 비교 결과는 값이다 ──

// 비교 결과 true / false 는 그냥 값이라 변수에 담을 수 있습니다.
const stock = 0;
const isSoldOut = stock === 0;
console.log(isSoldOut, typeof isSoldOut);
// 출력: true boolean

const userAge = 17;
const isAdult = userAge >= 19;
console.log(isAdult);
// 출력: false


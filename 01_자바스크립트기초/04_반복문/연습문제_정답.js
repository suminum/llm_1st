// ───── 문제 14 ─────
for (let row = 1; row <= 5; row++) {
  let line = ""; // 줄마다 새로 비웁니다 — 바깥 반복문 '안'에서 만들기
  for (let col = 1; col <= row; col++) {
    line += "*";
  }
  console.log(line);
}
// 출력: *
// 출력: **
// 출력: ***
// 출력: ****
// 출력: *****
// 안쪽 조건이 col <= row 라서 줄마다 개수가 달라집니다.


// ───── 문제 15 ─────
let money15 = 100;
let day15 = 1;

while (money15 <= 10000) {
  money15 *= 2;
  day15++;
}

console.log(`${day15}일째에 ${money15}원`);
// 출력: 8일째에 12800원
// 100 → 200 → 400 → 800 → 1600 → 3200 → 6400 → 12800
// 12800 이 되는 순간 조건이 false 가 되어 멈춥니다.


// ───── 문제 16 ─────
for (let row = 1; row <= 4; row++) {
  let line = "";
  for (let col = 1; col <= row; col++) {
    line += col; // 숫자를 문자열에 이어붙이면 글자가 됩니다
  }
  console.log(line);
}
// 출력: 1
// 출력: 12
// 출력: 123
// 출력: 1234
// line 이 문자열("")로 시작했기 때문에 + 가 이어붙이기로 동작합니다.
// line 을 0 으로 시작했다면 숫자 덧셈이 되어 완전히 다른 결과가 나옵니다.



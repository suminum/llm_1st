// ───── 심화 1 ─────
for (let dan = 2; dan <= 4; dan++) {
  let line = `${dan}단:`; // ★ 빈 문자열이 아니라 "2단:" 으로 시작합니다

  for (let i = 1; i <= 9; i++) {
    line += ` ${dan * i}`; // 앞에 공백을 하나 붙여 이어 갑니다
  }

  console.log(line);
}
// 출력: 2단: 2 4 6 8 10 12 14 16 18
// 출력: 3단: 3 6 9 12 15 18 21 24 27
// 출력: 4단: 4 8 12 16 20 24 28 32 36

// 핵심 두 가지
//   ① line 을 '바깥' 반복문 안에 만들었습니다.
//      안쪽에 만들면 곱할 때마다 새로 비워져서 마지막 값만 남습니다.
//      바깥보다 더 밖에 만들면 세 단이 한 줄에 다 이어집니다.
//   ② console.log 를 안쪽에 두면 27줄이 나옵니다. 바깥에 둬야 3줄입니다.
//
// "어느 반복문 안에 두느냐" 가 중첩 반복문의 전부입니다.


// ───── 심화 2 ─────
let result = "";
let count = 0;

for (let i = 1; i <= 100; i++) {
  if (i % 3 !== 0) {
    continue; // 3의 배수가 아니면 건너뛴다
  }
  if (i % 5 !== 0) {
    continue; // 5의 배수가 아니면 건너뛴다
  }

  // 여기까지 왔다면 둘 다 만족한 것입니다
  result += `${i} `;
  count++;
}

console.log(result.trim());
// 출력: 15 30 45 60 75 90
console.log(`총 ${count}개`);
// 출력: 총 6개

// continue 방식 vs if 방식
//   if (i % 3 === 0 && i % 5 === 0) { ... }  ← 이렇게 써도 결과는 같습니다
//
//   그런데 조건이 다섯 개쯤 되면 && 로 이은 줄이 화면을 넘어갑니다.
//   continue 로 하나씩 걸러내면 조건마다 한 줄씩이라 읽기 쉽고,
//   나중에 조건을 하나 더 넣을 때도 줄만 추가하면 됩니다.
//
//   05단원에서 배울 '조기 반환(return)' 과 똑같은 생각입니다.
//   "아니면 빨리 빠져나간다" 가 코드를 납작하게 만듭니다.
//
// trim() 을 쓴 이유
//   마지막 숫자 뒤에도 공백이 붙어 있습니다. 눈에는 안 보이지만 있습니다.
//   trim() 은 앞뒤 공백을 지웁니다. 10단원에서 다시 만납니다.


// ───── 심화 3 ─────
const number = 12345;

let rest = number; // 원본을 그대로 두려고 복사해서 씁니다
let reversed = 0;
let digits = 0;

while (rest > 0) {
  const last = rest % 10; // ① 맨 뒷자리 꺼내기
  reversed = reversed * 10 + last; // 자리를 한 칸 밀고 새 자리를 더한다
  rest = Math.floor(rest / 10); // ② 맨 뒷자리 떼어 버리기
  digits++;
}

console.log(reversed);
// 출력: 54321
console.log(`${digits}자리`);
// 출력: 5자리

// 한 바퀴씩 따라가 보면 이렇습니다.
//
//   rest    last   reversed 계산            reversed
//   12345    5     0 * 10 + 5                    5
//    1234    4     5 * 10 + 4                   54
//     123    3     54 * 10 + 3                 543
//      12    2     543 * 10 + 2               5432
//       1    1     5432 * 10 + 1             54321
//       0    -     rest 가 0 이라 반복 끝
//
// reversed * 10 이 하는 일
//   기존 숫자를 왼쪽으로 한 칸 밀어 오른쪽에 빈 자리를 만듭니다.
//   거기에 새로 꺼낸 자리를 채워 넣는 것입니다.
//
// 왜 문자열을 안 쓰나
//   String(number).split("").reverse().join("") 로 하면 한 줄입니다.
//   (06·08단원에서 배웁니다)
//   그런데 % 와 Math.floor 로 자릿수를 다루는 방법은
//   나중에 진법 변환, 자릿수 합 구하기 같은 데서 계속 나옵니다.
//   반복문으로 숫자를 분해하는 감각을 잡는 것이 이 문제의 목적입니다.

//
// 그리고 섹션 3의 경고는 여기서도 그대로입니다.
// 목록 안의 어느 하나가 price 를 안 갖고 있어도 검사는 조용합니다.

// ✏️ 직접 해보기 5 — menus 에서 4200원 이상인 메뉴의 이름만 뽑아 출력해 보세요.


// ── 섹션 6: 자주 하는 실수 ──

// [실수 1] : Menu 를 적었으니 안전하다고 믿기
//   섹션 3입니다. 적는 것은 주장이지 확인이 아닙니다.
//   내가 쓴 코드끼리는 맞춰 주지만, 서버가 다른 걸 보내면 못 잡습니다.

// [실수 2] 서버 응답을 그대로 any 로 쓰기
//   가장 흔한 any 유입 경로입니다. 적는 데 한 줄이면 됩니다.

// [실수 3] 실제 응답과 다른 모양을 적기
//   서버가 문자열로 주는데 number 라고 적으면, 실행 전까지 아무도 모릅니다.
//   응답을 한 번은 눈으로 찍어 보고 적으세요(console.log(loose) 로 충분합니다).

// [실수 4] 목록인데 [] 를 안 붙이기
//   Menu 라고 적고 배열을 받으면, menus.length 가 TS2339 로 걸립니다.
//   반대로 안 걸리고 넘어가는 경우도 있어 더 위험합니다.


// ── 정리 ──

// 1. JSON.parse 결과에 : 타입 을 적어 주면 그때부터 검사와 자동완성이 살아난다.
// 2. 응답이 문자열로 오면 모양도 string 으로 적어야 한다. 사실대로 적는 것이 원칙.
// 3. ★ 타입은 약속이지 검사가 아니다. 실제 값이 달라도 조용히 통과하고
//    쓰는 순간 실행 중에 터진다.
// 4. 내 코드끼리 안 맞는 것은 잡아 주고, 밖에서 들어온 값은 못 잡는다.
// 5. 그래서 밖에서 온 값은 쓰기 전에 확인한다. 제대로 된 방법은 05단원.
// 6. 목록은 뒤에 [] 를 붙인다. 콜백 매개변수는 문맥에서 알아낸다.


// ============================================================
// 직접 해보기 정답
// ============================================================
//
// 1) loose 는 any, menu 는 Menu 로 나옵니다.
//    loose 는 무엇을 해도 통과하고, menu 는 적어 둔 것만 됩니다.
//    한 줄 차이로 검사가 켜지고 꺼집니다.
//
// 2) 검사는 통과합니다. 그리고 출력도 9000 으로 '맞게' 나옵니다.
//    price 는 실제로 문자열 "4500" 인데 number 라고 적었는데도 그렇습니다.
//    곱하기가 문자열을 숫자로 바꿔 주기 때문입니다("4500" * 2 = 9000).
//
//    ★ 이게 가장 나쁜 경우입니다. 틀렸는데 맞게 나오니까요.
//    같은 값으로 더하기를 하면 바로 드러납니다.
//        console.log(legacy.price + 2);   → 45002
//    01단원 개념01의 "+ 만 특별하다" 가 여기서 다시 나옵니다.
//    검사도 통과하고 곱셈도 맞으니, 덧셈을 쓰는 날까지 아무도 모릅니다.
//    → 모양은 실제 응답 그대로 적어야 합니다.
//
// 3) 검사는 통과합니다. 실행하면 NaN 이 나옵니다.
//    "비쌈" * 2 는 NaN 입니다. 에러도 안 납니다.
//    섹션 3의 경고 그대로입니다. 화면에 NaN 이 찍히고 나서야 알게 됩니다.
//
// 4) null 이 나옵니다.
//    name 이 문자열이 아니라 숫자 123 이라 첫 번째 조건에서 걸러집니다.
//    price 는 맞지만 하나라도 어긋나면 null 입니다.
//
// 5) console.log(menus.filter((m) => m.price >= 4200).map((m) => m.name));
//    // 출력: [ '라떼' ]

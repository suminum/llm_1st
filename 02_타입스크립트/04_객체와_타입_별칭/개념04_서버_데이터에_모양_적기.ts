//     : Menu 라고 적는 것은 "이런 모양일 것이다" 라는 내 주장입니다.
//     타입스크립트는 그 주장을 검사하지 않고 믿습니다.
//
// 01단원 개념02에서 "node 는 타입을 지운다" 고 했습니다.
// 지워진 것은 실행할 때 아무 일도 하지 않습니다.

// ── 섹션 1: 에러 한 줄의 구조 ──

// tsc 가 내는 에러는 언제나 이 모양입니다.
//
//     개념03_에러_메시지_읽는_법.ts(23,7): error TS2322: Type 'string' is not ...
//     └───────────── 1 ─────────────┘ └2┘ └──3──┘  └────────── 4 ──────────┘
//
//     1. 어느 파일인가
//     2. 몇 번째 줄, 몇 번째 글자인가       ← (줄, 열) 입니다
//     3. 에러 번호
//     4. 무슨 일인가
//
// 순서대로 "어디서 · 무엇이" 입니다.
// 2번의 줄 번호만 봐도 절반은 해결됩니다. 그 줄로 가면 되니까요.
//
// 3번 번호는 외울 필요가 없습니다. 다만 인터넷에 검색할 때
// 긴 영어 문장 대신 TS2322 라고만 치면 되니 편합니다.

const 예시 = "에러 번호는 검색어로 쓰면 편합니다";
console.log(예시);
// 출력: 에러 번호는 검색어로 쓰면 편합니다

// ✏️ 직접 해보기 1 — 개념02 의 틀린예제를 검사했을 때 나온 에러 세 줄에서
//    '줄 번호' 만 세 개 뽑아 적어 보세요.


// ── 섹션 2: 다섯 개만 알면 된다 ──

// ── ① TS2322 : 담을 수 없다 ──
//
// 에러: TS2322 Type 'string' is not assignable to type 'number'.
// const price: number = "4000";
//
// 실수: assignable = "넣을 수 있는". not assignable = "넣을 수 없다".
//       읽는 법: "string 을 number 자리에 넣을 수 없습니다"
//       가장 많이 보게 될 에러입니다. 왼쪽이 실제, 오른쪽이 기대한 것입니다.

// 이 에러는 배열 안에서도 그대로 나옵니다.
//
// 에러: TS2322 Type 'string' is not assignable to type 'number'.
// const scores: number[] = [90, 85, "칠십"];
//
// 실수: 배열 전체가 아니라 "칠십" 이 있는 그 자리를 가리킵니다.
//       열 번호를 보면 정확히 어느 값인지 알 수 있습니다.

// ── ② TS2339 : 그런 이름이 없다 ──

const count: number = 3;
console.log(count);
// 출력: 3

// 에러: TS2339 Property 'toUpperCase' does not exist on type 'number'.
// console.log(count.toUpperCase());
//
// 실수: property = "속성", 점 뒤에 붙이는 이름을 말합니다.
//       읽는 법: "number 에는 toUpperCase 라는 게 없습니다"
//       toUpperCase 는 문자열에만 있습니다. 숫자에 쓰려고 한 것입니다.
//       JS 에서는 실행하다가 TypeError 로 터지던 자리입니다.

// ── ③ TS2551 : 그런 이름이 없다 + 이거 아니냐 ──

const cafe = { name: "봄날카페", price: 4500 };
console.log(cafe.name);
// 출력: 봄날카페

// 에러: TS2551 Property 'pirce' does not exist on type '{ name: string; price: number; }'. Did you mean 'price'?
// console.log(cafe.pirce);
//
// 실수: ② 와 같은 상황인데 비슷한 이름을 찾아 준 경우입니다.
//       Did you mean 'price'? = "price 를 쓰려던 것 아닌가요?"
//       이게 나오면 십중팔구 그게 맞습니다. 그대로 고치면 됩니다.

// ── ④ TS2345 : 넘긴 값이 안 맞는다 ──

console.log("하".repeat(3));
// 출력: 하하하

// 에러: TS2345 Argument of type 'string' is not assignable to parameter of type 'number'.
// console.log("하".repeat("3"));
//
// 실수: argument = "넘긴 값", parameter = "받기로 한 자리".
//       읽는 법: "숫자를 받기로 한 자리에 문자열을 넘겼습니다"
//       ① 과 문장이 거의 같습니다. 다른 점은 '변수에 담을 때' 가 아니라
//       '괄호 안에 넘길 때' 라는 것뿐입니다.
//       argument 와 parameter 는 03단원에서 제대로 다룹니다.

// ── ⑤ TS18048 : 없을 수도 있는 값이다 ──

const numbers = [10, 20, 30];
const big = numbers.find((n) => n > 100);
console.log(big);
// 출력: undefined

// 에러: TS18048 'big' is possibly 'undefined'.
// console.log(big + 1);
//
// 실수: possibly = "어쩌면". 읽는 법: "big 은 undefined 일 수도 있습니다"
//       "지금은 값이 있을 수도 있지만 없을 때도 있는데, 그건 생각해 보셨나요?"
//       라는 뜻입니다. 이 상황을 다루는 방법은 05단원에서 배웁니다.

// ✏️ 직접 해보기 2 — const t: string = 100; 을 써 보고
//    나오는 에러가 위 다섯 개 중 무엇인지, '왼쪽 오른쪽' 이 뭐가 뭔지 말해 보세요.


// ── 섹션 3: 에러가 여러 개 나오면 위에서부터 하나씩 ──

// 타입 에러는 한 번에 여러 개가 쏟아지는 일이 흔합니다.
// 스무 줄쯤 나오면 겁이 나지만, 대개 원인은 한두 개입니다.
//
//     1. 맨 위 에러의 줄로 간다
//     2. 그것만 고친다
//     3. 다시 npx tsc --noEmit 을 친다
//
// 한 개를 고치면 밑에 있던 열 개가 같이 사라지는 일이 자주 있습니다.
// 앞의 에러 때문에 뒤가 줄줄이 틀린 것으로 보였던 것뿐이기 때문입니다.
//
// 반대로 아래쪽 에러부터 손대면 원인이 아닌 곳을 고치게 됩니다.

// ✏️ 직접 해보기 3 — 아무 파일에 틀린 줄을 두 개 넣고 검사한 뒤,
//    위엣것 하나만 고치고 다시 검사해서 몇 개가 남는지 보세요.


// ── 섹션 4: 메시지에 나오는 영어 단어 ──

// 자주 나오는 단어는 이만큼입니다.
//
//     type          타입, 값의 종류
//     assignable    넣을 수 있는       (not assignable = 넣을 수 없다)
//     property      속성, 점 뒤의 이름
//     argument      넘긴 값
//     parameter     받기로 한 자리
//     possibly      어쩌면 ~일 수도
//     expected      기대한 것
//     required      반드시 있어야 하는
//     missing       빠졌다
//
// 이 아홉 개면 이 자료에서 만나는 메시지는 다 읽힙니다.

const 단어수 = 9;
console.log("외울 단어:", 단어수, "개");

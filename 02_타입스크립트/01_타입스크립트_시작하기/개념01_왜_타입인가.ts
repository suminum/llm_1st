// ── 섹션 6: 자주 하는 실수 ──

// [실수 1] "타입을 적었으니 이제 안전하다" 고 믿기
//   타입은 값의 '종류' 만 봅니다. 값이 옳은지는 안 봅니다.
//   위 fruitTotal 이 그 예입니다. 나이에 -5 를 넣어도 number 라서 통과합니다.

// [실수 2] "타입스크립트니까 알아서 다 잡아 주겠지" 라고 믿기
//   섹션 1이 반례입니다. 결과를 담을 자리에 타입을 안 적으면 안 잡힙니다.
//   막아 주는 것은 내가 기대를 적어 둔 자리뿐입니다.

// [실수 3] 타입 에러가 나면 코드가 안 돌아간다고 생각하기
//   반대입니다. 타입이 틀려도 코드는 그냥 돌아갑니다.
//   이게 워낙 중요해서 다음 파일(개념02) 전체를 여기에 씁니다.


// ── 정리 ──

// 1. 타입은 "이 자리에 올 값의 종류" 를 미리 적어 두는 것이다. 문법은 : 하나다.
// 2. 문자열에 + 를 쓰는 것은 타입스크립트도 안 막는다. 이어붙이기는 정당한 연산이라서다.
// 3. - * / 는 숫자 전용이라 바로 걸린다. 사고가 잦은 것은 하필 안 걸리는 + 다.
// 4. + 사고를 잡으려면 결과를 담을 자리에 : number 를 적어야 한다.
//    적어 둔 만큼만 막아 준다.
// 5. 잡아 주는 것 — 종류 착각, 이름 오타, 없을 수도 있는 값.
// 6. 못 잡는 것 — 계산 로직, 화면, 없는 데이터.
// 7. 실제로 가장 크게 체감되는 이득은 자동완성이다.



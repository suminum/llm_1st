// 타입스크립트가 무엇을 막아 주고, 무엇은 못 막는지를 봅니다.
//
// 처음부터 말해 두겠습니다. 타입스크립트는 만능이 아닙니다.
// 위의 사고 중 절반은 타입스크립트도 그냥 통과시킵니다.
// 어디까지 막아 주는지를 정확히 아는 것이 이 단원의 목표입니다.


// ── 섹션 1: 문자열에 + 를 쓰는 것은 타입스크립트도 막지 않는다 ──

// 장바구니 코드입니다. 수량은 화면 입력창에서 받아왔다고 생각하세요.
// 입력창 값은 무엇을 입력해도 언제나 문자열입니다.
const quantityText = "3"; // 입력창에서 온 값
const shipping = 3000;

console.log(quantityText + shipping);
// 출력: 33000
// 3 + 3000 = 3003 이 아닙니다. "3" 뒤에 "3000" 을 붙여서 "33000" 입니다.

// 놀라운 사실 — 이 줄은 타입스크립트에서도 에러가 안 납니다.
// 빨간 밑줄도 안 생깁니다. npx tsc --noEmit 도 조용히 통과합니다.
//
// 왜냐하면 문자열을 + 로 잇는 것은 원래 정당한 연산이기 때문입니다.
//
//     "봄날" + "카페"   →   "봄날카페"        ← 이건 아무 문제가 없죠
//
// 타입스크립트는 이 줄을 보고 "결과는 문자열이겠군" 하고 넘어갑니다.
// 여러분이 숫자를 원했다는 것을 알 방법이 없습니다.

// ✏️ 직접 해보기 1 — quantityText + shipping 의 결과에 typeof 를 찍어서
//    무슨 타입인지 확인해 보세요.


// ── 섹션 2: 반대로 - 와 * 는 바로 걸린다 ──

// 문자열끼리 빼는 것은 아무 의미가 없습니다. 그래서 타입스크립트가 막습니다.
//
// 에러: TS2362 The left-hand side of an arithmetic operation must be of type 'any', 'number', 'bigint' or an enum type.
// console.log(quantityText - shipping);
//
// 실수: "빼기의 왼쪽은 숫자여야 합니다" 라는 뜻입니다.
//       JS 에서는 이 줄이 -2997 을 조용히 내놓던 자리입니다.
//       확인했으면 다시 // 를 붙이세요.

// 곱하기도 같습니다.
//
// 에러: TS2362 The left-hand side of an arithmetic operation must be of type 'any', 'number', 'bigint' or an enum type.
// console.log(quantityText * 2);

// 여기서 규칙이 하나 보입니다.
//
//     + 만 특별하다.  - * / % 는 숫자 전용이라 바로 걸린다.
//
// 하필 사고가 제일 많이 나는 것이 + 입니다. 그래서 섹션 3이 필요합니다.

// ✏️ 직접 해보기 2 — quantityText / 3 을 써 보고 빨간 밑줄이 생기는지,
//    메시지가 섹션 2와 같은지 확인해 보세요. 확인 후 지우세요.


// ── 섹션 3: 담을 자리에 타입을 적으면 + 사고도 잡힌다 ──

// 타입을 적는 방법은 이름 뒤에 콜론( : )과 종류를 쓰는 것입니다.
const menuPrice: number = 4000;
//            └──────┘
//            이 부분이 새로 배우는 전부입니다.

console.log(menuPrice);
// 출력: 4000

// 이제 섹션 1의 그 줄을 number 자리에 담아 보겠습니다.
//
// 에러: TS2322 Type 'string' is not assignable to type 'number'.
// const wrongTotal: number = quantityText + shipping;
//
// 실수: 이제야 걸립니다.
//       "이 자리에는 숫자가 와야 하는데 문자열이 왔습니다" 라는 뜻입니다.
//
//       섹션 1에서는 왜 안 걸렸을까요?
//       그때는 결과를 어디에도 안 담고 그냥 출력만 했기 때문입니다.
//       타입스크립트는 "네가 원한 것이 무엇인지" 를 적어 줘야 비교할 수 있습니다.

// 이것이 타입을 적는 이유입니다.
//
//     타입은 '내가 기대하는 것' 을 코드에 적어 두는 일이고,
//     타입스크립트는 그 기대와 실제가 어긋날 때만 말해 줄 수 있다.
//
// 아무것도 안 적으면 아무것도 안 막아 줍니다.

// 물론 제대로 고치면 통과합니다.
const total: number = Number(quantityText) + shipping;
console.log(total);
// 출력: 3003


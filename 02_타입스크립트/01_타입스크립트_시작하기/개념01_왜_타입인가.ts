//    빨간 밑줄에 마우스를 올려 메시지를 읽어 보세요. 확인 후 지우세요.


// ── 섹션 4: 타입이 잡는 것과 못 잡는 것 ──

// [잡는 것 1] 값의 종류를 착각한 것 — 섹션 2, 3에서 봤습니다.

// [잡는 것 2] 이름 오타
const cafe = { name: "봄날카페", price: 4500 };
console.log(cafe.name);
// 출력: 봄날카페

// 에러: TS2551 Property 'pirce' does not exist on type '{ name: string; price: number; }'. Did you mean 'price'?
// console.log(cafe.pirce);
//
// 실수: JS 에서는 undefined 가 조용히 찍히던 자리입니다.
//       "혹시 price 를 쓰려던 것 아닌가요?" 까지 물어봐 줍니다.

// 다만 제안이 항상 나오지는 않습니다. 이름이 짧으면 후보를 못 고릅니다.
//
// 에러: TS2339 Property 'nmae' does not exist on type '{ name: string; price: number; }'.
// console.log(cafe.nmae);
//
// 실수: 같은 오타인데 이번엔 'Did you mean' 이 없습니다. 에러 번호도 다릅니다(TS2339).
//       name 은 네 글자뿐이라 nmae 와 너무 멀다고 판단한 것입니다.
//       "제안이 안 뜨네?" 하고 당황할 필요 없습니다. 없는 이름인 건 똑같습니다.

// [잡는 것 3] 있을 수도, 없을 수도 있는 값
const found = [10, 20, 30].find((n) => n > 100);
console.log(found);
// 출력: undefined
// find 는 못 찾으면 undefined 를 줍니다. JS 에서는 이걸 잊고 바로 쓰다가 터집니다.

// 에러: TS18048 'found' is possibly 'undefined'.
// console.log(found + 1);
//
// 실수: "없을 수도 있는데 그냥 쓰시려고요?" 라고 막아 줍니다.
//       이 상황을 다루는 방법은 05단원에서 배웁니다.

// ── 반대로, 타입이 못 잡는 것도 분명합니다 ──

// [못 잡는 것 1] 계산이 틀린 것
const applePrice: number = 1000;
const bananaPrice: number = 2000;
const fruitTotal: number = applePrice - bananaPrice; // 더해야 하는데 뺐습니다

console.log(fruitTotal);
// 출력: -1000
// 둘 다 number 라서 타입은 아무 말도 안 합니다. 완벽하게 통과합니다.
// 총액이 음수인 것은 타입의 관심사가 아닙니다.

// [못 잡는 것 2] 섹션 1의 + 사고 — 결과를 안 담으면 안 걸립니다.
// [못 잡는 것 3] 화면이 이상한 것, 글자가 겹치는 것 — 타입과 무관합니다.
// [못 잡는 것 4] 없는 데이터를 만들어 주지도 않습니다.
//                서버가 안 보내 준 값이 타입을 적는다고 생기지 않습니다.

// 정리하면 타입이 하는 일은 딱 한 가지입니다.
//
//     "이 자리에 들어올 수 있는 값의 종류" 를 미리 적어 두고,
//     어긋나면 실행하기 전에 알려 주는 것.

// ✏️ 직접 해보기 4 — fruitTotal 을 applePrice + bananaPrice 로 고치면
//    출력이 어떻게 바뀌는지, 타입 검사는 뭐라고 하는지 확인해 보세요.


// ── 섹션 5: 덤으로 따라오는 것 — 자동완성 ──

// 실제로 가장 크게 체감되는 이득은 이것입니다.
const order = { menu: "아메리카노", count: 2, isHot: true };

// VS Code 에서 order. 까지만 치면 menu / count / isHot 이 목록으로 뜹니다.
// 외우고 있을 필요가 없어집니다. 오타가 날 자리도 없어집니다.
console.log(order.menu, order.count, order.isHot);
// 출력: 아메리카노 2 true

// 남이 만든 함수를 쓸 때도 "이건 무엇을 받고 무엇을 돌려주는가" 가
// 마우스만 올리면 보입니다. 03단원에서 다시 다룹니다.

// ✏️ 직접 해보기 5 — order 에 마우스를 올려 보세요.

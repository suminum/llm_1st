// ── 틀린 곳 1: 숫자 자리에 문자열 ──

// 에러: TS2322 Type 'string' is not assignable to type 'number'.
const price: number = "4000";

console.log("가격:", price);
// 출력: 가격: 4000
// 따옴표가 붙은 "4000" 이 그대로 들어 있습니다. 숫자가 아닙니다.
// 그런데도 화면에는 4000 이라고 나옵니다. 눈으로는 구별이 안 됩니다.

console.log("정말 숫자인가:", typeof price);
// 출력: 정말 숫자인가: string
// typeof 로 찍어 봐야 비로소 문자열인 것이 드러납니다.
// : number 라고 적어 놓은 것이 무색합니다. node 는 그 표기를 지우고 실행하기 때문입니다.


// ── 틀린 곳 2: 없는 이름 ──

const cafe = { name: "봄날카페", price: 4500 };

// 에러: TS2551 Property 'pirce' does not exist on type '{ name: string; price: number; }'. Did you mean 'price'?
console.log("메뉴 가격:", cafe.pirce);
// 출력: 메뉴 가격: undefined
// 없는 이름을 읽으면 undefined 입니다. 에러가 아닙니다. 그냥 undefined 입니다.
// 이 값으로 계산을 하면 그때서야 NaN 이 되어 이상한 화면이 나옵니다.


// ── 틀린 곳 3: 없을 수도 있는 값을 그냥 쓰기 ──

const numbers = [10, 20, 30];
const big = numbers.find((n) => n > 100);

// 에러: TS18048 'big' is possibly 'undefined'.
console.log("100보다 큰 수 + 1 =", big + 1);
// 출력: 100보다 큰 수 + 1 = NaN
// undefined + 1 은 NaN 입니다. 이것도 에러가 아닙니다.
// 화면에 NaN 이 찍히고 나서야 뭔가 잘못됐다는 걸 알게 됩니다.


// ── 여기까지 정리 ──

console.log("---");

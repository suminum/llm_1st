//     지금 쓰는 것만 적는다. 나중에 더 쓰게 되면 그때 한 줄 더한다.
//
// 할인계산기.js 에는 함수가 둘, 상수가 하나 있습니다.
// 셋 다 쓰니까 셋 다 적었습니다. 만약 getShipping 을 안 쓴다면 안 적어도 됩니다.
//
// 판단 기준은 이렇습니다.
//
//   · 우리 코드가 부르는 것        →  적는다
//   · 그 함수가 돌려주는 값의 모양  →  적는다 (여기를 대충 적으면 섹션 5 사고가 납니다)
//   · 패키지 안에서만 쓰는 것       →  안 적는다
//
// 그리고 옮기기가 끝난 뒤에 @types 가 생겼는지 가끔 확인해 보세요.
// 생겼으면 손으로 적은 .d.ts 를 지우고 그쪽으로 갈아타는 편이 낫습니다.

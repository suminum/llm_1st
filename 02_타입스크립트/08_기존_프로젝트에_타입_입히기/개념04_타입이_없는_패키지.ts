// ── 섹션 8: node_modules 안의 패키지는 옆에 못 놓는다 ──

// 섹션 4의 방법에는 조건이 하나 붙어 있었습니다.
// 할인계산기.js 가 '내 폴더 안' 에 있어서 옆에 .d.ts 를 놓을 수 있었던 것입니다.
//
// 그런데 진짜 npm 패키지는 node_modules 안에 있습니다. 거기에 파일을 놓으면
//   · npm install 한 번에 지워지고
//   · git 에도 안 올라갑니다(node_modules 는 보통 제외합니다)
//
// 그래서 남의 패키지에는 섹션 4의 방법을 못 씁니다. declare module 을 씁니다.
// "이 이름으로 import 되는 것의 모양은 이렇다" 를 내 폴더에서 선언하는 것입니다.
//
//     // types/이상한계산기.d.ts    ← 파일 이름·위치는 자유. 내 프로젝트 안이면 됩니다
//     declare module "이상한계산기" {
//       export function 더하기(a: number, b: number): number;
//       export const 버전: string;
//     }
//
// 이 파일 하나만 있으면 아래가 통과합니다.
//
//     import { 더하기 } from "이상한계산기";
//     console.log(더하기(1, 2).toFixed(0));
//
// 섹션 1에서 본 TS7016 메시지가 사실 이 방법까지 같이 알려 주고 있었습니다.
// 뒷부분을 다시 읽어 보세요 — "or add a new declaration (.d.ts) file
// containing `declare module '...';`" 가 바로 이것입니다.
//
// 정리하면 갈림길은 하나입니다.
//
//     내 폴더 안의 .js        →  옆에 같은 이름의 .d.ts   (섹션 4)
//     node_modules 의 패키지  →  declare module "이름"     (여기)
//
// ★ 섹션 5의 위험이 여기에도 그대로 있습니다. 오히려 더 큽니다.
//   내 .js 는 열어서 확인이라도 하지만, 남의 패키지는 그러지 않게 되기 때문입니다.
//   declare module 은 '임시 처방' 입니다. @types 가 생기면 갈아타세요.

// ✏️ 직접 해보기 8 — 위 예제에서 export const 버전: string; 을
//    export const 버전: number; 로 바꿨다고 생각해 보세요.
//    버전.toFixed(1) 은 검사를 통과할까요? 실제 패키지가 "1.0" 을 준다면요?


// ── 섹션 9: 자주 하는 실수 ──

// [실수 1] .d.ts 에 실행되는 코드를 적기
//   선언 파일에는 모양만 적습니다. 함수 몸통 { } 을 적으면 안 됩니다.
//   declare 를 붙였는데 몸통을 적으면 바로 걸립니다.

// [실수 2] 파일 이름을 다르게 짓기
//   할인계산기.js 의 짝은 할인계산기.d.ts 입니다.
//   계산기.d.ts 라고 지으면 아무 일도 안 일어납니다. 조용히 TS7016 이 계속 납니다.

// [실수 3] 실제 .js 를 안 보고 짐작으로 적기
//   섹션 5입니다. 틀려도 조용하기 때문에 제일 위험합니다.
//   반드시 .js 를 열어서 무엇을 돌려주는지 확인하고 적으세요.

// [실수 4] as any 로 덮고 넘어가기
//   섹션 6입니다. 한 줄로 조용해지지만 그 모듈 전체를 포기하는 것입니다.

// [실수 5] @types 를 dependencies 에 넣기
//   타입은 실행할 때 사라집니다. -D 를 붙여 devDependencies 에 넣으세요.


// ── 정리 ──

// 1. 타입이 없는 모듈을 부르면 TS7016 이 난다. "모양을 적어 둔 파일이 없다" 는 뜻이다.
// 2. 순서는 셋이다. ① 패키지에 타입이 있나 ② @types 가 있나 ③ 없으면 내가 적는다.
// 3. @types 는 npm i -D @types/이름 으로 받는다. 이 자료의 @types/node 가 그것이다.
// 4. 직접 적을 때는 .d.ts 파일을 만든다. 짝은 파일 이름으로 맞춘다.
//    할인계산기.js 의 짝은 할인계산기.d.ts 다.
// 5. declare 는 "코드는 저쪽, 모양만 여기" 다. 함수 몸통을 적지 않는다.
// 6. .d.ts 는 내가 적는 약속이라 틀려도 조용하다. 실제 .js 를 보고 적어야 한다.
//    짐작으로 적은 타입은 as 와 다를 바가 없다.
// 7. 전부 적지 않는다. 지금 쓰는 것만 적고, 나중에 필요하면 한 줄 더한다.
// 8. 나중에 @types 가 생기면 손으로 적은 것을 지우고 갈아탄다.


// ============================================================
// 직접 해보기 정답
// ============================================================
//
// 1) 이름을 바꾸면 짝을 못 찾아서 이렇게 납니다.
//    error TS7016: Could not find a declaration file for module './타입없는_모듈/할인계산기.js'.
//    재현: 없음 — 파일을 지워야 재현되는 상황이라 조각 코드로 못 만듭니다.
//    되돌리면 다시 조용해집니다.
//    .d.ts 는 '있으면 붙고 없으면 안 붙는' 파일이라는 것이 눈으로 확인됩니다.
//
// 2) TS 딱지가 붙어 있습니다. zod 는 타입을 같이 넣어 보내는 패키지입니다.
//    그래서 npm i zod 만 하면 끝이고 @types/zod 같은 것은 없습니다.
//    (있는지 찾아보면 아예 존재하지 않습니다. 필요가 없으니까요)

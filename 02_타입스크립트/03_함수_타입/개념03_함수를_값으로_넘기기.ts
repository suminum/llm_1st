//
// JS자료 08단원에서 map · filter · forEach 를 배웠습니다.
// 그때 "함수를 값처럼 넘긴다" 는 것을 익혔습니다.
//
//     numbers.map(함수)
//                 └─ 이 자리에 함수가 들어간다
//
// 함수도 값이니 타입이 있습니다. 이 파일은 그 타입을 적는 법입니다.


// ── 섹션 1: 함수 타입은 화살표로 적는다 ──

// 지금까지 본 것 — 개념01의 add 는 이런 타입이었습니다.
function add(a: number, b: number) {
  return a + b;
}
console.log(add(3, 4));
// 출력: 7

//     (a: number, b: number) => number
//      └────── 받는 것 ─────┘    └ 주는 것
//
// 화살표 왼쪽이 매개변수, 오른쪽이 반환값입니다.
// 화살표 함수를 쓸 때의 모양과 비슷해서 외우기 쉽습니다.

// 이 표기를 변수에 쓸 수 있습니다.
const calc: (a: number, b: number) => number = add;
console.log(calc(10, 20));
// 출력: 30

// 다른 모양의 함수를 넣으면 걸립니다.
//
// 에러: TS2322 Type '(s: string) => string' is not assignable to type '(a: number, b: number) => number'.
// const wrong: (a: number, b: number) => number = (s: string) => s;
//
// 실수: 받는 것도 주는 것도 다릅니다.
//       함수끼리도 "모양이 맞는가" 를 검사합니다.

// ✏️ 직접 해보기 1 — 문자열 하나를 받아 숫자를 돌려주는 함수 타입을 적어 보세요.
//    (답의 모양: (◯◯: ◯◯) => ◯◯)


// ── 섹션 2: 콜백은 대개 안 적어도 된다 ──

// map 안에 넣는 함수의 매개변수에는 타입을 안 적어도 됩니다.
const prices = [4000, 4500, 5000];

const doubled = prices.map((p) => p * 2);
console.log(doubled);
// 출력: [ 8000, 9000, 10000 ]

// p 에 아무것도 안 적었는데 걸리지 않았습니다.
// 개념01에서 "매개변수는 무조건 적어야 한다" 고 했는데 왜 여기는 괜찮을까요?
//
//     prices 가 number[] 이므로,
//     map 이 하나씩 꺼내 주는 값은 number 일 수밖에 없기 때문입니다.
//
// 넘겨받을 쪽이 이미 정해져 있어서 알아낼 근거가 있는 것입니다.
// 이런 추론을 '문맥에서 알아낸다' 고 합니다.

// 그래서 p 를 잘못 쓰면 여전히 걸립니다.
//
// 에러: TS2339 Property 'toUpperCase' does not exist on type 'number'.
// const broken = prices.map((p) => p.toUpperCase());
//
// 실수: p 가 number 인 것을 알고 있으니 막습니다.
//       "안 적었으니 any 겠지" 가 아닙니다.

// filter 도 같습니다.
const expensive = prices.filter((p) => p >= 4500);
console.log(expensive);
// 출력: [ 4500, 5000 ]

// 문자열 배열이면 문자열로 알아냅니다.
const menus = ["아메리카노", "라떼"];
const lengths = menus.map((m) => m.length);
console.log(lengths);
// 출력: [ 5, 2 ]

// 규칙으로 정리하면 이렇습니다.
//
//     내가 만드는 함수의 매개변수   →  반드시 적는다
//     남의 함수에 넘기는 콜백       →  대개 안 적어도 된다

// ✏️ 직접 해보기 2 — menus 에서 글자 수가 3 이상인 것만 골라 출력해 보세요.


// ── 섹션 3: 콜백을 받는 함수를 직접 만들기 ──

// 이번엔 반대 입장입니다. 함수를 '받는' 함수를 만들어 봅니다.
function applyTwice(value: number, fn: (n: number) => number) {
  return fn(fn(value));
}

console.log(applyTwice(3, (n) => n * 2));
// 출력: 12
// 3 → 6 → 12 입니다.

console.log(applyTwice(3, (n) => n + 10));
// 출력: 23

// fn 의 타입을 적어 두었기 때문에,
// 넘기는 쪽에서 (n) => ... 의 n 을 안 적어도 됩니다. 섹션 2와 같은 이유입니다.

// 모양이 안 맞으면 넘기는 자리에서 걸립니다.
//
// 에러: TS2322 Type 'string' is not assignable to type 'number'.
// console.log(applyTwice(3, (n) => "결과 " + n));
//
// 실수: 숫자를 돌려주기로 한 자리에 문자열을 돌려주는 함수를 넘겼습니다.
//       에러가 넘기는 줄 전체가 아니라 "결과 " + n 부분을 콕 집어 나옵니다.
//       fn 의 모양을 미리 적어 둔 덕분에 화살표 안쪽까지 검사한 것입니다.

// 아무것도 안 돌려주는 콜백은 void 로 적습니다.
function repeat(times: number, action: (i: number) => void) {
  for (let i = 1; i <= times; i++) {
    action(i);
  }
}

repeat(3, (i) => console.log("반복", i));
// 출력: 반복 1
// 출력: 반복 2
// 출력: 반복 3

// ✏️ 직접 해보기 3 — 숫자 배열과 함수를 받아,
//    각 값에 그 함수를 적용한 결과를 출력하는 함수를 만들어 보세요.
//    (map 을 써도 되고 for 를 써도 됩니다)


// ── 섹션 4: 같은 함수 타입을 여러 번 쓸 때 ──

// 함수 타입 표기는 길어서 여러 번 쓰면 지저분해집니다.
function runA(fn: (a: number, b: number) => number) {
  return fn(1, 2);
}
function runB(fn: (a: number, b: number) => number) {
  return fn(10, 20);
}

console.log(runA(add), runB(add));
// 출력: 3 30

// (a: number, b: number) => number 를 두 번 적었습니다.
// 세 번, 네 번 나오면 고칠 때마다 전부 찾아 고쳐야 합니다.
//
// 이럴 때 타입에 이름을 붙일 수 있습니다. 04단원에서 배웁니다.
// 미리 모양만 보면 이렇습니다.
//
//     type Calc = (a: number, b: number) => number;
//     function runA(fn: Calc) { ... }
//
// 지금은 "길어지면 이름을 붙일 수 있구나" 정도만 알아 두세요.

// ✏️ 직접 해보기 4 — runA 와 runB 에 (n) => n * 100 을 넘겨 보세요.
//    걸리나요? 왜 그럴까요?


// ── 섹션 5: 자주 하는 실수 ──

// [실수 1] 함수 타입에 콜론을 쓰기
//   (a: number, b: number): number 는 함수를 '정의' 할 때의 모양입니다.
//   함수 '타입' 을 적을 때는 => 를 씁니다. 이 둘을 자주 헷갈립니다.

// [실수 2] 콜백 매개변수에 굳이 타입을 적기
//   prices.map((p: number) => p * 2) 도 되기는 합니다.
//   틀린 건 아니지만 길어지기만 합니다. 문맥에서 알아내니 맡기세요.

// [실수 3] 함수를 넘겨야 하는데 호출한 결과를 넘기기
//   applyTwice(3, double(2)) 처럼 괄호를 붙이면 함수가 아니라 값이 넘어갑니다.
//   JS자료 11단원에서 본 onclick = handler 와 onclick = handler() 의 차이입니다.

// [실수 4] 반환 타입이 void 인 콜백에서 값을 돌려주기
//   막지는 않습니다. 그냥 무시됩니다. void 는 "돌려줘도 안 쓴다" 에 가깝습니다.


// ── 정리 ──

// 1. 함수 타입은 (매개변수) => 반환값 으로 적는다. 화살표 왼쪽이 받는 것.
// 2. 함수끼리도 모양이 맞는지 검사한다. 매개변수와 반환값 둘 다 본다.
// 3. map · filter 같은 곳에 넘기는 콜백의 매개변수는 안 적어도 된다.
//    넘겨받을 쪽이 정해져 있어서 문맥에서 알아낸다.
// 4. 그래도 검사는 그대로 한다. 콜백 안에서 잘못 쓰면 걸린다.
// 5. 콜백을 받는 함수를 만들 때는 그 자리에 함수 타입을 적어 준다.
// 6. 아무것도 안 돌려주는 콜백은 => void 로 적는다.


// ============================================================
// 직접 해보기 정답
// ============================================================
//
// 1) (s: string) => number
//    이름(s)은 아무거나 써도 됩니다. 중요한 것은 종류와 순서입니다.
//    예: const len: (s: string) => number = (t) => t.length;
//
// 2) console.log(menus.filter((m) => m.length >= 3));   // 출력: [ '아메리카노' ]
//    '라떼' 는 2글자라 빠집니다.
//
// 3) function applyAll(values: number[], fn: (n: number) => number) {
//      console.log(values.map(fn));
//    }
//    applyAll([1, 2, 3], (n) => n * 10);      // 출력: [ 10, 20, 30 ]
//    map 에 fn 을 그대로 넘긴 것에 주목하세요. (n) => fn(n) 이라고 쓸 필요가 없습니다.
//
// 4) 걸리지 않습니다. 그냥 됩니다.
//    console.log(runA((n) => n * 100), runB((n) => n * 100));   // 출력: 100 1000
//
//    두 개짜리 함수를 받기로 한 자리에 한 개짜리를 넘겼는데도 통과합니다.
//    두 번째 값을 그냥 안 쓸 뿐이니 문제가 될 게 없기 때문입니다.
//    runA 는 fn(1, 2) 를 부르고, n 은 첫 번째 값 1 만 받아서 100 이 됩니다.
//
//    JS자료 08단원에서 arr.map((x) => x) 처럼 index 를 안 받고 써도 됐던
//    이유가 이것입니다. map 은 값·인덱스·배열 셋을 넘기지만 안 받으면 그만입니다.
//
//    반대로 '종류' 가 다르면 걸립니다. (s: string) => number 를 넘겨 보세요.
//    개수가 모자란 것은 봐주고, 종류가 다른 것은 안 봐줍니다(04단원 개념02 섹션3).

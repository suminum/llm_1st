// ── 섹션 1: 가장 기본 형태 ──

const age = 22;

if (age >= 19) {
  console.log("성인입니다");
}
// 출력: 성인입니다

// 조건이 false 면 중괄호 안이 통째로 건너뛰어집니다.
const age2 = 15;

if (age2 >= 19) {
  console.log("이 줄은 실행되지 않습니다");
}
// (아무것도 출력되지 않습니다)

// if 가 끝난 다음 줄은 조건과 상관없이 실행됩니다.
console.log("검사 끝");
// 출력: 검사 끝

// ✏️ 직접 해보기 1 — 점수가 90점 이상이면 "우수" 를 출력하는 if 문을 써 보세요. (점수는 95)


// ── 섹션 2: 중괄호와 들여쓰기 ──

// 중괄호 { } 는 "여기서부터 여기까지가 한 덩어리"라는 표시입니다.
// 안에 여러 줄을 넣을 수 있습니다.

const stock = 0;

if (stock === 0) {
  console.log("품절되었습니다");
  console.log("재입고를 기다려 주세요");
  console.log("알림 신청이 가능합니다");
}
// 출력: 품절되었습니다
// 출력: 재입고를 기다려 주세요
// 출력: 알림 신청이 가능합니다

// 중괄호 안의 코드는 스페이스 두 칸(또는 탭)만큼 들여씁니다.
// 들여쓰기는 컴퓨터에겐 상관없지만 사람에게는 아주 중요합니다.
// "어디까지가 if 안인지"를 눈으로 보여 주기 때문입니다.

// 실행할 줄이 하나면 중괄호를 생략할 수도 있습니다.
if (stock === 0) console.log("품절");
// 출력: 품절

// 하지만 생략하지 마세요. 나중에 줄을 하나 추가할 때 사고가 납니다.
// (섹션 5 실수 1에서 확인합니다)

// ✏️ 직접 해보기 2 — 잔액이 0이면 "잔액이 부족합니다" 와 "충전해 주세요" 를
//                    두 줄로 출력하는 if 문을 써 보세요. (잔액은 0)


// ── 섹션 3: 조건 자리에 들어갈 수 있는 것 ──

// if 의 괄호 안에는 true / false 가 나오는 식이면 뭐든 들어갑니다.

// [비교식]
const temperature = 31;
if (temperature > 30) {
  console.log("폭염 주의보");
}
// 출력: 폭염 주의보

// [논리식]
const isMember = true;
const totalPrice = 60000;
if (isMember && totalPrice >= 50000) {
  console.log("무료 배송");
}
// 출력: 무료 배송

// [불리언 변수 그대로]
const isLoggedIn = true;
if (isLoggedIn) {
  console.log("환영합니다");
}
// 출력: 환영합니다

// isLoggedIn === true 라고 써도 되지만 굳이 그럴 필요 없습니다.
// 이미 true / false 인 값이니까요.

// ✏️ 직접 해보기 3 — isOpen 이 true 일 때 "영업 중" 을 출력해 보세요.


// ── 섹션 4: 조건에 불리언이 아닌 값이 오면 ──

// 조건 자리에 숫자나 문자열을 넣으면 자동으로 true/false 로 바뀝니다.
// 01단원에서 배운 falsy 6개(0, "", null, undefined, NaN, false)면 false,
// 나머지는 전부 true 입니다.

const userName = "김민준";
if (userName) {
  console.log("이름이 있습니다");
}
// 출력: 이름이 있습니다

const emptyName = "";
if (emptyName) {
  console.log("이 줄은 실행되지 않습니다");
}
// (빈 문자열은 falsy 라서 건너뜁니다)

// 이 성질을 이용해 "값이 비었는지" 를 짧게 검사합니다.
const memo = null;
if (!memo) {
  console.log("메모가 없습니다");
}
// 출력: 메모가 없습니다

// [주의] 숫자 0 도 falsy 입니다.
const count = 0;
if (count) {
  console.log("이 줄은 실행되지 않습니다");
}
// 재고가 진짜 0개일 때도 "값이 없다"로 취급되어 버립니다.
// 숫자를 검사할 때는 뜻을 분명히 쓰세요.
if (count === 0) {
  console.log("재고가 0개입니다");
}
// 출력: 재고가 0개입니다


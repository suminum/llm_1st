console.log("이 줄은 if 와 상관없이 항상 실행됩니다");
// 출력: 이 줄은 if 와 상관없이 항상 실행됩니다
// 실수: 들여쓰기를 해 놔도 소용없습니다. 중괄호가 없으면 if 는 바로 다음
//       한 줄에만 걸립니다. 그래서 중괄호는 항상 쓰는 게 안전합니다.

// [실수 2] = 와 === 혼동
let level = 1;
// if (level = 5) { ... }
// 실수: level 에 5를 넣어 버리고, 5는 truthy 라서 항상 실행됩니다.
//       비교는 === 입니다.
if (level === 5) {
  console.log("레벨 5");
}
// (level 은 1이라 실행되지 않습니다)
console.log(level);
// 출력: 1

// [실수 3] if 뒤에 세미콜론 붙이기
const price = 100;
if (price > 1000); // ← 여기 세미콜론
{
  console.log("이 줄은 조건과 상관없이 실행됩니다");
}
// 출력: 이 줄은 조건과 상관없이 실행됩니다
// 실수: 세미콜론이 "if 문 끝"이 되어 버려서, 아래 중괄호는
//       if 와 무관한 그냥 덩어리가 됩니다. if 뒤에 세미콜론을 찍지 마세요.

// [실수 4] 범위를 수학처럼 쓰기 (02단원에서 배웠죠)
const score = 100;
if (10 < score < 30) {
  console.log("범위 안이라고 잘못 판단합니다");
}
// 출력: 범위 안이라고 잘못 판단합니다
// 실수: 100은 30보다 큰데도 실행됩니다.
//       score > 10 && score < 30 이라고 써야 합니다.



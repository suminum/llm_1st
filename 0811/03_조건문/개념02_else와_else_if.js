// ── 섹션 4: if 를 여러 개 쓰는 것과 else if 의 차이 ──

// 이 둘은 완전히 다릅니다. 아주 헷갈리는 지점입니다.

const point = 95;

// [else if — 하나만 실행]
if (point >= 90) {
  console.log("else if: 90점 이상");
} else if (point >= 80) {
  console.log("else if: 80점 이상");
}
// 출력: else if: 90점 이상

// [if 여러 개 — 맞는 것마다 전부 실행]
if (point >= 90) {
  console.log("if: 90점 이상");
}
if (point >= 80) {
  console.log("if: 80점 이상");
}
// 출력: if: 90점 이상
// 출력: if: 80점 이상

// 언제 무엇을 쓰나?
//   등급처럼 '하나만 골라야' 하면        → else if
//   조건마다 '따로따로 처리'해야 하면    → if 여러 개
//
// 예를 들어 "90점 이상이면 상장, 개근이면 개근상"은 서로 무관하므로 if 를 따로 씁니다.


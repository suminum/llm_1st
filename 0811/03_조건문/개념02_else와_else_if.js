// ── 섹션 1: else — 아니면 ──

const age = 15;

if (age >= 19) {
  console.log("성인입니다");
} else {
  console.log("미성년자입니다");
}
// 출력: 미성년자입니다

// if 와 else 중 하나는 반드시 실행됩니다. 둘 다 실행되는 일은 없습니다.

// else 에는 조건을 쓰지 않습니다. "나머지 전부"라는 뜻이니까요.
// } else (age < 19) {   ← 이렇게 쓰면 SyntaxError

const stock = 5;
if (stock > 0) {
  console.log("구매 가능");
} else {
  console.log("품절");
}
// 출력: 구매 가능

// ✏️ 직접 해보기 1 — 점수가 60점 이상이면 "합격", 아니면 "불합격" 을 출력해 보세요. (55점)


// ── 섹션 2: else if — 갈림길이 셋 이상일 때 ──

// else if 를 쓰면 조건을 여러 개 늘어놓을 수 있습니다.

const score = 85;

if (score >= 90) {
  console.log("A 등급");
} else if (score >= 80) {
  console.log("B 등급");
} else if (score >= 70) {
  console.log("C 등급");
} else {
  console.log("F 등급");
}
// 출력: B 등급

// 동작 방식이 중요합니다.
//   위에서부터 하나씩 검사합니다.
//   처음으로 true 가 되는 곳을 실행하고, 나머지는 전부 건너뜁니다.
//   그래서 85점은 "B 등급"만 출력되고 "C 등급"은 나오지 않습니다.

// 마지막 else 는 생략할 수 있습니다. 그러면 아무것도 안 맞을 때 그냥 넘어갑니다.
const temp = 15;
if (temp >= 28) {
  console.log("덥다");
} else if (temp <= 5) {
  console.log("춥다");
}
// (15도는 어느 조건에도 안 맞아서 아무것도 출력되지 않습니다)

console.log("판정 끝");
// 출력: 판정 끝

// ✏️ 직접 해보기 2 — 나이로 "어린이(13 미만) / 청소년(19 미만) / 성인" 을
//                    구분해 출력해 보세요. (나이는 16)


// ── 섹션 3: 순서가 결과를 바꾼다 ──

// else if 는 위에서부터 검사하므로 순서를 잘못 쓰면 틀립니다.

// [틀린 순서]
const score2 = 95;

if (score2 >= 70) {
  console.log("C 등급"); // 95점인데 여기서 걸려 버립니다
} else if (score2 >= 80) {
  console.log("B 등급");
} else if (score2 >= 90) {
  console.log("A 등급");
}
// 출력: C 등급
// 95는 70 이상이기도 하므로 첫 조건에서 걸리고 끝나 버립니다.

// [맞는 순서] 좁은 조건(큰 수)부터 씁니다.
if (score2 >= 90) {
  console.log("A 등급");
} else if (score2 >= 80) {
  console.log("B 등급");
} else if (score2 >= 70) {
  console.log("C 등급");
}
// 출력: A 등급

// 규칙: 범위를 나눌 때는 조건을 '한 방향으로' 정렬하세요.
//       큰 수에서 작은 수로 내려오거나, 작은 수에서 큰 수로 올라가거나
//       한 방향으로 정렬하면 됩니다.

// ✏️ 직접 해보기 3 — 배송비를 정해 출력해 보세요. (금액 30000)

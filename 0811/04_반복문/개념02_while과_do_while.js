// for 는 "몇 번 반복할지 아는" 경우에 좋습니다.
// while 은 "언제 끝날지 모르지만 조건이 맞는 동안" 반복할 때 씁니다.
//
//     while (조건) {
//        반복할 코드
//     }


// ── 섹션 1: while 기본 ──

let i = 1;

while (i <= 3) {
  console.log("while:", i);
  i++; // ← 이걸 빠뜨리면 무한 루프입니다
}
// 출력: while: 1
// 출력: while: 2
// 출력: while: 3

// for 와 비교하면 세 부분이 흩어져 있을 뿐 하는 일은 같습니다.
//
//   for   : for (let i = 1;  i <= 3;  i++) { ... }
//                  ^시작값    ^조건    ^증감
//
//   while : let i = 1;             ← 시작값은 밖에서
//           while (i <= 3) {       ← 조건만 괄호 안에
//             ...
//             i++;                 ← 증감은 안에서 직접
//           }
//
// 그래서 while 은 증감을 깜빡하기 쉽습니다. 이게 가장 흔한 사고입니다.

// ✏️ 직접 해보기 1 — while 로 1부터 5까지 출력해 보세요.


// ── 섹션 2: 언제 for 를 쓰고 언제 while 을 쓸까 ──

// [횟수를 안다] → for
for (let n = 1; n <= 3; n++) {
  console.log("3번 반복:", n);
}
// 출력: 3번 반복: 1
// 출력: 3번 반복: 2
// 출력: 3번 반복: 3

// [횟수를 모른다] → while
// 예: "잔액이 0보다 큰 동안 1000원씩 빼기"
let balance = 3500;
let usedCount = 0;

while (balance >= 1000) {
  balance -= 1000;
  usedCount++;
  console.log(`${usedCount}번 사용, 남은 잔액 ${balance}원`);
}
// 출력: 1번 사용, 남은 잔액 2500원
// 출력: 2번 사용, 남은 잔액 1500원
// 출력: 3번 사용, 남은 잔액 500원

console.log("최종 잔액:", balance);
// 출력: 최종 잔액: 500

// 3500원으로 몇 번 쓸 수 있는지 미리 세지 않아도 됩니다.
// "조건이 안 맞을 때까지" 알아서 돕니다.

// ✏️ 직접 해보기 2 — 10000원에서 3000원씩 빼면서 남은 돈을 출력해 보세요.


// ── 섹션 3: 조건이 처음부터 false 면 한 번도 안 돈다 ──

let count = 10;

while (count < 5) {
  console.log("이 줄은 실행되지 않습니다");
  count++;
}
// (10 < 5 가 처음부터 false 라 한 번도 실행되지 않습니다)

console.log("반복 끝, count =", count);
// 출력: 반복 끝, count = 10


// ── 섹션 4: do...while — 일단 한 번은 실행 ──

// do...while 은 조건 검사를 '나중에' 합니다.
// 그래서 조건이 false 여도 최소 한 번은 실행됩니다.

let j = 10;

do {
  console.log("do...while 은 일단 한 번 실행됩니다. j =", j);
  j++;
} while (j < 5);
// 출력: do...while 은 일단 한 번 실행됩니다. j = 10

// 마지막 while 뒤에 세미콜론이 붙는다는 점에 주의하세요.

// 같은 조건을 while 로 쓰면 아예 실행되지 않습니다.
let k = 10;
while (k < 5) {
  console.log("이 줄은 실행되지 않습니다");
  k++;
}

// 정상 동작도 봅시다.
let m = 1;
do {
  console.log("do...while 반복:", m);
  m++;
} while (m <= 3);
// 출력: do...while 반복: 1
// 출력: do...while 반복: 2
// 출력: do...while 반복: 3

// do...while 은 "입력을 일단 한 번 받고, 잘못됐으면 다시 받기" 같은 데 씁니다.
// 실무에서 자주 쓰이지는 않습니다. "이런 게 있다" 정도로 알아 두세요.

// ✏️ 직접 해보기 3 — do...while 로 1부터 3까지 출력해 보세요.


// ── 섹션 5: 무한 루프 ──

// while 에서 가장 흔한 사고입니다. 증감을 빠뜨리면 영원히 돕니다.
//
//   let n = 1;
//   while (n <= 3) {
//     console.log(n);      ← n 이 영원히 1
//   }
//
// 이러면 터미널이 멈추지 않습니다. Ctrl + C 를 눌러 강제 종료하세요.

// 안전장치를 두는 방법도 있습니다. 최대 횟수를 정해 두는 것입니다.
let tries = 0;
let found = false;

while (!found) {
  tries++;
  console.log(`${tries}번째 시도`);

  if (tries >= 3) {
    found = true; // 조건을 바꿔서 빠져나갑니다
  }
}
// 출력: 1번째 시도
// 출력: 2번째 시도
// 출력: 3번째 시도

console.log("총 시도 횟수:", tries);
// 출력: 총 시도 횟수: 3

// while (true) 로 두고 안에서 빠져나오는 방법은 다음 파일(개념03 break)에서 배웁니다.

// ✏️ 직접 해보기 4 — 위 코드를 5번 시도 후 멈추도록 고쳐 보세요.


// ── 섹션 6: 자주 하는 실수 ──

// [실수 1] 증감 빠뜨리기 → 무한 루프 (섹션 5)

// [실수 2] 시작값을 while 안에서 만들기
// while (x < 3) { let x = 0; ... }
// 실수: ReferenceError: x is not defined
//       let x 는 while 의 중괄호 안에서만 살기 때문에 조건식에서는 아예 보이지 않습니다.
//       시작값은 반드시 while 밖에서 만듭니다. (이 규칙은 05단원 개념06에서 자세히)

// [실수 3] while 뒤에 세미콜론
let p = 0;
// while (p < 3);
// { p++; }
// 실수: 세미콜론이 "반복할 내용"이 되어 아무것도 안 하며 영원히 돕니다.
//       do...while 은 세미콜론이 필요하지만, while 은 필요 없습니다.
console.log("p =", p);
// 출력: p = 0

// [실수 4] 조건이 절대 false 가 되지 않게 만들기
// let q = 1;
// while (q !== 10) { q += 3; }
// 실수: 1, 4, 7, 10 ... 이 경우엔 우연히 맞지만
//       q += 4 였다면 1, 5, 9, 13 으로 10을 건너뛰어 무한 루프입니다.
//       !== 보다 < 나 >= 같은 범위 조건이 안전합니다.


// ── 정리 ──

// 1. while (조건) { ... } — 조건이 true 인 동안 반복
// 2. 시작값은 밖에서, 증감은 안에서 직접. 증감을 빠뜨리면 무한 루프.
// 3. 횟수를 알면 for, 모르면 while.
// 4. do { ... } while (조건); — 조건이 false 여도 최소 한 번 실행
// 5. 무한 루프에 걸리면 터미널에서 Ctrl + C



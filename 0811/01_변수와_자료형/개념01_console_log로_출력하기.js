// 실행: node 개념01_console_log로_출력하기.js
// ============================================================
//
// 프로그래밍의 첫걸음은 "컴퓨터가 한 일을 눈으로 확인하는 것"입니다.
// console.log( ) 는 괄호 안의 것을 화면에 보여 달라는 명령입니다.
//
//     console.log( "안녕" );
//     └─────┬────┘ └──┬─┘ └ 문장이 끝났다는 표시(세미콜론)
//        명령 이름   보여줄 것
//
// 이 파일을 실행하면 아래 결과들이 위에서부터 차례로 찍힙니다.


// ── 섹션 1: 글자 출력하기 ──

// 글자(문자)는 반드시 따옴표로 감쌉니다.
console.log("안녕하세요");
// 출력: 안녕하세요

// 큰따옴표 " " 든 작은따옴표 ' ' 든 상관없습니다. 짝만 맞으면 됩니다.
console.log('오늘도 좋은 하루');
// 출력: 오늘도 좋은 하루

// console.log 를 여러 번 쓰면 한 줄씩 차례로 찍힙니다.
console.log("첫 번째 줄");
console.log("두 번째 줄");
// 출력: 첫 번째 줄
// 출력: 두 번째 줄

// ✏️ 직접 해보기 1 — 자기 이름을 출력해 보세요. (정답은 파일 맨 아래)


// ── 섹션 2: 숫자 출력하기 ──

// 숫자는 따옴표 없이 그냥 씁니다.
console.log(1200);
// 출력: 1200

// 따옴표를 씌우면 "숫자 모양의 글자"가 됩니다. 화면에는 똑같아 보이지만
// 컴퓨터는 둘을 다르게 봅니다. (자세한 차이는 개념03에서 배웁니다)
console.log("1200");
// 출력: 1200

// 계산식을 넣으면 계산 결과가 찍힙니다.
console.log(1200 + 800);
// 출력: 2000

// ✏️ 직접 해보기 2 — 삼각김밥 1200원 두 개의 값을 계산해서 출력해 보세요.


// ── 섹션 3: 한 번에 여러 개 출력하기 ──

// 쉼표( , )로 나열하면 한 줄에 띄어쓰기로 이어서 찍힙니다.
console.log("삼각김밥", 1200, "원");
// 출력: 삼각김밥 1200 원

// 글자와 숫자를 섞어도 됩니다.
console.log("총", 3, "개 구매");
// 출력: 총 3 개 구매

// ✏️ 직접 해보기 3 — "라떼" 4500 "원" 을 한 줄에 출력해 보세요.


// ── 섹션 4: 주석 — 컴퓨터가 무시하는 글 ──

// 줄 앞에 // 를 붙이면 그 줄은 실행되지 않습니다. 이것을 '주석'이라고 합니다.
// console.log("이 줄은 실행되지 않습니다");

// 여러 줄을 한꺼번에 주석 처리할 때는 /* 로 열고 */ 로 닫습니다.
/*
console.log("이것도");
console.log("실행되지 않습니다");
*/

// 코드 뒤에 붙일 수도 있습니다.
console.log("실행됩니다"); // ← 이 뒤부터는 설명글
// 출력: 실행됩니다

// 주석은 남에게 남기는 메모이자, 미래의 나에게 남기는 메모입니다.
// 이 자료의 설명도 전부 주석으로 쓰여 있습니다.


// ── 섹션 5: 자주 하는 실수 ──

// ★ 아래에서 SyntaxError 라고 적힌 것은 눈으로만 보세요. 주석을 풀지 마세요.
//   다른 에러(ReferenceError, TypeError)는 주석을 풀어도
//   그 줄에서만 나고 그 앞의 출력은 그대로 다 나옵니다.
//   그런데 SyntaxError 는 다릅니다. 자바스크립트가 파일을 아예 못 읽어서
//   출력이 한 줄도 안 나옵니다. 여러분이 망가뜨린 것이 아닙니다.
//   실수로 풀었다면 다시 // 를 붙이면 그대로 돌아옵니다.

// 아래 코드들은 전부 주석 처리해 두었습니다.
// 하나씩 주석을 풀고 실행해서 "어떤 에러가 나는지" 눈으로 본 다음,
// 다시 주석 처리하세요. 에러 메시지를 읽는 연습이 실력입니다.

// [실수 1] 따옴표를 빠뜨림 → ReferenceError
// console.log(안녕하세요);
// 실수: 따옴표가 없으면 컴퓨터는 '안녕하세요'라는 이름의 변수를 찾습니다.
//       그런 이름이 없으니 ReferenceError: 안녕하세요 is not defined

// [실수 2] 따옴표 짝이 안 맞음 → SyntaxError
// console.log("안녕하세요');
// 실수: 큰따옴표로 열었으면 큰따옴표로 닫아야 합니다.

// [실수 3] 이름 오타 → TypeError
// console.Log("안녕");
// 실수: 대문자 L 이 아니라 소문자 l 입니다. console.log 는 전부 소문자.

// [실수 4] 괄호를 안 닫음 → SyntaxError
// console.log("안녕";
// 실수: 여는 괄호 ( 하나에 닫는 괄호 ) 하나가 짝을 이뤄야 합니다.


// ── 정리 ──

// 1. console.log(내용);  →  내용을 화면에 출력
// 2. 글자는 따옴표로 감싼다.  숫자는 따옴표 없이 쓴다.
// 3. 쉼표로 나열하면 한 줄에 여러 개를 출력한다.
// 4. // 뒤는 주석. 컴퓨터가 무시한다.



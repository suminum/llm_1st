// ============================================================
// 개념 04 — RLS (행 수준 보안)
// ============================================================
//
// 이상한 이야기부터 시작합니다.
//
//   Supabase 의 anon key 는 **브라우저에 그대로 넣습니다.**
//   깃허브에 올라가도 됩니다. 누구나 볼 수 있습니다.
//
// 비밀번호를 공개하는 셈인데 왜 괜찮을까요?
// RLS 때문입니다. 이 단원에서 그걸 **진짜 프로젝트에 붙여서** 봅니다.
//
// ★★★ 이 단원은 이 자료에서 가장 위험한 부분입니다.
//   RLS 를 안 켜면 **아무나 자료를 다 읽고 지울 수 있습니다.**
//   실제로 그렇게 털린 사고가 많습니다. 끝까지 읽으세요.
//
// ── 돌리기 전에 ──
//
//   1) .env 에 SUPABASE_URL 과 SUPABASE_ANON_KEY 가 있어야 합니다  (설정.js)
//   2) SQL Editor 에 준비.sql 을 붙여 넣고 Run 하세요
//   3) Authentication → Sign In / Providers → Email 에서
//      **Confirm email 을 꺼 두세요.** 안 끄면 이 파일이 거기서 멈춥니다.
//   4) 인터넷이 필요합니다. 진짜 Supabase 프로젝트에 붙습니다.
//
// ★★ 5) 이 파일은 **중간에 SQL Editor 를 세 번 오갑니다.**
//
//   정책은 코드로 걸 수 없습니다. anon key 로는 create policy 가 안 됩니다.
//   DDL 은 자료를 다루는 권한이 아니라 표 자체를 바꾸는 권한이니까요.
//   그래서 이렇게 갑니다.
//
//     돌린다 → "★ 여기서 멈추고 아래 SQL 을 치고 오세요" → 치고 온다 → 다시 돌린다
//
//   세 번 반복하면 끝입니다. 관문 ① ② ③ ④ 로 표시해 뒀습니다.
//
// ★ 그래서 이 파일은 **돌릴 때마다 출력이 달라집니다.**
//   정책을 얼마나 걸었느냐에 따라 다른 장면이 나옵니다.
//   아래 `// 출력:` 은 "그 장면에 이르렀을 때" 나오는 것입니다.
//
// ★ 돌릴 때마다 회원 세 명을 새로 만듭니다.
//   Authentication → Users 에 실습 계정이 쌓입니다. 가끔 들어가서 지우세요.
//
// 실행: node 개념04_RLS_행_수준_보안.js
// ============================================================

// 이파일은Supabase가필요합니다

const { createClient } = require("@supabase/supabase-js");
const 설정 = require("./설정");

// ★★ 사람마다 클라이언트를 **따로** 만듭니다.
//
//   supabase-js 는 클라이언트 하나에 로그인 세션 하나를 들고 있습니다.
//   하나로 세 번 로그인하면 마지막 사람만 남습니다. 그러면 비교를 못 합니다.
//
//   persistSession: false 를 준 이유도 같습니다.
//   세션을 파일이나 브라우저 저장소에 남기면 다음 실행에 섞입니다.
//   여기서는 메모리에만 두고, 프로그램이 끝나면 사라지게 합니다.

function 새클라이언트() {
  return createClient(설정.SUPABASE_URL, 설정.SUPABASE_ANON_KEY, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
}



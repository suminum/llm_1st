// ============================================================
// 2. RLS 를 "켜기만" 하면 안전한가
// ============================================================
//
// 준비.sql 은 세 표에 전부 RLS 를 켰습니다.
//
//   alter table products enable row level security;
//   alter table reviews  enable row level security;
//   alter table memos    enable row level security;
//
// 그런데 products 에는 이런 정책을 같이 걸었습니다.
//
//   create policy "수업용 전체 허용" on products for all using (true) with check (true);
//
// 켜 놓고 전부 열어 둔 것입니다. 무슨 일이 생기는지 **직접 봅시다.**

async function 켜기만하면() {
  // 로그인을 안 합니다. anon key 만 든 손님입니다.
  const 손님 = 새클라이언트();

  const 상품 = await 손님.from("products").select("id, name, price").order("id");

  console.log("로그인도 안 했는데 보이는 상품:", 상품.data.length, "건");
  // 출력?: 로그인도 안 했는데 보이는 상품: 3 건
  console.log("가격도 보이나:", JSON.stringify(상품.data[0]));
  // 출력?: 가격도 보이나: {"id":1,"name":"USB 허브","price":23900}

  // 읽기만 되는 게 아닙니다. 쓰기도 됩니다.
  const 이름 = `털림확인-${Date.now()}`;

  const 넣기 = await 손님.from("products").insert({ name: 이름, category: "A" });
  console.log("로그인 안 한 사람이 상품을 넣을 수 있나:", 넣기.error ? "막힘" : "됨");
  // 출력: 로그인 안 한 사람이 상품을 넣을 수 있나: 됨

  const 지우기 = await 손님.from("products").delete().eq("name", 이름).select("id");
  console.log("넣은 것을 지울 수도 있나:", (지우기.data ?? []).length > 0 ? "됨" : "막힘");
  // 출력: 넣은 것을 지울 수도 있나: 됨

  // ★★★ "RLS 를 켰다" 와 "안전하다" 는 다른 말입니다.
  //
  //   using (true) 는 "모든 줄을 보여 줘라" 입니다.
  //   with check (true) 는 "어떤 줄이든 넣게 해라" 입니다.
  //   켠 것과 안 켠 것이 똑같아집니다.
  //
  //   ★ 준비.sql 이 일부러 이렇게 해 뒀습니다. 수업을 진행해야 하니까요.
  //     실제 서비스라면 이건 사고입니다.
  //     개념05 의 연습문제에서 이 정책을 제대로 조입니다.
  //
  // ★★★ 이게 실제로 일어나는 사고입니다.
  //
  //   앱을 만들어 배포합니다. 화면에는 내 것만 보이게 잘 짜 뒀습니다.
  //   그런데 브라우저 개발자 도구를 열면 anon key 가 보입니다.
  //   그 키로 직접 요청을 보내면 **전부** 나옵니다.
  //
  //     curl "https://xxxx.supabase.co/rest/v1/products?select=*" \
  //          -H "apikey: eyJ..."
  //
  //   화면에서 걸러 봐야 소용없습니다. 화면은 요청 결과를 보여 줄 뿐입니다.
  //   막는 것은 DB 쪽에서 해야 합니다.
  //
  // ★ 이게 SQLite 와 결정적으로 다른 점입니다.
  //
  //   SQLite   DB 는 서버 안에 있습니다. 내 API 를 거쳐야만 닿습니다.
  //            그래서 API 에서 권한을 확인하면 됐습니다.
  //
  //   Supabase DB 가 인터넷에 열려 있습니다.
  //            내 API 를 안 거치고 직접 부를 수 있습니다.
  //            그래서 **DB 자체가 스스로를 지켜야** 합니다.
  //
  // 이제 memos 로 갑니다. 이쪽은 정책을 하나도 안 걸어 뒀습니다.
}


// ============================================================
// 3. 회원 세 명을 코드로 만듭니다
// ============================================================
//
// RLS 의 핵심은 auth.uid() 입니다. "지금 요청을 보낸 사람의 id" 입니다.
// 그러니 **사람이 여럿 있어야** 이 단원을 볼 수 있습니다.
//
// ★ anon key 만으로 회원가입이 됩니다. 그게 정상입니다.
//   회원가입까지 막아 버리면 아무도 가입을 못 하니까요.
//   가입하면 auth.users 표에 줄이 생기고, 그 줄의 id 가 auth.uid() 입니다.
//
// ★★ auth.users 는 Supabase 가 만들어 둔 표입니다. 내가 만들지 않습니다.
//   준비.sql 의 memos.user_id 가 이 표를 references 하고 있습니다.

const 사람들 = [
  { 이름: "김민준", 영문: "minjun", 메모: "카드 비밀번호 힌트: 강아지 생일", 전화: "010-1111-1111" },
  { 이름: "이서연", 영문: "seoyeon", 메모: "금요일 회의는 3시", 전화: "010-2222-2222" },
  { 이름: "박도윤", 영문: "doyun", 메모: "주말에 등산", 전화: "010-3333-3333" },
];

// ★ 비밀번호는 ASCII 로 짓습니다. 한글을 넣지 마세요.
//   메일 주소도 로컬파트까지 전부 ASCII 로 씁니다.
//   한글 주소를 받아 주는 곳도 있지만, 안 받아 주면 원인을 찾기 어렵습니다.
const 실습비밀번호 = "class-Passw0rd!";

async function 회원세명만들기() {
  const 만든사람 = [];

  // ★ 메일 주소는 **매번 달라야** 합니다.
  //   이미 가입된 주소로 signUp 하면 새 세션을 못 받습니다.
  //   그래서 시각을 섞습니다. 한 번 돌릴 때의 시각 하나를 세 명이 나눠 씁니다.
  const 도장 = Date.now();

  for (const [자리, 사람] of 사람들.entries()) {
    const 클라이언트 = 새클라이언트();
    const 메일 = `class-${도장}-${자리 + 1}-${사람.영문}@example.com`;

    const 결과 = await 클라이언트.auth.signUp({ email: 메일, password: 실습비밀번호 });

    if (결과.error) {
      console.log(`★ ${사람.이름} 가입에 실패했습니다: ${결과.error.message}`);
      console.log("★ Authentication → Sign In / Providers → Email 을 확인하세요.");
      console.log("★   · Enable email provider 가 켜져 있어야 합니다");
      console.log("★   · 짧은 사이에 여러 번 돌렸다면 가입 횟수 제한입니다. 조금 뒤에 다시 하세요");
      return null;
    }

    // ★★★ 세션이 안 오면 여기서 멈춥니다. 조용히 흘려보내면 안 됩니다.
    //
    //   Confirm email 이 켜져 있으면 signUp 은 성공하는데 session 이 null 입니다.
    //   "가입은 됐지만 메일을 눌러 확인하기 전까지는 로그인이 아니다" 라는 뜻입니다.
    //   이 상태로 계속 가면 auth.uid() 가 null 이라 모든 장면이 이상해집니다.
    if (!결과.data.session) {
      console.log("★ 회원가입은 됐는데 로그인 세션이 안 왔습니다.");
      console.log("★ Confirm email 이 켜져 있습니다.");
      console.log("★ Authentication → Sign In / Providers → Email 에서 Confirm email 을 꺼 주세요.");
      console.log("★ 끄고 나서 이 파일을 다시 돌리세요. (★ 진짜 서비스에서는 반드시 켜 두어야 합니다)");
      return null;
    }

    만든사람.push({ ...사람, 클라이언트, 메일, id: 결과.data.user.id });
  }

  for (const 사람 of 만든사람) {
    console.log(`${사람.이름} | 가입 완료 | id ${사람.id.slice(0, 8)}…`);
  }
  // 출력?: 김민준 | 가입 완료 | id 3f2a91c4…
  // 출력?: 이서연 | 가입 완료 | id 8b71de02…
  // 출력?: 박도윤 | 가입 완료 | id c04f5a9e…

  // ★ id 가 uuid 입니다. 1, 2, 3 이 아닙니다.
  //   회원 id 는 순번으로 두면 안 됩니다. 남의 id 를 찍어 맞힐 수 있으니까요.
  //   Supabase 가 uuid 를 쓰는 이유입니다.
  //
  // ★★ 세 사람의 클라이언트가 서로 다릅니다.
  //   김민준.클라이언트 로 부르면 김민준의 토큰이 붙어 나갑니다.
  //   그 토큰 안의 id 가 Postgres 안에서 auth.uid() 가 됩니다.

  return 만든사람;
}


// ============================================================
// 4 ~ 8. 관문 네 개 — 여기가 이 단원의 본문입니다
// ============================================================
//
// 정책을 한 줄씩 걸어 가며, 그때마다 무엇이 달라지는지 봅니다.
// 정책을 못 거는 자리에서는 "★ 여기서 멈추고" 가 나옵니다. 세 번 나옵니다.

async function 실습(만든사람) {
  const [김민준, 이서연, 박도윤] = 만든사람;
  const 손님 = 새클라이언트(); // 로그인 안 한 사람

  // ── 지금 어느 관문인지는 "해 보고" 압니다 ──
  //
  // ★ 정책이 걸렸는지 코드에서 물어볼 수는 없습니다.
  //   pg_policies 는 pg_catalog 에 있고, PostgREST 는 public 스키마만 열어 줍니다.
  //   그래서 **해 보고 결과로** 알아냅니다. 아래가 전부 그 방식입니다.

  // ============================================================
  // 4. 관문 ① — 정책이 하나도 없으면
  // ============================================================
  //
  // 준비.sql 은 memos 에 RLS 만 켜고 정책은 하나도 안 걸었습니다.
  //
  //   alter table memos enable row level security;
  //
  // 이 한 줄이 무엇을 하는지 봅니다. 김민준은 **로그인한 상태**입니다.

  const 첫넣기 = await 김민준.클라이언트
    .from("memos")
    .insert({ content: 김민준.메모, phone: 김민준.전화 });

  if (첫넣기.error && 첫넣기.error.code !== "42501") {
    console.log("★ 뜻밖의 오류입니다:", 첫넣기.error.code, "|", 첫넣기.error.message);
    return null;
  }

  if (첫넣기.error) {
    console.log("로그인은 했는데 넣기 code:", 첫넣기.error.code, "| status:", 첫넣기.status);
    // 출력: 로그인은 했는데 넣기 code: 42501 | status: 403
    console.log("message:", 첫넣기.error.message);
    // 출력: message: new row violates row-level security policy for table "memos"

    const 첫읽기 = await 김민준.클라이언트.from("memos").select("*");

    console.log("읽기 결과:", JSON.stringify(첫읽기.data), "| error:", 첫읽기.error);
    // 출력: 읽기 결과: [] | error: null

    // ★★★ "켜기만 하고 정책을 안 걸면 아무도 아무것도 못 합니다."
    //
    //   로그인을 했는데도 안 됩니다. RLS 의 기본은 **전부 차단**입니다.
    //   허용은 정책으로만 생깁니다. 정책이 없으면 허용이 없습니다.
    //
    // ★★★ 그런데 읽기와 쓰기의 모양이 다릅니다. 여기를 꼭 보세요.
    //
    //   읽기  오류가 아니라 **빈 배열**입니다. error 는 null 입니다.
    //   쓰기  42501 / 403 으로 **거절**합니다.
    //
    //   왜 다르냐면 — 읽기는 "그 줄이 있는지 없는지" 조차 알려 주지 않기 위해서입니다.
    //   403 을 주면 "아, 여기 뭔가 있긴 있구나" 를 알게 됩니다.
    //   쓰기는 숨길 게 없습니다. 넣으려는 줄은 이미 내가 아는 값이니까요.
    //
    // ★★ 정책이 없을 때의 모습을 넷 다 적어 둡니다. 외워 두면 진단이 빨라집니다.
    //
    //     select  오류 없음, 빈 배열
    //     insert  ★ 42501 / 403
    //     update  오류 없음, **0건**
    //     delete  오류 없음, **0건**
    //
    //   **insert 만 오류를 냅니다.** 나머지 셋은 조용합니다.
    //   "안 되는데 오류가 없다" 면 RLS 를 가장 먼저 의심하세요.
    //
    // ★★ 그래서 이런 질문이 제일 많이 나옵니다.
    //
    //   "분명히 자료를 넣었는데 목록이 비어 있어요"
    //   "고쳤다는데 안 바뀌어요"
    //   "지웠는데 그대로예요"
    //
    //   셋 다 같은 원인입니다. 오류가 없으니 코드를 아무리 봐도 안 보입니다.
    //   Table Editor 로 가서 자료가 있는지 먼저 확인하세요.
    //   (그 화면은 service_role 로 보기 때문에 RLS 를 통과합니다)
    //
    // ★★★ status 가 **403** 입니다. 401 이 아닙니다.
    //
    //   401 Unauthorized   "네가 누군지 모르겠다" — 로그인부터 해라
    //   403 Forbidden      "누군지는 알겠는데 이건 안 된다" — 권한이 없다
    //
    //   PostgREST 는 요청에 토큰이 **있으면** 42501 을 403 으로 냅니다.
    //   anon key 도 JWT 라서, 로그인을 안 했어도 토큰은 늘 붙어 갑니다.
    //   그래서 RLS 에 막히면 사실상 항상 403 입니다.
    //
    //   ★ 화면에서 401 과 403 을 다르게 다뤄야 합니다.
    //     401 이면 로그인 화면으로, 403 이면 "권한이 없습니다" 를 보여 주세요.
    //     401 로 착각해서 로그인 화면을 띄우면 이미 로그인한 사용자가 무한히 맴돕니다.

    // ────────────────────────────────────────────────────────
    // ★ 여기서 멈추고 [1/3], SQL Editor 에 아래 네 줄을 치고 오세요.
    // ────────────────────────────────────────────────────────
    //
    //   create policy "내 메모만 읽기" on memos
    //     for select using (auth.uid() = user_id);
    //
    //   create policy "내 것으로만 넣기" on memos
    //     for insert with check (auth.uid() = user_id);
    //
    //   create policy "내 메모만 지우기" on memos
    //     for delete using (auth.uid() = user_id);
    //
    //   create policy "내 메모만 고치기" on memos
    //     for update
    //     using      (auth.uid() = user_id)
    //     with check (true);              -- ★ 일부러 활짝 열어 둡니다
    //
    // ★★ 왜 네 줄을 한꺼번에 거나요?
    //
    //   읽기 정책만 걸면 읽기는 뚫립니다. 그런데 **여전히 빈 배열**입니다.
    //   넣을 수가 없으니 볼 것이 없으니까요.
    //   게다가 그 상태는 코드에서 **구분이 안 됩니다.**
    //   "정책이 없어서 []" 인지 "내 줄이 없어서 []" 인지 똑같이 보입니다.
    //   방금 본 그 이유(있는지 없는지도 안 알려 준다) 때문입니다.
    //
    //   지우기 정책은 이 파일이 끝에서 스스로 치우기 위해 필요합니다.
    //
    // ★★★ 고치기 정책의 with check 를 `true` 로 적은 것은 **일부러**입니다.
    //   "일단 되게 하려고" 넣어 두고 그대로 남는, 아주 흔한 값입니다.
    //   이게 무슨 일을 하는지 관문 ③ 에서 진짜로 보실 겁니다.
    //
    // ★ 치고 나서 이 파일을 다시 돌리세요.

    return { 회차: "①", 절: 4, 제목: "memos 에 정책이 하나도 없습니다" };
  }

  // ============================================================
  // 5. 관문 ② — ★★★ 3줄이 1줄이 됩니다
  // ============================================================
  //
  // 여기까지 왔다는 것은 정책 네 줄을 걸고 오셨다는 뜻입니다.
  // 김민준의 메모가 방금 들어갔습니다.

  console.log("정책을 걸고 나니 넣기 status:", 첫넣기.status, "| error:", 첫넣기.error);
  // 출력: 정책을 걸고 나니 넣기 status: 201 | error: null

  const 김민준것 = await 김민준.클라이언트.from("memos").select("*");

  if ((김민준것.data ?? []).length === 0) {
    console.log("넣기는 됐는데 읽으면:", JSON.stringify(김민준것.data));
    // 출력: 넣기는 됐는데 읽으면: []
    console.log("★ 읽기 정책을 아직 안 거셨습니다. 4번 절의 첫 줄입니다.");
    // 출력: ★ 읽기 정책을 아직 안 거셨습니다. 4번 절의 첫 줄입니다.

    // ★★ 이게 "넣었는데 목록이 비어 있다" 의 정확한 모습입니다.
    //   넣기는 201 로 성공했고, 읽기는 오류 없이 []. 어디에도 빨간 글씨가 없습니다.
    //
    // ★★ 그래서 insert 뒤에 .select() 를 붙이는 습관이 중요합니다.
    //   읽기 정책이 없는데 .insert().select() 를 하면 **오류가 납니다.**
    //   42501 이 오고, 넣던 것도 통째로 되돌아갑니다(롤백). 줄이 남지 않습니다.
    //   "조용히 빈 배열" 이 아니라 오류라서, 문제가 그 자리에서 드러납니다.

    return { 회차: "①", 절: 4, 제목: "읽기 정책이 빠졌습니다" };
  }

  // 이서연과 박도윤도 각자 하나씩 넣습니다.
  let 넣은줄 = 1; // 김민준 것

  for (const 사람 of [이서연, 박도윤]) {
    const 결과 = await 사람.클라이언트
      .from("memos")
      .insert({ content: 사람.메모, phone: 사람.전화 });

    if (!결과.error) 넣은줄 += 1;
  }

  // ★ user_id 를 아무도 안 적었습니다.
  //   준비.sql 이 `user_id uuid not null default auth.uid()` 로 만들었기 때문입니다.
  //   로그인한 사람이 넣으면 자기 id 가 알아서 들어갑니다.

  async function 몇줄보이나(클라이언트) {
    const 결과 = await 클라이언트.from("memos").select("id");
    return (결과.data ?? []).length;
  }

  const 김민준줄 = await 몇줄보이나(김민준.클라이언트);
  const 이서연줄 = await 몇줄보이나(이서연.클라이언트);
  const 박도윤줄 = await 몇줄보이나(박도윤.클라이언트);
  const 손님줄 = await 몇줄보이나(손님);

  // ★ 김민준이 넣은 줄보다 적게 본다면 = 읽기 정책이 "내 것만" 인 상태입니다.
  const 읽기가좁다 = 김민준줄 < 넣은줄;

  if (읽기가좁다) {
    console.log("── 같은 memos 표를, 사람마다 이렇게 봅니다 ──");
    // 출력: ── 같은 memos 표를, 사람마다 이렇게 봅니다 ──
    console.log(`표에 있는 줄                | ${넣은줄}`);
    // 출력: 표에 있는 줄                | 3
    console.log(`김민준이 보는 줄            | ${김민준줄}`);
    // 출력: 김민준이 보는 줄            | 1
    console.log(`이서연이 보는 줄            | ${이서연줄}`);
    // 출력: 이서연이 보는 줄            | 1
    console.log(`박도윤이 보는 줄            | ${박도윤줄}`);
    // 출력: 박도윤이 보는 줄            | 1
    console.log(`로그인 안 한 사람이 보는 줄 | ${손님줄}`);
    // 출력: 로그인 안 한 사람이 보는 줄 | 0

    console.log("김민준에게 온 줄:", JSON.stringify(김민준것.data.map((줄) => 줄.content)));
    // 출력: 김민준에게 온 줄: ["카드 비밀번호 힌트: 강아지 생일"]

    // ★★★ 이 표가 이 단원의 전부입니다.
    //
    //   세 사람이 **같은 표에** 하나씩 넣었습니다. 표에는 3줄이 있습니다.
    //   그런데 김민준이 `select("*")` 를 하면 **1줄**만 옵니다.
    //   조건을 하나도 안 붙였는데 말입니다.
    //
    //   정책 한 줄이 한 일입니다.
    //
    //     create policy "내 메모만 읽기" on memos
    //       for select using (auth.uid() = user_id);
    //
    // ★★★ 이게 "행 수준" 입니다. 표를 막은 게 아닙니다. **줄을 고릅니다.**
    //
    //   김민준이 보낸 것            select * from memos
    //   Postgres 가 실제로 도는 것   select * from memos where (auth.uid() = user_id)
    //
    //   정책의 using 이 WHERE 에 **AND 로 붙습니다.**
    //   그래서 표 전체가 막히는 게 아니라, 내 줄만 남습니다.
    //   "표 수준" 이 아니라 "행 수준" 인 이유가 이것입니다.
    //
    // ★★ 남의 전화번호도 같이 사라졌습니다.
    //   줄이 안 오니 그 줄의 모든 칸이 안 옵니다.
    //   (칸 단위로 막는 것은 RLS 가 아니라 열 권한 grant 입니다. 다른 이야기입니다)
    //
    // ★★★ "표에 정말 3줄이 있나" 는 이 코드로는 못 셉니다.
    //
    //   anon key 로 세면 정책이 걸러 낸 뒤의 수가 나옵니다. 1 이 나옵니다.
    //   count 를 써도 똑같습니다. 세는 것도 select 라서 정책을 지나갑니다.
    //
    //   ★ SQL Editor 에서 직접 세 보세요. 3 이 나옵니다.
    //
    //       select count(*) from memos;
    //
    //   ★★ SQL Editor 는 service_role 로 돕니다. RLS 를 통과합니다.
    //     그래서 "대시보드에서는 보이는데 코드에서는 안 보인다" 가 생깁니다.
    //     그 차이가 이상한 게 아니라, 그게 RLS 가 일하고 있다는 증거입니다.
    //
    //   ★ 3 보다 큰 수가 나왔다면, 지난번에 중간에 멈춘 실습이 남은 것입니다.
    //     이 파일은 끝에서 자기가 만든 메모를 지우지만, Ctrl+C 로 끊으면 거기까지 못 갑니다.
    //     SQL Editor 에서 `delete from memos;` 로 한 번 비우고 다시 시작하세요.

    // ── 콕 집어 달라고 해도 안 나옵니다 ──

    const 콕집어 = await 김민준.클라이언트.from("memos").select("*").eq("user_id", 이서연.id);

    console.log("이서연 것을 콕 집어 달라고 하면:", (콕집어.data ?? []).length, "건");
    // 출력: 이서연 것을 콕 집어 달라고 하면: 0 건

    // ★★ 조건을 아무리 정확히 써도 안 나옵니다.
    //
    //   Postgres 가 실제로 도는 것은 이렇게 됩니다.
    //
    //     select * from memos
    //     where user_id = '이서연의 id'          ← 내가 보낸 조건
    //       and (auth.uid() = user_id)           ← 정책이 붙인 조건
    //
    //   두 조건이 동시에 참일 수가 없습니다. 그래서 0건입니다.
    //   ★ 이게 IDOR(남의 id 를 넣어 보는 공격) 가 여기서 안 통하는 이유입니다.
    //     서버 코드에서 "내 것인가" 를 확인하는 걸 깜빡해도, 정책이 아래에서 한 번 더 막습니다.
  } else {
    console.log("── 읽기 정책을 한 줄 더 걸었더니 ──");
    // 출력: ── 읽기 정책을 한 줄 더 걸었더니 ──
    console.log(`표에 있는 줄                | ${넣은줄}`);
    // 출력: 표에 있는 줄                | 3
    console.log(`김민준이 보는 줄            | ${김민준줄}`);
    // 출력: 김민준이 보는 줄            | 3

    // ★★★ 아까는 1줄이었습니다. 지금은 3줄입니다.
    //
    //   "내 메모만 읽기" 를 **지우지 않았는데도** 다 보입니다.
    //   한 줄을 더 걸었을 뿐입니다.
    //
    //     create policy "누구나 읽기" on memos for select using (true);
    //
    // ★★★ 정책이 여러 개면 **OR** 로 합쳐지기 때문입니다.
    //
    //     (auth.uid() = user_id)  or  (true)   →  언제나 참
    //
    //   좁은 정책을 아무리 잘 짜 두어도, 옆에 넓은 정책이 하나 생기면 그걸로 다 열립니다.
    //   ★ 그래서 "정책을 하나 추가" 는 언제나 **넓히는** 쪽입니다. 좁히지 못합니다.
    //     좁히려면 기존 정책을 고치거나, as restrictive 를 써야 합니다. (9번 절)
    //
    // ★★ 실무에서 이렇게 생깁니다.
    //   "관리자도 볼 수 있게 해 주세요" → 정책 하나 추가 → 조건을 잘못 적음 → 전부 공개.
    //   추가한 정책 하나만 보지 말고, 그 표의 정책 **전체**를 같이 보세요.
  }

  // ============================================================
  // 6. using 과 with check — 이제 진짜로 구분됩니다
  // ============================================================
  //
  // 4번 절에서 건 정책들을 다시 봅시다. 쓰는 말이 서로 다릅니다.
  //
  //   for select using (auth.uid() = user_id)        ← using
  //   for insert with check (auth.uid() = user_id)   ← with check
  //   for delete using (auth.uid() = user_id)        ← using
  //   for update using (...) with check (...)        ← 둘 다
  //
  //   using       "**이미 있는 줄** 중에 어떤 걸 건드리게 할까"
  //   with check  "**새로 생기거나 바뀐 줄** 이 어떤 모양이어야 할까"
  //
  // insert 에는 using 이 없습니다. 건드릴 기존 줄이 없으니까요.
  // select 에는 with check 가 없습니다. 새로 생기는 줄이 없으니까요.
  //
  // 말로만 하면 안 외워집니다. 김민준이 남의 것처럼 위장해서 넣어 봅니다.

  const 위장 = await 김민준.클라이언트
    .from("memos")
    .insert({ user_id: 이서연.id, content: "이서연이 쓴 것처럼 보이는 메모" });

  if (!위장.error) {
    console.log("★ 남의 id 로 넣는 것이 됐습니다. 넣기 정책의 with check 가 열려 있습니다.");
    console.log("★ 4번 절의 둘째 줄을 다시 보세요 — with check (auth.uid() = user_id) 여야 합니다.");
    return { 회차: "①", 절: 4, 제목: "넣기 정책의 with check 가 열려 있습니다" };
  }

  console.log("남의 id 로 넣기 code:", 위장.error.code, "| status:", 위장.status);
  // 출력: 남의 id 로 넣기 code: 42501 | status: 403
  console.log("message:", 위장.error.message);
  // 출력: message: new row violates row-level security policy for table "memos"

  // ★★★ 막은 것은 with check 입니다. using 은 아무 일도 안 했습니다.
  //
  //   user_id 를 안 적으면 default auth.uid() 가 채웁니다. 그래서 통과했습니다.
  //   user_id 를 **적으면** 그 값이 with check 를 통과해야 합니다.
  //   김민준의 auth.uid() 와 이서연의 id 는 다르니 거절됩니다.
  //
  // ★★ "화면에서 user_id 를 안 보내니까 괜찮다" 는 생각은 틀렸습니다.
  //   공격자는 화면을 안 씁니다. curl 로 아무 값이나 보냅니다.
  //   보내지 못하게 막는 곳은 화면이 아니라 with check 입니다.
  //
  // ★ 그리고 이건 읽기 정책이 넓든 좁든 똑같이 막힙니다.
  //   읽는 것과 쓰는 것은 다른 정책이 봅니다.

  // ============================================================
  // 7. 내 것을 남의 것으로 — 바꿔치기
  // ============================================================
  //
  // 고치기 정책은 이렇게 걸려 있습니다.
  //
  //   for update using (auth.uid() = user_id) with check (true)
  //
  // 먼저 내용만 고쳐 봅니다. 이건 당연히 됩니다.

  // ★ 반드시 user_id 로 걸러서 **내 줄**을 집습니다.
  //   관문 ③ 부터는 읽기가 넓어져서 select("*") 의 첫 줄이 남의 줄일 수 있습니다.
  const 내줄 = await 김민준.클라이언트
    .from("memos")
    .select("id")
    .eq("user_id", 김민준.id)
    .order("id");

  const 내메모id = 내줄.data[0].id;

  const 고치기 = await 김민준.클라이언트
    .from("memos")
    .update({ content: "내용을 고쳐 봅니다" })
    .eq("id", 내메모id)
    .select("id");

  if ((고치기.data ?? []).length === 0) {
    console.log("내 메모 고치기:", (고치기.data ?? []).length, "건 | error:", 고치기.error);
    console.log("★ 고치기 정책을 아직 안 거셨습니다. 4번 절의 넷째 줄입니다.");

    // ★★ 오류가 아니라 **0건**입니다. 4번 절에서 적어 둔 그대로입니다.
    //   update 는 정책이 없으면 조용히 0건입니다. delete 도 같습니다.

    return { 회차: "①", 절: 4, 제목: "고치기 정책이 빠졌습니다" };
  }

  console.log("내 메모 내용 고치기:", (고치기.data ?? []).length, "건");
  // 출력: 내 메모 내용 고치기: 1 건

  // ── ★★★ 이제 내용이 아니라 주인을 바꿔 봅니다 ──
  //
  //   with check 가 `true` 니까 무엇이든 통과할 것 같습니다. 해 봅시다.

  const 바꿔치기 = await 김민준.클라이언트
    .from("memos")
    .update({ user_id: 이서연.id })
    .eq("id", 내메모id);

  // ============================================================
  // 7-A. 관문 ② — with check 가 true 인데도 막힙니다
  // ============================================================

  if (읽기가좁다) {
    if (!바꿔치기.error) {
      console.log("★ 뜻밖입니다. 바꿔치기가 됐습니다. 읽기 정책을 다시 확인하세요.");
      await 이서연.클라이언트.from("memos").update({ user_id: 김민준.id }).eq("id", 내메모id);
      return { 회차: "①", 절: 4, 제목: "읽기 정책이 예상과 다릅니다" };
    }

    console.log("주인 바꿔치기 code:", 바꿔치기.error.code, "| status:", 바꿔치기.status);
    // 출력: 주인 바꿔치기 code: 42501 | status: 403

    const 그대로 = await 몇줄보이나(김민준.클라이언트);
    console.log("김민준의 줄은 그대로:", 그대로, "건");
    // 출력: 김민준의 줄은 그대로: 1 건

    // ★★★ 막혔습니다. **with check 는 true 인데** 말입니다.
    //
    //   using      (auth.uid() = user_id)   "김민준 것이니 고쳐도 된다"  → 통과
    //   with check (true)                   "고친 뒤 모양은 뭐든 좋다"   → 통과
    //
    //   둘 다 통과인데 42501 입니다. 왜일까요?
    //
    // ★★★ **읽기 정책이 막았습니다.**
    //
    //   Postgres 는 update 가 줄을 읽어야 할 때(where 조건을 쓰거나 고친 줄을 돌려받을 때)
    //   읽기 정책을 같이 겁니다. 그것도 **고치기 전 줄과 고친 뒤 줄 양쪽에** 겁니다.
    //
    //     고치기 전 줄  user_id = 김민준  → "내 메모만 읽기" 통과
    //     고친 뒤 줄    user_id = 이서연  → "내 메모만 읽기" ✗  → 42501
    //
    //   "고친 뒤에도 나에게 보이는 줄이어야 한다" 가 공짜로 붙은 셈입니다.
    //   supabase-js 는 update 에 항상 조건을 붙여 보내니, 이 규칙은 늘 적용됩니다.
    //
    // ★★★ 그래서 **읽기를 좁게 짜 두면 쓰기까지 같이 좁아집니다.**
    //   "내 것만 읽기" 정책 하나가, 고치기 정책의 허술함을 덮어 준 것입니다.
    //   RLS 정책을 하나씩 떼어 보면 안 되고 **묶어서** 봐야 하는 이유입니다.
    //
    // ★★ 그럼 with check (true) 는 안전한가요? **아닙니다.**
    //   덮어 주던 읽기 정책이 넓어지는 순간 그대로 뚫립니다.
    //   그리고 읽기 정책은 아주 쉽게 넓어집니다. "목록 화면을 만들어야 해서" 한 줄만 더 걸면 됩니다.
    //   다음 관문에서 **진짜로** 보겠습니다.

    // ────────────────────────────────────────────────────────
    // ★ 여기서 멈추고 [2/3], SQL Editor 에 아래 한 줄을 치고 오세요.
    // ────────────────────────────────────────────────────────
    //
    //   create policy "누구나 읽기" on memos
    //     for select using (true);
    //
    // ★ "내 메모만 읽기" 는 **지우지 마세요.** 한 줄을 더 걸 뿐입니다.
    //   memos 를 사내 게시판처럼 바꾸는 셈입니다. 흔히 하는 변경입니다.
    //
    // ★ 치고 나서 이 파일을 다시 돌리세요.

    return { 회차: "②", 절: 7, 제목: "읽기가 좁아서 바꿔치기가 막혀 있습니다" };
  }

  // ============================================================
  // 7-B. 관문 ③ — 읽기가 넓어지자 뚫립니다
  // ============================================================

  if (!바꿔치기.error) {
    console.log("주인 바꿔치기 status:", 바꿔치기.status, "| error:", 바꿔치기.error);
    // 출력: 주인 바꿔치기 status: 204 | error: null

    const 바꾼뒤이서연 = await 몇줄보이나(이서연.클라이언트);
    const 이서연것 = await 이서연.클라이언트.from("memos").select("content").eq("user_id", 이서연.id);

    console.log("바꿔치기 뒤 이서연의 줄:", 바꾼뒤이서연, "건 중 이서연 소유:", (이서연것.data ?? []).length, "건");
    // 출력: 바꿔치기 뒤 이서연의 줄: 3 건 중 이서연 소유: 2 건
    console.log("이서연 소유가 된 것:", JSON.stringify((이서연것.data ?? []).map((줄) => 줄.content)));
    // 출력?: 이서연 소유가 된 것: ["금요일 회의는 3시","내용을 고쳐 봅니다"]

    console.log("로그인 안 한 사람이 보는 줄:", 손님줄, "건");
    // 출력: 로그인 안 한 사람이 보는 줄: 3 건

    // ★★★ 이번엔 됐습니다. 정책은 **한 글자도 안 바뀌었습니다.**
    //
    //   바뀐 것은 읽기 정책 하나뿐입니다. "누구나 읽기" 를 더 걸었을 뿐입니다.
    //   그런데 고치기 정책의 구멍이 그대로 드러났습니다.
    //
    //     using      (auth.uid() = user_id)   "김민준 것이니 고쳐도 된다"  → 통과
    //     with check (true)                   "고친 뒤 모양은 뭐든 좋다"   → 통과
    //     읽기 정책이 새 줄을 검사               "누구나 읽기" 라 통과       → 통과
    //
    //   막는 것이 하나도 없습니다. 김민준의 메모가 이서연 것이 됐습니다.
    //
    // ★★★ 이게 update 정책에 with check 가 필요한 이유입니다.
    //   "내 것만 고칠 수 있다" 만으로는 부족합니다.
    //   "고친 **뒤에도** 내 것이어야 한다" 까지 적어야 합니다.
    //
    // ★★★ 그리고 이게 정책을 **묶어서** 봐야 하는 이유입니다.
    //   관문 ② 에서는 같은 고치기 정책이 안전해 보였습니다.
    //   읽기 정책 한 줄이 바뀌자 뚫렸습니다. 고치기 정책은 그대로인데 말입니다.
    //   "이 정책 하나는 괜찮은가" 가 아니라 "표 전체가 괜찮은가" 를 물어야 합니다.
    //
    // ★★ 로그인도 안 한 사람이 남의 메모를 3건 다 보고 있습니다.
    //   전화번호까지 같이 보입니다. `using (true)` 한 줄이 한 일입니다.
    //   이건 다음 관문에서 as restrictive 로 닫습니다.

    // 되돌립니다. 김민준은 못 합니다. 이제 그 줄은 이서연 것입니다.
    const 되돌리기 = await 이서연.클라이언트
      .from("memos")
      .update({ user_id: 김민준.id })
      .eq("id", 내메모id);

    console.log("이서연이 되돌려 줬나:", 되돌리기.error ? "실패" : "성공");
    // 출력: 이서연이 되돌려 줬나: 성공

    // ★ 되돌리는 것도 같은 구멍으로 합니다. 구멍은 양쪽으로 뚫려 있습니다.
    //   ★★ 만약 이서연이 안 되돌려 주면 김민준은 영영 못 찾습니다.
    //     고칠 수도, 지울 수도 없습니다. 자기 줄이 아니게 됐으니까요.

    // ────────────────────────────────────────────────────────
    // ★ 여기서 멈추고 [3/3], SQL Editor 에 아래를 치고 오세요.
    // ────────────────────────────────────────────────────────
    //
    //   drop policy "내 메모만 고치기" on memos;
    //
    //   create policy "내 메모만 고치기" on memos
    //     for update
    //     using      (auth.uid() = user_id)
    //     with check (auth.uid() = user_id);   -- ★ 이번엔 제대로
    //
    //   create policy "로그인해야 읽기" on memos
    //     as restrictive for select
    //     using (auth.uid() is not null);
    //
    // ★ 정책은 고칠 수 없습니다. drop 하고 다시 만듭니다.
    //   (alter policy 로 조건을 바꿀 수도 있지만, 수업에서는 drop/create 로 통일합니다)
    //
    // ★★ 둘째 것이 as restrictive 입니다. 9번 절에서 다시 설명합니다.
    //   "누구나 읽기" 를 지우지 않고도, 로그인 안 한 사람을 막습니다.
    //   permissive 는 OR 로 넓히고, restrictive 는 AND 로 좁힙니다.
    //
    // ★ 치고 나서 이 파일을 다시 돌리세요. 마지막입니다.

    return { 회차: "③", 절: 7, 제목: "고치기 정책의 with check 가 열려 있습니다" };
  }

  // ============================================================
  // 8. 관문 ④ — 제대로 걸었을 때
  // ============================================================

  console.log("제대로 건 뒤 바꿔치기 code:", 바꿔치기.error.code, "| status:", 바꿔치기.status);
  // 출력: 제대로 건 뒤 바꿔치기 code: 42501 | status: 403

  const 마지막김민준 = await 몇줄보이나(김민준.클라이언트);
  console.log("김민준이 보는 줄:", 마지막김민준, "건");
  // 출력: 김민준이 보는 줄: 3 건
  console.log("로그인 안 한 사람이 보는 줄:", 손님줄, "건");
  // 출력: 로그인 안 한 사람이 보는 줄: 0 건

  // ★★★ 읽기는 아직 "누구나" 인데도 바꿔치기가 막혔습니다.
  //
  //   이번엔 덮어 준 것이 없습니다. with check 가 **혼자서** 막았습니다.
  //
  //     using      (auth.uid() = user_id)   → 통과 (아직 김민준 것)
  //     with check (auth.uid() = user_id)   → ✗    (이서연 것이 되려 하니까)
  //
  //   관문 ② 와 결과는 같지만 **막은 사람이 다릅니다.**
  //   ② 는 읽기 정책이 우연히 막아 준 것이고, ④ 는 고치기 정책이 제 일을 한 것입니다.
  //   우연에 기대면 안 됩니다.
  //
  // ★★★ 그리고 로그인 안 한 사람이 3줄에서 **0줄**이 됐습니다.
  //
  //   "누구나 읽기" 는 그대로 있습니다. 지우지 않았습니다.
  //   as restrictive 한 줄이 AND 로 걸리면서 닫힌 것입니다.
  //
  //     ( "내 메모만 읽기"  or  "누구나 읽기" )   ← permissive 끼리 OR
  //       and ( "로그인해야 읽기" )               ← restrictive 는 AND
  //
  //   로그인한 사람은 앞이 참, 뒤도 참 → 3줄
  //   로그인 안 한 사람은 앞은 참인데 뒤가 거짓 → 0줄
  //
  // ★★ 지금 memos 는 이런 표가 됐습니다.
  //
  //     로그인한 사람은 모두의 메모를 읽는다      (사내 게시판)
  //     넣는 것은 자기 것으로만
  //     고치고 지우는 것은 자기 것만
  //     로그인 안 하면 아무것도 못 본다
  //
  //   ★ 다시 "개인 메모장" 으로 되돌리고 싶으면 넓힌 줄을 지우면 됩니다.
  //
  //       drop policy "누구나 읽기" on memos;
  //
  //     그러면 김민준이 보는 줄이 다시 1이 됩니다.
  //
  // ── 그럼 with check 를 **아예 안 쓰면** 어떻게 되나 ──
  //
  //   create policy "내 메모만 고치기" on memos
  //     for update using (auth.uid() = user_id);        -- with check 없음
  //
  // ★★★ 이건 안전합니다. 바꿔치기가 **막힙니다.**
  //
  //   Postgres 의 규칙이 이렇습니다.
  //
  //     "with check 를 안 적으면, using 을 with check 자리에도 그대로 쓴다"
  //     (PostgreSQL 문서 CREATE POLICY 항목)
  //
  //   그래서 위 정책은 사실상 아래와 같습니다.
  //
  //     using (auth.uid() = user_id) with check (auth.uid() = user_id)
  //
  // ★★ "update 에 with check 를 빼먹으면 뚫린다" 는 말을 인터넷에서 자주 봅니다.
  //   **틀린 말입니다.** 빼먹으면 using 이 대신 들어가서 오히려 안전합니다.
  //   진짜로 뚫리는 건 방금 본 것처럼 with check 를 **넓게 적었을 때**입니다.
  //
  //     with check (true)                      ← ★ 위험. 아무 모양이나 통과
  //     with check (auth.uid() is not null)     ← ★ 위험. 로그인만 하면 통과
  //     with check 없음                         ← 안전 (using 이 대신 들어감)
  //     with check (auth.uid() = user_id)       ← ★ 이렇게 쓰세요
  //
  // ★ 그래도 **적어 두는 쪽**을 권합니다.
  //   읽는 사람이 규칙을 모를 수 있습니다. 적혀 있으면 안 헷갈립니다.
  //   나중에 using 만 고치다가 뜻이 어긋나는 일도 막습니다.
  //
  // ★★ delete 에는 with check 가 없습니다. 지우면 새 줄이 안 생기니까요.
  //   using 만 있으면 됩니다.

  return null; // 관문을 모두 통과했습니다
}


// ============================================================
// 9. 정책이 여러 개면 OR 로 합쳐집니다
// ============================================================

function 정책이여러개면() {
  const 정책표 = [
    ["select", "using", "보여 줄 줄을 고릅니다"],
    ["insert", "with check", "넣을 수 있는 줄의 모양을 정합니다"],
    ["update", "using + with check", "★ 고칠 줄 + 고친 뒤 모양"],
    ["delete", "using", "지울 수 있는 줄을 고릅니다"],
  ];

  for (const [동작, 무엇, 설명] of 정책표) {
    console.log(`${동작} | ${무엇} | ${설명}`);
  }
  // 출력: select | using | 보여 줄 줄을 고릅니다
  // 출력: insert | with check | 넣을 수 있는 줄의 모양을 정합니다
  // 출력: update | using + with check | ★ 고칠 줄 + 고친 뒤 모양
  // 출력: delete | using | 지울 수 있는 줄을 고릅니다

  // ★★ 정책은 **여러 개면 OR 로 합쳐집니다.**
  //
  //   "내 메모 읽기" 와 "관리자는 다 읽기" 를 둘 다 만들면
  //   둘 중 하나만 맞아도 보입니다.
  //
  //   그래서 "이건 절대 안 보여야 해" 를 **보통 정책 하나로는** 못 막습니다.
  //   다른 정책이 열어 줄 수 있으니까요. 전체를 같이 봐야 합니다.
  //
  //   ★★★ 방금 본 것이 정확히 이것입니다.
  //     "내 메모만 읽기" 를 지우지 않았는데, "누구나 읽기" 한 줄이 더 걸리자
  //     김민준이 보는 줄이 1에서 3이 됐습니다. (관문 ③)
  //     products 도 같은 상태입니다. `using (true)` 정책 하나로 전부 열려 있습니다.
  //
  //   ★★ 그리고 그때 고치기 정책의 구멍까지 같이 열렸습니다.
  //     읽기 정책이 넓어지면 **읽기만** 넓어지는 게 아닙니다.
  //     update 는 읽기 정책도 같이 통과해야 하기 때문입니다. (7번 절)
  //
  // ★★★ 정확히 그 용도로 만들어진 정책이 따로 있습니다. `as restrictive` 입니다.
  //
  //   create policy "정지된 계정은 절대 안 됨" on memos
  //     as restrictive for select
  //     using ( (auth.jwt() -> 'app_metadata' ->> 'suspended') is distinct from 'true' );
  //
  //   · 기본은 `as permissive` 입니다. 안 적으면 이쪽입니다. → 서로 **OR**
  //   · `as restrictive` 는 서로, 그리고 permissive 묶음과 **AND** 로 걸립니다.
  //
  //   그래서 restrictive 정책이 하나라도 거짓이면 다른 정책이 아무리 열어 줘도 막힙니다.
  //   "무조건 막아야 하는 조건" 은 restrictive 로 한 번 걸어 두세요.
  //
  //   ★ 다만 restrictive 만 만들면 아무것도 안 보입니다.
  //     허용해 주는 permissive 정책이 최소 하나는 있어야 합니다.
  //     restrictive 는 "열어 주는" 게 아니라 "열린 것을 더 좁히는" 정책입니다.
  //
  //   ★★★ 관문 ④ 에서 이걸 진짜로 보셨습니다.
  //     "누구나 읽기" 를 그대로 둔 채, restrictive 한 줄로
  //     로그인 안 한 사람만 3줄에서 0줄이 됐습니다.
  //
  //       ( "내 메모만 읽기"  or  "누구나 읽기" )   ← permissive 끼리 OR
  //         and ( "로그인해야 읽기" )               ← restrictive 는 AND
  //
  // ★ is distinct from 을 쓴 이유
  //   app_metadata 에 suspended 가 아예 없으면 값이 null 입니다.
  //   `<> 'true'` 는 null 앞에서 null 이 되고, null 은 참이 아니라 막힙니다.
  //   정지된 적 없는 사람까지 전부 막히는 사고가 이렇게 납니다. (개념02 의 NULL 이야기)
}



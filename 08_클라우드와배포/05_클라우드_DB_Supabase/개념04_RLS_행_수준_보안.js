//
//   anon key 는 공개해도 됩니다. RLS 가 지켜 주기 때문입니다.
//   service_role key 는 RLS 를 전부 무시합니다. 서버에서만, .env 에서만.
//
//   RLS 를 켜기만 하고 정책이 없으면 아무도 아무것도 못 합니다.
//   RLS 를 켜고 using (true) 를 걸면 안 켠 것과 똑같습니다.
//   "켰다" 와 "안전하다" 는 다른 말입니다.
//
//   ★★★ 정책 한 줄이 3줄을 1줄로 만듭니다. (관문 ②)
//
//     create policy "내 메모만 읽기" on memos
//       for select using (auth.uid() = user_id);
//
//     표에 있는 줄 3 · 김민준 1 · 이서연 1 · 로그인 안 한 사람 0
//
//     표를 막은 게 아니라 **줄을 고른** 것입니다. 그래서 "행 수준" 입니다.
//     using 이 WHERE 에 AND 로 붙는다고 생각하면 정확합니다.
//
//   select  using
//   insert  with check
//   update  using + with check   ★ using 은 고치기 전, with check 는 고친 뒤
//   delete  using
//
//   ★★★ update 는 **읽기 정책까지 같이** 통과해야 합니다. 고친 뒤 줄도 나에게 보여야 합니다.
//     그래서 "내 것만 읽기" 가 걸려 있으면, 고치기 정책이 허술해도 바꿔치기가 막힙니다. (관문 ②)
//     읽기를 넓히는 순간 그 방패가 사라지고 그대로 뚫립니다. (관문 ③)
//     ★ 정책은 하나씩 보지 말고 **표 전체를 묶어서** 보세요.
//
//   ★ with check 를 안 적으면 using 이 그 자리에 들어갑니다 (안전).
//     "with check 를 빼먹으면 뚫린다" 는 말은 틀렸습니다.
//     진짜 위험한 건 with check 를 **넓게** 적는 것입니다. true 나 is not null.
//
//   정책이 여러 개면 OR 입니다. 정책을 추가하면 언제나 **넓어집니다.**
//   좁히려면 기존 정책을 고치거나 as restrictive 를 쓰세요. (관문 ④)
//
//   ★ 정책이 없을 때의 모습
//
//     select  오류 없음, 빈 배열
//     insert  42501 / 403
//     update  오류 없음, 0건
//     delete  오류 없음, 0건
//
//   insert 만 오류를 냅니다. "안 되는데 오류가 없다" 면 RLS 를 먼저 의심하세요.
//
//   확인은 화면이 아니라 curl · pg_policies · Advisors 로.
//
// 다음(개념05) 에서 저장소를 Supabase 로 또 갈아 끼웁니다.
// 02단원에서 만든 저장소검사를 그대로 통과시키는 것이 목표입니다.

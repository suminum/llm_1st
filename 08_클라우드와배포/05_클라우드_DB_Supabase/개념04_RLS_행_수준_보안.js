async function 준비확인() {
  const 손님 = 새클라이언트();

  for (const 표 of ["products", "memos"]) {
    const 결과 = await 손님.from(표).select("id").limit(1);

    if (!결과.error) continue;

    console.log(`★ ${표} 표를 읽지 못했습니다: ${결과.error.message}`);

    if (결과.status === 0) {
      console.log("★ 인터넷이 끊겼거나 SUPABASE_URL 이 틀렸습니다. (개념03 의 status 0)");
    } else if (결과.status === 401) {
      console.log("★ SUPABASE_ANON_KEY 를 다시 복사해 넣으세요.");
    } else if (결과.error.code === "PGRST205") {
      console.log("★ 표는 있는데 PostgREST 가 아직 모를 수 있습니다. (준비.sql 끝의 설명)");
      console.log("★ 잠깐 뒤에 다시 돌리거나, SQL Editor 에서 notify pgrst, 'reload schema'; 를 치세요.");
    } else {
      console.log("★ SQL Editor 에 준비.sql 을 붙여 넣고 Run 하세요.");
    }

    return false;
  }

  return true;
}


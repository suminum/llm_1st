async function 시작() {
  키두개();

  if (!(await 준비확인())) return;

  await 켜기만하면();

  const 만든사람 = await 회원세명만들기();
  if (!만든사람) return;

  let 다음할일 = null;

  try {
    다음할일 = await 실습(만든사람);
  } finally {
    await 치우기(만든사람);
  }

  정책이여러개면();
  자주쓰는정책();
  서버는어떻게();
  확인하는법();
  마무리(다음할일);
}


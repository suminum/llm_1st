// ============================================================
// 개념 01 — 왜 클라우드 DB 인가
// ============================================================
//
// 02단원까지 SQLite 를 썼습니다. 잘 동작했습니다.
// 그런데 배포를 하려고 보면 막히는 것들이 있습니다.
//
// 그 벽이 뭔지 먼저 보고, Supabase 가 그중 무엇을 풀어 주는지 봅니다.
//
// 실행: node 개념01_왜_클라우드_DB인가.js
// ============================================================

const { DatabaseSync } = require("node:sqlite");
const fs = require("node:fs");
const path = require("node:path");

const 폴더 = path.join(__dirname, "실험용");
fs.rmSync(폴더, { recursive: true, force: true });
fs.mkdirSync(폴더, { recursive: true });

// ============================================================
// 1. 벽 ① — DB 가 서버 한 대에 붙어 있습니다
// ============================================================
//
// SQLite 는 파일입니다. 그 파일은 서버 컴퓨터 안에 있습니다.
//
//   서버를 두 대로 늘리면?
//   → DB 파일도 두 개가 됩니다. 서로 다른 자료를 갖게 됩니다.
//
// 직접 봅시다. 서버 두 대를 흉내 냅니다.

const A서버 = new DatabaseSync(path.join(폴더, "A서버.db"));
const B서버 = new DatabaseSync(path.join(폴더, "B서버.db"));

for (const db of [A서버, B서버]) {
  db.exec("CREATE TABLE 상품 (id INTEGER PRIMARY KEY, name TEXT NOT NULL) STRICT");
}

// 사용자가 A 서버로 요청을 보내 상품을 만들었습니다
A서버.prepare("INSERT INTO 상품 (name) VALUES (?)").run("USB 허브");

// 다음 요청이 B 서버로 갔습니다 (부하 분산은 순서를 보장하지 않습니다)
console.log("A 서버가 아는 상품:", A서버.prepare("SELECT COUNT(*) AS n FROM 상품").get().n);
// 출력: A 서버가 아는 상품: 1
console.log("B 서버가 아는 상품:", B서버.prepare("SELECT COUNT(*) AS n FROM 상품").get().n);
// 출력: B 서버가 아는 상품: 0

// ★★ 사용자 입장에서는 "방금 만든 게 사라졌어요" 입니다.
//   새로고침할 때마다 있다 없다 합니다. 재현이 안 돼서 찾기가 아주 어렵습니다.
//
// ★ 서버를 왜 두 대로 늘리나요?
//
//   · 한 대로는 요청을 다 못 받아서
//   · 한 대가 죽어도 서비스가 살아 있게 하려고
//   · 무중단 배포를 하려고 (한 대씩 교체)
//
//   PM2 클러스터(05단원) 로 한 컴퓨터에서 프로세스를 여러 개 띄워도
//   같은 파일을 쓰니 이 문제는 안 생깁니다. 대신 "database is locked" 를 만납니다.
//   컴퓨터를 늘리는 순간 이 벽에 부딪힙니다.

A서버.close();
B서버.close();

// ============================================================
// 2. 벽 ② — 배포하면 자료가 사라집니다
// ============================================================
//
// 요즘 배포 방식(컨테이너, Vercel, Cloud Run 등) 은
// 새 코드를 올릴 때 컴퓨터를 통째로 새것으로 바꿉니다.
//
//   그 안에 있던 파일도 같이 사라집니다.
//   data/상품.db 가 없어집니다.
//
// ★ 이걸 "저장이 안 남는(ephemeral) 파일 시스템" 이라고 합니다.
//
//   배포할 때마다 회원이 0명이 됩니다.
//   개발할 때는 안 보입니다. 내 컴퓨터에서는 파일이 그대로 있으니까요.
//
// ★ 안 사라지게 하려면 "볼륨" 을 붙여야 합니다.
//   EC2 에 직접 올리면(04~05단원) 디스크가 그대로라 괜찮습니다.
//   그래도 다음 벽이 남습니다.

// ============================================================
// 3. 벽 ③ — 백업과 복구를 내가 다 해야 합니다
// ============================================================

const 원본 = new DatabaseSync(path.join(폴더, "원본.db"));
원본.exec("CREATE TABLE 상품 (id INTEGER PRIMARY KEY, name TEXT NOT NULL) STRICT");
원본.exec("INSERT INTO 상품 (name) VALUES ('USB 허브'), ('27인치 모니터')");

const 백업경로 = path.join(폴더, "백업.db");
원본.exec(`VACUUM INTO '${백업경로.replace(/\\/g, "/")}'`);

console.log("백업 만들었나:", fs.existsSync(백업경로));
// 출력: 백업 만들었나: true

// 02단원 개념02 에서 배운 방법입니다. 어렵지 않습니다.
// 그런데 이걸 **매일 자동으로** 하고, **다른 곳에 보관**하고,
// **복구가 되는지 정기적으로 확인**해야 합니다.
//
//   언제 백업할 것인가        cron 을 짜야 합니다
//   어디에 둘 것인가          같은 서버에 두면 서버가 죽을 때 같이 죽습니다
//   얼마나 오래 둘 것인가     디스크가 찹니다
//   3일 전 상태로 되돌리려면  그 시점 백업이 있어야 합니다
//
// ★ 클라우드 DB 는 이걸 기본으로 해 줍니다.
//   Supabase 는 매일 백업하고, 상위 요금제에서는 "특정 시점으로 되돌리기" 도 됩니다.
//
// ★★★ 다만 **무료 요금제에는 자동 백업이 없습니다.** (Pro 부터입니다)
//
//   수업 실습은 무료로 충분하지만, 이 절의 "백업을 알아서 해 준다" 는
//   유료 요금제 이야기입니다. 무료로 쓰는 동안에는 스스로 챙겨야 합니다.
//
//     대시보드 → Database → Backups 에서 직접 내려받거나
//     pg_dump 로 주기적으로 받아 두세요.

원본.close();

// ============================================================
// 4. 벽 ④ — 브라우저에서 직접 못 씁니다
// ============================================================
//
// SQLite 파일은 서버 안에 있습니다. 브라우저가 열 수 없습니다.
// 그래서 API 서버를 반드시 만들어야 합니다.
//
// 지금까지 우리가 한 게 그것입니다. 그리고 그게 정상입니다.
//
// ★ 그런데 Supabase 는 DB 앞에 REST API 를 자동으로 붙여 줍니다.
//   표를 만들면 곧바로 이런 주소가 생깁니다.
//
//     GET  /rest/v1/products?category=eq.A&order=id
//     POST /rest/v1/products
//
//   컨트롤러와 라우트를 안 만들어도 CRUD 가 됩니다.
//
// ★★ 그럼 우리가 배운 게 필요 없나요? 아닙니다.
//
//   "판매 중인 상품은 못 지운다" 같은 업무 규칙은 여전히 어딘가에 있어야 합니다.
//   브라우저가 DB 를 직접 부르면 그 규칙을 어길 수 있습니다.
//
//   그래서 실무에서는 이렇게 나눕니다.
//
//     단순한 읽기          브라우저 → Supabase 직접 (빠르고 코드가 적습니다)
//     업무 규칙이 있는 쓰기  브라우저 → 내 API 서버 → Supabase
//
//   그리고 직접 부르는 경우를 안전하게 만드는 장치가 RLS 입니다. (개념04)

// ============================================================
// 5. 벽 ⑤ — 같이 볼 방법이 없습니다
// ============================================================
//
// "김대리, 지금 상품 표 좀 봐 줄래요?" 를 어떻게 할까요?
//
//   SQLite 파일을 카톡으로 보낸다  → 그 사이 자료가 바뀝니다
//   서버에 SSH 로 들어간다         → 모두에게 서버 접속 권한을 줘야 합니다
//
// ★ Supabase 는 웹 화면에서 표를 보고 고칠 수 있습니다.
//   엑셀처럼 생겼습니다. SQL 을 모르는 기획자도 자료를 볼 수 있습니다.
//   권한도 사람마다 줄 수 있습니다.

// ============================================================
// 6. 그럼 SQLite 는 나쁜 건가요
// ============================================================
//
// 아닙니다. 02단원까지 배운 게 헛일이 아닙니다.
//
// ★ SQLite 가 더 나은 경우
//
//   · 서버가 한 대고 앞으로도 한 대일 때
//   · 읽기가 압도적으로 많을 때 (블로그, 문서 사이트)
//   · 응답이 아주 빨라야 할 때 (네트워크 왕복이 없습니다)
//   · 데스크톱·모바일 앱 안에 넣을 때
//   · 시험·개발용 DB
//
//   실제로 규모 있는 서비스를 SQLite 로 운영하는 회사들이 있습니다.
//
// ★ 클라우드 DB 가 필요한 경우
//
//   · 서버가 여러 대일 때
//   · 배포하면 파일이 사라지는 환경일 때
//   · 백업·복구를 맡기고 싶을 때
//   · 브라우저나 모바일 앱이 직접 접근해야 할 때
//   · 팀이 같이 자료를 봐야 할 때
//
// ★★ 그리고 배운 SQL 은 그대로 씁니다.
//   SELECT·JOIN·GROUP BY·색인·트랜잭션 — 전부 Postgres 에도 있습니다.
//   문법 차이가 조금 있을 뿐입니다. (개념02)

const 비교 = [
  ["여러 서버에서 같이 쓰기", "✗", "○"],
  ["배포해도 안 사라짐", "△ (볼륨 필요)", "○"],
  ["백업 자동", "✗ (직접)", "○"],
  ["브라우저에서 직접", "✗", "○"],
  ["웹으로 같이 보기", "✗", "○"],
  ["설치 없이 시작", "○", "△ (가입 필요)"],
  ["응답 속도", "○ (같은 컴퓨터)", "△ (네트워크 왕복)"],
  ["돈", "○ (0원)", "△ (무료 한도 있음)"],
];

console.log("항목                    SQLite      Supabase");
// 출력: 항목                    SQLite      Supabase
for (const [항목, sqlite, supabase] of 비교) {
  console.log(`${항목} / ${sqlite} / ${supabase}`);
}
// 출력: 여러 서버에서 같이 쓰기 / ✗ / ○
// 출력: 배포해도 안 사라짐 / △ (볼륨 필요) / ○
// 출력: 백업 자동 / ✗ (직접) / ○
// 출력: 브라우저에서 직접 / ✗ / ○
// 출력: 웹으로 같이 보기 / ✗ / ○
// 출력: 설치 없이 시작 / ○ / △ (가입 필요)
// 출력: 응답 속도 / ○ (같은 컴퓨터) / △ (네트워크 왕복)
// 출력: 돈 / ○ (0원) / △ (무료 한도 있음)

// ★ 마지막 두 줄을 잊지 마세요.
//
//   네트워크 왕복이 생깁니다. DB자료의 N+1 이 여기서 진짜 문제가 됩니다.
//   로컬 SQLite 에서 3배였던 게 200배가 됩니다. 그때 한 이야기가 이것입니다.

// ============================================================
// 7. Supabase 가 뭔가
// ============================================================
//
// 한 줄로 말하면 "Postgres 한 대에 필요한 것들을 미리 붙여 놓은 것" 입니다.
//
// ★★ 먼저 오해부터 걷어 냅니다.
//
//   Supabase 는 새로운 데이터베이스가 아닙니다.
//   Supabase 라는 문법도, Supabase 만의 저장 방식도 없습니다.
//
//   여러분이 New project 를 눌러 만드는 것은 **Postgres 서버 한 대**입니다.
//   나머지는 전부 그 앞에 세워 둔 도우미들입니다.
//
// 여섯 개를 하나씩 봅니다. 지금 다 외울 필요는 없습니다.
// 이 수업에서 실제로 쓰는 것은 앞의 둘(Postgres, PostgREST) 과 RLS 뿐입니다.
// 나머지는 "그런 게 있다" 만 알아 두면 나중에 필요할 때 찾아갑니다.

// ------------------------------------------------------------
// 7-1. Postgres — 이게 전부입니다
// ------------------------------------------------------------
//
//   프로젝트 하나 = Postgres 한 대. 그 이상도 이하도 아닙니다.
//
//     · DB자료에서 배운 SQL 이 그대로 돕니다
//     · psql 로 직접 붙을 수 있습니다 (연결 문자열을 줍니다)
//     · pg_dump 로 통째로 받아서 다른 곳에 부을 수 있습니다
//
//   ★★ 그래서 "Supabase 를 배운다" 가 아니라 "Postgres 를 배운다" 가 맞습니다.
//     Supabase 를 떠나도 그 지식은 남습니다. Firebase 와 가장 크게 다른 점입니다.
//
// ── 붙는 방법이 두 가지입니다 ──
//
//   ① HTTPS 로 (443 포트) — @supabase/supabase-js. 이 단원에서 쓰는 방법입니다.
//   ② Postgres 로 직접 (5432 포트) — pg, Prisma, psql, DBeaver 같은 보통의 DB 도구
//
//   ★ 둘 다 같은 DB 를 봅니다. 골라 쓰면 됩니다.
//     ①은 브라우저에서도 되고 RLS 가 걸립니다.
//     ②는 서버에서만 되고 RLS 를 건너뜁니다(연결할 때 쓴 계정 권한을 따릅니다).
//
//   ★★ 04~05단원에서 EC2 에 올린 뒤 ②로 붙다가 막히면 이것부터 보세요.
//
//     · 직접 연결(5432) 주소가 IPv6 만 줄 때가 있습니다. EC2 가 IPv4 면 못 붙습니다
//       → 대시보드가 같이 주는 **Connection pooler** 주소(6543) 를 쓰면 됩니다
//     · 풀러의 transaction 모드는 prepared statement 를 못 씁니다
//       → 드라이버 설정에서 끄라고 나옵니다 (Prisma 는 ?pgbouncer=true)
//
// ── 확장(extension) 을 켤 수 있습니다 ──
//
//   Dashboard → Database → Extensions 에서 클릭 한 번입니다.
//
//     pgcrypto     암호화·해시 함수
//     uuid-ossp    uuid 만들기
//     pg_cron      DB 안에서 정해진 시각에 SQL 실행
//     pgvector     ★ 임베딩 검색 (AI자료 05단원 문서 QA 에서 쓰는 그 벡터입니다)
//     postgis      지도·좌표
//     pg_net       DB 안에서 HTTP 요청 보내기
//
//   ★ 이것들도 Postgres 기능이지 Supabase 기능이 아닙니다. 옮겨 가도 따라옵니다.

// ------------------------------------------------------------
// 7-2. PostgREST — 표가 곧 API 입니다
// ------------------------------------------------------------
//
//   Postgres 앞에 PostgREST 라는 프로그램이 서 있습니다.
//   하는 일은 하나입니다. **HTTP 요청을 SQL 로 바꿔서 Postgres 에 넘깁니다.**
//
//     GET /rest/v1/products?category=eq.A&order=id.asc&limit=3
//        ↓ PostgREST 가 바꿉니다
//     SELECT * FROM products WHERE category = 'A' ORDER BY id ASC LIMIT 3
//
//   ★ 그래서 표를 만드는 순간 API 가 생깁니다. 라우터도 컨트롤러도 안 만듭니다.
//     표를 지우면 API 도 같이 사라집니다. 둘이 같은 것이니까요.
//     열을 하나 추가하면 그 열이 곧바로 응답에 들어옵니다.
//
//   ★★★ 그럼 아무나 부를 수 있는 것 아닌가요 — 맞습니다. 그래서 RLS 가 필수입니다.
//
//     PostgREST 는 "누가 무엇을 볼 수 있는가" 를 판단하지 않습니다.
//     그 판단은 Postgres 안에서 합니다. 그게 개념04 입니다.
//     RLS 를 안 켜고 표를 만들면 그 표는 인터넷에 그냥 열려 있는 것입니다.
//
//   ★ 밖으로 나가는 것은 public 스키마의 표뿐입니다.
//     내보내기 싫은 표는 다른 스키마에 두면 주소 자체가 안 생깁니다.
//
//   ★ 표뿐 아니라 뷰(view) 와 함수도 주소가 생깁니다.
//     복잡한 조회는 뷰로 만들어 두고 그 뷰를 부르는 방법을 많이 씁니다.
//
//   개념03 에서 자바스크립트 클라이언트가 이 주소를 어떻게 만드는지 봅니다.

// ------------------------------------------------------------
// 7-3. Auth — 회원표가 내 DB 안에 있습니다
// ------------------------------------------------------------
//
//   가입·로그인·비밀번호 재설정·소셜 로그인을 대신 해 줍니다.
//   (구글, 카카오, 깃허브, 애플, 매직 링크, 전화번호 …)
//
//   ★★★ 여기가 Supabase 를 이해하는 열쇠입니다.
//
//   로그인한 사람의 정보가 **같은 Postgres 안의 auth.users 표**에 들어갑니다.
//   멀리 떨어진 회원 서비스가 아닙니다. 내 DB 안에 있는 표입니다.
//
//   그래서 이런 게 됩니다.
//
//     create table reviews (

async function 동작확인() {
  console.log("전부:", (await 저장소.전부()).map((상품) => 상품.name).join(", "));
  // 출력: 전부: USB 허브, 27인치 모니터, 무선 마우스

  // ★ 준비.sql 이 넣어 둔 세 줄입니다. id 순서로 옵니다.
  //   저장소가 .order("id") 를 붙였기 때문입니다. 안 붙이면 순서가 보장되지 않습니다.

  const 하나 = await 저장소.하나(1);
  console.log("하나(1):", 하나.name, "/", 하나.status);
  // 출력: 하나(1): USB 허브 / 판매중

  const 없는것 = await 저장소.하나(9999);
  console.log("하나(9999):", 없는것, `(${typeof 없는것})`);
  // 출력: 하나(9999): null (object)

  // ★ null 입니다. undefined 가 아닙니다.
  //   서비스의 if (상품 === null) 이 그대로 걸립니다.
  //   저장소가 .maybeSingle() 을 썼기 때문입니다. .single() 이었으면 오류가 났습니다.

  const 만든것 = await 저장소.추가({ name: "검사용-무선 키보드", category: "C" });
  console.log("추가:", JSON.stringify(만든것));
  // 출력?: 추가: {"id":7,"name":"검사용-무선 키보드","category":"C","status":"품절"}

  // ★ id 가 4 가 아닙니다. 섹션 2 의 검사가 번호를 이미 몇 개 썼습니다.
  //   지운 번호는 **되돌아오지 않습니다.** identity 는 되감기지 않습니다.
  //   그래서 이 줄의 출력 주석에는 물음표가 붙어 있습니다. 돌릴 때마다 달라집니다.
  //
  // ★★ status 를 안 줬는데 '품절' 입니다. 누가 넣었을까요?
  //   저장소가 넣었습니다 — 상품저장소.js 의 `값.status ?? "품절"` 입니다.
  //   그런데 표에도 `default '품절'` 이 있습니다. (준비.sql)
  //   같은 기본값이 두 군데 있는 셈입니다. 한쪽만 고치면 그날부터 어긋납니다.

  const 고친것 = await 저장소.수정(만든것.id, { status: "판매중" });
  console.log("수정:", 고친것.status, "/ name 그대로:", 고친것.name);
  // 출력: 수정: 판매중 / name 그대로: 검사용-무선 키보드

  console.log("수정(9999):", await 저장소.수정(9999, { status: "품절" }));
  // 출력: 수정(9999): null

  console.log("삭제:", await 저장소.삭제(만든것.id));
  // 출력: 삭제: true
  console.log("삭제(9999):", await 저장소.삭제(9999));
  // 출력: 삭제(9999): false

  console.log("남은:", (await 저장소.전부()).length);
  // 출력: 남은: 3

  // ★★ 준비.sql 의 세 줄로 돌아왔습니다. 넣었다 지웠으니 제자리입니다.
  //
  // ★★★ 02단원까지는 지금자료() 로 배열을 들여다볼 수 있었습니다.
  //   이제 그런 창문이 없습니다. 표 안이 궁금하면 **표에 물어봐야 합니다.**
  //   저장소.전부() 도 요청 하나입니다. 그게 진짜 DB 입니다.

  // ── 얼마나 걸리나 ──

  console.time("전부() 한 번");
  await 저장소.전부();
  console.timeEnd("전부() 한 번");
  // 출력?: 전부() 한 번: 87.2ms

  // ★★ 02단원 SQLite 는 1ms 안쪽이었습니다. 여기는 수십 ms 입니다.
  //   Region 을 Seoul 로 안 골랐으면 200ms 가 넘을 수도 있습니다.
  //   왕복 한 번의 값이 이만큼 비싸졌습니다.
  //   그 차이가 N+1 을 무섭게 만드는 것입니다. (DB자료 06단원 개념05)
}


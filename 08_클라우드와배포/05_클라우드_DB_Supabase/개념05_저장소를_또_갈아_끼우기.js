// 이파일은Supabase가필요합니다

const { createClient } = require("@supabase/supabase-js");
const 설정 = require("./설정");
const 상품저장소 = require("./상품저장소");

// ★ 클라이언트는 여기서 딱 한 번 만들고, 저장소에 **넣어 줍니다.**
//   상품저장소.js 는 createClient 를 부르지 않습니다. 받아서 씁니다.
//   왜 그렇게 했는지는 섹션 7 에서 이야기합니다.

const sb = createClient(설정.SUPABASE_URL, 설정.SUPABASE_ANON_KEY, {
  auth: { persistSession: false },
});

const 저장소 = 상품저장소.만들기(sb);

// ── 시험이 남긴 줄을 치웁니다 ──
//
// 이 파일이 만드는 줄은 이름이 전부 "검사용" 으로 시작합니다.
// 그래서 이 한 줄이면 준비.sql 상태로 돌아갑니다.
//
// ★ 준비.sql 이 넣어 둔 세 줄(USB 허브 · 27인치 모니터 · 무선 마우스)은
//   이름이 "검사용" 으로 시작하지 않으니 지워지지 않습니다.
//
// ★★★ 절대 `delete().gte("id", 0)` 같은 걸로 표를 통째로 비우지 마세요.
//   reviews 가 products 를 `on delete cascade` 로 참조합니다. (준비.sql)
//   products 를 비우면 reviews 까지 같이 사라집니다.
//   되돌리기는 "내가 만든 것만 지우기" 가 제일 안전합니다.

async function 치우기() {
  const { error } = await sb.from("products").delete().like("name", "검사용%");

  // ★ 치우기가 실패한 것을 조용히 넘기면 안 됩니다.
  //   다음 사람이 "왜 나는 통과가 안 되지" 로 한참 헤매게 됩니다.
  if (error) console.error("★ 치우기 실패:", error.message, "— products 표를 직접 확인하세요");
}

// ============================================================
// 1. 02단원의 저장소검사를 그대로 가져옵니다
// ============================================================
//
// 02단원 연습문제 15번에서 만든 것입니다. 한 글자도 안 고쳤습니다.
// 저장소가 무엇으로 만들어졌는지 이 함수는 모릅니다. 알 필요도 없습니다.
//
// ★ 이번에는 이 함수가 **진짜 Postgres 표**를 상대로 돕니다.
//   그래도 함수는 그대로입니다. 그게 이 단원의 요지입니다.

async function 저장소검사(저장소) {
  const 실패 = [];
  let 통과 = 0;

  const 확인 = (이름, 조건) => {
    if (조건) 통과 += 1;
    else 실패.push(이름);
  };

  확인("내보내는함수", ["전부", "하나", "추가", "수정", "삭제"]
    .every((이름) => typeof 저장소[이름] === "function"));

  확인("없으면null", (await 저장소.하나(999999)) === null);

  확인("삭제false", (await 저장소.삭제(999999)) === false);

  const 시험용 = await 저장소.추가({ name: "검사용 상품", category: "A" });
  확인("id고정", (await 저장소.수정(시험용.id, { id: 888888, category: "B" })).id === 시험용.id);

  const 고친것 = await 저장소.수정(시험용.id, { category: "C" });
  확인("칸유지", 고친것.name === 시험용.name && 고친것.status === 시험용.status);

  await 저장소.삭제(시험용.id);

  return { 통과, 실패 };
}

// ★ 검사가 만드는 줄은 "검사용 상품" 하나뿐이고, 스스로 지웁니다.
//   준비.sql 이 넣어 둔 세 줄은 건드리지 않습니다.
//   그래도 도중에 터질 수 있으니 아래에서 try/finally 로 한 번 더 감쌉니다.

// ============================================================
// 2. 돌려 봅니다
// ============================================================

async function 검사하기() {
  const 결과 = await 저장소검사(저장소);

  console.log(`통과: ${결과.통과}개, 실패: ${JSON.stringify(결과.실패)}`);
  // 출력: 통과: 5개, 실패: []

  // ★★★ 02단원의 SQLite 저장소와 **같은 결과**입니다.
  //
  //   위층에서 보면 구별이 안 됩니다. 그게 목표였습니다.
  //   저장소 안은 완전히 다릅니다 — SQL 한 줄 없고, 전부 HTTP 요청입니다.
  //   방금 그 다섯 개는 서울(또는 여러분이 고른 지역)의 진짜 Postgres 가 대답한 것입니다.
}


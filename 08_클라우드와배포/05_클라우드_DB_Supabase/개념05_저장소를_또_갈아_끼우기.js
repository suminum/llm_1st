// 4. 오류를 어떻게 다듬는가
// ============================================================

async function 오류확인() {
  // ── 이름이 겹치면 ──
  //
  // products.name 에 unique 가 걸려 있습니다. (준비.sql)
  // 흉내가 아니라 Postgres 가 진짜로 23505 를 냅니다.

  try {
    await 저장소.추가({ name: "무선 마우스", category: "A" });
  } catch (에러) {
    console.log(`중복 → 종류=${에러.종류} status=${에러.status} code=${에러.code}`);
    // 출력: 중복 → 종류=중복 status=409 code=23505
  }

  // ★★ 저장소가 Postgres 오류 코드를 우리 말로 바꿔 줬습니다.
  //
  //   위층은 23505 가 뭔지 몰라도 됩니다. 에러.status 만 보면 됩니다.
  //   02단원에서는 이 번역을 서버.js 의 에러 처리기에서 했습니다.
  //   여기서는 저장소로 옮겼습니다. 어느 쪽이 나을까요?
  //
  //   저장소에 두면    DB 를 아는 층이 DB 오류를 다룹니다. 일관됩니다.
  //   에러 처리기에 두면  저장소가 짧아집니다. 대신 위층이 DB 를 조금 압니다.
  //
  //   정답은 없습니다. **한 곳에만 두면 됩니다.**
  //   두 곳에 나눠 두면 어디를 고쳐야 할지 매번 헷갈립니다.

  // ── RLS 에 막히면 ──
  //
  // ★ products 로는 이 오류를 낼 수 없습니다.
  //   준비.sql 이 "수업용 전체 허용" 정책을 걸어 뒀거든요. 다 통과합니다.
  //
  // ★★ 그래서 memos 표로 냅니다. memos 는 RLS 만 켜고 **정책이 하나도 없습니다.**
  //   정책이 없으면 "아무도 아무것도 못 한다" 입니다. (개념04)
  //   아래 요청은 진짜로 나가고, 진짜로 거절당합니다.

  const 넣기 = await sb.from("memos").insert({ content: "권한 시험" }).select();

  console.log(`RLS → code=${넣기.error.code} status=${넣기.status}`);
  // 출력: RLS → code=42501 status=403
  console.log("message:", 넣기.error.message);
  // 출력: message: new row violates row-level security policy for table "memos"

  // ★ status 가 **403** 입니다. 401 이 아닙니다.
  //   anon key 도 JWT 라서 토큰은 늘 붙어 갑니다.
  //   "네가 누군지는 알겠는데 이건 안 된다" 이므로 403 입니다. (개념04)
  //
  // ★★ 이 요청만 저장소를 거치지 않았습니다. 상품저장소는 products 만 보니까요.
  //   저장소를 거쳤다면 상품저장소.js 의 다듬은오류() 가 이 42501 을 받아서
  //   `종류="권한없음", status=403` 으로 바꿔 줍니다. 바로 그 줄이 이 코드를 기다립니다.
  //   위층은 여기서도 42501 을 몰라도 됩니다.

  // ── 네트워크가 끊기면 ──
  //
  // ★★★ 이 파일에서 **여기 한 군데만** 일부러 고장 낸 클라이언트를 씁니다.
  //
  //   수업 중에 진짜로 랜선을 뽑을 수는 없습니다.
  //   그래서 fetch 가 무조건 터지도록 만든 클라이언트를 하나 끼웁니다.
  //   주소도 키도 가짜입니다. 요청은 나가지 않습니다.
  //   **나머지는 전부 진짜 프로젝트에 붙어서 돌았습니다.**

  const 끊긴것 = createClient("https://example.supabase.co", "example-key", {
    auth: { persistSession: false },
    global: { fetch: async () => { throw new TypeError("fetch failed"); } },
  });
  const 끊긴저장소 = 상품저장소.만들기(끊긴것);

  try {
    await 끊긴저장소.전부();
  } catch (에러) {
    console.log(`네트워크 → 종류=${에러.종류} status=${에러.status}`);
    // 출력: 네트워크 → 종류=연결실패 status=503
  }

  // ★★ 지금 이게 **주입의 값어치**입니다.
  //   저장소 코드를 한 글자도 안 고치고 "선이 끊긴 상황" 을 만들어 봤습니다.
  //   저장소가 모듈 안에서 createClient 를 불렀다면 이 시험은 아예 못 합니다.
  //
  // ★★★ 503 을 고른 이유
  //
  //   500 은 "내 서버가 잘못했다" 입니다.
  //   503 은 "지금은 안 되니 나중에 다시 오라" 입니다.
  //
  //   DB 가 잠깐 안 되는 것은 재시도하면 될 수도 있는 일입니다.
  //   클라이언트가 그걸 구분할 수 있어야 합니다.
  //   Retry-After 헤더를 같이 주면 더 좋습니다.
  //
  // ★ SQLite 에서는 이 경우가 없었습니다. 클라우드로 오면서 생긴 상태입니다.
}

